// app/services/payroll-period.mjs · 一个日期：发薪期末
// ----------------------------------------------------------------------------
// 三个入口读的是**同一批**工资数据，问的也是同一个问题 ——「这个人在我范围内吗」：
//
//   ① 打印页   payslip-print.sheet()   按门店出单（财务打印、发到店、员工签收）
//   ② 工资条列表 payroll.listSlips()    页面明细 / CSV 导出 / MCP 工具
//   ③ 发放清单   payout.paylist()        给财务在网银里逐笔核对
//
// "这个人"是**当期期末那天**在哪家店的人。
//
// ★ 为什么必须是期末，不是今天：
//   补打上月单时，按今天取会把 7 月调到 B 店的人印成 B 店，而那张纸是给
//   **6 月的钱**签字的。行闸同理 —— 按今天判，被调走的人会凭空消失、
//   刚调进来的人会凭空多出来，而两条路都"看起来对"，只是人不一样。
//   工资条列表原来一道闸都没有（见 payroll.mjs 的注释），发放清单原来按今天 ——
//   于是同一个人在打印页和 CSV 上会落在不同门店，或者干脆只在其中一边出现。
//
// ★ 为什么把表达式抽成一处：
//   三个地方各写一遍，改口径的那天必定漏一处；漏掉的那一处不会报错，
//   它只会让一张单子上少了个人。所以这里只提供**一个**表达式，谁也不许手抄。
//
// ★ 用法：`periodEndSql('$2')` 要求那条 SQL 的第 2 个参数是期间字符串（YYYY-MM，
//   与 pay_run.period 同格式）。占位符做成参数，是因为各条 SQL 的参数位置不同 ——
//   位置不同不能成为"再抄一遍表达式"的理由。
// ============================================================================

/**
 * 发薪期末（'2026-03' → 2026-03-31）的 SQL 表达式。
 *
 * @param {string} ph 期间参数在 SQL 里的占位符，如 '$1' / '$2'。
 * @returns {string} 可直接拼进 SQL 的表达式（已带外层括号，可跟 @> 或当函数实参）。
 */
export function periodEndSql(ph = '$1') {
  return `(date_trunc('month', to_date(${ph}, 'YYYY-MM')) + interval '1 month - 1 day')::date`;
}
