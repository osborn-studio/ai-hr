-- ============================================================================
-- 083_position.sql · 岗位（业务岗位，不是权限角色）
-- ----------------------------------------------------------------------------
-- 到 082 为止，"岗位"这件事被混在 sys_role 里：boss / store_mgr / store_deputy…
-- 那是**权限角色**（能碰哪类资源），不是**业务岗位**（销售主管 / 实施顾问）。
-- 两者不是一回事：
--
--   · 一个人可以同时是"销售主管"和"销售"（用户就是这么要求的）；
--   · 一个部门可以有多个岗位（销售部：销售主管 + 销售）；
--   · 岗位会换人，权限角色不必跟着换（转岗两周，权限还在走流程）；
--   · 外包人员是岗位属性，不是角色（他不该有员工那些权限）。
--
-- 所以单独一张表：position（岗位档案，人为可加）+ person_position（任职，带区间）。
--
-- ★ 与权限角色的关系：**岗位不自动给权限**。
--   岗位是"他是干什么的"，权限是"他能碰什么"，中间要不要连、怎么连，
--   是客户的决定（有的公司一人多岗但只给一个角色的权限）。
--   硬连起来会出现"设了岗位就有了工资条权限"——那是一次静默的提权。
-- ============================================================================

CREATE TABLE position (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         varchar(32) NOT NULL,
  name         varchar(64) NOT NULL,
  org_id       bigint REFERENCES org_unit(id),   -- 归属部门（可空：跨部门岗位）
  level        smallint NOT NULL DEFAULT 2,      -- 1=主管/负责人 2=员工
  is_outsourced boolean NOT NULL DEFAULT false,  -- 外包岗位：不进内部编制口径
  description  varchar(200),
  is_active    boolean NOT NULL DEFAULT true,
  created_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uk_pos_code UNIQUE (code),
  CONSTRAINT ck_pos_level CHECK (level IN (1, 2))
);

COMMENT ON TABLE position IS
  '业务岗位档案（销售主管/实施顾问…）。与 sys_role（权限角色）是两件事：'
  '岗位说明"他干什么"，角色说明"他能碰什么"。岗位不自动授角色。';

CREATE TABLE person_position (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id   bigint NOT NULL REFERENCES person(id),
  position_id bigint NOT NULL REFERENCES position(id),
  valid_from  date   NOT NULL,
  valid_to    date,
  set_by      varchar(64) NOT NULL DEFAULT 'system',
  CONSTRAINT ck_pp_span CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

-- ★ 同一人同一岗位不得有两条重叠的任职：一人多岗是允许的（不同岗位），
--   但"同一岗位任职两次"只会制造"到底哪条有效"的问题。
ALTER TABLE person_position ADD CONSTRAINT ex_pp_no_overlap
  EXCLUDE USING gist (person_id WITH =, position_id WITH =,
                      daterange(valid_from, valid_to, '[]') WITH &&);

CREATE INDEX ix_pp_person ON person_position (person_id, valid_from DESC);
CREATE INDEX ix_pp_position ON person_position (position_id, valid_from DESC);

-- ---------------------------------------------------------------------------
-- 岗位：建 / 授 / 撤
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_position_upsert(
  p_code varchar, p_name varchar, p_org bigint DEFAULT NULL,
  p_level smallint DEFAULT 2, p_outsourced boolean DEFAULT false,
  p_desc varchar DEFAULT NULL
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_id bigint;
BEGIN
  IF p_name IS NULL OR length(btrim(p_name)) < 2 THEN
    RAISE EXCEPTION 'E_POS_NAME: 岗位名称至少 2 个字';
  END IF;
  INSERT INTO public.position(code, name, org_id, level, is_outsourced, description)
  VALUES (btrim(p_code), btrim(p_name), p_org, p_level, p_outsourced, p_desc)
  ON CONFLICT (code) DO UPDATE
     SET name = EXCLUDED.name, org_id = EXCLUDED.org_id, level = EXCLUDED.level,
         is_outsourced = EXCLUDED.is_outsourced, description = EXCLUDED.description
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION fn_position_assign(
  p_person bigint, p_position bigint, p_from date, p_by varchar DEFAULT 'system'
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_id bigint;
BEGIN
  -- 已在任职期内（同日授两次）→ 幂等返回
  SELECT id INTO v_id FROM public.person_position
   WHERE person_id = p_person AND position_id = p_position AND valid_to IS NULL
     AND daterange(valid_from, valid_to, '[]') @> p_from;
  IF v_id IS NOT NULL THEN RETURN v_id; END IF;

  INSERT INTO public.person_position(person_id, position_id, valid_from, set_by)
  VALUES (p_person, p_position, p_from, p_by) RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION fn_position_end(
  p_person bigint, p_position bigint, p_on date
) RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  UPDATE public.person_position SET valid_to = p_on - 1
   WHERE person_id = p_person AND position_id = p_position AND valid_to IS NULL
     AND valid_from <= p_on;
END;
$$;

/** 某部门（含子树）的岗位与在岗人数 */
CREATE OR REPLACE FUNCTION fn_position_list(p_org bigint DEFAULT NULL, p_on date DEFAULT NULL)
RETURNS TABLE (position_id bigint, code varchar, name varchar, level smallint,
               is_outsourced boolean, org_id bigint, org_name varchar, holders int,
               holder_names text)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE v_on date := COALESCE(p_on, public.app_today());
BEGIN
  RETURN QUERY
  SELECT p.id, p.code, p.name, p.level, p.is_outsourced, p.org_id, o.name,
         COALESCE(cnt.n, 0)::int,
         COALESCE(cnt.names, '')::text
    FROM public.position p
    LEFT JOIN public.org_unit o ON o.id = p.org_id
    LEFT JOIN LATERAL (
      SELECT count(*)::int AS n, string_agg(pe.full_name, '、' ORDER BY pe.full_name) AS names
        FROM public.person_position pp
        JOIN public.person pe ON pe.id = pp.person_id
        JOIN public.employment e ON e.person_id = pp.person_id
       WHERE pp.position_id = p.id
         AND daterange(pp.valid_from, pp.valid_to, '[]') @> v_on
         AND daterange(e.hire_date, e.leave_date, '[]') @> v_on
    ) cnt ON true
   WHERE p.is_active
     AND (p_org IS NULL OR p.org_id = p_org
          OR p.org_id IN (SELECT c.id FROM public.org_unit c
                           JOIN public.org_unit me ON me.id = p_org
                          WHERE c.path LIKE me.path || '%'))
   ORDER BY p.level, p.name;
END;
$$;

COMMENT ON FUNCTION fn_position_list IS
  '岗位清单：含在岗人数与人名。一人多岗时，他在每个岗位下都算一次 —— '
  '这是对的：编制看的是"岗位有没有人"，不是"人头去重"。';

-- 岗位视图：组织页"按岗位"看的那份数据
CREATE OR REPLACE VIEW v_position_filled AS
SELECT p.id AS position_id, p.code, p.name AS position_name, p.level,
       p.is_outsourced, o.id AS org_id, o.name AS org_name,
       count(DISTINCT pp.person_id)::int AS holders
  FROM position p
  LEFT JOIN org_unit o ON o.id = p.org_id
  LEFT JOIN person_position pp
    ON pp.position_id = p.id
   AND daterange(pp.valid_from, pp.valid_to, '[]') @> public.app_today()
 WHERE p.is_active
 GROUP BY p.id, p.code, p.name, p.level, p.is_outsourced, o.id, o.name;

