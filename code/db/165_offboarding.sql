-- ============================================================================
-- 165_offboarding.sql · 离职交接：一张离职单 + 交接清单 + 离职证明 + 竞业限制
-- ----------------------------------------------------------------------------
-- 现状：离职只有 `employment.leave_date` 一个日期。
--   · 054 补了 `fn_emp_terminate`（写日期 + 收归属 + 留一条原因），134/135 补了
--     **钱怎么算**（N、代通知金、年假折现）。但"离职"这件事本身仍然缺三块：
--
--   ① **没有"一张单"**：谁提的、什么时候提的、最后一天是哪天、交接给谁、
--      清单有没有做完 —— 都答不出来。能查到的只有"他哪天走的"和"原因是四个字"。
--      而劳动争议里被问的第一句往往是"他自己辞的还是公司让他走的、谁批的"。
--
--   ② **交接清单没有落点**：工牌、钥匙、电脑、客户资料、在办事项 ——
--      谁收了、什么时候收的。这些东西没有一个系统内的位置，就只能记在微信里；
--      而"东西还没还、人已经走了"是可以变成实际损失的（门禁、客户流失）。
--
--   ③ **离职证明没有**：《劳动合同法》第五十条——用人单位**应当在**解除或者
--      终止劳动合同时出具证明。这不是"锦上添花"，是法定义务；而且它直接决定
--      员工能不能入职下一家。漏出这张纸，员工回头主张"无法就业的损失"。
--
--   ④ **竞业限制没有**：约定了才有，且必须写清范围、期限、补偿标准；
--      **没约定就不能事后加**（事后加的限制没有对价，法院不认，还会被反诉）。
--
-- ★ 五条设计取舍：
--
--   ① **离职是一条单据（employee_exit），不是一个 UPDATE。**
--      054 的 fn_emp_terminate 只写日期与原因，它是"办理"而不是"记录过程"。
--      单据要能回答：谁提的（created_by）、哪天提的（apply_date）、最后一天
--      （last_work_date）、交给谁（handover_to）、谁批的（approved_by）、
--      什么时候办完的（done_at）。直接改日期，改完就再也查不出这些。
--
--   ② **交接清单是行（exit_handover_item），不是单上的一个"是否交接"布尔。**
--      一张单上打一个勾，回答不了"电脑还没还"这件事。而真正的争议恰恰是
--      "哪一件没还、什么时候该还"。所以一件一行，各自有归还时刻。
--
--   ③ **离职证明只写四要素 + 年限，不写原因、不写评价、不写竞业。**
--      《劳动合同法实施条例》第二十四条已把内容限定在"劳动合同期限、
--      解除或者终止的日期、工作岗位、本单位工作年限"。
--      多写一句"因严重违纪解除"，下家会追问，员工可以主张名誉侵权；
--      多写一句"表现优秀"，将来公司想说"不能胜任"就自相矛盾。
--      所以生成函数里**根本没有**原因这个变量 —— 不是"记得别写"，是写不出来。
--
--   ④ **竞业限制"没约定"也要留一行（status='none'）。**
--      留 NULL（没有记录）与"明确没约定"在事后是两件完全不同的事：
--      前者说不清当时谈没谈，后者是当时的结论。而 status='agreed' 才要求
--      范围/期限/补偿齐全，库里的 CHECK 让它没法"约定了但没写补偿"。
--
--   ⑤ **生效时才动 employment / 合同 / 归属，且只截到最后工作日，不改历史。**
--      与 163 的异动同一条规矩：按日子切段，不 UPDATE 历史。离职日当天仍算
--      在职（007 的 '[]' 口径），所以归属段与合同的终止日都落在**最后工作日**
--      而不是次日 —— 差一天就是一天的工资与一天的门禁权限。
--
-- 刻意**不动**的：
--   · 社保停缴：跨系统（社保申报在 012/141），这里只给提示（W_EXIT_SI_OPEN）
--     由 HR 去停；本文件不改 si_* 任何一行 —— 少缴一个月是补不回来的。
--   · 补偿金金额：走 134/135 的独立结算单，离职单只提供"人、最后一天、原因"。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 离职单
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.employee_exit (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           varchar(32)  NOT NULL UNIQUE,
  employee_id    bigint       NOT NULL,          -- person.id（与 163 同：不挂外键）
  kind           varchar(16)  NOT NULL,
  apply_date     date         NOT NULL,          -- 提出离职那天（不是最后一天）
  last_work_date date         NOT NULL,          -- 最后工作日（当天仍算在职）
  reason         varchar(200) NOT NULL,
  handover_to    bigint,                         -- 交接给谁（person.id）
  status         varchar(16)  NOT NULL DEFAULT 'draft',
  approved_by    varchar(64),
  done_at        timestamptz,                    -- 办结时刻（不是最后工作日）
  created_by     varchar(64)  NOT NULL,
  created_at     timestamptz  NOT NULL DEFAULT now(),

  CONSTRAINT ck_ee_kind CHECK (kind IN
    ('resign','terminate','retire','contract_end')),
  CONSTRAINT ck_ee_status CHECK (status IN ('draft','approved','done','cancelled')),
  CONSTRAINT ck_ee_reason CHECK (length(btrim(reason)) >= 4),
  -- 办结必须有办结时刻；没办结不许有（与 163 的 applied_at 同一个写法）
  CONSTRAINT ck_ee_done CHECK ((status = 'done') = (done_at IS NOT NULL)),
  -- 交接给自己等于没交代
  CONSTRAINT ck_ee_handover_self CHECK (handover_to IS NULL OR handover_to <> employee_id)
);

-- ★ 同一人不能有两张未完成的离职单 —— 用**部分唯一索引**表达，不用应用层 if。
--   "两次离职办两遍"会让最后一天被改掉，而那天已经发过的工资、已经停掉的社保
--   不会跟着变。这条约束在导入、脚本、将来的新接口上一样生效。
CREATE UNIQUE INDEX IF NOT EXISTS ux_ee_open
  ON public.employee_exit (employee_id) WHERE status IN ('draft','approved');

CREATE INDEX IF NOT EXISTS ix_ee_emp ON public.employee_exit (employee_id, last_work_date DESC);
CREATE INDEX IF NOT EXISTS ix_ee_due ON public.employee_exit (last_work_date)
  WHERE status IN ('draft','approved');

COMMENT ON TABLE public.employee_exit IS
  '离职单（165）：提出日 / 最后工作日 / 原因 / 交接人 / 审批 / 办结时刻。'
  '★ 离职是一条单据而不是一次 UPDATE —— 直接改 employment.leave_date，'
  '改完就再也答不出"谁提的、谁批的、交给谁"。';
COMMENT ON COLUMN public.employee_exit.apply_date IS
  '提出离职的日期，与最后工作日分开存。提前 30 日通知（劳动合同法第三十七条）'
  '算的就是这两个日期之间；合成一个字段就再也算不出来。';
COMMENT ON COLUMN public.employee_exit.last_work_date IS
  '最后工作日。★ 当天仍算在职（007 的 ''[]'' 口径）：归属段与合同终止日都落在这一天，'
  '落到次日会多给一天工资、多留一天门禁。';

-- ---------------------------------------------------------------------------
-- 2. 交接清单（一件一行）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.exit_handover_item (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exit_id     bigint       NOT NULL REFERENCES public.employee_exit(id) ON DELETE CASCADE,
  item        varchar(120) NOT NULL,
  category    varchar(16)  NOT NULL DEFAULT 'asset',
  is_returned boolean      NOT NULL DEFAULT false,
  returned_at timestamptz,
  note        varchar(200),
  created_at  timestamptz  NOT NULL DEFAULT now(),

  CONSTRAINT ck_ehi_cat CHECK (category IN ('asset','document','account','work')),
  CONSTRAINT ck_ehi_item CHECK (length(btrim(item)) > 0),
  -- 归还了才有归还时刻；没归还不许有（否则"什么时候收的"是编的）
  CONSTRAINT ck_ehi_returned CHECK (is_returned = (returned_at IS NOT NULL)),
  -- 同一张单上同名条目视为同一件（编号写进 note）：不然重复提交会插出两行工牌
  CONSTRAINT uk_ehi_item UNIQUE (exit_id, item)
);

CREATE INDEX IF NOT EXISTS ix_ehi_exit ON public.exit_handover_item (exit_id, category);

COMMENT ON TABLE public.exit_handover_item IS
  '交接清单（165）：工牌 / 钥匙 / 电脑（asset）、客户资料（document）、'
  '账号（account）、在办事项（work）。★ 一件一行，各自有归还时刻 —— '
  '单上打一个"已交接"勾回答不了"哪一件还没还"，而那正是争议的形态。';
COMMENT ON COLUMN public.exit_handover_item.category IS
  'asset=资产（工牌/钥匙/电脑） document=资料（客户名单/合同原件） '
  'account=账号与款项（系统账号、备用金、借款结清） work=在办事项。'
  '★ 前三种是"关键项"：没归还时 fn_exit_check 出预警（W_EXIT_HANDOVER_OPEN）。';

-- ---------------------------------------------------------------------------
-- 3. 竞业限制
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.non_compete (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id bigint       NOT NULL,
  exit_id     bigint       REFERENCES public.employee_exit(id) ON DELETE CASCADE,
  scope       varchar(200),                 -- 限制范围（地域/业务/岗位）
  months      int,                          -- 期限（月），法定上限 24
  monthly_pay numeric(12,2),                -- 月补偿标准
  start_date  date,
  end_date    date,
  status      varchar(8)   NOT NULL DEFAULT 'none',
  created_by  varchar(64)  NOT NULL,
  created_at  timestamptz  NOT NULL DEFAULT now(),

  CONSTRAINT ck_nc_status CHECK (status IN ('none','agreed','waived')),
  -- ★ 《劳动合同法》第二十四条：竞业限制期限不得超过**二年**
  CONSTRAINT ck_nc_months CHECK (months IS NULL OR months BETWEEN 1 AND 24),
  CONSTRAINT ck_nc_pay CHECK (monthly_pay IS NULL OR monthly_pay > 0),
  -- 约定了就必须四样齐全：范围、期限、补偿、起止。缺补偿的竞业条款，员工可以不履行
  CONSTRAINT ck_nc_agreed CHECK (
    status <> 'agreed' OR (
      scope IS NOT NULL AND length(btrim(scope)) >= 2
      AND months IS NOT NULL
      AND monthly_pay IS NOT NULL AND monthly_pay > 0
      AND start_date IS NOT NULL AND end_date IS NOT NULL
      AND end_date > start_date)),
  -- 没约定 / 明确放弃：四样都必须为空。
  -- ★ 留着半份补偿标准，"没约定"过几个月就会被读成"约定了"。
  CONSTRAINT ck_nc_none CHECK (
    status = 'agreed' OR (
      scope IS NULL AND months IS NULL AND monthly_pay IS NULL
      AND start_date IS NULL AND end_date IS NULL)),
  -- 一张离职单最多一条竞业约定（同一个人可以有多段离职，各有一条）
  CONSTRAINT uk_nc_exit UNIQUE (exit_id)
);

CREATE INDEX IF NOT EXISTS ix_nc_emp ON public.non_compete (employee_id, status);

COMMENT ON TABLE public.non_compete IS
  '竞业限制（165）：scope/monthly_pay/months(≤24)/起止。'
  '★ 三态而不是布尔：none=明确没约定、agreed=约定了、waived=约定了但公司放弃要求履行。'
  '"没约定"要留一行，否则事后说不清当时谈没谈；而没约定就**不能**事后补加 —— '
  '事后加的限制没有对价，员工可以不履行。';
COMMENT ON COLUMN public.non_compete.monthly_pay IS
  '月补偿标准。法定下限是劳动合同解除前十二个月平均工资的 30%（司法解释一第三十六条），'
  'fn_exit_check 低于这个数只报预警不拦 —— 各地口径与"低于最低工资按最低工资"的'
  '地方规定不一致，硬拦会把人逼去线下签。';

-- ---------------------------------------------------------------------------
-- 4. 开单
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_exit_open(
  p_employee    bigint,
  p_kind        varchar,
  p_apply_date  date,
  p_last_work   date,
  p_reason      varchar,
  p_handover_to bigint DEFAULT NULL,
  p_by          varchar DEFAULT 'system'
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_hire  date;
  v_code  varchar(32);
  v_id    bigint;
  v_n     int;
BEGIN
  IF p_last_work IS NULL OR p_apply_date IS NULL THEN
    RAISE EXCEPTION 'E_EXIT_NO_DATE: 提出日与最后工作日都必填（"今天"在跨月那天会变成另一天，'
      '而跨月那天差一天就是一笔工资）';
  END IF;
  IF p_kind IS NULL OR p_kind NOT IN ('resign','terminate','retire','contract_end') THEN
    RAISE EXCEPTION 'E_EXIT_KIND: 离职类型只能是 resign/terminate/retire/contract_end，收到 %', p_kind;
  END IF;
  IF p_reason IS NULL OR length(btrim(p_reason)) < 4 THEN
    RAISE EXCEPTION 'E_EXIT_NO_REASON: 离职原因至少 4 个字 —— 只留一个日期，'
      '三个月后没人答得出"他为什么走"';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.person p WHERE p.id = p_employee) THEN
    RAISE EXCEPTION 'E_EXIT_NO_EMPLOYEE: 人员 % 不存在', p_employee;
  END IF;
  IF p_handover_to IS NOT NULL THEN
    IF p_handover_to = p_employee THEN
      RAISE EXCEPTION 'E_EXIT_SELF_HANDOVER: 交接人不能是他自己（交接给自己等于没交代）';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.person p WHERE p.id = p_handover_to) THEN
      RAISE EXCEPTION 'E_EXIT_NO_HANDOVER: 交接人 % 不存在', p_handover_to;
    END IF;
  END IF;

  -- 当前这一段任职（leave_date IS NULL）。已离职的人再开单，等于把日期改掉
  SELECT e.hire_date INTO v_hire
    FROM public.employment e
   WHERE e.person_id = p_employee AND e.leave_date IS NULL
   ORDER BY e.hire_date DESC LIMIT 1;
  IF v_hire IS NULL THEN
    RAISE EXCEPTION 'E_EXIT_NO_EMPLOYMENT: 人员 % 没有在册的任职记录（可能已经办过离职）', p_employee;
  END IF;
  IF p_last_work < v_hire THEN
    RAISE EXCEPTION 'E_EXIT_BEFORE_HIRE: 最后工作日 % 早于入职日 % —— 这不是离职，是没入过职',
      p_last_work, v_hire;
  END IF;

  IF EXISTS (SELECT 1 FROM public.employee_exit x
              WHERE x.employee_id = p_employee AND x.status IN ('draft','approved')) THEN
    RAISE EXCEPTION 'E_EXIT_DUP_OPEN: 人员 % 已经有一张未完成的离职单 —— '
      '两张单子会让"最后一天是哪天"说不清，先办结或取消前一张', p_employee;
  END IF;

  v_code := 'LZ' || to_char(p_apply_date, 'YYYYMM') || '-'
    || lpad(((SELECT count(*) FROM public.employee_exit x
               WHERE x.apply_date >= date_trunc('month', p_apply_date)) + 1)::text, 4, '0');

  INSERT INTO public.employee_exit
    (code, employee_id, kind, apply_date, last_work_date, reason, handover_to,
     status, created_by)
  VALUES (v_code, p_employee, p_kind, p_apply_date, p_last_work, btrim(p_reason),
     p_handover_to, 'draft', p_by)
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_exit_open IS
  '开一张离职单（165）：校验最后工作日不早于入职日、同一个人不能有两张未完成的单、'
  '交接人不能是自己。★ 与 054 的 fn_emp_terminate 分工：那个是"办"，这个是"记" —— '
  '单据先立起来，交接、审批、证明都挂在单上，最后才 fn_exit_apply 落库。';

-- ---------------------------------------------------------------------------
-- 5. 校验：block / warn（与 163、160 同一套形态）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_exit_check(
  p_employee  bigint,
  p_last_work date DEFAULT NULL,
  p_exit      bigint DEFAULT NULL
) RETURNS TABLE (level varchar, code varchar, message varchar)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE
  v_hire    date;
  v_last    date;
  v_c_no    varchar(48);
  v_c_from  date;
  v_c_to    date;
  v_days    numeric(8,2);
  v_n       int;
  v_names   text;
  v_si      int;
BEGIN
  IF p_last_work IS NULL THEN
    RETURN QUERY SELECT 'block'::varchar, 'E_EXIT_NO_DATE'::varchar,
      '最后工作日必填（不填就只能"今天"，而"今天"在跨月那天会变成另一天）'::varchar;
    RETURN;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.person p WHERE p.id = p_employee) THEN
    RETURN QUERY SELECT 'block'::varchar, 'E_EXIT_NO_EMPLOYEE'::varchar,
      format('人员 %s 不存在', p_employee)::varchar;
    RETURN;
  END IF;

  SELECT e.hire_date INTO v_hire
    FROM public.employment e
   WHERE e.person_id = p_employee AND e.leave_date IS NULL
   ORDER BY e.hire_date DESC LIMIT 1;
  IF v_hire IS NULL THEN
    RETURN QUERY SELECT 'block'::varchar, 'E_EXIT_NO_EMPLOYMENT'::varchar,
      format('人员 %s 没有在册的任职记录（可能已经办过离职）—— 再办一次会把'
             || '"他哪天走的"改掉，而那天发过的工资不会跟着变', p_employee)::varchar;
    RETURN;
  END IF;

  IF p_last_work < v_hire THEN
    RETURN QUERY SELECT 'block'::varchar, 'E_EXIT_BEFORE_HIRE'::varchar,
      format('最后工作日 %s 早于入职日 %s —— 这不是离职，是没入过职',
             p_last_work, v_hire)::varchar;
    RETURN;
  END IF;

  IF EXISTS (SELECT 1 FROM public.employee_exit x
              WHERE x.employee_id = p_employee
                AND x.status IN ('draft','approved')
                AND x.id IS DISTINCT FROM p_exit) THEN
    RETURN QUERY SELECT 'block'::varchar, 'E_EXIT_DUP_OPEN'::varchar,
      '这个人已经有一张未完成的离职单 —— 两张单子会让"最后一天是哪天"说不清，'
      '先办结或取消前一张'::varchar;
    RETURN;
  END IF;

  v_last := p_last_work;

  -- ---- warn 1：还有在履行的合同没终止（生效时会终止，所以是提示不是拦）----
  SELECT c.contract_no, c.start_date, c.end_date INTO v_c_no, v_c_from, v_c_to
    FROM public.employment_contract c
   WHERE c.employee_id = p_employee AND c.status = 'signed'
     AND daterange(c.start_date, c.end_date, '[]') @> v_last
   ORDER BY c.start_date DESC LIMIT 1;
  IF v_c_no IS NOT NULL THEN
    RETURN QUERY SELECT 'warn'::varchar, 'W_EXIT_CONTRACT_LIVE'::varchar,
      format('合同 %s（%s ~ %s）仍在履行：生效时会被置为 terminated、'
             || '终止日落在最后工作日 %s —— 先确认合同期限与实际离职日之间的差额'
             || '（提前解除与到期终止的补偿算法不同，见 134）',
             v_c_no, v_c_from, COALESCE(v_c_to::text, '无固定期限'), v_last)::varchar;
  END IF;

  -- ---- warn 2：还有未休年假（要折现，不能随离职默默消失）----
  SELECT COALESCE((SELECT sum(g.qty) FROM public.leave_grant g
                     JOIN public.leave_type t ON t.id = g.leave_type_id
                    WHERE g.employee_id = p_employee AND t.code = 'ANNUAL'
                      AND (g.valid_to IS NULL OR g.valid_to >= v_last)), 0)
       - COALESCE((SELECT sum(u.qty) FROM public.leave_usage u
                     JOIN public.leave_type t ON t.id = u.leave_type_id
                    WHERE u.employee_id = p_employee AND t.code = 'ANNUAL'
                      AND u.state IN ('frozen','used','forfeited')), 0)
    INTO v_days;
  IF v_days > 0 THEN
    RETURN QUERY SELECT 'warn'::varchar, 'W_EXIT_LEAVE_LEFT'::varchar,
      format('还有 %s 天年假未休：按制度 LEAVE_TERM_HANDLING 处理（折现或作废），'
             || '折现要进离职当月工资条并按 200%% 或 300%% 计（见 129/057）—— '
             || '额度不会因为办了离职自动消失', v_days)::varchar;
  END IF;

  -- ---- warn 3：交接清单里的关键项没归还（含借款/备用金这类 account 项）----
  IF p_exit IS NOT NULL THEN
    SELECT count(*)::int, string_agg(h.item, '、' ORDER BY h.item)
      INTO v_n, v_names
      FROM public.exit_handover_item h
     WHERE h.exit_id = p_exit AND NOT h.is_returned
       AND h.category IN ('asset','document','account');
    IF v_n > 0 THEN
      RETURN QUERY SELECT 'warn'::varchar, 'W_EXIT_HANDOVER_OPEN'::varchar,
        format('还有 %s 件关键交接项未归还：%s —— 资产/资料/账号（含借款与备用金结清）'
               || '没交接完就办结，事后只剩一句"好像是还了"', v_n, v_names)::varchar;
    END IF;
  END IF;

  -- ---- warn 4：竞业期内又有了新任职（只提示：系统看不到对方是哪一家）----
  IF EXISTS (SELECT 1 FROM public.non_compete n
              WHERE n.employee_id = p_employee AND n.status = 'agreed'
                AND daterange(n.start_date, n.end_date, '[]') @> CURRENT_DATE)
     AND EXISTS (SELECT 1 FROM public.employment e2
                  WHERE e2.person_id = p_employee AND e2.hire_date > v_last) THEN
    RETURN QUERY SELECT 'warn'::varchar, 'W_EXIT_NC_REHIRE'::varchar,
      '这个人在竞业限制期内又有新任职：系统只知道"他又上班了"，看不到对方是哪一家 —— '
      '需人工核对是否同行；若确属同行，公司要么主张违约责任，要么按约定支付补偿'::varchar;
  END IF;

  -- ---- warn 5：社保还在缴（跨系统，本文件不改 si_* 任何一行）----
  SELECT count(*)::int INTO v_si FROM public.si_policy p;
  IF v_si > 0 THEN
    RETURN QUERY SELECT 'warn'::varchar, 'W_EXIT_SI_OPEN'::varchar,
      format('最后工作日 %s 之后要把社保与公积金停缴：本系统不做这件事'
             || '（申报在 012/141），请在申报端操作。少缴一个月补不回来，'
             || '多缴一个月退不回来', v_last)::varchar;
  END IF;

  RETURN;
END;
$$;

