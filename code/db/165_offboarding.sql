-- ---------------------------------------------------------------------------
-- 6. 生效：写 leave_date + 终止合同 + 收口归属
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_exit_apply(
  p_exit bigint,
  p_by   varchar DEFAULT 'system'
) RETURNS TABLE (exit_id bigint, employment_rows int, contract_rows int, assignment_rows int)
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  x        record;
  e        record;
  v_emp    int := 0;
  v_ctr    int := 0;
  v_seg    int := 0;
BEGIN
  SELECT * INTO x FROM public.employee_exit WHERE id = p_exit FOR UPDATE;
  IF x.id IS NULL THEN
    RAISE EXCEPTION 'E_EXIT_NOT_FOUND: 离职单 % 不存在', p_exit;
  END IF;
  IF x.status = 'done' THEN
    RAISE EXCEPTION 'E_EXIT_DONE: 离职单 % 已于 % 办结，不能重复生效'
      '（重复生效会把最后一天改掉，而那天发过的工资不会跟着变）', x.code, x.done_at;
  END IF;
  IF x.status = 'cancelled' THEN
    RAISE EXCEPTION 'E_EXIT_CANCELLED: 离职单 % 已取消，不能再生效（要办就重新开一张）', x.code;
  END IF;

  SELECT * INTO e FROM public.employment
   WHERE person_id = x.employee_id AND leave_date IS NULL
   ORDER BY hire_date DESC LIMIT 1
   FOR UPDATE;
  IF e.id IS NULL THEN
    RAISE EXCEPTION 'E_EXIT_ALREADY_LEFT: 人员 % 的任职已经结束 —— 再办一次会把日期改掉，'
      '而那天发过的工资与已经停掉的社保不会跟着变', x.employee_id;
  END IF;
  IF x.last_work_date < e.hire_date THEN
    RAISE EXCEPTION 'E_EXIT_BEFORE_HIRE: 最后工作日 % 早于入职日 %',
      x.last_work_date, e.hire_date;
  END IF;

  -- ---- ① 任职结束。★ '[]' 口径：最后工作日当天仍算在职（007）----
  UPDATE public.employment SET leave_date = x.last_work_date WHERE id = e.id;
  GET DIAGNOSTICS v_emp = ROW_COUNT;

  -- ---- ② 在履行的合同 → terminated，终止日 = 最后工作日 ----
  --   ★ 只动 status='signed' 且区间覆盖最后工作日的那一份：没签的草稿不是"在履行"，
  --     签了但期限已过的也不该被改成"解除"（那是到期，不是解除）。
  UPDATE public.employment_contract c
     SET status = 'terminated',
         terminate_at = x.last_work_date,
         terminate_note = COALESCE(NULLIF(btrim(c.terminate_note), ''),
                                   '离职单 ' || x.code),
         updated_at = now()
   WHERE c.employee_id = x.employee_id
     AND c.status = 'signed'
     AND daterange(c.start_date, c.end_date, '[]') @> x.last_work_date;
  GET DIAGNOSTICS v_ctr = ROW_COUNT;

  -- ---- ③ 归属段收口到最后工作日 ----
  --   ★ 只收口"还开着"（valid_to IS NULL）且已经开始的段。人走了归属还挂着，
  --     花名册看不见他，但"这家店几个人"的口径会数着他 —— 两个数都自洽，加起来错。
  UPDATE public.employee_org_assignment a
     SET valid_to = x.last_work_date
   WHERE a.employee_id = x.employee_id
     AND a.valid_to IS NULL
     AND a.valid_from <= x.last_work_date;
  GET DIAGNOSTICS v_seg = ROW_COUNT;

  -- ---- ④ 054 的离职记录（只增不改）：已经由 fn_emp_terminate 写过的就跳过 ----
  INSERT INTO public.employment_termination (employment_id, leave_date, reason, created_by)
  VALUES (e.id, x.last_work_date, x.reason, p_by)
  ON CONFLICT (employment_id) DO NOTHING;

  -- ---- ⑤ 单据办结 ----
  UPDATE public.employee_exit
     SET status = 'done', done_at = now(), approved_by = COALESCE(approved_by, p_by)
   WHERE id = p_exit;

  RETURN QUERY SELECT p_exit, v_emp, v_ctr, v_seg;
END;
$$;

COMMENT ON FUNCTION fn_exit_apply IS
  '离职生效（165）：写 employment.leave_date、把在履行的合同置 terminated'
  '（terminate_at = 最后工作日）、归属段收口到最后工作日、补一条 054 的离职记录、'
  '单据转 done。返回各表受影响行数。★ 归零也算成功（本来就没有合同/归属的人），'
  '所以不拿行数当判据 —— 判据是 leave_date 变了没有。';

-- ---------------------------------------------------------------------------
-- 7. 离职证明（法定四要素 + 年限，**写不出原因**）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_exit_certificate(p_exit bigint)
RETURNS text
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE
  x         record;
  v_hire    date;
  v_name    varchar(64);
  v_id      varchar(64);
  v_job     varchar(64);
  v_months  int;
  v_years   text;
  v_body    text;
BEGIN
  SELECT * INTO x FROM public.employee_exit WHERE id = p_exit;
  IF x.id IS NULL THEN
    RAISE EXCEPTION 'E_EXIT_NOT_FOUND: 离职单 % 不存在', p_exit;
  END IF;
  -- ★ 只给办结的单出证明：还没办完就出，等于提前宣布"劳动关系已结束"
  IF x.status <> 'done' THEN
    RAISE EXCEPTION 'E_EXIT_NOT_DONE: 离职单 % 还没办结（当前 %），不能出离职证明 —— '
      '证明写的是"已于某日解除或终止"，提前出就是提前宣告劳动关系结束', x.code, x.status;
  END IF;

  SELECT p.full_name INTO v_name FROM public.person p WHERE p.id = x.employee_id;
  IF v_name IS NULL THEN
    RAISE EXCEPTION 'E_EXIT_NO_EMPLOYEE: 人员 % 不存在', x.employee_id;
  END IF;

  SELECT e.hire_date INTO v_hire FROM public.employment e
   WHERE e.person_id = x.employee_id AND e.hire_date <= x.last_work_date
   ORDER BY e.hire_date DESC LIMIT 1;
  IF v_hire IS NULL THEN
    RAISE EXCEPTION 'E_EXIT_NO_EMPLOYMENT: 人员 % 没有可用的入职记录，算不出本单位工作年限',
      x.employee_id;
  END IF;

  -- 证件号：法定要素之一。★ 空着就拒绝，不印一个空栏（空栏的证明下家用不了）
  SELECT pp.profile_value INTO v_id
    FROM public.person_profile pp
   WHERE pp.person_id = x.employee_id AND pp.profile_type = 'national_id'
   ORDER BY (pp.verified_by IS NOT NULL) DESC, pp.id DESC LIMIT 1;
  IF v_id IS NULL OR btrim(v_id) = '' THEN
    RAISE EXCEPTION 'E_EXIT_NO_IDCARD: 人员 % 没有身份证号档案 —— 离职证明的证件号空着，'
      '这份纸在下一家单位用不了；先补档案再出证明', x.employee_id;
  END IF;

  -- 岗位：按"最后工作日仍在履行的合同 → 最近一份合同 → 最近一次异动"三级取
  SELECT c.job_title INTO v_job FROM public.employment_contract c
   WHERE c.employee_id = x.employee_id
     AND daterange(c.start_date, c.end_date, '[]') @> x.last_work_date
   ORDER BY (c.status = 'signed') DESC, c.start_date DESC LIMIT 1;
  IF v_job IS NULL THEN
    SELECT c.job_title INTO v_job FROM public.employment_contract c
     WHERE c.employee_id = x.employee_id ORDER BY c.start_date DESC LIMIT 1;
  END IF;
  IF v_job IS NULL THEN
    SELECT COALESCE(g.new_job_title, g.old_job_title) INTO v_job
      FROM public.employee_change g
     WHERE g.employee_id = x.employee_id AND g.status = 'applied'
     ORDER BY g.effective_date DESC LIMIT 1;
  END IF;
  -- ★ 岗位缺失时**不拒**：法定要求"应当出具"，拒开比字段不完美更糟
  v_job := COALESCE(NULLIF(btrim(COALESCE(v_job, '')), ''), '岗位未在系统中登记');

  -- 本单位工作年限：最后工作日 - 入职日 的整月数
  v_months := (extract(year FROM age(x.last_work_date, v_hire)) * 12
             + extract(month FROM age(x.last_work_date, v_hire)))::int;
  IF v_months < 1 THEN
    v_years := '不满 1 个月';
  ELSE
    v_years := concat_ws(' ',
      CASE WHEN v_months / 12 > 0
           THEN (v_months / 12)::text || ' 年' END,
      CASE WHEN v_months % 12 > 0
           THEN (v_months % 12)::text || ' 个月' END);
  END IF;

  -- ★ 这份正文里没有"原因"、没有"表现"、没有"竞业" —— 不是靠自觉，是根本没有变量。
  --   《劳动合同法实施条例》第二十四条把内容限定在四要素 + 工作年限；
  --   多写一句，下家会追问，员工可以主张名誉侵权（而公司还没有证据）。
  v_body :=
      '                解除（终止）劳动合同证明' || E'\n\n'
   || '姓名：'       || v_name || E'\n'
   || '身份证号：'   || btrim(v_id) || E'\n'
   || '工作岗位：'   || v_job || E'\n'
   || '入职日期：'   || to_char(v_hire, 'YYYY-MM-DD') || E'\n'
   || '离职日期：'   || to_char(x.last_work_date, 'YYYY-MM-DD') || E'\n'
   || '本单位工作年限：' || v_years || E'\n\n'
   || '    兹证明上述人员与本单位之间的劳动合同已于 '
   || to_char(x.last_work_date, 'YYYY-MM-DD')
   || ' 解除或终止，双方劳动关系自此结束。本单位已依法为其办理相关手续。'
   || E'\n\n'
   || '（此处加盖单位公章）                    出具日期：'
   || to_char(CURRENT_DATE, 'YYYY-MM-DD');

  RETURN v_body;
END;
$$;

COMMENT ON FUNCTION fn_exit_certificate IS
  '离职证明正文（165）：姓名 / 身份证号 / 岗位 / 入职日 / 离职日 / 本单位工作年限 + 盖章位。'
  '★ 函数里**没有**"离职原因"这个变量，所以写不出原因、评价、竞业 —— '
  '《劳动合同法实施条例》第二十四条限定为四要素与工作年限；写多了，'
  '下家会追问，员工可以主张名誉侵权，而公司拿不出证据。';

