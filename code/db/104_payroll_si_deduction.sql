-- ============================================================================
-- 104_payroll_si_deduction.sql · 多险种社保 + 个税专项附加扣除
-- ----------------------------------------------------------------------------
-- 到 103 为止，社保只有一个数：养老 8%。真实工资条上至少四行：
-- 养老、医疗、失业、公积金（有的还有工伤/生育，但个人不缴）。
-- 只算养老的后果不是"少扣一点"，是**实发比该发的多**，而多发的钱退不回来。
--
-- 专项附加扣除（子女教育/房贷/租房/赡养老人/继续教育）也是同理：
-- 不扣就等于多扣个税，员工每月少拿到手的钱，年底汇算才找回来 ——
-- 而那时候他已经觉得"这个系统算错了"。
--
-- ── 三条设计判断 ──────────────────────────────────────────────────────────
--
-- ① **险种从 si_policy 循环取，不写死**：客户在哪个城市、公积金比例多少，
--    是配置；写成 `pension 0.08` 的常量，等于替客户决定了社保政策。
--    没有政策的险种**跳过**（不是按 0 算，也不是报错）—— 见 ②。
--
-- ② **养老必须有政策**，其余可以没有：养老是法定必缴，缺它一定是配置漏了
--    （E_SI_POLICY_MISSING）；医疗/失业/公积金在部分地区/部分人群可以没有
--    （比如外地农业户口不缴公积金），按"没配就不缴"处理，并在工资条上看得到。
--
-- ③ **专项附加扣除不进明细行**：它不改变"应发"，只改变"应纳税所得"。
--    塞进 payslip_item 会让勾稽（明细和 = 应发 − 社保 − 个税）不平，
--    而那条勾稽是工资条唯一能自证的方式。所以它是 payslip 的一列。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 专项附加扣除
-- ---------------------------------------------------------------------------
CREATE TABLE tax_deduction (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id      bigint NOT NULL REFERENCES person(id),
  kind           varchar(24) NOT NULL,
  monthly_amount numeric(12,2) NOT NULL CHECK (monthly_amount >= 0),
  valid_from     date NOT NULL,
  valid_to       date,
  note           varchar(200),
  created_by     varchar(64) NOT NULL DEFAULT 'system',
  created_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_td_kind CHECK (kind IN
    ('child_edu','infant_care','housing_loan','housing_rent','elderly','continuing_edu')),
  CONSTRAINT ck_td_span CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

CREATE INDEX ix_td_person ON tax_deduction (person_id, valid_from DESC);

COMMENT ON TABLE tax_deduction IS
  '个税专项附加扣除（按月额度）。一个人的同一类扣除不允许重叠 —— '
  '重叠后"这个月扣多少"取决于查询习惯，而查询习惯会变。';

ALTER TABLE tax_deduction ADD CONSTRAINT ex_td_no_overlap
  EXCLUDE USING gist (person_id WITH =, kind WITH =,
                      daterange(valid_from, valid_to, '[]') WITH &&);

CREATE OR REPLACE FUNCTION fn_tax_deduction(p_person bigint, p_on date)
RETURNS numeric
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT COALESCE(sum(monthly_amount), 0)::numeric(12,2)
    FROM public.tax_deduction
   WHERE person_id = p_person AND daterange(valid_from, valid_to, '[]') @> p_on;
$$;

COMMENT ON FUNCTION fn_tax_deduction IS
  '某人某月的专项附加扣除合计。只认当期有效的 —— 房贷还完了要关掉，不能一直扣。';

-- 工资条补一列：它是计税基数的一部分，不是明细项（见文件头 ③）
ALTER TABLE payslip
  ADD COLUMN IF NOT EXISTS special_deduction numeric(12,2) NOT NULL DEFAULT 0;

