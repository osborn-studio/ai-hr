-- ============================================================================
-- 145_roster_write.sql · 排班补上写入路径（062 那条 P0 债的收尾）
-- ----------------------------------------------------------------------------
-- 062 记的债说得很清楚：008 的三张表（schedule / schedule_segment / confirm_sheet）
-- **没有任何写入路径**，只能靠种子插。后果不是"少一个功能"，是
-- `CONFIRM_MISSING` 这条异常项永远返回它该有的那几个数 —— 一条永远不变的异常，
-- 比没有这一项更坏：它看起来在工作。
--
-- 这一轮把那条路补上，并且**只补一条**：计划 → 段 → 确认单 → 门店确认 → 锁定。
-- 每一步都是业务动作，不是一个"通用写接口"：
--
--   ① **排班（fn_roster_assign）**：人 × 日 × 班次。按 shift_def 的上下班时间
--      落成当天的一个段（跨零点落到次日）；建段就**同事务建确认单**（not_started）。
--      "段有行、确认单没有行"在 008 里是**缺陷**，所以它不能靠人记得去补 ——
--      生成段的那一句旁边就生成单。
--
--   ② **推送（fn_roster_push）**：把该店该期间还没开始的确认单推到门店，
--      并写下"本该谁确认、何时到期"。**没有可推的就报错**：推一份空周表
--      给门店，等于让人签一张没内容的字。
--
--   ③ **确认（fn_roster_confirm）**：只收 pushed。门店说不行就必须写意见 ——
--      没有意见的争议，排班的人改不了也改不动（他不知道改哪里）。
--
--   ④ **锁定（fn_roster_lock）**：只从 store_confirmed 锁。**有争议不许锁** ——
--      锁定的意思是"这张表门店认了，之后不再改"，而争议还在的时候锁，
--      等于把争议一起封进去。
--
-- ★ 三条与排班有关的判断，写在这里是因为它们都有代价：
--
--   · **同人同日不许时间重叠**：重叠的段在算薪那边是两倍工时，而"排错了"
--     与"加了班"在段表里长得一样。用 EXISTS + 区间相交判，**不加 EXCLUDE 约束** ——
--     表上已有数据未必过得了那条约束，加约束会在升级当天把库拦住。
--     判的时候要看**前一天/后一天**的段：只看当天会漏掉跨零点的那一段。
--
--   · **跨店支援要写原因**：p_store 与这个人的成本组织不同，就不是"顺手一排"，
--     是一次承诺（谁的人、给谁用、用到哪天）。少于 4 个字直接拒。
--     没登记成本组织的人也算跨店 —— 不知道他属于哪家店时，"这不是跨店"
--     是一个没有依据的结论。
--
--   · **锁定/门店已确认的班不能改**：锁定是门店签过的字。要改先退回，
--     退回这个动作现在没有入口 —— 那是**故意**的：退回顾名思义要有人负责，
--     而不是页面上一个"撤销"按钮。
--
-- ★ 两件不做的事：
--   · 不做"超时自动确认"（008 的 timeout_auto）。本仓没有调度器，
--     写成"打开页面时顺带算一下"就变成"谁登录谁触发"，那不是定时。
--   · 不同步 067 的 roster_slot 看板层。两张表各写一遍必然漂，
--     页面这一轮改用 fn_roster_week（直接读 schedule/segment）——
--     旧看板函数改名为 fn_roster_slot_week，名字说出它读的是哪张表。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 0. 三张表的主键补生成方式（第十一次同一个坑）
-- ---------------------------------------------------------------------------
-- 008 写的是 `id bigint PRIMARY KEY`，没有 IDENTITY。种子与测试都写显式 id，
-- 所以从来没红过；而"排一个班"是第一个**由人正常插入**它的路径，
-- 一插就是 23502 not-null on id —— 报错指向 id，看起来像数据缺失。
-- 与 142 给 si_policy 补 IDENTITY 是同一条规矩：
-- **凡"会被 INSERT 的表"，主键一律给生成方式。**
DO $$
DECLARE
  v_tbl text;
BEGIN
  FOREACH v_tbl IN ARRAY ARRAY['schedule','schedule_segment','confirm_sheet'] LOOP
    IF NOT EXISTS (SELECT 1 FROM pg_attribute
                    WHERE attrelid = ('public.' || v_tbl)::regclass
                      AND attname = 'id' AND attidentity <> '') THEN
      EXECUTE format('ALTER TABLE public.%I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY',
                     v_tbl);
      -- 存量用的是显式 id，序列没被推过 —— 不 setval 的话下一条就撞 1
      EXECUTE format(
        'SELECT setval(pg_get_serial_sequence(%L, %L), '
        '              GREATEST((SELECT COALESCE(max(id), 1) FROM public.%I), 1))',
        'public.' || v_tbl, 'id', v_tbl);
    END IF;
  END LOOP;
END $$;

-- ---------------------------------------------------------------------------
-- 1. 班次补一个稳定的数字 id
-- ---------------------------------------------------------------------------
-- 062 的债第一个问题就是"`schedule.shift_id` 连外键都没有"。它现在仍然没有外键
-- （存量数据里的 shift_id 是种子随手写的 1），但**新写入必须有个可信的映射**，
-- 否则每排一次班就要猜一个数字。给 shift_def 加一列，值只增不改：
-- 以后新增班次由同一段 DO 继续往后编号，历史 schedule 的 shift_id 永远指得回去。
ALTER TABLE shift_def ADD COLUMN IF NOT EXISTS shift_id bigint;

DO $$
DECLARE
  v_base bigint;
BEGIN
  SELECT COALESCE(max(shift_id), 0) INTO v_base FROM public.shift_def;
  WITH t AS (
    SELECT code, row_number() OVER (ORDER BY start_time, end_time, code) AS rn
      FROM public.shift_def WHERE shift_id IS NULL
  )
  UPDATE public.shift_def s SET shift_id = v_base + t.rn
    FROM t WHERE s.code = t.code;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS ux_sd_shift_id ON shift_def (shift_id);

COMMENT ON COLUMN shift_def.shift_id IS
  '班次的数字 id（145）。schedule.shift_id 存的就是它 —— schedule.shift_id 仍然没有外键'
  '（008 的存量数据对不上），但**新排班只写这一列的值**，不再现编数字。';

-- ---------------------------------------------------------------------------
-- 2. 争议意见要落库
-- ---------------------------------------------------------------------------
-- 008 的 confirm_sheet 只记状态，不记"为什么不行"。门店点"有争议"而不写原因的话，
-- 排班的人拿到一个 disputed、不知道改哪里 —— 于是他会按自己的猜测改，
-- 而猜错的那一次会以"门店又退回"结束，两轮之后这条流程就没人用了。
ALTER TABLE confirm_sheet ADD COLUMN IF NOT EXISTS dispute_note varchar(500);

COMMENT ON COLUMN confirm_sheet.dispute_note IS
  '门店退回的原因（145）。只在 status=''disputed'' 时写，其它状态必须为空 —— '
  '它不是备注栏，是"这条排班为什么不行"的证据。';

-- ---------------------------------------------------------------------------
-- 3. 排班：一段一班，建段即建确认单
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_roster_assign(
  p_employee bigint,
  p_date     date,
  p_shift    varchar,
  p_store    bigint,
  p_reason   varchar,
  p_by       varchar
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_sd     record;
  v_sched  bigint;
  v_seg    bigint;
  v_start  timestamptz;
  v_end    timestamptz;
  v_cost   bigint;
  v_state  int;
BEGIN
  IF p_employee IS NULL OR p_date IS NULL OR p_store IS NULL THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 人、日期、门店都不能为空';
  END IF;

  -- ★ 员工必须真的在职。没有这条，随便传一个 id 就能造出一条"不存在的人"的段，
  --   而且不报错：页面看不见、考勤不会去查、算薪也不会碰上它 ——
  --   直到有人对着 schedule 表问"store_id=1 这条是谁的"。
  --   只校验"这个人存在"，不校验"这一天在职"：排完班再离职是真实会发生的
  --   （人还没走，下个月的班先排上），把在职日也卡住会把这种正常操作拦在门外。
  IF NOT EXISTS (SELECT 1 FROM public.employment em WHERE em.person_id = p_employee) THEN
    RAISE EXCEPTION 'E_ROSTER_NO_EMPLOYEE: 人 % 在库里没有任何任职记录（排班要挂在真人身上）',
      p_employee;
  END IF;

  SELECT * INTO v_sd FROM public.shift_def WHERE code = p_shift;
  IF v_sd.code IS NULL THEN
    RAISE EXCEPTION 'E_ROSTER_SHIFT: 班次 % 不存在', p_shift;
  END IF;
  IF v_sd.shift_id IS NULL THEN
    RAISE EXCEPTION 'E_ROSTER_SHIFT: 班次 % 没有 shift_id，重跑 145 迁移', p_shift;
  END IF;

  -- ① 锁定 / 门店已确认：先看这个人当天已有的单到哪一步
  --    ★ 争议不拦改班：disputed 的出口就是"改排班后重新推送"，
  --      把它也拦住的话，争议一旦产生就再也解不开（confirm 只收 pushed）。
  SELECT max(CASE cs.status WHEN 'locked' THEN 3
                            WHEN 'store_confirmed' THEN 2
                            ELSE 0 END)
    INTO v_state
    FROM public.schedule s
    JOIN public.schedule_segment sg ON sg.schedule_id = s.id
    JOIN public.confirm_sheet cs ON cs.segment_id = sg.id
   WHERE s.employee_id = p_employee AND s.work_date = p_date;

  IF v_state = 3 THEN
    RAISE EXCEPTION 'E_ROSTER_LOCKED: % 在 % 的排班已锁定，改班要先退回（那是门店签过的字）',
      p_employee, p_date;
  END IF;
  IF v_state = 2 THEN
    RAISE EXCEPTION 'E_ROSTER_CONFIRMED: % 在 % 的排班门店已确认，改班要先退回成"未开始"',
      p_employee, p_date;
  END IF;

  -- ② 跨店支援：p_store 与人所属的成本组织不同
  --    ★ 没登记成本组织（NULL）也算跨店：不知道他属于哪家店时，
  --      "这不是跨店"是一个没有依据的结论。
  SELECT a.org_id INTO v_cost
    FROM public.employee_org_assignment a
   WHERE a.employee_id = p_employee
     AND a.dim_code = 'cost_org'
     AND daterange(a.valid_from, a.valid_to, '[]') @> p_date
   ORDER BY a.valid_from DESC
   LIMIT 1;

  IF v_cost IS DISTINCT FROM p_store
     AND length(btrim(COALESCE(p_reason, ''))) < 4 THEN
    RAISE EXCEPTION 'E_ROSTER_CROSS_REASON: % 的成本组织是 %，排到门店 % 属于跨店支援 —— '
                    '要写至少 4 个字的原因（跨店是一次承诺，不是顺手一排）',
      p_employee, COALESCE(v_cost::text, '未登记'), p_store;
  END IF;

  -- ③ 时间：当天上下班；下班 <= 上班 = 跨零点，落到次日
  IF NOT v_sd.is_rest THEN
    v_start := (p_date + v_sd.start_time) AT TIME ZONE public.app_tz();
    v_end   := (p_date + v_sd.end_time)   AT TIME ZONE public.app_tz();
    IF v_end <= v_start THEN
      v_end := v_end + interval '1 day';
    END IF;

    -- ④ 同人相邻日不许时间重叠
    --    ★ 只看当天会漏掉跨零点那一段：昨天闭店 17:00-01:00 撞不到今天的早班，
    --      但昨天 20:00 起的加班段会撞今天的早班。
    --    ★ 用区间相交判，不加 EXCLUDE 约束：存量数据未必过得了约束，
    --      约束会在升级当天把库拦住，而它拦的是"历史"，不是"这次排错"。
    IF EXISTS (
      SELECT 1
        FROM public.schedule s
        JOIN public.schedule_segment sg ON sg.schedule_id = s.id
       WHERE s.employee_id = p_employee
         AND s.work_date BETWEEN p_date - 1 AND p_date + 1
         AND s.work_date <> p_date      -- 当天旧班要换掉，不算冲突
         AND tstzrange(sg.start_at, sg.end_at, '[)') && tstzrange(v_start, v_end, '[)')
    ) THEN
      RAISE EXCEPTION 'E_ROSTER_OVERLAP: % 在 % 前后已有与 %-% 重叠的段（同一时段两段 = 两倍工时）',
        p_employee, p_date, v_start, v_end;
    END IF;
  END IF;

  -- ⑤ 同一天可以有多段（上午 A 店、下午 B 店），但**时段不许重叠**
  --   ★ 第一版是"当天旧班整条删掉换新"：排班人以为加了第二个班、实际把第一个
  --     覆盖掉了，而页面上那格只显示一个班，看不出少了东西。静默覆盖比报错难查。
  --     008 的 UNIQUE(employee_id, work_date, shift_id) 本来就允许同日多个班次 ——
  --     那是为跨店支援留的位，删掉它就等于把这个能力焊死。
  --   ★ 同一班次重复点 → 幂等：返回已有那条。重复点不该报错，也不该多一条。
  SELECT s.id INTO v_sched
    FROM public.schedule s
   WHERE s.employee_id = p_employee AND s.work_date = p_date
     AND s.shift_id = v_sd.shift_id AND s.store_id = p_store
   LIMIT 1;
  IF v_sched IS NOT NULL THEN RETURN v_sched; END IF;

  IF NOT v_sd.is_rest AND EXISTS (
    SELECT 1
      FROM public.schedule s
      JOIN public.schedule_segment sg ON sg.schedule_id = s.id
     WHERE s.employee_id = p_employee AND s.work_date = p_date
       AND tstzrange(sg.start_at, sg.end_at, '[)') && tstzrange(v_start, v_end, '[)')
  ) THEN
    RAISE EXCEPTION 'E_ROSTER_OVERLAP: % 在 % 已有与 %-% 重叠的班次'
      '（同一时段两段 = 两倍工时；要换班请先清掉那一段）',
      p_employee, p_date, v_start, v_end;
  END IF;

  INSERT INTO public.schedule(employee_id, work_date, shift_id, store_id)
  VALUES (p_employee, p_date, v_sd.shift_id, p_store)
  RETURNING id INTO v_sched;

  -- ★★ 同时写一行 roster_slot（067 那张表）。不是冗余，是**必须**：
  --   roster_slot 还在算薪链路上，有四个读者：
  --     · fn_att_person_period —— PAY_WORKDAYS_SOURCE='roster' 时的应出勤天数
  --     · fn_is_rest_day（120/125 两版）—— 休息日加班判定（200% 还是 150%）
  --     · fn_att_period_report —— 考勤报表的排班天数
  --   只写 schedule 不写它，这几处会静默退化：应出勤变 0（退回日历）、
  --   休息日加班全部按平日算 —— 而页面看起来一切正常，错的是钱。
  --   两张表并存不好，但"改四个读者"是另一次大手术；这里先用**单一写入口双写**
  --   把它焊住，并在 145 头部登记为待清理。
  --   ★ UNIQUE(employee_id, work_date) 只容一行：同一天多段时这里存第一段
  --     （roster_slot 只回答"这天有没有班、什么班"，不承载分段）。
  INSERT INTO public.roster_slot(employee_id, store_id, work_date, shift_code, updated_by)
  VALUES (p_employee, p_store, p_date, p_shift, p_by)
  ON CONFLICT (employee_id, work_date) DO UPDATE
    SET store_id = EXCLUDED.store_id,
        shift_code = EXCLUDED.shift_code,
        updated_by = EXCLUDED.updated_by,
        updated_at = now();

  -- ⑥ 建段 + 确认单同生
  --    ★ 008：段表有行 = 该有确认单。"漏生成"不是一种状态，是一个缺陷。
  --      所以这两条 INSERT 必须挨着写，中间不能有"以后再补"的余地。
  IF NOT v_sd.is_rest THEN
    INSERT INTO public.schedule_segment(schedule_id, seq, store_id, start_at, end_at)
    VALUES (v_sched, 1, p_store, v_start, v_end)
    RETURNING id INTO v_seg;

    INSERT INTO public.confirm_sheet(segment_id, status)
    VALUES (v_seg, 'not_started');
  END IF;

  RETURN v_sched;
END;
$$;

COMMENT ON FUNCTION fn_roster_assign IS
  '排一个班（145）：按 shift_def 落段（跨零点落到次日），建段即建确认单（not_started）。'
  '同人相邻日区间重叠拒（E_ROSTER_OVERLAP）、锁定或门店已确认拒（E_ROSTER_LOCKED / '
  'E_ROSTER_CONFIRMED）、跨店无原因拒（E_ROSTER_CROSS_REASON）。'
  '休息班只建 schedule 不建段 —— 段表里"休息"不是一段工时。';

-- ---------------------------------------------------------------------------
-- 3b. 撤销：排错的班要能撤，否则"改"这件事没有出路
-- ---------------------------------------------------------------------------
-- ★ 为什么必须有这一个函数：`fn_roster_assign` 不覆盖同日已有的段（重叠就拒），
--   而 `fn_roster_confirm` 只收 pushed —— 于是门店退回（disputed）之后，
--   这条排班**改不了（重叠）、锁不上（有争议）、也撤不掉**，整条流程死在这里。
--   一个"有争议就再也解不开"的确认流程，最后一定会变成"谁都不点争议"。
--
-- ★ 撤销为什么不做成"assign 时静默覆盖"：
--   排班人以为加了第二个班、实际把第一个覆盖掉了，页面上那格只剩一个班，
--   看不出少了东西 —— 静默覆盖比报错难查。要撤就显式撤。
--
-- ★ 已锁定 / 门店已确认的照样拒：撤销也是一种改。要撤先退回，
--   而"退回"这个动作现在没有入口，那是故意的（它得有个人负责）。
CREATE OR REPLACE FUNCTION fn_roster_clear(
  p_employee bigint, p_date date, p_shift varchar, p_by varchar
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_shift bigint;
  v_state int;
  v_n     int;
BEGIN
  IF p_employee IS NULL OR p_date IS NULL THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 人和日期都不能为空';
  END IF;

  -- p_shift 为空 = 撤这一天全部（排错了整天时用）。给了班次就只撤那一个。
  IF p_shift IS NOT NULL THEN
    SELECT shift_id INTO v_shift FROM public.shift_def WHERE code = p_shift;
    IF v_shift IS NULL THEN
      RAISE EXCEPTION 'E_ROSTER_SHIFT: 班次 % 不存在', p_shift;
    END IF;
  END IF;

  SELECT max(CASE cs.status WHEN 'locked' THEN 3
                            WHEN 'store_confirmed' THEN 2
                            ELSE 0 END)
    INTO v_state
    FROM public.schedule s
    LEFT JOIN public.schedule_segment sg ON sg.schedule_id = s.id
    LEFT JOIN public.confirm_sheet cs ON cs.segment_id = sg.id
   WHERE s.employee_id = p_employee AND s.work_date = p_date
     AND (v_shift IS NULL OR s.shift_id = v_shift);

  IF v_state = 3 THEN
    RAISE EXCEPTION 'E_ROSTER_LOCKED: % 在 % 的排班已锁定，撤班要先退回（那是门店签过的字）',
      p_employee, p_date;
  END IF;
  IF v_state = 2 THEN
    RAISE EXCEPTION 'E_ROSTER_CONFIRMED: % 在 % 的排班门店已确认，撤班要先退回成"未开始"',
      p_employee, p_date;
  END IF;

  -- 段与确认单随 schedule 级联删除（008 的外键是 ON DELETE CASCADE）
  DELETE FROM public.schedule s
   WHERE s.employee_id = p_employee AND s.work_date = p_date
     AND (v_shift IS NULL OR s.shift_id = v_shift);
  GET DIAGNOSTICS v_n = ROW_COUNT;

  -- ★ 同步撤掉 roster_slot（算薪链路上那四个读者看的是它）。
  --   只删 schedule 不删它，会出现"排班表上没了、算薪还认为他那天上班"。
  --   ★ 判据用"这一天还剩不剩班"，而不是按班次匹配：shift_def 的主键是 code，
  --     schedule.shift_id 是另一个序列，两边没有可直接比的列（写 d.id 会直接
  --     报 column does not exist —— 而且是在建库时就炸，整条迁移都过不去）。
  --     同一天多段时，撤掉其中一段不该把 roster_slot 一起删掉，所以看"还剩没剩"。
  IF NOT EXISTS (SELECT 1 FROM public.schedule s2
                  WHERE s2.employee_id = p_employee AND s2.work_date = p_date) THEN
    DELETE FROM public.roster_slot r
     WHERE r.employee_id = p_employee AND r.work_date = p_date;
  END IF;

  IF v_n = 0 THEN
    RAISE EXCEPTION 'E_ROSTER_BAD_STATE: % 在 % 没有可撤的班（% 那条也没排过）',
      p_employee, p_date, COALESCE(p_shift, '任意班次');
  END IF;

  RETURN v_n;
END;
$$;

COMMENT ON FUNCTION fn_roster_clear IS
