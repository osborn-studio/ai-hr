-- ---------------------------------------------------------------------------
-- 4. 门店确认流程：推 → 确认 → 锁定
-- ---------------------------------------------------------------------------
-- 该期间的段（按段的门店，不是排班门店：跨店支援时签字的是收人的那家店）
CREATE OR REPLACE FUNCTION fn_roster_push(
  p_store bigint, p_period varchar, p_by varchar
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_from  date;
  v_to    date;
  v_days  numeric;
  v_due   timestamptz;
  v_owner bigint;
  v_n     int;
BEGIN
  IF p_store IS NULL THEN RAISE EXCEPTION 'E_ARG_INVALID: 门店必填'; END IF;
  IF p_period !~ '^\d{4}-\d{2}$' THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 期间写 YYYY-MM（收到 %）', p_period;
  END IF;
  v_from := to_date(p_period || '-01', 'YYYY-MM-DD');
  v_to   := (v_from + interval '1 month')::date;

  -- 到期日：制度项 CLOSE_DAY 天；**取不到就用 3 天**。
  -- 制度项没登记时 fn_policy_effective 会抛 E_POLICY_UNDEFINED，
  -- 所以先看 policy_def 有没有这一项 —— 排班不该因为"还没配这项制度"整批推不出去。
  IF EXISTS (SELECT 1 FROM public.policy_def WHERE code = 'CLOSE_DAY') THEN
    SELECT value_num INTO v_days
      FROM public.fn_policy_effective('CLOSE_DAY', p_store, public.app_today());
  END IF;
  v_days := COALESCE(v_days, 3);
  IF v_days < 1 THEN v_days := 1; END IF;   -- 0 天 = 当天到期，等于逼门店当场签
  v_due := ((public.app_today() + v_days::int)::timestamp + interval '1 day - 1 second')
             AT TIME ZONE public.app_tz();

  -- 本该谁确认：该店的店长账号（角色 store_mgr **且数据范围覆盖这家店**）。
  -- ★ 不用 fn_appr_resolve_role：它的 direct 分支只按角色取人、不看组织，
  --   会把 A 店店长当成 C 店店长的确认人。
  -- ★ 多个店长都覆盖这家店时，**离得最近的赢**（范围锚点更深的那一个）：
  --   一个挂"整棵树"的集团级店长与一个只管本店的店长同时存在时，
  --   该签这张表的是本店那个 —— 按 id 随便挑一个，会让签字人变成"系统选的"。
  -- ★ 取不到就是 NULL —— 不编一个"第一个账号"出来。
  --   界面上显示"未指派确认人"比显示一个错的店长好。
  SELECT a.id INTO v_owner
    FROM public.sys_user_role ur
    JOIN public.sys_account a ON a.id = ur.user_id AND a.status = 'active'
    JOIN public.sys_role r ON r.id = ur.role_id AND r.code = 'store_mgr' AND r.is_active
   WHERE ur.superseded_by IS NULL
     AND daterange(ur.effective_from, ur.effective_to, '[)') @> public.app_today()
     AND EXISTS (
       SELECT 1 FROM public.sys_data_scope_rule ru
        JOIN public.org_unit tgt ON tgt.id = p_store
        WHERE ru.data_scope_id = ur.data_scope_id
          AND ru.dimension IN ('attendance_org', 'cost_org')
          AND (ru.value_type = 'all'
               OR (ru.value_type = 'nodes' AND p_store = ANY(ru.value_ids))
               OR (ru.value_type = 'node_subtree' AND EXISTS (
                     SELECT 1 FROM public.org_unit st
                      WHERE st.id = ANY(ru.value_ids)
                        AND tgt.path LIKE st.path || '%')))
     )
   ORDER BY (
     -- 覆盖锚点有多深：'nodes' 的锚点就是这家店本身（最深），
     -- 'node_subtree' 的锚点是子树的根（越往下越具体），'all' 最浅（0）
     SELECT max(CASE ru2.value_type
                  WHEN 'all'   THEN 0
                  WHEN 'nodes' THEN length((SELECT path FROM public.org_unit WHERE id = p_store))
                  ELSE length(st.path)
                END)
       FROM public.sys_data_scope_rule ru2
       LEFT JOIN public.org_unit st ON st.id = ANY(ru2.value_ids)
      WHERE ru2.data_scope_id = ur.data_scope_id
        AND ru2.dimension IN ('attendance_org', 'cost_org')
   ) DESC, a.id
   LIMIT 1;

  UPDATE public.confirm_sheet cs
     SET status = 'pushed', confirm_due_at = v_due, confirm_owner_id = v_owner
    FROM public.schedule_segment sg
    JOIN public.schedule s ON s.id = sg.schedule_id
   WHERE cs.segment_id = sg.id
     AND sg.store_id = p_store
     AND s.work_date >= v_from AND s.work_date < v_to
     AND cs.status = 'not_started';
  GET DIAGNOSTICS v_n = ROW_COUNT;

  -- ★ 推一份空周表给门店，等于让人签一张没内容的字：签了之后"这周没问题"是假的。
  IF v_n = 0 THEN
    RAISE EXCEPTION 'E_ROSTER_EMPTY: 门店 % 的 % 没有待推送的确认单（推空表等于让人签一张没内容的字）',
      p_store, p_period;
  END IF;

  RETURN v_n;
END;
$$;

COMMENT ON FUNCTION fn_roster_push IS
  '把该店该期间 not_started 的确认单推到 pushed（145），并写确认人与到期日。'
  '到期日取制度项 CLOSE_DAY（没配就用 3 天），确认人取该店店长账号（取不到为 NULL）。'
  '没有可推的报 E_ROSTER_EMPTY —— 空表不许推。';

CREATE OR REPLACE FUNCTION fn_roster_confirm(
  p_store bigint, p_period varchar, p_ok boolean, p_note varchar, p_by varchar
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_from   date;
  v_to     date;
  v_n      int;
  v_states text;
BEGIN
  IF p_store IS NULL THEN RAISE EXCEPTION 'E_ARG_INVALID: 门店必填'; END IF;
  IF p_period !~ '^\d{4}-\d{2}$' THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 期间写 YYYY-MM（收到 %）', p_period;
  END IF;
  v_from := to_date(p_period || '-01', 'YYYY-MM-DD');
  v_to   := (v_from + interval '1 month')::date;

  IF p_ok IS NULL THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 要明确说"认可"还是"不认可"（ok=1 / ok=0）';
  END IF;

  -- ★ 不认可必须写意见：没有意见的争议，排班的人不知道改哪里。
  IF NOT p_ok AND length(btrim(COALESCE(p_note, ''))) < 4 THEN
    RAISE EXCEPTION 'E_ROSTER_NO_NOTE: 退回必须写意见（至少 4 个字）—— 没有意见的争议，门店改不了也改不动';
  END IF;

  UPDATE public.confirm_sheet cs
     SET status = CASE WHEN p_ok THEN 'store_confirmed' ELSE 'disputed' END,
         dispute_note = CASE WHEN p_ok THEN NULL ELSE btrim(p_note) END
    FROM public.schedule_segment sg
    JOIN public.schedule s ON s.id = sg.schedule_id
   WHERE cs.segment_id = sg.id
     AND sg.store_id = p_store
     AND s.work_date >= v_from AND s.work_date < v_to
     AND cs.status = 'pushed';
  GET DIAGNOSTICS v_n = ROW_COUNT;

  -- 一条都没转到：把"现在都是什么状态"点出来 —— 只说"没有可确认的单"
  -- 会让人以为这条期间是空的，实际上可能是还没推，或者已经确认完了。
  IF v_n = 0 THEN
    SELECT string_agg(t.status || '×' || t.n, '、' ORDER BY t.status) INTO v_states
      FROM (SELECT cs.status, count(*) AS n
              FROM public.confirm_sheet cs
              JOIN public.schedule_segment sg ON sg.id = cs.segment_id
              JOIN public.schedule s ON s.id = sg.schedule_id
             WHERE sg.store_id = p_store
               AND s.work_date >= v_from AND s.work_date < v_to
             GROUP BY cs.status) t;
    RAISE EXCEPTION 'E_ROSTER_BAD_STATE: 门店 % 的 % 没有"已推送"的确认单，只能从已推送转（当前：%）',
      p_store, p_period, COALESCE(v_states, '一条单都没有');
  END IF;

  -- 谁点的确认没写进 confirm_sheet：008 的 confirmed_by 只在 source='manual'
  -- （= 最终锁定）时才有意义，ck_cs_source_consistent 不允许它随手填。
  -- 这一动作的人留在 app 层留痕里（runWrite 的 actor）。
  RETURN v_n;
END;
$$;

COMMENT ON FUNCTION fn_roster_confirm IS
  '门店确认（145）：只能从 pushed 转 —— 认可 → store_confirmed，不认可 → disputed 且必须写意见。'
  '返回条数；一条都转不动时报 E_ROSTER_BAD_STATE 并把当前各状态点出来。';

CREATE OR REPLACE FUNCTION fn_roster_lock(
  p_store bigint, p_period varchar, p_by varchar
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_from   date;
  v_to     date;
  v_n      int;
  v_dis    int;
  v_first  date;
  v_states text;
  v_uid    bigint;
BEGIN
  IF p_store IS NULL THEN RAISE EXCEPTION 'E_ARG_INVALID: 门店必填'; END IF;
  IF p_period !~ '^\d{4}-\d{2}$' THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 期间写 YYYY-MM（收到 %）', p_period;
  END IF;
  v_from := to_date(p_period || '-01', 'YYYY-MM-DD');
  v_to   := (v_from + interval '1 month')::date;

  -- ★ 有争议不许锁：锁定的意思是"这张表门店认了，之后不再改"。
  --   争议还在的时候锁，等于把争议一起封进去 —— 之后既没人改，也没人知道它不对。
  SELECT count(*)::int, min(s.work_date) INTO v_dis, v_first
    FROM public.confirm_sheet cs
    JOIN public.schedule_segment sg ON sg.id = cs.segment_id
    JOIN public.schedule s ON s.id = sg.schedule_id
   WHERE sg.store_id = p_store
     AND s.work_date >= v_from AND s.work_date < v_to
     AND cs.status = 'disputed';

  IF v_dis > 0 THEN
    RAISE EXCEPTION 'E_ROSTER_BAD_STATE: 门店 % 的 % 还有 % 条争议没处理（最早 %）—— 先处理争议再锁定',
      p_store, p_period, v_dis, v_first;
  END IF;

  -- 锁定的人：p_by 可能是登录名（人手动调用），也可能是账号 id（app 层传的 uid，
  -- 见 server.mjs 的 runWrite actor）—— 两种都认，先认登录名。
  -- 能解出账号就记成 manual（008 的"已确认"要靠这个来源区分）；
  -- 解不出就留 NULL —— 那会让 v_segment_confirm 显示 unconfirmed，
  -- 这是对的：说不清是谁锁的，就不该在报表上算"有人确认过"。
  SELECT id INTO v_uid FROM public.sys_account
   WHERE login = btrim(COALESCE(p_by, '')) LIMIT 1;
  IF v_uid IS NULL THEN
    SELECT id INTO v_uid FROM public.sys_account
     WHERE id::text = btrim(COALESCE(p_by, '')) LIMIT 1;
  END IF;

  UPDATE public.confirm_sheet cs
     SET status  = 'locked',
         source  = CASE WHEN v_uid IS NULL THEN NULL ELSE 'manual' END,
         confirmed_by = v_uid,
         auto_confirmed_at = NULL
    FROM public.schedule_segment sg
    JOIN public.schedule s ON s.id = sg.schedule_id
   WHERE cs.segment_id = sg.id
     AND sg.store_id = p_store
     AND s.work_date >= v_from AND s.work_date < v_to
     AND cs.status = 'store_confirmed';
  GET DIAGNOSTICS v_n = ROW_COUNT;

  IF v_n = 0 THEN
    SELECT string_agg(t.status || '×' || t.n, '、' ORDER BY t.status) INTO v_states
      FROM (SELECT cs.status, count(*) AS n
              FROM public.confirm_sheet cs
              JOIN public.schedule_segment sg ON sg.id = cs.segment_id
              JOIN public.schedule s ON s.id = sg.schedule_id
             WHERE sg.store_id = p_store
               AND s.work_date >= v_from AND s.work_date < v_to
             GROUP BY cs.status) t;
    RAISE EXCEPTION 'E_ROSTER_BAD_STATE: 门店 % 的 % 没有"门店已确认"的单，只能从已确认锁（当前：%）',
      p_store, p_period, COALESCE(v_states, '一条单都没有');
  END IF;

  RETURN v_n;
END;
$$;

COMMENT ON FUNCTION fn_roster_lock IS
  '锁定（145）：只从 store_confirmed 锁；有 disputed 直接拒并点名条数与最早一天。'
  '锁定后 fn_roster_assign 拒改（E_ROSTER_LOCKED）。';

-- ---------------------------------------------------------------------------
-- 5. 周视图（读）：按 schedule/segment 出，不生成日期序列
-- ---------------------------------------------------------------------------
-- 078 的 fn_roster_week 读的是 067 的 roster_slot 看板层，与本文件写的
-- schedule/segment 是**两张表**。名字撞车且签名不同（旧的是 2 参），
-- PostgreSQL 的函数重载在"有默认值的版本"与"参数更少的版本"同时存在时，
-- 2 参调用会直接 `function is not unique` —— 所以旧的那个改名，名字也说出它读什么。
DROP FUNCTION IF EXISTS fn_roster_week(bigint, date);

CREATE FUNCTION fn_roster_slot_week(p_store bigint, p_from date)
RETURNS TABLE (employee_id bigint, employee_no varchar, full_name varchar,
               work_date date, shift_code varchar, color varchar, shift_name varchar,
               work_minutes int, segments jsonb)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
BEGIN
  RETURN QUERY
  SELECT p.id, n.no, p.full_name, g.d::date, s.shift_code, sd.color, sd.name,
         sd.work_minutes, sd.segments
    FROM generate_series(p_from, p_from + 6, interval '1 day') g(d)
    JOIN public.employment e ON daterange(e.hire_date, e.leave_date, '[]') @> g.d::date
    JOIN public.person p ON p.id = e.person_id
    JOIN public.employee_org_assignment a
      ON a.employee_id = p.id AND a.dim_code = 'attendance_org'
     AND daterange(a.valid_from, a.valid_to, '[]') @> g.d::date
    LEFT JOIN public.employee_no n ON n.assigned_person_id = p.id AND n.retired_at IS NULL
    LEFT JOIN public.roster_slot s ON s.employee_id = p.id AND s.work_date = g.d::date
    LEFT JOIN public.shift_def sd ON sd.code = s.shift_code
   WHERE ($1 IS NULL OR a.org_id = $1)
   ORDER BY p.id, g.d;
END;
$$;

COMMENT ON FUNCTION fn_roster_slot_week IS
  '067/078 的看板视图（145 改名）：读 roster_slot，人 × 日 × 班次。'
  '它**不参与算薪**；读 plan → 段 → 确认单那条链路的视图叫 fn_roster_week。';

CREATE FUNCTION fn_roster_week(p_store bigint, p_from date, p_days int DEFAULT 7)
RETURNS TABLE (employee_id bigint, person_name varchar, employee_no varchar,
               work_date date, shift_code varchar, shift_name varchar, color varchar,
               start_at timestamptz, end_at timestamptz, is_rest boolean,
               confirm_status varchar, seg_store_id bigint)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
BEGIN
  IF p_days IS NULL OR p_days < 1 OR p_days > 31 THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 天数取 1..31（收到 %）', p_days;
  END IF;

  -- ★ 只回有排班的格子，**不生成日期序列**：生成了的话"没排班"和"排了休息"
  --   在结果里长得一样（都是空班次），而这两件事完全不同 ——
  --   一个是"还没人排"，一个是"这天他休息"。空格由调用方补。
  RETURN QUERY
  SELECT sc.employee_id, pe.full_name::varchar,
         (SELECT n.no FROM public.employee_no n
           WHERE n.assigned_person_id = pe.id AND n.retired_at IS NULL
           ORDER BY n.assigned_at DESC LIMIT 1)::varchar,
         sc.work_date,
         COALESCE(sd.code, 'LINE'), COALESCE(sd.name, '划线'), COALESCE(sd.color, '#0f766e'),
         sg.start_at, sg.end_at, COALESCE(sd.is_rest, false),
         cs.status, sg.store_id
    FROM public.schedule sc
    JOIN public.person pe ON pe.id = sc.employee_id
    LEFT JOIN public.schedule_segment sg ON sg.schedule_id = sc.id
    LEFT JOIN public.confirm_sheet cs ON cs.segment_id = sg.id
    LEFT JOIN public.shift_def sd ON sd.shift_id = sc.shift_id
   WHERE sc.store_id = p_store
     AND sc.work_date >= p_from
     AND sc.work_date < p_from + p_days
   ORDER BY sc.employee_id, sc.work_date, sg.seq;
END;
$$;

COMMENT ON FUNCTION fn_roster_week IS
  '周视图（145）：该店这段日期里每个人的每天，从 schedule/segment 出。'
  '**只回有排班的格子**（稀疏行）—— 生成日期序列会把"没排班"和"排了休息"混成一样。'
  'confirm_status 取自确认单：not_started / pushed / store_confirmed / locked / disputed，'
  '休息班没有段，这几个字段为 NULL。';

