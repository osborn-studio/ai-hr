-- ============================================================================
-- 072_ext_sync.sql · 外部系统对接（钉钉/飞书）：三个域 + 账号绑定 + 运行记录
-- ----------------------------------------------------------------------------
-- 设计口径在 docs/14_打卡与钉钉飞书对接_设计.md，这里落的是那四条硬规矩：
--
--   ① **只接三个域**：组织、人员、考勤原始记录。不接"考勤结果"
--      （钉钉的迟到/缺卡判定是按它的考勤组规则算的，与本系统的休息扣除、
--      跨天归属口径不同，接结论等于把两套账混进一个字段）。
--   ② **全部单向**：外部 → 本系统。本系统改了不回写，因为"两边都能改"
--      必然产生"谁赢"的问题，而那个问题的答案会随时间变化。
--   ③ **对不上就不动**：外部人员没有映射时**不自动建人**，
--      而是进待处理清单 —— 自动建人会造出"未命名员工"，而它们会计进报表口径。
--   ④ **运行记录**：每次同步都留一行（总量/成功/跳过/失败/耗时/游标），
--      于是"同步停了"是页面上能看见的一件事，而不是"某天开始数据没动过"。
--
-- 本迁移只建结构与幂等入口；adapter 在 app/services/dingtalk.mjs，
-- 编排在 tools/sync-dingtalk.mjs。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 外部系统档案
-- ---------------------------------------------------------------------------
CREATE TABLE ext_system (
  code   varchar(16) PRIMARY KEY,          -- dingtalk | feishu
  name   varchar(32) NOT NULL,
  kind   varchar(16) NOT NULL,             -- im_hr
  note   varchar(200),
  CONSTRAINT ck_es_kind CHECK (kind IN ('im_hr'))
);

INSERT INTO ext_system(code, name, kind, note) VALUES
  ('dingtalk', '钉钉', 'im_hr', '组织/人员/考勤原始记录单向同步'),
  ('feishu',   '飞书', 'im_hr', '同上；adapter 未接')
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 2. 组织对照：外部部门 → 本地组织
-- ---------------------------------------------------------------------------
-- ★ 为什么允许多个外部部门映射到**同一个**本地组织：本系统的组织只有
--   集团/区域/门店三层（那是"算薪与考勤归属"的结构），而钉钉的部门是
--   "行政汇报线"，两者不同构。测试帐套里 15 个部门都挂在同一家门店下，
--   是**真实的选择**（一家店装全公司），不是偷懒 —— 部门名记在 ext_name 里。
CREATE TABLE ext_org_map (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  system_code varchar(16) NOT NULL REFERENCES ext_system(code),
  ext_id     varchar(64) NOT NULL,          -- 钉钉 deptId
  ext_name   varchar(128) NOT NULL,         -- 部门名快照（外部改名要看得见）
  ext_parent varchar(64),                   -- 上级部门 ext_id（用于还原树）
  org_id     bigint NOT NULL REFERENCES org_unit(id),
  synced_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uk_eom UNIQUE (system_code, ext_id)
);

-- ---------------------------------------------------------------------------
-- 3. 人员对照：外部用户 → person
-- ---------------------------------------------------------------------------
CREATE TABLE ext_person_map (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  system_code varchar(16) NOT NULL REFERENCES ext_system(code),
  ext_user_id varchar(64) NOT NULL,         -- 钉钉 userId
  person_id   bigint NOT NULL REFERENCES person(id),
  ext_name    varchar(64) NOT NULL,
  ext_dept    varchar(128),                 -- 部门名快照
  account_id  bigint,                       -- 建出来的登录账号（sys_account.id）
  synced_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uk_epm UNIQUE (system_code, ext_user_id)
);

CREATE INDEX ix_epm_person ON ext_person_map (person_id);

-- ---------------------------------------------------------------------------
-- 4. 同步运行记录（"同步停了"要能被看见）
-- ---------------------------------------------------------------------------
CREATE TABLE ext_sync_run (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  system_code varchar(16) NOT NULL REFERENCES ext_system(code),
  domain      varchar(16) NOT NULL,          -- org | person | punch
  started_at  timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  total_rows  int NOT NULL DEFAULT 0,
  ok_rows     int NOT NULL DEFAULT 0,
  skip_rows   int NOT NULL DEFAULT 0,
  fail_rows   int NOT NULL DEFAULT 0,
  cursor      varchar(64),                   -- 水位（本批处理到哪）
  note        text,
  run_by      varchar(64) NOT NULL DEFAULT 'sync',
  -- ★ 四个计数必须加起来等于总量：少掉的行不能"藏在中间"。
  --   与 066 的导入批次同一条纪律。
  CONSTRAINT ck_esr_sum CHECK (finished_at IS NULL
    OR ok_rows + skip_rows + fail_rows = total_rows),
  CONSTRAINT ck_esr_domain CHECK (domain IN ('org','person','punch','account'))
);

CREATE INDEX ix_esr_recent ON ext_sync_run (system_code, domain, started_at DESC);

/** 最近一次各域同步的健康度：滞后多少分钟、成没成 */
CREATE VIEW v_ext_sync_health AS
SELECT s.code AS system_code, s.name AS system_name, r.domain,
       r.started_at, r.finished_at, r.total_rows, r.ok_rows, r.skip_rows, r.fail_rows,
       round(extract(epoch FROM (now() - r.started_at)) / 60.0, 1) AS minutes_ago,
       (r.finished_at IS NOT NULL AND r.fail_rows = 0)              AS last_ok
  FROM ext_system s
  LEFT JOIN LATERAL (
    SELECT * FROM ext_sync_run x
     WHERE x.system_code = s.code
     ORDER BY x.started_at DESC LIMIT 1
  ) r ON true;

-- ---------------------------------------------------------------------------
-- 5. 同步入口：开始 / 结束
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_ext_sync_begin(
  p_system varchar, p_domain varchar, p_by varchar DEFAULT 'sync'
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_id bigint;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.ext_system WHERE code = p_system) THEN
    RAISE EXCEPTION 'E_EXT_SYSTEM: 外部系统 % 未登记', p_system;
  END IF;
  INSERT INTO public.ext_sync_run(system_code, domain, run_by)
  VALUES (p_system, p_domain, p_by) RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION fn_ext_sync_end(
  p_run bigint, p_total int, p_ok int, p_skip int, p_fail int,
  p_cursor varchar DEFAULT NULL, p_note text DEFAULT NULL
) RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  UPDATE public.ext_sync_run
     SET finished_at = now(), total_rows = p_total, ok_rows = p_ok,
         skip_rows = p_skip, fail_rows = p_fail, cursor = p_cursor, note = p_note
   WHERE id = p_run;
END;
$$;

-- ---------------------------------------------------------------------------
-- 6. 对照写入（幂等）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_ext_org_map_put(
  p_system varchar, p_ext_id varchar, p_ext_name varchar, p_ext_parent varchar,
  p_org bigint
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_id bigint;
BEGIN
  INSERT INTO public.ext_org_map(system_code, ext_id, ext_name, ext_parent, org_id, synced_at)
  VALUES (p_system, p_ext_id, p_ext_name, p_ext_parent, p_org, now())
  ON CONFLICT (system_code, ext_id) DO UPDATE
     SET ext_name = EXCLUDED.ext_name, ext_parent = EXCLUDED.ext_parent,
         org_id = EXCLUDED.org_id, synced_at = now()
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION fn_ext_person_map_put(
  p_system varchar, p_ext_user varchar, p_person bigint,
  p_ext_name varchar, p_ext_dept varchar, p_account bigint DEFAULT NULL
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_id bigint;
BEGIN
  INSERT INTO public.ext_person_map(system_code, ext_user_id, person_id, ext_name, ext_dept,
                                    account_id, synced_at)
  VALUES (p_system, p_ext_user, p_person, p_ext_name, p_ext_dept, p_account, now())
  ON CONFLICT (system_code, ext_user_id) DO UPDATE
     SET person_id = EXCLUDED.person_id, ext_name = EXCLUDED.ext_name,
         ext_dept = EXCLUDED.ext_dept,
         account_id = COALESCE(EXCLUDED.account_id, public.ext_person_map.account_id),
         synced_at = now()
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

-- ---------------------------------------------------------------------------
-- 7. 外部打卡落库：只写原始事件，幂等键 = (source, ext_id)
-- ---------------------------------------------------------------------------
-- ★ 与 fn_punch 的区别（这正是设计文档里那条"打卡不写工时"的延伸）：
--   · fn_punch 用**服务器时间**（人在页面上按一下）
--   · fn_punch_ingest 用**外部系统给的时间**（钉钉记录的时刻），因为那是证据
--   · 两者都不算工时；工时仍走 排班段 → 考勤日 那条链路
CREATE OR REPLACE FUNCTION fn_punch_ingest(
  p_employee bigint,
  p_at       timestamptz,
  p_kind     varchar,
  p_source   varchar,
  p_ext_id   varchar,
  p_store    bigint DEFAULT NULL,
  p_device   varchar DEFAULT NULL
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_id bigint; v_store bigint; v_new boolean := false;
BEGIN
  IF p_kind NOT IN ('in','out') THEN
    RAISE EXCEPTION 'E_PUNCH_KIND: 打卡类型只能是 in / out（收到 %）', p_kind;
  END IF;
  IF p_source NOT IN ('dingtalk','feishu','device') THEN
    RAISE EXCEPTION 'E_PUNCH_SOURCE: 外部来源只能是 dingtalk / feishu / device（收到 %）', p_source;
  END IF;
  IF p_ext_id IS NULL OR length(btrim(p_ext_id)) = 0 THEN
    RAISE EXCEPTION 'E_EXT_NO_KEY: 外部打卡必须给幂等键（ext_id），否则重放会翻倍';
  END IF;

  v_store := p_store;
  IF v_store IS NULL THEN
    SELECT a.org_id INTO v_store
      FROM public.employee_org_assignment a
     WHERE a.employee_id = p_employee AND a.dim_code = 'attendance_org'
       AND daterange(a.valid_from, a.valid_to, '[]') @> (p_at AT TIME ZONE public.app_tz())::date
     ORDER BY a.valid_from DESC LIMIT 1;
  END IF;

  INSERT INTO public.punch(employee_id, punch_at, kind, source, store_id, device_id, ext_id)
  VALUES (p_employee, p_at, p_kind, p_source, v_store, p_device, p_ext_id)
  ON CONFLICT (source, ext_id) WHERE ext_id IS NOT NULL DO NOTHING
  RETURNING id INTO v_id;

  -- 冲突（重复导入）时 v_id 为 NULL：回一行已有的 id，让调用方能区分"新进/已存在"
  IF v_id IS NULL THEN
    SELECT id INTO v_id FROM public.punch
     WHERE source = p_source AND ext_id = p_ext_id;
    v_new := false;
  ELSE
    v_new := true;
  END IF;

  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_punch_ingest IS
  '外部（钉钉/飞书/考勤机）打卡落库：幂等键 (source, ext_id)，只写原始事件。'
  '重复导入返回既有 id，不新增行 —— 而"有没有新进"要靠调用方比对前后行数。';

