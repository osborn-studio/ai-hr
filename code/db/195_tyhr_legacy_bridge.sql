-- Explicit compatibility projection. New company/person/employment remain the
-- source of identity. Nothing is projected until an administrator confirms the
-- real payroll/SI subjects and the legacy organization destination.
CREATE TABLE ty_legacy_company_binding (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id bigint NOT NULL UNIQUE REFERENCES ty_company(id),
  legacy_org_id bigint NOT NULL UNIQUE REFERENCES org_unit(id),
  payroll_legal_entity_id bigint NOT NULL REFERENCES legal_entity(id),
  si_legal_entity_id bigint NOT NULL REFERENCES legal_entity(id),
  effective_from date NOT NULL,
  created_by bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE ty_legacy_assignment_binding (
  employment_id bigint NOT NULL REFERENCES ty_employment(id),
  dim_code varchar(24) NOT NULL REFERENCES sys_perm_dim(code),
  legacy_assignment_id bigint NOT NULL UNIQUE REFERENCES employee_org_assignment(id),
  PRIMARY KEY(employment_id,dim_code)
);
CREATE UNIQUE INDEX ux_ty_company_legacy_global ON ty_company(legacy_org_id) WHERE legacy_org_id IS NOT NULL;
CREATE UNIQUE INDEX ux_ty_person_legacy_global ON ty_person(legacy_person_id) WHERE legacy_person_id IS NOT NULL;
CREATE UNIQUE INDEX ux_ty_employment_legacy_global ON ty_employment(legacy_employment_id) WHERE legacy_employment_id IS NOT NULL;
ALTER TABLE ty_company ADD CONSTRAINT fk_ty_company_legacy_org FOREIGN KEY(legacy_org_id) REFERENCES org_unit(id);
ALTER TABLE ty_person ADD CONSTRAINT fk_ty_person_legacy_person FOREIGN KEY(legacy_person_id) REFERENCES person(id);
ALTER TABLE ty_employment ADD CONSTRAINT fk_ty_employment_legacy_emp FOREIGN KEY(legacy_employment_id) REFERENCES employment(id);

CREATE FUNCTION fn_ty_bridge_company(p_company bigint,p_parent bigint,p_existing_org bigint,
  p_payroll bigint,p_si bigint,p_from date,p_actor bigint,p_create_root boolean DEFAULT false)
RETURNS jsonb LANGUAGE plpgsql SET search_path='' AS $$
DECLARE c public.ty_company%ROWTYPE; b public.ty_legacy_company_binding%ROWTYPE; v_org bigint; v_parent bigint:=p_parent;
BEGIN
  SELECT * INTO c FROM public.ty_company WHERE id=p_company FOR UPDATE;
  IF NOT FOUND OR c.status<>'active' THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='请先启用有效的门店公司'; END IF;
  IF p_from IS NULL OR p_actor IS NULL THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='桥接生效日与操作者必填'; END IF;
  IF NOT EXISTS(SELECT 1 FROM public.legal_entity WHERE id=p_payroll)
    OR NOT EXISTS(SELECT 1 FROM public.legal_entity WHERE id=p_si) THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='必须明确选择已有发薪主体与社保主体，不能按公司名推断';
  END IF;
  SELECT * INTO b FROM public.ty_legacy_company_binding WHERE company_id=p_company;
  IF FOUND THEN
    IF b.payroll_legal_entity_id<>p_payroll OR b.si_legal_entity_id<>p_si OR b.effective_from<>p_from
       OR (p_existing_org IS NOT NULL AND p_existing_org<>b.legacy_org_id) THEN
      RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='公司已有兼容映射，修改主体或生效期须另走迁移复核';
    END IF;
    RETURN jsonb_build_object('company_id',c.id,'legacy_org_id',b.legacy_org_id,'created',false);
  END IF;
  v_org:=COALESCE(p_existing_org,c.legacy_org_id);
  IF v_org IS NOT NULL THEN
    IF NOT EXISTS(SELECT 1 FROM public.org_unit WHERE id=v_org AND kind='dept') THEN
      RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='已有兼容节点必须是旧模型的门店适配节点';
    END IF;
  ELSE
    IF v_parent IS NULL THEN
      IF NOT p_create_root OR EXISTS(SELECT 1 FROM public.org_unit WHERE parent_id IS NULL) THEN
        RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='请选择兼容组织父节点；仅空兼容域可显式建立根节点';
      END IF;
      v_parent:=public.fn_org_add(NULL,'天意兼容业务根','group',NULL);
    END IF;
    IF NOT EXISTS(SELECT 1 FROM public.org_unit WHERE id=v_parent) THEN
      RAISE EXCEPTION USING ERRCODE='23503',MESSAGE='兼容组织父节点不存在';
    END IF;
    v_org:=public.fn_org_add(v_parent,('兼容·'||c.name)::varchar,'dept',NULL);
  END IF;
  INSERT INTO public.ty_legacy_company_binding(company_id,legacy_org_id,payroll_legal_entity_id,si_legal_entity_id,effective_from,created_by)
    VALUES(c.id,v_org,p_payroll,p_si,p_from,p_actor);
  UPDATE public.ty_company SET legacy_org_id=v_org WHERE id=c.id;
  RETURN jsonb_build_object('company_id',c.id,'legacy_org_id',v_org,'legacy_parent_org_id',v_parent,'created',true);
END; $$;

CREATE FUNCTION fn_ty_bridge_employment(p_employment bigint,p_actor bigint,
  p_monthly numeric DEFAULT NULL,p_salary_from date DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SET search_path='' AS $$
DECLARE e public.ty_employment%ROWTYPE; pe public.ty_person%ROWTYPE; b public.ty_legacy_company_binding%ROWTYPE;
  old_e public.employment%ROWTYPE; v_person bigint; v_emp bigint; v_no text; d record; v_a bigint;
BEGIN
  SELECT * INTO e FROM public.ty_employment WHERE id=p_employment FOR UPDATE;
  IF NOT FOUND OR e.status='cancelled' THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='雇佣不存在或已取消'; END IF;
  SELECT * INTO pe FROM public.ty_person WHERE id=e.person_id FOR UPDATE;
  IF pe.status<>'active' THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='人员已停用，不能建立业务映射'; END IF;
  SELECT * INTO b FROM public.ty_legacy_company_binding WHERE company_id=e.company_id;
  IF NOT FOUND OR b.effective_from>e.hire_date THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='公司主体/组织映射缺失或未覆盖入职日';
  END IF;
  IF EXISTS(SELECT 1 FROM public.ty_employment other_e WHERE other_e.person_id=e.person_id AND other_e.id<>e.id
    AND other_e.status<>'cancelled' AND daterange(other_e.hire_date,other_e.leave_date,'[]') && daterange(e.hire_date,e.leave_date,'[]')) THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='此人存在并行雇佣，旧模块按人员管理不能无损映射，请使用新版流程或先复核';
  END IF;
  IF p_monthly IS NOT NULL AND (p_monthly<=0 OR p_salary_from IS NULL OR p_salary_from<e.hire_date
      OR (e.leave_date IS NOT NULL AND p_salary_from>e.leave_date)) THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='月薪标准及其生效日必须明确且落在雇佣期间内';
  END IF;
  v_person:=pe.legacy_person_id;
  v_no:='G'||e.group_id::text||':'||pe.person_number;
  IF length(v_no)>32 THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='兼容工号超过旧模块32位限制，需另配置编号别名，不能截断'; END IF;
  IF v_person IS NULL THEN
    v_person:=public.fn_person_create(pe.full_name::varchar);
    PERFORM public.fn_assign_employee_no(v_person,v_no::varchar);
    UPDATE public.ty_person SET legacy_person_id=v_person WHERE id=pe.id;
  ELSE
    PERFORM public.fn_assign_employee_no(v_person,v_no::varchar);
  END IF;
  IF e.legacy_employment_id IS NOT NULL THEN
    SELECT * INTO old_e FROM public.employment WHERE id=e.legacy_employment_id;
    IF old_e.person_id<>v_person OR old_e.legal_entity_id<>b.payroll_legal_entity_id
      OR old_e.hire_date<>e.hire_date OR old_e.leave_date IS DISTINCT FROM e.leave_date THEN
      RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='已桥接雇佣与当前来源不一致，请复核，不覆盖历史';
    END IF;
    v_emp:=e.legacy_employment_id;
  ELSE
    IF EXISTS(SELECT 1 FROM public.employment old WHERE old.person_id=v_person
      AND daterange(old.hire_date,old.leave_date,'[]') && daterange(e.hire_date,e.leave_date,'[]')) THEN
      RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='兼容人员已有重叠雇佣，不能重复投影';
    END IF;
    INSERT INTO public.employment(person_id,legal_entity_id,hire_date,leave_date)
      VALUES(v_person,b.payroll_legal_entity_id,e.hire_date,e.leave_date) RETURNING id INTO v_emp;
    FOR d IN SELECT * FROM (VALUES('cost_org'::varchar,b.legacy_org_id),('attendance_org'::varchar,b.legacy_org_id),
      ('payroll_legal_entity'::varchar,b.payroll_legal_entity_id),('si_entity'::varchar,b.si_legal_entity_id)) AS x(dim_code,org_id)
    LOOP
      INSERT INTO public.employee_org_assignment(employee_id,dim_code,org_id,valid_from,valid_to)
        VALUES(v_person,d.dim_code,d.org_id,e.hire_date,e.leave_date) RETURNING id INTO v_a;
      INSERT INTO public.ty_legacy_assignment_binding(employment_id,dim_code,legacy_assignment_id) VALUES(e.id,d.dim_code,v_a);
    END LOOP;
    UPDATE public.ty_employment SET legacy_employment_id=v_emp WHERE id=e.id;
  END IF;
  IF p_monthly IS NOT NULL THEN
    IF EXISTS(SELECT 1 FROM public.salary_standard WHERE employment_id=v_emp AND effective_from=p_salary_from
      AND monthly_amount<>p_monthly) THEN
      RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='同日已有不同月薪标准，须经调薪流程处理';
    END IF;
    IF NOT EXISTS(SELECT 1 FROM public.salary_standard WHERE employment_id=v_emp AND effective_from=p_salary_from) THEN
      INSERT INTO public.salary_standard(employment_id,monthly_amount,effective_from) VALUES(v_emp,p_monthly,p_salary_from);
    END IF;
  END IF;
  RETURN jsonb_build_object('employment_id',e.id,'person_id',pe.id,'legacy_person_id',v_person,
    'legacy_employment_id',v_emp,'legacy_employee_no',v_no,'salary_configured',
    EXISTS(SELECT 1 FROM public.salary_standard WHERE employment_id=v_emp));
END; $$;

CREATE FUNCTION fn_ty_bridge_employment_end_sync() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
BEGIN
  IF NEW.legacy_employment_id IS NOT NULL AND (NEW.leave_date IS DISTINCT FROM OLD.leave_date) THEN
    IF NEW.leave_date IS NULL THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='已有兼容业务的离职不可直接撤回，请走复核流程'; END IF;
    UPDATE public.employee_org_assignment a SET valid_to=NEW.leave_date
      FROM public.ty_legacy_assignment_binding m WHERE m.employment_id=NEW.id AND m.legacy_assignment_id=a.id;
    UPDATE public.employment SET leave_date=NEW.leave_date WHERE id=NEW.legacy_employment_id;
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_ty_bridge_employment_end AFTER UPDATE OF leave_date ON ty_employment
FOR EACH ROW EXECUTE FUNCTION fn_ty_bridge_employment_end_sync();

