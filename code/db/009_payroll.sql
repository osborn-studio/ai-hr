-- ============================================================================
-- 009_payroll.sql · 算薪批次 / 工资条 / 待确认项（T03 尾巴 + T04 入口）
-- ----------------------------------------------------------------------------
-- 两条硬承诺：
--   ① **封账后不得改工资。** 不是"权限上不给改"，是数据库不允许改。
--      否则"这个月工资发了多少"永远可被事后修改，而报表看起来一致。
--   ② **待确认项可算、未追认、不阻塞算薪。**
--      阻塞会被绕过：第一次发薪日就有人把它改成"已确认"。
--
-- 一条结构性安排：
--   更正走**调整单**，不改原工资条。历史工资条只读归档。
--   "重算历史"等于改历史，而改过之后没人知道哪个数是真的。
-- ============================================================================

CREATE TABLE salary_item (
  code        varchar(32) PRIMARY KEY,
  name        varchar(64) NOT NULL,
  item_kind   varchar(16) NOT NULL,     -- fixed | variable | formula | statistic
  CONSTRAINT ck_si_kind CHECK (item_kind IN ('fixed','variable','formula','statistic'))
);

CREATE TABLE pay_run (
  -- ★ 第五次同一个坑，而且这次藏得最深：pay_run 不是**库函数**插入的，
  --   是**应用层**插入的，所以 Q14/Q15 那两条"函数插入的表必须有生成方式"
  --   扫不到它。它一直没暴露，是因为测试里永远命中"批次已存在"那个分支 ——
  --   真正的 INSERT 路径（首次算薪）没有任何断言走过。
  --   第一次走到就是 23502 not-null violation on id，看起来像数据缺失。
  --   ⇒ 断言要覆盖"首次"分支，不只是"重复"分支。
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period          varchar(7) NOT NULL,          -- 2026-03
  legal_entity_id bigint NOT NULL,
  calc_version    int NOT NULL DEFAULT 1,
  status          varchar(16) NOT NULL DEFAULT 'draft',
  sealed_at       timestamptz,
  UNIQUE (period, legal_entity_id, calc_version),
  CONSTRAINT ck_pr_status CHECK (status IN ('draft','sealed','paid')),
  CONSTRAINT ck_pr_sealed CHECK ((status = 'draft') = (sealed_at IS NULL))
);

CREATE TABLE payslip (
  -- ★ 第四次同一个坑：函数 INSERT 的表，surrogate PK 必须有生成方式。
  --   这类错的报错是 not-null violation 指向 id，看起来像数据缺失。
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pay_run_id   bigint NOT NULL REFERENCES pay_run(id),
  employee_id  bigint NOT NULL,
  gross_amount numeric(12,2) NOT NULL DEFAULT 0,
  net_amount   numeric(12,2) NOT NULL DEFAULT 0,
  UNIQUE (pay_run_id, employee_id)
);

CREATE TABLE payslip_item (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payslip_id      bigint NOT NULL REFERENCES payslip(id) ON DELETE CASCADE,
  item_code       varchar(32) NOT NULL REFERENCES salary_item(code),
  amount          numeric(12,2) NOT NULL,
  -- ★ 待确认项：可算、未追认。它挂在这一版的**钱**上，不挂在规则上 ——
  --   规则可以长期待确认，但每一版算出来的钱要单独追认。
  is_provisional  boolean NOT NULL DEFAULT false,
  provisional_until_period varchar(7),          -- 最晚追认期，不得超过下一期
  CONSTRAINT ck_pi_prov CHECK (
       (is_provisional = false AND provisional_until_period IS NULL)
    OR (is_provisional = true  AND provisional_until_period IS NOT NULL)
  )
);

-- ---------------------------------------------------------------------------
-- 封账冻结：三条路径
-- ---------------------------------------------------------------------------
-- ★ 只拦"改 payslip"不够。真正的绕过路径是：
--   「改 pay_run 回 draft → 改 payslip → 再 seal」——每一步都是合法 UPDATE。
CREATE OR REPLACE FUNCTION fn_payrun_freeze() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF OLD.status IN ('sealed','paid') THEN
    IF NEW.status = 'draft' THEN
      RAISE EXCEPTION 'E_PAYRUN_REOPEN: 已封账批次不能回 draft（更正走调整单）';
    END IF;
    IF NEW.period <> OLD.period OR NEW.legal_entity_id <> OLD.legal_entity_id THEN
      RAISE EXCEPTION 'E_PAYRUN_KEY_IMMUTABLE: 批次键不可修改';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_payrun_freeze BEFORE UPDATE ON pay_run
  FOR EACH ROW EXECUTE FUNCTION fn_payrun_freeze();

CREATE OR REPLACE FUNCTION fn_payslip_frozen() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE v_status varchar(16);
BEGIN
  SELECT status INTO v_status FROM public.pay_run
   WHERE id = COALESCE(NEW.pay_run_id, OLD.pay_run_id);
  IF v_status IN ('sealed','paid') THEN
    RAISE EXCEPTION 'E_PAYSLIP_FROZEN: 批次已封账，工资条不可改（更正走调整单）';
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$;
CREATE TRIGGER trg_payslip_frozen BEFORE UPDATE OR DELETE ON payslip
  FOR EACH ROW EXECUTE FUNCTION fn_payslip_frozen();
-- ★ 顺序：函数必须先定义，触发器才能引用它。
--   （写第一版时把 CREATE TRIGGER 放在了函数前面 —— 这属于"只有建库才会报"的错，
--     而它报的是 function does not exist，看起来像函数名写错。）
CREATE OR REPLACE FUNCTION fn_check_run_open(p_run bigint) RETURNS void
LANGUAGE plpgsql STABLE SET search_path = '' AS $$
DECLARE v_status varchar(16);
BEGIN
  SELECT status INTO v_status FROM public.pay_run WHERE id = p_run;
  IF v_status IN ('sealed','paid') THEN
    RAISE EXCEPTION 'E_PAYSLIP_FROZEN: 批次 % 已封账，工资条明细不可改', p_run;
  END IF;
END;
$$;

-- 明细表不直接挂 pay_run_id，要先经 payslip 找到批次
CREATE OR REPLACE FUNCTION fn_payslip_item_frozen_wrapper() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE v_run bigint;
BEGIN
  SELECT pay_run_id INTO v_run FROM public.payslip
   WHERE id = COALESCE(NEW.payslip_id, OLD.payslip_id);
  PERFORM public.fn_check_run_open(v_run);
  RETURN COALESCE(NEW, OLD);
END;
$$;

CREATE TRIGGER trg_payslip_item_frozen BEFORE UPDATE OR DELETE ON payslip_item
  FOR EACH ROW EXECUTE FUNCTION fn_payslip_item_frozen_wrapper();

-- ---------------------------------------------------------------------------
-- 待确认项的有效期：最多一期
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_provisional_period_ok() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE v_period varchar(7);
BEGIN
  IF NEW.is_provisional THEN
    SELECT period INTO v_period FROM public.pay_run
      JOIN public.payslip p ON p.pay_run_id = pay_run.id
     WHERE p.id = NEW.payslip_id;
    -- 简单而诚实的判据：追认期不得晚于下一期（YYYY-MM 字符串可比较）
    IF NEW.provisional_until_period > to_char(
         (to_date(v_period || '-01','YYYY-MM-DD') + interval '1 month'), 'YYYY-MM') THEN
      RAISE EXCEPTION 'E_PROVISIONAL_TOO_LONG: 待确认项有效期不得超过 1 个发薪期（批次 %，追认至 %）',
        v_period, NEW.provisional_until_period;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_provisional_period BEFORE INSERT OR UPDATE ON payslip_item
  FOR EACH ROW EXECUTE FUNCTION fn_provisional_period_ok();
