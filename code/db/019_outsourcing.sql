-- ============================================================================
-- 019_outsourcing.sql · 外包协同：供应商受限账号 + 双方对账
-- ----------------------------------------------------------------------------
-- 两个结构性判断，先写在最前面，因为后面所有东西都由它们决定：
--
-- ① **外包人员不是 person 的一种。**
--    如果建成 person + employment(legal_entity=供应商)，那么所有"按 person"
--    的清单会**自动包含**他们：个税申报、社保申报、工资条、人员编制。
--    而把这些清单一一改对，靠的是每个查询都记得加一个排除条件——
--    今天加对 12 处，第 13 处会忘，而忘了的表现是"外包工出现在个税名单里"。
--    独立表意味着：**排除是默认，包含才需要显式写**。
--
-- ② **真对账需要两份独立的数。**
--    同一张表存"我方工时/对方工时"两列，那不是对账，是自洽性检查——
--    它只能发现录入错误，发现不了"我们记的班次不一样"。
--    所以我方一份表、对方一份表，由两条不同的写入路径产生，
--    对账是**比对两份来源不同的记录**，不是校验一份记录的两个字段。
--
-- 一条功能边界（写死，防止被扩容）：本模块只到"应付供应商"，
-- 不碰供应商与其员工的劳动关系、不代发工资、不做个税代扣。
-- ============================================================================

CREATE TABLE supplier (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code       varchar(24) NOT NULL UNIQUE,
  name       varchar(128) NOT NULL,
  status     varchar(16) NOT NULL DEFAULT 'active',
  tax_no     varchar(32),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_sup_status CHECK (status IN ('active','suspended','terminated'))
);

-- ---------------------------------------------------------------------------
-- 受限账号：不是"内部账号多加一个 supplier 字段"
-- ---------------------------------------------------------------------------
-- ★ 内部账号与供应商账号放在同一张表里，会让"这个账号能看什么"
--   由若干布尔列的组合决定；而那些组合里必然有一格是错的。
--   分表之后，供应商账号**在结构上**拿不到内部角色。
CREATE TABLE supplier_account (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id bigint      NOT NULL REFERENCES supplier(id),
  login       varchar(64) NOT NULL UNIQUE,
  display_name varchar(64) NOT NULL,
  can_submit  boolean     NOT NULL DEFAULT true,   -- 可提交工时/确认结算
  status      varchar(16) NOT NULL DEFAULT 'active',
  CONSTRAINT ck_sa_status CHECK (status IN ('active','disabled'))
);

-- ---------------------------------------------------------------------------
-- 外包人员：独立表，没有 person_id
-- ---------------------------------------------------------------------------
CREATE TABLE outsourced_worker (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id bigint       NOT NULL REFERENCES supplier(id),
  full_name   varchar(64)  NOT NULL,
  id_card_no  varchar(32),                    -- 脱敏存储由字段权限管，这里只存哈希前缀
  worker_code varchar(32)  NOT NULL,          -- 供应商侧的人员编号
  valid_from  date         NOT NULL,
  valid_to    date,
  CONSTRAINT uk_ow_code UNIQUE (supplier_id, worker_code),
  CONSTRAINT ck_ow_span CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

COMMENT ON TABLE outsourced_worker IS
  '外包人员。**刻意没有 person_id**：一旦与内部自然人同表，'
  '个税/社保/工资条/编制的每一个"按 person"的清单都会自动包含他们，'
  '而排除要靠每处查询记得加条件——加对 12 处，第 13 处会忘。';

-- ---------------------------------------------------------------------------
-- 派工：外包人员在某家门店、某段时间
-- ---------------------------------------------------------------------------
CREATE TABLE outsourced_assignment (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  worker_id  bigint NOT NULL REFERENCES outsourced_worker(id),
  store_id   bigint NOT NULL,
  valid_from date   NOT NULL,
  valid_to   date,
  CONSTRAINT ck_oa_span CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

-- ---------------------------------------------------------------------------
-- 两份工时：我方一份、对方一份
-- ---------------------------------------------------------------------------
CREATE TABLE outsourced_timesheet (          -- 我方：班组长/店长确认
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  worker_id   bigint       NOT NULL REFERENCES outsourced_worker(id),
  work_date   date         NOT NULL,
  hours       numeric(6,2) NOT NULL,
  confirmed_by varchar(64) NOT NULL,          -- 空 = 未确认，故 NOT NULL
  confirmed_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_ot_hours CHECK (hours > 0 AND hours <= 24),
  CONSTRAINT uk_ot UNIQUE (worker_id, work_date)
);

CREATE TABLE supplier_timesheet (            -- 对方：供应商账号提交
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  worker_id    bigint       NOT NULL REFERENCES outsourced_worker(id),
  work_date    date         NOT NULL,
  hours        numeric(6,2) NOT NULL,
  submitted_by varchar(64)  NOT NULL,         -- supplier_account.login
  submitted_at timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT ck_st_hours CHECK (hours > 0 AND hours <= 24),
  CONSTRAINT uk_st UNIQUE (worker_id, work_date)
);

-- ---------------------------------------------------------------------------
-- 行级隔离：供应商只能看自己的
-- ---------------------------------------------------------------------------
-- ★ 用 RLS 而不是"每个查询记得加 WHERE supplier_id = ?"。
--   后者是十二处里忘一处；前者忘不了，因为过滤条件不在应用代码里。
--   判据是会话变量 app.supplier_id —— 由登录时设定，不由请求参数传。
ALTER TABLE supplier_timesheet      ENABLE ROW LEVEL SECURITY;
ALTER TABLE supplier_timesheet      FORCE  ROW LEVEL SECURITY;  -- 连 owner 也受约束
ALTER TABLE outsourced_worker       ENABLE ROW LEVEL SECURITY;
ALTER TABLE outsourced_worker       FORCE  ROW LEVEL SECURITY;

CREATE POLICY pol_st_own ON supplier_timesheet
  USING (worker_id IN (SELECT w.id FROM outsourced_worker w
                        WHERE w.supplier_id = NULLIF(current_setting('app.supplier_id', true), '')::bigint));

CREATE POLICY pol_ow_own ON outsourced_worker
  USING (supplier_id = NULLIF(current_setting('app.supplier_id', true), '')::bigint);

COMMENT ON POLICY pol_ow_own ON outsourced_worker IS
  '「缺失」在 PostgreSQL 会话变量里有**两种形态**：从未设过 → NULL；'
  '设过又 RESET → 空串。只判 NULL 时，第二种会在 ::bigint 上直接报错，'
  '而报错会被上层 catch 成 500，看起来像服务故障而不是"没登录"。'
  'NULLIF(..., '''') 把两种形态归一，于是"没设"稳定命中 0 行（fail-closed）。';

-- ---------------------------------------------------------------------------
-- 单价：按生效日版本，改价不追溯
-- ---------------------------------------------------------------------------
CREATE TABLE supplier_rate (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id    bigint       NOT NULL REFERENCES supplier(id),
  effective_from date         NOT NULL,
  unit_price     numeric(10,4) NOT NULL,       -- 元/小时
  CONSTRAINT uk_sr UNIQUE (supplier_id, effective_from),
  CONSTRAINT ck_sr_price CHECK (unit_price >= 0)
);

CREATE OR REPLACE FUNCTION fn_supplier_rate(p_supplier bigint, p_on date)
RETURNS numeric
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE v numeric;
BEGIN
  SELECT unit_price INTO v FROM public.supplier_rate
   WHERE supplier_id = p_supplier AND effective_from <= p_on
   ORDER BY effective_from DESC LIMIT 1;
  IF v IS NULL THEN
    RAISE EXCEPTION 'E_SUPPLIER_RATE_MISSING: 供应商 % 在 % 之前没有生效单价', p_supplier, p_on;
  END IF;
  RETURN v;
END;
$$;

-- ---------------------------------------------------------------------------
-- 差异视图：两份数比出来的每一个不一致
-- ---------------------------------------------------------------------------
-- ★ 差异只有三种形态，处置各不相同，不能压成一个"差异数"：
--   only_ours   我方记了、对方没记     -> 多半是对方漏报
--   only_theirs 对方记了、我方没记     -> 多半是我们漏排班
--   hours_differ 都有但不一样          -> 事实分歧，必须人判
-- 三种压成 |ours - theirs| 一个数，会让第一种和第二种看起来一样，
-- 而它们的处理方向相反（一个去催对方补，一个去查我们自己的排班）。
CREATE OR REPLACE FUNCTION fn_supplier_diff(p_supplier bigint, p_period varchar)
RETURNS TABLE (worker_id bigint, work_date date, kind varchar,
               ours numeric, theirs numeric, hours_diff numeric)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  WITH w AS (SELECT id FROM public.outsourced_worker WHERE supplier_id = p_supplier),
       o AS (SELECT t.worker_id, t.work_date, t.hours FROM public.outsourced_timesheet t
              WHERE t.worker_id IN (SELECT id FROM w)
                AND to_char(t.work_date,'YYYY-MM') = p_period),
       s AS (SELECT t.worker_id, t.work_date, t.hours FROM public.supplier_timesheet t
              WHERE t.worker_id IN (SELECT id FROM w)
                AND to_char(t.work_date,'YYYY-MM') = p_period)
  SELECT COALESCE(o.worker_id, s.worker_id),
         COALESCE(o.work_date, s.work_date),
         CASE WHEN s.worker_id IS NULL THEN 'only_ours'
              WHEN o.worker_id IS NULL THEN 'only_theirs'
              ELSE 'hours_differ' END,
         o.hours, s.hours,
         COALESCE(o.hours,0) - COALESCE(s.hours,0)
    FROM o FULL JOIN s ON s.worker_id = o.worker_id AND s.work_date = o.work_date
   WHERE o.worker_id IS NULL OR s.worker_id IS NULL
      OR o.hours <> s.hours;
$$;

-- ---------------------------------------------------------------------------
-- 结算单
-- ---------------------------------------------------------------------------
CREATE TABLE settlement (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id  bigint      NOT NULL REFERENCES supplier(id),
  period       varchar(7)  NOT NULL,
  status       varchar(16) NOT NULL DEFAULT 'draft',
  our_hours    numeric(12,2),
  our_amount   numeric(14,2),
  their_hours  numeric(12,2),
  their_amount numeric(14,2),
  diff_count   int,
  submitted_at timestamptz,
  confirmed_at timestamptz,
  CONSTRAINT uk_settle UNIQUE (supplier_id, period),
  CONSTRAINT ck_settle_period CHECK (period ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  CONSTRAINT ck_settle_status CHECK (status IN ('draft','submitted','disputed','confirmed')),
  -- ★ 争议状态必须带差异条数，且必须 > 0。
  --   写成 "disputed 时 diff_count 非空" 会允许 diff_count = 0 的争议——
  --   那意味着一张没有任何差异的单被判成了有争议，而它会拦住正常结算。
  CONSTRAINT ck_settle_diff CHECK (status <> 'disputed' OR diff_count > 0),
  CONSTRAINT ck_settle_confirmed CHECK ((status = 'confirmed') = (confirmed_at IS NOT NULL))
);

-- 生成结算单：双方各自汇总，**不取平均、不取小、不取大**
CREATE OR REPLACE FUNCTION fn_settle_build(p_supplier bigint, p_period varchar)
RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_id bigint; v_our numeric; v_their numeric; v_price numeric; v_diff int;
  v_our_amt numeric; v_their_amt numeric; v_status varchar(16);
BEGIN
  SELECT COALESCE(sum(t.hours),0) INTO v_our
    FROM public.outsourced_timesheet t
    JOIN public.outsourced_worker w ON w.id = t.worker_id
   WHERE w.supplier_id = p_supplier AND to_char(t.work_date,'YYYY-MM') = p_period;

  SELECT COALESCE(sum(t.hours),0) INTO v_their
    FROM public.supplier_timesheet t
    JOIN public.outsourced_worker w ON w.id = t.worker_id
   WHERE w.supplier_id = p_supplier AND to_char(t.work_date,'YYYY-MM') = p_period;

  SELECT count(*)::int INTO v_diff
    FROM public.fn_supplier_diff(p_supplier, p_period);

  v_price := public.fn_supplier_rate(p_supplier, (p_period || '-01')::date);
  v_our_amt   := round(v_our   * v_price, 2);
  v_their_amt := round(v_their * v_price, 2);
  v_status := CASE WHEN v_diff = 0 THEN 'submitted' ELSE 'disputed' END;

  INSERT INTO public.settlement(supplier_id, period, status, our_hours, our_amount,
                               their_hours, their_amount, diff_count, submitted_at)
  VALUES (p_supplier, p_period, v_status, v_our, v_our_amt, v_their, v_their_amt, v_diff,
          clock_timestamp())
  ON CONFLICT (supplier_id, period) DO UPDATE
    SET status = EXCLUDED.status, our_hours = EXCLUDED.our_hours,
        our_amount = EXCLUDED.our_amount, their_hours = EXCLUDED.their_hours,
        their_amount = EXCLUDED.their_amount, diff_count = EXCLUDED.diff_count
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_settle_build IS
  '两份数各自保留，差异只记条数。**不取平均、不取小、不取大**——'
  '取任一边都是替双方做了一个他们没有同意的决定，而单据看起来是完整的。';

-- 冻结：确认后不可改
CREATE OR REPLACE FUNCTION fn_settle_frozen() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF OLD.status = 'confirmed' THEN
    IF TG_OP = 'DELETE' THEN
      RAISE EXCEPTION 'E_SETTLE_CONFIRMED_DELETED: 已确认的结算单 % 不可删', OLD.id;
    END IF;
    IF NEW.status = 'draft' THEN
      RAISE EXCEPTION 'E_SETTLE_REOPEN: 已确认的结算单 % 不可退回 draft', OLD.id;
    END IF;
    IF NEW.our_hours <> OLD.our_hours OR NEW.their_hours <> OLD.their_hours
       OR NEW.our_amount <> OLD.our_amount OR NEW.their_amount <> OLD.their_amount THEN
      RAISE EXCEPTION 'E_SETTLE_AMOUNT_FROZEN: 已确认的结算单 % 金额与工时不可改', OLD.id;
    END IF;
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$;

CREATE TRIGGER trg_settle_frozen
  BEFORE UPDATE OR DELETE ON settlement
  FOR EACH ROW EXECUTE FUNCTION fn_settle_frozen();

-- 确认：只有双方数据一致才能确认
CREATE OR REPLACE FUNCTION fn_settle_confirm(p_id bigint, p_by varchar)
RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_status varchar(16); v_diff int;
BEGIN
  SELECT status, diff_count INTO v_status, v_diff
    FROM public.settlement WHERE id = p_id FOR UPDATE;
  IF v_status IS NULL THEN RAISE EXCEPTION 'E_SETTLE_NOT_FOUND: %', p_id; END IF;
  IF v_status = 'confirmed' THEN RAISE EXCEPTION 'E_SETTLE_ALREADY: 结算单 % 已确认', p_id; END IF;
  IF v_diff > 0 THEN
    RAISE EXCEPTION 'E_SETTLE_HAS_DIFF: 结算单 % 有 % 条差异，不可确认', p_id, v_diff;
  END IF;
  UPDATE public.settlement
     SET status='confirmed', confirmed_at=clock_timestamp() WHERE id = p_id;
END;
$$;
