-- ============================================================================
-- 115_att_daily_import_version.sql · 日报可调 + Excel 覆盖 + 多版本
-- ----------------------------------------------------------------------------
-- 114 给了月报（人×期间）。但现实里 HR 首先是改**某一天**：
-- "老王 11-03 那天漏打卡了，实际上了 8 小时" —— 这是日报粒度的事。
-- 而月报只能改月度合计，改完就再也说不清"是哪一天不对"。
--
-- 所以这一版补三块：
--
--   ① 日报人工调整（att_daily_adjust）
--      封账前可以直接改当天的人日工时，改动留痕；
--      封账后不允许改 —— 那是已有的规矩（fn_ads_frozen + 补账通道），
--      这里只把错误提示写得更清楚，不另开一条绕过它的路。
--
--   ② Excel 导入覆盖（att_import_batch / att_import_row）
--      日报表：工号 + 日期 + 工时；月报表：工号 + 各项天数/工时。
--      两阶段：先解析出**逐行结论**（哪行通过、哪行为什么不行），再点"应用"落库。
--      一次导入几十人，最怕的是"看起来导进去了"，所以行级结论必须留着。
--
--   ③ 多版本（att_period_version）
--      每次生成/导入/确认都留一份全量快照 + 摘要。HR 说"我上周调过一版"，
--      能翻出来看；两版之间能对比，而不是只能说"改过了"。
--
-- ★ 为什么版本存快照 jsonb 而不是只存变更：
--   只存变更要"回放到某一天"才能知道当时的样子，而回放依赖中间没有被改过 ——
--   这个前提在真实系统里从来不成立。快照笨，但它永远答得出"当时是多少"。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 日报调整留痕
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS att_daily_adjust (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id  bigint       NOT NULL,
  work_date    date         NOT NULL,
  store_id     bigint       NOT NULL,
  field_name   varchar(32)  NOT NULL,
  before_value numeric(8,2),
  after_value  numeric(8,2),
  reason       varchar(200) NOT NULL,
  adjusted_by  varchar(64)  NOT NULL,
  adjusted_at  timestamptz  NOT NULL DEFAULT now(),

  CONSTRAINT ck_ada_reason CHECK (length(btrim(reason)) >= 4),
  CONSTRAINT ck_ada_changed CHECK (before_value IS DISTINCT FROM after_value)
);

COMMENT ON TABLE att_daily_adjust IS
  '考勤日报（人日）的手工调整痕迹：改了哪天、哪个字段、改前改后、为什么、谁改的。'
  '封账后不允许走这条路（那是补账通道的事），所以这里的行只会出现在未封账期间。';

-- ---------------------------------------------------------------------------
-- 2. 导入批次（日报 / 月报共用一套）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS att_import_batch (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind       varchar(16)  NOT NULL,          -- daily / monthly
  period     varchar(7)   NOT NULL,
  filename   varchar(200) NOT NULL,
  row_total  int          NOT NULL DEFAULT 0,
  row_ok     int          NOT NULL DEFAULT 0,
  row_fail   int          NOT NULL DEFAULT 0,
  status     varchar(16)  NOT NULL DEFAULT 'parsed',
  note       varchar(300),
  created_by varchar(64)  NOT NULL,
  created_at timestamptz  NOT NULL DEFAULT now(),
  applied_at timestamptz,

  CONSTRAINT ck_aib_kind CHECK (kind IN ('daily','monthly')),
  CONSTRAINT ck_aib_period CHECK (period ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  CONSTRAINT ck_aib_status CHECK (status IN ('parsed','applied','failed')),
  -- 应用过就必须有应用时间：否则"这条到底生效没有"没法判
  CONSTRAINT ck_aib_applied CHECK ((status = 'applied') = (applied_at IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS att_import_row (
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id  bigint      NOT NULL REFERENCES att_import_batch(id) ON DELETE CASCADE,
  row_no    int         NOT NULL,
  ok        boolean     NOT NULL,
  error     text,
  payload   jsonb       NOT NULL,
  -- 通过的行必须没有错误文本；不通过的行必须写清原因。
  -- 少了这条，"通过"和"没检查"在库里同形。
  CONSTRAINT ck_air_result CHECK (
    (ok AND error IS NULL) OR (NOT ok AND error IS NOT NULL)
  )
);

COMMENT ON TABLE att_import_row IS
  '导入的逐行结论。通过行带 payload（应用时按它落库），不通过行带原因。'
  '★ 行级结论必须留下：一次导几十人，最坏的情况是"看起来导进去了"。';

-- ---------------------------------------------------------------------------
-- 3. 版本快照
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS att_period_version (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period        varchar(7)   NOT NULL,
  legal_entity_id bigint     NOT NULL,
  version_no    int          NOT NULL,
  source        varchar(16)  NOT NULL,       -- build / import / manual / confirm / reopen
  row_count     int          NOT NULL,
  digest        text         NOT NULL,       -- 摘要：用来快速判断"两版是不是一样"
  snapshot      jsonb        NOT NULL,       -- 全量行
  note          varchar(200),
  created_by    varchar(64)  NOT NULL,
  created_at    timestamptz  NOT NULL DEFAULT now(),

  CONSTRAINT ck_apv_source CHECK (source IN ('build','import','manual','confirm','reopen')),
  UNIQUE (period, legal_entity_id, version_no)
);

COMMENT ON TABLE att_period_version IS
  '考勤月报的版本快照：每次生成/导入/手调/确认/重开各留一版，可回看、可对比。'
  'digest 是"这些数字的指纹"——两版 digest 相同就是没变，不用逐行比。';

-- ---------------------------------------------------------------------------
-- 4. 日报调整：改某一天的工时
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_att_daily_set(
  p_employee bigint, p_work_date date, p_hours numeric,
  p_reason varchar, p_by varchar)
RETURNS numeric
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  a public.attendance_daily_store%ROWTYPE;
  v_reason varchar(200) := btrim(COALESCE(p_reason, ''));
  v_in numeric(6,2);
  v_break numeric(6,2);
BEGIN
  IF length(v_reason) < 4 THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 调整必须写原因（至少 4 个字）—— 改了没理由等于没留痕';
  END IF;
  IF p_hours IS NULL OR p_hours < 0 THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 工时不能为空或负数';
  END IF;

  SELECT * INTO a FROM public.attendance_daily_store x
   WHERE x.employee_id = p_employee AND x.work_date = p_work_date;
  IF a.id IS NULL THEN
    -- ★ 不"顺手建一条"：新建人日等于替门店决定"这天他来了"，
    --   而正确做法是补一条打卡/补勤，让它自己算出来。
    RAISE EXCEPTION 'E_ATT_NO_ROW: % 在 % 没有考勤人日记录；要新增请走补勤或考勤机导入',
      p_employee, p_work_date;
  END IF;

  IF a.work_hours = p_hours THEN
    -- 改成同一个值不算改动：留一条 before=after 的记录会被 ck_ada_changed 拒，
    -- 而报约束错误的体验比"什么都没发生"差得多
    RETURN p_hours;
  END IF;

  -- 工时与在岗/休息时长必须自洽（原表有 chk_ads_sum / chk_ads_off）：
  --   hourly：work = 在岗；否则 work = 在岗 − 在岗内休息
  IF a.snap_on_duty_break_basis = 'hourly' THEN
    v_in := p_hours;
  ELSE
    v_break := a.break_on_duty_hours;
    v_in := p_hours + v_break;
  END IF;
  IF v_in > a.span_hours THEN
    RAISE EXCEPTION 'E_ATT_TOO_LONG: 工时 % 超出当天班次跨度 %（% ~ %）',
      p_hours, a.span_hours, a.shift_start_at, a.shift_end_at;
  END IF;

  -- 封账保护由 trg_ads_frozen 触发器兜底；这里先给一句能读懂的提示
  IF EXISTS (SELECT 1 FROM public.attendance_close c
              WHERE c.store_id = a.store_id
                AND c.period = to_char(p_work_date, 'YYYY-MM') AND c.status = 'closed') THEN
    RAISE EXCEPTION 'E_ATT_CLOSED: % 已在 % 封账，考勤不可改；封账后的修正请走补账',
      a.store_id, to_char(p_work_date, 'YYYY-MM');
  END IF;

  UPDATE public.attendance_daily_store
     SET work_hours = p_hours, in_attendance_hours = v_in
   WHERE id = a.id;

  INSERT INTO public.att_daily_adjust(employee_id, work_date, store_id, field_name,
                                     before_value, after_value, reason, adjusted_by)
  VALUES (p_employee, p_work_date, a.store_id, 'work_hours',
          a.work_hours, p_hours, v_reason, p_by);

  RETURN p_hours;
END;
$$;

COMMENT ON FUNCTION fn_att_daily_set IS
  '手工调整某人某天的工时（联动在岗时长保持自洽），并留痕。'
  '没有当天人日时拒绝：新建人日等于替门店决定"他来了"，该走补勤/导入。'
  '封账期间拒绝变更（与触发器同一条规矩，这里给更清楚的提示）。';

-- ---------------------------------------------------------------------------
-- 5. 写版本快照
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_att_period_version_write(
  p_period varchar, p_entity bigint, p_source varchar, p_by varchar, p_note varchar DEFAULT NULL)
RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_no int;
  v_snap jsonb;
  v_n int;
  v_digest text;
BEGIN
  SELECT COALESCE(max(version_no), 0) + 1 INTO v_no
    FROM public.att_period_version
   WHERE period = p_period AND legal_entity_id = p_entity;

  SELECT COALESCE(jsonb_agg(jsonb_build_object(
           'person_id', r.person_id,
           'work_days', r.work_days,
           'calendar_days', r.calendar_days,
           'roster_days', r.roster_days,
           'present_days', r.present_days,
           'leave_days', r.leave_days,
           'personal_leave_days', r.personal_leave_days,
           'absent_days', r.absent_days,
           'work_hours', r.work_hours,
           'ot_hours', r.ot_hours,
           'status', r.status
         ) ORDER BY r.person_id), '[]'::jsonb),
         count(*)::int
    INTO v_snap, v_n
    FROM public.att_period_report r
   WHERE r.period = p_period AND r.legal_entity_id = p_entity;

  IF v_n = 0 THEN
    RAISE EXCEPTION 'E_ATT_NO_REPORT: % 还没有月报，先"生成"再谈版本', p_period;
  END IF;

  -- 摘要用 md5(整份快照的规范文本)：两版一样就是没变，不必逐行比
  v_digest := md5(v_snap::text);

  INSERT INTO public.att_period_version(period, legal_entity_id, version_no, source,
                                       row_count, digest, snapshot, note, created_by)
  VALUES (p_period, p_entity, v_no, p_source, v_n, v_digest, v_snap,
          left(COALESCE(p_note, ''), 200), p_by);
  RETURN v_no;
END;
$$;

COMMENT ON FUNCTION fn_att_period_version_write IS
  '把当前月报整份存为一版（v1、v2…），带 md5 摘要。source 标明这版是生成/导入/手调/确认来的。';

-- ---------------------------------------------------------------------------
-- 6. 导入落库（月报）：只覆盖给了值的字段
-- ---------------------------------------------------------------------------
-- ★ 走 att_import_row 的 payload，不直接吃外部数组：
--   应用时要重读"当时校验通过的那一行"，而不是"再解析一次文件"。
--   文件可能已经被换掉，而批次号还在。
CREATE OR REPLACE FUNCTION fn_att_period_import_apply(
  p_batch bigint, p_period varchar, p_entity bigint, p_by varchar)
RETURNS TABLE (applied int, skipped int, failed int)
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  b public.att_import_batch%ROWTYPE;
  rw record;
  rep record;
  v_applied int := 0; v_skipped int := 0; v_failed int := 0;
  v_err text;
BEGIN
  SELECT * INTO b FROM public.att_import_batch WHERE id = p_batch FOR UPDATE;
  IF b.id IS NULL THEN RAISE EXCEPTION 'E_NOT_FOUND: 导入批次 % 不存在', p_batch; END IF;
  IF b.kind <> 'monthly' THEN
    RAISE EXCEPTION 'E_IMPORT_KIND: 批次 % 是 % 导入，不能用月报应用', p_batch, b.kind;
  END IF;
  IF b.status = 'applied' THEN
    RAISE EXCEPTION 'E_ALREADY_APPLIED: 批次 % 已经应用过（重复应用会把"导入"变成"再导一次"）', p_batch;
  END IF;
  IF b.period <> p_period THEN
    RAISE EXCEPTION 'E_IMPORT_PERIOD: 批次期间 % 与目标期间 % 不一致', b.period, p_period;
  END IF;

  -- 期初就把"已确认"的整体拦下：只拦一半会让这一期一半新一半旧
  IF EXISTS (SELECT 1 FROM public.att_period_report x
              WHERE x.period = p_period AND x.legal_entity_id = p_entity
                AND x.status = 'confirmed') THEN
    RAISE EXCEPTION 'E_ATT_REPORT_CONFIRMED: % 的月报已确认，导入覆盖前请先重开', p_period;
  END IF;

  FOR rw IN SELECT * FROM public.att_import_row WHERE batch_id = p_batch AND ok ORDER BY row_no
  LOOP
    BEGIN
      SELECT * INTO rep FROM public.att_period_report x
       WHERE x.period = p_period AND x.person_id = (rw.payload->>'person_id')::bigint
       FOR UPDATE;
      IF rep.id IS NULL THEN
        v_skipped := v_skipped + 1;    -- 校验阶段已认定"没这一期月报"，这里不该发生
        CONTINUE;
      END IF;

      -- 缺的 key 不动：Excel 里留空 = 这一列不改，而不是"改成 0"
      UPDATE public.att_period_report SET
        work_days           = COALESCE((rw.payload->>'work_days')::numeric, work_days),
        present_days        = COALESCE((rw.payload->>'present_days')::numeric, present_days),
        leave_days          = COALESCE((rw.payload->>'leave_days')::numeric, leave_days),
        personal_leave_days = COALESCE((rw.payload->>'personal_leave_days')::numeric,
                                       personal_leave_days),
        absent_days         = COALESCE((rw.payload->>'absent_days')::numeric, absent_days),
        work_hours          = COALESCE((rw.payload->>'work_hours')::numeric, work_hours),
        ot_hours            = COALESCE((rw.payload->>'ot_hours')::numeric, ot_hours),
        updated_at          = now()
       WHERE id = rep.id;

      v_applied := v_applied + 1;
    EXCEPTION WHEN others THEN
      v_failed := v_failed + 1;
      v_err := SQLERRM;
      UPDATE public.att_import_row SET ok = false, error = left(v_err, 500) WHERE id = rw.id;
    END;
  END LOOP;

  UPDATE public.att_import_batch
     SET status = 'applied', applied_at = now(),
         row_ok = v_applied, row_fail = b.row_fail + v_failed
   WHERE id = p_batch;

  applied := v_applied; skipped := v_skipped; failed := v_failed;
  RETURN NEXT;
END;
$$;

COMMENT ON FUNCTION fn_att_period_import_apply IS
  '把月报导入批次落库：只覆盖 Excel 里给了值的字段（留空=不改），逐行记失败原因。'
  '已确认的期间整体拒绝（只拦一半会让这一期一半新一半旧）；批次不可重复应用。';

-- ---------------------------------------------------------------------------
-- 7. 日报导入落库：工号 + 日期 + 工时
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_att_daily_import_apply(p_batch bigint, p_by varchar)
RETURNS TABLE (applied int, skipped int, failed int)
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  b public.att_import_batch%ROWTYPE;
  rw record;
  a public.attendance_daily_store%ROWTYPE;
  v_applied int := 0; v_skipped int := 0; v_failed int := 0;
BEGIN
  SELECT * INTO b FROM public.att_import_batch WHERE id = p_batch FOR UPDATE;
  IF b.id IS NULL THEN RAISE EXCEPTION 'E_NOT_FOUND: 导入批次 % 不存在', p_batch; END IF;
  IF b.kind <> 'daily' THEN
    RAISE EXCEPTION 'E_IMPORT_KIND: 批次 % 是 % 导入，不能用日报应用', p_batch, b.kind;
  END IF;
  IF b.status = 'applied' THEN
    RAISE EXCEPTION 'E_ALREADY_APPLIED: 批次 % 已经应用过', p_batch;
  END IF;

  FOR rw IN SELECT * FROM public.att_import_row WHERE batch_id = p_batch AND ok ORDER BY row_no
  LOOP
    BEGIN
      -- 日报覆盖走 fn_att_daily_set：它自己会留痕、会拒封账期间、会校验自洽。
      -- 这样"导入的"和"手工调的"在库里是同一种痕迹 —— 出事时不用想"这条是从哪条路进来的"。
      PERFORM public.fn_att_daily_set(
        (rw.payload->>'employee_id')::bigint,
        (rw.payload->>'work_date')::date,
        (rw.payload->>'work_hours')::numeric,
        COALESCE(rw.payload->>'reason', '考勤日报导入覆盖'),
        p_by);
      v_applied := v_applied + 1;
    EXCEPTION WHEN others THEN
      v_failed := v_failed + 1;
      UPDATE public.att_import_row SET ok = false, error = left(SQLERRM, 500) WHERE id = rw.id;
    END;
  END LOOP;

  UPDATE public.att_import_batch
     SET status = 'applied', applied_at = now(),
         row_ok = v_applied, row_fail = b.row_fail + v_failed
   WHERE id = p_batch;

  applied := v_applied; skipped := v_skipped; failed := v_failed;
  RETURN NEXT;
END;
$$;

COMMENT ON FUNCTION fn_att_daily_import_apply IS
  '日报导入落库：每行走 fn_att_daily_set，所以"导入改的"和"手工改的"留同一种痕迹。'
  '封账期间的行会逐行失败并写明原因（不会因为一行失败而整批不落）。';

