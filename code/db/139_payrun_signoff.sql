-- ---------------------------------------------------------------------------
-- 4. 发起会签
-- ---------------------------------------------------------------------------
-- p_users: {"cashier": 1, "finance": 2, "biz": 3} —— 角色 → 账号 id。
--   没给的角色用 pay_signoff_role.default_user_id；都没有就报错（不能让人签不了）。
-- 重新发起：旧的 pending/objected 行作废（void），approved 行保留 ——
--   已经签过的意思不能因为重发起就丢，但重新发起的这一轮要重新签。
CREATE OR REPLACE FUNCTION fn_signoff_start(
  p_run bigint, p_by text, p_users jsonb DEFAULT '{}'::jsonb
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  r      record;
  v_n    int := 0;
  v_uid  bigint;
BEGIN
  SELECT * INTO r FROM public.pay_run WHERE id = p_run;
  IF r.id IS NULL THEN RAISE EXCEPTION 'E_RUN_NOT_FOUND: %', p_run; END IF;
  IF r.status <> 'draft' THEN
    RAISE EXCEPTION 'E_RUN_SEALED: 批次 % 已封账，不能再发起会签', p_run;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.payslip p WHERE p.pay_run_id = p_run) THEN
    RAISE EXCEPTION 'E_SIGNOFF_EMPTY: 批次 % 还没有工资条，先算薪再发起会签', p_run;
  END IF;

  -- 上一轮：未定的作废（不删，留痕），已签的保留
  -- ★ 作废也要给 decided_at：约束是"状态与时刻同生同灭"，
  --   非 pending 而没有时刻会被 ck_prs_decided 直接拒（这次就是撞在这条上）。
  --   对 void 行来说，这个时刻就是"作废于"。
  UPDATE public.pay_run_signoff s
     SET status = 'void', decided_at = clock_timestamp()
   WHERE s.pay_run_id = p_run AND s.status IN ('pending');

  FOR r IN
    SELECT d.code, d.name, d.seq, d.default_user_id
      FROM public.pay_signoff_role d
     WHERE d.is_active
     ORDER BY d.seq, d.code
  LOOP
    v_uid := COALESCE((p_users ->> r.code)::bigint, r.default_user_id);
    IF v_uid IS NULL THEN
      RAISE EXCEPTION 'E_SIGNOFF_NO_ASSIGNEE: 角色「%」没有指定签字人（也没有默认签字人）。'
        '会签不能"谁都可以签"——那样等于没人负责', r.name;
    END IF;
    IF v_uid <= 0 THEN
      RAISE EXCEPTION 'E_SIGNOFF_NO_USER: 角色「%」指定的账号 % 无效', r.name, v_uid;
    END IF;

    INSERT INTO public.pay_run_signoff(pay_run_id, role_code, role_name, seq, assignee_user_id)
    VALUES (p_run, r.code, r.name, r.seq, v_uid)
    ON CONFLICT (pay_run_id, role_code) DO UPDATE
      -- 已签的不动（一个人签过就是签过）；未签/异议的改成新指定人 + 回到 pending
      SET assignee_user_id = EXCLUDED.assignee_user_id,
          status      = CASE WHEN pay_run_signoff.status = 'approved'
                             THEN 'approved' ELSE 'pending' END,
          decided_at  = CASE WHEN pay_run_signoff.status = 'approved'
                             THEN pay_run_signoff.decided_at ELSE NULL END,
          decided_by  = CASE WHEN pay_run_signoff.status = 'approved'
                             THEN pay_run_signoff.decided_by ELSE NULL END,
          note        = CASE WHEN pay_run_signoff.status = 'approved'
                             THEN pay_run_signoff.note ELSE NULL END;
    v_n := v_n + 1;
  END LOOP;

  RETURN v_n;
END;
$$;

COMMENT ON FUNCTION fn_signoff_start IS
  '发起工资表会签：按启用的角色生成待签行，签字人必须指定（或角色上配了默认人）。'
  '重新发起时未签的行作废、已签的保留（签过的意思不丢，但这一轮要重新签）。';

-- ---------------------------------------------------------------------------
-- 5. 签字 / 提异议
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_signoff_decide(
  p_id bigint, p_user bigint, p_ok boolean, p_note text DEFAULT NULL
) RETURNS varchar
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  s record;
  v_status varchar(16);
BEGIN
  SELECT * INTO s FROM public.pay_run_signoff WHERE id = p_id FOR UPDATE;
  IF s.id IS NULL THEN RAISE EXCEPTION 'E_SIGNOFF_NOT_FOUND: %', p_id; END IF;

  -- ★ 只能签自己那一行。不校验的话，"会签"就退化成"谁点一下都算通过"，
  --   而审计看的正是"这一行是谁签的"。
  IF s.assignee_user_id <> p_user THEN
    RAISE EXCEPTION 'E_SIGNOFF_NOT_YOURS: 这一行指定给账号 %，你（%）不能代签',
      s.assignee_user_id, p_user;
  END IF;
  IF s.status NOT IN ('pending') THEN
    RAISE EXCEPTION 'E_SIGNOFF_CLOSED: 这一行已经是 % ，不能重复签', s.status;
  END IF;
  IF EXISTS (SELECT 1 FROM public.pay_run r WHERE r.id = s.pay_run_id AND r.status <> 'draft') THEN
    RAISE EXCEPTION 'E_RUN_SEALED: 批次已封账，不能再签';
  END IF;

  IF p_ok THEN
    v_status := 'approved';
  ELSE
    IF p_note IS NULL OR length(btrim(p_note)) < 4 THEN
      RAISE EXCEPTION 'E_SIGNOFF_NO_NOTE: 提异议必须写清是什么异议（至少 4 个字）——'
        '只说"有问题"的话，发起人无从修改';
    END IF;
    v_status := 'objected';
  END IF;

  UPDATE public.pay_run_signoff
     SET status = v_status, decided_at = clock_timestamp(), decided_by = p_user,
         note = NULLIF(btrim(COALESCE(p_note, '')), '')
   WHERE id = p_id;

  RETURN v_status;
END;
$$;

COMMENT ON FUNCTION fn_signoff_decide IS
  '签字或提异议。只能签自己那一行（代签会让"谁签的"失去意义）；'
  '提异议必须写原因（至少 4 字），否则发起人无从修改。';

-- ---------------------------------------------------------------------------
-- 6. 会签状态：封账门禁用，也给界面用
-- ---------------------------------------------------------------------------
-- 返回每个角色的状态与"能不能封账"。一门两用：界面据此显示进度，
-- fn_pay_run_seal 据此拦人 —— 两处若各算一遍，"页面说能封、点了封不了"就会出现。
CREATE OR REPLACE FUNCTION fn_signoff_status(p_run bigint)
RETURNS TABLE (
  -- ★ 必须把行 id 带出来：界面签字要按 id 调 fn_signoff_decide。
  --   第一版只返回 role_code，界面只能"按角色反查"—— 而那一刻手里根本没有 id。
  id bigint,
  role_code varchar, role_name varchar, seq smallint, assignee bigint,
  assignee_name varchar, status varchar, decided_at timestamptz,
  decided_by_name varchar, note varchar, is_required boolean, can_seal boolean
)
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
#variable_conflict use_column
-- ★ OUT 参数名 id 与表列 s.id / a.id 同名，PL/pgSQL 默认把裸名当成变量 →
--   "column reference id is ambiguous"。这句让列优先（本函数所有列引用都带别名）。
--   与 136 的 fn_payslip_diff 同一个坑：RETURNS TABLE 的列名是变量。
DECLARE
  v_required boolean;
  v_run      record;
  v_rows     int;
  v_bad      int;
BEGIN
  SELECT value_text = 'on' INTO v_required
    FROM public.fn_policy_effective('PAY_SIGNOFF_REQUIRED', NULL, public.app_today());
  v_required := COALESCE(v_required, false);

  SELECT * INTO v_run FROM public.pay_run WHERE id = p_run;

  SELECT count(*) FILTER (WHERE s.status <> 'void'),
         count(*) FILTER (WHERE s.status IN ('pending','objected'))
    INTO v_rows, v_bad
    FROM public.pay_run_signoff s WHERE s.pay_run_id = p_run;

  RETURN QUERY
  SELECT s.id, s.role_code, s.role_name, s.seq, s.assignee_user_id,
         COALESCE(a.display_name, '账号 ' || s.assignee_user_id),
         s.status, s.decided_at,
         COALESCE(d.display_name, CASE WHEN s.decided_by IS NULL THEN NULL
                                       ELSE '账号 ' || s.decided_by END),
         s.note,
         v_required,
         -- 能封账的条件（两种"可以"）：
         --   ① 没发起会签 且 制度不强制 → 允许（与上线前行为一致）
         --   ② 发起过会签 → **必须全部签完**，不管制度开没开
         -- ★ ② 是"一旦发出去就按会签算"：制度只决定"要不要发起"，
         --   而不是"发起了也能无视结果"。否则会出现"有异议还能封账"，
         --   那会签就只是给人看的装饰。
         (v_run.status = 'draft' AND ((v_rows = 0 AND NOT v_required)
                                   OR (v_rows > 0 AND v_bad = 0)))
    FROM public.pay_run_signoff s
    -- LEFT JOIN + 兜底文案：没有账号档案时也要能显示"谁该签"，
    -- 否则会签页整行消失，而人以为"没发起"
    LEFT JOIN public.sys_account a ON a.id = s.assignee_user_id
    LEFT JOIN public.sys_account d ON d.id = s.decided_by
   WHERE s.pay_run_id = p_run AND s.status <> 'void'
   ORDER BY s.seq, s.role_code;
END;
$$;

COMMENT ON FUNCTION fn_signoff_status IS
  '会签进度 + 能否封账。封账门禁与界面共用这一个判据 —— 各算一遍会出现"页面说能封、点了封不了"。';

-- ---------------------------------------------------------------------------
-- 7. 封账：以前只能直接 UPDATE，现在有函数
-- ---------------------------------------------------------------------------
-- ★ 封账是"这批数定了"的承诺。所以它必须做三件事：
--   ① 只允许 draft（封了不能再封）；
--   ② 必须有工资条（空批次封账没有意义）；
--   ③ 会签强制时，必须全部签完（有异议就是没签完 —— 异议是要改数的信号）。
CREATE OR REPLACE FUNCTION fn_pay_run_seal(p_run bigint, p_by text)
RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  r        record;
  v_req    boolean;
  v_total  int;
  v_bad    int;
  v_names  text;
BEGIN
  SELECT * INTO r FROM public.pay_run WHERE id = p_run FOR UPDATE;
  IF r.id IS NULL THEN RAISE EXCEPTION 'E_RUN_NOT_FOUND: %', p_run; END IF;
  IF r.status <> 'draft' THEN
    RAISE EXCEPTION 'E_RUN_SEALED: 批次 % 已经是 % 状态', p_run, r.status;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.payslip p WHERE p.pay_run_id = p_run) THEN
    RAISE EXCEPTION 'E_SEAL_EMPTY: 批次 % 没有工资条，不能封账', p_run;
  END IF;

  SELECT value_text = 'on' INTO v_req
    FROM public.fn_policy_effective('PAY_SIGNOFF_REQUIRED', NULL, public.app_today());

  SELECT count(*) FILTER (WHERE s.status <> 'void'),
         count(*) FILTER (WHERE s.status IN ('pending','objected'))
    INTO v_total, v_bad
    FROM public.pay_run_signoff s WHERE s.pay_run_id = p_run;

  -- ① 制度强制却没发起 → 拒
  IF COALESCE(v_req, false) AND v_total = 0 THEN
    RAISE EXCEPTION 'E_SIGNOFF_NOT_STARTED: 制度要求封账前完成会签，但批次 % 还没发起会签', p_run;
  END IF;

  -- ② 发起过会签就必须签完（不管制度开没开）。
  --    否则"有异议也能封账"，会签就只是装饰。
  IF v_total > 0 THEN
    IF v_bad > 0 THEN
      -- ★ ORDER BY 必须写在聚合函数里（string_agg(x, '、' ORDER BY ...)）：
      --   写成语句末尾的 ORDER BY 会得到 "column s.seq must appear in the GROUP BY clause"，
      --   而那个错看起来像"我漏了 GROUP BY"，实际是聚合函数自带排序这个语法。
      SELECT string_agg(s.role_name || '（' ||
               CASE s.status WHEN 'objected' THEN '有异议' ELSE '未签' END || '）',
               '、' ORDER BY s.seq)
        INTO v_names
        FROM public.pay_run_signoff s
       WHERE s.pay_run_id = p_run AND s.status IN ('pending','objected');
      RAISE EXCEPTION 'E_SIGNOFF_PENDING: 还有 % 个会签未完成：%。'
        '有异议的先改数，再重新发起会签', v_bad, v_names;
    END IF;
  END IF;

  UPDATE public.pay_run
     SET status = 'sealed', sealed_at = clock_timestamp(), sealed_by = p_by
   WHERE id = p_run;
END;
$$;

COMMENT ON FUNCTION fn_pay_run_seal IS
  '封账。只允许 draft、必须有工资条；制度开启会签时要求全部签完（有异议即未完成）。'
  'sealed_by 记下"谁定的"—— 以前只有时间没有责任人。';

