-- ===========================================================================
-- 139 · 工资表会签：谁看过、谁提了异议、什么时候定稿
-- ===========================================================================
-- 现状：算完薪直接封账（status='sealed'）。中间没有任何记录 ——
-- 而真实场景里这张表要出去三趟：出纳核金额、财务核个税与社保、业务负责人核奖金。
-- 异议往往就出在"某个店长发现自己奖金少了"，而这些沟通发生在微信里，
-- 系统里查不到 —— 出事时连"当初谁看过"都答不上来。
--
-- 这一版只做**签字**，不做审批流引擎：
--   · 不做可配置多级审批（那是另一个产品）；
--   · 不按岗位自动找人（人在休假就签不了）—— 由发起人指定"这张表谁签"，
--     现实里也确实是"发给老王看"这件事；
--   · 会签结果要么全通过、要么有异议。**有异议就不许封账**，
--     否则会签只是走过场，反而给了"已审核"的错觉。
--
-- ★ 默认不强制（制度项 PAY_SIGNOFF_REQUIRED = off）：不改变上线前的封账行为。
--   打开之后，没签完的批次封不了账。这类"口径有两种合法答案"的事做成配置项，
--   而不是替客户选。
-- ===========================================================================

-- 封账人：原来只有 sealed_at，没有 sealed_by —— 封了账不知道是谁封的
ALTER TABLE pay_run ADD COLUMN IF NOT EXISTS sealed_by varchar(64);

COMMENT ON COLUMN pay_run.sealed_by IS
  '封账操作人（账号 id 或登录名）。与 sealed_at 同生同灭：封账之后这就是"谁定的"的唯一答案。';

-- ---------------------------------------------------------------------------
-- 1. 会签角色：预置三种，可增删
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pay_signoff_role (
  code       varchar(24) PRIMARY KEY,
  name       varchar(48) NOT NULL,
  seq        smallint    NOT NULL DEFAULT 10,
  is_active  boolean     NOT NULL DEFAULT true,
  -- 常用签字人（发起时作为默认值；实际签字人写在会签行上）
  default_user_id bigint
);

COMMENT ON TABLE pay_signoff_role IS
  '工资表会签角色。seq 决定签字顺序（出纳 → 财务 → 业务），但顺序只是提示，'
  '系统不强制"必须按顺序签" —— 现实里常常是同时发出去。';

INSERT INTO pay_signoff_role(code, name, seq) VALUES
  ('cashier', '出纳（核金额）', 10),
  ('finance', '财务负责人（核个税与社保）', 20),
  ('biz',     '业务负责人（核奖金提成）', 30)
