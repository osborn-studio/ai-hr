-- ---------------------------------------------------------------------------
-- 2. 会签行：一张工资表 × 一个角色 = 一行
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pay_run_signoff (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pay_run_id      bigint NOT NULL REFERENCES pay_run(id),
  role_code       varchar(24) NOT NULL,
  role_name       varchar(48) NOT NULL,          -- 快照：角色改名后历史单据仍可读
  seq             smallint NOT NULL DEFAULT 10,
  -- ★ 不挂 sys_account 外键：系统的登录身份是 user_id（sys_user_credential），
  --   而 sys_account 是"建帐时开出来的账号档案"，可以有身份没档案（迁移直接建库、
  --   或钉钉同步进来的帐套）。挂外键会让这类环境的会签直接建不起来，
  --   报的还是"账号不存在"——看起来像配错了人。
  assignee_user_id bigint NOT NULL,
  status          varchar(16) NOT NULL DEFAULT 'pending',
  decided_at      timestamptz,
  decided_by      bigint,
  note            varchar(300),
  CONSTRAINT uk_prs_role UNIQUE (pay_run_id, role_code),
  CONSTRAINT ck_prs_status CHECK (status IN ('pending','approved','objected','void')),
  -- ★ 状态与时刻同生同灭（与 leave_request / pay_run 同一条规矩）：
  --   非 pending 必须有 decided_at，pending 必须没有。
  CONSTRAINT ck_prs_decided CHECK ((status = 'pending') = (decided_at IS NULL)),
  -- 提异议必须写清是什么异议，否则发起人无从修
  CONSTRAINT ck_prs_objected CHECK (status <> 'objected' OR (note IS NOT NULL AND length(btrim(note)) >= 4))
);

CREATE INDEX IF NOT EXISTS ix_prs_run ON pay_run_signoff(pay_run_id);

COMMENT ON TABLE pay_run_signoff IS
  '工资表会签行。status: pending 待签 / approved 已签 / objected 提异议 / void 作废（重新发起时旧行作废，不删）。';

