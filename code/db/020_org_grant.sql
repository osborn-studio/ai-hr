-- ============================================================================
-- 020_org_grant.sql · 组织级授权（集团统一管理）
-- ----------------------------------------------------------------------------
-- 前面十八个迁移里，授权主体只有一个：**账号**（sys_user_role.user_id）。
-- 那适合"每个门店各管各的"，不适合集团：
--
--   集团把"门店 HR"这个角色授给「华东区」，华东区下 47 家门店的 HR
--   应该全部生效，而不是让实施把 47 条授权逐条敲一遍。
--
--   更麻烦的是新开一家店：逐条授权的做法下，它**不会**获得任何权限，
--   而症状是"新店 HR 登录进去什么都看不到"——看起来像账号配错了。
--
-- 所以授权主体有两类，且第二类是"组织"，不是"一组账号"：
--
--   ① 账号直接授权（sys_user_role，既有）
--   ② 组织授权（sys_org_grant）—— 组织成员**继承**，且沿组织树**向上继承**
--
-- 三条判据决定这一层对不对：
--   · 继承单向：授在祖先 → 后代获得；授在后代 → 祖先**不**获得
--   · 每条有效权限必须能回答「它从哪来」（direct / org + 哪个组织）
--   · 组织停用时授权随之失效，且必须报出影响多少个账号
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 组织可用性
-- ---------------------------------------------------------------------------
-- 组织撤销在完整系统里应当体现在组织版本快照（017）里：撤销的节点不再出现
-- 在新版本的快照中。但"停用"是一个比"撤销"更轻的动作（暂停、合并中），
-- 它不改树形，只改可用性，所以单独一列。
ALTER TABLE org_unit ADD COLUMN is_active boolean NOT NULL DEFAULT true;

COMMENT ON COLUMN org_unit.is_active IS
  '停用不等于撤销：停用后组织仍在树里（历史归属仍指得到它），'
  '但它名下的授权**不再生效**。两者分开，是因为"暂停"与"消失"在报表上必须不同。';

-- ---------------------------------------------------------------------------
-- 账号属于哪个组织
-- ---------------------------------------------------------------------------
-- ★ 这一层不能省。没有它，"组织授权"就只能靠"账号名去猜它属于哪个部门"，
--   而那件事在任何一个真实的集团里都猜不对（一人多岗、兼管、代管）。
--
-- 也**不能**用 employment 的组织归属代替：账号是"谁在登录"，
-- 任职是"谁在被算钱"。一个人可以登录了但还没入职，也可以离职了仍要查历史。
CREATE TABLE sys_user_org (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        bigint      NOT NULL,
  org_id         bigint      NOT NULL REFERENCES org_unit(id),
  effective_from date        NOT NULL,
  effective_to   date,
  CONSTRAINT ck_suo_span CHECK (effective_to IS NULL OR effective_to > effective_from)
);

ALTER TABLE sys_user_org ADD CONSTRAINT ex_suo_no_overlap
  EXCLUDE USING gist (
    user_id WITH =,
    daterange(effective_from, effective_to, '[)') WITH &&
  );

-- ---------------------------------------------------------------------------
-- 组织级授权
-- ---------------------------------------------------------------------------
CREATE TABLE sys_org_grant (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id         bigint      NOT NULL REFERENCES org_unit(id),
  role_id        bigint      NOT NULL,
  data_scope_id  bigint      NOT NULL REFERENCES sys_data_scope(id),
  effective_from date        NOT NULL,
  effective_to   date,
  granted_by     varchar(64) NOT NULL,
  -- ★ 理由必填且不能是空白。给一个组织授权，等于一次给几十上百人开权限，
  --   而"为什么"是事后唯一能复查的东西。空白理由能通过 NOT NULL。
  reason         varchar(200) NOT NULL,
  revoked_at     timestamptz,
  CONSTRAINT ck_sog_span   CHECK (effective_to IS NULL OR effective_to > effective_from),
  CONSTRAINT ck_sog_reason CHECK (length(btrim(reason)) >= 4),
  -- 撤销必须是显式事实，不是"删掉那行"——删掉之后没人知道这里曾经有过授权
  CONSTRAINT ck_sog_revoke CHECK (revoked_at IS NULL OR revoked_at >= effective_from::timestamptz)
);

CREATE INDEX ix_sog_org ON sys_org_grant(org_id) WHERE revoked_at IS NULL;

-- ---------------------------------------------------------------------------
-- 账号的组织链（自身 + 全部祖先）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_user_org_chain(p_user bigint, p_on date)
RETURNS TABLE (org_id bigint, depth int)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  WITH mine AS (
    SELECT u.org_id, o.path
      FROM public.sys_user_org u
      JOIN public.org_unit o ON o.id = u.org_id
     WHERE u.user_id = p_user
       AND daterange(u.effective_from, u.effective_to, '[)') @> p_on
  )
  -- 沿 path 前缀向上取：归属于自己的组织 → 它的父 → 祖父 …
  -- 用 path 而不是递归 CTE：树深个位数，前缀匹配一次扫完，且与 001 的
  -- node_subtree 是同一套语义——两处用两种算法，迟早给出两个答案。
  SELECT DISTINCT p.id,
         array_length(string_to_array(p.path, '.'), 1) AS depth
    FROM public.org_unit p
   WHERE EXISTS (SELECT 1 FROM mine m WHERE m.path LIKE p.path || '%');
$$;

COMMENT ON FUNCTION fn_user_org_chain IS
  '返回账号在 p_on 所属组织及其全部祖先。**向上**是唯一的继承方向：'
  '授权给区域，门店的人获得；授权给门店，区域的人不获得——'
  '反向继承会让"某家店的特殊权限"悄悄变成整个区域的权限。';

-- ---------------------------------------------------------------------------
-- 有效权限：直接授权 ∪ 组织继承，且每条带来源
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_effective_roles(p_user bigint, p_on date)
RETURNS TABLE (role_id bigint, data_scope_id bigint, source varchar(16), via_org_id bigint)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  -- ① 直接授权
  SELECT ur.role_id, ur.data_scope_id, 'direct'::varchar(16), NULL::bigint
    FROM public.sys_user_role ur
   WHERE ur.user_id = p_user
     AND ur.superseded_by IS NULL
     AND daterange(ur.effective_from, ur.effective_to, '[)') @> p_on
  UNION
  -- ② 组织继承（沿祖先链向上）
  SELECT g.role_id, g.data_scope_id, 'org'::varchar(16), g.org_id
    FROM public.sys_org_grant g
    JOIN public.org_unit o ON o.id = g.org_id
   WHERE o.is_active                                  -- 组织停用 → 授权失效
     AND g.revoked_at IS NULL
     AND daterange(g.effective_from, g.effective_to, '[)') @> p_on
     AND g.org_id IN (SELECT c.org_id FROM public.fn_user_org_chain(p_user, p_on) c);
$$;

COMMENT ON FUNCTION fn_effective_roles IS
  'UNION 去重，但**来源保留**：同一角色既直接授又从组织继承时，两行都在。'
  '去掉来源只剩 role_id 的话，审计只能回答"他有这个权限"，'
  '而真正要回答的是"他为什么有"——转岗之后解释不清的那一类问题都出自这里。';

-- ---------------------------------------------------------------------------
-- 组织停用的影响面
-- ---------------------------------------------------------------------------
-- ★ 停用一个组织之前必须能回答"会影响多少个账号"。
--   答不出来的时候，人会把 is_active 直接改成 false 试一下，
--   而试完的后果分散在几十个账号的登录体验上，没有人汇总过。
CREATE OR REPLACE FUNCTION fn_org_grant_impact(p_org bigint)
RETURNS TABLE (grant_count int, user_count int, role_ids bigint[])
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  WITH chain AS (
    -- 该组织及其**所有后代**——授在区域，受影响的是整个子树
    SELECT o.id FROM public.org_unit o
     WHERE o.id = p_org
        OR o.path LIKE (SELECT path || '%' FROM public.org_unit WHERE id = p_org)
  ), g AS (
    SELECT g.id, g.role_id FROM public.sys_org_grant g
     WHERE g.org_id IN (SELECT id FROM chain) AND g.revoked_at IS NULL
  ), u AS (
    SELECT DISTINCT uo.user_id
      FROM public.sys_user_org uo WHERE uo.org_id IN (SELECT id FROM chain)
  )
  SELECT (SELECT count(*)::int FROM g),
         (SELECT count(*)::int FROM u),
         (SELECT COALESCE(array_agg(DISTINCT role_id), '{}') FROM g);
$$;

-- ---------------------------------------------------------------------------
-- 接线：入口函数改用有效权限
-- ---------------------------------------------------------------------------
-- 判据写了但不接线，等于没写。下面两段是 001 里 app_begin_scope 的替换：
-- 原来直接读 sys_user_role，现在读 fn_effective_roles，于是组织授权
-- **真的会**灌进临时表，而不仅仅是"登记了一条记录"。
CREATE OR REPLACE FUNCTION fn_scope_rules(p_user bigint, p_as_of date)
RETURNS TABLE (dimension varchar(24), value_type varchar(16), value_ids bigint[], kind varchar(8))
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  -- 同一角色被多条路径授予时，data_scope 会重复；DISTINCT 让每条范围只出现一次，
  -- 否则临时表里同一维度会被灌入重复值（结果不错但行数虚高，而虚高的分母
  -- 会让人以为"范围很大"）。
  SELECT DISTINCT ru.dimension, ru.value_type, ru.value_ids, dm.kind
    FROM public.fn_effective_roles(p_user, p_as_of) er
    JOIN public.sys_data_scope_rule ru ON ru.data_scope_id = er.data_scope_id
    JOIN public.sys_perm_dim        dm ON dm.code        = ru.dimension;
$$;

CREATE OR REPLACE FUNCTION fn_deny_roles(p_user bigint, p_as_of date)
RETURNS TABLE (role_id bigint)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT DISTINCT er.role_id FROM public.fn_effective_roles(p_user, p_as_of) er;
$$;
