-- ============================================================================
-- 064_ledger.sql · 建帐：新公司进来，从"空库"到"能用"的那几步
-- ----------------------------------------------------------------------------
-- 到 064 为止，这套系统**没有"开一个新客户"的路径**：组织、人员、账号全是
-- 种子写进去的。演示没问题，但客户签约后的第一件事就是"给我开一个帐套"，
-- 而那时只能靠人对着 SQL 抄一遍种子 —— 抄漏一个门店、抄错一个角色，
-- 都不会报错，只会让对面在第三天发现"我们店少了一家"。
--
-- 这一层补三件事，顺序就是真实顺序：
--
--   ① **开帐套**（fn_ledger_open）：名称、编码、启用期间。启用期间一旦写定
--      不再改（改它等于让已经算过的薪换个会计期间）。
--   ② **加组织**（fn_org_add）：集团 → 区域 → 门店，path 自动派生，层级受约束。
--   ③ **加账号**（fn_account_create）：账号主档 + 角色 + 数据范围，一次落。
--
-- 三个设计判断：
--
--   A. **帐套只有一份，但表要有**。真正的多帐套（一家代账公司管十个客户）
--      需要在**每一张业务表**上加 tenant 维度 —— 那是一次大改，不是加张表。
--      所以这里建"帐套档案"，并明确写出：**目前不做多租户隔离**，
--      多开一份帐套 = 多起一个实例（一个库一份数据）。
--      把这句话写在表注释里，比写在 README 里更容易被下一个接手的人看到。
--
--   B. **账号是主档，角色是授权**。原来 sys_user 根本不存在，只有
--      sys_user_role 里的裸 user_id —— 于是"这个人叫什么、能不能登录"
--      无处可查。没有主档的账号体系，删一个人只能靠记得去删三张表。
--
--   C. **建帐与运营分开**。建帐只写结构性数据（帐套/组织/账号/制度），
--      不灌业务数据（考勤、工资条）。业务数据靠运营产生 ——
--      演示数据是"演示脚本"的事，不是建帐的事。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 0. sys_user_role.id 补生成方式（第九次同一个坑）
-- ---------------------------------------------------------------------------
-- 001 写的是 `id bigint PRIMARY KEY` —— 没有 IDENTITY。种子一直写显式 id，
-- 所以从来没红过；而"加账号"是第一个**由函数插入**它的路径，立刻就 23502。
-- Q14 那条机器判据扫的是"会被函数 INSERT 的表"，这次它本该先抓到 ——
-- 但本迁移自己就是那个函数，所以只能人抓。教训写在这里：
-- **新增一个往老表里插数据的函数时，先确认老表的主键有生成方式。**
ALTER TABLE sys_user_role ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
-- 同一个坑的第二张表：org_unit 也是这样（种子写显式 id 10/11/12/30）。
-- 建帐是第一个"由函数插组织"的路径 —— 23502 not-null on id 立刻出现。
ALTER TABLE org_unit        ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE sys_data_scope  ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

-- ★ 四维词表也必须进迁移：它原来只在 server.mjs 的种子里。
--   建帐在没有种子的库上给账号造数据范围时，`dimension='cost_org'` 会撞
--   sys_data_scope_rule_dimension_fkey —— 报错只说 FK，看起来像"范围配错了"，
--   其实是"这张词表从来没被谁补全过"。与第 0 节同一条教训。
INSERT INTO sys_perm_dim(code, kind, label) VALUES
  ('cost_org',            'org',    '成本组织'),
  ('attendance_org',      'org',    '考勤组织'),
  ('payroll_legal_entity','entity', '发薪法人'),
  ('si_entity',           'entity', '参保主体')
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 1. 帐套档案
-- ---------------------------------------------------------------------------
CREATE TABLE sys_ledger (
  id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  code         varchar(32) NOT NULL UNIQUE,
  name         varchar(96) NOT NULL,
  start_period varchar(7)  NOT NULL,
  status       varchar(16) NOT NULL DEFAULT 'draft',
  created_by   varchar(64) NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  activated_at timestamptz,
  CONSTRAINT ck_lg_period CHECK (start_period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  CONSTRAINT ck_lg_status CHECK (status IN ('draft','active')),
  -- 启用必有时间；草稿必没有。两个字段同生同灭，否则"启用了但不知道哪天"
  CONSTRAINT ck_lg_active CHECK ((status = 'active') = (activated_at IS NOT NULL))
);

COMMENT ON TABLE sys_ledger IS
  '帐套档案。**目前不做多租户隔离**：多开一份帐套 = 多起一个实例（一个库一份数据）。'
  '真做多帐套要在每张业务表上加 tenant 维度，那是一次大改 —— 写在这里，'
  '免得下一个接手的人以为"加张表就能开第二个客户"。';

-- ---------------------------------------------------------------------------
-- 2. 账号主档
-- ---------------------------------------------------------------------------
CREATE TABLE sys_account (
  id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  login        varchar(64) NOT NULL UNIQUE,
  display_name varchar(64) NOT NULL,
  -- 绑人：账号与员工是**两个实体**（009/053 的同一判断）。可以有人没账号（门店店员），
  -- 也可以有账号没人（系统管理员）。
  person_id    bigint REFERENCES person(id),
  status       varchar(16) NOT NULL DEFAULT 'active',
  created_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_sa_status CHECK (status IN ('active','disabled')),
  -- ★ 下限 2 而不是 3：`hr` 这样的登录名是常态，而"3 位起步"这种约定
  --   会在建第一个帐号时报 23514，报错只说 ck_sa_login，看不出是长度。
  CONSTRAINT ck_sa_login  CHECK (login ~ '^[a-zA-Z0-9_.-]{2,64}$')
);

COMMENT ON TABLE sys_account IS
  '账号主档：登录名 / 显示名 / 绑定的人 / 状态。'
  '原来只有 sys_user_role 里的裸 user_id —— 没有主档，删一个人要靠记得去删三张表。';

-- ---------------------------------------------------------------------------
-- 3. 开帐套
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_ledger_open(
  p_code varchar, p_name varchar, p_start_period varchar, p_by varchar
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_id bigint; v_n int;
BEGIN
  SELECT count(*)::int INTO v_n FROM public.sys_ledger;
  IF v_n > 0 THEN
    RAISE EXCEPTION 'E_LEDGER_EXISTS: 这个库里已经有帐套了（当前 % 份）。'
      '本系统一份库只放一份帐套 —— 多客户请各自起实例', v_n;
  END IF;
  IF p_start_period !~ '^[0-9]{4}-(0[1-9]|1[0-2])$' THEN
    RAISE EXCEPTION 'E_LEDGER_PERIOD: 启用期间必须是 YYYY-MM，收到 %', p_start_period;
  END IF;
  IF p_name IS NULL OR length(btrim(p_name)) < 2 THEN
    RAISE EXCEPTION 'E_LEDGER_NAME: 帐套名称至少 2 个字';
  END IF;

  INSERT INTO public.sys_ledger(code, name, start_period, created_by)
  VALUES (btrim(p_code), btrim(p_name), p_start_period, p_by)
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION fn_ledger_activate(p_by varchar) RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_id bigint;
BEGIN
  SELECT id INTO v_id FROM public.sys_ledger WHERE status = 'draft' FOR UPDATE;
  IF v_id IS NULL THEN
    RAISE EXCEPTION 'E_LEDGER_NO_DRAFT: 没有待启用的帐套（可能已经启用过了）';
  END IF;
  -- 启用前至少要有一个集团根组织，否则启用之后第一步就卡住
  IF NOT EXISTS (SELECT 1 FROM public.org_unit WHERE parent_id IS NULL) THEN
    RAISE EXCEPTION 'E_LEDGER_NO_ORG: 还没有集团根组织 —— 先建组织再启用';
  END IF;
  UPDATE public.sys_ledger SET status = 'active', activated_at = now() WHERE id = v_id;
END;
$$;

-- ---------------------------------------------------------------------------
-- 4. 加组织（集团 / 区域 / 门店）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_org_add(
  p_parent bigint,          -- NULL = 建集团根（只允许一个）
  p_name   varchar,
  p_kind   varchar          -- group | region | store
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_parent public.org_unit%ROWTYPE;
  v_depth  int;
  v_seq    int;
  v_path   varchar(200);
  v_id     bigint;
BEGIN
  IF p_kind NOT IN ('group','region','store') THEN
    RAISE EXCEPTION 'E_ORG_KIND: 组织类型只能是 group / region / store（收到 %）', p_kind;
  END IF;
  IF p_name IS NULL OR length(btrim(p_name)) < 2 THEN
    RAISE EXCEPTION 'E_ORG_NAME: 组织名称至少 2 个字';
  END IF;

  IF p_parent IS NULL THEN
    IF p_kind <> 'group' THEN
      RAISE EXCEPTION 'E_ORG_ROOT: 根组织只能是 group（集团）';
    END IF;
    IF EXISTS (SELECT 1 FROM public.org_unit WHERE parent_id IS NULL) THEN
      RAISE EXCEPTION 'E_ORG_ROOT_EXISTS: 已经有集团根组织了（一份帐套只有一个集团）';
    END IF;
    v_path := '001';
  ELSE
    SELECT * INTO v_parent FROM public.org_unit WHERE id = p_parent;
    IF v_parent.id IS NULL THEN
      RAISE EXCEPTION 'E_ORG_NO_PARENT: 上级组织 % 不存在', p_parent;
    END IF;
    v_depth := array_length(string_to_array(v_parent.path, '.'), 1);
    -- 层级约束：集团(1) → 区域(2) → 门店(3)。不限制的话会出现"门店下面再挂门店"，
    -- 而那会让"这个门店有几个人"的汇总把下级店也算进去。
    IF (v_depth = 1 AND p_kind <> 'region')
       OR (v_depth = 2 AND p_kind <> 'store')
       OR v_depth >= 3 THEN
      RAISE EXCEPTION 'E_ORG_DEPTH: 上级（第 % 层）下面只能挂 %',
        v_depth, CASE v_depth WHEN 1 THEN 'region' WHEN 2 THEN 'store' ELSE '（没有下一层）' END;
    END IF;

    -- 同级序号：取现有子节点里最大的三位段 +1
    SELECT COALESCE(max((substring(path from '([0-9]+)$'))::int), 0) + 1 INTO v_seq
      FROM public.org_unit WHERE parent_id = p_parent;
    v_path := v_parent.path || '.' || lpad(v_seq::text, 3, '0');
  END IF;

  INSERT INTO public.org_unit(parent_id, name, path) VALUES (p_parent, btrim(p_name), v_path)
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_org_add IS
  '加组织：path 自动派生（父 path + 三位序号），层级硬约束 集团→区域→门店。'
  '不约束的话会出现"门店下面再挂门店"，而"这个门店有几个人"的汇总会把下级店算进去。';

-- ---------------------------------------------------------------------------
-- 5. 加账号（主档 + 角色 + 数据范围）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_account_create(
  p_login    varchar,
  p_display  varchar,
  p_role     varchar,        -- 角色 code（063）
  p_org      bigint,         -- 数据范围挂在哪个组织上（NULL = 全集团）
  p_person   bigint DEFAULT NULL,
  p_by       varchar DEFAULT 'system'
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_role public.sys_role%ROWTYPE;
  v_scope bigint;
  v_uid   bigint;
BEGIN
  SELECT * INTO v_role FROM public.sys_role WHERE code = p_role AND is_active;
  IF v_role.id IS NULL THEN
    RAISE EXCEPTION 'E_ACCOUNT_ROLE: 角色 % 不存在（见 sys_role）', p_role;
  END IF;

  INSERT INTO public.sys_account(login, display_name, person_id)
  VALUES (btrim(p_login), btrim(p_display), p_person)
  RETURNING id INTO v_uid;

  -- 数据范围：按"这个组织 + 它的整棵子树"造一个专用 scope（同 020 的 node_subtree）。
  -- ★ 集团账号也要造自己的范围，**不假设"1 号范围存在"** ——
  --   1 号是种子建的；建帐脚本跑在没有种子的库上，那条假设立刻变成 FK 报错
  --   （sys_user_role_data_scope_id_fkey），而它看起来像"范围配错了"。
  IF p_org IS NULL THEN
    SELECT id INTO v_scope FROM public.org_unit WHERE parent_id IS NULL LIMIT 1;
    IF v_scope IS NULL THEN
      RAISE EXCEPTION 'E_LEDGER_NO_ORG: 还没有集团根组织 —— 先加组织再加账号';
    END IF;
    p_org := v_scope;                        -- 集团账号 = 根组织的整棵子树
  END IF;

  IF true THEN
    INSERT INTO public.sys_data_scope(name, combinator) VALUES ('账号:' || p_login, 'intersection')
    RETURNING id INTO v_scope;
    INSERT INTO public.sys_data_scope_rule(data_scope_id, dimension, value_type, value_ids)
    SELECT v_scope, 'cost_org', 'node_subtree', ARRAY[p_org]::bigint[];
    INSERT INTO public.sys_data_scope_rule(data_scope_id, dimension, value_type, value_ids)
    SELECT v_scope, 'attendance_org', 'node_subtree', ARRAY[p_org]::bigint[];
    INSERT INTO public.sys_data_scope_rule(data_scope_id, dimension, value_type, value_ids)
    SELECT v_scope, 'payroll_legal_entity', 'nodes', ARRAY[1]::bigint[];
    INSERT INTO public.sys_data_scope_rule(data_scope_id, dimension, value_type, value_ids)
    SELECT v_scope, 'si_entity', 'nodes', ARRAY[1]::bigint[];
  END IF;

  INSERT INTO public.sys_user_role(user_id, role_id, data_scope_id, granted_by, grant_kind,
                                   grant_reason, effective_from)
  VALUES (v_uid, v_role.id, v_scope, NULL, 'ROLE', '建帐创建：' || p_by, current_date);

  RETURN v_uid;
END;
$$;

COMMENT ON FUNCTION fn_account_create IS
  '加账号：主档 + 角色 + 专有数据范围，一次落。'
  '口令不在这里 —— 哈希必须在应用层用 scrypt 现算（库侧只存摘要）。';

