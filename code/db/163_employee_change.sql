-- ============================================================================
-- 163_employee_change.sql · 员工异动：调岗 / 转店 / 用工类型转换 → 变更协议
-- ----------------------------------------------------------------------------
-- 现状：调薪有 salary_adjustment（带生效日），归属有 employee_org_assignment
-- （带有效期段），合同有 employment_contract。但**没有任何东西把"一个人被调走了"
-- 这件事记成一条单据**，而它恰恰是劳动争议里最高发的一类：
--
--   · 员工被调到另一家店，系统里改了归属，合同上的"工作地点"还是老店；
--     员工主张"未经协商变更工作地点"，公司拿不出书面变更 —— 按原合同履行。
--   · 员工从店员提为店长，工资涨了、岗位改了，合同没改；
--     离职时算经济补偿，基数按"合同约定工资"还是"实际工资"？两套说法。
--
-- 《劳动合同法》第三十五条：变更劳动合同，应当**采用书面形式**，协商一致。
-- 所以"在系统里改一下"不等于变更完成 —— 必须有那份书面的东西。
--
-- ★ 四条设计取舍：
--
--   ① **异动是一条单据（employee_change），不是一个 UPDATE。**
--      单据里存新旧值与原因；改了什么、谁批的、什么时候生效，都可查。
--      直接改档案的写法，事后只能回答"现在是什么"，答不出"什么时候变成的"。
--
--   ② **按生效日切段，绝不改历史。**
--      归属是带有效期的段（014 的排他约束保证不重叠），转店就是"旧段截到
--      生效日前一天 + 新段从生效日开"。这样上个月的工资重算，用的仍是上个月的
--      门店与岗位 —— 而直接 UPDATE 会让历史算薪跟着变，且改不回来。
--
--   ③ **变更必须落一份书面协议：生成新合同（prev_id 串链），不改原合同。**
--      原合同是"当时双方签了什么"的证据，改它等于销毁证据。
--      新合同状态是 draft —— 面签后才生效，系统不替人签。
--
--   ④ **降职/降薪要理由，且降薪不在本文件里做。**
--      降薪走 106 的 salary_adjustment（已有校验与按月版本）；这里只管
--      岗位、工作地点、归属、用工类型。两类混在一张单子里，
--      将来查"这次调岗到底动没动钱"要多 join 三张表。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 异动单
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.employee_change (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          varchar(32)  NOT NULL UNIQUE,
  employee_id   bigint       NOT NULL,          -- person.id
  kind          varchar(24)  NOT NULL,
  effective_date date        NOT NULL,
  reason        varchar(200) NOT NULL,

  -- 新旧值：只存"这次动了的字段"，没动的留 NULL
  old_job_title   varchar(64),
  new_job_title   varchar(64),
  old_workplace   varchar(96),
  new_workplace   varchar(96),
  old_org_id      bigint,
  new_org_id      bigint,
  old_hours_system varchar(16),
  new_hours_system varchar(16),

  -- 关联的调薪单（可选）：一次异动常常既调岗又调薪，但钱走 106
  salary_adjust_id bigint REFERENCES public.salary_adjustment(id),

  status        varchar(16)  NOT NULL DEFAULT 'draft',
  contract_id   bigint REFERENCES public.employment_contract(id),  -- 生成的变更协议
  created_by    varchar(64)  NOT NULL,
  approved_by   varchar(64),
  applied_at    timestamptz,
  created_at    timestamptz  NOT NULL DEFAULT now(),

  CONSTRAINT ck_ecg_kind CHECK (kind IN
    ('position','transfer_store','employment_type','hours_system')),
  CONSTRAINT ck_ecg_status CHECK (status IN ('draft','approved','applied','cancelled')),
  CONSTRAINT ck_ecg_reason CHECK (length(btrim(reason)) >= 4),
  -- 一次异动至少要动一样东西，否则它是一条没有内容的单据
  CONSTRAINT ck_ecg_has_change CHECK (
       old_job_title IS DISTINCT FROM new_job_title
    OR old_workplace IS DISTINCT FROM new_workplace
    OR old_org_id    IS DISTINCT FROM new_org_id
    OR old_hours_system IS DISTINCT FROM new_hours_system),
  -- applied 必须有生效时刻；没 applied 不许有
  CONSTRAINT ck_ecg_applied CHECK ((status = 'applied') = (applied_at IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS ix_ecg_emp ON public.employee_change (employee_id, effective_date DESC);
CREATE INDEX IF NOT EXISTS ix_ecg_pending ON public.employee_change (effective_date)
  WHERE status IN ('draft','approved');

COMMENT ON TABLE public.employee_change IS
  '员工异动单（163）：调岗 / 转店 / 用工类型 / 工时制度。'
  '★ 薪资变动不在本表（走 106 的 salary_adjustment），但可以关联一张 —— '
  '查"这次调岗动没动钱"不用 join 三张表猜。';
COMMENT ON COLUMN public.employee_change.old_org_id IS
  '原成本组织。转店时新旧都填，apply 会按生效日把旧归属段截断、插入新段 ——'
  '不 UPDATE 现值，否则上个月补算工资会按新门店算。';

-- ---------------------------------------------------------------------------
-- 2. 校验：block / warn（与合同、排班同一套形态）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_change_check(
  p_employee bigint,
  p_kind     varchar,
  p_date     date,
  p_new_org  bigint DEFAULT NULL
) RETURNS TABLE (level varchar, code varchar, message varchar)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE
  v_c   record;
BEGIN
  IF p_date IS NULL THEN
    RETURN QUERY SELECT 'block'::varchar, 'E_CHG_NO_DATE'::varchar,
      '生效日必填（不填就只能"立即生效"，而立即生效会让当月的工资说不清按哪一版算）'::varchar;
    RETURN;
  END IF;

  -- 异动必须落在一份已签合同的有效期内：合同之外没有"变更"可言
  SELECT * INTO v_c
    FROM public.employment_contract c
   WHERE c.employee_id = p_employee AND c.status = 'signed'
     AND daterange(c.start_date, c.end_date, '[]') @> p_date
   ORDER BY c.start_date DESC LIMIT 1;
  IF v_c.id IS NULL THEN
    RETURN QUERY SELECT 'block'::varchar, 'E_CHG_NO_CONTRACT'::varchar,
      format('生效日 %s 这个人没有已签的合同在履行 —— 没有合同就没有"变更"，'
             || '先补签合同（或走入职链）', p_date)::varchar;
    RETURN;
  END IF;

  IF p_date <= v_c.start_date THEN
    RETURN QUERY SELECT 'block'::varchar, 'E_CHG_BEFORE_START'::varchar,
      format('生效日 %s 不晚于本份合同起始日 %s —— 这不是变更，是签合同',
             p_date, v_c.start_date)::varchar;
    RETURN;
  END IF;

  -- 转店：目标门店要存在，且不能就是现在这家
  IF p_kind = 'transfer_store' THEN
    IF p_new_org IS NULL THEN
      RETURN QUERY SELECT 'block'::varchar, 'E_CHG_NO_ORG'::varchar,
        '转店必须给目标门店'::varchar;
      RETURN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.org_unit o WHERE o.id = p_new_org) THEN
      RETURN QUERY SELECT 'block'::varchar, 'E_CHG_NO_ORG'::varchar,
        format('目标组织 %s 不存在', p_new_org)::varchar;
      RETURN;
    END IF;
    IF EXISTS (SELECT 1 FROM public.employee_org_assignment a
                WHERE a.employee_id = p_employee AND a.dim_code = 'cost_org'
                  AND a.org_id = p_new_org
                  AND daterange(a.valid_from, a.valid_to, '[]') @> p_date) THEN
      RETURN QUERY SELECT 'warn'::varchar, 'W_CHG_SAME_ORG'::varchar,
        '这个人本来就挂在目标门店上，这次转店可能没有实际变化'::varchar;
    END IF;
  END IF;

  -- 同一人已有未生效的异动：两次异动叠在一起，谁生效说不清
  IF EXISTS (SELECT 1 FROM public.employee_change g
              WHERE g.employee_id = p_employee
                AND g.status IN ('draft','approved')
                AND g.effective_date <> p_date) THEN
    RETURN QUERY SELECT 'warn'::varchar, 'W_CHG_PENDING'::varchar,
      '这个人已经有一张未生效的异动单（生效日不同）—— 两张单子会互相覆盖，'
      '建议先处理掉前一张'::varchar;
  END IF;
  RETURN;
END;
$$;

COMMENT ON FUNCTION fn_change_check IS
  '异动校验（163）：生效日必填、必须落在一份已签合同期内、不能早于合同起始日、'
  '转店要有目标门店；已有未生效异动时给预警（两张单子互相覆盖，事后说不清谁生效）。';

-- ---------------------------------------------------------------------------
-- 3. 立项与生效
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_change_open(
  p_employee bigint,
  p_kind     varchar,
  p_date     date,
  p_reason   varchar,
  p_new      jsonb,
  p_by       varchar DEFAULT 'system'
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_c     record;
  v_seqs  record;
  v_code  varchar(32);
  v_id    bigint;
BEGIN
  SELECT * INTO v_c
    FROM public.employment_contract c
   WHERE c.employee_id = p_employee AND c.status = 'signed'
     AND daterange(c.start_date, c.end_date, '[]') @> p_date
   ORDER BY c.start_date DESC LIMIT 1;

  v_code := 'YD' || to_char(p_date, 'YYYYMM') || '-'
    || lpad(((SELECT count(*) FROM public.employee_change g
               WHERE g.effective_date >= date_trunc('month', p_date)) + 1)::text, 4, '0');

  -- 当前归属（转店时填 old/new）
  SELECT a.org_id INTO v_seqs FROM public.employee_org_assignment a
   WHERE a.employee_id = p_employee AND a.dim_code = 'cost_org'
     AND daterange(a.valid_from, a.valid_to, '[]') @> p_date
   ORDER BY a.valid_from DESC LIMIT 1;

  INSERT INTO public.employee_change
    (code, employee_id, kind, effective_date, reason,
     old_job_title, new_job_title, old_workplace, new_workplace,
     old_org_id, new_org_id, old_hours_system, new_hours_system,
     salary_adjust_id, status, created_by)
  VALUES (v_code, p_employee, p_kind, p_date, p_reason,
     CASE WHEN p_new ? 'job_title' THEN v_c.job_title END,
     NULLIF(btrim(COALESCE(p_new->>'job_title','')), ''),
     CASE WHEN p_new ? 'workplace' THEN v_c.workplace END,
     NULLIF(btrim(COALESCE(p_new->>'workplace','')), ''),
     CASE WHEN p_new ? 'org_id' THEN v_seqs.org_id END,
     NULLIF(p_new->>'org_id','')::bigint,
     CASE WHEN p_new ? 'hours_system' THEN v_c.hours_system END,
     NULLIF(btrim(COALESCE(p_new->>'hours_system','')), ''),
     NULLIF(p_new->>'salary_adjust_id','')::bigint,
     'draft', p_by)
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_change_open IS
  '开一张异动单（163）：只存"这次动了的字段"（没传的留 NULL），'
  '旧值从当前在履行的合同与归属里取 —— 让人手填旧值，就会填错，而旧值是"变更前是什么"的唯一记录。';

CREATE OR REPLACE FUNCTION public.fn_change_apply(
  p_change bigint,
  p_by     varchar DEFAULT 'system'
) RETURNS TABLE (change_id bigint, contract_id bigint, contract_no varchar, seg_from date)
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  g       record;
  c       record;
  v_tpl   bigint;
  v_no    varchar(48);
  v_seq   int;
  v_cid   bigint;
  v_org   bigint;
BEGIN
  SELECT * INTO g FROM public.employee_change WHERE id = p_change FOR UPDATE;
  IF g.id IS NULL THEN
    RAISE EXCEPTION 'E_CHG_NOT_FOUND: 异动单 % 不存在', p_change;
  END IF;
  IF g.status = 'applied' THEN
    RAISE EXCEPTION 'E_CHG_APPLIED: 异动单 % 已于 % 生效，不能重复生效', g.code, g.applied_at;
  END IF;

  SELECT * INTO c FROM public.employment_contract c2
   WHERE c2.employee_id = g.employee_id AND c2.status = 'signed'
     AND daterange(c2.start_date, c2.end_date, '[]') @> g.effective_date
   ORDER BY c2.start_date DESC LIMIT 1;
  IF c.id IS NULL THEN
    RAISE EXCEPTION 'E_CHG_NO_CONTRACT: 生效日 % 这个人没有已签合同在履行', g.effective_date;
  END IF;

  -- ---- 1. 归属：旧段截断到生效日前一天，新段从生效日开（不改现值，见文件头 ②）----
  IF g.new_org_id IS NOT NULL AND g.new_org_id IS DISTINCT FROM g.old_org_id THEN
    UPDATE public.employee_org_assignment a
       SET valid_to = g.effective_date - 1
     WHERE a.employee_id = g.employee_id AND a.dim_code = 'cost_org'
       AND a.valid_to IS NULL
       AND a.valid_from < g.effective_date;
    INSERT INTO public.employee_org_assignment
      (employee_id, dim_code, org_id, valid_from)
    VALUES (g.employee_id, 'cost_org', g.new_org_id, g.effective_date);
  END IF;

  -- ---- 2. 书面变更：生成新合同，prev_id 指向原合同（不改原合同）----
  SELECT t.id INTO v_tpl FROM public.contract_template t
   WHERE t.kind = c.kind AND t.is_active ORDER BY t.version DESC, t.id LIMIT 1;

  SELECT count(*)::int INTO v_seq FROM public.employment_contract c3
   WHERE c3.legal_entity_id = c.legal_entity_id
     AND c3.start_date >= date_trunc('year', g.effective_date);
  v_no := 'BG' || lpad(c.legal_entity_id::text,
                       GREATEST(2, length(c.legal_entity_id::text)), '0') || '-'
          || to_char(g.effective_date, 'YYYY') || '-'
          || lpad((v_seq + 1)::text, 4, '0');

  INSERT INTO public.employment_contract
    (employee_id, legal_entity_id, contract_no, kind, start_date, end_date,
     probation_from, probation_to, job_title, workplace, employee_address,
     hours_system, wage_amount, wage_unit, pay_day, template_id, status, prev_id)
  VALUES (g.employee_id, c.legal_entity_id, v_no, c.kind, g.effective_date, c.end_date,
     -- ★ 变更协议**不带试用期**：同一单位只能约定一次（也谈不上"再试用一次"）
     NULL, NULL,
     COALESCE(g.new_job_title, c.job_title),
     COALESCE(g.new_workplace, c.workplace),
     c.employee_address,
     COALESCE(g.new_hours_system, c.hours_system),
     c.wage_amount, c.wage_unit, c.pay_day, v_tpl, 'draft', c.id)
  RETURNING id INTO v_cid;

  -- ★ 这里**不**截断原合同。截断要等变更协议**签署之后**（见下面的触发器）：
  --   提前截断的后果是"生效日之后这个人没有生效合同" —— 协议还躺在草稿里没签，
  --   而原合同已经被切掉了。那一刻花名册上他会显示"未签合同"，
  --   财务报表与社保申报也会跟着认错。变更的完成以签署为准，不以建单为准。
  UPDATE public.employee_change
     SET status = 'applied', applied_at = now(), contract_id = v_cid,
         approved_by = COALESCE(approved_by, p_by)
   WHERE id = p_change;

  RETURN QUERY SELECT p_change, v_cid, v_no::varchar, g.effective_date;
END;
$$;

COMMENT ON FUNCTION fn_change_apply IS
  '异动生效（163）：按生效日切归属段（旧段截到前一天、新段从生效日开，不改历史）、'
  '生成一份**合同变更协议**（prev_id 串链，状态 draft，面签后才算完），'
  '并把原合同的终止日改到生效日前一天 —— 两份合同不能同时"在履行"。'
  '★ 不改原合同的岗位/工资：原合同是"当时签了什么"的证据，改了就是销毁证据。';

