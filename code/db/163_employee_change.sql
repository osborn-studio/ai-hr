-- ---------------------------------------------------------------------------
-- 6. 变更协议签署后，才把上一份合同截断（背靠背，时间点才对）
-- ---------------------------------------------------------------------------
-- ★ 为什么放在触发器而不是 fn_change_apply：
--   "上一份合同什么时候结束"这件事只取决于"这一份什么时候签"。
--   放在 apply 里，等于假设"建单即生效"；而现实里协议可能在抽屉里躺两周。
--   放在签署那一刻，任何路径（变更协议、手工续签、将来的批量导入）都一致。
CREATE OR REPLACE FUNCTION fn_ec_close_prev() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF NEW.prev_id IS NOT NULL AND NEW.status = 'signed'
     AND (OLD.status IS DISTINCT FROM 'signed') THEN
    UPDATE public.employment_contract
       SET end_date = NEW.start_date - 1
     WHERE id = NEW.prev_id
       AND (end_date IS NULL OR end_date > NEW.start_date - 1);
  END IF;
  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION fn_ec_close_prev IS
  '变更/续签协议签署后，把上一份合同的终止日改到本份起始日前一天 —— '
  '两份合同不能同时在履行（花名册取"起始最晚那份"时会在同一天两份之间抖动）。'
  '★ 只在签署那一刻做：建单就截断会让"协议还没签"期间这个人没有生效合同。';

DROP TRIGGER IF EXISTS trg_ec_close_prev ON public.employment_contract;
CREATE TRIGGER trg_ec_close_prev
  AFTER UPDATE ON public.employment_contract
  FOR EACH ROW EXECUTE FUNCTION fn_ec_close_prev();

