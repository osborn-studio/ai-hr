-- ============================================================================
-- 011_leave.sql · 假期类型 / 额度台账 / 四态余额（T03）
-- ----------------------------------------------------------------------------
-- 一条结构决定：**余额不存列，由台账派生。**
--
-- 存一个 balance numeric 的话，冻结、已用、过期三处各自更新它，
-- 而它们由三条不同路径触发（申请、审批、到期任务）。三处一漂，
-- 表现是"某个人年假少了半天"，而三张表看起来都正常。
--
-- 四态：
--   granted   授予（台账）
--   frozen    申请中冻结
--   used      已批准消耗
--   expired   到期作废（按类型策略：void 作废 / payout 折薪）
--   available = granted(未过期) - frozen - used
-- ============================================================================

CREATE TABLE leave_type (
  id            bigint PRIMARY KEY,
  code          varchar(24) NOT NULL UNIQUE,
  name          varchar(64) NOT NULL,
  -- ★ 到期未休怎么处理：作废还是折薪。这是业务选，不是技术选。
  expire_policy varchar(16) NOT NULL DEFAULT 'void',
  CONSTRAINT ck_lt_policy CHECK (expire_policy IN ('void','payout'))
);

CREATE TABLE leave_grant (
  -- ★ 主键必须有生成方式。只有 PRIMARY KEY 而没有 IDENTITY 时，
  --   函数里插入忘了给 id 会报 not-null —— 而报错信息指向 id，不像忘了设计主键。
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id   bigint NOT NULL,
  leave_type_id bigint NOT NULL REFERENCES leave_type(id),
  qty           numeric(8,2) NOT NULL,
  valid_from    date NOT NULL,
  valid_to      date,                      -- NULL = 长期有效
  CONSTRAINT ck_lg_qty CHECK (qty > 0),
  CONSTRAINT ck_lg_span CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

CREATE TABLE leave_usage (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id   bigint NOT NULL,
  leave_type_id bigint NOT NULL REFERENCES leave_type(id),
  qty           numeric(8,2) NOT NULL,
  state         varchar(16) NOT NULL DEFAULT 'frozen',
  request_id    bigint,
  CONSTRAINT ck_lu_qty CHECK (qty > 0),
  CONSTRAINT ck_lu_state CHECK (state IN ('frozen','used','released')),
  CONSTRAINT ck_lu_effect CHECK (qty <> 0)
);

-- ---------------------------------------------------------------------------
-- 四态余额视图
-- ---------------------------------------------------------------------------
CREATE VIEW v_leave_balance AS
WITH g AS (
  SELECT employee_id, leave_type_id,
         SUM(qty) FILTER (WHERE valid_to IS NULL OR valid_to >= current_date) AS granted,
         SUM(qty) FILTER (WHERE valid_to IS NOT NULL AND valid_to <  current_date) AS expired
    FROM leave_grant GROUP BY employee_id, leave_type_id
), u AS (
  SELECT employee_id, leave_type_id,
         SUM(qty) FILTER (WHERE state = 'frozen') AS frozen,
         SUM(qty) FILTER (WHERE state = 'used')   AS used
    FROM leave_usage GROUP BY employee_id, leave_type_id
)
SELECT COALESCE(g.employee_id, u.employee_id)       AS employee_id,
       COALESCE(g.leave_type_id, u.leave_type_id)   AS leave_type_id,
       COALESCE(g.granted, 0)                        AS granted,
       COALESCE(g.expired, 0)                        AS expired,
       COALESCE(u.frozen, 0)                         AS frozen,
       COALESCE(u.used, 0)                           AS used,
       COALESCE(g.granted, 0) - COALESCE(u.frozen, 0) - COALESCE(u.used, 0) AS available
  FROM g FULL JOIN u
    ON u.employee_id = g.employee_id AND u.leave_type_id = g.leave_type_id;

COMMENT ON VIEW v_leave_balance IS
  'available 由台账派生，不落列。存列的话三处（申请/审批/到期）各自更新它，必然漂。';

-- ---------------------------------------------------------------------------
-- 冻结：不得超过可用额度
-- ---------------------------------------------------------------------------
-- ★ 必须写成"读视图 + 判 + 写"的同一个函数，不能分两步：
--   分两步时，两个并发申请都读到 available=7，各冻 5，结果 -3。
--   这里用 SELECT ... FOR UPDATE 锁该员工的授予行，把窗口挤掉。
CREATE OR REPLACE FUNCTION fn_leave_freeze(
  p_employee bigint, p_type bigint, p_qty numeric, p_request bigint
) RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_avail numeric;
BEGIN
  PERFORM 1 FROM public.leave_grant
   WHERE employee_id = p_employee AND leave_type_id = p_type FOR UPDATE;

  SELECT COALESCE(available, 0) INTO v_avail
    FROM public.v_leave_balance
   WHERE employee_id = p_employee AND leave_type_id = p_type;

  IF p_qty > COALESCE(v_avail, 0) THEN
    RAISE EXCEPTION 'E_LEAVE_OVER_QUOTA: 可用 % 小时，申请 % 小时',
      COALESCE(v_avail, 0), p_qty;
  END IF;

  INSERT INTO public.leave_usage(employee_id, leave_type_id, qty, state, request_id)
  VALUES (p_employee, p_type, p_qty, 'frozen', p_request);
END;
$$;

-- 审批通过：冻结转已用（额度不变，只是状态前进）
CREATE OR REPLACE FUNCTION fn_leave_approve(p_request bigint) RETURNS void
LANGUAGE sql SET search_path = '' AS $$
  UPDATE public.leave_usage SET state = 'used'
   WHERE request_id = p_request AND state = 'frozen';
$$;

-- 驳回：释放冻结
CREATE OR REPLACE FUNCTION fn_leave_reject(p_request bigint) RETURNS void
LANGUAGE sql SET search_path = '' AS $$
  UPDATE public.leave_usage SET state = 'released'
   WHERE request_id = p_request AND state = 'frozen';
$$;
