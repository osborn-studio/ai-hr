-- ============================================================================
-- 167_recruit_interview.sql · 招聘的后半段：面试记录 / 背景调查 / 录用审批链
-- ----------------------------------------------------------------------------
-- 025 把"编制 → 需求 → offer → 人"这条线打通了，162 又把入职接到合同上。
-- 但真正决定"要不要发这个 offer"的那几步，系统里**一个字都没有**：
--
--   ① **面试没有记录**。几轮、谁面的、几分、通过还是淘汰、为什么 —— 全在邮件
--      与面试官的脑子里。后果有两个，都很具体：
--      · 录用三个月后这人不行，回头要答"当时为什么说他行" —— 答不出。
--        没有评语的面试记录，与没有记录的区别只是"以为有记录"。
--      · 同一个候选人被两个需求各面一轮，两拨面试官互相不知道 ——
--        重复约面、重复占用面试官时间，候选人被问两遍同样的问题。
--
--   ② **背调没有落点**。查了什么、结论是什么、谁查的、**候选人有没有书面授权** ——
--      一样都没有。《个人信息保护法》第十三条、第二十九条：处理个人信息要有
--      单独同意；背景调查查的是学历、前雇主、征信、无犯罪记录，全是敏感信息。
--      没有授权先查了，性质不是"流程漏了一步"，是违法处理个人信息 ——
--      而系统里连"查过"这件事都没有痕迹，也就没有证据能证明"没查"。
--
--   ③ **录用审批链没有**。offer 一建出来就是 pending，025 只校验了编制，
--      没有人签字。编制校验回答的是"这个编还能不能招"，回答不了
--      "这个人的这个价，谁批的"。发出去的 offer 是法律承诺，不能由
--      "谁都能按的那个按钮"决定。
--
-- ★ 四条设计取舍（每条都是被现有结构逼出来的）：
--
--   ① **面试不挂 offer，挂 requisition + candidate_key。**
--      这一条是查过现有表才下的结论：offer **承载不了"还没发 offer 的候选人"**，
--      三条硬证据（不是猜）：
--        a. `fn_offer_issue` 建 offer 时**同时**写一条 `offer_version`（岗位/月薪/
--           有效期），而一封还没决定要不要发的 offer 没有薪资可写 ——
--           写了就是一份"已经承诺过"的条款，`offer_version` 还是 append-only
--           （025 的 trg_ov_append_only），错了删不掉，只能再加一版把错的那版留在库里。
--        b. `uk_offer_live_candidate` 是**部分唯一索引**，只允许一个候选人持有
--           **一个** pending/accepted 的 offer。而"同一候选人被两个岗位重复面"
--           恰恰是要记两轮面试的场景 —— 用 offer 承载就造不出第二条载体，
--           唯一索引会直接拒绝。这不是配置问题，是模型问题。
--        c. `fn_offer_issue` 要过 `fn_hc_can_offer`：编制不够就发不出 offer。
--           面试发生在**编制被占用之前**（招 1 个人可能面 8 个），
--           让面试去消耗编制，等于面试还没开始就把编用完了。
--      所以载体是 `requisition_id + candidate_key`：需求是"招人这件事"的容器，
--      候选人在需求下被面，与"最后有没有发 offer"解耦。
--      `candidate_name` 也存一份：candidate_key 是不可逆 hash，读记录的是人；
--      而且"面试人不能是候选人本人"这条校验需要一个名字做操作数。
--
--   ② **背调先授权，授权与记录同一行。**
--      `consent_at` 为空的行表示"还没有授权"，这种行**不允许有结论**
--      （ck_bg_consent：checked_at 非空则 consent_at 必填）。
--      约束在表上，不在函数里 —— 函数会被绕过（运维 SQL、将来的批量导入），
--      约束不会。`fn_bg_check_add` 只是给这条红线一个**名字**（E_BG_NO_CONSENT），
--      让调用方知道"被拒是因为缺签字"，而不是看到一个 23514。
--
--   ③ **"三步齐备"是派生量，不是 offer 的第 4 种状态。**
--      `offer.status` 的枚举是 025 定的 pending/accepted/rejected/withdrawn/onboarded，
--      没有 approved，而 025 不可改。硬塞一个状态进去只有两条路：改 025 的 CHECK
--      （动了别人的结论），或者加一列 `approved_at`（多一个必然与审批表不同步的
--      时间戳 —— 加签、撤回、重批都会让它变旧）。
--      所以"可发"由 `fn_offer_issuable` 从 `offer_approval` **算**出来：
--      三步都 approved 且无 rejected 即为可发。这与 025 里"过期靠时点派生、
--      不靠定时任务改状态"是同一条取舍：**能被算出来的状态，不要存第二份。**
--
--   ④ **淘汰要写清为什么，风险也要。**
--      `conclusion='reject'` 没有 ≥10 字评语 → 拒（ck_ir_reject_note）；
--      背调结论 `risk` 没有 ≥10 字说明 → 拒（ck_bg_detail）。
--      这两条都是为了同一个问题：半年后有人问"当时为什么",系统要答得出。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 面试轮次
-- ---------------------------------------------------------------------------
CREATE TABLE public.interview_round (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requisition_id bigint       NOT NULL REFERENCES public.requisition(id),
  candidate_key  varchar(64)  NOT NULL,
  candidate_name varchar(64)  NOT NULL,
  round_no       int          NOT NULL,
  interviewer    varchar(64)  NOT NULL,
  scheduled_at   timestamptz  NOT NULL,
  method         varchar(16)  NOT NULL,
  score          int,
  conclusion     varchar(16),
  comment        varchar(1000),
  created_at     timestamptz  NOT NULL DEFAULT now(),

  -- ★ 唯一性按"需求 + 候选人 + 轮次"，不按"候选人 + 轮次"：
  --   同一候选人被两个岗位各面一轮是**两个不同的事实**（见文件头 ①b），
  --   按候选人唯一就记不下第二条，而那条正是"重复面"的证据。
  CONSTRAINT uk_ir_round  UNIQUE (requisition_id, candidate_key, round_no),
  CONSTRAINT ck_ir_round  CHECK (round_no BETWEEN 1 AND 9),
  CONSTRAINT ck_ir_method CHECK (method IN ('onsite','video','phone')),
  CONSTRAINT ck_ir_score  CHECK (score IS NULL OR score BETWEEN 0 AND 100),
  CONSTRAINT ck_ir_concl  CHECK (conclusion IS NULL OR conclusion IN ('pass','hold','reject')),
  CONSTRAINT ck_ir_name   CHECK (length(btrim(candidate_name)) >= 2),
  CONSTRAINT ck_ir_who    CHECK (length(btrim(interviewer)) >= 2),
  -- ★ 淘汰必须写清为什么（≥10 字）。这不是"字段校验"，
  --   而是这套记录唯一的存在理由：录用后回头查"当时为什么说他不行"。
  --   没有这一条，reject 行的评语可以是"不合适"三个字，等于没有记录。
  CONSTRAINT ck_ir_reject_note CHECK (
    conclusion IS DISTINCT FROM 'reject'
    OR length(btrim(COALESCE(comment, ''))) >= 10)
);

CREATE INDEX ix_ir_cand ON public.interview_round (candidate_key, scheduled_at DESC);
CREATE INDEX ix_ir_rq   ON public.interview_round (requisition_id, round_no);

COMMENT ON TABLE public.interview_round IS
  '面试轮次（167）：候选人 × 需求 × 第几轮。'
  '★ 不挂 offer：还没发 offer 的候选人在 offer 表里没有行，而强制建行就等于'
  '先写一份 append-only 的薪资承诺（见文件头 ①）。';
COMMENT ON COLUMN public.interview_round.comment IS
  '评语。conclusion=reject 时必填且 ≥10 字 —— 面试记录的价值全在"为什么"，'
  '而"不合适"三个字与空白在事后查询时没有区别。';

-- ---------------------------------------------------------------------------
-- 2. 背景调查
-- ---------------------------------------------------------------------------
CREATE TABLE public.background_check (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidate_key varchar(64) NOT NULL,
  kind          varchar(16) NOT NULL,
  consent_at    timestamptz,              -- NULL = 未授权，不许查
  checked_at    timestamptz,
  result        varchar(16),
  detail        varchar(500),
  checked_by    varchar(64),
  created_at    timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT ck_bg_key    CHECK (length(btrim(candidate_key)) >= 1),
  CONSTRAINT ck_bg_kind   CHECK (kind IN ('education','employment','credit','criminal')),
  CONSTRAINT ck_bg_result CHECK (result IS NULL OR result IN ('clear','risk','unknown')),
  -- ★★ 合规红线（唯一一条用"拒"而不是"警告"处理的合规规则）：
  --    有结论就必须有授权时间。CHECK 在 INSERT 与 UPDATE 上都求值，
  --    所以"先插一条无授权行、事后再 UPDATE 补结果"这条路也走不通。
  CONSTRAINT ck_bg_consent CHECK (checked_at IS NULL OR consent_at IS NOT NULL),
  -- 授权必须早于或等于调查：倒填的授权时间不是授权，是事后补签
  CONSTRAINT ck_bg_order   CHECK (checked_at IS NULL OR checked_at >= consent_at),
  -- 结论与调查时间同生同灭：有结论没时间 = 不知道什么时候查的，
  -- 有时间没结论 = 查了但结论丢了（两者都让这条记录无法被引用）
  CONSTRAINT ck_bg_done    CHECK ((checked_at IS NULL) = (result IS NULL)),
  CONSTRAINT ck_bg_who     CHECK (checked_at IS NULL
                                  OR length(btrim(COALESCE(checked_by, ''))) >= 1),
  -- risk 必须写清是什么风险（与 ck_ir_reject_note 同一条理由）
  CONSTRAINT ck_bg_detail  CHECK (result IS DISTINCT FROM 'risk'
                                  OR length(btrim(COALESCE(detail, ''))) >= 10)
);

CREATE INDEX ix_bg_cand ON public.background_check (candidate_key, kind, created_at DESC);

COMMENT ON TABLE public.background_check IS
  '背景调查（167）：一条行 = 一次授权的调查（可只有授权、结论待补）。'
  '★ consent_at 为空 = 未授权，此时 checked_at 必须为空（ck_bg_consent）——'
  '《个人信息保护法》要求单独同意，先查后补授权是违法处理，不是流程瑕疵。';
COMMENT ON COLUMN public.background_check.consent_at IS
  '候选人书面授权的时间。NULL 表示没有授权；这一列为空时不许有调查结论 —— '
  '这条约束是表级的，不是函数级的：运维 SQL 与将来的批量导入一样要被拦住。';
-- ★ 这一条注释是给"用 grep 判生死"的人看的：`employment` 在本文件里只以
--   kind 取值的身份出现，与 employment 任职表没有关系 —— 顺手 grep 一遍
--   很容易读成"招聘动了任职表"，而一行注释比一次解释便宜。
COMMENT ON COLUMN public.background_check.kind IS
  '背调种类：education=学历 employment=前雇主 credit=征信 criminal=无犯罪记录。'
  '★ kind=''employment'' 是"查前雇主"，与 employment 任职表**无关**；'
  '本文件对 employment / employment_contract 零读写。';

-- ---------------------------------------------------------------------------
-- 3. 录用审批链（hc / budget / hr_head 三步）
-- ---------------------------------------------------------------------------
CREATE TABLE public.offer_approval (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  offer_id   bigint      NOT NULL REFERENCES public.offer(id),
  step       varchar(16) NOT NULL,
  approver   varchar(64),
  decision   varchar(16) NOT NULL DEFAULT 'pending',
  decided_at timestamptz,
  note       varchar(500),
  created_at timestamptz NOT NULL DEFAULT now(),

  -- 一个 offer 的每一步只有一条记录：审批是签字，不是可以反复覆盖的字段。
  -- 想改主意要留痕（谁在什么时候把 approved 改成 rejected），
  -- 而不是悄悄改掉那一行 —— 那一行是"当时签了什么"的唯一证据。
  CONSTRAINT uk_oa       UNIQUE (offer_id, step),
  CONSTRAINT ck_oa_step  CHECK (step IN ('hc','budget','hr_head')),
  CONSTRAINT ck_oa_dec   CHECK (decision IN ('pending','approved','rejected')),
  -- 有决定就有时间；pending 不许有决定时间
  CONSTRAINT ck_oa_when  CHECK ((decision = 'pending') = (decided_at IS NULL)),
  -- 签了字就要有人签
  CONSTRAINT ck_oa_who   CHECK (decision = 'pending'
                                OR length(btrim(COALESCE(approver, ''))) >= 1),
  -- 驳回必须写理由（≥4 字）：否则申请人只看到"被驳回"，不知道要改什么
  CONSTRAINT ck_oa_note  CHECK (decision <> 'rejected'
                                OR length(btrim(COALESCE(note, ''))) >= 4)
);

CREATE INDEX ix_oa_offer ON public.offer_approval (offer_id, step);

COMMENT ON TABLE public.offer_approval IS
  '录用审批链（167）：hc（编制）/ budget（预算）/ hr_head（HR 负责人）三步。'
  '★ 三步齐备不落成 offer 的第 4 种状态 —— 由 fn_offer_issuable 从本表派生'
  '（025 的 ck_of_status 没有 approved，且能被算出来的状态不该再存一份）。';

-- ---------------------------------------------------------------------------
-- 4. 记一轮面试
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_interview_add(
  p_rq             bigint,
  p_candidate_key  varchar,
  p_candidate_name varchar,
  p_round_no       int,
  p_interviewer    varchar,
  p_scheduled_at   timestamptz,
  p_method         varchar,
  p_score          int     DEFAULT NULL,
  p_conclusion     varchar DEFAULT NULL,
  p_comment        varchar DEFAULT NULL
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_status varchar(16);
  v_max    int;
  v_id     bigint;
BEGIN
  SELECT q.status INTO v_status FROM public.requisition q WHERE q.id = p_rq;
  IF v_status IS NULL THEN
    RAISE EXCEPTION 'E_RQ_NOT_FOUND: 需求 % 不存在 —— 面试要挂在一条真实的需求上', p_rq;
  END IF;
  -- 面试是为"这条需求招人"服务的。需求关了还加轮次，等于对着一个不存在的
  -- 名额继续面人 —— 后面要么发出超编 offer，要么白面。
  IF v_status <> 'open' THEN
    RAISE EXCEPTION 'E_RQ_CLOSED: 需求 % 已是 %，不能再加面试轮次', p_rq, v_status;
  END IF;

  -- ★ 轮次逐个递增：跳号会让"第 2 轮去哪了"永远说不清
  --   （是没记，还是记在别人名下，还是本来就没面）。
  SELECT COALESCE(max(r.round_no), 0) INTO v_max
    FROM public.interview_round r
   WHERE r.requisition_id = p_rq AND r.candidate_key = p_candidate_key;

  IF p_round_no IS NULL OR p_round_no <> v_max + 1 THEN
    RAISE EXCEPTION 'E_RCI_ROUND_GAP: 该候选人在需求 % 上已记到第 % 轮，本次只能是第 % 轮（收到 %）',
      p_rq, v_max, v_max + 1, COALESCE(p_round_no::text, '空');
  END IF;

  -- ★ 面试人不能是候选人本人。按名字判：库里没有"候选人 ↔ 员工"的映射
  --   （候选人还没入职，person 表里没有他），唯一可用的共同操作数是姓名。
  --   这拦的是录入错误（把自己的号填成面试人），不是有意的舞弊 ——
  --   有意的舞弊在库里长不成校验。
  IF lower(btrim(COALESCE(p_interviewer, '')))
     = lower(btrim(COALESCE(p_candidate_name, ''))) THEN
    RAISE EXCEPTION 'E_RCI_SELF: 面试人与候选人同名（%），不能自己面自己', p_interviewer;
  END IF;

  INSERT INTO public.interview_round
    (requisition_id, candidate_key, candidate_name, round_no,
     interviewer, scheduled_at, method, score, conclusion, comment)
  VALUES
    (p_rq, p_candidate_key, p_candidate_name, p_round_no,
     p_interviewer, p_scheduled_at, p_method, p_score, p_conclusion, p_comment)
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_interview_add IS
  '记一轮面试（167）：需求必须 open、轮次必须逐个递增、面试人不能是候选人本人；'
  '淘汰必须有 ≥10 字评语（ck_ir_reject_note）。'
  '★ 轮次按"需求 + 候选人"各自计数：同一候选人被两个岗位各面一轮，是两条独立的链。';

-- ---------------------------------------------------------------------------
-- 5. 记一次背调（授权 + 结论）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_bg_check_add(
  p_candidate_key varchar,
  p_kind          varchar,
  p_consent_at    timestamptz,
  p_checked_at    timestamptz DEFAULT NULL,
  p_result        varchar       DEFAULT NULL,
  p_detail        varchar       DEFAULT NULL,
  p_checked_by    varchar       DEFAULT NULL
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_id bigint;
BEGIN
  -- ★ 没有授权时间就不许落这一行。这不是"参数必填"，是合规红线：
  --   允许落一行 consent_at 为 NULL 的"调查中"，下一个人就会顺手把结论填上去
  --   （表上的 ck_bg_consent 会拦，但那时已经写了一半、错在更远的地方被发现）。
  IF p_consent_at IS NULL THEN
    RAISE EXCEPTION 'E_BG_NO_CONSENT: 候选人 % 的 % 背调没有书面授权时间 —— '
      '先取得单独同意并登记授权时间，才能开始查', p_candidate_key, p_kind;
  END IF;

  INSERT INTO public.background_check
    (candidate_key, kind, consent_at, checked_at, result, detail, checked_by)
  VALUES
    (p_candidate_key, p_kind, p_consent_at, p_checked_at, p_result, p_detail, p_checked_by)
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_bg_check_add IS
  '记一次背调（167）：授权时间必填（E_BG_NO_CONSENT）。'
  '先登记授权、结论后补 —— 同一行两次写是允许的（p_checked_at 传空即"已授权待查"）。'
  '★ 结论相关的四条规则（有结论必须有授权、授权不晚于调查、结论与时间同生同灭、'
  'risk 要写清是什么）都在表约束上，函数只是给"缺授权"这件事一个名字。';

-- ---------------------------------------------------------------------------
-- 6. 三步审批
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_offer_issuable(p_offer bigint)
RETURNS boolean
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT EXISTS (SELECT 1 FROM public.offer o WHERE o.id = p_offer)
     AND (SELECT count(DISTINCT a.step)::int FROM public.offer_approval a
           WHERE a.offer_id = p_offer AND a.decision = 'approved') = 3
     AND NOT EXISTS (SELECT 1 FROM public.offer_approval a
                      WHERE a.offer_id = p_offer AND a.decision = 'rejected');
$$;

COMMENT ON FUNCTION fn_offer_issuable IS
  'offer 是否"可发"（167）：hc / budget / hr_head 三步都 approved 且无驳回。'
  '★ 派生量，不落成 offer 的状态列：加一列 approved_at 就会与审批表不同步 ——'
  '撤签、改签、重批都会让它变旧，而变旧的那天它仍然"看起来对"。';

CREATE OR REPLACE FUNCTION public.fn_offer_approve(
  p_offer    bigint,
  p_step     varchar,
  p_approver varchar,
  p_decision varchar,
  p_note     varchar DEFAULT NULL
) RETURNS TABLE (
  step        varchar,
  decision    varchar,
  steps_ok    int,
  issuable    boolean,
  offer_status varchar
)
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_status varchar(16);
  v_ok     int;
  v_rej    int;
BEGIN
  SELECT o.status INTO v_status FROM public.offer o WHERE o.id = p_offer FOR UPDATE;
  IF v_status IS NULL THEN
    RAISE EXCEPTION 'E_OFFER_NOT_FOUND: offer % 不存在', p_offer;
  END IF;
  -- 只有 pending 的 offer 需要审批。已经 accepted/onboarded 的再"批一次"，
  -- 会让人以为这次批准是它发出去的前提 —— 而它早就发出去了。
  IF v_status <> 'pending' THEN
    RAISE EXCEPTION 'E_OA_NOT_LIVE: offer % 已是 %，不再进入审批', p_offer, v_status;
  END IF;

  IF p_step IS NULL OR p_step NOT IN ('hc','budget','hr_head') THEN
    RAISE EXCEPTION 'E_OA_STEP: 未知审批环节 %（只有 hc / budget / hr_head 三步）',
      COALESCE(p_step, '空');
  END IF;
  -- decision 只收 approved / rejected：写 pending 等于占掉这一步的名额
  -- 却什么都没决定，而 uk_oa 会让真正的签字再也插不进来。
  IF p_decision IS NULL OR p_decision NOT IN ('approved','rejected') THEN
    RAISE EXCEPTION 'E_OA_DECISION: % 不是有效决定（只能是 approved / rejected）',
      COALESCE(p_decision, '空');
  END IF;

  IF EXISTS (SELECT 1 FROM public.offer_approval a
              WHERE a.offer_id = p_offer AND a.step = p_step) THEN
    RAISE EXCEPTION 'E_OA_STEP_DONE: offer % 的 % 环节已有审批记录 —— '
      '签字不可覆盖（要改主意请留一条新记录说明改了什么，而不是改掉原签字）',
      p_offer, p_step;
  END IF;

  IF p_decision = 'rejected'
     AND length(btrim(COALESCE(p_note, ''))) < 4 THEN
    RAISE EXCEPTION 'E_OA_NO_NOTE: 驳回 % 环节必须写理由（≥4 字）—— '
      '否则申请人只看到"被驳回"，不知道要改什么', p_step;
  END IF;

  INSERT INTO public.offer_approval (offer_id, step, approver, decision, decided_at, note)
  VALUES (p_offer, p_step, p_approver, p_decision, now(), p_note);

  -- ★ 任一步驳回 → offer 走 rejected。这一步必须在这里做：
  --   offer 停在 pending 上，它仍然占着 uk_offer_live_candidate 的那个唯一名额
  --   （同一候选人只能有一个有效 offer），于是"这个人被否了，另一个岗想给他发
  --   offer"会撞唯一索引 —— 拒绝信息说的是约束名，看起来像数据坏了。
  IF p_decision = 'rejected' THEN
    UPDATE public.offer SET status = 'rejected' WHERE id = p_offer;
  END IF;

  SELECT count(DISTINCT a.step)::int INTO v_ok
    FROM public.offer_approval a
   WHERE a.offer_id = p_offer AND a.decision = 'approved';
  SELECT count(*)::int INTO v_rej
    FROM public.offer_approval a
   WHERE a.offer_id = p_offer AND a.decision = 'rejected';

  RETURN QUERY SELECT p_step::varchar, p_decision::varchar, v_ok,
    (v_ok = 3 AND v_rej = 0),
    (SELECT o.status FROM public.offer o WHERE o.id = p_offer)::varchar;
END;
$$;

COMMENT ON FUNCTION fn_offer_approve IS
  '录用审批（167）：记一步签字；三步都 approved 才 issuable=true，'
  '任一步 rejected 则 offer 置 rejected（同时释放"一个候选人只能有一个有效 offer"的名额）。'
  '★ 每步只能签一次（E_OA_STEP_DONE）：签字是证据，覆盖签字等于销毁证据。';

-- ---------------------------------------------------------------------------
-- 7. 这个人的老底：被面过几次、投过几个岗、有没有重复
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_candidate_history(p_candidate_key varchar)
RETURNS TABLE (
  candidate_key   varchar,
  rounds          int,
  requisitions    int,
  offers          int,
  passed_rounds   int,
  rejected_rounds int,
  first_round_at  timestamptz,
  last_round_at   timestamptz,
  is_duplicate    boolean,
  positions       text,
  note            text
)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  WITH ir AS (
    SELECT r.* FROM public.interview_round r WHERE r.candidate_key = p_candidate_key
  ), rq AS (
    -- "投过哪些岗位" = 面试记录里的需求 ∪ offer 里的需求
    -- （有 offer 但没面试记录的路径可能存在：内部推荐直接发 offer）
    SELECT DISTINCT q.id, q.position
      FROM public.requisition q
     WHERE q.id IN (SELECT ir.requisition_id FROM ir
                    UNION
                    SELECT o.requisition_id FROM public.offer o
                     WHERE o.candidate_key = p_candidate_key)
  )
  SELECT
    p_candidate_key::varchar,
    (SELECT count(*)::int FROM ir),
    (SELECT count(*)::int FROM rq),
    (SELECT count(*)::int FROM public.offer o WHERE o.candidate_key = p_candidate_key),
    (SELECT count(*)::int FROM ir WHERE conclusion = 'pass'),
    (SELECT count(*)::int FROM ir WHERE conclusion = 'reject'),
    (SELECT min(i.scheduled_at) FROM ir i),
    (SELECT max(i.scheduled_at) FROM ir i),
    ((SELECT count(*) FROM rq) > 1),
    (SELECT string_agg(format('%s#%s', x.id, x.position), '、' ORDER BY x.id) FROM rq x)::text,
    CASE
      WHEN (SELECT count(*) FROM rq) > 1 THEN
        format('这个 candidate_key 出现在 %s 个需求的面试里（%s）—— '
               || 'candidate_key 相同即同一个人：先看是不是重复约面，'
               || '再确认两个岗位是不是都在招（同时发两份 offer 会被唯一索引拒绝）',
               (SELECT count(*) FROM rq),
               (SELECT string_agg(format('%s#%s', x.id, x.position), '、' ORDER BY x.id) FROM rq x))
      WHEN (SELECT count(*) FROM ir) = 0
       AND (SELECT count(*) FROM public.offer o WHERE o.candidate_key = p_candidate_key) = 0 THEN
        '库里没有这个 candidate_key 的任何记录 —— 可能是新候选人，也可能是 key 抄错了'
      ELSE NULL
    END::text;
$$;

COMMENT ON FUNCTION fn_candidate_history IS
  '候选人历史（167）：面过几轮、投过几个岗位、有没有重复投递/重复面试。'
  '★ 永远返回一行（0 轮也返回）：返回零行会让调用方把"查不到"与"查失败"混为一谈。'
  '★ 重复的判据是"出现在 >1 个需求里"。同一需求下的多轮面试是正常的流程，不算重复。';

