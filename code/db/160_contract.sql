INSERT INTO public.legal_entity (id, name, note)
SELECT DISTINCT r.legal_entity_id,
       '法人 #' || r.legal_entity_id::text || '（待补全）',
       '160 回填：发薪批次里出现过的主体'
  FROM public.pay_run r
 WHERE r.legal_entity_id IS NOT NULL
ON CONFLICT (id) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 1. 合同模板：正文带 {{占位符}}，只用来"生成一次"
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.contract_template (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        varchar(32)  NOT NULL UNIQUE,
  name        varchar(96)  NOT NULL,
  -- 适用的合同类型；一份模板只服务一种类型，避免模板里到处 if
  kind        varchar(16)  NOT NULL,
  body        text         NOT NULL,
  version     int          NOT NULL DEFAULT 1,
  is_active   boolean      NOT NULL DEFAULT true,
  note        varchar(200),
  created_at  timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT ck_ct_kind CHECK (kind IN ('fixed','open','task','parttime','intern')),
  CONSTRAINT ck_ct_body CHECK (length(btrim(body)) > 0)
);

COMMENT ON TABLE public.contract_template IS
  '合同模板（160）。body 里用 {{占位符}}，渲染时由 fn_contract_render 一次性替换。'
  '模板**只用来生成**：签署时把渲染结果整段存进 employment_contract.body_snapshot，'
  '之后改模板不影响已签合同 —— 一份 2026 年签的合同里不该出现 2027 年修订的条款。';
COMMENT ON COLUMN public.contract_template.kind IS
  'fixed=固定期限 open=无固定期限 task=以完成一定工作任务为期限 '
  'parttime=非全日制 intern=实习。一份模板只服务一种类型，模板里不写 if。';

-- ---------------------------------------------------------------------------
-- 2. 合同：一个人可以有多份（续签），但同一时间只能有一份在履行的
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.employment_contract (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id    bigint       NOT NULL,          -- person.id（与 144 同：不挂外键）
  legal_entity_id bigint      NOT NULL,          -- 甲方主体（与 pay_run 同口径）
  contract_no    varchar(48)  NOT NULL UNIQUE,
  kind           varchar(16)  NOT NULL,

  -- 期限：无固定期限的 end_date 必须为空（用 CHECK 表达，不用应用层 if）
  start_date     date         NOT NULL,
  end_date       date,

  -- 试用期：起止都存。只存"几个月"会让"含在合同期内"这件事无处检查。
  probation_from date,
  probation_to   date,

  job_title      varchar(64)  NOT NULL,
  workplace      varchar(96)  NOT NULL,
  -- ★ 乙方通讯/送达地址：法律上这是**合同条款**（送达地址确认），
  --   不属于人事档案 —— 007 的 person_profile 里也确实没有 address。
  employee_address varchar(200) NOT NULL,
  -- 工时制度：标准 / 综合计算 / 不定时。综合与不定时要审批备案，
  -- 所以这里存的是**合同约定**，备案号在 130 的工时制度那边单独管。
  hours_system   varchar(16)  NOT NULL DEFAULT 'standard',

  wage_amount    numeric(12,2) NOT NULL,
  wage_unit      varchar(8)   NOT NULL DEFAULT 'month',   -- month | hour
  pay_day        int          NOT NULL DEFAULT 15,        -- 每月几号发薪

  template_id    bigint REFERENCES public.contract_template(id),
  -- ★ 签署那一刻的正文快照（见文件头 ①）
  body_snapshot  text,

  status         varchar(16)  NOT NULL DEFAULT 'draft',
  sign_date      date,
  signed_by      varchar(64),                 -- 甲方签署人（账号 id 或姓名）
  -- 续签指针：这份合同是接着哪一份签的
  prev_id        bigint REFERENCES public.employment_contract(id),

  terminate_at   date,
  terminate_note varchar(200),
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT ck_ec_kind CHECK (kind IN ('fixed','open','task','parttime','intern')),
  CONSTRAINT ck_ec_status CHECK (status IN
    ('draft','pending_sign','signed','terminated','expired')),
  CONSTRAINT ck_ec_hours CHECK (hours_system IN ('standard','comprehensive','irregular')),
  CONSTRAINT ck_ec_wage_unit CHECK (wage_unit IN ('month','hour')),
  CONSTRAINT ck_ec_wage CHECK (wage_amount > 0),
  CONSTRAINT ck_ec_payday CHECK (pay_day BETWEEN 1 AND 28),
  CONSTRAINT ck_ec_span CHECK (end_date IS NULL OR end_date > start_date),
  -- ★ 无固定期限不能有终止日；其他类型必须有（见文件头 ⑤）
  CONSTRAINT ck_ec_open_end CHECK (
    (kind = 'open'  AND end_date IS NULL)
    OR (kind <> 'open' AND end_date IS NOT NULL)),
  -- 试用期起止要么都填、要么都不填；且必须落在合同期内
  CONSTRAINT ck_ec_prob_pair CHECK (
    (probation_from IS NULL) = (probation_to IS NULL)),
  CONSTRAINT ck_ec_prob_in CHECK (
    probation_from IS NULL
    OR (probation_from >= start_date AND probation_to <= COALESCE(end_date, probation_to)
        AND probation_to >= probation_from)),
  -- 签了才有签署日；没签不该有
  CONSTRAINT ck_ec_sign CHECK ((status IN ('signed','terminated','expired')) = (sign_date IS NOT NULL)),
  CONSTRAINT ck_ec_snapshot CHECK (status = 'draft' OR body_snapshot IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS ix_ec_emp ON public.employment_contract (employee_id, start_date DESC);
CREATE INDEX IF NOT EXISTS ix_ec_live ON public.employment_contract (employee_id)
  WHERE status IN ('signed','pending_sign');
CREATE INDEX IF NOT EXISTS ix_ec_end ON public.employment_contract (end_date)
  WHERE status = 'signed' AND end_date IS NOT NULL;

COMMENT ON TABLE public.employment_contract IS
  '人事合同（160）。一人可多份（续签/变更），prev_id 串成链。'
  'body_snapshot 是签署时的正文快照 —— 模板改了不影响已签的那一份。';
COMMENT ON COLUMN public.employment_contract.hours_system IS
  '合同约定的工时制度。standard=标准工时；comprehensive=综合计算工时；'
  'irregular=不定时。后两种要审批备案（130 单独管备案号），这里只存"约定了哪种"。';
COMMENT ON COLUMN public.employment_contract.pay_day IS
  '每月发薪日（1–28）。★ 不填 29/30/31：那几天在小月不存在，'
  '写 31 的公司每到 2 月就要解释一次"为什么晚发"。';

-- ---------------------------------------------------------------------------
-- 3. 法定试用期上限（劳动合同法第十九条）
-- ---------------------------------------------------------------------------
-- 分档：
--   合同期 3 个月以上不满 1 年      → 试用期 ≤ 1 个月
--   1 年以上不满 3 年                → ≤ 2 个月
--   3 年以上固定期限 / 无固定期限    → ≤ 6 个月
--   以完成一定工作任务为期限 / 不满 3 个月 → **不得约定试用期**
-- 同一用人单位与同一劳动者**只能约定一次**试用期（续签不得再来一次）。
CREATE OR REPLACE FUNCTION public.fn_contract_probation_max(
  p_kind varchar, p_start date, p_end date
) RETURNS int
LANGUAGE plpgsql IMMUTABLE
SET search_path = ''
AS $$
DECLARE
  v_months numeric;
BEGIN
  IF p_kind IN ('task', 'parttime', 'intern') THEN
    RETURN 0;                     -- 不得约定试用期
  END IF;
  IF p_kind = 'open' THEN
    RETURN 6;
  END IF;
  IF p_start IS NULL OR p_end IS NULL THEN
    RETURN 0;                     -- 没期限就谈不上分档，交给上层报错
  END IF;
  -- 按月折算：不足一个月的零头按月比例算（3 个月零 5 天仍算"不满 1 年"）
  v_months := (EXTRACT(YEAR FROM age(p_end, p_start)) * 12
               + EXTRACT(MONTH FROM age(p_end, p_start)));
  IF v_months < 3 THEN
    RETURN 0;
  ELSIF v_months < 12 THEN
    RETURN 1;
  ELSIF v_months < 36 THEN
    RETURN 2;
  ELSE
    RETURN 6;
  END IF;
END;
$$;

COMMENT ON FUNCTION fn_contract_probation_max IS
  '法定试用期上限（月）：不满3个月/完成一定任务/非全日制/实习=0；3个月~1年=1；'
  '1~3年=2；3年以上及无固定期限=6。按"满月数"分档，不足一月按比例（不四舍五入抬档）。';

-- ---------------------------------------------------------------------------
-- 4. 校验：返回 block / warn 行（与排班规则同一套形态）
-- ---------------------------------------------------------------------------
-- ★ block = 违法，不许存；warn = 有风险，允许存但要看得见。
--   两者分开的理由：把预警做成硬拦，人会去绕开系统（在 Excel 里签），
--   那样连"有这份合同"都查不到，比预警更糟。
CREATE OR REPLACE FUNCTION public.fn_contract_check(
  p_employee bigint,
  p_entity   bigint,
  p_kind     varchar,
  p_start    date,
  p_end      date,
  p_prob_from date,
  p_prob_to   date,
  p_exclude_id bigint DEFAULT NULL
) RETURNS TABLE (level varchar, code varchar, message varchar)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE
  v_max   int;
  v_months numeric;
  v_n     int;
  v_exist int;
BEGIN
  -- ① 期限本身
  IF p_start IS NULL THEN
    RETURN QUERY SELECT 'block'::varchar, 'E_CT_NO_START'::varchar,
      '合同起始日必填（没有起始日的合同无法证明劳动关系从哪天开始）'::varchar;
    RETURN;
  END IF;
  IF p_kind = 'open' AND p_end IS NOT NULL THEN
    RETURN QUERY SELECT 'block'::varchar, 'E_CT_OPEN_HAS_END'::varchar,
      '无固定期限合同不能有终止日（填了终止日，它在法律上就是固定期限）'::varchar;
    RETURN;
  END IF;
  IF p_kind <> 'open' AND p_end IS NULL THEN
    RETURN QUERY SELECT 'block'::varchar, 'E_CT_NO_END'::varchar,
      '这种合同类型必须填终止日（不填就是无固定期限，两者不能混）'::varchar;
    RETURN;
  END IF;
  IF p_end IS NOT NULL AND p_end <= p_start THEN
    RETURN QUERY SELECT 'block'::varchar, 'E_CT_BAD_SPAN'::varchar,
      format('终止日 %s 不晚于起始日 %s（写反了）', p_end, p_start)::varchar;
    RETURN;
  END IF;

  -- ② 试用期：上限 + 只能一次
  IF p_prob_from IS NOT NULL THEN
    v_max := public.fn_contract_probation_max(p_kind, p_start, p_end);
    IF v_max = 0 THEN
      RETURN QUERY SELECT 'block'::varchar, 'E_CT_PROB_NOT_ALLOWED'::varchar,
        ('这种合同不得约定试用期：以完成一定工作任务为期限、非全日制、实习，'
         || '以及合同期不满 3 个月的，都没有试用期')::varchar;
      RETURN;
    END IF;
    v_months := round((EXTRACT(DAY FROM age(p_prob_to, p_prob_from)) / 30.0)::numeric, 2);
    -- 用"日历月差"判更稳：起止同月同日算整月
    v_months := (EXTRACT(YEAR FROM age(p_prob_to, p_prob_from)) * 12
                 + EXTRACT(MONTH FROM age(p_prob_to, p_prob_from)));
    IF v_months > v_max THEN
      RETURN QUERY SELECT 'block'::varchar, 'E_CT_PROB_TOO_LONG'::varchar,
        format('试用期 %s 个月超过法定上限 %s 个月（合同期 %s ~ %s）',
               v_months, v_max, p_start, p_end)::varchar;
      RETURN;
    END IF;
    IF p_prob_from < p_start OR p_prob_to > COALESCE(p_end, p_prob_to) THEN
      RETURN QUERY SELECT 'block'::varchar, 'E_CT_PROB_OUT'::varchar,
        '试用期必须包含在合同期限内（试用期不能"先试用、后签合同"）'::varchar;
      RETURN;
    END IF;
    SELECT count(*)::int INTO v_n
      FROM public.employment_contract c
     WHERE c.employee_id = p_employee
       AND c.legal_entity_id = p_entity
       AND c.probation_from IS NOT NULL
       AND c.status IN ('signed','terminated','expired')
       AND (p_exclude_id IS NULL OR c.id <> p_exclude_id);
    IF v_n > 0 THEN
      RETURN QUERY SELECT 'block'::varchar, 'E_CT_PROB_AGAIN'::varchar,
        ('同一单位与同一劳动者只能约定一次试用期 —— 这个人在这家主体已经有过一次'
         || '（续签不得再约定试用期）')::varchar;
      RETURN;
    END IF;
  END IF;

  -- ③ 预警：同一人同一主体已有在履行的合同
  SELECT count(*)::int INTO v_exist
    FROM public.employment_contract c
   WHERE c.employee_id = p_employee
     AND c.status = 'signed'
     AND (p_exclude_id IS NULL OR c.id <> p_exclude_id)
     AND daterange(c.start_date, c.end_date, '[]')
         && daterange(p_start, p_end, '[]');
  IF v_exist > 0 THEN
    RETURN QUERY SELECT 'warn'::varchar, 'W_CT_OVERLAP'::varchar,
      '这段时间里这个人已经有一份在履行的合同（同一时间两份合同，续签时要先结束上一份）'::varchar;
  END IF;

  -- ④ 预警：连续两次固定期限后应订无固定期限
  IF p_kind = 'fixed' THEN
    SELECT count(*)::int INTO v_n
      FROM public.employment_contract c
     WHERE c.employee_id = p_employee
       AND c.kind = 'fixed'
       AND c.status IN ('signed','expired','terminated')
       AND (p_exclude_id IS NULL OR c.id <> p_exclude_id);
    IF v_n >= 2 THEN
      RETURN QUERY SELECT 'warn'::varchar, 'W_CT_OPEN_DUE'::varchar,
        format('这将是第 %s 份固定期限合同 —— 连续两次后应订无固定期限，'
               || '除非劳动者提出订立固定期限（要留书面）', v_n + 1)::varchar;
    END IF;
  END IF;
  RETURN;
END;
$$;

COMMENT ON FUNCTION fn_contract_check IS
  '合同校验（160）：block=违法不许存（试用期超限/不该有试用期/试用期重复/'
  '无固定期限填了终止日/期限写反）；warn=有风险但允许存（同期两份合同、'
  '二次固定期限后应订无固定期限）。分开的理由见文件头 ③。';

-- ---------------------------------------------------------------------------
-- 5. 渲染：{{占位符}} → 实际值；缺字段**报错**，不静默留 {{}}
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_contract_render(p_contract bigint)
RETURNS text
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE
  c       record;
  t       record;
  v_body  text;
  v_map   jsonb;
  v_key   text;
  v_val   text;
  v_miss  text[] := '{}';
BEGIN
  SELECT * INTO c FROM public.employment_contract WHERE id = p_contract;
  IF c.id IS NULL THEN
    RAISE EXCEPTION 'E_CT_NOT_FOUND: 合同 % 不存在', p_contract;
  END IF;
  IF c.template_id IS NULL THEN
    RAISE EXCEPTION 'E_CT_NO_TEMPLATE: 合同 % 没有关联模板，无法生成正文', p_contract;
  END IF;
  SELECT * INTO t FROM public.contract_template WHERE id = c.template_id;
  v_body := t.body;

  v_map := jsonb_build_object(
    '合同编号', c.contract_no,
    '甲方名称', (SELECT COALESCE(l.name, '法人 #' || c.legal_entity_id::text)
                   FROM public.legal_entity l WHERE l.id = c.legal_entity_id),
    '甲方信用代码', (SELECT l.credit_code FROM public.legal_entity l
                     WHERE l.id = c.legal_entity_id),
    '甲方地址', (SELECT l.address FROM public.legal_entity l
                 WHERE l.id = c.legal_entity_id),
    '甲方法定代表人', (SELECT l.legal_rep FROM public.legal_entity l
                       WHERE l.id = c.legal_entity_id),
    '乙方姓名', (SELECT p.full_name FROM public.person p WHERE p.id = c.employee_id),
    -- 007 的档案是 profile_type（national_id / mobile / bank_card），不是 field_code
    '乙方证件号', (SELECT v.profile_value FROM public.person_profile v
                    WHERE v.person_id = c.employee_id AND v.profile_type = 'national_id'
                    ORDER BY (v.verified_by IS NOT NULL) DESC LIMIT 1),
    '乙方住址', c.employee_address,
    '乙方电话', (SELECT v.profile_value FROM public.person_profile v
                  WHERE v.person_id = c.employee_id AND v.profile_type = 'mobile'
                  ORDER BY (v.verified_by IS NOT NULL) DESC LIMIT 1),
    '合同类型', (CASE c.kind WHEN 'fixed' THEN '固定期限' WHEN 'open' THEN '无固定期限'
                             WHEN 'task' THEN '以完成一定工作任务为期限'
                             WHEN 'parttime' THEN '非全日制' ELSE '实习' END),
    '起始日', to_char(c.start_date, 'YYYY 年 MM 月 DD 日'),
    '终止日', CASE WHEN c.end_date IS NULL THEN '（无固定期限，无终止日）'
                   ELSE to_char(c.end_date, 'YYYY 年 MM 月 DD 日') END,
    '试用期起', CASE WHEN c.probation_from IS NULL THEN '（无试用期）'
                     ELSE to_char(c.probation_from, 'YYYY 年 MM 月 DD 日') END,
    '试用期止', CASE WHEN c.probation_to IS NULL THEN '（无试用期）'
                     ELSE to_char(c.probation_to, 'YYYY 年 MM 月 DD 日') END,
    '岗位', c.job_title,
    '工作地点', c.workplace,
    '工时制度', CASE c.hours_system WHEN 'standard' THEN '标准工时制'
                    WHEN 'comprehensive' THEN '综合计算工时制' ELSE '不定时工作制' END,
    '工资', to_char(c.wage_amount, 'FM999,999,990.00')
            || CASE c.wage_unit WHEN 'month' THEN ' 元/月' ELSE ' 元/小时' END,
