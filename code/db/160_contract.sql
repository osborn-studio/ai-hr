-- ============================================================================
-- 160_contract.sql · 人事合同：填关键项 → 校验 → 生成标准格式 → 打印盖章
-- ----------------------------------------------------------------------------
-- 前面 159 份迁移里，人事这块一直没有"合同"本身 —— 只有 134/135 的解除与遣散
-- （那是合同**结束**时的算法）。而合同是人事的地基：
--
--   · 没有合同，"入职"就只是一个日期，答不出"他跟我们是什么关系、到哪天为止"；
--   · 没有合同，续签、试用期、无固定期限这三件事都无处落，而它们直接决定
--     解除时是 N 还是 2N（违法解除）；
--   · 没有合同，工资单与考勤都无法引用"约定的岗位/工作地点/工时制度"，
--     调到别的城市却没有书面变更，是劳动争议里最常见的一类。
--
-- 这一层做的是"填报 → 校验 → 生成标准格式 → 打印盖章"。**不做电子签章**
-- （那要 CA 与存证服务，是另一件事），但把"签的是哪一版、什么时候签的、
-- 内容是什么"存成不可改的快照。
--
-- ★ 五条设计取舍：
--
--   ① **正文存快照（body_snapshot），不存"模板引用"。**
--      模板改了，已签的合同不能跟着变 —— 一份 2026 年签的合同里，
--      2027 年修订的模板不该出现。所以签署那一刻把渲染结果整段存下来，
--      模板只用来"生成一次"。
--
--   ② **法定试用期上限在库里判，模板里不写死。**
--      试用期超限是**违法条款**（不是"不规范"），后果是该条款无效 +
--      已履行的按转正后工资补差。这种错不能靠"填表的人记得"。
--      分档见 fn_contract_probation_max（劳动合同法第十九条）。
--
--   ③ **续签次数与无固定期限只做"预警"，不做硬拦。**
--      连续两次固定期限后应订无固定期限 —— 但法条留了"劳动者提出订立
--      固定期限"这个例外，系统判不了当事人怎么提的。硬拦会逼人绕开系统，
--      所以：出预警、留痕、由人决定（与排班规则同一套 block/warn 形态）。
--
--   ④ **一条"用工满一个月未签书面"的预警。**
--      这是双倍工资风险的起算点（劳动合同法第八十二条），而它非常安静：
--      人在上班、工资在发、系统里一切正常，直到有人离职时提出来。
--      预警挂在"在职但没有生效合同"的人身上，不是挂在合同上。
--
--   ⑤ **合同期限类型决定 end_date 能不能为空，用 CHECK 表达，不用应用层 if。**
--      无固定期限填了终止日、固定期限没填终止日，这两种错在应用层判会漏
--      （导入、后台脚本、将来的新接口都会绕过去）。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 0. 法人主档：合同甲方必须是一个有名字、有信用代码、有地址的主体
-- ---------------------------------------------------------------------------
-- ★ 这一步是合同逼出来的：`employment.legal_entity_id` / `pay_run.legal_entity_id`
--   一直是**裸 bigint**（007 起），仓里从来没有法人主档 —— 于是打印出来的
--   工资单只能写"法人 #1"，而合同上写"法人 #1"是无效的（主体不明）。
--   主档补上，工资单与合同共用同一份主体信息。
--
-- ★ 不加外键、只回填：存量 employments 的 entity id 可能不在主档里，
--   直接加外键会让建库当场失败（那正是"升级当天全停摆"的形态）。
--   改成"乐观并存 + 缺失可见"：主档没有的行，渲染时显示"法人 #N"，
--   一眼能看出还没配，而不是悄悄编一个名字。
CREATE TABLE IF NOT EXISTS public.legal_entity (
  id           bigint PRIMARY KEY,
  name         varchar(96)  NOT NULL,
  credit_code  varchar(32),          -- 统一社会信用代码
  address      varchar(200),         -- 注册地址
  legal_rep    varchar(64),          -- 法定代表人
  stamp_name   varchar(96),          -- 盖章用的主体全称（常与 name 相同）
  bank_name    varchar(96),
  bank_account varchar(48),
  is_active    boolean       NOT NULL DEFAULT true,
  note         varchar(200),
  created_at   timestamptz   NOT NULL DEFAULT now(),
  CONSTRAINT ck_le_name CHECK (length(btrim(name)) > 0)
);

COMMENT ON TABLE public.legal_entity IS
  '法人主档（160）。合同甲方与工资单表头都读它 —— 在此之前 entity 只是裸 id，'
  '一份盖了章但主体写错的合同/工资单是要重开的。';
COMMENT ON COLUMN public.legal_entity.stamp_name IS
  '盖章用的主体全称。与 name 分开是因为有"对外简称"与"公章全称"不一致的客户，'
  '而合同上必须用公章全称。';

-- 回填：把存量里出现过的 entity id 建成占位行（名字明确写"待补全"，不编造）
