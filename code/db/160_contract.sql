    '签订日期', to_char(COALESCE(c.sign_date, CURRENT_DATE), 'YYYY 年 MM 月 DD 日')
  );

  -- 逐个占位符替换；**缺失就报错**，不静默留 {{xxx}}
  --   静默留痕的后果：打印出来一张写着 {{乙方证件号}} 的合同，盖章发出去，
  --   而双方都以为是"系统会填"。
  FOR v_key IN SELECT jsonb_object_keys(v_map) LOOP
    v_val := COALESCE(v_map ->> v_key, '');
    IF btrim(v_val) = '' AND (v_key LIKE '乙方%' OR v_key LIKE '甲方%') THEN
      v_miss := v_miss || v_key;
    END IF;
    v_body := replace(v_body, '{{' || v_key || '}}', v_val);
  END LOOP;

  IF array_length(v_miss, 1) > 0 THEN
    RAISE EXCEPTION 'E_CT_FIELD_MISSING: 这些关键字段是空的，签之前要补：%',
      array_to_string(v_miss, '、');
  END IF;
  IF v_body ~ '\{\{[^}]+\}\}' THEN
    RAISE EXCEPTION 'E_CT_PLACEHOLDER: 模板里还有未定义的占位符：%',
      (regexp_matches(v_body, '\{\{[^}]+\}\}', 'g'))[1];
  END IF;
  RETURN v_body;
END;
$$;

