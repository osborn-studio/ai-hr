-- ============================================================================
-- 022_headcount.sql · 编制与人力预算
-- ----------------------------------------------------------------------------
-- 编制不是"人数上限"这种技术参数，它是**资源分配**：
-- 集团批 1000 个编，区域拿 200，门店拿 40。谁多拿一个，谁就少一个。
-- 所以这一层的核心不是"拦住超编"，是**把分配关系本身表达对**。
--
-- 三条设计判断，写在最前面：
--
-- ① **下分是分配，不是复制。**
--    集团给华东区 100，华东区给 A店 40、B店 35，则华东区自己只剩 25。
--    如果把"给区域 100"理解成"区域下每家店各 100"，那总数会按层数指数膨胀，
--    而每一层的账面都自洽——这类错不会在任何单点上暴露。
--
-- ② **额度只增不改（版本行），不是就地 UPDATE。**
--    "上个月额度是多少"必须还能查出来。就地 UPDATE 之后，
--    上个月超编的事实会随着额度被调高而消失，而没有任何一处报错。
--
-- ③ **超编不由系统假装不存在。**
--    真实业务里超编一定会发生（并购、旺季、交接期）。系统能做的不是"拒绝"，
--    而是让超编**必须显式**：要么先调编，要么带审批走超编通道。
--    只做拒绝的结果是把人挂到别的门店去——数据变干净了，事实没有变。
--
-- 一条口径做成配置项（不替客户选）：
--    HEADCOUNT_MODE      = 'cascaded'（逐级下分，默认）| 'group_pool'（集团一个池子）
--    HEADCOUNT_OVER      = 'require_approval'（默认）| 'reject'
-- ============================================================================

