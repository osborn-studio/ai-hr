-- ---------------------------------------------------------------------------
-- 编制额度（append-only 版本行）
-- ---------------------------------------------------------------------------
CREATE TABLE headcount_budget (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id     bigint      NOT NULL REFERENCES org_unit(id),
  period     varchar(7)  NOT NULL,          -- 'YYYY-MM'
  version    int         NOT NULL,
  quota      int         NOT NULL,
  set_by     varchar(64) NOT NULL,
  reason     varchar(200) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uk_hb UNIQUE (org_id, period, version),
  CONSTRAINT ck_hb_period CHECK (period ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  CONSTRAINT ck_hb_quota  CHECK (quota >= 0),
  CONSTRAINT ck_hb_ver    CHECK (version >= 1),
  CONSTRAINT ck_hb_reason CHECK (length(btrim(reason)) >= 4)
);

-- ★ 只增不改。就地 UPDATE 会让"上个月额度是多少"永久丢失，
--   而它丢失的方式是**上个月超编的事实消失**——没有任何一处会报错。
CREATE OR REPLACE FUNCTION fn_hb_append_only() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  RAISE EXCEPTION 'E_HC_APPEND_ONLY: 编制额度只增不改（调编请用 fn_hc_set 追加新版本）';
END;
$$;

CREATE TRIGGER trg_hb_append_only
  BEFORE UPDATE OR DELETE ON headcount_budget
  FOR EACH ROW EXECUTE FUNCTION fn_hb_append_only();

-- ---------------------------------------------------------------------------
-- 取当期生效额度（最大 version）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_hc_quota(p_org bigint, p_period varchar)
RETURNS int
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT quota FROM public.headcount_budget
   WHERE org_id = p_org AND period = p_period
   ORDER BY version DESC LIMIT 1;
$$;

-- 直接子组织已分走的合计（不含更深层：深层是从子组织自己那份里再分的）
CREATE OR REPLACE FUNCTION fn_hc_allocated(p_org bigint, p_period varchar)
RETURNS int
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT COALESCE(sum(public.fn_hc_quota(c.id, p_period)), 0)::int
    FROM public.org_unit c
   WHERE c.parent_id = p_org AND c.is_active;
$$;

-- 自己还剩多少**可下分**（不是"可招"，两者差一个已占编）
CREATE OR REPLACE FUNCTION fn_hc_available(p_org bigint, p_period varchar)
RETURNS int
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT COALESCE(public.fn_hc_quota(p_org, p_period), 0)
       - public.fn_hc_allocated(p_org, p_period);
$$;

-- 占编：子树内 cost_org 归属在本期期末仍然有效的人数（**派生，不落列**）
CREATE OR REPLACE FUNCTION fn_hc_used(p_org bigint, p_period varchar)
RETURNS int
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  WITH me AS (SELECT path FROM public.org_unit WHERE id = p_org),
       p_end AS (SELECT (to_date(p_period || '-01','YYYY-MM-DD') + interval '1 month - 1 day')::date AS d)
  SELECT count(DISTINCT a.employee_id)::int
    FROM public.employee_org_assignment a
    JOIN public.org_unit o ON o.id = a.org_id
   WHERE a.dim_code = 'cost_org'
     AND daterange(a.valid_from, a.valid_to, '[]') @> (SELECT d FROM p_end)
     AND o.path LIKE (SELECT path || '%' FROM me);
$$;

COMMENT ON FUNCTION fn_hc_used IS
  '占编是派生的，不落列。存一列 used 的话，入职/离职/调动三条路径各自更新它，'
  '必然漂——而漂的表现是"报表说还有 3 个编，实际招不进第 1 个人"。';

-- 还能招几个：额度 − 已下分给下级 − 自身已占
-- ★ 这个数与 fn_hc_available 不是一回事，而它们最常被混用：
--   available 是"还能往下分多少"，hireable 是"还能招几个"。
--   一个区域 available=3、used=2，它实际只能再招 1 个；
--   把它当成"还能招 3 个"，招到第 2 个就超编，而每一步都合规。
CREATE OR REPLACE FUNCTION fn_hc_hireable(p_org bigint, p_period varchar)
RETURNS int
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT COALESCE(public.fn_hc_quota(p_org, p_period), 0)
       - public.fn_hc_allocated(p_org, p_period)
       - public.fn_hc_used(p_org, p_period);
$$;


-- ---------------------------------------------------------------------------
-- 调编：追加新版本，且子项之和不得超父项
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_hc_set(
  p_org bigint, p_period varchar, p_quota int,
  p_by varchar, p_reason varchar
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_parent bigint; v_ver int;
  v_parent_quota int; v_siblings int; v_mode varchar(24);
BEGIN
  IF p_quota < 0 THEN
    RAISE EXCEPTION 'E_HC_NEGATIVE: 额度不能为负（% 个）', p_quota;
  END IF;

  -- 逐级下分模式下：子项之和不得超过父项额度
  SELECT value_text INTO v_mode
    FROM public.fn_policy_effective('HEADCOUNT_MODE', p_org, (p_period || '-01')::date);
  SELECT parent_id INTO v_parent FROM public.org_unit WHERE id = p_org;

  -- 集团一个池子时，"分给下级"这件事根本不存在。
  -- 允许给下级设额度会让两套口径同时在跑：池子里按总数卡，下级又按自己那份卡，
  -- 而两边都不知道对方存在。
  IF COALESCE(v_mode, 'cascaded') = 'group_pool' AND v_parent IS NOT NULL THEN
    RAISE EXCEPTION 'E_HC_NOT_CASCADED: 编制为集团池模式，% 不应有自己的额度', p_org;
  END IF;

  IF COALESCE(v_mode, 'cascaded') = 'cascaded' AND v_parent IS NOT NULL THEN
    v_parent_quota := public.fn_hc_quota(v_parent, p_period);
    IF v_parent_quota IS NOT NULL THEN
      -- 兄弟已分走的合计（本次自己那条按新值算）
      SELECT COALESCE(sum(CASE WHEN c.id = p_org THEN p_quota
                               ELSE public.fn_hc_quota(c.id, p_period) END), 0)
        INTO v_siblings
        FROM public.org_unit c
       WHERE c.parent_id = v_parent AND c.is_active;

      IF v_siblings > v_parent_quota THEN
        RAISE EXCEPTION 'E_HC_OVER_ALLOCATED: % 的下属组织合计 % 个，超过它自己的 % 个',
          v_parent, v_siblings, v_parent_quota;
      END IF;
    END IF;
  END IF;

  SELECT COALESCE(max(version), 0) + 1 INTO v_ver
    FROM public.headcount_budget WHERE org_id = p_org AND period = p_period;

  INSERT INTO public.headcount_budget(org_id, period, version, quota, set_by, reason)
  VALUES (p_org, p_period, v_ver, p_quota, p_by, p_reason);

  RETURN v_ver;
END;
$$;

COMMENT ON FUNCTION fn_hc_set IS
  '子项之和 ≤ 父项额度，这条判据只在**逐级下分**模式下成立。'
  'group_pool 模式下不存在"分给下级"这件事，子组织也不该有自己的额度。';

-- ---------------------------------------------------------------------------
-- 三张必须能看的清单
-- ---------------------------------------------------------------------------
-- ① 超编：占编 > 额度
CREATE OR REPLACE FUNCTION fn_hc_over(p_period varchar)
RETURNS TABLE (org_id bigint, name varchar, quota int, used int, over_by int)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT o.id, o.name, public.fn_hc_quota(o.id, p_period),
         public.fn_hc_used(o.id, p_period),
         public.fn_hc_used(o.id, p_period) - public.fn_hc_quota(o.id, p_period)
    FROM public.org_unit o
   WHERE o.is_active
     AND public.fn_hc_quota(o.id, p_period) IS NOT NULL
     AND public.fn_hc_used(o.id, p_period) > public.fn_hc_quota(o.id, p_period)
   ORDER BY 5 DESC;
$$;

-- ② 没编制却有在职：忘了下编，永远不超编，而它看起来"很正常"
CREATE OR REPLACE FUNCTION fn_hc_uncovered(p_period varchar)
RETURNS TABLE (org_id bigint, name varchar, used int)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT o.id, o.name, public.fn_hc_used(o.id, p_period)
    FROM public.org_unit o
   WHERE o.is_active
     AND public.fn_hc_quota(o.id, p_period) IS NULL
     AND public.fn_hc_used(o.id, p_period) > 0
   ORDER BY 3 DESC;
$$;

COMMENT ON FUNCTION fn_hc_uncovered IS
  '没有额度就没有判据：占编 200 人也不会超编，而报表上一片绿。'
  '这条清单的存在，是为了让"忘了下编"与"编制充足"不同形。';

-- ③ 分配有余：父项额度 - 子项合计 - 自身占编，可能为负
CREATE OR REPLACE FUNCTION fn_hc_slack(p_period varchar)
RETURNS TABLE (org_id bigint, name varchar, quota int, allocated int, unallocated int)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT o.id, o.name, public.fn_hc_quota(o.id, p_period),
         public.fn_hc_allocated(o.id, p_period),
         public.fn_hc_available(o.id, p_period)
    FROM public.org_unit o
   WHERE o.is_active AND public.fn_hc_quota(o.id, p_period) IS NOT NULL
   ORDER BY 5 DESC;
$$;

-- ---------------------------------------------------------------------------
-- 占编校验：新增长期归属时检查
-- ---------------------------------------------------------------------------
-- ★ 只在**配了额度**时才检查。没有编制管理的客户不该被这套东西拦住，
--   但"没配额度"必须由 fn_hc_uncovered 报出来，不能静默变成无限额。
CREATE OR REPLACE FUNCTION fn_hc_guard() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_quota int; v_used int; v_policy varchar(24); v_basis varchar(16);
  v_period varchar(7);
BEGIN
  IF NEW.dim_code <> 'cost_org' THEN RETURN NEW; END IF;

  v_period := to_char(NEW.valid_from, 'YYYY-MM');
  v_quota  := public.fn_hc_quota(NEW.org_id, v_period);
  IF v_quota IS NULL THEN RETURN NEW; END IF;   -- 未配额度：不拦，但会被 uncovered 报出

  v_used := public.fn_hc_used(NEW.org_id, v_period);
  IF v_used < v_quota THEN RETURN NEW; END IF;

  SELECT value_text INTO v_policy
    FROM public.fn_policy_effective('HEADCOUNT_OVER', NEW.org_id, NEW.valid_from);
  IF COALESCE(v_policy, 'require_approval') = 'reject' THEN
    RAISE EXCEPTION 'E_HC_FULL: % 在 % 已用满 % 个编制', NEW.org_id, v_period, v_quota;
  END IF;

  -- require_approval：不拒绝，但必须留一条超编审批，否则下一句就抛
  SELECT value_text INTO v_basis
    FROM public.fn_policy_effective('HEADCOUNT_OVER_BASIS', NEW.org_id, NEW.valid_from);
  IF v_basis IS NULL THEN
    RAISE EXCEPTION 'E_HC_OVER_NO_APPROVAL: % 在 % 已超编（%/%），'
      '新增占用必须带超编审批（HEADCOUNT_OVER_BASIS）', NEW.org_id, v_period, v_used, v_quota;
  END IF;

  INSERT INTO public.headcount_over_log(org_id, period, employee_id, quota, used_at_insert,
                                        basis, approved_by)
  VALUES (NEW.org_id, v_period, NEW.employee_id, v_quota, v_used, v_basis, current_user);
  RETURN NEW;
END;
$$;

CREATE TABLE headcount_over_log (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id         bigint      NOT NULL REFERENCES org_unit(id),
  period         varchar(7)  NOT NULL,
  employee_id    bigint      NOT NULL,
  quota          int         NOT NULL,
  used_at_insert int         NOT NULL,
  basis          varchar(200) NOT NULL,
  approved_by    varchar(64) NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TRIGGER trg_hc_guard
  BEFORE INSERT ON employee_org_assignment
  FOR EACH ROW EXECUTE FUNCTION fn_hc_guard();
