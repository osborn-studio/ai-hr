-- ============================================================================
-- 114_att_period_report.sql · 考勤月报：HR 确认过的"最终数字"，薪资只吃这张表
-- ----------------------------------------------------------------------------
-- 现状的问题不是"算错"，是**没有一个地方能落笔**。
--
-- 现在算薪直接从 attendance_daily_store（人日）+ 打卡 + 请假表现算。
-- 现实里的流程不是这样：
--
--     考勤机/打卡 → 系统汇总 → HR 看报表、核对、**手调几个数** → 确认 → 传给薪资
--
-- 少了"报表"这一层，三件事没有答案：
--   ① HR 发现某人漏打卡 1 天，想改成出勤 21 天 —— 改哪儿？
--     改人日要伪造一条打卡记录，改打卡表又会被下次同步冲掉。
--   ② 薪资算完，HR 说"这个数不对，我当时调过" —— 系统里没有任何记录能对上。
--   ③ 同一个期间重算两次，结果可能不同（期间中间补录了考勤）。
--      而工资必须是**可重复**的：同样输入永远同样输出。
--
-- 所以这一版加两层：
--
--   att_period_report   人 × 期间 一行，存**最终数字**（应出勤/实出勤/请假/工时/加班）
--                       status: draft（可调） → confirmed（HR 确认，薪资只认这个）
--   att_period_adjust   每一次手调的痕迹：字段、改前、改后、原因、谁改的
--
-- 薪资侧（fn_att_person_period）改为：
--   **有 confirmed 月报 → 用月报的数字**；没有 → 退回实时汇总（等于旧行为）。
--   这样"上线即改变所有人工资"不会发生，而一旦 HR 确认了，数字就固定下来。
--
-- ★ 为什么月报不是"再存一份汇总"而是"最终数字"：
--   汇总可以随时重算，最终数字不能 —— 它代表"HR 在这一刻认可了这个数"。
--   确认后重算不会改它（build 会跳过 confirmed），要改必须显式 reopen（留痕）。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 月报表
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS att_period_report (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period        varchar(7)   NOT NULL,
  person_id     bigint       NOT NULL REFERENCES person(id),
  legal_entity_id bigint     NOT NULL,

  -- 应出勤：最终值。HR 可以调（比如公司统一放假不发通知，日历算多了）
  work_days     numeric(6,2) NOT NULL,
  -- 下面两个是"算 work_days 时看到的参考值"，留证据用：改过之后还能看出原来多少
  calendar_days numeric(6,2) NOT NULL,
  roster_days   numeric(6,2) NOT NULL DEFAULT 0,

  present_days  numeric(6,2) NOT NULL DEFAULT 0,
  leave_days    numeric(6,2) NOT NULL DEFAULT 0,
  personal_leave_days numeric(6,2) NOT NULL DEFAULT 0,
  absent_days   numeric(6,2) NOT NULL DEFAULT 0,
  work_hours    numeric(8,2) NOT NULL DEFAULT 0,
  ot_hours      numeric(8,2) NOT NULL DEFAULT 0,

  workdays_source varchar(16) NOT NULL DEFAULT 'calendar',

  status        varchar(16)  NOT NULL DEFAULT 'draft',
  confirmed_by  varchar(64),
  confirmed_at  timestamptz,
  note          varchar(200),

  built_at      timestamptz  NOT NULL DEFAULT now(),
  updated_at    timestamptz  NOT NULL DEFAULT now(),

  CONSTRAINT ck_apr_period CHECK (period ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  CONSTRAINT ck_apr_status CHECK (status IN ('draft','confirmed')),
  -- 状态与确认人同生同灭：只加列不写这条，会留下"已确认但没人确认"的一行
  CONSTRAINT ck_apr_confirmed CHECK (
    (status = 'confirmed') = (confirmed_by IS NOT NULL AND confirmed_at IS NOT NULL)
  ),
  -- 应出勤不能是 0：它是折算的分母，0 会让 prorata 除零、日薪无穷大
  CONSTRAINT ck_apr_workdays CHECK (work_days > 0),
  CONSTRAINT ck_apr_nonneg CHECK (
    LEAST(present_days, leave_days, personal_leave_days, absent_days,
          work_hours, ot_hours, calendar_days, roster_days) >= 0
  ),
  UNIQUE (period, person_id)
);

COMMENT ON TABLE att_period_report IS
  '考勤月报（人×期间）：HR 确认过的最终数字，薪资只认 confirmed 的这一行。'
  '★ work_days 是"应出勤"最终值（不是 21.75 月计薪天数）；'
  'calendar_days / roster_days 是生成时的参考值，用来在改过之后仍能看出"原来多少"。';

COMMENT ON COLUMN att_period_report.work_days IS
  '应出勤天数（最终值，可被 HR 调整，必 > 0）。折算类公式的分母就是它。';

-- ---------------------------------------------------------------------------
-- 2. 调整留痕
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS att_period_adjust (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id   bigint       NOT NULL REFERENCES att_period_report(id) ON DELETE CASCADE,
  field_name  varchar(32)  NOT NULL,
  before_value numeric(10,2),
  after_value  numeric(10,2),
  reason      varchar(200) NOT NULL,
  adjusted_by varchar(64)  NOT NULL,
  adjusted_at timestamptz  NOT NULL DEFAULT now(),

  -- 空白理由不行：NOT NULL 能通过一个空格，而"改了但没理由"等于没留痕
  CONSTRAINT ck_apa_reason CHECK (length(btrim(reason)) >= 4),
  CONSTRAINT ck_apa_changed CHECK (before_value IS DISTINCT FROM after_value)
);

COMMENT ON TABLE att_period_adjust IS
  '考勤月报的每一次手调：字段 / 改前 / 改后 / 原因 / 谁改的。'
  '★ 只追加不改写。HR 问"这个 21 是谁改的"，查这张表就是答案。';

-- ---------------------------------------------------------------------------
-- 3. 生成 / 刷新（幂等；已确认的跳过）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_att_period_build(
  p_period varchar, p_entity bigint, p_by varchar)
RETURNS TABLE (built int, skipped_confirmed int, people int)
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_end date;
  e record;
  a record;
  v_personal numeric(6,2);
  v_absent numeric(6,2);
  r record;
BEGIN
  IF p_period !~ '^\d{4}-(0[1-9]|1[0-2])$' THEN
    RAISE EXCEPTION 'E_PERIOD_INVALID: 期间必须是 YYYY-MM（收到 %）', p_period;
  END IF;
  v_end := (to_date(p_period || '-01','YYYY-MM-DD') + interval '1 month - 1 day')::date;

  built := 0; skipped_confirmed := 0; people := 0;

  FOR e IN
    SELECT em.person_id, em.legal_entity_id
      FROM public.employment em
     WHERE em.legal_entity_id = p_entity
       AND daterange(em.hire_date, em.leave_date, '[]') @> v_end
     ORDER BY em.person_id
  LOOP
    people := people + 1;

    SELECT * INTO r FROM public.att_period_report x
     WHERE x.period = p_period AND x.person_id = e.person_id;

    -- ★ 已确认的不动。"再汇总一次"不该能改掉 HR 已经认可的数字 ——
    --   那正是"最终数字"与"汇总"的区别。要改必须显式 reopen。
    IF r.id IS NOT NULL AND r.status = 'confirmed' THEN
      skipped_confirmed := skipped_confirmed + 1;
      CONTINUE;
    END IF;

    SELECT * INTO a FROM public.fn_att_person_period(e.person_id, p_period);
    SELECT COALESCE(public.fn_leave_approved_days(e.person_id, p_period, 'PERSONAL'), 0)
      INTO v_personal;
    -- 旷工 = 应出勤 − 实出勤 − 请假（不小于 0）。这只是**生成时的估算**，
    -- HR 可以改：现实里"没来"常被更正成"调休"或"外出办事"。
    v_absent := GREATEST(a.work_days - a.present_days - a.leave_days, 0);

    INSERT INTO public.att_period_report AS t
      (period, person_id, legal_entity_id, work_days, calendar_days, roster_days,
       present_days, leave_days, personal_leave_days, absent_days,
       work_hours, ot_hours, workdays_source, status, note, built_at, updated_at)
    VALUES
      (p_period, e.person_id, e.legal_entity_id, a.work_days, a.calendar_days, a.roster_days,
       a.present_days, a.leave_days, v_personal, v_absent,
       a.work_hours, a.ot_hours, a.workdays_source, 'draft', NULL, now(), now())
    ON CONFLICT (period, person_id) DO UPDATE
      SET work_days = EXCLUDED.work_days,
          calendar_days = EXCLUDED.calendar_days,
          roster_days = EXCLUDED.roster_days,
          present_days = EXCLUDED.present_days,
          leave_days = EXCLUDED.leave_days,
          -- ★ 事假不覆盖：它可能已被 HR 调过。汇总口径的事假在 fn_leave_approved_days 里，
          --   这里只在该行还是"全 0 新建"时写入（见下面的条件）
          personal_leave_days = CASE WHEN t.updated_at = t.built_at
                                     THEN EXCLUDED.personal_leave_days
                                     ELSE t.personal_leave_days END,
          absent_days = EXCLUDED.absent_days,
          work_hours = EXCLUDED.work_hours,
          ot_hours = EXCLUDED.ot_hours,
          workdays_source = EXCLUDED.workdays_source,
          updated_at = now()
    WHERE t.status = 'draft';

    built := built + 1;
  END LOOP;

  RETURN NEXT;
END;
$$;

COMMENT ON FUNCTION fn_att_period_build IS
  '按期间汇总生成考勤月报（draft）。已 confirmed 的行跳过并计入 skipped_confirmed。'
  '幂等：可反复跑；跑一次不会改掉 HR 的手调结果（事假只在首次写入）。';

-- ---------------------------------------------------------------------------
-- 4. HR 调整一个字段（白名单 + 必须原因 + 留痕）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_att_period_set(
  p_report bigint, p_field varchar, p_value numeric, p_reason varchar, p_by varchar)
RETURNS numeric
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  r public.att_period_report%ROWTYPE;
  v_before numeric(10,2);
  v_reason varchar(200) := btrim(COALESCE(p_reason, ''));
BEGIN
  SELECT * INTO r FROM public.att_period_report WHERE id = p_report FOR UPDATE;
  IF r.id IS NULL THEN RAISE EXCEPTION 'E_ATT_REPORT_NOT_FOUND: %', p_report; END IF;
  IF r.status <> 'draft' THEN
    RAISE EXCEPTION 'E_ATT_REPORT_CONFIRMED: 月报已确认（%），要改请先重开并写明原因', r.period;
  END IF;
  IF length(v_reason) < 4 THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 调整必须写原因（至少 4 个字）—— 改了没理由等于没留痕';
  END IF;
  IF p_value IS NULL OR p_value < 0 THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 值不能为空或负数';
  END IF;

  -- ★ 白名单写死，不用动态 SQL：动态列名是 SQL 注入最经典的那扇门，
  --   而这里只有 9 个字段，逐个列出来成本远低于"以后某天有人拼错一个变量"。
  IF    p_field = 'work_days'           THEN v_before := r.work_days;
  ELSIF p_field = 'present_days'        THEN v_before := r.present_days;
  ELSIF p_field = 'leave_days'          THEN v_before := r.leave_days;
  ELSIF p_field = 'personal_leave_days' THEN v_before := r.personal_leave_days;
  ELSIF p_field = 'absent_days'         THEN v_before := r.absent_days;
  ELSIF p_field = 'work_hours'          THEN v_before := r.work_hours;
  ELSIF p_field = 'ot_hours'            THEN v_before := r.ot_hours;
  ELSE
    RAISE EXCEPTION 'E_ATT_FIELD: 不能调整字段「%」（可调：work_days/present_days/'
                    'leave_days/personal_leave_days/absent_days/work_hours/ot_hours）', p_field;
  END IF;

  -- 应出勤是折算分母，不能改成 0
  IF p_field = 'work_days' AND p_value <= 0 THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 应出勤必须大于 0（它是折算的分母）';
  END IF;

  IF p_field = 'work_days' THEN
    UPDATE public.att_period_report SET work_days = p_value, updated_at = now() WHERE id = p_report;
  ELSIF p_field = 'present_days' THEN
    UPDATE public.att_period_report SET present_days = p_value, updated_at = now() WHERE id = p_report;
  ELSIF p_field = 'leave_days' THEN
    UPDATE public.att_period_report SET leave_days = p_value, updated_at = now() WHERE id = p_report;
  ELSIF p_field = 'personal_leave_days' THEN
    UPDATE public.att_period_report SET personal_leave_days = p_value, updated_at = now() WHERE id = p_report;
  ELSIF p_field = 'absent_days' THEN
    UPDATE public.att_period_report SET absent_days = p_value, updated_at = now() WHERE id = p_report;
  ELSIF p_field = 'work_hours' THEN
    UPDATE public.att_period_report SET work_hours = p_value, updated_at = now() WHERE id = p_report;
  ELSIF p_field = 'ot_hours' THEN
    UPDATE public.att_period_report SET ot_hours = p_value, updated_at = now() WHERE id = p_report;
  END IF;

  -- 改了就留痕（一次调整一条，不合并：合并会把"改了三次"写成一次）
  INSERT INTO public.att_period_adjust(report_id, field_name, before_value, after_value,
                                      reason, adjusted_by)
  VALUES (p_report, p_field, v_before, p_value, v_reason, p_by);

  RETURN p_value;
END;
$$;

COMMENT ON FUNCTION fn_att_period_set IS
  'HR 调整月报的单个字段：白名单、必须原因、每次一条留痕。已确认的月报拒改。';

-- ---------------------------------------------------------------------------
-- 5. 确认 / 重开
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_att_period_confirm(
  p_period varchar, p_entity bigint, p_by varchar)
RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_n int;
BEGIN
  UPDATE public.att_period_report
     SET status = 'confirmed', confirmed_by = p_by, confirmed_at = now(), updated_at = now()
   WHERE period = p_period AND legal_entity_id = p_entity AND status = 'draft';
  GET DIAGNOSTICS v_n = ROW_COUNT;

  IF v_n = 0 THEN
    -- 区分"没有月报"与"都已经确认了"：两者的处置完全不同
    IF EXISTS (SELECT 1 FROM public.att_period_report
                WHERE period = p_period AND legal_entity_id = p_entity) THEN
      RAISE EXCEPTION 'E_ATT_ALREADY_CONFIRMED: % 的月报已全部确认', p_period;
    END IF;
    RAISE EXCEPTION 'E_ATT_NO_REPORT: % 还没有月报，先点"生成"', p_period;
  END IF;
  RETURN v_n;
END;
$$;

COMMENT ON FUNCTION fn_att_period_confirm IS
  '把一期月报整体确认为 confirmed（薪资从此只认这批数字）。';

CREATE OR REPLACE FUNCTION fn_att_period_reopen(
  p_period varchar, p_entity bigint, p_reason varchar, p_by varchar)
RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_n int; r record;
BEGIN
  IF length(btrim(COALESCE(p_reason,''))) < 4 THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 重开必须写原因（至少 4 个字）—— 它会把已认可的数字变成待改';
  END IF;

  -- 重开前先看这一期有没有已算出的工资条：有的话必须提醒，
  -- 因为"确认后重开再改"意味着"已经按旧数字发出的钱"与库里的数不一致了。
  IF EXISTS (SELECT 1 FROM public.payslip p JOIN public.pay_run pr ON pr.id = p.pay_run_id
              WHERE pr.period = p_period AND pr.kind = 'monthly') THEN
    RAISE EXCEPTION 'E_ATT_HAS_PAYSLIP: % 已经有工资条，重开会造成"发出去的钱"与"库里的数"不一致；'
                    '请先作废该期工资批次再重开', p_period;
  END IF;

  FOR r IN SELECT id FROM public.att_period_report
            WHERE period = p_period AND legal_entity_id = p_entity AND status = 'confirmed'
  LOOP
    -- 重开本身也留一条痕迹：字段记 '__reopen__'，原因就是 HR 写的理由
    INSERT INTO public.att_period_adjust(report_id, field_name, before_value, after_value,
                                        reason, adjusted_by)
    VALUES (r.id, '__reopen__', NULL, NULL, btrim(p_reason), p_by);
  END LOOP;

  UPDATE public.att_period_report
     SET status = 'draft', confirmed_by = NULL, confirmed_at = NULL, updated_at = now()
   WHERE period = p_period AND legal_entity_id = p_entity AND status = 'confirmed';
  GET DIAGNOSTICS v_n = ROW_COUNT;
  RETURN v_n;
END;
$$;

COMMENT ON FUNCTION fn_att_period_reopen IS
  '重开一期月报（confirmed → draft）。已出工资条时拒绝 —— 那会让"发出去的钱"与库里的数对不上。';

-- ---------------------------------------------------------------------------
-- 6. 薪资侧：有确认月报就用月报的数字
-- ---------------------------------------------------------------------------
-- ★ 返回列与 111 完全一致（8 列），算薪与公式不用改。
--   只多一个 workdays_source = 'report'，让人一眼看出"这个数是 HR 确认过的"。
CREATE OR REPLACE FUNCTION fn_att_person_period(p_person bigint, p_period varchar)
RETURNS TABLE (present_days numeric, work_days numeric, leave_days numeric,
               work_hours numeric, ot_hours numeric,
               calendar_days numeric, roster_days numeric, workdays_source varchar)
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE
  r record;
  v_start date;
  v_end date;
  v_std_h numeric(6,2);
  v_src   varchar(16);
BEGIN
  IF p_period !~ '^\d{4}-(0[1-9]|1[0-2])$' THEN
    RAISE EXCEPTION 'E_PERIOD_INVALID: 期间必须是 YYYY-MM（收到 %）', p_period;
  END IF;
  v_start := to_date(p_period || '-01', 'YYYY-MM-DD');
  v_end := (v_start + interval '1 month - 1 day')::date;

  -- ① 有 HR 确认过的月报 → 就是它。这是"薪资根据那张表上的最终数字做工资"。
  SELECT * INTO r FROM public.att_period_report x
   WHERE x.period = p_period AND x.person_id = p_person AND x.status = 'confirmed';
  IF r.id IS NOT NULL THEN
    present_days    := r.present_days;
    work_days       := r.work_days;
    leave_days      := r.leave_days;
    work_hours      := r.work_hours;
    ot_hours        := r.ot_hours;
    calendar_days   := r.calendar_days;
    roster_days     := r.roster_days;
    workdays_source := 'report';           -- 数字来自 HR 确认的月报，不是现算的
    RETURN NEXT;
    RETURN;
  END IF;

  -- ② 没有确认月报 → 实时汇总（等于 111 的行为，上线不改变任何人的工资）
  SELECT COALESCE(value_num, 8) INTO v_std_h
    FROM public.fn_policy_effective('PAY_WORK_HOURS_DAY', NULL, v_end);

  SELECT COALESCE(count(DISTINCT a.work_date), 0)::numeric,
         COALESCE(sum(a.work_hours), 0)::numeric,
         COALESCE(sum(GREATEST(a.work_hours - v_std_h, 0)), 0)::numeric
    INTO present_days, work_hours, ot_hours
    FROM public.attendance_daily_store a
   WHERE a.employee_id = p_person AND a.work_date BETWEEN v_start AND v_end
     AND a.work_hours > 0;

  IF present_days = 0 THEN
    SELECT count(DISTINCT (p.punch_at AT TIME ZONE public.app_tz())::date)::numeric
      INTO present_days
      FROM public.punch p
     WHERE p.employee_id = p_person
       AND (p.punch_at AT TIME ZONE public.app_tz())::date BETWEEN v_start AND v_end;
    IF present_days IS NULL THEN present_days := 0; END IF;
  END IF;

  calendar_days := public.fn_calendar_workdays(v_start, v_end);

  SELECT COALESCE(count(*), 0)::numeric INTO roster_days
    FROM public.roster_slot rs
    JOIN public.shift_def sd ON sd.code = rs.shift_code
   WHERE rs.employee_id = p_person
     AND rs.work_date BETWEEN v_start AND v_end
     AND NOT sd.is_rest;

  SELECT COALESCE(value_text, 'calendar') INTO v_src
    FROM public.fn_policy_effective('PAY_WORKDAYS_SOURCE', NULL, v_end);

  IF v_src = 'policy' THEN
    SELECT COALESCE(value_num, 21.75) INTO work_days
      FROM public.fn_policy_effective('PAY_DAYS_PER_MONTH', NULL, v_end);
    workdays_source := 'policy';
  ELSIF v_src = 'roster' AND roster_days > 0 THEN
    work_days := roster_days;
    workdays_source := 'roster';
  ELSE
    work_days := calendar_days;
    workdays_source := 'calendar';
  END IF;

  SELECT COALESCE(sum(public.fn_leave_approved_days(p_person, p_period, t.code)), 0)::numeric
    INTO leave_days
    FROM public.leave_type t;

  RETURN NEXT;
END;
$$;

COMMENT ON FUNCTION fn_att_person_period IS
  '某人某期的考勤口径。★ 优先取 HR 已确认的考勤月报（workdays_source=report）；'
  '没有确认月报时退回实时汇总（calendar/roster/policy）。'
  '这样"HR 确认过的数字"与"系统现算的数字"不会在同一期里打架。';

-- ---------------------------------------------------------------------------
-- 7. 事假扣款：优先用月报的事假天数
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_leave_deduction(p_employee bigint, p_period varchar)
RETURNS numeric
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT COALESCE(round(
           COALESCE(
             -- HR 在月报里改过事假天数 → 用改后的（那才是"最终数字"）
             (SELECT r.personal_leave_days FROM public.att_period_report r
               WHERE r.period = p_period AND r.person_id = p_employee
                 AND r.status = 'confirmed'),
             public.fn_leave_approved_days(p_employee, p_period, 'PERSONAL'))
           * (SELECT s.monthly_amount
                   / GREATEST((SELECT COALESCE(value_num, 21.75)
                                 FROM public.fn_policy_effective(
                                      'PAY_DAYS_PER_MONTH', NULL,
                                      (to_date(p_period || '-01','YYYY-MM-DD')
                                       + interval '1 month - 1 day')::date)), 1)
                FROM public.salary_standard s
                JOIN public.employment e ON e.id = s.employment_id
               WHERE e.person_id = p_employee
               ORDER BY s.effective_from DESC LIMIT 1), 2), 0);
$$;

