-- ============================================================================
-- 109_commission_rule.sql · 提成规则：按销售额自动算，不再逐月手敲
-- ----------------------------------------------------------------------------
-- 到 108 为止，提成是"一个人一个月一个数"，由人手工录。
-- 销售场景里这不是一个可持续的做法：10 个门店 30 个销售，每月靠手敲必错，
-- 而错了之后只能对账才发现 —— 那时候钱已经发了。
--
-- 这一版给三样东西：
--   ① **销售额**（commission_basis）：一个人一个月一个数，可录入可导入；
--   ② **规则**（commission_rule + tier）：阶梯累进，按岗位/部门/全局三级取用；
--   ③ **算**（fn_commission_calc）：算出金额，再写成一条 commission_record。
--
-- 三条判断：
--
-- ① **提成仍然落到 commission_record**，算薪只读那张表（approved 才发）。
--    规则引擎是"生成器"，不是"另一个工资来源" —— 否则同一个人的提成会有两处口径。
--
-- ② **阶梯是累进的**（分段计费），不是"达到就全额按高档"。
--    全额跳档会让"多卖 1 元少拿 500"这种事真的发生，而销售一眼就能看出来。
--
-- ③ **规则按 岗位 → 部门 → 全局 取第一条**：越具体越优先。
--    同一层有多条启用规则就是配置错，直接拒（E_COMM_RULE_AMBIGUOUS）——
--    让系统挑一个"看起来合理"的，等于把口径问题藏起来。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 销售额
-- ---------------------------------------------------------------------------
CREATE TABLE commission_basis (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id    bigint NOT NULL REFERENCES person(id),
  period       varchar(7) NOT NULL,
  sales_amount numeric(14,2) NOT NULL CHECK (sales_amount >= 0),
  note         varchar(200),
  updated_by   varchar(64) NOT NULL DEFAULT 'system',
  updated_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_cb_period CHECK (period ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  CONSTRAINT uk_cb_person_period UNIQUE (person_id, period)
);

COMMENT ON TABLE commission_basis IS
  '销售额：一个人一个月一个数。提成规则拿它算钱 —— 规则不是凭空的，得有一个基数。';

-- ---------------------------------------------------------------------------
-- 2. 规则与阶梯
-- ---------------------------------------------------------------------------
CREATE TABLE commission_rule (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           varchar(32) NOT NULL UNIQUE,
  name           varchar(96) NOT NULL,
  scope_org      bigint REFERENCES org_unit(id),
  scope_position bigint REFERENCES position(id),
  is_active      boolean NOT NULL DEFAULT true,
  sort_order     int NOT NULL DEFAULT 100,
  created_by     varchar(64) NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE commission_rule_tier (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rule_id     bigint NOT NULL REFERENCES commission_rule(id) ON DELETE CASCADE,
  from_amount numeric(14,2) NOT NULL CHECK (from_amount >= 0),
  to_amount   numeric(14,2),
  rate        numeric(6,4) NOT NULL CHECK (rate >= 0 AND rate <= 1),
  CONSTRAINT ck_crt_span CHECK (to_amount IS NULL OR to_amount > from_amount),
  CONSTRAINT uk_crt_from UNIQUE (rule_id, from_amount)
);

COMMENT ON TABLE commission_rule_tier IS
  '阶梯：from_amount 起、to_amount 止（NULL = 无上限），rate 是该段的费率。'
  '累进计算（分段计费），不是达到就全额跳档 —— 全额跳档会让"多卖 1 元少拿 500"真的发生。';

-- ---------------------------------------------------------------------------
-- 3. 算：找规则 → 累进 → 金额
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_commission_rule_of(p_person bigint, p_on date)
RETURNS bigint
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE
  v_org bigint; v_pos bigint; v_rule bigint; v_n int;
BEGIN
  -- 这个人当前的组织与岗位（岗位优先，其次部门，最后全局）
  SELECT a.org_id INTO v_org FROM public.employee_org_assignment a
   WHERE a.employee_id = p_person AND a.dim_code = 'attendance_org' AND a.valid_to IS NULL
   ORDER BY a.valid_from DESC LIMIT 1;
  SELECT pp.position_id INTO v_pos FROM public.person_position pp
   WHERE pp.person_id = p_person AND daterange(pp.valid_from, pp.valid_to, '[]') @> p_on
   ORDER BY pp.valid_from DESC LIMIT 1;

  IF v_pos IS NOT NULL THEN
    SELECT count(*), min(id) INTO v_n, v_rule FROM public.commission_rule
     WHERE is_active AND scope_position = v_pos;
    IF v_n > 1 THEN
      RAISE EXCEPTION 'E_COMM_RULE_AMBIGUOUS: 岗位 % 有 % 条启用的提成规则，请只留一条', v_pos, v_n;
    END IF;
    IF v_n = 1 THEN RETURN v_rule; END IF;
  END IF;

  IF v_org IS NOT NULL THEN
    SELECT count(*), min(id) INTO v_n, v_rule FROM public.commission_rule r
     WHERE r.is_active AND r.scope_org IS NOT NULL
       AND (SELECT path FROM public.org_unit WHERE id = r.scope_org)
           = (SELECT path FROM public.org_unit WHERE id = v_org);
    IF v_n > 1 THEN
      RAISE EXCEPTION 'E_COMM_RULE_AMBIGUOUS: 部门 % 有 % 条启用的提成规则，请只留一条', v_org, v_n;
    END IF;
    IF v_n = 1 THEN RETURN v_rule; END IF;
  END IF;

  SELECT count(*), min(id) INTO v_n, v_rule FROM public.commission_rule
   WHERE is_active AND scope_position IS NULL AND scope_org IS NULL;
  IF v_n > 1 THEN
    RAISE EXCEPTION 'E_COMM_RULE_AMBIGUOUS: 全局有 % 条启用的提成规则，请只留一条', v_n;
  END IF;
  RETURN v_rule;   -- 可能为 NULL：没有规则就不算提成
END;
$$;

COMMENT ON FUNCTION fn_commission_rule_of IS
  '取适用的提成规则：岗位 → 同部门 → 全局，越具体越优先。'
  '同一层多于一条就报 E_COMM_RULE_AMBIGUOUS —— 让系统挑一个"看起来合理"的等于把口径问题藏起来。';

CREATE OR REPLACE FUNCTION fn_commission_calc(p_person bigint, p_period varchar)
RETURNS numeric
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE
  v_sales numeric(14,2);
  v_rule bigint;
  v_on date;
  v_amt numeric(14,2);
BEGIN
  SELECT sales_amount INTO v_sales FROM public.commission_basis
   WHERE person_id = p_person AND period = p_period;
  IF v_sales IS NULL THEN RETURN 0; END IF;   -- 没录销售额 = 本期没有提成，不是错误

  v_on := (to_date(p_period || '-01','YYYY-MM-DD') + interval '1 month - 1 day')::date;
  v_rule := public.fn_commission_rule_of(p_person, v_on);
  IF v_rule IS NULL THEN RETURN 0; END IF;

  -- 累进：每段只对"落在这一段里的那部分"计费
  SELECT COALESCE(sum(
           (LEAST(v_sales, COALESCE(t.to_amount, v_sales)) - t.from_amount) * t.rate
         ), 0)
    INTO v_amt
    FROM public.commission_rule_tier t
   WHERE t.rule_id = v_rule AND v_sales > t.from_amount;

  RETURN round(GREATEST(v_amt, 0), 2);
END;
$$;

COMMENT ON FUNCTION fn_commission_calc IS
  '按销售额与阶梯算提成（累进）。没有销售额或没有适用规则时返回 0 —— '
  '这两种都是"本期没有提成"，不是错误。';

/**
 * 算出来并写成一条 commission_record（status=approved，算薪直接可用）。
 * 已有同人同期的 approved 记录时**覆盖金额**而不是新增：
 * 同一期两条提成会让算薪把它加两遍。
 */
CREATE OR REPLACE FUNCTION fn_commission_apply(p_person bigint, p_period varchar,
                                               p_by varchar DEFAULT 'system')
RETURNS numeric
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_amt numeric(12,2); v_id bigint;
BEGIN
  v_amt := public.fn_commission_calc(p_person, p_period);
  IF v_amt <= 0 THEN RETURN 0; END IF;

  SELECT id INTO v_id FROM public.commission_record
   WHERE person_id = p_person AND period = p_period AND status = 'approved'
   ORDER BY id DESC LIMIT 1;
  IF v_id IS NOT NULL THEN
    UPDATE public.commission_record SET amount = v_amt, basis = '按提成规则自动计算'
     WHERE id = v_id;
  ELSE
    INSERT INTO public.commission_record(person_id, period, amount, basis, status, created_by)
    VALUES (p_person, p_period, v_amt, '按提成规则自动计算', 'approved', p_by);
  END IF;
  RETURN v_amt;
END;
$$;

COMMENT ON FUNCTION fn_commission_apply IS
  '按规则算提成并落成 commission_record（覆盖同期已有的一条，不是新增）。'
  '同期两条会让算薪把它加两遍。';

