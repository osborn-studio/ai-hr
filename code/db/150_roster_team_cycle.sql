-- ============================================================================
-- 150_roster_team_cycle.sql · 班组排班 + 周期排班（白皮书 2.2.2 / 2.2.5）
-- ----------------------------------------------------------------------------
-- 前面四轮（145 排班写入、148 划线、149 规则）做的都是"一个人、一天、一个班"。
-- 而门店真实的排班动作是**成批**的，产品为此有两个入口：
--
--   2.2.2 班组排班：把人先分成组（早班组 / 后厨组 / 收银组），
--         然后"给这一组排今天的早班"——一次点，全组落。
--         没有班组，排一个 12 人的早班要点 12 下，且每点一下都要重新想
--         "这个人在不在这个组"。这个"想"就是错排的来源。
--
--   2.2.5 周期排班：把"第 1 天早、第 2 天早、第 3 天休"这种循环存成一个模板，
--         然后对某个人铺一段日期（一个月、一个季度）。餐饮的班本来就是循环的，
--         不存模板就只能一周一周手工重复，而手工重复的第二次开始就会漂。
--
-- ★ 四条落库时的取舍，每条都有代价，写在这里：
--
--   ① **一个人只能在一个班组**（产品原话"以最后更新的班组为准"）。
--      所以加人时若他已在别的组，是**移动**，不是拒绝：门店真实动作是
--      "把小王从早班组调到收银组"，如果这里报错，人就永远调不过去，
--      操作员最后会去删组重建 —— 而那会把整组的历史关系一起丢掉。
--      移动是 UPDATE 一行（唯一索引保证只有一行），旧组的其他成员一个不动。
--
--   ② **班组不承载工时**。它只是"排班时的一次选择"，工时仍然只能由
--      schedule_segment 算。把组也当成工时来源，就有了第二条算薪口径。
--
--   ③ **周期铺排必须"部分成功"**。一次铺 30 天，第 17 天撞上已锁定的班，
--      整批回滚的话，操作员会以为是"系统坏了"而重试；
--      重试还是同一处失败 —— 于是他会改日期绕过去，绕过去的那几天就漏排了。
--      所以：**每天独立判、失败只跳过并留原因，不整体失败**。
--      代价是"部分成功"必须被看见 —— 函数返回 skipped 与原因，页面要显示，
--      否则它和"全成功"长得一样。
--
--   ④ **跳过规则按产品原话实现三条**：当日已请假 / 当日已锁定 / 跨店借调在外。
--      规则放在这里而不是服务层：服务层可以被别的入口绕过（MCP、批量导入），
--      而"给请假的人排了班"在页面上看起来完全正常。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 班组：一个组织下的一组人
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS roster_team (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       varchar(96) NOT NULL,
  org_id     bigint      NOT NULL,               -- 门店/区域的 org_unit.id
  created_by varchar(64) NOT NULL DEFAULT 'system',
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 同一家店不许有两个同名组：重名之后"给早班组排班"这句话就指不到具体一组，
-- 而操作员会以为排的是自己刚才建的那个。
CREATE UNIQUE INDEX IF NOT EXISTS ux_rt_org_name ON roster_team (org_id, name);
CREATE INDEX IF NOT EXISTS ix_rt_org ON roster_team (org_id);

COMMENT ON TABLE roster_team IS
  '班组（150）：一个组织下的一组人，用于"整组排班"。'
  '★ 它**不承载工时** —— 工时的唯一来源仍是 schedule_segment；'
  '把班组也当工时来源就等于多出第二条算薪口径。';

CREATE TABLE IF NOT EXISTS roster_team_member (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id     bigint NOT NULL REFERENCES roster_team(id) ON DELETE CASCADE,
  employee_id bigint NOT NULL,                   -- person.id
  added_by    varchar(64) NOT NULL DEFAULT 'system',
  joined_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uk_rtm_team UNIQUE (team_id, employee_id)
);

-- ★★ 全局一人一组：`UNIQUE (employee_id) WHERE 1=1`。
--   写成部分索引是为了让"部分"这件事在 DDL 里可见（产品要的是全局唯一，
--   没有第二个条件），而不是一条看起来能加条件的普通唯一约束。
--   为什么不是 UNIQUE(team_id, employee_id) 就够：那允许一个人同时在三个组，
--   于是"给早班组排班"会把收银组的人也排上早班，而两个组都排同一天时
--   第二组直接撞 fn_roster_assign 的重叠校验 —— 报错指向"时段重叠"，
--   真正的原因（一个人两个组）根本看不出来。
CREATE UNIQUE INDEX IF NOT EXISTS ux_rtm_one_team ON roster_team_member (employee_id) WHERE 1 = 1;
CREATE INDEX IF NOT EXISTS ix_rtm_team ON roster_team_member (team_id);

COMMENT ON TABLE roster_team_member IS
  '班组成员（150）。★ 全局一人一组（ux_rtm_one_team）：产品原话是"以最后更新的班组为准"，'
  '所以加人时若已在别的组，是把这一行 UPDATE 过去（移动），不是拒绝 —— '
  '拒绝会让人永远调不过组，操作员最后会删组重建，把整组关系一起丢掉。';

-- ---------------------------------------------------------------------------
-- 2. 建组
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_team_create(
  p_name varchar, p_org bigint, p_by varchar
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_name varchar(96) := btrim(COALESCE(p_name, ''));
  v_id   bigint;
BEGIN
  IF v_name = '' THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 班组名称必填';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.org_unit o WHERE o.id = p_org) THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 组织 % 不存在（班组建在门店/区域上）', p_org;
  END IF;

  BEGIN
    INSERT INTO public.roster_team(name, org_id, created_by)
    VALUES (v_name, p_org, COALESCE(NULLIF(btrim(p_by), ''), 'system'))
    RETURNING id INTO v_id;
  EXCEPTION WHEN unique_violation THEN
    -- 重名不静默返回旧组：操作员以为自己建了个新组，往里加人时
    -- 才发现组里已经有三个陌生人 —— 那是"改名"还是"加错了"，他分不清。
    RAISE EXCEPTION 'E_ROSTER_BAD_STATE: 组织 % 下已有同名班组「%」，换个名字或直接往里加人',
      p_org, v_name;
  END;

  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_team_create IS
  '建班组（150）。同组织重名拒（E_ROSTER_BAD_STATE）：重名之后"给早班组排班"指不到具体哪一组。';

-- ---------------------------------------------------------------------------
-- 3. 加人：一个人只在一个组 —— 已在别组就是"移动"
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_team_add(
  p_team bigint, p_employees bigint[], p_by varchar
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_by   varchar(64) := COALESCE(NULLIF(btrim(p_by), ''), 'system');
  v_emp  bigint;
  v_n    int := 0;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.roster_team t WHERE t.id = p_team) THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 班组 % 不存在', p_team;
  END IF;
  IF p_employees IS NULL OR cardinality(p_employees) = 0 THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 至少给一个人（person.id 数组）';
  END IF;

  FOREACH v_emp IN ARRAY p_employees LOOP
    -- ★ 与 fn_roster_assign 同一条理由：人必须真的在库里有任职。
    --   不校验的话，随便一个 id 都能进组，之后整组排班时那一条会静默失败，
    --   而"12 个人排了 11 个"在页面上看不出来。
    IF NOT EXISTS (SELECT 1 FROM public.employment em WHERE em.person_id = v_emp) THEN
      RAISE EXCEPTION 'E_ROSTER_NO_EMPLOYEE: 人 % 在库里没有任何任职记录', v_emp;
    END IF;

    -- ★ 移动语义：UPDATE 到目标组（唯一索引保证这个人只有一行）。
    --   UPDATE 而不是 DELETE+INSERT：joined_at 保留"第一次进组"的时间，
    --   而这一列是"这人什么时候开始归这个组管"的依据 —— 删了再插就没有了。
    UPDATE public.roster_team_member m
       SET team_id = p_team, added_by = v_by, joined_at = now()
     WHERE m.employee_id = v_emp;

    IF NOT FOUND THEN
      INSERT INTO public.roster_team_member(team_id, employee_id, added_by)
      VALUES (p_team, v_emp, v_by);
    END IF;

    v_n := v_n + 1;
  END LOOP;

  RETURN v_n;
END;
$$;

COMMENT ON FUNCTION fn_team_add IS
  '往班组加人（150），返回本次落库的人数。★ 一人一组：已在别组的人是被**移过来**'
  '（UPDATE 那一行，保留 joined_at），不是报错 —— 拒绝会让人永远调不过组。';

-- ---------------------------------------------------------------------------
-- 4. 整组排班：给全组某天排同一个班次
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_team_assign(
  p_team bigint, p_date date, p_shift varchar, p_store bigint, p_by varchar
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_emp  bigint;
  v_ok   int := 0;
  v_skip int := 0;
  v_msg  text;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.roster_team t WHERE t.id = p_team) THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 班组 % 不存在', p_team;
  END IF;
  -- 空组不静默返回 0：操作员点完"排班"什么都没发生，会以为按钮坏了。
  IF NOT EXISTS (SELECT 1 FROM public.roster_team_member m WHERE m.team_id = p_team) THEN
    RAISE EXCEPTION 'E_ROSTER_EMPTY: 班组 % 里还没有人，先加人再排班', p_team;
  END IF;
  -- 班次先验一次：落在循环外的话，异常会被下面的 WHEN OTHERS 吞成"跳过"，
  -- 于是"班次码写错了"会表现成"全组都跳过了"，而原因是同一句。
  IF NOT EXISTS (SELECT 1 FROM public.shift_def s WHERE s.code = p_shift) THEN
    RAISE EXCEPTION 'E_ROSTER_SHIFT: 班次 % 不存在', p_shift;
  END IF;

  FOR v_emp IN SELECT m.employee_id FROM public.roster_team_member m
                WHERE m.team_id = p_team ORDER BY m.employee_id
  LOOP
    BEGIN
      -- 跨店原因给一句固定的：班组排班的门店就是调用方给的门店，
      -- 这次排班本身就是"给这家店用人"的承诺，不需要每个人再问一遍。
      PERFORM public.fn_roster_assign(v_emp, p_date, p_shift, p_store,
                                      '班组统一排班', COALESCE(p_by, 'system'));
      v_ok := v_ok + 1;
    EXCEPTION WHEN OTHERS THEN
      -- ★ 一个人失败不能拖垮整组：12 个人里有 1 个已锁定，
      --   整批回滚的结果是"一次都没排上"，而他会重试、再失败、再重试。
      --   跳过 + 计数，让调用方看到"11 成 1 跳"，然后单独处理那一个人。
      v_skip := v_skip + 1;
      v_msg  := split_part(SQLERRM, E'\n', 1);
      RAISE NOTICE '班组 % 排班跳过 person % @ %：%', p_team, v_emp, p_date, v_msg;
    END;
  END LOOP;

  RETURN v_ok;
END;
$$;

COMMENT ON FUNCTION fn_team_assign IS
  '给全组某天排同一个班次（150），返回成功条数，内部逐人调 fn_roster_assign。'
  '★ 单人失败只跳过、不整体回滚（已锁定/重叠/规则超限都算）—— '
  '否则 12 人里 1 个失败就是"一次都没排上"，操作员会重试到放弃。'
  '调用方要用"组员数 - 返回数"把跳过的量显示出来，不然部分成功和全成功长得一样。';

-- ---------------------------------------------------------------------------
-- 5. 周期：把"第 N 天什么班"存成模板
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS roster_cycle (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       varchar(96) NOT NULL,
  org_id     bigint      NOT NULL,
  days       int         NOT NULL,
  -- [{"day":1,"shift":"EARLY"},{"day":2,"shift":"EARLY"},{"day":3,"shift":"REST"}]
  pattern    jsonb       NOT NULL,
  created_by varchar(64) NOT NULL DEFAULT 'system',
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_rc_days    CHECK (days BETWEEN 2 AND 31),
  -- 结构校验只做到"是数组"：day 是否连续、班次是否存在要看 shift_def，
  -- 那是 CHECK 够不着的东西（CHECK 里不能查别的表），放在 fn_cycle_set 里。
  CONSTRAINT ck_rc_pattern CHECK (jsonb_typeof(pattern) = 'array'
                                  AND jsonb_array_length(pattern) >= 2)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_rc_org_name ON roster_cycle (org_id, name);

COMMENT ON TABLE roster_cycle IS
  '排班周期模板（150）：days = 循环长度，pattern 是 [{day,shift}] 的数组，day 从 1 到 days。'
  '存模板而不是每次现场填，是因为餐饮的班本来就是循环的 —— 手工重复的第二次开始就会漂。';

-- ---------------------------------------------------------------------------
-- 6. 存/改模板：新增与覆盖同一入口
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_cycle_set(
  p_id bigint, p_name varchar, p_org bigint, p_pattern jsonb, p_by varchar
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_name  varchar(96) := btrim(COALESCE(p_name, ''));
  v_days  int;
  v_cnt   int;
  v_dist  int;
  v_cmn   int;
  v_cmx   int;
  v_bad   text;
  v_id    bigint := p_id;
  v_n     int;
BEGIN
  IF v_name = '' THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 周期名称必填';
  END IF;
  IF p_pattern IS NULL OR jsonb_typeof(p_pattern) <> 'array' THEN
    RAISE EXCEPTION 'E_ARG_INVALID: pattern 必须是数组，形如 [{"day":1,"shift":"EARLY"}]';
  END IF;

  -- ★ 先把"形状"验干净再 cast：`(e->>'day')::int` 碰上 "第一天" 会抛 22P02，
  --   而 22P02 不是业务码，映射层会把它当成 500 服务故障 ——
  --   操作员看到"系统错误"，实际只是他把 1 写成了中文。
  IF EXISTS (
    SELECT 1 FROM jsonb_array_elements(p_pattern) e
     WHERE jsonb_typeof(e -> 'day')   IS DISTINCT FROM 'number'
        OR jsonb_typeof(e -> 'shift') IS DISTINCT FROM 'string'
  ) THEN
    RAISE EXCEPTION 'E_ARG_INVALID: pattern 的每一项都要有数字 day 与字符串 shift';
  END IF;

  SELECT count(*)::int, count(DISTINCT (e ->> 'day')::int),
         min((e ->> 'day')::int), max((e ->> 'day')::int)
    INTO v_cnt, v_dist, v_cmn, v_cmx
    FROM jsonb_array_elements(p_pattern) e;

  v_days := v_cmx;

  -- day 集合必须正好是 1..days：有空洞 = 那几天没有班（是"没排"不是"排休"），
  -- 有重复 = 一天两个班（谁赢取决于数组顺序，那是静默的错）。
  IF v_cmn <> 1 OR v_dist <> v_cnt OR v_cmx <> v_cnt THEN
    RAISE EXCEPTION 'E_ARG_INVALID: pattern 的 day 必须从 1 连续到 %（不能缺、不能重）', v_cmx;
  END IF;
  IF v_days < 2 OR v_days > 31 THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 周期长度取 2..31 天，当前 % 天', v_days;
  END IF;

  SELECT string_agg(DISTINCT e ->> 'shift', ', ') INTO v_bad
    FROM jsonb_array_elements(p_pattern) e
   WHERE NOT EXISTS (SELECT 1 FROM public.shift_def s WHERE s.code = e ->> 'shift');
  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION 'E_ROSTER_SHIFT: 班次 % 不存在（见 shift_def）', v_bad;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.org_unit o WHERE o.id = p_org) THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 组织 % 不存在', p_org;
  END IF;

  BEGIN
    IF v_id IS NULL THEN
      INSERT INTO public.roster_cycle(name, org_id, days, pattern, created_by)
      VALUES (v_name, p_org, v_days, p_pattern,
              COALESCE(NULLIF(btrim(p_by), ''), 'system'))
      RETURNING id INTO v_id;
    ELSE
      UPDATE public.roster_cycle
         SET name = v_name, org_id = p_org, days = v_days, pattern = p_pattern
       WHERE id = v_id;
      GET DIAGNOSTICS v_n = ROW_COUNT;
      IF v_n = 0 THEN
        RAISE EXCEPTION 'E_ARG_INVALID: 周期 % 不存在（不传 id 是新建）', p_id;
      END IF;
    END IF;
  EXCEPTION WHEN unique_violation THEN
    RAISE EXCEPTION 'E_ROSTER_BAD_STATE: 组织 % 下已有同名周期「%」', p_org, v_name;
  END;

  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_cycle_set IS
  '新建或覆盖排班周期（150）：p_id 为空则新建，否则整条覆盖。'
  '校验三件事：day 集合必须正好 1..days（缺/重都拒）、days 取 2..31、每个 shift 在 shift_def 里存在。'
  'day 有重复时**不取最后一个**：谁赢取决于数组顺序，那是静默的错。';

-- ---------------------------------------------------------------------------
-- 7. 套用周期：从 from_date 起循环铺到 to_date
-- ---------------------------------------------------------------------------
-- 返回一行汇总：planned = 排上的天数，skipped = 跳过的天数，
-- skip_reason = 逐日原因（"07-03 已请假；07-07 已锁定"）。没有跳过就是 NULL。
--
-- ★ 为什么只回一行而不是一天一行：套用是一次"批量动作"，调用方要回答的
--   第一个问题是"成了几天、没成几天、为什么"。逐日明细在 schedule 与
--   skip_reason 里都能查回来，而一个 90 行的返回体会让页面自己去数。
CREATE OR REPLACE FUNCTION fn_cycle_apply(
  p_cycle bigint, p_employee bigint, p_from date, p_to date,
  p_store bigint, p_by varchar
) RETURNS TABLE (planned int, skipped int, skip_reason text)
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_days   int;
  v_pattern jsonb;
  v_by     varchar(64) := COALESCE(NULLIF(btrim(p_by), ''), 'system');
  v_day    date;
  v_idx    int;
  v_shift  varchar;
  v_cost   bigint;
  v_plan   int := 0;
  v_skip   int := 0;
  v_why    text[] := ARRAY[]::text[];
  v_r      text;
BEGIN
  SELECT c.days, c.pattern INTO v_days, v_pattern
    FROM public.roster_cycle c WHERE c.id = p_cycle;
  IF v_days IS NULL THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 周期 % 不存在', p_cycle;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.employment em WHERE em.person_id = p_employee) THEN
    RAISE EXCEPTION 'E_ROSTER_NO_EMPLOYEE: 人 % 在库里没有任何任职记录', p_employee;
  END IF;
  IF p_from IS NULL OR p_to IS NULL OR p_to < p_from THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 起止日期不合法（to_date 不能早于 from_date）';
  END IF;
  -- 一段最多铺一年：再多就不是"排班"而是"导入"，而 366 天之后
  -- 规则、班次、在职状态几乎一定都变过，铺出来的是废数据。
  IF p_to - p_from > 366 THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 一次最多铺 366 天';
  END IF;

  v_day := p_from;
  WHILE v_day <= p_to LOOP
    v_idx := ((v_day - p_from) % v_days) + 1;

    SELECT e ->> 'shift' INTO v_shift
      FROM jsonb_array_elements(v_pattern) e
     WHERE (e ->> 'day')::int = v_idx
     LIMIT 1;

    -- ① 当日已请假（只认审批通过的：pending 还没批，按它跳过等于
    --    让一张没人审的单子把整条排班挡住）
    IF EXISTS (SELECT 1 FROM public.leave_request lr
                WHERE lr.employee_id = p_employee AND lr.status = 'approved'
                  AND daterange(lr.date_from, lr.date_to, '[]') @> v_day) THEN
      v_skip := v_skip + 1;
      v_why  := v_why || (to_char(v_day, 'MM-DD') || ' 已请假');

    -- ② 当日已锁定：锁是门店签过的字，铺上去只会被 fn_roster_assign 拒。
    ELSIF EXISTS (
      SELECT 1 FROM public.schedule s
        JOIN public.schedule_segment sg ON sg.schedule_id = s.id
        JOIN public.confirm_sheet cs ON cs.segment_id = sg.id
       WHERE s.employee_id = p_employee AND s.work_date = v_day
         AND cs.status = 'locked') THEN
      v_skip := v_skip + 1;
      v_why  := v_why || (to_char(v_day, 'MM-DD') || ' 已锁定');

    ELSE
      -- ③ 跨店借调在外：当天的成本组织不是这家店，说明这个人借给别人用了。
      --    这里**跳过**而不是硬排：借调在外的人被原店排了班，
      --    结果是两边都以为他上班，而实际只有一份人。
      SELECT a.org_id INTO v_cost
        FROM public.employee_org_assignment a
       WHERE a.employee_id = p_employee AND a.dim_code = 'cost_org'
         AND daterange(a.valid_from, a.valid_to, '[]') @> v_day
       ORDER BY a.valid_from DESC LIMIT 1;

      IF v_cost IS NOT NULL AND v_cost <> p_store THEN
        v_skip := v_skip + 1;
        v_why  := v_why || (to_char(v_day, 'MM-DD') || ' 借调在外');

      ELSE
        BEGIN
          PERFORM public.fn_roster_assign(p_employee, v_day, v_shift, p_store,
                                          '周期铺排', v_by);
          v_plan := v_plan + 1;
        EXCEPTION WHEN OTHERS THEN
          -- ★ 不整体失败：铺 30 天第 17 天撞了重叠，回滚等于"一天都没排上"，
          --   操作员会重试 —— 还是同一处失败，然后他改日期绕过去，
          --   绕过去的那几天就永远漏排了。
          v_skip := v_skip + 1;
          v_r := split_part(SQLERRM, E'\n', 1);
          -- 去掉业务码前缀，页面上的原因栏不该出现 E_ROSTER_OVERLAP
          v_r := regexp_replace(v_r, '^E_[A-Z0-9_]+\s*:\s*', '');
          v_why := v_why || (to_char(v_day, 'MM-DD') || ' ' || left(v_r, 60));
        END;
      END IF;
    END IF;

    v_day := v_day + 1;
  END LOOP;

  planned    := v_plan;
  skipped    := v_skip;
  skip_reason := NULLIF(array_to_string(v_why, '；'), '');
  RETURN NEXT;
END;
$$;

COMMENT ON FUNCTION fn_cycle_apply IS
  '按周期给人铺一段日期（150）：从 p_from 起按 pattern 循环，每天调 fn_roster_assign。'
  '跳过规则（产品原话）：当日已请假（approved）/ 当日已锁定 / 跨店借调在外，'
  '以及 fn_roster_assign 拒掉的（重叠、规则超限）—— 都只跳过并记原因，'
  '**不整体失败**：一次铺 30 天不能因为第 17 天失败就全丢。'
  '返回一行汇总，skip_reason 是"MM-DD 原因；…"形式的逐日说明，没有跳过则为 NULL。';

