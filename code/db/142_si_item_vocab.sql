-- ============================================================================
-- 142_si_item_vocab.sql · 险种只有一个名字：在入口处归一
-- ----------------------------------------------------------------------------
-- 141 的社保申报表第一次跑真实数据，就抓到一件原来没人看得见的事：
--
--   某人的 si_policy.item 写成 `unemploy`，算薪**照扣了这笔钱**
--   （因为算社保时用的是 si_policy 里的比例，不看名字），
--   但工资条上**没有失业险这一行** —— 因为算薪里那串 CASE 只认 `unemployment`。
--
-- 后果有三层，一层比一层难发现：
--   ① 员工看工资条，明细里少了失业险，而实发少的钱是对的 —— 他以为自己被多扣了；
--   ② v_payslip_consistency 会红（明细之和 ≠ 应发 − 社保 − 个税），但那是个
--      需要人去读的视图；
--   ③ 申报表按险种列不出来（141 的 emp_missing 会点名，这就是它被发现的路径）——
--      而社保申报少一个险种，是要补申报的。
--
-- 根因不是哪一处写错了，是**同一个东西有两个名字**：
--   si_policy.item 用英文键（pension / unemploy / housing…），
--   payslip_item.item_code 用工资项（SI_PENSION / SI_UNEMPLOYMENT…），
--   而中间那张映射表在两个地方各写了一遍（141 的 fn_si_item_code 与算薪里的 CASE）。
--   两处映射迟早不同步，且不同步时**不报错**：钱照扣，行不写。
--
-- ★ 修法：在**入口**归一，而不是在出口补三种拼写。
--   si_policy 是人为录入的表，所以让写入时的值自动落成规范键（触发器），
--   存量数据同步改正。这样：
--     · 算薪那串 CASE 只需要认四个规范键（不需要改一行代码）；
--     · 141 的 fn_si_item_code 里的别名分支变成"兜底"，而不是唯一依靠；
--     · 以后再有人录 `housing`、`endowment`、`medicare`，也不会多出一个新险种。
--
-- ★ 不做的事：不合并"养老 vs 机关事业养老"这类**真实存在的两个险种**。
--   归一只处理拼写别名，不碰业务语义 —— 归一错了比不归一更糟。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 0. si_policy.id 补生成方式（第十次同一个坑）
-- ---------------------------------------------------------------------------
-- 012 写的是 `id bigint PRIMARY KEY`，没有 IDENTITY。种子与测试都写显式 id，
-- 所以从来没红过；而"补一条险种政策"是第一个**由人正常插入**它的路径，
-- 一插就是 23502 not-null on id —— 报错指向 id，看起来像数据缺失。
-- 与 064 给 sys_user_role / org_unit 补 IDENTITY 是同一条规矩：
-- **凡"会被 INSERT 的表"，主键一律给生成方式。**
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_attribute
                  WHERE attrelid = 'public.si_policy'::regclass
                    AND attname = 'id' AND attidentity <> '') THEN
    ALTER TABLE public.si_policy ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    -- 存量用的是显式 id，序列没被推过 —— 不 setval 的话下一条就撞 1
    PERFORM setval(pg_get_serial_sequence('public.si_policy', 'id'),
                   COALESCE((SELECT max(id) FROM public.si_policy), 1));
  END IF;
END $$;

-- ---------------------------------------------------------------------------
-- 1. 规范键
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_si_item_canon(p_item varchar)
RETURNS varchar
LANGUAGE sql IMMUTABLE
SET search_path = ''
AS $$
  SELECT CASE lower(btrim(COALESCE(p_item, '')))
           WHEN 'pension'      THEN 'pension'
           WHEN 'endowment'    THEN 'pension'        -- 养老金的另一种叫法
           WHEN 'medical'      THEN 'medical'
           WHEN 'medicare'     THEN 'medical'
           WHEN 'unemploy'     THEN 'unemployment'   -- ★ 就是这一条害的
           WHEN 'unemployment' THEN 'unemployment'
           WHEN 'injury'       THEN 'injury'
           WHEN 'maternity'    THEN 'maternity'
           WHEN 'housing'      THEN 'housing_fund'
           WHEN 'housing_fund' THEN 'housing_fund'
           WHEN 'fund'         THEN 'housing_fund'
           ELSE lower(btrim(COALESCE(p_item, '')))   -- 认不出的原样保留：不猜
         END::varchar;
$$;

COMMENT ON FUNCTION fn_si_item_canon IS
  '险种键归一：拼写别名 → 规范键，认不出的原样返回（不猜、不丢）。'
  '只做拼写归一，不做业务语义合并 —— 把两个真险种并成一个，比不归一更糟。';

-- ---------------------------------------------------------------------------
-- 2. 存量数据改正
-- ---------------------------------------------------------------------------
-- ★ 改之前先确认不会撞唯一键：某个城市某天如果同时存在 unemploy 与 unemployment
--   两条，改正就会撞 (city,item,effective_from)。那时**不静默删一条** ——
--   两条费率可能不同，删哪条都是替客户做决定。让它报错，人来定。
DO $$
DECLARE
  r record;
  v_dup int;
BEGIN
  FOR r IN
    SELECT DISTINCT city, item FROM public.si_policy
     WHERE item <> public.fn_si_item_canon(item)
  LOOP
    SELECT count(*)::int INTO v_dup
      FROM public.si_policy a
      JOIN public.si_policy b
        ON b.city = a.city AND b.effective_from = a.effective_from
       AND b.item = public.fn_si_item_canon(a.item)
     WHERE a.city = r.city AND a.item = r.item;

    IF v_dup > 0 THEN
      RAISE EXCEPTION 'E_SI_ITEM_DUP: % 在 % 同时存在别名与规范键的记录（% → %），'
        '费率可能不同，不能替你合并 —— 先人工核一遍再删掉多余的那条', 
        r.item, r.city, r.item, public.fn_si_item_canon(r.item);
    END IF;

    UPDATE public.si_policy
       SET item = public.fn_si_item_canon(item)
     WHERE city = r.city AND item = r.item;

    RAISE NOTICE '险种键归一：% → %（%）', r.item, public.fn_si_item_canon(r.item), r.city;
  END LOOP;
END $$;

-- ---------------------------------------------------------------------------
-- 3. 入口归一：以后写进来的值自动落成规范键
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_si_item_normalize() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  NEW.item := public.fn_si_item_canon(NEW.item);
  IF NEW.item IS NULL OR NEW.item = '' THEN
    RAISE EXCEPTION 'E_SI_ITEM_EMPTY: 险种键不能为空';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_si_item_normalize ON si_policy;
CREATE TRIGGER trg_si_item_normalize
  BEFORE INSERT OR UPDATE OF item ON si_policy
  FOR EACH ROW EXECUTE FUNCTION fn_si_item_normalize();

COMMENT ON FUNCTION fn_si_item_normalize IS
  'si_policy.item 写入时归一成规范键。在**入口**修正，比在出口兼容三种拼写可靠 —— '
  '出口兼容漏一处就是"钱扣了、行没写"，而那种错不报错。';

