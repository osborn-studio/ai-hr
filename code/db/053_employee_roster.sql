-- ============================================================================
-- 053_employee_roster.sql · 员工花名册：一个 HR 系统没有"员工列表"
-- ----------------------------------------------------------------------------
-- 到 052 为止，界面上能看考勤、工资条、审批、编制、招聘、绩效 —— 唯独
-- **没有一处能看"我们有哪些人"**。person / employment / employee_org_assignment
-- 三张表都在，可它们只被种子和入职函数写过，从来没有一个读的出口。
--
-- 这是"表在、门没有"的另一半：前面五次是**没有写入路径**，这次是**没有读取路径**。
-- 而它的失败形态更滑稽 —— 不是错，是"这个系统看起来没有员工"。
--
-- 三条判断：
--   ① **行闸照旧**：花名册按 cost_org 过滤，与其他读接口同一套临时表。
--      另开一条"看人"的判据，就会出现"看得到花名册、点进去看不到考勤"的错位。
--   ② **字段掩码照旧**：身份证是 fail-closed 的（003 的规矩：无配置即 masked）。
--      花名册是最容易"顺手 SELECT *"的地方，而 SELECT * 等于绕过字段权限。
--   ③ **在离职按 as_of 判**：不给"当前在职"这种说法 —— 同一个查询在跨月那天
--      会变成另一个答案，而报表口径必须能复现。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 0. person_profile 也补生成方式
-- ---------------------------------------------------------------------------
-- ★ Q14 只扫"被**函数** INSERT 的表"，而这张表是**种子**插的 ——
--   所以它一直没被扫出来。第一次想用无 id 的方式插它，就是
--   "null value in column id violates not-null"。
--   教训写在这里：Q14 的覆盖面是"函数插入"，**种子插入不覆盖**；
--   凡是"以后可能有别的插入方"的表，主键就该有生成方式。
ALTER TABLE person_profile ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

