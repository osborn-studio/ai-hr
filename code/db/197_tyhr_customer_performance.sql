CREATE FUNCTION fn_ty_perf_issue(code text,message text) RETURNS jsonb LANGUAGE sql IMMUTABLE SET search_path='' AS $$
  SELECT jsonb_build_array(jsonb_build_object('code',code,'message',message));
$$;

-- Unit-bearing, verified inputs only. No Excel formula text is executed.
CREATE FUNCTION fn_ty_perf_company_score(inputs jsonb,rules jsonb) RETURNS jsonb LANGUAGE plpgsql IMMUTABLE SET search_path='' AS $$
DECLARE issues jsonb='[]'; deductions jsonb='[]'; rule jsonb; inp jsonb; band jsonb; n numeric; d numeric; total numeric=0; hits integer; score numeric;
BEGIN
  IF rules->>'confirmed' IS DISTINCT FROM 'true' THEN issues=issues||public.fn_ty_perf_issue('RULE_UNCONFIRMED','方案口径尚未确认'); END IF;
  IF jsonb_typeof(rules->'metrics') IS DISTINCT FROM 'array' OR jsonb_array_length(rules->'metrics')=0 THEN
    issues=issues||public.fn_ty_perf_issue('METRIC_RULE_MISSING','缺少指标及扣分规则');
  ELSE
    FOR rule IN SELECT value FROM jsonb_array_elements(rules->'metrics') LOOP
      inp=inputs->(rule->>'code'); d=NULL;
      IF inp IS NULL OR inp->>'status' IS DISTINCT FROM 'verified' THEN
        issues=issues||public.fn_ty_perf_issue('INPUT_UNVERIFIED','指标 '||coalesce(rule->>'code','?')||' 缺失、源表错误或尚未核验'); CONTINUE;
      END IF;
      IF inp->>'unit' IS DISTINCT FROM rule->>'unit' OR coalesce(rule->>'unit','')='' THEN
        issues=issues||public.fn_ty_perf_issue('UNIT_CONFLICT','指标 '||(rule->>'code')||' 单位不一致'); CONTINUE;
      END IF;
      IF (inp->>'value') IS NULL OR (inp->>'value') !~ '^-?[0-9]+([.][0-9]+)?$' THEN
        issues=issues||public.fn_ty_perf_issue('VALUE_INVALID','指标 '||(rule->>'code')||' 不是有效数值'); CONTINUE;
      END IF;
      n=(inp->>'value')::numeric;
      IF rule->>'method'='target_attainment' THEN
        IF coalesce(inp->>'target','') !~ '^[0-9]+([.][0-9]+)?$' OR (inp->>'target')::numeric<=0 THEN
          issues=issues||public.fn_ty_perf_issue('TARGET_INVALID','预算/目标必须为正，零预算不可自动判定'); CONTINUE;
        END IF;
        n=n/(inp->>'target')::numeric;
      END IF;
      IF rule->>'method'='direct_deduction' THEN
        d=n;
      ELSIF rule->>'method' IN ('deduction_bands','target_attainment') AND jsonb_typeof(rule->'bands')='array' THEN
        hits=0;
        FOR band IN SELECT value FROM jsonb_array_elements(rule->'bands') LOOP
          IF (NOT band ? 'min' OR n>=(band->>'min')::numeric) AND (NOT band ? 'max' OR n<(band->>'max')::numeric) THEN
            d=(band->>'deduction')::numeric; hits=hits+1;
          END IF;
        END LOOP;
        IF hits<>1 THEN d=NULL; END IF;
      END IF;
      IF d IS NULL OR d<0 OR coalesce((rule->>'weight')::numeric,1)<0 THEN
        issues=issues||public.fn_ty_perf_issue('BAND_INVALID','指标 '||(rule->>'code')||' 阈值未覆盖、重叠或扣分无效'); CONTINUE;
      END IF;
      d=d*coalesce((rule->>'weight')::numeric,1); total=total+d;
      deductions=deductions||jsonb_build_array(jsonb_build_object('code',rule->>'code','observed',n,'deduction',d));
    END LOOP;
  END IF;
  IF jsonb_array_length(issues)=0 THEN
    score=greatest(coalesce((rules->>'score_floor')::numeric,0),coalesce((rules->>'score_base')::numeric,1)-total);
  END IF;
  RETURN jsonb_build_object('score',score,'deductions',deductions,'issues',issues);
EXCEPTION WHEN invalid_text_representation OR numeric_value_out_of_range THEN
  RETURN jsonb_build_object('score',NULL,'deductions',deductions,'issues',issues||public.fn_ty_perf_issue('RULE_NUMBER_INVALID','规则含无效数字'));
END; $$;

CREATE FUNCTION fn_ty_perf_rating(score numeric,bands jsonb) RETURNS jsonb LANGUAGE plpgsql IMMUTABLE SET search_path='' AS $$
DECLARE b jsonb; chosen jsonb; threshold numeric; best numeric;
BEGIN
  IF score IS NULL OR jsonb_typeof(bands) IS DISTINCT FROM 'array' THEN RETURN NULL; END IF;
  FOR b IN SELECT value FROM jsonb_array_elements(bands) LOOP
    threshold=(b->>'min_score')::numeric;
    IF threshold<=score AND (best IS NULL OR threshold>best) THEN chosen=b;best=threshold; END IF;
  END LOOP;
  IF chosen->>'grade' IS NULL OR chosen->>'factor' IS NULL OR (chosen->>'factor')::numeric<0 THEN RETURN NULL; END IF;
  RETURN chosen;
EXCEPTION WHEN invalid_text_representation OR numeric_value_out_of_range THEN RETURN NULL;
END; $$;

CREATE FUNCTION fn_ty_perf_calculate(cid bigint,actor bigint) RETURNS integer LANGUAGE plpgsql SET search_path='' AS $$
DECLARE c public.ty_perf_cycle%ROWTYPE; v integer; co record; pm record; pr record; m date; rules jsonb; scored jsonb; rating jsonb;
  inp public.ty_perf_company_metric%ROWTYPE; issues jsonb; score_issues jsonb; details jsonb; sc numeric; amt numeric; base numeric; factor numeric;
  deps bigint[]; total_weight numeric; months integer; n integer; r record; seen integer; lastrow public.ty_perf_person_month%ROWTYPE;
  monthly_amt numeric; alt_amt numeric; score_sum numeric; avg_score numeric; alt_base numeric; alt_rating jsonb; alt_rules jsonb; alt_issues jsonb;
BEGIN
  SELECT * INTO c FROM public.ty_perf_cycle WHERE id=cid FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'E_TY_NOT_FOUND: 考核周期不存在'; END IF;
  IF c.status='confirmed' THEN RAISE EXCEPTION 'E_TY_CONFLICT: 已确认周期不可重新计算'; END IF;
  IF NOT EXISTS(SELECT 1 FROM public.ty_perf_cycle_company WHERE cycle_id=cid) THEN RAISE EXCEPTION 'E_TY_ARGUMENT: 请先选择考核公司'; END IF;
  v=c.result_version+1;
  months=(extract(year FROM age(c.end_date,c.start_date))*12+extract(month FROM age(c.end_date,c.start_date)))::integer;
  FOR co IN SELECT company_id FROM public.ty_perf_cycle_company WHERE cycle_id=cid ORDER BY company_id LOOP
    FOR m IN SELECT generate_series(c.start_date,c.end_date-interval '1 month',interval '1 month')::date LOOP
      rules=c.rules||coalesce(c.rules->'company_overrides'->co.company_id::text,'{}')
        ||coalesce(c.rules->'month_overrides'->to_char(m,'YYYY-MM'),'{}')
        ||coalesce(c.rules->'company_overrides'->co.company_id::text->'month_overrides'->to_char(m,'YYYY-MM'),'{}');
      SELECT * INTO inp FROM public.ty_perf_company_metric WHERE cycle_id=cid AND company_id=co.company_id AND period=m;
      scored=public.fn_ty_perf_company_score(coalesce(inp.metrics,'{}'),rules); issues=scored->'issues'; sc=(scored->>'score')::numeric;
      IF inp.source_saved_score IS NOT NULL AND sc IS NOT NULL AND abs(sc-inp.source_saved_score)>coalesce((rules->>'score_tolerance')::numeric,0.0001) THEN
        issues=issues||public.fn_ty_perf_issue('SOURCE_SCORE_MISMATCH','重算分数与源表保存值不一致');
      END IF;
      rating=public.fn_ty_perf_rating(sc,rules->'rating_bands');
      IF rating IS NULL AND sc IS NOT NULL THEN issues=issues||public.fn_ty_perf_issue('RATING_RULE_MISSING','分数未匹配评级档位'); END IF;
      INSERT INTO public.ty_perf_result(cycle_id,result_version,kind,company_id,period,score,rating,factor,dependencies,issues,details)
      VALUES(cid,v,'company',co.company_id,m,sc,rating->>'grade',(rating->>'factor')::numeric,ARRAY[co.company_id],issues,
        jsonb_build_object('deductions',scored->'deductions','source_ref',inp.source_ref,'source_saved_score',inp.source_saved_score));
    END LOOP;
  END LOOP;
  FOR pm IN SELECT * FROM public.ty_perf_person_month WHERE cycle_id=cid ORDER BY person_id,period LOOP
    issues='[]'; details='{}'; sc=NULL; amt=NULL; factor=NULL; base=NULL; deps=ARRAY[pm.company_id];
    rules=c.rules;
    IF pm.score_source='company' THEN
      SELECT * INTO r FROM public.ty_perf_result WHERE cycle_id=cid AND result_version=v AND kind='company' AND company_id=pm.company_id AND period=pm.period;
      sc=r.score;
      IF jsonb_array_length(coalesce(r.issues,'[]'))>0 THEN issues=issues||public.fn_ty_perf_issue('COMPANY_SCORE_BLOCKED','归属公司该月绩效仍有阻断问题'); END IF;
      rules=rules||coalesce(c.rules->'company_overrides'->pm.company_id::text,'{}')
        ||coalesce(c.rules->'month_overrides'->to_char(pm.period,'YYYY-MM'),'{}')
        ||coalesce(c.rules->'company_overrides'->pm.company_id::text->'month_overrides'->to_char(pm.period,'YYYY-MM'),'{}');
    ELSE
      rules=rules||coalesce(c.rules->'month_overrides'->to_char(pm.period,'YYYY-MM'),'{}');
      IF rules->'management'->>'method' IS DISTINCT FROM 'weighted_company_scores' OR rules->'management'->>'confirmed' IS DISTINCT FROM 'true' THEN
        issues=issues||public.fn_ty_perf_issue('MANAGEMENT_RULE_UNCONFIRMED','管理责任聚合算法尚未确认');
      END IF;
      total_weight=0;sc=0;seen=0;
      FOR pr IN SELECT * FROM public.ty_perf_responsibility WHERE cycle_id=cid AND person_id=pm.person_id AND period=pm.period LOOP
        deps=array_append(deps,pr.company_id);total_weight=total_weight+pr.weight;seen=seen+1;
        SELECT * INTO r FROM public.ty_perf_result WHERE cycle_id=cid AND result_version=v AND kind='company' AND company_id=pr.company_id AND period=pm.period;
        IF pr.status<>'verified' OR r.score IS NULL OR jsonb_array_length(coalesce(r.issues,'[]'))>0 THEN
          issues=issues||public.fn_ty_perf_issue('RESPONSIBILITY_BLOCKED','责任范围、权重或公司绩效尚未核验');
        ELSE sc=sc+r.score*pr.weight; END IF;
      END LOOP;
      IF seen=0 OR abs(total_weight-1)>0.000001 THEN issues=issues||public.fn_ty_perf_issue('WEIGHT_SUM_INVALID','管理责任权重合计必须为1'); END IF;
      rules=rules||coalesce(rules->'management','{}');
    END IF;
    IF rules->>'confirmed' IS DISTINCT FROM 'true' THEN issues=issues||public.fn_ty_perf_issue('RULE_UNCONFIRMED','方案口径尚未确认'); END IF;
    IF pm.source_saved_score IS NOT NULL AND sc IS NOT NULL AND abs(sc-pm.source_saved_score)>coalesce((rules->>'score_tolerance')::numeric,0.0001) THEN
      issues=issues||public.fn_ty_perf_issue('SOURCE_SCORE_MISMATCH','个人月分数与源表保存值不一致');
    END IF;
    score_issues=issues;
    IF pm.eligibility_status<>'verified' THEN issues=issues||public.fn_ty_perf_issue('ELIGIBILITY_UNCONFIRMED','该月资格/折算比例尚未核验'); END IF;
    rating=public.fn_ty_perf_rating(sc,rules->'rating_bands'); factor=(rating->>'factor')::numeric;
    IF rating IS NULL THEN issues=issues||public.fn_ty_perf_issue('RATING_RULE_MISSING','个人分数未匹配评级档位'); END IF;
    base=(rules->'grade_bases'->>pm.grade_id::text)::numeric;
    IF pm.bonus_base_override IS NOT NULL THEN
      base=pm.bonus_base_override;
      IF pm.bonus_base_status<>'verified' THEN issues=issues||public.fn_ty_perf_issue('PERSON_BASE_UNCONFIRMED','个人月度基数覆盖尚未核验'); END IF;
    END IF;
    IF base IS NULL OR base<0 THEN issues=issues||public.fn_ty_perf_issue('GRADE_BASE_MISSING','该月职级奖金基数缺失'); END IF;
    IF sc IS NOT NULL AND factor IS NOT NULL AND base IS NOT NULL THEN amt=base*factor*sc*pm.eligibility_weight; END IF;
    IF pm.source_saved_amount IS NOT NULL AND amt IS NOT NULL AND abs(amt-pm.source_saved_amount)>coalesce((rules->>'amount_tolerance')::numeric,1) THEN
      issues=issues||public.fn_ty_perf_issue('SOURCE_AMOUNT_MISMATCH','个人月奖金与源表保存值不一致');
    END IF;
    INSERT INTO public.ty_perf_result(cycle_id,result_version,kind,company_id,person_id,employment_id,period,score,rating,factor,base_amount,amount,dependencies,issues,blocking,details)
    VALUES(cid,v,'person_month',pm.company_id,pm.person_id,pm.employment_id,pm.period,sc,rating->>'grade',factor,base,amt,
      ARRAY(SELECT DISTINCT unnest(deps)),issues,c.rules->>'aggregation' IS DISTINCT FROM 'average_score_last_grade',
      jsonb_build_object('score_issues',score_issues,'grade_id',pm.grade_id,'score_source',pm.score_source,'eligibility_weight',pm.eligibility_weight,'source_ref',pm.source_ref,'source_saved_amount',pm.source_saved_amount));
  END LOOP;
  FOR pr IN SELECT DISTINCT person_id FROM public.ty_perf_person_month WHERE cycle_id=cid LOOP
    issues='[]';alt_issues='[]';deps=ARRAY[]::bigint[];amt=0;score_sum=0;n=0;
    SELECT * INTO lastrow FROM public.ty_perf_person_month WHERE cycle_id=cid AND person_id=pr.person_id ORDER BY period DESC LIMIT 1;
    FOR r IN SELECT * FROM public.ty_perf_result WHERE cycle_id=cid AND result_version=v AND kind='person_month' AND person_id=pr.person_id LOOP
      n=n+1;deps=deps||r.dependencies;amt=amt+coalesce(r.amount,0);
      score_sum=score_sum+coalesce(r.score,0);
      IF r.amount IS NULL OR jsonb_array_length(r.issues)>0 THEN issues=issues||public.fn_ty_perf_issue('MONTH_BLOCKED','参与汇总月份仍有阻断问题'); END IF;
      IF r.score IS NULL OR jsonb_array_length(coalesce(r.details->'score_issues','[]'))>0 THEN alt_issues=alt_issues||public.fn_ty_perf_issue('MONTH_SCORE_BLOCKED','参与平均的月度分数仍有阻断问题'); END IF;
    END LOOP;
    IF n<>months THEN
      issues=issues||public.fn_ty_perf_issue('MONTH_MISSING','需逐月明确归属、职级及资格；缺月不可补零');
      alt_issues=alt_issues||public.fn_ty_perf_issue('MONTH_MISSING','需逐月明确分数；缺月不可补零');
    END IF;
    monthly_amt=CASE WHEN jsonb_array_length(issues)=0 THEN floor(amt/months) ELSE NULL END;
    avg_score=CASE WHEN n=months THEN score_sum/months ELSE NULL END;
    alt_rules=c.rules||coalesce(c.rules->'company_overrides'->lastrow.company_id::text,'{}')
      ||coalesce(c.rules->'month_overrides'->to_char(lastrow.period,'YYYY-MM'),'{}')
      ||coalesce(c.rules->'company_overrides'->lastrow.company_id::text->'month_overrides'->to_char(lastrow.period,'YYYY-MM'),'{}');
    IF lastrow.score_source='management' THEN alt_rules=alt_rules||coalesce(alt_rules->'management','{}'); END IF;
    alt_rating=public.fn_ty_perf_rating(avg_score,alt_rules->'rating_bands');
    alt_base=coalesce(lastrow.bonus_base_override,(alt_rules->'grade_bases'->>lastrow.grade_id::text)::numeric);
    IF alt_rating IS NULL OR alt_base IS NULL THEN alt_issues=alt_issues||public.fn_ty_perf_issue('ALTERNATIVE_BASIS_MISSING','平均分方案缺少评级或期末职级基数'); END IF;
    IF lastrow.bonus_base_override IS NOT NULL AND lastrow.bonus_base_status<>'verified' THEN alt_issues=alt_issues||public.fn_ty_perf_issue('PERSON_BASE_UNCONFIRMED','期末个人基数覆盖尚未核验'); END IF;
    IF lastrow.eligibility_status<>'verified' THEN alt_issues=alt_issues||public.fn_ty_perf_issue('ELIGIBILITY_UNCONFIRMED','期末资格/比例尚未核验'); END IF;
    alt_amt=CASE WHEN jsonb_array_length(alt_issues)=0 THEN avg_score*(alt_rating->>'factor')::numeric*alt_base*lastrow.eligibility_weight ELSE NULL END;
    IF c.rules->>'alternative_rounding'='floor' THEN alt_amt=floor(alt_amt);
    ELSIF c.rules->>'alternative_rounding'='round_2' THEN alt_amt=round(alt_amt,2); END IF;
    IF c.rules->>'aggregation'='average_score_last_grade' THEN
      issues=alt_issues;amt=alt_amt;
      IF c.rules->>'alternative_eligibility' IS DISTINCT FROM 'last_month' OR coalesce(c.rules->>'alternative_rounding','') NOT IN ('none','floor','round_2') THEN
        issues=issues||public.fn_ty_perf_issue('ALTERNATIVE_POLICY_UNCONFIRMED','平均分方案需明确期末资格及舍入口径');
      END IF;
      IF lastrow.source_saved_alternative_cycle_amount IS NOT NULL AND amt IS NOT NULL AND abs(amt-lastrow.source_saved_alternative_cycle_amount)>coalesce((c.rules->>'amount_tolerance')::numeric,1) THEN
        issues=issues||public.fn_ty_perf_issue('SOURCE_ALTERNATIVE_AMOUNT_MISMATCH','平均分方案与源表替代方案保存值不一致');
      END IF;
    ELSIF c.rules->>'aggregation'='floor_average_months' THEN
      amt=monthly_amt;
      IF lastrow.source_saved_cycle_amount IS NOT NULL AND amt IS NOT NULL AND abs(amt-lastrow.source_saved_cycle_amount)>coalesce((c.rules->>'amount_tolerance')::numeric,1) THEN
        issues=issues||public.fn_ty_perf_issue('SOURCE_CYCLE_AMOUNT_MISMATCH','周期奖金与源表月平均保存值不一致');
      END IF;
    ELSE
      amt=NULL;issues=issues||public.fn_ty_perf_issue('AGGREGATION_UNCONFIRMED','需明确选择逐月金额平均或平均分期末职级方案');
    END IF;
    IF c.rules->>'payout_assignment' IS DISTINCT FROM 'last_month_employment' THEN issues=issues||public.fn_ty_perf_issue('PAYOUT_ASSIGNMENT_UNCONFIRMED','奖金接收雇佣/公司归属口径尚未确认'); END IF;
    INSERT INTO public.ty_perf_result(cycle_id,result_version,kind,company_id,person_id,employment_id,period,amount,dependencies,issues,details)
    VALUES(cid,v,'person_bonus',lastrow.company_id,pr.person_id,lastrow.employment_id,c.payout_period,amt,
      ARRAY(SELECT DISTINCT unnest(deps)),issues,jsonb_build_object('month_count',n,'expected_months',months,'aggregation',c.rules->>'aggregation','payout_assignment',c.rules->>'payout_assignment',
        'monthly_bonus_average',monthly_amt,'average_score_last_grade',alt_amt,'average_score',avg_score,'last_grade_id',lastrow.grade_id,
        'difference',monthly_amt-alt_amt,'comparison_only_not_approval',true,'alternative_issues',alt_issues));
  END LOOP;
  UPDATE public.ty_perf_cycle SET status='calculated',result_version=v,calculated_revision=input_revision WHERE id=cid;
  INSERT INTO public.ty_audit(actor_id,action,entity_kind,entity_id,after_data) VALUES(actor,'calculate','performance',cid,jsonb_build_object('result_version',v,'input_revision',c.input_revision));
  RETURN v;
END; $$;

CREATE FUNCTION fn_ty_perf_confirm(cid bigint,version integer,actor bigint,reason text) RETURNS void LANGUAGE plpgsql SET search_path='' AS $$
DECLARE c public.ty_perf_cycle%ROWTYPE;
BEGIN
  SELECT * INTO c FROM public.ty_perf_cycle WHERE id=cid FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'E_TY_NOT_FOUND: 考核周期不存在'; END IF;
  IF c.status<>'calculated' OR c.result_version<>version OR c.calculated_revision IS DISTINCT FROM c.input_revision THEN
    RAISE EXCEPTION 'E_TY_CONFLICT: 结果版本已变化或输入尚未重算';
  END IF;
  IF coalesce(btrim(reason),'')='' THEN RAISE EXCEPTION 'E_TY_ARGUMENT: 确认需填写核验依据'; END IF;
  IF NOT EXISTS(SELECT 1 FROM public.ty_perf_result WHERE cycle_id=cid AND result_version=version AND kind='person_bonus') THEN
    RAISE EXCEPTION 'E_TY_ARGUMENT: 无人员奖金结果，不可确认';
  END IF;
  IF EXISTS(SELECT 1 FROM public.ty_perf_result WHERE cycle_id=cid AND result_version=version AND blocking AND (jsonb_array_length(issues)>0 OR (kind='person_bonus' AND amount IS NULL))) THEN
    RAISE EXCEPTION 'E_TY_CONFLICT: 尚有未核验规则、缺数、单位或源值对账问题，不可确认';
  END IF;
  UPDATE public.ty_perf_cycle SET status='confirmed',confirmed_at=now(),confirmed_by=actor,confirmation_note=reason WHERE id=cid;
  INSERT INTO public.ty_audit(actor_id,action,entity_kind,entity_id,after_data) VALUES(actor,'confirm','performance',cid,jsonb_build_object('result_version',version,'reason',reason));
END; $$;

