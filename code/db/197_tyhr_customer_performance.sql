-- Configurable restaurant performance. No customer workbook or personal data is seeded.
-- Periods are first-of-month dates; cycle end_date is exclusive.
CREATE TABLE ty_perf_cycle (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id bigint NOT NULL REFERENCES ty_group(id),
  code text NOT NULL CHECK (btrim(code)<>''), name text NOT NULL CHECK (btrim(name)<>''),
  start_date date NOT NULL, end_date date NOT NULL,
  payout_period date NOT NULL, currency_code text NOT NULL DEFAULT 'CNY' CHECK(currency_code ~ '^[A-Z]{3}$'),
  status text NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','calculated','confirmed')),
  rules jsonb NOT NULL DEFAULT '{}', source_refs jsonb NOT NULL DEFAULT '[]',
  confirmation_note text, input_revision integer NOT NULL DEFAULT 0,
  calculated_revision integer, result_version integer NOT NULL DEFAULT 0,
  confirmed_at timestamptz, confirmed_by bigint, created_by bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK(start_date<end_date AND start_date=date_trunc('month',start_date)::date AND end_date=date_trunc('month',end_date)::date),
  CHECK(end_date<=start_date+interval '12 months'),
  CHECK(payout_period=date_trunc('month',payout_period)::date),
  CHECK(jsonb_typeof(rules)='object' AND jsonb_typeof(source_refs)='array'),
  UNIQUE(group_id,code), UNIQUE(id,group_id)
);
CREATE TABLE ty_perf_cycle_company (
  cycle_id bigint NOT NULL REFERENCES ty_perf_cycle(id) ON DELETE CASCADE,
  company_id bigint NOT NULL REFERENCES ty_company(id), PRIMARY KEY(cycle_id,company_id)
);
CREATE TABLE ty_perf_company_metric (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id bigint NOT NULL, company_id bigint NOT NULL, period date NOT NULL,
  metrics jsonb NOT NULL CHECK(jsonb_typeof(metrics)='object'),
  source_saved_score numeric, source_ref jsonb NOT NULL DEFAULT '{}',
  FOREIGN KEY(cycle_id,company_id) REFERENCES ty_perf_cycle_company(cycle_id,company_id),
  UNIQUE(cycle_id,company_id,period)
);
CREATE TABLE ty_perf_person_month (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id bigint NOT NULL, company_id bigint NOT NULL, period date NOT NULL,
  person_id bigint NOT NULL REFERENCES ty_person(id), employment_id bigint NOT NULL REFERENCES ty_employment(id),
  grade_id bigint NOT NULL REFERENCES ty_grade(id),
  score_source text NOT NULL DEFAULT 'company' CHECK(score_source IN ('company','management')),
  eligibility_weight numeric NOT NULL DEFAULT 1 CHECK(eligibility_weight BETWEEN 0 AND 1),
  eligibility_status text NOT NULL DEFAULT 'unverified' CHECK(eligibility_status IN ('verified','unverified')),
  bonus_base_override numeric CHECK(bonus_base_override>=0),
  bonus_base_status text NOT NULL DEFAULT 'unverified' CHECK(bonus_base_status IN ('verified','unverified')),
  source_saved_score numeric, source_saved_amount numeric, source_saved_cycle_amount numeric, source_saved_alternative_cycle_amount numeric, source_ref jsonb NOT NULL DEFAULT '{}',
  FOREIGN KEY(cycle_id,company_id) REFERENCES ty_perf_cycle_company(cycle_id,company_id),
  UNIQUE(cycle_id,person_id,period)
);
CREATE TABLE ty_perf_responsibility (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id bigint NOT NULL, person_id bigint NOT NULL REFERENCES ty_person(id),
  company_id bigint NOT NULL, period date NOT NULL,
  weight numeric NOT NULL CHECK(weight>0 AND weight<=1),
  status text NOT NULL DEFAULT 'unverified' CHECK(status IN ('verified','unverified')),
  source_ref jsonb NOT NULL DEFAULT '{}',
  FOREIGN KEY(cycle_id,company_id) REFERENCES ty_perf_cycle_company(cycle_id,company_id),
  UNIQUE(cycle_id,person_id,company_id,period)
);
CREATE TABLE ty_perf_result (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id bigint NOT NULL REFERENCES ty_perf_cycle(id), result_version integer NOT NULL,
  kind text NOT NULL CHECK(kind IN ('company','person_month','person_bonus')),
  company_id bigint NOT NULL, person_id bigint REFERENCES ty_person(id), employment_id bigint REFERENCES ty_employment(id),
  period date NOT NULL, score numeric, rating text, factor numeric, base_amount numeric, amount numeric,
  dependencies bigint[] NOT NULL, issues jsonb NOT NULL DEFAULT '[]', blocking boolean NOT NULL DEFAULT true, details jsonb NOT NULL DEFAULT '{}',
  FOREIGN KEY(cycle_id,company_id) REFERENCES ty_perf_cycle_company(cycle_id,company_id),
  CHECK(jsonb_typeof(issues)='array'),
  CHECK((kind='company' AND person_id IS NULL AND employment_id IS NULL) OR (kind<>'company' AND person_id IS NOT NULL AND employment_id IS NOT NULL))
);
CREATE UNIQUE INDEX ty_perf_result_company ON ty_perf_result(cycle_id,result_version,company_id,period) WHERE kind='company';
CREATE UNIQUE INDEX ty_perf_result_person ON ty_perf_result(cycle_id,result_version,kind,person_id,period) WHERE kind<>'company';
CREATE INDEX ty_perf_result_scope ON ty_perf_result(cycle_id,result_version,company_id);

CREATE FUNCTION fn_ty_perf_cycle_guard() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
BEGIN
  IF TG_OP IN ('UPDATE','DELETE') AND OLD.status='confirmed' THEN
    RAISE EXCEPTION 'E_TY_CONFLICT: 已确认绩效不可修改或删除，请另建修正周期';
  END IF;
  IF TG_OP='UPDATE' AND (NEW.group_id<>OLD.group_id OR NEW.start_date<>OLD.start_date OR NEW.end_date<>OLD.end_date) THEN
    RAISE EXCEPTION 'E_TY_ARGUMENT: 周期集团及期间不可直接变更';
  END IF;
  IF TG_OP='UPDATE' AND (NEW.rules IS DISTINCT FROM OLD.rules OR NEW.source_refs IS DISTINCT FROM OLD.source_refs) THEN
    NEW.input_revision=OLD.input_revision+1; NEW.status='draft';
  END IF;
  IF TG_OP='UPDATE' AND NEW.status='confirmed' THEN
    IF OLD.status<>'calculated' OR NEW.result_version<>OLD.result_version OR NEW.calculated_revision IS DISTINCT FROM OLD.input_revision
      OR NEW.confirmed_at IS NULL OR NEW.confirmed_by IS NULL OR coalesce(btrim(NEW.confirmation_note),'')='' THEN
      RAISE EXCEPTION 'E_TY_CONFLICT: 必须使用当前已计算版本并填写确认依据';
    END IF;
    IF NOT EXISTS(SELECT 1 FROM public.ty_perf_result WHERE cycle_id=OLD.id AND result_version=OLD.result_version AND kind='person_bonus')
      OR EXISTS(SELECT 1 FROM public.ty_perf_result WHERE cycle_id=OLD.id AND result_version=OLD.result_version AND blocking AND
        (jsonb_array_length(issues)>0 OR (kind='person_bonus' AND amount IS NULL))) THEN
      RAISE EXCEPTION 'E_TY_CONFLICT: 缺少完整可确认奖金结果或仍有阻断问题';
    END IF;
  END IF;
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER ty_perf_cycle_guard BEFORE UPDATE OR DELETE ON ty_perf_cycle FOR EACH ROW EXECUTE FUNCTION fn_ty_perf_cycle_guard();

CREATE FUNCTION fn_ty_perf_input_guard() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE cid bigint; c public.ty_perf_cycle%ROWTYPE; e public.ty_employment%ROWTYPE; gid bigint;
BEGIN
  IF TG_OP='DELETE' THEN cid=OLD.cycle_id; ELSE cid=NEW.cycle_id; END IF;
  SELECT * INTO c FROM public.ty_perf_cycle WHERE id=cid FOR UPDATE;
  IF c.status='confirmed' THEN RAISE EXCEPTION 'E_TY_CONFLICT: 已确认绩效输入及结果不可修改'; END IF;
  IF TG_OP='UPDATE' AND NEW.cycle_id<>OLD.cycle_id THEN RAISE EXCEPTION 'E_TY_ARGUMENT: 记录不可移至其他周期'; END IF;
  IF TG_OP<>'DELETE' THEN
    SELECT group_id INTO gid FROM public.ty_company WHERE id=NEW.company_id;
    IF gid IS DISTINCT FROM c.group_id THEN RAISE EXCEPTION 'E_TY_ARGUMENT: 公司不属于周期集团'; END IF;
    IF TG_TABLE_NAME NOT IN ('ty_perf_cycle_company','ty_perf_result') THEN
      IF NEW.period<>date_trunc('month',NEW.period)::date OR NEW.period<c.start_date OR NEW.period>=c.end_date THEN
        RAISE EXCEPTION 'E_TY_ARGUMENT: 输入月份不属于考核周期';
      END IF;
    END IF;
    IF TG_TABLE_NAME IN ('ty_perf_person_month','ty_perf_responsibility') THEN
      IF NOT EXISTS(SELECT 1 FROM public.ty_person WHERE id=NEW.person_id AND group_id=c.group_id) THEN
        RAISE EXCEPTION 'E_TY_ARGUMENT: 人员不属于周期集团';
      END IF;
    END IF;
    IF TG_TABLE_NAME='ty_perf_person_month' THEN
      SELECT * INTO e FROM public.ty_employment WHERE id=NEW.employment_id;
      IF e.person_id IS DISTINCT FROM NEW.person_id OR e.company_id IS DISTINCT FROM NEW.company_id OR e.group_id IS DISTINCT FROM c.group_id
        OR e.status='cancelled' OR e.hire_date>=NEW.period+interval '1 month' OR (e.leave_date IS NOT NULL AND e.leave_date<NEW.period) THEN
        RAISE EXCEPTION 'E_TY_ARGUMENT: 人员、雇佣、公司和归属月份不匹配';
      END IF;
      IF NOT EXISTS(SELECT 1 FROM public.ty_grade WHERE id=NEW.grade_id AND group_id=c.group_id) THEN
        RAISE EXCEPTION 'E_TY_ARGUMENT: 职级不属于周期集团';
      END IF;
    END IF;
  END IF;
  IF TG_TABLE_NAME<>'ty_perf_result' THEN
    UPDATE public.ty_perf_cycle SET input_revision=input_revision+1,status='draft' WHERE id=cid;
  END IF;
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END; $$;
