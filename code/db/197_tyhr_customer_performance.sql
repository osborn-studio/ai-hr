CREATE TRIGGER ty_perf_metric_guard BEFORE INSERT OR UPDATE OR DELETE ON ty_perf_company_metric FOR EACH ROW EXECUTE FUNCTION fn_ty_perf_input_guard();
CREATE TRIGGER ty_perf_person_guard BEFORE INSERT OR UPDATE OR DELETE ON ty_perf_person_month FOR EACH ROW EXECUTE FUNCTION fn_ty_perf_input_guard();
CREATE TRIGGER ty_perf_responsibility_guard BEFORE INSERT OR UPDATE OR DELETE ON ty_perf_responsibility FOR EACH ROW EXECUTE FUNCTION fn_ty_perf_input_guard();
CREATE TRIGGER ty_perf_result_guard BEFORE INSERT OR UPDATE OR DELETE ON ty_perf_result FOR EACH ROW EXECUTE FUNCTION fn_ty_perf_input_guard();

