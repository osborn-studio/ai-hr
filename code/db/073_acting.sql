-- ---------------------------------------------------------------------------
-- 3. 代理授权
-- ---------------------------------------------------------------------------
CREATE TABLE sys_acting_grant (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- 谁把他的权限交出去（主管）
  principal_user bigint NOT NULL,
  -- 交给谁（副手）
  agent_user     bigint NOT NULL,
  -- 代理的是哪个角色（不是"全部权限"，是**某个角色**：副手顶上的是主管这个岗）
  role_id        bigint NOT NULL REFERENCES sys_role(id),
  valid_from     timestamptz NOT NULL,
  valid_to       timestamptz NOT NULL,
  set_by_user    bigint NOT NULL,          -- 谁设的（必须是 principal 或超管）
  reason         varchar(200) NOT NULL,
  revoked_at     timestamptz,
  revoked_by     bigint,
  created_at     timestamptz NOT NULL DEFAULT now(),

  -- ★ 必须有结束时间，且不能早于开始：没有"永久代理"
  CONSTRAINT ck_ag_span   CHECK (valid_to > valid_from),
  -- ★ 上限 90 天：长期顶上就是改岗位，该走人事流程而不是这里
  CONSTRAINT ck_ag_max    CHECK (valid_to <= valid_from + interval '90 days'),
  CONSTRAINT ck_ag_notself CHECK (principal_user <> agent_user),
  CONSTRAINT ck_ag_reason CHECK (length(btrim(reason)) >= 4)
);

CREATE INDEX ix_ag_agent ON sys_acting_grant (agent_user, valid_from DESC, valid_to DESC);
CREATE INDEX ix_ag_principal ON sys_acting_grant (principal_user, valid_from DESC);

COMMENT ON TABLE sys_acting_grant IS
  '副职代理：主管把自己的**某个角色**在**一段时间内**交给副手。'
  '到期自动失效靠时间窗判断（不靠定时任务）；撤销留痕不删行。';

/** 当前生效的代理（审计与界面都要看这个） */
CREATE VIEW v_acting_active AS
SELECT g.id, g.principal_user, pu.display_name AS principal_name,
       g.agent_user, au.display_name AS agent_name,
       g.role_id, r.code AS role_code, r.name AS role_name,
       g.valid_from, g.valid_to, g.reason, g.set_by_user, g.created_at
  FROM sys_acting_grant g
  JOIN sys_account pu ON pu.id = g.principal_user
  JOIN sys_account au ON au.id = g.agent_user
  JOIN sys_role r ON r.id = g.role_id
 WHERE g.revoked_at IS NULL
   AND now() >= g.valid_from AND now() < g.valid_to;

-- ---------------------------------------------------------------------------
-- 4. 设定 / 撤销
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_acting_grant_set(
  p_principal bigint, p_agent bigint, p_role varchar,
  p_from timestamptz, p_to timestamptz, p_by bigint, p_reason varchar
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_role public.sys_role%ROWTYPE;
  v_id bigint;
  v_held boolean;
  v_by_super boolean;
BEGIN
  SELECT * INTO v_role FROM public.sys_role WHERE code = p_role AND is_active;
  IF v_role.id IS NULL THEN
    RAISE EXCEPTION 'E_ACTING_ROLE: 角色 % 不存在', p_role;
  END IF;
  IF p_principal = p_agent THEN
    RAISE EXCEPTION 'E_ACTING_SELF: 不能代理给自己';
  END IF;

  -- a) 只有主管本人，或超管代设（代设也留痕：set_by 与 principal 不同即可看出来）
  SELECT COALESCE(bool_or(r.is_super), false) INTO v_by_super
    FROM public.fn_effective_roles(p_by, public.app_today()) e
    JOIN public.sys_role r ON r.id = e.role_id AND r.is_active;
  IF p_by <> p_principal AND NOT v_by_super THEN
    RAISE EXCEPTION 'E_ACTING_NOT_PRINCIPAL: 只有主管本人（或系统管理员）能设定代理';
  END IF;

  -- d) 主管必须**自己拥有**这个角色 —— 不能代理出自己没有的权限
  SELECT EXISTS (
    SELECT 1 FROM public.fn_effective_roles(p_principal, public.app_today()) e
     WHERE e.role_id = v_role.id
  ) INTO v_held;
  IF NOT v_held THEN
    RAISE EXCEPTION 'E_ACTING_ROLE_NOT_HELD: % 当前没有「%」这个角色，不能把它代理出去',
      p_principal, v_role.name;
  END IF;

  -- 超管角色一律不许代理：那是权限提升，不是"顶班"
  IF v_role.is_super THEN
    RAISE EXCEPTION 'E_ACTING_SUPER: 超级角色不许代理（那是权限提升，不是顶班）';
  END IF;

  INSERT INTO public.sys_acting_grant(principal_user, agent_user, role_id,
                                      valid_from, valid_to, set_by_user, reason)
  VALUES (p_principal, p_agent, v_role.id, p_from, p_to, p_by, btrim(p_reason))
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION fn_acting_grant_revoke(p_id bigint, p_by bigint)
RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v public.sys_acting_grant%ROWTYPE; v_super boolean;
BEGIN
  SELECT * INTO v FROM public.sys_acting_grant WHERE id = p_id FOR UPDATE;
  IF v.id IS NULL THEN RAISE EXCEPTION 'E_ACTING_NOT_FOUND: 代理 #% 不存在', p_id; END IF;
  IF v.revoked_at IS NOT NULL THEN RETURN; END IF;   -- 幂等

  SELECT COALESCE(bool_or(r.is_super), false) INTO v_super
    FROM public.fn_effective_roles(p_by, public.app_today()) e
    JOIN public.sys_role r ON r.id = e.role_id AND r.is_active;
  IF p_by <> v.principal_user AND p_by <> v.agent_user AND NOT v_super THEN
    RAISE EXCEPTION 'E_ACTING_NOT_PARTY: 只有主管、副手本人或系统管理员能撤销';
  END IF;

  UPDATE public.sys_acting_grant SET revoked_at = now(), revoked_by = p_by WHERE id = p_id;
END;
$$;

-- ---------------------------------------------------------------------------
-- 5. 权限判据接入代理（在 071 版本上追加一段，其余完全不变）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_role_can(
  p_user     bigint,
  p_resource varchar,
  p_action   varchar DEFAULT 'read'      -- read | write
) RETURNS boolean
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE v_ok boolean; v_readonly boolean; v_today date := public.app_today();
BEGIN
  IF p_action NOT IN ('read','write') THEN
    RAISE EXCEPTION 'E_ROLE_ACTION: 动作只能是 read / write（收到 %）', p_action;
  END IF;

  IF EXISTS (SELECT 1 FROM public.fn_effective_roles(p_user, v_today) e
               JOIN public.sys_role r ON r.id = e.role_id
              WHERE r.is_super AND r.is_active)
  THEN RETURN true; END IF;

  SELECT bool_or(rr.can_read OR (p_action = 'write' AND rr.can_write))
    INTO v_ok
    FROM public.fn_effective_roles(p_user, v_today) e
    JOIN public.sys_role r ON r.id = e.role_id AND r.is_active
    JOIN public.sys_role_resource rr
      ON rr.role_id = e.role_id AND rr.resource_code = p_resource
   WHERE CASE p_action
           WHEN 'read'  THEN rr.can_read
           ELSE rr.can_write
         END;

  -- ★ 代理：本人角色不够时，看他是否正处在某条代理的窗口内。
  --   判据只有一条：now() 在 [valid_from, valid_to) 且未撤销 ——
  --   **不查任何"是否已生效"的标记列**，所以不存在"定时任务没跑，代理一直有效"。
  IF NOT COALESCE(v_ok, false) THEN
    SELECT bool_or(rr.can_read OR (p_action = 'write' AND rr.can_write))
      INTO v_ok
      FROM public.sys_acting_grant g
      JOIN public.sys_role r ON r.id = g.role_id AND r.is_active
      JOIN public.sys_role_resource rr
        ON rr.role_id = g.role_id AND rr.resource_code = p_resource
     WHERE g.agent_user = p_user
       AND g.revoked_at IS NULL
       AND now() >= g.valid_from AND now() < g.valid_to
       AND CASE p_action
             WHEN 'read'  THEN rr.can_read
             ELSE rr.can_write
           END;
  END IF;

  IF p_action = 'write' THEN
    SELECT true INTO v_readonly
      FROM public.fn_effective_roles(p_user, v_today) e
      JOIN public.sys_user_role ur
        ON ur.user_id = p_user AND ur.role_id = e.role_id AND ur.readonly_only
     LIMIT 1;
    IF COALESCE(v_readonly, false) THEN RETURN false; END IF;
  END IF;

  RETURN COALESCE(v_ok, false);
END;
$$;

COMMENT ON FUNCTION fn_role_can IS
  '岗位判据：read / write。三层来源 —— 直接与组织继承的角色（020/063）、'
  '以及**有期限的代理**（073）。代理只在窗口内生效，不靠定时任务。';

