-- ============================================================================
-- 073_acting.sql · 角色分配（老板/店长/副店长/人事/薪酬）+ 副职代理
-- ----------------------------------------------------------------------------
-- 两个诉求，其实是两件事：
--
--   ① **岗位不同**（店长 / 副店长 / 人事主管 / 薪酬专员 / 店员）——
--      这是"他平时能做什么"，用 sys_role_matrix 表达（063 已有）。
--   ② **主管不在时副手顶上** —— 这不是岗位，是**有期限的代理**。
--      所以它不能靠在 sys_role 里再加一个"副店长有全部权限"的角色：
--      那样副手在主管在的时候也有全部权限，"副"这个字就没意义了。
--
-- 代理的四条硬规矩（每条都会有一条断言）：
--   a) **必须由主管本人设定**（或超管代设并留痕）。副手不能自己给自己开。
--   b) **必须有起止时间**。没有"永久代理"—— 永久代理等于改岗位，
--      而改岗位是有审批与生效日的事，不该从这个口子发生。
--   c) **只能在窗口内生效，且到期自动失效**。靠时间窗判断，不靠定时任务：
--      定时任务没跑就会"一直在代理"，而那个错没人会注意到。
--   d) **不能代理出主管自己没有的角色**。副店长最多拿到店长的权限，
--      不可能通过代理摸到 admin / 老板 —— 这是一条权限提升（privilege escalation）防线。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 老板 = 业务全权（与 admin 的"系统全权"并列，但语义不同）
-- ---------------------------------------------------------------------------
-- ★ 这里刻意**不**把 boss 设成 is_super：
--   063 的约束写着"超级角色只能是 admin"，而那条约束是对的 ——
--   超级角色是"绕过授权判据"，那属于系统层；老板要的是"业务上什么都能做"，
--   那是**把资源全给到他**，两者不该混成一个开关。
--   于是老板的权限是**逐资源授**的，只是用 CROSS JOIN 一次给全：
--   新增资源那天老板自动也有（这符合"老板"的语义，而 063 里担心的
--   "自动扩大范围"针对的是**岗位**，不是老板）。
INSERT INTO sys_role_resource(role_id, resource_code, can_read, can_write)
SELECT r.id, res.resource_code, true, true
  FROM sys_role r CROSS JOIN sys_perm_resource res
 WHERE r.code = 'boss'
ON CONFLICT (role_id, resource_code) DO UPDATE
   SET can_read = true, can_write = true;

UPDATE sys_role SET description = '业务全权：所有资源可读可写（授权与系统参数仍归 admin）'
 WHERE code = 'boss';

-- ---------------------------------------------------------------------------
-- 1.5 sys_role.id 补生成方式（第十次同一个坑）
-- ---------------------------------------------------------------------------
-- 063 建这张表时 id 是裸 bigint PRIMARY KEY —— 种子一直写显式 id，所以从没红过。
-- 而"新增一个角色"是第一个**由迁移/函数插入**它的路径，立刻 23502。
-- ★ 顺手把序列对齐：ADD IDENTITY 是从 1 开始的，而表里已经有 10–17 这些显式 id，
--   不对齐的话下一次插入就撞主键，报错还说 duplicate key —— 看起来像数据重复。
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                  WHERE table_schema='public' AND table_name='sys_role'
                    AND column_name='id' AND is_identity='YES') THEN
    ALTER TABLE public.sys_role ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
  PERFORM setval(pg_get_serial_sequence('public.sys_role','id'),
                 GREATEST(COALESCE((SELECT max(id) FROM public.sys_role), 0), 1));
END $$;

