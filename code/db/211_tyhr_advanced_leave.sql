CREATE FUNCTION fn_ty_leave_request_balance_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE rid bigint;r ty_leave_request%ROWTYPE;expected text;BEGIN
 IF TG_TABLE_NAME='ty_leave_request' THEN rid:=NEW.id;ELSE rid:=NEW.request_id;END IF;
 SELECT * INTO r FROM ty_leave_request WHERE id=rid;
 expected:=CASE r.status WHEN 'pending' THEN 'held' WHEN 'approved' THEN 'allocated' WHEN 'taken' THEN 'taken' ELSE 'released' END;
 IF (SELECT coalesce(sum(quantity),0) FROM ty_leave_allocation WHERE request_id=rid)<>r.quantity
 OR EXISTS(SELECT 1 FROM ty_leave_allocation WHERE request_id=rid AND state<>expected) THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='申请数量、审批状态与权益占用不守恒';END IF;RETURN NEW;END;$$;
CREATE CONSTRAINT TRIGGER trg_ty_leave_request_balance AFTER INSERT OR UPDATE ON ty_leave_request DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION fn_ty_leave_request_balance_guard();
CREATE CONSTRAINT TRIGGER trg_ty_leave_alloc_balance AFTER INSERT OR UPDATE ON ty_leave_allocation DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION fn_ty_leave_request_balance_guard();
