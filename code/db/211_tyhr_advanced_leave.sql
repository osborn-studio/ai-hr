CREATE FUNCTION fn_ty_leave_identity_guard() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='假期账户或批次历史不可删除';END IF;
 IF TG_TABLE_NAME='ty_leave_account' THEN
  IF NEW.relationship_id<>OLD.relationship_id OR NEW.code<>OLD.code OR NEW.unit<>OLD.unit THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='假期账户身份不可搬运';END IF;
 ELSE
  IF NEW.account_id<>OLD.account_id OR NEW.stable_key<>OLD.stable_key OR NEW.scheme_id<>OLD.scheme_id OR NEW.entitlement_year<>OLD.entitlement_year OR NEW.valid_from<>OLD.valid_from OR NEW.expires_on IS DISTINCT FROM OLD.expires_on OR NEW.statutory<>OLD.statutory THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='权益批次身份及法定性质不可改写';END IF;
 END IF;RETURN NEW;END;$$;
