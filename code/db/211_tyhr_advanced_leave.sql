CREATE FUNCTION fn_ty_leave_event_post() RETURNS trigger LANGUAGE plpgsql AS $$ DECLARE l ty_leave_lot%ROWTYPE; BEGIN
 SELECT * INTO l FROM ty_leave_lot WHERE id=NEW.lot_id FOR UPDATE;
 IF NEW.event_kind='expire' AND l.statutory THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='法定权益不得定时清零'; END IF;
 IF NEW.event_kind='expire' THEN UPDATE ty_leave_lot SET expired=expired-NEW.delta WHERE id=l.id;
 ELSE UPDATE ty_leave_lot SET granted=granted+NEW.delta WHERE id=l.id;END IF;
 IF NEW.delta<>0 THEN UPDATE ty_leave_account SET revision=revision+1 WHERE id=l.account_id;END IF;RETURN NEW;END;$$;
CREATE TRIGGER trg_ty_leave_event_post AFTER INSERT ON ty_leave_event FOR EACH ROW EXECUTE FUNCTION fn_ty_leave_event_post();
CREATE FUNCTION fn_ty_leave_allocation_post() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='假期占用不可删除，请释放';END IF;
 IF TG_OP='INSERT' AND NEW.state<>'held' THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='占用必须从待批预占开始';END IF;
 IF TG_OP='UPDATE' THEN
  IF NEW.account_id<>OLD.account_id OR NEW.request_id<>OLD.request_id OR NEW.lot_id<>OLD.lot_id OR NEW.quantity<>OLD.quantity
   OR NOT((OLD.state='held' AND NEW.state IN('allocated','released')) OR (OLD.state='allocated' AND NEW.state IN('taken','released')))
   THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='假期占用状态或身份变更不合法';END IF;
  UPDATE ty_leave_lot SET held=held-CASE WHEN OLD.state='held' THEN OLD.quantity ELSE 0 END,
   allocated=allocated-CASE WHEN OLD.state='allocated' THEN OLD.quantity ELSE 0 END WHERE id=OLD.lot_id;
 END IF;
 UPDATE ty_leave_lot SET held=held+CASE WHEN NEW.state='held' THEN NEW.quantity ELSE 0 END,
 allocated=allocated+CASE WHEN NEW.state='allocated' THEN NEW.quantity ELSE 0 END,
 taken=taken+CASE WHEN NEW.state='taken' THEN NEW.quantity ELSE 0 END WHERE id=NEW.lot_id;
 UPDATE ty_leave_account SET revision=revision+1 WHERE id=NEW.account_id;RETURN NEW;END;$$;
CREATE TRIGGER trg_ty_leave_allocation_post AFTER INSERT OR UPDATE OR DELETE ON ty_leave_allocation FOR EACH ROW EXECUTE FUNCTION fn_ty_leave_allocation_post();
