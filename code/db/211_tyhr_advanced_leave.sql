CREATE FUNCTION fn_ty_leave_reference_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE r ty_leave_relationship%ROWTYPE;v_emp ty_employment%ROWTYPE;a ty_leave_account%ROWTYPE;s ty_leave_scheme%ROWTYPE;
BEGIN
 IF TG_TABLE_NAME='ty_leave_relationship_employment' THEN
  SELECT * INTO r FROM ty_leave_relationship WHERE id=NEW.relationship_id FOR UPDATE;
  SELECT * INTO v_emp FROM ty_employment WHERE id=NEW.employment_id;
  IF r.group_id<>v_emp.group_id OR r.person_id<>v_emp.person_id OR v_emp.status='cancelled' OR v_emp.hire_date<r.valid_from OR (r.valid_to IS NOT NULL AND (v_emp.leave_date IS NULL OR v_emp.leave_date>=r.valid_to)) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='实际关系与公司关系人员、集团或期间不一致';END IF;
 ELSIF TG_TABLE_NAME IN('ty_leave_lot','ty_leave_request') THEN
  SELECT * INTO a FROM ty_leave_account WHERE id=NEW.account_id;
  SELECT * INTO r FROM ty_leave_relationship WHERE id=a.relationship_id;
  SELECT * INTO s FROM ty_leave_scheme WHERE id=NEW.scheme_id;
  IF s.group_id<>r.group_id OR s.jurisdiction<>r.jurisdiction OR s.unit<>a.unit OR s.code<>a.code OR s.status<>'published'
   OR (s.company_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM ty_leave_relationship_employment x JOIN ty_employment e ON e.id=x.employment_id WHERE x.relationship_id=r.id AND e.company_id=s.company_id)) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='假期规则与账户的集团、公司、地区或计量不一致';END IF;
  IF TG_TABLE_NAME='ty_leave_lot' THEN
   IF NEW.statutory<>s.statutory THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='法定权益标志不可降级';END IF;
  ELSE
   IF NOT EXISTS(SELECT 1 FROM ty_leave_relationship_employment WHERE relationship_id=r.id AND employment_id=NEW.employment_id) THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='申请公司关系不属于该实际关系';END IF;
   PERFORM 1 FROM ty_leave_relationship WHERE id=r.id FOR UPDATE;
   IF NEW.status IN('pending','approved','taken') AND EXISTS(SELECT 1 FROM ty_leave_request q JOIN ty_leave_account ac ON ac.id=q.account_id WHERE ac.relationship_id=r.id AND q.id<>NEW.id AND q.status IN('pending','approved','taken') AND tstzrange(q.starts_at,q.ends_at,'[)')&&tstzrange(NEW.starts_at,NEW.ends_at,'[)')) THEN RAISE EXCEPTION USING ERRCODE='23P01',MESSAGE='同一实际关系的假期时间重叠';END IF;
  END IF;
 END IF;RETURN NEW;
END;$$;
CREATE TRIGGER trg_ty_leave_rel_reference BEFORE INSERT OR UPDATE ON ty_leave_relationship_employment FOR EACH ROW EXECUTE FUNCTION fn_ty_leave_reference_guard();
CREATE TRIGGER trg_ty_leave_lot_reference BEFORE INSERT OR UPDATE ON ty_leave_lot FOR EACH ROW EXECUTE FUNCTION fn_ty_leave_reference_guard();
