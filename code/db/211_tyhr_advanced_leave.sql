CREATE TABLE ty_leave_scheme (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 group_id bigint NOT NULL REFERENCES ty_group(id), company_id bigint,
 code text NOT NULL CHECK(btrim(code)<>''), version integer NOT NULL CHECK(version>0),
 name text NOT NULL CHECK(btrim(name)<>''), jurisdiction text NOT NULL CHECK(jurisdiction IN('CN','HK')),
 unit text NOT NULL CHECK(unit IN('day','minute')), statutory boolean NOT NULL,
 valid_from date NOT NULL, valid_to date, rules jsonb NOT NULL CHECK(jsonb_typeof(rules)='object'),
 status text NOT NULL DEFAULT 'draft' CHECK(status IN('draft','published')),
