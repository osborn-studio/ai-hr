CREATE FUNCTION fn_ty_leave_scheme_period_guard() RETURNS trigger LANGUAGE plpgsql AS $$ DECLARE s ty_leave_scheme%ROWTYPE;n ty_leave_scheme%ROWTYPE;BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='假期发布历史不得删除';END IF;
 SELECT * INTO s FROM ty_leave_scheme WHERE id=NEW.scheme_id;
 IF s.status<>'published' OR s.group_id<>NEW.group_id OR s.code<>NEW.code OR coalesce(s.company_id,0)<>NEW.company_scope OR s.valid_from<>NEW.valid_from OR s.valid_to IS DISTINCT FROM NEW.original_valid_to THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='发布生效段须对应已核准规则正文';END IF;
 IF TG_OP='INSERT' AND (NEW.valid_to IS DISTINCT FROM NEW.original_valid_to OR NEW.superseded_by IS NOT NULL) THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='初次发布区间须与规则批准区间相同';END IF;
 IF TG_OP='UPDATE' THEN
  SELECT * INTO n FROM ty_leave_scheme WHERE id=NEW.superseded_by;
  IF NEW.scheme_id<>OLD.scheme_id OR NEW.original_valid_to IS DISTINCT FROM OLD.original_valid_to OR OLD.superseded_by IS NOT NULL OR NEW.superseded_by IS NULL OR n.id IS NULL OR NEW.valid_to IS NULL OR n.status<>'published' OR n.group_id<>s.group_id OR n.code<>s.code OR n.company_id IS DISTINCT FROM s.company_id OR NEW.valid_to<>n.valid_from OR NEW.valid_to<=OLD.valid_from OR (OLD.valid_to IS NOT NULL AND NEW.valid_to>=OLD.valid_to) THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='旧规则仅能由已批准后续版本关闭生效段';END IF;
 END IF;RETURN NEW;END;$$;
