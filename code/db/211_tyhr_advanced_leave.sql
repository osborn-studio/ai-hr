CREATE TABLE ty_leave_lot (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,account_id bigint NOT NULL REFERENCES ty_leave_account(id),
 stable_key text NOT NULL CHECK(btrim(stable_key)<>''),scheme_id bigint NOT NULL REFERENCES ty_leave_scheme(id),
 entitlement_year integer NOT NULL CHECK(entitlement_year BETWEEN 1900 AND 9999),
 valid_from date NOT NULL,expires_on date,statutory boolean NOT NULL,
 granted numeric(18,4) NOT NULL DEFAULT 0,held numeric(18,4) NOT NULL DEFAULT 0,
 allocated numeric(18,4) NOT NULL DEFAULT 0,taken numeric(18,4) NOT NULL DEFAULT 0,
 cash_reserved numeric(18,4) NOT NULL DEFAULT 0,expired numeric(18,4) NOT NULL DEFAULT 0,
