CREATE FUNCTION fn_ty_leave_document_guard() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='假期单据和预演历史不可删除';END IF;
 IF TG_TABLE_NAME='ty_leave_request' THEN
  IF (to_jsonb(NEW)-ARRAY['status','approved_by']) IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['status','approved_by']) THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='申请事实不可改写，须取消重提或办理更正';END IF;
  IF NEW.status<>OLD.status AND NOT((OLD.status='pending' AND NEW.status IN('approved','rejected','cancelled')) OR (OLD.status='approved' AND NEW.status IN('taken','cancelled'))) THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='申请状态不可逆跳';END IF;
  IF NEW.status IN('approved','rejected') AND (NEW.approved_by IS NULL OR NEW.approved_by=NEW.created_by) THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='申请须由另一经办复核';END IF;
  IF NEW.status='taken' AND NEW.ends_at>clock_timestamp() THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='未来占用不能记为实际已休';END IF;
 ELSE
  IF (to_jsonb(NEW)-ARRAY['approved_by','applied_at']) IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['approved_by','applied_at']) OR OLD.applied_at IS NOT NULL OR NEW.applied_at IS NULL OR NEW.approved_by IS NULL OR NEW.approved_by=NEW.created_by THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='调整预演不可改写，只能双人复核一次生效';END IF;
 END IF;RETURN NEW;END;$$;
