 UNIQUE(group_id,code,version), UNIQUE(id,group_id)
);
-- An explicit source key represents a reviewed actual-employer continuity scope,
-- not an invented V9 legal-relationship id. Company employment segments attach below.
CREATE TABLE ty_leave_relationship (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
