-- ============================================================================
-- 153_dispatch.sql · 借调（人员调度）：一张单 + 一条带有效期的归属
-- ----------------------------------------------------------------------------
-- 产品原话（照抄，因为它们是这一版全部的判据）：
--
--   「在开始支援时自动调入被支援门店考勤组，支援结束自动回到原考勤组，
--     无需人为手动操作」                                  —— 潮牛壹号
--   「按天调度…按天统计各产线的工时成本，成本分摊更加精细化」 —— 产品介绍 p18
--   「不同的支援任务会有不同的薪资」
--   「审批通过，考勤机只绑定对应门店的员工（规避就近打卡）」   —— 京小盒
--
-- ★★ 这一版唯一需要想清楚的事：**"自动调入/自动调回"是怎么实现的。**
--
--   两种做法看起来都能跑通，但只有一种是对的：
--
--   ✗ 每天跑一个作业，把在场人的 attendance_org 搬来搬去，到期再搬回去。
--     它需要调度器；漏跑一天就是一天的成本算错店；重复跑会把区间改成零长度；
--     中途换人、提前结束、补跑，每一种都要在那个作业里再写一遍例外。
--     最要命的是：**它没有"历史"** —— 搬完只剩当前值，回头看上个月的报表
--     会按今天的归属重算，而报表看起来完全正常。
--
--   ✓ 审批通过时写**一条带起止日期的归属**（employee_org_assignment，
--     dim_code='attendance_org'，valid_from=支援开始，valid_to=支援结束）。
--     之后什么都不用做：
--       · 考勤按 attendance_org **时点**归属算 → 支援那几天自动落在目标门店
--         （"考勤机只绑定对应门店的员工"就是这条的语义，不是另加一条校验）
--       · 报表按组织汇总工时 → **成本自动分摊**，不需要第二个 cost_share 字段
--       · 到期不需要删这条归属：它自带 valid_to，过期即失效 → "自动调回"
--         不需要定时任务，也不需要有人记得点一下
--       · 补跑/重算任何历史期间，读到的都是当时那条归属 → 上个月的数不会变
--
--   下面 fn_dispatch_approve 里额外做的那一刀（把原归属切到支援前一天、
--   再补一条"复归段"）不是设计选择，是 014 建的 ex_eoa_no_overlap 逼出来的：
--   同一 (employee, dim) 的区间不许重叠，而原来那条 attendance_org 是开到
--   无期的（valid_to IS NULL）—— 不切开它，借调段根本插不进去。
--   切完之后时间轴仍然是"一个人一件事一段"，语义没变。
--
-- ★ 「不同的支援任务会有不同的薪资」这一版**不做**：那需要支援任务档案
--   （task）与薪资项绑定，属于算薪侧。这里只留 reason 与两个组织，
--   工资条怎么反映它，由后续的薪资项决定 —— 现在硬塞一个 rate 字段，
--   只会得到一个"存了但没人算"的数。
-- ============================================================================

CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ---------------------------------------------------------------------------
-- 1. 借调单
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS roster_dispatch (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id bigint NOT NULL,
  from_org    bigint NOT NULL,              -- 原考勤组（建单时取时点归属）
  to_org      bigint NOT NULL,              -- 被支援门店
  from_date   date   NOT NULL,
  to_date     date   NOT NULL,              -- 含当天：'"[]"' 语义，与归属表一致
  reason      varchar(200) NOT NULL,
  status      varchar(16) NOT NULL DEFAULT 'draft',
  -- 审批意见 / 结束说明。**不在需求列的清单里，是补的**：
  -- 驳回不写意见等于"这个人这次支援黄了"没有任何解释，HR 下次还会再提一遍。
  note        varchar(200),
  approved_by varchar(64),
  approved_at timestamptz,
  ended_at    timestamptz,
  created_by  varchar(64) NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT ck_rd_status CHECK (status IN
    ('draft','approved','rejected','cancelled','finished')),
  CONSTRAINT ck_rd_span CHECK (to_date >= from_date),
  CONSTRAINT ck_rd_diff_org CHECK (from_org <> to_org),
  -- 原因至少 4 个字：'支援' 两个字就够的话，这条路最后没人写原因
  CONSTRAINT ck_rd_reason CHECK (length(btrim(reason)) >= 4),

  -- ★ 状态与时刻同生同灭。写成 (status='approved') 是不对的：
  --   finished 是 approved 之后的状态，它同样有过审批。
  CONSTRAINT ck_rd_approved CHECK (
    (status IN ('approved','finished')) = (approved_at IS NOT NULL)
    AND (status IN ('approved','finished')) = (approved_by IS NOT NULL)
  ),
  CONSTRAINT ck_rd_ended CHECK ((status = 'finished') = (ended_at IS NOT NULL))
);

COMMENT ON TABLE roster_dispatch IS
  '借调单。**单据本身不承载成本**：审批通过时写一条带有效期的 attendance_org 归属，'
  '考勤按维度时点取值 → 支援期间自动落目标门店，报表按组织汇总 → 成本自动分摊。'
  '到期不删归属（带 valid_to 自然失效），所以"自动调回"不需要定时任务。';

COMMENT ON COLUMN roster_dispatch.from_org IS
  '原考勤组。建单时取该人 from_date 当天的 attendance_org 时点归属，'
  '取不到回退 cost_org；审批通过时会按当时的事实再校正一次。';
COMMENT ON COLUMN roster_dispatch.note IS
  '审批意见 / 结束说明。驳回必须写（E_DISPATCH_NO_NOTE）—— 没意见的驳回等于没留痕。';

-- ★ 同一人不得有两条**占用日历**的借调。
--   谓词只算 approved/finished：draft 是"还没批"，rejected/cancelled 是"没发生"，
--   让它们也占日历会得到一个"草稿把正式单挡住"的库。
--   finished 也算：一个人不可能同一天在两个店上过班，历史同样不能重叠。
ALTER TABLE roster_dispatch ADD CONSTRAINT ex_rd_no_overlap
  EXCLUDE USING gist (
    employee_id WITH =,
    daterange(from_date, to_date, '[]') WITH &&
  ) WHERE (status IN ('approved','finished'));

CREATE INDEX IF NOT EXISTS ix_rd_person ON roster_dispatch(employee_id, from_date, to_date);
CREATE INDEX IF NOT EXISTS ix_rd_org    ON roster_dispatch(to_org, from_date);

-- ---------------------------------------------------------------------------
-- 2. 建单
-- ---------------------------------------------------------------------------
-- 建单只做校验，**不动归属**：草稿不该改变任何人的考勤口径。
CREATE OR REPLACE FUNCTION fn_dispatch_create(
  p_employee bigint,
  p_to_org   bigint,
  p_from     date,
  p_to       date,
  p_reason   varchar,
  p_by       varchar
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  o          public.org_unit%ROWTYPE;
  v_from_org bigint;
  v_reason   varchar(200);
  v_id       bigint;
BEGIN
  IF p_employee IS NULL OR p_to_org IS NULL OR p_from IS NULL OR p_to IS NULL THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 员工、目标组织、起止日期都必填';
  END IF;
  IF p_to < p_from THEN
    RAISE EXCEPTION 'E_DISPATCH_DATE_RANGE: 借调区间写反了（% → %）', p_from, p_to;
  END IF;

  -- ① 人在职（按借调**开始那天**判：提前一个月提的单，人当天必须在职）
  IF NOT public.fn_is_active(p_employee, p_from) THEN
    RAISE EXCEPTION 'E_DISPATCH_NO_EMPLOYEE: 员工 % 在 % 不在职', p_employee, p_from;
  END IF;

  -- ② 目标组织：存在、启用、不是集团
  SELECT * INTO o FROM public.org_unit WHERE id = p_to_org;
  IF o.id IS NULL THEN
    RAISE EXCEPTION 'E_DISPATCH_ORG_NOT_FOUND: 目标组织 % 不存在', p_to_org;
  END IF;
  IF NOT o.is_active THEN
    RAISE EXCEPTION 'E_DISPATCH_ORG_INACTIVE: 目标组织「%」已停用', o.name;
  END IF;
  -- 076 之后"门店"就是 kind='dept'（'store' 已归一）。集团不能作为支援目标：
  -- 借调的目标一定是"一个具体的干活地点"，集团节点下面没有考勤组。
  IF o.kind = 'group' THEN
    RAISE EXCEPTION 'E_DISPATCH_ORG_KIND: 「%」是集团节点，借调目标只能是区域或门店/部门', o.name;
  END IF;

  -- ③ 区间不重叠。**必须排在"原考勤组"之前**：借调期间那条归属已经把
  --    attendance_org 改成了目标店，先算 from_org 会得到"目标店 → 目标店"，
  --    于是重叠被报成 E_DISPATCH_SAME_ORG —— 调用方会以为"他已经在那儿了"，
  --    而不是"这段日历已经被占了"。错的是日期，不是人。
  --
  --    口径比排斥约束宽一格：**草稿也算占位**（NOT IN rejected/cancelled）。
  --    排斥约束只能管 approved/finished（parted index 的谓词），但如果允许
  --    两张草稿压在同一段日历上，第二张批下去时才炸 —— 而那时申请人已经等了
  --    三天。提的时候就告诉他"这段已经有人提了"，比批的时候才发现有用。
  --    第一张不批了，驳回/作废之后这段就腾出来了。
  IF EXISTS (
    SELECT 1 FROM public.roster_dispatch d
     WHERE d.employee_id = p_employee
       AND d.status NOT IN ('rejected','cancelled')
       AND daterange(d.from_date, d.to_date, '[]') && daterange(p_from, p_to, '[]')
  ) THEN
    RAISE EXCEPTION 'E_DISPATCH_OVERLAP: 员工 % 在 % → % 已经有一张借调单'
      '（草稿也算），同一人同一天只能在被支援的那家店', p_employee, p_from, p_to;
  END IF;

  -- ④ 原考勤组：先 attendance_org，再回退 cost_org
  SELECT a.org_id INTO v_from_org
    FROM public.employee_org_assignment a
   WHERE a.employee_id = p_employee AND a.dim_code = 'attendance_org'
     AND daterange(a.valid_from, a.valid_to, '[]') @> p_from
   ORDER BY a.valid_from DESC LIMIT 1;

  IF v_from_org IS NULL THEN
    SELECT a.org_id INTO v_from_org
      FROM public.employee_org_assignment a
     WHERE a.employee_id = p_employee AND a.dim_code = 'cost_org'
       AND daterange(a.valid_from, a.valid_to, '[]') @> p_from
     ORDER BY a.valid_from DESC LIMIT 1;
  END IF;

  IF v_from_org IS NULL THEN
    RAISE EXCEPTION 'E_DISPATCH_NO_ORG: 员工 % 在 % 没有考勤组织也没有成本组织，'
      '不知道该把他从哪借出去（先补归属再提借调）', p_employee, p_from;
  END IF;
  IF v_from_org = p_to_org THEN
    RAISE EXCEPTION 'E_DISPATCH_SAME_ORG: 员工 % 在 % 已经归属 %，不需要借调',
      p_employee, p_from, p_to_org;
  END IF;

  -- ⑤ 原因
  v_reason := left(btrim(COALESCE(p_reason, '')), 200);
  IF length(v_reason) < 4 THEN
    RAISE EXCEPTION 'E_DISPATCH_NO_REASON: 借调必须写原因（至少 4 个字，'
      '比如"B 店周末缺人"），现在收到「%」', COALESCE(p_reason, '');
  END IF;

  INSERT INTO public.roster_dispatch
    (employee_id, from_org, to_org, from_date, to_date, reason, created_by)
  VALUES (p_employee, v_from_org, p_to_org, p_from, p_to, v_reason, COALESCE(p_by, 'system'))
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_dispatch_create IS
  '建借调草稿。校验：在职（按开始日）/ 目标组织存在且非集团 / 有原考勤组（回退成本组织）/'
  '原因 >= 4 字 / 同一人区间不与已生效借调重叠。**不改任何归属** —— 草稿不该改变考勤口径。';

-- ---------------------------------------------------------------------------
-- 3. 审批：通过时写那条带有效期的归属
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_dispatch_approve(
  p_id   bigint,
  p_ok   boolean,
  p_by   varchar,
  p_note varchar DEFAULT NULL
) RETURNS varchar
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  d           public.roster_dispatch%ROWTYPE;
  v_cur       public.employee_org_assignment%ROWTYPE;
  v_next      public.employee_org_assignment%ROWTYPE;
  v_note      varchar(200);
  v_other     int;
  v_resume_to date;
  v_resume_org bigint;
BEGIN
  SELECT * INTO d FROM public.roster_dispatch WHERE id = p_id FOR UPDATE;
  IF d.id IS NULL THEN
    RAISE EXCEPTION 'E_DISPATCH_NOT_FOUND: 借调单 % 不存在', p_id;
  END IF;
  -- 只能从 draft 转。驳回的不能通过、通过的不能再审 —— 这是状态机，不是参数校验。
  IF d.status <> 'draft' THEN
    RAISE EXCEPTION 'E_DISPATCH_BAD_STATE: 借调单 % 已是「%」，只有草稿能审批', p_id, d.status;
  END IF;

  v_note := NULLIF(left(btrim(COALESCE(p_note, '')), 200), '');

  -- ---- 驳回 ----
  IF p_ok IS NOT TRUE THEN
    IF v_note IS NULL OR length(v_note) < 4 THEN
      RAISE EXCEPTION 'E_DISPATCH_NO_NOTE: 驳回必须写意见（至少 4 个字）——'
        '不写的话申请人只会重新提一遍';
    END IF;
    UPDATE public.roster_dispatch SET status = 'rejected', note = v_note WHERE id = p_id;
    RETURN 'rejected';
  END IF;

  -- ---- 通过 ----
  -- ① 建单之后可能又批了另一张压在同一段日历上的单（建单时会拦草稿重叠，
  --    但"两张草稿都提了、先批了后一张"这条路仍然存在）。批之前**再校验一次**。
  IF EXISTS (
    SELECT 1 FROM public.roster_dispatch x
     WHERE x.employee_id = d.employee_id AND x.id <> d.id
       AND x.status IN ('approved','finished')
       AND daterange(x.from_date, x.to_date, '[]') && daterange(d.from_date, d.to_date, '[]')
  ) THEN
    RAISE EXCEPTION 'E_DISPATCH_OVERLAP: 员工 % 在 % → % 已经有一段有效借调'
      '（草稿期间批的），这段不能再通过', d.employee_id, d.from_date, d.to_date;
  END IF;

  -- ② 找到借调开始那天**正在生效**的考勤归属段
  SELECT * INTO v_cur
    FROM public.employee_org_assignment a
   WHERE a.employee_id = d.employee_id AND a.dim_code = 'attendance_org'
     AND daterange(a.valid_from, a.valid_to, '[]') @> d.from_date
   ORDER BY a.valid_from DESC LIMIT 1
   FOR UPDATE;

  v_resume_org := COALESCE(v_cur.org_id, d.from_org);

  -- 建单时人还在 A 店，批的时候已经调去 B 店了 —— 这不是"借调"，是过期的单
  IF v_resume_org = d.to_org THEN
    RAISE EXCEPTION 'E_DISPATCH_SAME_ORG: 员工 % 现在已归属 %，'
      '这张单建的时候还是从别处借（%），请作废重提',
      d.employee_id, d.to_org, d.from_org;
  END IF;

  -- ③ 借调窗口内不允许有别人的组织变更（预排的调动/上一张借调）
  --    v_cur 自己会被切开，所以先排掉它，再数剩下的。
  IF v_cur.id IS NOT NULL AND v_cur.valid_to IS NOT NULL AND v_cur.valid_to < d.to_date THEN
    RAISE EXCEPTION 'E_DISPATCH_ORG_BUSY: 员工 % 的考勤归属在 % 就结束了，'
      '覆盖不了整段借调（% → %），先把那条归属补齐或缩短借调',
      d.employee_id, v_cur.valid_to, d.from_date, d.to_date;
  END IF;

  SELECT count(*) INTO v_other
    FROM public.employee_org_assignment a
   WHERE a.employee_id = d.employee_id AND a.dim_code = 'attendance_org'
     AND daterange(a.valid_from, a.valid_to, '[]') && daterange(d.from_date, d.to_date, '[]')
     AND (v_cur.id IS NULL OR a.id <> v_cur.id);
  IF v_other > 0 THEN
    RAISE EXCEPTION 'E_DISPATCH_ORG_BUSY: 员工 % 在 % → % 之间已经有别的考勤归属变更'
      '（预排的调动或另一段借调），借调会和它打架', d.employee_id, d.from_date, d.to_date;
  END IF;

  -- ④ 切开原段 → 借调段 → 复归段
  --    时间轴（'[]'）：  原店 [.., from-1] | 目标店 [from, to] | 原店 [to+1, ..]
  IF v_cur.id IS NOT NULL THEN
    UPDATE public.employee_org_assignment
       SET valid_to = d.from_date - 1 WHERE id = v_cur.id;
  END IF;

  INSERT INTO public.employee_org_assignment
    (employee_id, dim_code, org_id, valid_from, valid_to)
  VALUES (d.employee_id, 'attendance_org', d.to_org, d.from_date, d.to_date);

  -- 复归段：到期**不删**这段借调归属，也不需要定时任务 ——
  -- 这条复归段让 to_date 之后自然回到原店，且历史上每一天都有唯一答案。
  --
  -- ★ 只在"原来真有一段 attendance_org"时才补复归段。原来没有的话
  --   （from_org 是从 cost_org 回退来的），补一条开到无期的 attendance_org
  --   会把"跟着成本组织走"变成"钉死在今天这个值"—— 以后 cost_org 变了，
  --   attendance_org 不会再跟。借调结束后回到回退逻辑，本身就是原来那个答案。
  IF v_cur.id IS NOT NULL THEN
    v_resume_to := v_cur.valid_to;                 -- 原段本来是开到无期就继续无期
    SELECT * INTO v_next
      FROM public.employee_org_assignment a
     WHERE a.employee_id = d.employee_id AND a.dim_code = 'attendance_org'
       AND a.valid_from > d.to_date
     ORDER BY a.valid_from LIMIT 1;
    IF v_next.id IS NOT NULL
       AND (v_resume_to IS NULL OR v_resume_to > v_next.valid_from - 1) THEN
      v_resume_to := v_next.valid_from - 1;        -- 后面还有预排的变更，复归段到这里为止
    END IF;

    IF v_resume_to IS NULL OR v_resume_to >= d.to_date + 1 THEN
      INSERT INTO public.employee_org_assignment
        (employee_id, dim_code, org_id, valid_from, valid_to)
      VALUES (d.employee_id, 'attendance_org', v_resume_org, d.to_date + 1, v_resume_to);
    END IF;
  END IF;

  -- ⑤ 单据落状态。from_org 按批准当天的事实校正 —— 建单时那条可能已经过期。
  UPDATE public.roster_dispatch
     SET status = 'approved', approved_by = COALESCE(p_by, 'system'),
         approved_at = now(), note = v_note, from_org = v_resume_org
   WHERE id = d.id;

  RETURN 'approved';
END;
$$;

COMMENT ON FUNCTION fn_dispatch_approve IS
  '审批借调。通过 = 写一条 attendance_org 归属（valid_from=from_date, valid_to=to_date）'
  '+ 切成三段（原店 / 目标店 / 复归段）。此后考勤与成本按维度时点自动落对门店，'
  '到期不需要任何定时任务。驳回必须写意见；只能从 draft 转；通过前再校验一次重叠。';

-- ---------------------------------------------------------------------------
-- 4. 提前结束
-- ---------------------------------------------------------------------------
-- ★ p_on 有默认值（今天），但**不写死 current_date**：
--   断言要能钉住"某一天结束"这个事实，用 current_date 的话同一条断言换一天两个答案。
CREATE OR REPLACE FUNCTION fn_dispatch_end(
  p_id bigint,
  p_by varchar,
  p_on date DEFAULT NULL
) RETURNS varchar
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  d     public.roster_dispatch%ROWTYPE;
  v_on  date;
  v_act date;
BEGIN
  SELECT * INTO d FROM public.roster_dispatch WHERE id = p_id FOR UPDATE;
  IF d.id IS NULL THEN
    RAISE EXCEPTION 'E_DISPATCH_NOT_FOUND: 借调单 % 不存在', p_id;
  END IF;
  IF d.status <> 'approved' THEN
    RAISE EXCEPTION 'E_DISPATCH_BAD_STATE: 借调单 % 是「%」，只有已通过的借调能结束',
      p_id, d.status;
  END IF;

  v_act := COALESCE(p_on, current_date);

  -- 还没开始就结束 = 撤单：把那条归属删掉，什么都不留（它是我在审批时插的，没有别处引用）
  IF v_act < d.from_date THEN
    DELETE FROM public.employee_org_assignment
     WHERE employee_id = d.employee_id AND dim_code = 'attendance_org'
       AND org_id = d.to_org
       AND valid_from = d.from_date AND valid_to = d.to_date;
    UPDATE public.roster_dispatch
       SET status = 'cancelled',
           note = left(concat_ws('；', note, '未开始即撤回'), 200)
     WHERE id = d.id;
    RETURN 'cancelled';
  END IF;

  -- 实际到哪天为止：不超过原计划
  v_on := LEAST(v_act, d.to_date);

  -- 归属段原位收口 —— 这一段就是"提前调回"的全部实现
  UPDATE public.employee_org_assignment
     SET valid_to = v_on
   WHERE employee_id = d.employee_id AND dim_code = 'attendance_org'
     AND org_id = d.to_org
     AND valid_from = d.from_date AND valid_to = d.to_date;

  -- ★ 复归段也要跟着提前。少了这一句会出现一段**归属空档**：
  --   借调段收到 11-17、复归段还从 11-19 起 → 11-18 那天这个人既不在 A 店
  --   也不在 B 店，考勤与报表都查不到他，而页面上什么都看不出来。
  --   （探针里就是这样抓到的：11-18 的时点归属为空。）
  UPDATE public.employee_org_assignment
     SET valid_from = v_on + 1
   WHERE employee_id = d.employee_id AND dim_code = 'attendance_org'
     AND valid_from = d.to_date + 1;

  -- ★ to_date 一起改成实际结束日：它现在**代表"实际支援了哪几天"**，
  --   而 fn_dispatch_active / fn_dispatch_cost 都按它算。留着原计划日期的话，
  --   一个 11-15 提前回来的人会在 11-20 之前一直被当成"还在借调"，
  --   排班会跳过他，成本会继续往目标店转移 —— 两个都不会报错。
  UPDATE public.roster_dispatch
     SET status = 'finished', ended_at = now(), to_date = v_on,
         note = left(concat_ws('；', note, '提前结束：原计划至 ' || d.to_date), 200)
   WHERE id = d.id;

  RETURN 'finished';
END;
$$;

COMMENT ON FUNCTION fn_dispatch_end IS
  '提前结束借调：把那条 attendance_org 归属的 valid_to 收到今天（不超过原计划），'
  '并把 to_date 改成实际结束日（否则"还在借调"会一直成立）。'
  '还没开始就结束 → 删归属、状态 cancelled。p_on 默认今天，断言可钉住具体日期。';

-- ---------------------------------------------------------------------------
-- 5. 某人某天是否在借调中
-- ---------------------------------------------------------------------------
-- 给周期排班 / 划线用：这些人那天在别的店，本店的排班必须跳过。
-- 没有这条，两个店会同时给他排班，工时被算两遍。
CREATE OR REPLACE FUNCTION fn_dispatch_active(
  p_person bigint,
  p_on     date
) RETURNS TABLE (
  dispatch_id bigint, to_org bigint, to_org_name varchar, from_date date, to_date date
)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT d.id, d.to_org, o.name, d.from_date, d.to_date
    FROM public.roster_dispatch d
    JOIN public.org_unit o ON o.id = d.to_org
   WHERE d.employee_id = p_person
     AND d.status IN ('approved','finished')
     AND daterange(d.from_date, d.to_date, '[]') @> p_on
   ORDER BY d.from_date DESC
   LIMIT 1;
$$;

COMMENT ON FUNCTION fn_dispatch_active IS
  '某人某天是否在借调中（返回目标门店）。排班/划线要跳过这些人，'
  '否则两个店会同时给他排班、工时被算两遍。finished 也算 —— to_date 是实际结束日。';

-- ---------------------------------------------------------------------------
-- 6. 借调带来的成本转移
-- ---------------------------------------------------------------------------
-- ★ 工时取 attendance_daily_store.work_hours，不取 att_period_report：
--   att_period_report 是**人 × 月**一行，一个人 11 月上半月在 A 店、下半月借去 B 店，
--   月报只有一个 work_hours，没法按天切开 —— 用它算分摊，只能按天数比例估算，
--   而估算值会和工资条上的实际工时对不上，对账时第一个被发现。
--   人日表有 (employee, store, work_date, work_hours)，是唯一能"按天分"的口径。
--   代价：必须已经导入/生成了人日。没有考勤就没有分摊额 —— 这是对的，
--   没干活的天不该产生成本转移。
--
-- ★ 谁承担成本：借出方（p_from_org）的工时成本**转到** to_org。
--   返回的每一行是"某个目标门店接收了多少成本"，调用方拿去做两侧分录。
CREATE OR REPLACE FUNCTION fn_dispatch_cost(
  p_from_org bigint,
  p_period   varchar
) RETURNS TABLE (
  org_id bigint, org_name varchar, person_count int, days int, hours numeric
)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE
  v_start date;
  v_end   date;
BEGIN
  IF p_period IS NULL OR p_period !~ '^\d{4}-(0[1-9]|1[0-2])$' THEN
    RAISE EXCEPTION 'E_PERIOD_INVALID: 期间写 YYYY-MM，收到「%」', COALESCE(p_period, '');
  END IF;
  v_start := (p_period || '-01')::date;
  v_end   := (v_start + interval '1 month - 1 day')::date;

  RETURN QUERY
  SELECT x.to_org, x.org_name,
         count(DISTINCT x.employee_id)::int,   -- 涉及几个人
         count(*)::int,                        -- 人天：人日表 (employee,work_date) 唯一，一行就是一人一天
         round(sum(x.work_hours), 2)
    FROM (SELECT d.to_org AS to_org, o.name AS org_name,
                 a.employee_id, a.work_date, a.work_hours
            FROM public.roster_dispatch d
            JOIN public.attendance_daily_store a
              ON a.employee_id = d.employee_id
             AND a.work_date BETWEEN d.from_date AND d.to_date
            JOIN public.org_unit o ON o.id = d.to_org
           WHERE d.from_org = p_from_org
             AND d.status IN ('approved','finished')
             AND a.work_date BETWEEN v_start AND v_end) x
   GROUP BY x.to_org, x.org_name
   ORDER BY x.to_org;
END;
$$;

COMMENT ON FUNCTION fn_dispatch_cost IS
  '某借出组织在某期间的工时成本转移：按 (借调天数 × 实际人日工时) 汇总到目标门店。'
  '工时取 attendance_daily_store（人日）而不是 att_period_report（人×月）——'
  '月报没法把一个月的工时按天切给两家店，切不开就只能估算，而估算与工资条对不上。'
  'days = 借调窗口内实际有考勤记录的**人天**（没干活的天不产生转移）。';
