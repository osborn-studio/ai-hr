-- ============================================================================
-- 129_annual_leave_cashout.sql · 未休年假折现（法定 300%，含已发工资）
-- ----------------------------------------------------------------------------
-- 057 把折现"刻意不做"，理由写得很实：单价、计税、社保基数、出哪张单，
-- 五个问题每一个都能让财务和 HR 吵起来。这一版逐个回答，答案都写在下面对应小节。
--
-- 法条依据（这一条最容易被算错，所以原文摆出来）：
--   《职工带薪年休假条例》第 5 条第 3 款：
--     "单位确因工作需要不能安排职工休年休假的，经职工本人同意，
--      可以不安排职工休年休假。对职工应休未休的年休假天数，
--      单位应当按照该职工日工资收入的 **300%** 支付年休假工资报酬。"
--   《企业职工带薪年休假实施办法》（人社部令第 1 号）
--     第 3 条：累计工作已满 1 年不满 10 年 5 天；满 10 年不满 20 年 10 天；满 20 年 15 天。
--     第 10 条：300% 中含"用人单位支付职工正常工作期间的工资收入"。
--     第 11 条：日工资收入 = 月工资 ÷ 21.75；月工资 = 前 12 个月剔除加班费后的月平均。
--     第 12 条：当年度已过日历天数 ÷ 365 × 全年应享受天数 − 已安排天数，
--               折算后**不足 1 整天的部分不支付**。
--
-- ★★ 最容易错的那一处：**300% 里已经包含正常工资**。
--    所以员工在职时工资照发、折现时**只能再补 200%**。
--    按 300% 全额再发一遍 = 付了 400%，多付一倍。
--    这也是"离职当月工资已发到离职日"时同样只能用 200% 的原因。
--    法定默认因此是 extra_200，total_300 保留但标注"优于法定、成本翻倍"。
--
-- 五个问题的答案（057 留下的）：
--   ① 单价：前 12 个月应发（剔除 OT_PAY 与 AL_CASHOUT）÷ 实际月数 ÷ 21.75。
--      剔除 AL_CASHOUT 是我加的：不剔的话今年折一次、明年基数被自己抬高。
--   ② 计税：不特殊处理 —— 它进工资条一行、进应发合计，自然走累计预扣。
--      单独按"偶然所得"计税是错的（它不是偶然所得，是工资性收入）。
--   ③ 社保基数：不进。基数按**月薪标准**申报（105 的规矩），一笔一次性折现
--      不该改变申报基数 —— 各地对"上年度月平均工资"的口径也不含这种一次性补偿。
--   ④ 出哪张单：进当月工资条一行 AL_CASHOUT，不另开单。
--      另开单会让"应发合计"这个数在财务口径上分成两处，对账时必然要手工加。
--   ⑤ 要不要审批：要。折现是**发钱**，走"登记 → 算薪时落账"两步，
--      登记单据可查、可作废，不会因为改了制度项就把历史月份的钱改掉。
--
-- 配置项规矩照旧（客户 2026-10-17 定下的）：
--   · 默认 off = 上线前行为（以前一分不折）；
--   · 集团定，门店不能自己定（同一集团两种折现口径，集团报表无法解释）；
--   · 改配置 ⇒ 行为真的跟着变，有反例断言（AL4/AL5/AL6）。
-- ============================================================================

