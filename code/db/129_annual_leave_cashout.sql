-- 按 code 取假种 id（各处散着写 SELECT id FROM leave_type WHERE code=... 容易抄错列）
CREATE OR REPLACE FUNCTION fn_leave_type_id(p_code varchar)
RETURNS bigint
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT lt.id FROM public.leave_type lt WHERE lt.code = p_code;
$$;

COMMENT ON FUNCTION fn_leave_type_id IS
  '按 code 取假种 id。假种 id 不是 identity（126 踩过），写死数字会在重灌库后指向别的假种。';

-- ★ 折现**不进** leave_usage，理由是一个已踩过的坑：
--   作废折现单时要把额度还回去。如果冲减写在 leave_usage 里，
--   就得再造一个"反向行"把它抵掉 —— 而 available 的公式里没有这一项，
--   于是作废之后额度永远少一块，且看不出来少在哪。
--   折现天数直接由 leave_cashout 派生（见第 7 节的视图），作废即自动加回，
--   不需要反向行，也不会漂。台账（谁、几天、多少钱、为什么）在 leave_cashout 里。

-- ---------------------------------------------------------------------------
-- 1. 累计工龄：入职前的年限得能录进来
-- ---------------------------------------------------------------------------
-- 年假天数按**累计**工作年限算，不是本单位年限。一个人 30 岁入职，
-- 累计工龄 8 年，第一年就该有 5 天年假，而不是"新员工没有"。
-- 系统只能看到本单位入职日，入司前的年限必须人工录 —— 所以给它一列。
-- 默认 0 = 只按本单位年限算（上线前的行为，有断言兜底）。
ALTER TABLE employment ADD COLUMN IF NOT EXISTS prior_work_years numeric(4,1) NOT NULL DEFAULT 0;

ALTER TABLE employment DROP CONSTRAINT IF EXISTS ck_emp_prior_years;
ALTER TABLE employment ADD CONSTRAINT ck_emp_prior_years
  CHECK (prior_work_years >= 0 AND prior_work_years <= 50);

COMMENT ON COLUMN employment.prior_work_years IS
  '入司前累计工作年限（年）。年假天数按"累计工龄"算，系统看不到入司前，必须人工录。'
  '默认 0 = 只按本单位年限（上线前行为）。';

-- ---------------------------------------------------------------------------
-- 2. 年假天数档位（法定 5/10/15，可上调不可下调）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS annual_leave_tier (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  years_from numeric(4,1) NOT NULL,      -- 累计工龄下限（含）
  days       numeric(4,1) NOT NULL,      -- 全年应享天数
  note       varchar(120),

  CONSTRAINT uk_alt UNIQUE (years_from),
  CONSTRAINT ck_alt_years CHECK (years_from >= 0),
  CONSTRAINT ck_alt_days CHECK (days > 0 AND days <= 30),
  -- ★ 硬下限：法定 5 / 10 / 15。企业可以更好（给 7 天、12 天），
  --   不能更少 —— 少给就是违法，这个不留给界面去"灵活"（与病假 60% 同一条规矩）。
  CONSTRAINT ck_alt_legal CHECK (
    days >= CASE WHEN years_from >= 20 THEN 15
                 WHEN years_from >= 10 THEN 10
                 ELSE 5 END)
);

INSERT INTO annual_leave_tier(years_from, days, note) VALUES
  (0,  5,  '满 1 年不满 10 年（法定）'),
  (10, 10, '满 10 年不满 20 年（法定）'),
  (20, 15, '满 20 年以上（法定）')
ON CONFLICT (years_from) DO NOTHING;

COMMENT ON TABLE annual_leave_tier IS
  '年假天数档位：累计工龄满 years_from 年起，全年应享 days 天。'
  '默认灌法定三档（5/10/15），界面可上调（优于法定），不许下调（违法）。';

-- 累计工龄（年）：入司前年限 + 本单位年限（按 365.25 天/年折算，含当天）
CREATE OR REPLACE FUNCTION fn_cumulative_years(p_employee bigint, p_on date)
RETURNS numeric
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT round(COALESCE(e.prior_work_years, 0)
               + GREATEST((p_on - e.hire_date), 0) / 365.25, 2)
    FROM public.employment e
   WHERE e.person_id = p_employee
     AND daterange(e.hire_date, e.leave_date, '[]') @> p_on
   ORDER BY e.hire_date DESC LIMIT 1;
$$;

COMMENT ON FUNCTION fn_cumulative_years IS
  '累计工龄（年）= 入司前年限 + 本单位年限。年假天数按它查档，不按本单位年限。';

-- 按累计工龄查应享天数（查不到档位时回退法定 5 天，不返回 NULL）
CREATE OR REPLACE FUNCTION fn_annual_leave_days(p_employee bigint, p_on date)
RETURNS numeric
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT COALESCE(
    (SELECT t.days FROM public.annual_leave_tier t
      WHERE t.years_from <= COALESCE(public.fn_cumulative_years(p_employee, p_on), 0)
      ORDER BY t.years_from DESC LIMIT 1),
    5);
$$;

-- ---------------------------------------------------------------------------
-- 3. 折现台账
-- ---------------------------------------------------------------------------
-- ★ 为什么不直接写进 leave_usage 就完事：折现是"发钱"，钱要有个去处
--   （哪个月发、发了多少、基数是多少）。只改余额的话，月底对不上账时
--   没人说得清那 5 天是"休了"还是"折了"还是"作废了"。
CREATE TABLE IF NOT EXISTS leave_cashout (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id    bigint NOT NULL,
  leave_type_id  bigint NOT NULL REFERENCES leave_type(id),
  leave_year     int    NOT NULL,
  days           numeric(6,2) NOT NULL,
  monthly_wage   numeric(12,2) NOT NULL,   -- 折算基数（前 12 个月剔除加班费后的平均）
  daily_wage     numeric(14,4) NOT NULL,
  rate           numeric(4,2) NOT NULL,    -- 2.00 额外补 200% / 3.00 一次性 300%
  amount         numeric(12,2) NOT NULL,
  settle_period  varchar(7)  NOT NULL,     -- 落到哪个月工资（YYYY-MM）
  status         varchar(12) NOT NULL DEFAULT 'pending',
  reason         varchar(200) NOT NULL,
  created_by     varchar(64) NOT NULL DEFAULT 'system',
  created_at     timestamptz NOT NULL DEFAULT now(),
  payslip_id     bigint,

  CONSTRAINT ck_lc_days   CHECK (days > 0),
  CONSTRAINT ck_lc_rate   CHECK (rate >= 2.0 AND rate <= 3.0),
  CONSTRAINT ck_lc_amount CHECK (amount > 0),
  CONSTRAINT ck_lc_status CHECK (status IN ('pending','paid','void')),
  CONSTRAINT ck_lc_period CHECK (settle_period ~ '^\d{4}-(0[1-9]|1[0-2])$')
);

-- 同一个人、同一年、同一个假种，只能有一条有效折现。
-- 用部分唯一索引而不是 UNIQUE(...) —— 作废的单据要能重开，
-- 而"作废之后不许重开"会让填错一次就永远折不了。
CREATE UNIQUE INDEX IF NOT EXISTS ux_lc_once
  ON leave_cashout (employee_id, leave_type_id, leave_year)
  WHERE status <> 'void';

CREATE INDEX IF NOT EXISTS ix_lc_settle ON leave_cashout (settle_period, status);

COMMENT ON TABLE leave_cashout IS
  '未休年假折现台账。status: pending 已登记待发 / paid 已进工资条 / void 作废。'
  'rate=2 额外补 200%（法定：工资已照发）/ rate=3 一次性 300%（优于法定，成本翻倍）。';

-- ---------------------------------------------------------------------------
-- 4. 应休未休天数（第 12 条的折算）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_annual_leave_unused(p_employee bigint, p_on date)
RETURNS numeric
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE
  v_year    int := EXTRACT(year FROM p_on)::int;
  v_entitle numeric(6,2);
  v_elapsed int;
  v_prorata numeric(8,2);
  v_taken   numeric(6,2);
  v_cashed  numeric(6,2);
  v_unused  numeric(6,2);
  v_avail   numeric(6,2);
BEGIN
  v_entitle := public.fn_annual_leave_days(p_employee, p_on);

  -- 已过日历天数（含当天）。12/31 当日 = 365（闰年 366），比例正好 1。
  v_elapsed := p_on - make_date(v_year, 1, 1) + 1;
  v_prorata := round(v_entitle * v_elapsed / 365.0, 4);

  -- 已休：只算本年批准的 ANNUAL 申请。按 date_from 归年 —— 跨年那几天
  -- 归到起始年，会让 12/31–1/2 的三天全算在上一年。
  SELECT COALESCE(SUM(lr.qty), 0) INTO v_taken
    FROM public.leave_request lr
    JOIN public.leave_type lt ON lt.id = lr.leave_type_id
   WHERE lr.employee_id = p_employee AND lt.code = 'ANNUAL'
     AND lr.status = 'approved'
     AND lr.date_from >= make_date(v_year, 1, 1)
     AND lr.date_from <= p_on;

  -- 已折现：不算"休"，但也不能再折一次
  SELECT COALESCE(SUM(c.days), 0) INTO v_cashed
    FROM public.leave_cashout c
   WHERE c.employee_id = p_employee AND c.leave_year = v_year
     AND c.status <> 'void';

  -- ★ 第 12 条原文："折算后不足 1 整天的部分不予支付" → FLOOR。
  --   用 round 会让 0.6 天变成 1 天，也就是多付一天的钱 —— 而"多付"没人投诉，
  --   所以这种错会一直在，直到审计查到。用 GREATEST 兜住负数（休多了不该倒扣钱）。
  v_unused := GREATEST(floor(v_prorata - v_taken - v_cashed), 0);

  -- ★ 再用**授予额度**封顶：没给过额度的人不该折出现金。
  --   这条在离职场景是必须的 —— 有人台账只授予 5 天、按工龄算应有 15 天，
  --   不封顶就会折 15 天，余额变成 −10，而负数在余额页上看起来像系统算错了。
  --   没有授予记录（NULL）时不封顶：视为按制度直接享有。
  SELECT b.available INTO v_avail
    FROM public.v_leave_balance b
   WHERE b.employee_id = p_employee
     AND b.leave_type_id = public.fn_leave_type_id('ANNUAL');

  IF v_avail IS NOT NULL THEN
    v_unused := LEAST(v_unused, GREATEST(v_avail, 0));
  END IF;

  RETURN v_unused;
END;
$$;

COMMENT ON FUNCTION fn_annual_leave_unused IS
  '应休未休天数 = min(floor(全年应享 × 已过日历天/365 − 已休 − 已折现), 授予余额)，不足 1 天不付。'
  '第 12 条原文如此；用 round 会多付，而多付不会有人投诉，所以必须写成 floor。';

-- ---------------------------------------------------------------------------
-- 5. 折现基数：前 12 个月剔除加班费的月平均（第 11 条）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_cashout_monthly_wage(p_employee bigint, p_on date)
RETURNS numeric
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE
  v_avg   numeric(12,2);
  v_std   numeric(12,2);
  v_n     int;
BEGIN
  -- ★ 剔除两类：OT_PAY（第 11 条明写剔除加班费）、AL_CASHOUT（折现自己抬高基数）。
  --   提成与年终奖**不剔** —— 它们都是工资性收入，法条没给剔的理由。
  SELECT round(avg(x.m), 2), count(*) INTO v_avg, v_n
    FROM (
      SELECT (p.gross_amount - COALESCE(SUM(pi.amount) FILTER (
                WHERE pi.item_code IN ('OT_PAY','AL_CASHOUT','ANNUAL_BONUS')), 0)) AS m
        FROM public.payslip p
        JOIN public.pay_run pr ON pr.id = p.pay_run_id
        LEFT JOIN public.payslip_item pi ON pi.payslip_id = p.id
       WHERE p.employee_id = p_employee
         AND pr.status IN ('sealed','paid')
         AND pr.period <= to_char(p_on, 'YYYY-MM')
       GROUP BY p.id, p.gross_amount, pr.period
       ORDER BY pr.period DESC
       LIMIT 12
    ) x;

  IF v_n > 0 AND v_avg > 0 THEN
    RETURN v_avg;
  END IF;

  -- 一个月工资条都没有（新入职、或历史没导）：回退月薪标准，并在调用方留痕
  SELECT s.monthly_amount INTO v_std
    FROM public.salary_standard s
    JOIN public.employment e ON e.id = s.employment_id
   WHERE e.person_id = p_employee AND s.effective_from <= p_on
   ORDER BY s.effective_from DESC LIMIT 1;

  RETURN COALESCE(v_std, 0);
END;
$$;

COMMENT ON FUNCTION fn_cashout_monthly_wage IS
  '折现基数 = 前 12 个月应发（剔除 OT_PAY / AL_CASHOUT / ANNUAL_BONUS）的月平均；'
  '没有历史工资条时回退月薪标准。第 11 条：剔除加班费，未说剔除提成。';

-- ---------------------------------------------------------------------------
-- 5b. 试算：界面要在**登记之前**告诉 HR 会付多少钱
-- ---------------------------------------------------------------------------
-- 不给试算的话，HR 只能靠"登记一下看看"来估金额，而登记已经是留痕的动作。
CREATE OR REPLACE FUNCTION fn_annual_leave_quote(p_employee bigint, p_on date)
RETURNS TABLE(days numeric, monthly_wage numeric, daily_wage numeric,
              rate numeric, amount numeric, mode varchar)
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE
  v_mode varchar(16);
  v_days_pp numeric(6,2);
  v_m  numeric(12,2);
  v_d  numeric(14,4);
  v_days numeric(6,2);
  v_rate numeric(4,2);
BEGIN
  SELECT value_text INTO v_mode
    FROM public.fn_policy_effective('LEAVE_ANNUAL_CASHOUT', NULL, p_on);
  v_mode := COALESCE(v_mode, 'off');

  SELECT COALESCE(value_num, 21.75) INTO v_days_pp
    FROM public.fn_policy_effective('PAY_DAYS_PER_MONTH', NULL, p_on);

  v_days := public.fn_annual_leave_unused(p_employee, p_on);
  v_m    := public.fn_cashout_monthly_wage(p_employee, p_on);
  v_d    := CASE WHEN v_m > 0 THEN round(v_m / GREATEST(v_days_pp, 1), 4) ELSE 0 END;
  v_rate := CASE v_mode WHEN 'total_300' THEN 3.0 WHEN 'extra_200' THEN 2.0 ELSE 0 END;

  days := v_days; monthly_wage := v_m; daily_wage := v_d;
  rate := v_rate; amount := round(v_d * v_days * v_rate, 2); mode := v_mode;
  RETURN NEXT;
END;
$$;

COMMENT ON FUNCTION fn_annual_leave_quote IS
  '折现试算：返回天数 / 基数 / 日薪 / 费率 / 金额 / 当前制度口径。mode=off 时 rate=0、amount=0。'
  '界面用它做"登记前预览"，避免 HR 靠登记一张单才知道要付多少钱。';

-- ---------------------------------------------------------------------------
-- 6. 登记折现（发钱前的一步，可查可作废）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_annual_leave_cashout(
  p_employee bigint,
  p_on       date,
  p_period   varchar,
  p_reason   varchar,
  p_by       varchar DEFAULT 'system'
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_mode    varchar(16);
  v_days    numeric(6,2);
  v_monthly numeric(12,2);
  v_daily   numeric(14,4);
  v_rate    numeric(4,2);
  v_days_pp numeric(6,2);
  v_amt     numeric(12,2);
  v_type    bigint;
  v_year    int := EXTRACT(year FROM p_on)::int;
  v_id      bigint;
BEGIN
  IF p_reason IS NULL OR length(btrim(p_reason)) < 4 THEN
    RAISE EXCEPTION 'E_ALC_NO_REASON: 折现必须写原因（至少 4 个字）；'
      '只留一个金额，三个月后没人答得出"为什么给他折现"';
  END IF;

  -- ★ 同一年只能有一张有效折现单。不拦的话会撞部分唯一索引（23505），
  --   而那个报错读起来像"数据库出错了"，不像"你今年已经折过了"。
  IF EXISTS (SELECT 1 FROM public.leave_cashout c
              WHERE c.employee_id = p_employee
                AND c.leave_year = EXTRACT(year FROM p_on)::int
                AND c.status <> 'void') THEN
    RAISE EXCEPTION 'E_ALC_EXISTS: 员工 % 在 % 年已经登记过折现单；'
      '要改口径先把原单作废，再重新登记（作废后额度会自动加回）',
      p_employee, EXTRACT(year FROM p_on)::int;
  END IF;

  SELECT value_text INTO v_mode
    FROM public.fn_policy_effective('LEAVE_ANNUAL_CASHOUT', NULL, p_on);

  IF COALESCE(v_mode, 'off') = 'off' THEN
    RAISE EXCEPTION 'E_ALC_OFF: 制度项 LEAVE_ANNUAL_CASHOUT 当前是 off（默认），'
      '未休年假一律不折现。要折现请先由 HR 主管以上改这项制度';
  END IF;

  IF v_mode NOT IN ('extra_200','total_300') THEN
    RAISE EXCEPTION 'E_ALC_MODE: LEAVE_ANNUAL_CASHOUT 的取值 % 不认识（off/extra_200/total_300）', v_mode;
  END IF;

  SELECT COALESCE(value_num, 21.75) INTO v_days_pp
    FROM public.fn_policy_effective('PAY_DAYS_PER_MONTH', NULL, p_on);

  v_days := public.fn_annual_leave_unused(p_employee, p_on);
  IF v_days <= 0 THEN
    RAISE EXCEPTION 'E_ALC_NO_UNUSED: 员工 % 在 % 没有应休未休年假（折算后不足 1 天），没有可折现的部分',
      p_employee, p_on;
  END IF;

  v_monthly := public.fn_cashout_monthly_wage(p_employee, p_on);
  IF v_monthly <= 0 THEN
    RAISE EXCEPTION 'E_ALC_NO_WAGE: 员工 % 没有月薪标准也没有历史工资条，算不出折现基数', p_employee;
  END IF;

  v_daily := round(v_monthly / GREATEST(v_days_pp, 1), 4);
  v_rate  := CASE WHEN v_mode = 'total_300' THEN 3.0 ELSE 2.0 END;
  v_amt   := round(v_daily * v_days * v_rate, 2);
  v_type  := public.fn_leave_type_id('ANNUAL');

  INSERT INTO public.leave_cashout(employee_id, leave_type_id, leave_year, days,
                                   monthly_wage, daily_wage, rate, amount,
                                   settle_period, reason, created_by)
  VALUES (p_employee, v_type, v_year, v_days, v_monthly, v_daily, v_rate, v_amt,
          p_period, btrim(p_reason), p_by)
  RETURNING id INTO v_id;

  -- 额度冲减不写在这里：余额视图直接减 leave_cashout 的天数（见第 7 节）。
  -- 写进 leave_usage 就得为作废再造反向行，而 available 公式里没这一项，
  -- 作废之后额度会永远少一块，且看不出来少在哪。
  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_annual_leave_cashout IS
  '登记未休年假折现：只写 leave_cashout（pending）。额度由视图按本表派生，作废即自动加回。'
  'rate：extra_200 补 2 倍（法定，工资已照发）/ total_300 一次付 3 倍（优于法定）。'
  '不做自动折现 —— 折现是发钱，要有单据、有原因、有人签字。';

-- 折现作废：钱还没进工资条才能作废，且额度要还回去
CREATE OR REPLACE FUNCTION fn_annual_leave_cashout_void(
  p_id bigint, p_why varchar, p_by varchar DEFAULT 'system'
) RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE c public.leave_cashout%ROWTYPE;
BEGIN
  SELECT * INTO c FROM public.leave_cashout WHERE id = p_id FOR UPDATE;
  IF c.id IS NULL THEN RAISE EXCEPTION 'E_ALC_NOT_FOUND: 折现单 % 不存在', p_id; END IF;
  IF c.status = 'paid' THEN
    RAISE EXCEPTION 'E_ALC_PAID: 折现单 % 已经进了工资条（% 月），不能作废；'
      '要改就在那个月红冲，否则账上会凭空少一笔钱', p_id, c.settle_period;
  END IF;
  IF c.status = 'void' THEN RETURN; END IF;
  IF p_why IS NULL OR length(btrim(p_why)) < 4 THEN
    RAISE EXCEPTION 'E_ALC_VOID_REASON: 作废要写原因（至少 4 个字）';
  END IF;

  -- 只改状态：额度在视图里按 status <> 'void' 汇总，改完立即加回。
  -- 不做反向行 —— 反向行会留下两条互抵的记录，对账时解释起来比不还更难。
  UPDATE public.leave_cashout SET status = 'void' WHERE id = p_id;
END;
$$;

-- ---------------------------------------------------------------------------
-- 7. 余额视图：折现天数直接从 leave_cashout 派生
-- ---------------------------------------------------------------------------
-- ★ 必须 DROP 再建：CREATE OR REPLACE VIEW 不允许改列序。
--   057 那条注释已经记过一次这个坑（42P16 读起来像改错了名字）。
--
-- ★ cashed 不是 leave_usage 的状态，是 leave_cashout 的汇总：
--   作废一张折现单（status='void'）额度应当立刻回到可用，
--   写成台账状态的话得再造一条反向行才能还回去，而 available 公式里没有反向行这一项。
DROP VIEW IF EXISTS v_leave_balance;
CREATE VIEW v_leave_balance AS
WITH g AS (
  SELECT employee_id, leave_type_id,
         SUM(qty) FILTER (WHERE valid_to IS NULL OR valid_to >= current_date) AS granted,
         SUM(qty) FILTER (WHERE valid_to IS NOT NULL AND valid_to <  current_date) AS expired
    FROM leave_grant GROUP BY employee_id, leave_type_id
), u AS (
  SELECT employee_id, leave_type_id,
         SUM(qty) FILTER (WHERE state = 'frozen')    AS frozen,
         SUM(qty) FILTER (WHERE state = 'used')      AS used,
         SUM(qty) FILTER (WHERE state = 'forfeited') AS forfeited
    FROM leave_usage GROUP BY employee_id, leave_type_id
), c AS (
  SELECT employee_id, leave_type_id, SUM(days) AS cashed
    FROM leave_cashout WHERE status <> 'void'
   GROUP BY employee_id, leave_type_id
)
SELECT COALESCE(g.employee_id, u.employee_id, c.employee_id)       AS employee_id,
       COALESCE(g.leave_type_id, u.leave_type_id, c.leave_type_id) AS leave_type_id,
       COALESCE(g.granted, 0)                        AS granted,
       COALESCE(g.expired, 0)                        AS expired,
       COALESCE(u.frozen, 0)                         AS frozen,
       COALESCE(u.used, 0)                           AS used,
       COALESCE(u.forfeited, 0)                      AS forfeited,
       COALESCE(c.cashed, 0)                         AS cashed,
       COALESCE(g.granted, 0) - COALESCE(u.frozen, 0) - COALESCE(u.used, 0)
                              - COALESCE(u.forfeited, 0)
                              - COALESCE(c.cashed, 0) AS available
  FROM g
  FULL JOIN u ON u.employee_id = g.employee_id AND u.leave_type_id = g.leave_type_id
  FULL JOIN c ON c.employee_id  = COALESCE(g.employee_id,  u.employee_id)
             AND c.leave_type_id = COALESCE(g.leave_type_id, u.leave_type_id);

COMMENT ON VIEW v_leave_balance IS
  'available 由三张表派生：leave_grant（授予）/ leave_usage（冻结·已用·作废）/ leave_cashout（已折现）。'
  '折现来自 leave_cashout 而不是台账状态，作废即自动加回可用。';

-- ---------------------------------------------------------------------------
-- 8. 离职结算支持 cashout（057 的 none / forfeit 之外再加一种）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_leave_close_on_exit(p_employee bigint, p_on date)
RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_org   bigint;
  v_mode  varchar(16);
  v_rows  int := 0;
  v_period varchar(7);
  v_done  boolean;
  r       record;
BEGIN
  SELECT a.org_id INTO v_org
    FROM public.employee_org_assignment a
   WHERE a.employee_id = p_employee AND a.dim_code = 'cost_org'
     AND daterange(a.valid_from, a.valid_to, '[]') @> p_on
   ORDER BY a.valid_from DESC LIMIT 1;

  IF v_org IS NULL THEN
    SELECT id INTO v_org FROM public.org_unit WHERE parent_id IS NULL LIMIT 1;
  END IF;

  SELECT value_text INTO v_mode
    FROM public.fn_policy_effective('LEAVE_TERM_HANDLING', v_org, p_on);

  IF v_mode IS NULL OR v_mode = 'none' THEN
    RETURN 0;
  END IF;

  IF v_mode NOT IN ('forfeit','cashout') THEN
    RAISE EXCEPTION 'E_LEAVE_TERM_MODE: 制度项 LEAVE_TERM_HANDLING 的取值 % 不认识'
      '（只支持 none / forfeit / cashout）', v_mode;
  END IF;

  IF EXISTS (SELECT 1 FROM public.leave_usage
              WHERE employee_id = p_employee AND state = 'frozen') THEN
    RAISE EXCEPTION 'E_LEAVE_PENDING_ON_EXIT: 员工 % 还有待批的请假，'
      '先处理掉再办离职（否则结算完再批假，余额会变成负数）', p_employee;
  END IF;

  IF v_mode = 'cashout' THEN
    -- ★ 折现落在**离职当月**工资条上，不落到下月：
    --   离职的人下个月不在工资单里，落错月份这笔钱就再也发不出去。
    v_period := to_char(p_on, 'YYYY-MM');
    FOR r IN
      SELECT b.leave_type_id, b.available, lt.code
        FROM public.v_leave_balance b
        JOIN public.leave_type lt ON lt.id = b.leave_type_id
       WHERE b.employee_id = p_employee AND b.available > 0
    LOOP
      v_done := false;
      IF r.code = 'ANNUAL' THEN
        BEGIN
          PERFORM public.fn_annual_leave_cashout(
            p_employee, p_on, v_period,
            '离职结算：剩余年假折现', 'system');
          v_done := true;
        EXCEPTION WHEN OTHERS THEN
          -- 折不成只有两种原因：制度项 off、折算后不足 1 天。
          -- 这时**不能因此办不了离职**，但额度也不能留着 —— 下面会作废掉。
          -- 金额类错误（没有月薪、没有基数）上面已经拦过，走到这里的不是那类。
          v_done := false;
        END;
      END IF;
      IF NOT v_done THEN
        -- 没折成的年假与非年假（调休、婚假等）一律作废：
        -- 057 的规矩是"法定只保护年假报酬"，而年假已经折不成的部分没有报酬可保护。
        -- 不作废会留下"人走了、额度还挂着"，下次同 person 再入职直接继承旧额度。
        INSERT INTO public.leave_usage(employee_id, leave_type_id, qty, state, request_id)
        VALUES (p_employee, r.leave_type_id, r.available, 'forfeited', NULL);
      ELSE
        -- ★ 折现只折"应休未休"（按工龄折算）那部分，而授予额度里可能还有往年结转，
        --   折完会剩一截。人已经走了，剩的额度必须一起作废 ——
        --   否则余额页上会出现"离职员工还有 17 天年假"，看着像系统算错了。
        INSERT INTO public.leave_usage(employee_id, leave_type_id, qty, state, request_id)
        SELECT p_employee, r.leave_type_id, b.available, 'forfeited', NULL
          FROM public.v_leave_balance b
         WHERE b.employee_id = p_employee AND b.leave_type_id = r.leave_type_id
           AND b.available > 0;
      END IF;
      v_rows := v_rows + 1;
    END LOOP;
    RETURN v_rows;
  END IF;

  FOR r IN
    SELECT b.leave_type_id, b.available
      FROM public.v_leave_balance b
     WHERE b.employee_id = p_employee AND b.available > 0
  LOOP
    INSERT INTO public.leave_usage(employee_id, leave_type_id, qty, state, request_id)
    VALUES (p_employee, r.leave_type_id, r.available, 'forfeited', NULL);
    v_rows := v_rows + 1;
  END LOOP;

  RETURN v_rows;
END;
$$;

COMMENT ON FUNCTION fn_leave_close_on_exit IS
  '离职时按 LEAVE_TERM_HANDLING 处理剩余额度：none 不动 / forfeit 核销 / cashout 折现。'
  'cashout 只折年假（法定只保护年假报酬），其余假种仍作废；折现落到离职当月工资条。'
  '默认 none —— 配置项默认值必须等于上线前的行为。';

