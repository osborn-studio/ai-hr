-- ============================================================================
-- 014_transfer.sql · 归属线与调动（T02.5）
-- ----------------------------------------------------------------------------
-- 这是整套设计里最难的一条线：**四条归属线同时动，但互相独立**。
--
--   发薪法人    跟合同走，调动不变（除非转签主体）
--   参保主体    跟社保走，跨市调动不等于转移社保
--   成本组织    跟实际干活的店走 —— 门店毛利要真实
--   考勤组织    跟实际打卡的店走 —— 排班归"谁管他"
--
-- 四条线在库里是**四个独立维度 + 各自带时间版本**，不是"一个部门字段加例外"。
-- 这条流真正要证的是：一次调动能让其中两条变、另两条不变，且历史查询仍然正确。
-- ============================================================================

-- 归属类：区间用 '[]'（一个日子），不是 '[)'（一个切换点）
CREATE TABLE employee_org_assignment (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id bigint NOT NULL,
  dim_code    varchar(24) NOT NULL REFERENCES sys_perm_dim(code),
  org_id      bigint NOT NULL,
  valid_from  date NOT NULL,
  valid_to    date,
  CONSTRAINT ck_eoa_span CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

-- ★ 同一维度的区间不得重叠。注意是 (employee, dim) 而非 (employee)——
--   四个维度各自独立成账，合并检查会让"成本组织与考勤组织同时换"互相挡住。
ALTER TABLE employee_org_assignment ADD CONSTRAINT ex_eoa_no_overlap
  EXCLUDE USING gist (
    employee_id WITH =, dim_code WITH =,
    daterange(valid_from, valid_to, '[]') WITH &&
  );

-- ---------------------------------------------------------------------------
-- 调动单
-- ---------------------------------------------------------------------------
CREATE TABLE transfer_order (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id     bigint NOT NULL,
  effective_date  date NOT NULL,
  -- NULL = 这一项不变。用 NULL 表达"不变"比用"和原来一样"更明确：
  -- 前者是"没提这件事"，后者会被读成"提到了一样的值"。
  new_cost_org_id       bigint,
  new_attendance_org_id bigint,
  new_legal_entity_id   bigint,       -- 非空 = 转签主体（会新开一段任职）
  status          varchar(16) NOT NULL DEFAULT 'draft',
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_to_status CHECK (status IN ('draft','effective','cancelled'))
);

-- ---------------------------------------------------------------------------
-- 执行调动
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_transfer_apply(p_order bigint)
RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  o public.transfer_order%ROWTYPE;
  v_emp bigint;
BEGIN
  SELECT * INTO o FROM public.transfer_order WHERE id = p_order FOR UPDATE;
  IF o.id IS NULL THEN
    RAISE EXCEPTION 'E_TRANSFER_NO_ORDER: 调动单 % 不存在', p_order;
  END IF;
  IF o.status <> 'draft' THEN
    RAISE EXCEPTION 'E_TRANSFER_ALREADY: 调动单 % 已是 %', p_order, o.status;
  END IF;

  SELECT id INTO v_emp FROM public.employment
   WHERE person_id = o.employee_id AND leave_date IS NULL LIMIT 1;

  -- ① 成本组织：关旧段、开新段（'[]' 语义：旧段到生效日前一天）
  IF o.new_cost_org_id IS NOT NULL THEN
    UPDATE public.employee_org_assignment
       SET valid_to = o.effective_date - 1
     WHERE employee_id = o.employee_id AND dim_code = 'cost_org' AND valid_to IS NULL;
    INSERT INTO public.employee_org_assignment(employee_id, dim_code, org_id, valid_from)
    VALUES (o.employee_id, 'cost_org', o.new_cost_org_id, o.effective_date);
  END IF;

  -- ② 考勤组织：同上
  IF o.new_attendance_org_id IS NOT NULL THEN
    UPDATE public.employee_org_assignment
       SET valid_to = o.effective_date - 1
     WHERE employee_id = o.employee_id AND dim_code = 'attendance_org' AND valid_to IS NULL;
    INSERT INTO public.employee_org_assignment(employee_id, dim_code, org_id, valid_from)
    VALUES (o.employee_id, 'attendance_org', o.new_attendance_org_id, o.effective_date);
  END IF;

  -- ③ 转签主体：这是唯一会动"发薪法人"的动作，且它动的不是字段，是**新开一段任职**
  IF o.new_legal_entity_id IS NOT NULL THEN
    UPDATE public.employment SET leave_date = o.effective_date - 1
     WHERE id = v_emp;
    INSERT INTO public.employment(person_id, legal_entity_id, hire_date)
    VALUES (o.employee_id, o.new_legal_entity_id, o.effective_date);
  END IF;

  UPDATE public.transfer_order SET status = 'effective' WHERE id = p_order;
END;
$$;

-- ---------------------------------------------------------------------------
-- 时点查询：某一天，这个人的四条归属分别是什么
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_attr_asof(p_employee bigint, p_on date)
RETURNS TABLE (dim_code varchar(24), value_id bigint)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  -- 成本/考勤组织：取归属表
  SELECT a.dim_code, a.org_id
    FROM public.employee_org_assignment a
   WHERE a.employee_id = p_employee
     AND daterange(a.valid_from, a.valid_to, '[]') @> p_on
  UNION ALL
  -- 发薪法人：取当天在职的那段任职
  SELECT 'payroll_legal_entity', e.legal_entity_id
    FROM public.employment e
   WHERE e.person_id = p_employee
     AND daterange(e.hire_date, e.leave_date, '[]') @> p_on;
$$;

COMMENT ON FUNCTION fn_attr_asof IS
  '四维归属按时点查。这条函数是"跨店支援当天成本落哪家店"的唯一答案来源——'
  '用当前值代替时点值，会把上个月的门店毛利算错，而报表看起来完全正常。';
