-- ---------------------------------------------------------------------------
-- 3. 工资结构（拆分，不改总额）
-- ---------------------------------------------------------------------------
CREATE TABLE salary_structure_item (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employment_id  bigint NOT NULL REFERENCES employment(id),
  item_code      varchar(32) NOT NULL REFERENCES salary_item(code),
  amount         numeric(12,2) NOT NULL CHECK (amount >= 0),
  effective_from date NOT NULL,
  effective_to   date,
  set_by         varchar(64) NOT NULL DEFAULT 'system',
  CONSTRAINT ck_ssi_span CHECK (effective_to IS NULL OR effective_to >= effective_from)
);

-- 同一份任职、同一个工资项，不许有两段重叠的约定：
-- 重叠之后"这个人岗位津贴到底多少"取决于查询习惯，而查询习惯会变。
ALTER TABLE salary_structure_item ADD CONSTRAINT ex_ssi_no_overlap
  EXCLUDE USING gist (employment_id WITH =, item_code WITH =,
                      daterange(effective_from, effective_to, '[]') WITH &&);

CREATE INDEX ix_ssi_emp ON salary_structure_item (employment_id, effective_from DESC);

COMMENT ON TABLE salary_structure_item IS
  '工资结构拆分（基本工资/岗位津贴/餐补/通讯…）。各项之和必须等于 salary_standard.monthly_amount：'
  '总额只有一个来源，结构只解释它由哪些项组成。';

-- ---------------------------------------------------------------------------
-- 4. 提成（算工资）与报销（不算工资）
-- ---------------------------------------------------------------------------
CREATE TABLE commission_record (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id  bigint NOT NULL REFERENCES person(id),
  period     varchar(7) NOT NULL,
  amount     numeric(12,2) NOT NULL CHECK (amount >= 0),
  basis      varchar(200),
  status     varchar(16) NOT NULL DEFAULT 'approved',
  created_by varchar(64) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_cr_period CHECK (period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  CONSTRAINT ck_cr_status CHECK (status IN ('pending','approved','void'))
);

CREATE INDEX ix_cr_person_period ON commission_record (person_id, period);

COMMENT ON TABLE commission_record IS
  '提成：计入应发、计税、工资条上单独一行。status=approved 才参与算薪 —— '
  '与请假同一条规矩：未追认的钱不发。';

CREATE TABLE expense_claim (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id  bigint NOT NULL REFERENCES person(id),
  period     varchar(7) NOT NULL,
  category   varchar(32) NOT NULL,
  amount     numeric(12,2) NOT NULL CHECK (amount > 0),
  note       varchar(200),
  status     varchar(16) NOT NULL DEFAULT 'pending',
  created_by varchar(64) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_ec_period CHECK (period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  CONSTRAINT ck_ec_status CHECK (status IN ('pending','approved','paid','rejected'))
);

CREATE INDEX ix_ec_person_period ON expense_claim (person_id, period);

COMMENT ON TABLE expense_claim IS
  '报销：**不是工资**。不进应发、不计税、不进工资条明细 —— 混进去会让个税算错，'
  '也会让"应发合计"在财务口径上失真。它单独一张单、单独付款。';

-- ---------------------------------------------------------------------------
-- 5. 工资结构：设置 / 读取
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_salary_structure_set(
  p_employment bigint, p_from date, p_items jsonb, p_by varchar DEFAULT 'system'
) RETURNS numeric
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_total numeric(12,2); v_monthly numeric(12,2); v_bad text;
BEGIN
  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'E_SS_EMPTY: 工资结构至少要有一项';
  END IF;

  -- 只允许 fixed 项：把 IIT / SI_EMPLOYEE 拆进结构会把"算出来的"写成"约定的"，
  -- 之后没人分得清这一行是政策还是这个月的巧合。
  SELECT string_agg(DISTINCT x->>'item_code', '、') INTO v_bad
    FROM jsonb_array_elements(p_items) x
    LEFT JOIN public.salary_item si ON si.code = (x->>'item_code')
   WHERE si.code IS NULL OR si.item_kind <> 'fixed';
  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION 'E_SS_ITEM: 只能拆固定工资项，且必须是已登记项（收到：%）', v_bad;
  END IF;

  SELECT COALESCE(sum((x->>'amount')::numeric), 0) INTO v_total
    FROM jsonb_array_elements(p_items) x;
  IF v_total < 0 THEN RAISE EXCEPTION 'E_SS_SUM: 各项不能为负'; END IF;

  SELECT s.monthly_amount INTO v_monthly
    FROM public.salary_standard s
   WHERE s.employment_id = p_employment AND s.effective_from <= p_from
   ORDER BY s.effective_from DESC LIMIT 1;
  IF v_monthly IS NULL THEN
    RAISE EXCEPTION 'E_SS_NO_STANDARD: 这份任职在 % 之前没有月薪标准，先定月薪再拆结构', p_from;
  END IF;

  -- ★ 合计必须等于月薪标准。不等就拒，不做"按比例缩放"——
  --   缩放会让用户以为设的是 13000，实际发出来是别的数。
  IF abs(v_total - v_monthly) > 0.005 THEN
    RAISE EXCEPTION 'E_SS_SUM: 各项之和 % 与月薪标准 % 不一致（结构只解释总额由什么组成，不改总额）',
      v_total, v_monthly;
  END IF;

  -- 关掉旧的一版（只关 p_from 之前仍生效的，历史不动）
  UPDATE public.salary_structure_item
     SET effective_to = p_from - 1
   WHERE employment_id = p_employment AND effective_to IS NULL AND effective_from < p_from;

  INSERT INTO public.salary_structure_item(employment_id, item_code, amount, effective_from, set_by)
  SELECT p_employment, x->>'item_code', (x->>'amount')::numeric, p_from, p_by
    FROM jsonb_array_elements(p_items) x;

  RETURN v_total;
END;
$$;

COMMENT ON FUNCTION fn_salary_structure_set IS
  '设置工资结构：合计必须等于月薪标准（E_SS_SUM），只允许 fixed 项（E_SS_ITEM），'
  '旧版本按 effective_to 关闭而不是删除 —— 历史工资条要能解释当时的结构。';

CREATE OR REPLACE FUNCTION fn_salary_structure_of(p_employment bigint, p_on date)
RETURNS TABLE (item_code varchar, name varchar, amount numeric)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT s.item_code, i.name, s.amount
    FROM public.salary_structure_item s
    JOIN public.salary_item i ON i.code = s.item_code
   WHERE s.employment_id = p_employment
     AND daterange(s.effective_from, s.effective_to, '[]') @> p_on
   ORDER BY (s.item_code = 'BASE') DESC, i.code;
$$;

CREATE OR REPLACE FUNCTION fn_commission_amount(p_person bigint, p_period varchar)
RETURNS numeric
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT COALESCE(sum(amount), 0)::numeric(12,2)
    FROM public.commission_record
   WHERE person_id = p_person AND period = p_period AND status = 'approved';
$$;

CREATE OR REPLACE FUNCTION fn_expense_amount(p_person bigint, p_period varchar)
RETURNS numeric
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT COALESCE(sum(amount), 0)::numeric(12,2)
    FROM public.expense_claim
   WHERE person_id = p_person AND period = p_period AND status IN ('approved','paid');
$$;

-- ---------------------------------------------------------------------------
-- 6. 日薪：读制度项（默认 21.75，与原来的硬编码同值）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_leave_deduction(p_employee bigint, p_period varchar)
RETURNS numeric
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT COALESCE(round(
           public.fn_leave_approved_days(p_employee, p_period, 'PERSONAL')
           * (SELECT s.monthly_amount
                   / COALESCE((SELECT value_num FROM public.fn_policy_effective(
                        'PAY_DAYS_PER_MONTH', NULL, public.app_today())), 21.75)
                FROM public.salary_standard s
                JOIN public.employment e ON e.id = s.employment_id
               WHERE e.person_id = p_employee
               ORDER BY s.effective_from DESC LIMIT 1), 2), 0);
$$;

COMMENT ON FUNCTION fn_leave_deduction IS
  '事假扣款 = 天数 × 日薪。日薪 = 月薪标准 ÷ 月计薪天数（制度 PAY_DAYS_PER_MONTH，'
  '默认 21.75 与原来硬编码同值；改制度会真的改扣款，见 ST 组反例）。';

-- ---------------------------------------------------------------------------
-- 7. 算薪主过程：加提成、按结构拆明细（金额口径不变）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_payroll_calc(p_run bigint)
RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  r public.pay_run%ROWTYPE;
  e record;
  v_period_end date;
  v_base numeric(12,2);
  v_leave numeric(12,2);
  v_si_base numeric(12,2);
  v_si numeric(12,2);
  v_rate numeric(6,4);
  v_gross numeric(12,2);
  v_taxable numeric(14,2);
  v_cum_prev numeric(14,2);
  v_cum_paid_tax numeric(14,2);
  v_tax numeric(12,2);
  v_net numeric(12,2);
  v_threshold numeric(12,2);
  v_slip bigint;
  v_n int := 0;
  v_unclosed text;
  v_perf numeric(12,2);
  v_comm numeric(12,2);
  v_fixed_other numeric(12,2);
  v_struct_n int;
BEGIN
  SELECT * INTO r FROM public.pay_run WHERE id = p_run FOR UPDATE;
  IF r.id IS NULL THEN RAISE EXCEPTION 'E_RUN_NOT_FOUND: %', p_run; END IF;
  IF r.status <> 'draft' THEN
    RAISE EXCEPTION 'E_RUN_SEALED: 批次 % 已封账，不可重算', p_run;
  END IF;

  SELECT string_agg(u.store_id || '(' || u.why || ')', '、') INTO v_unclosed
    FROM public.fn_att_unclosed(r.period) u;
  IF v_unclosed IS NOT NULL THEN
    RAISE EXCEPTION 'E_ATT_NOT_CLOSED: 本期有考勤但未封账的门店：%。'
      '未封账即算薪，等于用一份还会变的数据发钱。', v_unclosed;
  END IF;

  IF EXISTS (SELECT 1 FROM public.perf_cycle c
              WHERE c.pay_period = r.period AND c.status <> 'sealed') THEN
    RAISE EXCEPTION 'E_PERF_NOT_SEALED: % 关联的绩效周期未封存，算薪会按一份还会变的分发钱',
      r.period;
  END IF;

  v_period_end := (to_date(r.period || '-01','YYYY-MM-DD') + interval '1 month - 1 day')::date;
  SELECT threshold INTO v_threshold FROM public.tax_param WHERE year = left(r.period,4)::int;

  FOR e IN
    SELECT em.id AS employment_id, em.person_id, em.legal_entity_id
      FROM public.employment em
     WHERE em.legal_entity_id = r.legal_entity_id
       AND daterange(em.hire_date, em.leave_date, '[]') @> v_period_end
  LOOP
    SELECT s.monthly_amount INTO v_base
      FROM public.salary_standard s
     WHERE s.employment_id = e.employment_id AND s.effective_from <= v_period_end
     ORDER BY s.effective_from DESC LIMIT 1;
    IF v_base IS NULL THEN CONTINUE; END IF;

    v_leave := public.fn_leave_deduction(e.person_id, r.period);
    v_perf  := round(v_base * COALESCE(public.fn_perf_factor(e.person_id, r.period), 0), 2);
    -- ★ 提成是工资：计入应发、参与计税。只认 approved —— 未追认的钱不发。
    v_comm  := public.fn_commission_amount(e.person_id, r.period);
    v_gross := v_base - v_leave + v_perf + v_comm;

    SELECT rate_employee INTO v_rate FROM public.si_policy
     WHERE city='上海' AND item='pension' AND effective_from <= v_period_end
     ORDER BY effective_from DESC LIMIT 1;
    IF v_rate IS NULL THEN
      RAISE EXCEPTION 'E_SI_POLICY_MISSING: 上海 养老保险 在 % 之前没有生效的政策', v_period_end;
    END IF;
    v_si_base := public.fn_si_base('上海','pension', v_base, v_period_end);
    v_si := round(v_si_base * v_rate, 2);

    v_taxable := GREATEST(v_gross - v_si - v_threshold, 0);

    SELECT COALESCE(SUM(p.cum_taxable),0), COALESCE(SUM(p.tax_amount),0)
      INTO v_cum_prev, v_cum_paid_tax
      FROM public.payslip p JOIN public.pay_run pr ON pr.id = p.pay_run_id
     WHERE p.employee_id = e.person_id
       AND left(pr.period,4) = left(r.period,4)
       AND pr.period < r.period
       AND pr.status IN ('sealed','paid');

    v_tax := public.fn_iit_month(v_cum_prev + v_taxable, v_cum_paid_tax);
    v_net := v_gross - v_si - v_tax;

    INSERT INTO public.payslip(pay_run_id, employee_id, gross_amount, net_amount,
                               si_employee, tax_amount, cum_taxable, leave_deduct)
    VALUES (p_run, e.person_id, v_gross, v_net, v_si, v_tax, v_cum_prev + v_taxable, v_leave)
    ON CONFLICT (pay_run_id, employee_id) DO UPDATE
      SET gross_amount=EXCLUDED.gross_amount, net_amount=EXCLUDED.net_amount,
          si_employee=EXCLUDED.si_employee, tax_amount=EXCLUDED.tax_amount,
          cum_taxable=EXCLUDED.cum_taxable, leave_deduct=EXCLUDED.leave_deduct
    RETURNING id INTO v_slip;

    DELETE FROM public.payslip_item WHERE payslip_id = v_slip;

    -- 明细：有结构就逐项拆（BASE = 总额 − 其它固定项），没有就一行 BASE。
    -- ★ 拆分不改变金额：所有行加起来仍然等于 v_base。
    SELECT count(*), COALESCE(sum(amount), 0) INTO v_struct_n, v_fixed_other
      FROM public.fn_salary_structure_of(e.employment_id, v_period_end) s
     WHERE s.item_code <> 'BASE';

    IF v_struct_n > 0 THEN
      INSERT INTO public.payslip_item(payslip_id, item_code, amount)
      SELECT v_slip, s.item_code, s.amount
        FROM public.fn_salary_structure_of(e.employment_id, v_period_end) s
       WHERE s.item_code <> 'BASE';
      INSERT INTO public.payslip_item(payslip_id, item_code, amount) VALUES
        (v_slip, 'BASE', v_base - v_fixed_other);
    ELSE
      INSERT INTO public.payslip_item(payslip_id, item_code, amount) VALUES
        (v_slip,'BASE', v_base);
    END IF;

    IF v_leave <> 0 THEN
      INSERT INTO public.payslip_item(payslip_id, item_code, amount) VALUES
        (v_slip,'LEAVE_DEDUCT', -v_leave);
    END IF;
    IF v_si <> 0 THEN
      INSERT INTO public.payslip_item(payslip_id, item_code, amount) VALUES
        (v_slip,'SI_EMPLOYEE', -v_si);
    END IF;
    IF v_tax <> 0 THEN
      INSERT INTO public.payslip_item(payslip_id, item_code, amount) VALUES
        (v_slip,'IIT', -v_tax);
    END IF;
    IF v_perf <> 0 THEN
      INSERT INTO public.payslip_item(payslip_id, item_code, amount) VALUES
        (v_slip,'PERF_BONUS', v_perf);
    END IF;
    IF v_comm <> 0 THEN
      INSERT INTO public.payslip_item(payslip_id, item_code, amount) VALUES
        (v_slip,'COMMISSION', v_comm);
    END IF;

    v_n := v_n + 1;
  END LOOP;

  IF v_n = 0 THEN
    RAISE EXCEPTION 'E_PAYROLL_NO_ELIGIBLE: 批次 % 一个人都没算出来（检查月薪标准与在职区间）', p_run;
  END IF;

  RETURN v_n;
END;
$$;

COMMENT ON FUNCTION fn_payroll_calc IS
  '算薪主过程。应发 = 月薪标准 − 事假扣款 + 绩效 + 提成；实发 = 应发 − 社保 − 个税。'
  '报销不进这里 —— 它不是工资，不参与计税与应发合计。';

