-- ============================================================================
-- 087_salary_structure.sql · 工资表：结构拆分 + 提成 + 报销
-- ----------------------------------------------------------------------------
-- 到 086 为止，"工资"只有一个数：salary_standard.monthly_amount。
-- 这对发钱够用，对**解释**不够用 —— 员工问"我这 13000 是怎么来的"，
-- 工资条上只有一行"基本工资 13000"，等于没回答。
--
-- 这一版把"月薪总额"拆成项，并引入两类浮动收入。三条边界先写清楚：
--
--   ① **总额只有一个来源**：salary_standard.monthly_amount 仍是月薪总额，
--      salary_structure_item 只是"它由哪些项组成"。所以结构合计必须等于总额，
--      不等就拒（E_SS_SUM）。否则两处都能定义工资，对不上时没人知道该信哪个。
--
--   ② **结构不改变金额**：算薪仍以 monthly_amount 为基数，结构只影响工资条的
--      明细行怎么拆（BASE = 总额 − 其它固定项）。这样加结构不会让任何人的
--      工资变动一分钱 —— 默认值必须等于上线前的行为。
--
--   ③ **报销不是工资**：报销不进应发、不计税、不进工资条明细。
--      它单独一张单子、单独付款。混进工资条会让个税算错，也会让
--      "应发合计"这个数在财务口径上失真。
--
-- 提成（commission）是**工资**：计入应发、计税、进明细 COMMISSION 一行。
-- 法定假与工时是**制度项**，不是硬编码：客户是 8 小时制还是综合工时，
-- 决定日薪怎么算，这件事不该由代码替客户决定。
-- ============================================================================

