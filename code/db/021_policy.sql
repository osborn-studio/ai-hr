-- ============================================================================
-- 021_policy.sql · 集团制度下发与门店覆盖
-- ----------------------------------------------------------------------------
-- 020 解决了"谁能做什么"（权限可分配到组织）。集团统一管理的另一半是：
-- **制度本身统一下发**，而门店的差异是被允许的、被记录的、被限制的。
--
-- 这一层最常见的错法是"每个门店一张配置表，集团给个默认值"——
-- 那不是统一管理，那是**没有管理**：默认值一旦可被任意覆盖，
-- 集团改一次口径，几十家店各按各的旧值跑，而每一家都能说"我这是配置的"。
--
-- 真正的统一管理有两层，缺一层都不成立：
--
--   ① 集团发布制度值（带版本、带生效日），未覆盖的单位**立即跟随**
--   ② **"这一项允不允许被覆盖"由集团逐项声明**，不是所有项都能改
--
-- ② 是关键，也是最容易被省掉的：如果任何项都能被门店覆盖，
-- 那"集团统一"就只是一句默认值。而"哪些必须统一、哪些可因地制宜"
-- 本身是一个管理决定，不能由技术默认成"都能改"。
--
-- 再加一条事实性约束：**覆盖失效时不能静默消失**。
-- 集团把某项改成"不许覆盖"之后，存量覆盖会变成"存在但不生效"——
-- 这种状态必须能被单独列出来，否则它会一直躺在表里，
-- 直到某天有人把开关打开，一批两年前的旧值同时复活。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 制度项定义
-- ---------------------------------------------------------------------------
CREATE TABLE policy_def (
  code               varchar(48) PRIMARY KEY,
  name               varchar(96) NOT NULL,
  domain             varchar(24) NOT NULL,
  value_type         varchar(16) NOT NULL,      -- numeric | text | bool | enum
  -- ★ 集团逐项声明：这一项门店能不能自己定
  allow_org_override boolean     NOT NULL DEFAULT false,
  -- 覆盖的截止层级：'group' 只有集团能定；'region' 到区域为止；'store' 门店可定
  override_floor     varchar(16) NOT NULL DEFAULT 'group',
  unit               varchar(16),
  CONSTRAINT ck_pd_type  CHECK (value_type IN ('numeric','text','bool','enum')),
  CONSTRAINT ck_pd_floor CHECK (override_floor IN ('group','region','store')),
  CONSTRAINT ck_pd_floor_gate CHECK (allow_org_override OR override_floor = 'group')
);

COMMENT ON COLUMN policy_def.override_floor IS
  '覆盖可以下发到哪一层。它比 allow_org_override 更细：'
  '"允许覆盖"但只允许到区域，意味着门店仍然不能自己定——'
  '两者合成一个布尔会把"区域可调、门店不可调"这个真实需求表达不出来。';

-- ---------------------------------------------------------------------------
-- 集团值：按版本，只增不改
-- ---------------------------------------------------------------------------
CREATE TABLE policy_value (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  policy_code    varchar(48)  NOT NULL REFERENCES policy_def(code),
  effective_from date         NOT NULL,
  value_num      numeric(18,4),
  value_text     varchar(200),
  published_by   varchar(64)  NOT NULL,
  reason         varchar(200) NOT NULL,
  CONSTRAINT uk_pv UNIQUE (policy_code, effective_from),
  CONSTRAINT ck_pv_reason CHECK (length(btrim(reason)) >= 4)
);

-- ---------------------------------------------------------------------------
-- 门店/区域覆盖
-- ---------------------------------------------------------------------------
CREATE TABLE policy_override (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id         bigint       NOT NULL REFERENCES org_unit(id),
  policy_code    varchar(48)  NOT NULL REFERENCES policy_def(code),
  effective_from date         NOT NULL,
  effective_to   date,
  value_num      numeric(18,4),
  value_text     varchar(200),
  reason         varchar(200) NOT NULL,
  approved_by    varchar(64)  NOT NULL,
  CONSTRAINT ck_po_span   CHECK (effective_to IS NULL OR effective_to > effective_from),
  CONSTRAINT ck_po_reason CHECK (length(btrim(reason)) >= 4)
);

ALTER TABLE policy_override ADD CONSTRAINT ex_po_no_overlap
  EXCLUDE USING gist (
    org_id WITH =, policy_code WITH =,
    daterange(effective_from, effective_to, '[)') WITH &&
  );

-- ---------------------------------------------------------------------------
-- 解析：从最近祖先往上找，找不到就用集团值
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_policy_effective(
  p_code varchar, p_org bigint, p_on date
) RETURNS TABLE (value_num numeric, value_text varchar, source varchar(16), via_org_id bigint)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE
  v_allow   boolean;
  v_floor   varchar(16);
BEGIN
  SELECT d.allow_org_override, d.override_floor INTO v_allow, v_floor
    FROM public.policy_def d WHERE d.code = p_code;
  IF v_allow IS NULL THEN
    RAISE EXCEPTION 'E_POLICY_UNDEFINED: 制度项 % 未定义', p_code;
  END IF;

  -- ① 覆盖：只在允许时找，且**只沿自己的祖先链**——不能横向看兄弟单位
  IF v_allow THEN
    RETURN QUERY
      SELECT ov.value_num, ov.value_text, 'org'::varchar(16), ov.org_id
        FROM public.policy_override ov
        JOIN public.org_unit po ON po.id = ov.org_id
       WHERE ov.policy_code = p_code
         AND daterange(ov.effective_from, ov.effective_to, '[)') @> p_on
         -- 覆盖的组织必须是本单位或本单位的上层（path 前缀关系）
         AND (SELECT path FROM public.org_unit WHERE id = p_org) LIKE po.path || '%'
         -- 层级限制：'region' 时只有区域及以上能覆盖
         AND (v_floor = 'store'
              OR (v_floor = 'region'
                  AND array_length(string_to_array(po.path, '.'), 1) <= 2))
       ORDER BY length(po.path) DESC   -- 最近的祖先优先
       LIMIT 1;
    IF FOUND THEN RETURN; END IF;
  END IF;

  -- ② 集团值（按生效版本，latest <= p_on）
  RETURN QUERY
    SELECT v.value_num, v.value_text, 'group'::varchar(16), NULL::bigint
      FROM public.policy_value v
     WHERE v.policy_code = p_code AND v.effective_from <= p_on
     ORDER BY v.effective_from DESC LIMIT 1;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'E_POLICY_NO_VALUE: 制度项 % 在 % 之前没有集团值', p_code, p_on;
  END IF;
END;
$$;

COMMENT ON FUNCTION fn_policy_effective IS
  '先找覆盖（就近祖先优先），找不到用集团值；都没有就报错。'
  '报错而不是返回 NULL：一个没有值的制度项会让下游按 NULL 算出一堆数，'
  '而那些数看起来是"配置还没填"，实际是"这个月所有人按零算"。';

-- ---------------------------------------------------------------------------
-- 失效的覆盖：存在但不生效
-- ---------------------------------------------------------------------------
-- ★ 集团把某项改成"不许覆盖"之后，存量覆盖不会消失，只是不再被读到。
--   这类记录必须能单独列出来——否则它躺在表里，直到有人把开关打开，
--   一批旧值同时复活，而那一天不会有任何人预期到。
CREATE OR REPLACE FUNCTION fn_policy_orphan_overrides()
RETURNS TABLE (policy_code varchar, org_id bigint, org_name varchar,
               effective_from date, why varchar)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT ov.policy_code, ov.org_id, o.name, ov.effective_from,
         CASE WHEN NOT d.allow_org_override
                THEN '集团已改为不允许覆盖'
              ELSE '超出允许的覆盖层级（floor=' || d.override_floor || '）'
         END
    FROM public.policy_override ov
    JOIN public.policy_def  d ON d.code   = ov.policy_code
    JOIN public.org_unit    o ON o.id     = ov.org_id
   WHERE NOT d.allow_org_override
      OR (d.override_floor = 'region'
          AND array_length(string_to_array(o.path, '.'), 1) > 2);
$$;

-- ---------------------------------------------------------------------------
-- 集团改值的影响面
-- ---------------------------------------------------------------------------
-- 改一个集团值之前必须能回答：有多少单位会跟着变、多少单位已被覆盖不受影响。
-- 两个数都要，只报前者会让人以为"改了就都能生效"。
CREATE OR REPLACE FUNCTION fn_policy_impact(p_code varchar, p_on date)
RETURNS TABLE (total_orgs int, following int, overridden int)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  WITH o AS (SELECT id FROM public.org_unit WHERE is_active),
       r AS (SELECT o.id,
                    (SELECT source FROM public.fn_policy_effective(p_code, o.id, p_on)) AS src
               FROM o)
  SELECT (SELECT count(*)::int FROM r),
         (SELECT count(*)::int FROM r WHERE src = 'group'),
         (SELECT count(*)::int FROM r WHERE src = 'org');
$$;


-- ---------------------------------------------------------------------------
-- 接线：制度 → 考勤口径的默认值
-- ---------------------------------------------------------------------------
-- ★ 制度是**写入时的输入**，不是读取时的规则。
--   这一句是整条链路里最容易做错的地方：
--   如果口径在读取时按当前制度现算，那集团改一次口径，
--   去年已经发过的工时也会跟着变——而工资已经按去年的数发过了。
--   所以制度只决定「新写入的行按哪一支」，写进去之后就由 snap_* 列固化。
CREATE OR REPLACE FUNCTION fn_att_default_basis(p_store bigint, p_on date)
RETURNS varchar(12)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE v numeric;
BEGIN
  SELECT value_num INTO v
    FROM public.fn_policy_effective('BREAK_DEDUCT', p_store, p_on);
  IF v IS NULL THEN
    RAISE EXCEPTION 'E_POLICY_NO_VALUE: BREAK_DEDUCT 在 % 无值，无法确定在岗休息口径', p_on;
  END IF;
  -- 1 = 扣除在岗休息 -> allowance 口径；0 = 不扣 -> hourly 口径
  RETURN CASE WHEN v = 1 THEN 'allowance'::varchar(12) ELSE 'hourly'::varchar(12) END;
END;
$$;

COMMENT ON FUNCTION fn_att_default_basis IS
  '制度只决定「新写入的行按哪一支」，写进去之后由 snap_on_duty_break_basis 固化。'
  '若口径在读取时现算，集团改一次口径会把去年已发过钱的工时也改掉。';
