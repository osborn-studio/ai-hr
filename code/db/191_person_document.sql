-- ============================================================================
-- 191_person_document.sql · 证照 / 签证台账（香港线的合规资料）
-- ----------------------------------------------------------------------------
-- docs/45 的盘点把这一条列为「6 项无」之一：门店花名册里**没有 HKID/护照号、
-- 没有签证/工作许可类型与到期日**（docs/42 §六.9 原话）。这件事的代价不是
-- "少一列"：
--
--   · 香港门店雇外籍/内地员工，签证到期没续 = 该员工**从到期那天起不能上班**，
--     而工资照发、MPF 照供 —— 这在劳工处与入境处是两条线的问题；
--   · 证照到期是**未来事件**，靠人记必然漏。所以本表存在的目的不是"存证件照片"，
--     是让一句 SQL 能回答"90 天内谁的证件到期"。
--
-- ★ 设计一：证照是**一个人可以有多本**（护照换发、签证续签、港澳通行证…），
--   所以是一张子表，不是 person 上的几列。person 上加 3 列的话，
--   换一次护照就要覆盖旧号 —— 而旧号在历史出入境记录里仍然要对得上。
--   `UNIQUE (person_id, doc_type, doc_no)`：同一个人、同一类证件、同一个号，
--   只该有一条；换发的新护照是**另一个号**，自然是新的一行（旧行留着不删）。
--
-- ★ 设计二：**列 expiry_date 建索引**，因为本表唯一的日常查询是按到期日筛
--   （`fn_documents_expiring`）。没有索引时它一样能跑，只是随着人多了变慢 ——
--   而"变慢"不会有人报，最后是 HR 说"这个页面要转 20 秒"。
--
-- ★ 设计三：`issuing_country` 用 ISO 3166-1 alpha-2（'HK' / 'CN' / 'PH' …），
--   不用中文国名 —— 中文国名有简繁与俗称（"香港" / "中国香港" / "Hong Kong"），
--   而发证国是要跟证件上对得上的字段。允许 NULL：老资料里这一格常常是空的，
--   强制填会让人随便填一个。
--
-- ★ 设计四：**与算薪无耦合**（docs/44 的口径：证照不在任何工资公式里）。
--   所以本表**不接进任何算薪函数、不进 salary_standard、不进 MPF 供款判定**。
--   它只服务两件事：合规清单（谁快到期了）与人事档案留存。
--   ★ 特别地：**没有 MPF 账号 ≠ 没交 MPF**、**有签证 ≠ 该发薪** ——
--     把这两件事接进算薪，会让"资料没录全"变成"工资算错"，而算错的钱是要补的。
--
-- 幂等：CREATE TABLE IF NOT EXISTS / CREATE INDEX IF NOT EXISTS / CREATE OR REPLACE。
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.person_document (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id        bigint NOT NULL REFERENCES public.person(id),
  -- passport=护照 / visa=签证(工作许可) / id_card=身份证(HKID 与内地身份证同归此类) / other
  doc_type         varchar(16) NOT NULL,
  doc_no           varchar(64) NOT NULL,
  issue_date       date,
  expiry_date      date,                     -- NULL = 长期有效（如永久性居民身份证）
  issuing_country  varchar(2),               -- ISO 3166-1 alpha-2；NULL = 老资料未填
  note             varchar(200),
  created_by       varchar(64),
  created_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_doc_type CHECK (doc_type IN ('passport','visa','id_card','other')),
  -- ★ 到期日不得早于签发日：写反了不会报错，只会让"已过期"与"未生效"两种状态
  --   在清单上同形 —— 而 HR 要区分这两种。
  CONSTRAINT ck_doc_span CHECK (expiry_date IS NULL OR issue_date IS NULL
                                OR expiry_date >= issue_date),
  CONSTRAINT ck_doc_no   CHECK (length(btrim(doc_no)) > 0),
  CONSTRAINT ux_doc_no   UNIQUE (person_id, doc_type, doc_no)
);

CREATE INDEX IF NOT EXISTS ix_doc_expiry ON public.person_document (expiry_date);
CREATE INDEX IF NOT EXISTS ix_doc_person ON public.person_document (person_id);

COMMENT ON TABLE public.person_document IS
  '证照/签证台账（191）。一人可多本（换发的新号是新行，旧行不删）。'
  'UNIQUE (person_id, doc_type, doc_no)。'
  '★★ 与算薪**无耦合**（docs/44）：本表不进任何工资/MPF 公式。'
  '它的用途只有两个：合规到期清单（fn_documents_expiring）与档案留存。'
  '★ 到期日是**未来事件**，所以要能按 expiry_date 筛（ix_doc_expiry）；'
  '证照过期不等于不能发薪，但等于"从那天起不能上班"。';

COMMENT ON COLUMN public.person_document.expiry_date IS
  '到期日。NULL = 长期有效（如永久性居民身份证），**不是"忘了填"**；'
  '确实不知道到期日的，写 note 说明，不要填一个假日期 —— 假日期会在清单里'
  '变成一条永远不该出现的提醒，然后整张清单被忽略。';

COMMENT ON COLUMN public.person_document.issuing_country IS
  'ISO 3166-1 alpha-2（HK / CN / PH …）。不用中文国名：简繁与俗称混填后，'
  '按国家筛人就筛不准（"香港"/"中国香港"/"Hong Kong" 三个值指同一件事）。';

-- ---------------------------------------------------------------------------
-- 只读函数：p_days 天内到期（默认按"今天"算，业务时区）
-- ---------------------------------------------------------------------------
-- ★ 只算**当前在职**的人：离职的人证件到期不需要续 —— 混在同一张清单里，
--   清单会越用越长，然后没人看（"提醒列表只要有一半是噪音，就整张作废"）。
-- ★ 用 app_today() 而不是 current_date：这是业务时区里的今天（071 的规矩）。
CREATE OR REPLACE FUNCTION public.fn_documents_expiring(p_days int DEFAULT 90)
RETURNS TABLE (
  person_id       bigint,
  full_name       varchar,
  doc_type        varchar,
  doc_no          varchar,
  expiry_date     date,
  days_left       int,
  issuing_country varchar,
  note            varchar
)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE v_today date;
BEGIN
  IF p_days IS NULL OR p_days <= 0 OR p_days > 3650 THEN
    RAISE EXCEPTION 'E_ARG_INVALID: p_days 必须是 1..3650 之间的天数（收到 %）', p_days;
  END IF;
  v_today := public.app_today();

  RETURN QUERY
  SELECT d.person_id, p.full_name, d.doc_type::varchar, d.doc_no::varchar,
         d.expiry_date,
         (d.expiry_date - v_today)::int,
         d.issuing_country::varchar,
         d.note::varchar
    FROM public.person_document d
    JOIN public.person p ON p.id = d.person_id
   WHERE d.expiry_date IS NOT NULL
     AND d.expiry_date >= v_today                 -- 已过期的不算"将到期"（另一张清单）
     AND d.expiry_date <= v_today + p_days
     -- 当前在职：任职段覆盖今天（007 的 '[]'：离职日当天仍算在职）
     AND EXISTS (SELECT 1 FROM public.employment e
                  WHERE e.person_id = d.person_id
                    AND daterange(e.hire_date, e.leave_date, '[]') @> v_today)
   ORDER BY d.expiry_date, d.person_id, d.doc_type;
END;
$$;

COMMENT ON FUNCTION fn_documents_expiring IS
  'p_days 天内到期的证照（191），按到期日升序。只含**当前在职**的人'
  '（离职者的证件不需要续，混进来会让提醒清单变噪音）与**未过期**的'
  '（已过期的属于另一张清单，两者的处理方式不同：一个要续，一个要停班）。'
  '★ 时点用 app_today()（业务时区），不是 current_date。';

