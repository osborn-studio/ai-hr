CREATE FUNCTION fn_ty_assert_company_financial_locale(p_company bigint,p_region text,p_currency text,p_require boolean DEFAULT false)
RETURNS void LANGUAGE plpgsql SET search_path='' AS $$
DECLARE loc record;
BEGIN
 SELECT * INTO loc FROM public.fn_ty_company_locale(p_company);
 IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='地区核验公司不存在';END IF;
 IF p_currency IS NULL OR p_currency !~ '^[A-Z]{3}$' OR (p_region IS NOT NULL AND p_region !~ '^[A-Z]{2}$') THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='工资或绩效必须明确地区及币种格式';
 END IF;
 IF p_require AND p_region IS NULL THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='确认前须明确地区，不能从币种或名称推断';END IF;
 IF loc.currency_code IS NOT NULL AND loc.currency_code<>p_currency THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='工资或绩效币种与公司品牌帐套不一致';
 END IF;
 IF loc.region_code IS NOT NULL AND p_region IS NOT NULL AND loc.region_code<>p_region THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='工资或绩效地区与公司品牌帐套不一致';
 END IF;
 IF EXISTS(SELECT 1 FROM public.ty_financial_locale_lock f WHERE f.company_id=p_company
   AND (f.currency_code<>p_currency OR (f.region_code IS NOT NULL AND p_region IS NOT NULL AND f.region_code<>p_region))) THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='公司已确认金额使用了不同地区或币种，请建立独立主体或版本';
 END IF;
END $$;

CREATE FUNCTION fn_ty_assert_rule_jurisdiction(p_rules jsonb,p_rule_region text,p_business_region text)
RETURNS void LANGUAGE plpgsql IMMUTABLE SET search_path='' AS $$
DECLARE r jsonb; module text; expected text;
BEGIN
 IF p_rule_region IS NULL OR NOT(p_rule_region ~ '^[A-Z]{2}$' OR p_rule_region='CUSTOM') THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='工资规则地区无效';
 END IF;
 IF p_rule_region<>'CUSTOM' AND p_business_region IS NOT NULL AND p_rule_region<>p_business_region THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='工资规则地区与公司批次地区不一致';
 END IF;
 FOR r IN SELECT * FROM jsonb_array_elements(p_rules) LOOP
  module:=COALESCE(r->>'jurisdiction_module','BASE');
  IF module NOT IN ('BASE','HK_MPF','CN_IIT','CN_SOCIAL_INSURANCE') THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='工资规则地区模块无效';
  END IF;
  expected:=CASE WHEN module='HK_MPF' THEN 'HK' WHEN module IN ('CN_IIT','CN_SOCIAL_INSURANCE') THEN 'CN' ELSE NULL END;
  IF expected IS NOT NULL AND (p_rule_region<>expected OR (p_business_region IS NOT NULL AND p_business_region<>expected)) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='地区专属工资模块不能用于其他地区或CUSTOM通用规则';
  END IF;
 END LOOP;
END $$;

CREATE FUNCTION fn_ty_lock_financial_locale(p_company bigint,p_region text,p_currency text,p_kind text,p_source bigint)
RETURNS void LANGUAGE plpgsql SET search_path='' AS $$
BEGIN
 PERFORM public.fn_ty_assert_company_financial_locale(p_company,p_region,p_currency,true);
 INSERT INTO public.ty_financial_locale_lock(company_id,group_id,ledger_id,brand_id,region_code,currency_code,source_kind,source_id)
  SELECT c.id,c.group_id,c.ledger_id,COALESCE(c.brand_id,l.brand_id),p_region,p_currency,p_kind,p_source
  FROM public.ty_company c JOIN public.ty_ledger l ON l.id=c.ledger_id WHERE c.id=p_company
 ON CONFLICT(company_id,source_kind,source_id) DO NOTHING;
END $$;

CREATE FUNCTION fn_ty_payroll_locale_guard() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE r record; rs public.ty_payroll_ruleset%ROWTYPE;
BEGIN
 IF NEW.status='confirmed' THEN PERFORM id FROM public.ty_group WHERE id=NEW.group_id FOR UPDATE;END IF;
 IF TG_OP='UPDATE' AND (NEW.currency IS DISTINCT FROM OLD.currency OR (OLD.region_code IS NOT NULL AND NEW.region_code IS DISTINCT FROM OLD.region_code)) THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='工资业务地区和币种不能直接改写，请建立新批次';
 END IF;
 IF NEW.status='confirmed' AND NEW.region_code IS NULL THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='确认工资前必须明确地区';END IF;
 IF NEW.ruleset_id IS NOT NULL THEN
  SELECT * INTO rs FROM public.ty_payroll_ruleset WHERE id=NEW.ruleset_id;
  IF rs.currency<>NEW.currency THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='工资规则币种与工资批次不一致';END IF;
  PERFORM public.fn_ty_assert_rule_jurisdiction(rs.rules,rs.region,NEW.region_code);
 END IF;
 FOR r IN SELECT company_id FROM public.ty_payroll_row WHERE batch_id=NEW.id AND company_id IS NOT NULL LOOP
  PERFORM public.fn_ty_assert_company_financial_locale(r.company_id,NEW.region_code,NEW.currency,NEW.status='confirmed');
  IF NEW.status='confirmed' THEN PERFORM public.fn_ty_lock_financial_locale(r.company_id,NEW.region_code,NEW.currency,'payroll_batch',NEW.id);END IF;
 END LOOP;
 RETURN NEW;
END $$;
CREATE TRIGGER ty_payroll_locale_guard BEFORE INSERT OR UPDATE ON ty_payroll_batch FOR EACH ROW EXECUTE FUNCTION fn_ty_payroll_locale_guard();

