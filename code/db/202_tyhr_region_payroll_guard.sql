CREATE FUNCTION fn_ty_financial_master_locale_guard() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE before_region text;before_currency text;after_region text;after_currency text;l public.ty_ledger%ROWTYPE;b public.ty_brand%ROWTYPE;
BEGIN
 -- Serialize locale maintenance with financial confirmation for this group.
 -- Recheck parent configuration after acquiring the lock: a preceding 201
 -- trigger may have read it before waiting for a concurrent transaction.
 PERFORM id FROM public.ty_group WHERE id=OLD.group_id FOR UPDATE;
 IF TG_TABLE_NAME='ty_company' THEN
  SELECT region_code,currency_code INTO before_region,before_currency FROM public.fn_ty_company_locale(OLD.id);
  SELECT * INTO l FROM public.ty_ledger WHERE id=NEW.ledger_id;SELECT * INTO b FROM public.ty_brand WHERE id=COALESCE(NEW.brand_id,l.brand_id);
  after_region:=COALESCE(b.region_code,l.region_code);after_currency:=COALESCE(b.currency_code,l.currency_code);
  IF b.region_code IS NOT NULL AND l.region_code IS NOT NULL AND (b.region_code<>l.region_code OR b.currency_code<>l.currency_code) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='公司品牌与帐套地区币种冲突';
  END IF;
  IF (before_region IS DISTINCT FROM after_region OR before_currency IS DISTINCT FROM after_currency)
   AND EXISTS(SELECT 1 FROM public.ty_financial_locale_lock WHERE company_id=OLD.id) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='公司已有确认金额，地区币种须建立新版本，不能直接改变归属';
  END IF;
 ELSE
  IF TG_TABLE_NAME='ty_ledger' THEN
   IF NEW.brand_id IS NOT NULL THEN
    SELECT * INTO b FROM public.ty_brand WHERE id=NEW.brand_id;
    IF b.region_code IS NOT NULL AND (NEW.region_code IS DISTINCT FROM b.region_code OR NEW.currency_code IS DISTINCT FROM b.currency_code) THEN
     RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='帐套与品牌地区币种冲突';
    END IF;
   END IF;
  END IF;
  IF TG_TABLE_NAME='ty_brand' AND OLD.region_code IS NULL AND NEW.region_code IS NOT NULL AND EXISTS(
   SELECT 1 FROM public.ty_ledger x WHERE x.brand_id=NEW.id AND x.region_code IS NOT NULL
    AND (x.region_code<>NEW.region_code OR x.currency_code<>NEW.currency_code)) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='品牌与既有帐套地区币种冲突';
  END IF;
  IF NEW.region_code IS DISTINCT FROM OLD.region_code OR NEW.currency_code IS DISTINCT FROM OLD.currency_code THEN
   IF (TG_TABLE_NAME='ty_brand' AND (EXISTS(SELECT 1 FROM public.ty_financial_locale_lock WHERE brand_id=OLD.id)
     OR EXISTS(SELECT 1 FROM public.ty_company c JOIN public.ty_ledger x ON x.id=c.ledger_id JOIN public.ty_financial_locale_lock f ON f.company_id=c.id WHERE COALESCE(c.brand_id,x.brand_id)=OLD.id)))
    OR (TG_TABLE_NAME='ty_ledger' AND (EXISTS(SELECT 1 FROM public.ty_financial_locale_lock WHERE ledger_id=OLD.id)
     OR EXISTS(SELECT 1 FROM public.ty_company c JOIN public.ty_financial_locale_lock f ON f.company_id=c.id WHERE c.ledger_id=OLD.id))) THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='品牌或帐套已有确认金额，地区币种须建立新版本';
   END IF;
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER ty_zz_financial_company_locale_guard BEFORE UPDATE ON ty_company FOR EACH ROW EXECUTE FUNCTION fn_ty_financial_master_locale_guard();
CREATE TRIGGER ty_zz_financial_brand_locale_guard BEFORE UPDATE ON ty_brand FOR EACH ROW EXECUTE FUNCTION fn_ty_financial_master_locale_guard();
