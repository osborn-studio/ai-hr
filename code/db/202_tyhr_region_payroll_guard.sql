   ('TYHR.PERF.REGION','绩效地区币种、确认主档地域历史锁定','PAYROLL','STRUCT','ty_perf_locale_guard','public','ty_perf_cycle','TRIGGER','node test/customer-payroll.test.mjs','node test/customer-payroll.test.mjs')
