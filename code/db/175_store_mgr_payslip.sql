-- ============================================================================
-- 175_store_mgr_payslip.sql · 店长能看**本店**工资条（只读，实发仍然掩码）
-- ----------------------------------------------------------------------------
-- 现象（演示级）：店长打开"工资条"那一屏是 **403**，不是"实发打码"。
--
-- 根因不在行闸，也不在字段策略，而在**岗位矩阵漏了一行**：
--   063 的 `sys_role_resource` 给 store_mgr(16) 配了考勤、请假、花名册、报表、
--   绩效、审批，**唯独没有 payslip**。而 063 的规矩是"未登记即拒绝"，
--   于是店长连"看这一行"的资格都没有 —— 页面拿到的是一次请求失败。
--
-- ★ 这是"矩阵漏了"，不是"设计取舍"。演示时它尤其糟：观众看到 403 只会觉得
--   系统坏了，而真实意图是"店长该看到本店的工资条，只是实发是打码的"。
--
-- ★★ 两件事必须分开给，别一起给：
--   ① **能不能看这一行** → 本迁移（can_read，不给 can_write）；
--   ② **能看这个字段吗** → 003 的字段策略。这里**故意什么都不配**：
--      `fn_field_action` 的兜底就是 masked（"无配置 = 掩码，不是可见"），
--      所以 net_amount 对店长仍是 null。给角色补一行资源 ≠ 放宽一个字段 ——
--      在 sys_field_permission 里补一行 visible 才是放宽，而那不该发生。
--
-- ★ 行闸完全不动：店长还是只到本店（cost_org 的 node_subtree 由建账号时
--   fn_account_create（064）按"这个门店 + 整棵子树"造的那个 scope 决定）。
--   本迁移只解决"岗位层"这一半，行闸那一半原本就是对的。
--
-- ★ 为什么另开迁移而不是改 063：迁移是事实，不是草稿（169/173 同一条）。
--   改已应用的迁移会让 schema_migration 里的 sha256 与文件对不上。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 店长：payslip 只读
-- ---------------------------------------------------------------------------
-- ★ 只写 can_read，**不写 can_write**：店长不是算薪的人。工资条是"发下去让人
--   签字"的凭证，能改它等于能改员工签字确认过的数。
-- ★ ON CONFLICT 只更新 can_read：万一某个库上这一行被人工改成 can_read=false，
--   重跑要能修回来；但**绝不能**顺手动 can_write（那会把"只读"变成"可写"，
--   而这条 SQL 看起来只是在补一行读权限）。
INSERT INTO sys_role_resource (role_id, resource_code, can_read, can_write) VALUES
  (16, 'payslip', true, false)
ON CONFLICT (role_id, resource_code) DO UPDATE SET can_read = true;

