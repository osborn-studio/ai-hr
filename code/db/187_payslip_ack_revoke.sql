-- ============================================================================
-- 187_payslip_ack_revoke.sql · 工资条签收的**撤回**（不是把回执删掉）
-- ----------------------------------------------------------------------------
-- 186 把"线上签收"做出来了，同时把"撤回"明确写成**本期不做**（186:17-21）：
--   "真要做就加一张撤销记录表，而不是 UPDATE 掉原来那条 ——
--    UPDATE 掉的回执等于'这个员工从来没签过'，而那是不实的。"
-- 本文件就是那张表。三条设计在下面说清，因为它们决定了后面所有读数的语义。
--
-- ★ 设计一：撤回 = **新增一条撤销记录**，原回执一个字节都不动
--   `payslip_ack` 仍是 append-only（185/186 的触发器继续拒 UPDATE/DELETE）。
--   于是同一张工资条会出现两个并存的事实：
--     · 他签过（payslip_ack 那一行，时间、方式、经办人都还在）
--     · 这个签收后来被谁、因为什么撤掉了（payslip_ack_revoke 那一行）
--   而"当前有效签收"是**派生**的：有回执且没有撤销记录。
--   反过来做（UPDATE 掉回执 / 加一列 is_revoked）会同时坏两件事：
--     · 谁签的这一事实消失 —— 事后无法回答"他到底签没签过"；
--     · 加了 is_revoked 就等于给 append-only 表开了一个可变字段，
--       下一次"顺手改一下 acked_at"就只需要多写一行 UPDATE。
--
-- ★ 设计二：`UNIQUE (ack_id)` —— 一条回执只能撤一次
--   撤两次不是"又撤了一次"，而是"有人对同一条回执做了两个不同的判断"。
--   第二次必须被拒（E_ACK_ALREADY_REVOKED，服务层判），否则撤销记录会
--   随点击次数增长，而"为什么撤"的答案有两个。要改理由就出示一条新事实：
--   走审批/更正，不是再点一次。
--
-- ★ 设计三：撤销记录本身也是 append-only
--   理由与 186 同一条：删掉一条撤销记录等于"这次撤回没发生过"，而员工的
--   签收已经被它作废了 —— 两份不实叠在一起，比单份更难查。
--   所以 trg_ackrv_append_only 拒 UPDATE/DELETE。
--
-- ★ 不加外键（沿用 186:27-28）：历史批次清理时，回执不该阻塞删除；
--   被引用的回执消失后，"这条撤回发生过"这件事仍然成立（ack_id 只是号码）。
--
-- ★ 副作用（必须写在明处）：撤回之后 v_payslip_ack_progress 的 acked 会**减 1**，
--   于是"8 月签收率 92.3%"在有人撤回之后会变成 92.0% —— **历史签收率会变**。
--   这不是 bug：签收率问的是"现在有多少张单是有效签收的"，而不是
--   "曾经最多有多少张签过"。要回答后者用 payslip_ack 本身（它没被改过）。
--   报表若需要"曾经签过"的口径，必须另起一列，不要偷偷改这一个。
--
-- 幂等：CREATE TABLE IF NOT EXISTS / CREATE OR REPLACE / DROP TRIGGER IF EXISTS
--       / ON CONFLICT DO NOTHING。不动 001–186 的任何字节。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 撤回记录
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.payslip_ack_revoke (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ack_id     bigint      NOT NULL,          -- payslip_ack.id（无外键，理由见文件头）
  revoked_by bigint      NOT NULL,          -- 操作人（sys_account.id，不是 person.id）
  reason     text        NOT NULL,
  at         timestamptz NOT NULL DEFAULT now(),
  -- 一条回执只能撤一次：第二次不是"再撤一次"，是对同一事实的第二个判断
  CONSTRAINT uk_ackrv_ack UNIQUE (ack_id),
  -- 理由 ≥ 4 个字。库里也判一遍：服务层会被绕过（MCP / 批量导入 / 手工 SQL），
  -- 而"撤了但没写为什么"正是这类记录最容易被质疑的地方。
  CONSTRAINT ck_ackrv_reason CHECK (length(btrim(reason)) >= 4)
);

CREATE INDEX IF NOT EXISTS ix_ackrv_at ON public.payslip_ack_revoke (at DESC);
CREATE INDEX IF NOT EXISTS ix_ackrv_by ON public.payslip_ack_revoke (revoked_by, at DESC);

COMMENT ON TABLE public.payslip_ack_revoke IS
  '工资条签收的撤回（187）。★ 撤回是**新增一条记录**，不是 UPDATE/DELETE 原回执（186:17-21）：'
  '原回执仍然是事实（他签过），撤销记录回答"这个签收后来被谁因为什么作废了"。'
  '有效签收 = 有回执且没有撤销记录（见 v_payslip_ack_effective / fn_payslip_ack_state）。'
  '一条回执只能撤一次（uk_ackrv_ack）；本表自身 append-only。';

COMMENT ON COLUMN public.payslip_ack_revoke.revoked_by IS
  '操作人（sys_account.id）。★ 不是 person.id：撤回一般由 HR 做，'
  '而这个 HR 本人不一定是这家店的员工；与 186 的 acked_by 用同一套身份口径。';

COMMENT ON COLUMN public.payslip_ack_revoke.ack_id IS
  '被撤的那条回执（payslip_ack.id）。无外键（与 186 同理）：历史批次清理时'
  '回执可能被删，但"这条撤回发生过"仍然成立。';

-- ---------------------------------------------------------------------------
-- 2. 撤销记录 append-only
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_ackrv_append_only()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  RAISE EXCEPTION 'E_ACKRV_READONLY: 签收撤回记录不可 % —— 删掉它等于"这次撤回没发生过"，'
                  '而员工的签收已经被它作废了（要改就新增一条更正，不是改这条）', TG_OP;
END;
$$;

DROP TRIGGER IF EXISTS trg_ackrv_append_only ON public.payslip_ack_revoke;
CREATE TRIGGER trg_ackrv_append_only
  BEFORE UPDATE OR DELETE ON public.payslip_ack_revoke
  FOR EACH ROW EXECUTE FUNCTION public.fn_ackrv_append_only();

-- ---------------------------------------------------------------------------
-- 3. "有效签收"的唯一表达式：有回执 且 没有撤销记录
-- ---------------------------------------------------------------------------
-- ★ 做成视图而不是在每处读接口写 LEFT JOIN + NOT EXISTS：
--   签收进度、未签名单、打印脚注、员工自助页至少四个地方要问同一个问题，
--   各写一遍的结果是"某处把撤回过的人还列在已签里"，而那一处不会报错。
--   读路径只要把 `LEFT JOIN payslip_ack a` 换成
--   `LEFT JOIN v_payslip_ack_effective a`，语义就从"签过"变成"有效"。
CREATE OR REPLACE VIEW public.v_payslip_ack_effective AS
  SELECT a.id, a.payslip_id, a.employee_id, a.pay_run_id,
         a.acked_at, a.method, a.acked_by, a.ip, a.note
    FROM public.payslip_ack a
   WHERE NOT EXISTS (SELECT 1 FROM public.payslip_ack_revoke r WHERE r.ack_id = a.id);

COMMENT ON VIEW public.v_payslip_ack_effective IS
  '有效签收（187）：payslip_ack 里**没有**对应撤销记录的那些行。'
  '★ 列与 payslip_ack 完全一致（去掉 id 之外没有新增、没有改名），'
  '  所以读路径只需把 JOIN 的表名换掉，不用改 SELECT 列表。'
  '★ 与 payslip_ack 的区别就是"他签过" vs "他现在有效的签收" —— 两者都要能查到。';

-- ---------------------------------------------------------------------------
-- 4. 一张工资条的签收状态（一次问清六个问题）
-- ---------------------------------------------------------------------------
-- 返回**恰好一行**，即使这张单不存在（acked=false）——
-- 否则调用方要为"查无此行"写一个分支，而那个分支通常写成"当作已签"。
--
-- ★ acked_at / method 在"已撤回"时**仍然返回原值**：
--   它们回答的是"他什么时候、用什么方式签的"，撤回不改变已发生的事。
--   要看撤销本身用 revoked / revoked_at / revoke_reason 三列。
CREATE OR REPLACE FUNCTION public.fn_payslip_ack_state(p_slip bigint)
RETURNS TABLE (
  acked         boolean,
  acked_at      timestamptz,
  method        varchar,
  revoked       boolean,
  revoked_at    timestamptz,
  revoke_reason text
)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT (a.id IS NOT NULL AND r.id IS NULL),
         a.acked_at,
         a.method::varchar,
         (r.id IS NOT NULL),
         r.at,
         r.reason
    FROM (SELECT 1) AS one
    LEFT JOIN public.payslip_ack a ON a.payslip_id = p_slip
    LEFT JOIN public.payslip_ack_revoke r ON r.ack_id = a.id;
$$;

COMMENT ON FUNCTION fn_payslip_ack_state IS
  '一张工资条的签收状态（187）：是否有效签收 / 何时签的 / 用什么方式 / 是否被撤 / 何时撤 / 为什么撤。'
  '★ 永远返回一行（单不存在时 acked=false）：调用方不必为"查无此行"开分支，'
  '  而那种分支常见的写法是把空结果当成"已签"。'
  '★ 已撤回时 acked_at 与 method 仍返回原值 —— 撤回不改变"他签过"这件事。';

-- ---------------------------------------------------------------------------
-- 5. 签收进度改成按"有效签收"算（撤回后不计入 acked）
-- ---------------------------------------------------------------------------
-- ★ 这是本文件对既有读数**唯一**的修改，改的是语义不是形状：
--   列名、列序、类型全部保持不变（CREATE OR REPLACE VIEW 也不允许改），
--   只把 LEFT JOIN 的目的表从 payslip_ack 换成 v_payslip_ack_effective。
--   于是 pending = slips − acked 自动把"撤回过的"重新算成未签 ——
--   这正是"撤回"该有的效果：这张单又回到了"没人认"的状态。
--
-- ★ 历史签收率会随之变化（撤回一张 8 月的单，8 月签收率就会降）。
--   这是设计选择，不是精度问题：签收率回答"现在有多少张有效签收"。
--   要"曾经签过多少张"请直接查 payslip_ack（一次都没被改过）。
CREATE OR REPLACE VIEW public.v_payslip_ack_progress AS
  SELECT p.pay_run_id,
         count(*)::int                                              AS slips,
         count(a.id)::int                                            AS acked,
         (count(*) - count(a.id))::int                                AS pending,
         round(100.0 * count(a.id) / NULLIF(count(*), 0), 1)          AS ack_rate,
         max(a.acked_at)                                              AS last_ack_at
    FROM public.payslip p
    LEFT JOIN public.v_payslip_ack_effective a ON a.payslip_id = p.id
   GROUP BY p.pay_run_id;

COMMENT ON VIEW public.v_payslip_ack_progress IS
  '每期签收进度（186/187）：slips / acked / pending / ack_rate / last_ack_at。'
  '★ 187 起 acked 只数**有效签收**（撤回的不算，pending 相应 +1），'
  '  于是历史签收率会随撤回变化 —— 这是"现在有多少张有效签收"的口径，不是"曾经签过多少"。'
  '★ 这里仍然**不做行闸**（186 的理由不变）：谁看得到哪些门店由服务层 fn_scope_people 收窄。';

-- 186 在表注释里写了"不做撤回"，那句话已被本文件取代 —— 就地更正，
-- 不去改 186 的任何字节。
COMMENT ON TABLE public.payslip_ack IS
  '工资条签收（186）。一张单一条回执（ux_ack_payslip）；method 区分本人线上/纸质代录/导入。'
  '★ 与 payslip_view_log 不是一回事：那是"谁看过"（取证），这是"我认不认这张数"（闭环）。'
  '★ 187 起可以**撤回**，但撤回是往 payslip_ack_revoke 新增一条记录，原回执仍 append-only；'
  '  "有效签收" = 有回执且没有撤销记录（v_payslip_ack_effective）。'
  '  仍然不要 UPDATE 掉回执 —— 那等于"他没签过"。';

