-- ---------------------------------------------------------------------------
-- ④ 汇总视图：一次跑完要看的那一行
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_chk_summary(p_as_of date)
RETURNS TABLE (bucket varchar(16), n int)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT c.bucket, count(*)::int
    FROM public.fn_chk_coverage(p_as_of) c
   GROUP BY c.bucket
   ORDER BY c.bucket;
$$;

COMMENT ON FUNCTION fn_chk_summary IS
  '四桶分开报，不给单一百分比。「通过率 95%」会把"1 条从来没跑过"和'
  '"1 条真的失败"折成同一个数，而这两件事的处置完全相反。';
