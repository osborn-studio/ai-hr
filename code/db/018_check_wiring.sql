-- 002 建了 sys_check_registry / sys_check_run / fn_chk_coverage，
-- 但**从来没有任何东西往里写过一行**。于是 fn_chk_coverage 的结论永远是
-- never_run——一个从不上报的报表，与没有报表在效果上相同，
-- 而它更坏的地方是：它长得像一个已经在跑的东西。
--
-- 本文件只做三件事：
--   ① 补一个记录函数（唯一写入口）
--   ② 登记本仓全部断言组的身份
--   ③ 让"覆盖率"从一个空表变成能回答"哪一组上次跑成什么样"
--
-- 不做的（写清楚，免得被当成已做）：
--   · 不做定时调度 —— 谁在什么时候跑，是部署层的事，本文件不假装有
--   · 不自动修红 —— 判据红只记录，不触发任何动作
-- ============================================================================

-- ---------------------------------------------------------------------------
-- ① sys_check_run.id 补生成方式
-- ---------------------------------------------------------------------------
-- ★ 这一条是**判据自己抓出来的**，不是我想起来的。
--   接线一开，fn_chk_record 就会 INSERT 进这张表，于是 test/run.mjs 的 Q14
--   （「会被函数 INSERT 的表，主键必须有生成方式」）立刻红——它抓的正是
--   这类错：表有主键、没有生成方式，函数插入时报 not-null 指向 id，
--   而报错看起来像数据缺失，不像表设计问题。
ALTER TABLE sys_check_run
  ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

-- ★ 加完 IDENTITY 必须同步序列。ADD GENERATED 建的新序列从 1 开始，
--   而表里可能已有行——下一次自动插入就撞主键。
--   本仓在这一点上错过五次（Q14 是那条机器判据），这是第六次的现场。
SELECT setval(pg_get_serial_sequence('sys_check_run','id'),
              GREATEST((SELECT COALESCE(max(id), 1) FROM sys_check_run), 1));

-- ---------------------------------------------------------------------------
-- ② 唯一写入口
-- ---------------------------------------------------------------------------
-- ★ 不允许多个函数各写一遍 verdict + run。两处写同一件事，
--   必然有一处先写、一处后写，而"最后一次是谁写的"没有地方记。
CREATE OR REPLACE FUNCTION fn_chk_record(
  p_code    varchar,
  p_outcome varchar,
  p_hits    bigint  DEFAULT NULL,
  p_sample  jsonb   DEFAULT NULL
) RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_exists boolean;
BEGIN
  SELECT EXISTS (SELECT 1 FROM public.sys_check_registry WHERE check_code = p_code)
    INTO v_exists;
  -- 未登记的判据不许留痕。允许它写，就等于允许"跑了一条没人知道的检查"，
  -- 而那种检查的结论没有任何地方会去读——它只会让运行表看起来更热闹。
  IF NOT v_exists THEN
    RAISE EXCEPTION 'E_CHK_UNREGISTERED: 判据 % 未登记，不允许记录结论', p_code;
  END IF;

  INSERT INTO public.sys_check_run(check_code, run_at, outcome, hit_count, sample)
  VALUES (p_code, clock_timestamp(), p_outcome, p_hits, p_sample);

  UPDATE public.sys_check_registry
     SET verdict = CASE p_outcome
                     WHEN 'pass'    THEN 'green'
                     WHEN 'fail'    THEN 'red'
                     WHEN 'error'   THEN 'red'
                     ELSE 'yellow'          -- skipped：既不是通过也不是失败
                   END,
         updated_at = now()
   WHERE check_code = p_code;
END;
$$;

COMMENT ON FUNCTION fn_chk_record IS
  '判据结果的唯一写入口。skipped 记 yellow 不记 green —— '
  '「没跑」与「跑过且通过」在报告上必须不同色，否则被跳过的检查看起来是绿的。';

