-- ============================================================================
-- 166_si_ledger.sql · 社保参保台账：谁在哪个月、在哪个城市、参了哪些险种、基数几
-- ----------------------------------------------------------------------------
-- 到 165 为止，社保这条线上有三样东西：
--   · 012 的 si_policy（哪个城市哪个险种、上下限与费率）
--   · 133 的 si_base_declare（一年一次的申报基数，夹过上下限）
--   · 141 的 fn_declare_si（**申报时临时算**的逐人逐险种申报表）
--
-- 唯独没有"参保这件事本身"的记录。于是四个问题今天都答不出：
--
--   ① **「我 3 月参保了吗？」** —— 只能靠"3 月有没有工资条、工资条上有没有扣社保、
--      当时 hire_date 是否在 3 月"反推。三个条件各自都可能对、合起来仍可能错：
--      3 月在发工资但社保由别的主体缴、3 月在缴但工资条还没出、月中入职按政策
--      当月不缴却发了整月工资。**没有一条记录能直接回答是/否。**
--   ② **增减员时点。** 入职当月缴不缴、离职当月缴到几号，各地口径不同（有的按 15 日
--      前后切、有的按整月）。从 hire_date **推算**会在跨月那天给出两个答案 ——
--      而社保少缴要补缴加滞纳金，多缴退不回来。时点必须是一条显式记录。
--   ③ **年度调基不留痕。** 每年 7 月调基，旧基数被覆盖后，员工拿着工资条问
--      「为什么这个月多扣了 80 块」，系统只能回答"现在的基数是多少"，
--      答不出"从多少调到多少、哪天调的、谁调的"。稽核要的恰恰是后者。
--   ④ **缴费明细与工资条没人对账。** 工资条上扣的个人部分，与台账按
--      基数 × 费率算出来的，理应一致。不一致时两边都不报错：钱扣了，
--      台账上没有（或反过来）。**这类错只有在有人逐行比的时候才出现。**
--
-- ★ 五条设计取舍：
--
--   ① **参保是一条带起止月的记录，不是从入职日算出来的。**
--      start_period / end_period 是 YYYY-MM 的**缴费月**（不是日期）。跨月那天
--      政策怎么切，由录入的人按当地口径决定，系统不替他推算 —— 推算在
--      「15 日前后」这类规则下必然给出两个答案，而两个答案都"看起来合理"。
--
--   ② **期间不重叠靠排他约束，不靠调用方自觉。**
--      同一个人 + 同一城市 + 同一险种的期间用 daterange 表达，配 btree_gist
--      排他约束（照 014 的 ex_eoa_no_overlap）。重叠会被数据库直接拒（23P01）——
--      包括"补录去年的参保"撞上已有段、"调基新段没把旧段收口"这两种最常见的写法错。
--      应用层再判一次没有意义：它总会被导入脚本、后台作业、将来的新接口绕过去。
--
--   ③ **费率与基数落在台账行里，月度明细只读台账。**
--      fn_si_month 不回查 si_policy —— 政策每年会改，用它重算历史月份，
--      等于让"去年 3 月的社保"随今年的政策变化。这与工资条封账同一条规矩：
--      落账时的数就是那个数，要改就走调基/更正，不改历史。
--
--   ④ **调基是"收口旧段 + 新开一段 + 写一条留痕"，不是 UPDATE 基数。**
--      UPDATE 会把"上个月按旧基数扣了多少"一起改掉，工资条却已经发了。
--      留痕表 si_base_history 只增不改（触发器拒 UPDATE/DELETE）——
--      它是稽核时唯一的证据链。
--
--   ⑤ **对账把"缺一边"也当成差异。**
--      工资扣了、台账没有（no_ledger）与台账有、工资没扣（no_payslip）
--      都是真实缺口，不能因为"另一边是空的"就不算差异 —— 那正好是漏保/漏扣。
--      只有两边都在且相等才是 ok。
--
-- ★ 不做的事：
--   · 不做"参保城市自动取 employment"——employment 上没有这个字段（141 用的是
--     字面量 '上海'）。真做多城市要改数据模型，这里让调用方显式给 city，
--     并在台账里落下来，至少从此"每个人在哪个城市参保"有答案。
--   · 不做"基数按上年度月平均自动算"——那是 133 的 fn_si_declare_build，
--     本文件只消费它的结果（fn_si_declared_base）；两份自动算必然漂。
-- ============================================================================

CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ---------------------------------------------------------------------------
-- 0. 缴费月（YYYY-MM）↔ 日期区间
-- ---------------------------------------------------------------------------
-- ★ 排他约束里的表达式必须是 IMMUTABLE。to_date / ::date 受 DateStyle 影响，
--   是 STABLE，不能进索引表达式；make_date + substr 才是纯函数。
--   认不出的格式返回 NULL（CHECK 会先拒掉，这里只是不让函数在表达式里抛错）。
CREATE OR REPLACE FUNCTION fn_sil_period_ok(p_period varchar)
RETURNS boolean
LANGUAGE sql IMMUTABLE
SET search_path = ''
AS $$
  SELECT COALESCE(p_period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$', false);
$$;

COMMENT ON FUNCTION fn_sil_period_ok IS
  '缴费月格式（YYYY-MM）。台账的起止月用它校验 —— 2026-3、2026-13、2026-3-1 都不接受。';

CREATE OR REPLACE FUNCTION fn_sil_month_first(p_period varchar)
RETURNS date
LANGUAGE sql IMMUTABLE
SET search_path = ''
AS $$
  SELECT CASE WHEN p_period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'
              THEN make_date(substr(p_period, 1, 4)::int,
                             substr(p_period, 6, 2)::int, 1)
         END;
$$;

CREATE OR REPLACE FUNCTION fn_sil_month_last(p_period varchar)
RETURNS date
LANGUAGE sql IMMUTABLE
SET search_path = ''
AS $$
  SELECT CASE WHEN p_period IS NULL THEN NULL
              WHEN p_period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$' THEN
                (CASE WHEN substr(p_period, 6, 2)::int = 12
                      THEN make_date(substr(p_period, 1, 4)::int + 1, 1, 1)
                      ELSE make_date(substr(p_period, 1, 4)::int,
                                     substr(p_period, 6, 2)::int + 1, 1)
                 END) - 1
         END;
$$;

COMMENT ON FUNCTION fn_sil_month_last IS
  '缴费月最后一天；NULL 表示"还在缴"（区间上界无穷）。'
  '调基要把旧段收口到生效月的上一个月，用的就是这个月界的定义。';

CREATE OR REPLACE FUNCTION fn_sil_prev_period(p_period varchar)
RETURNS varchar
LANGUAGE sql IMMUTABLE
SET search_path = ''
AS $$
  SELECT CASE WHEN p_period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$' THEN
           CASE WHEN substr(p_period, 6, 2)::int = 1
                THEN (substr(p_period, 1, 4)::int - 1)::text || '-12'
                ELSE substr(p_period, 1, 4)
                     || '-' || lpad((substr(p_period, 6, 2)::int - 1)::text, 2, '0')
           END
         END::varchar;
$$;

-- ---------------------------------------------------------------------------
-- 1. 参保台账
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.si_enrollment (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id    bigint       NOT NULL,          -- person.id
  city           varchar(32)  NOT NULL,          -- 参保城市（与 si_policy.city 同源）
  item           varchar(24)  NOT NULL,          -- 险种规范键（与 si_policy.item 同源）
  -- ★ 缴费月，不是日期：跨月那天怎么切由当地口径决定，不做推算（见文件头 ①）
  start_period   varchar(7)   NOT NULL,          -- 起缴月 YYYY-MM
  end_period     varchar(7),                     -- 末缴月；NULL = 仍在缴
  base_amount    numeric(12,2) NOT NULL,         -- 这一段适用的缴费基数（已夹上下限）
  -- ★ 费率随行落账：政策改了不影响这一段已缴的月份（见文件头 ③）
  rate_employee  numeric(6,4) NOT NULL DEFAULT 0,
  rate_employer  numeric(6,4) NOT NULL DEFAULT 0,
  source         varchar(16)  NOT NULL DEFAULT 'hire',
  note           varchar(200),
  created_by     varchar(64)  NOT NULL DEFAULT 'system',
  created_at     timestamptz  NOT NULL DEFAULT now(),

  CONSTRAINT ck_sie_city   CHECK (length(btrim(city)) > 0),
  CONSTRAINT ck_sie_period_start CHECK (public.fn_sil_period_ok(start_period)),
  CONSTRAINT ck_sie_period_end   CHECK (end_period IS NULL
                                        OR (public.fn_sil_period_ok(end_period)
                                            AND end_period >= start_period)),
  CONSTRAINT ck_sie_base   CHECK (base_amount > 0),
  CONSTRAINT ck_sie_rate   CHECK (rate_employee BETWEEN 0 AND 1
                                  AND rate_employer BETWEEN 0 AND 1),
  CONSTRAINT ck_sie_item   CHECK (length(btrim(item)) > 0),
  -- ★ 'leave' 是**停缴事件**的来源。停缴只改 end_period，不改 source ——
  --   把 hire 改写成 leave 会把"这段是怎么开始的"抹掉，而那正是台账要回答的。
  CONSTRAINT ck_sie_source CHECK (source IN ('hire','transfer','adjust','leave'))
);

COMMENT ON TABLE public.si_enrollment IS
  '社保参保台账（166）。一行 = 一个人在一个城市参加一个险种的一段连续缴费期。'
  '存在这一行的意思是"这些月份这个人确实在缴"，不是"按政策应该缴"；'
  '申报表（141）仍然按政策出，两者对不上就是漏保或错报。';
COMMENT ON COLUMN public.si_enrollment.start_period IS
  '起缴月 YYYY-MM。入职当月缴不缴、离职当月缴到几月，由录入按当地口径给 —— '
  '从 hire_date 推算会在跨月 15 日前后给出两个都"看起来合理"的答案。';
COMMENT ON COLUMN public.si_enrollment.end_period IS
  '末缴月 YYYY-MM（含）；NULL = 仍在缴。"停缴"是给这一段填上末月，不是删行 —— '
  '删了就无法回答"他 3 月参保了吗"。';
COMMENT ON COLUMN public.si_enrollment.base_amount IS
  '这一段适用的缴费基数（已按 si_policy 的上下限夹过）。调基不是改这个字段，'
  '而是把旧段收口到调整月前一个月、再新开一段（见 fn_si_adjust_base）。';

-- ★ 同一人 + 同城 + 同险种，期间不得重叠。
--   表达成 [起缴月 1 号, 末缴月最后一天]，'[]' 语义与 014/007 一致：
--   起止月都算"在缴"。NULL 上界 = 无穷，于是"重复参保"与"停缴后忘了收口就再开一段"
--   都会被 23P01 直接拒掉。
ALTER TABLE public.si_enrollment ADD CONSTRAINT ex_sie_no_overlap
  EXCLUDE USING gist (
    employee_id WITH =,
    city        WITH =,
    item        WITH =,
    daterange(public.fn_sil_month_first(start_period),
              public.fn_sil_month_last(end_period), '[]') WITH &&
  );

CREATE INDEX IF NOT EXISTS ix_sie_emp_period
  ON public.si_enrollment (employee_id, start_period);
CREATE INDEX IF NOT EXISTS ix_sie_city_period
  ON public.si_enrollment (city, start_period);

-- ---------------------------------------------------------------------------
-- 2. 基数调整留痕（只增不改）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.si_base_history (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id      bigint       NOT NULL,
  city             varchar(32)  NOT NULL,
  -- ★ 比需求多一列 item：各项的上下限可能不同（养老与医疗的封顶常不同），
  --   同一个"调基动作"落到各险种的实际基数也可能不同。不留 item，
  --   稽核时看到两行同样的"旧 11396 → 新 12000"无法判断是哪一项。
  item             varchar(24)  NOT NULL,
  effective_period varchar(7)   NOT NULL,        -- 从哪个缴费月起按新基数
  old_base         numeric(12,2) NOT NULL,
  new_base         numeric(12,2) NOT NULL,
  reason           varchar(200) NOT NULL,
  changed_by       varchar(64)  NOT NULL,
  changed_at       timestamptz  NOT NULL DEFAULT now(),

  CONSTRAINT ck_sbh_period CHECK (public.fn_sil_period_ok(effective_period)),
  CONSTRAINT ck_sbh_base   CHECK (old_base > 0 AND new_base > 0),
  CONSTRAINT ck_sbh_diff   CHECK (old_base <> new_base),
  CONSTRAINT ck_sbh_reason CHECK (length(btrim(reason)) >= 4),
  CONSTRAINT uk_sbh UNIQUE (employee_id, city, item, effective_period)
);

COMMENT ON TABLE public.si_base_history IS
  '社保基数调整留痕（166）。只增不改 —— 触发器拒绝 UPDATE/DELETE。'
  '回答的是"为什么这个月扣多了"：从哪个缴费月起、旧基数多少、新基数多少、谁调的、为什么。';

CREATE OR REPLACE FUNCTION fn_sbh_append_only() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  RAISE EXCEPTION 'E_SIL_HISTORY_APPEND_ONLY: 基数调整留痕只增不改（% 被拒）', TG_OP;
END;
$$;

COMMENT ON FUNCTION fn_sbh_append_only IS
  '留痕表拒绝 UPDATE/DELETE。留痕能被改，它就不再是证据 —— '
  '要更正就再调一次基（新开一段 + 新写一条留痕），历史两条都在。';

DROP TRIGGER IF EXISTS trg_sbh_append_only ON public.si_base_history;
CREATE TRIGGER trg_sbh_append_only
  BEFORE UPDATE OR DELETE ON public.si_base_history
  FOR EACH ROW EXECUTE FUNCTION fn_sbh_append_only();

-- ---------------------------------------------------------------------------
-- 3. 参保：批量参保险种
-- ---------------------------------------------------------------------------
-- p_items 支持两种写法：
--   ["pension","medical","unemployment"]                    ← 基数自动取
--   [{"item":"pension","base_amount":12000}, ...]           ← 指定基数（仍会夹上下限）
--
-- 基数来源（按优先级）：
--   ① 入参显式给的 base_amount
--   ② 133 的申报基数（fn_si_declared_base）
--   ③ 该月有效的月薪标准（salary_standard）
-- 三者都没有 → E_SIL_NO_BASE。**不猜 0**：0 基数缴出来是"免缴"，与漏保同形。
--
-- ★ 同一段已经存在且基数/费率完全一致 → 跳过（幂等），返回 0。
--   不一致或期间重叠 → 让排他约束拒（23P01），不在这里另写一套重叠判断：
--   两套判断必然有一处漏，而漏的那次是"重复参保五个月"。
CREATE OR REPLACE FUNCTION fn_si_enroll(
  p_employee    bigint,
  p_city        varchar,
  p_items       jsonb,
  p_from_period varchar,
  p_by          varchar DEFAULT 'system'
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_city   varchar(32) := btrim(COALESCE(p_city, ''));
  v_start  date;
  v_end    date;
  v_hired  date;
  v_left   date;
  v_decl   numeric(12,2);
  v_wage   numeric(12,2);
  v_base   numeric(12,2);
  v_floor  numeric(12,2);
  v_ceil   numeric(12,2);
  v_re     numeric(6,4);
  v_rr     numeric(6,4);
  v_src    varchar(16);
  v_seen   int := 0;
  v_n      int := 0;
  r        record;
BEGIN
  IF p_employee IS NULL OR p_employee <= 0 THEN
    RAISE EXCEPTION 'E_SIL_BAD_ARG: employee 必须是正整数';
  END IF;
  IF v_city = '' THEN
    RAISE EXCEPTION 'E_SIL_BAD_ARG: city 不能为空（参保城市决定用哪一套费率与上下限）';
  END IF;
  IF NOT public.fn_sil_period_ok(p_from_period) THEN
    RAISE EXCEPTION 'E_SIL_BAD_ARG: 起缴月必须是 YYYY-MM（收到 %）', p_from_period;
  END IF;
  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'E_SIL_BAD_ARG: items 必须是非空数组（险种键列表）';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.person WHERE id = p_employee) THEN
    RAISE EXCEPTION 'E_SIL_NO_EMPLOYEE: 员工 % 不存在', p_employee;
  END IF;

  v_start := public.fn_sil_month_first(p_from_period);
  v_end   := public.fn_sil_month_last(p_from_period);

  -- ★ 离职月取"最后一段任职"的离职日：只要还有一段在职（leave_date IS NULL），
  --   这个人就没离职。直接 max(leave_date) 会在"离职后又返聘"的人身上取到
  --   上一段的离职日，于是新一段的参保被误判成"晚于离职月"。
  SELECT min(e.hire_date),
         CASE WHEN count(*) FILTER (WHERE e.leave_date IS NULL) > 0 THEN NULL
              ELSE max(e.leave_date) END
    INTO v_hired, v_left
    FROM public.employment e WHERE e.person_id = p_employee;
  IF v_hired IS NULL THEN
    RAISE EXCEPTION 'E_SIL_NO_EMPLOYEE: 员工 % 没有任何任职记录 —— 参保必须挂在任职上', p_employee;
  END IF;
  IF v_start < date_trunc('month', v_hired)::date THEN
    RAISE EXCEPTION 'E_SIL_BEFORE_HIRE: 起缴月 % 早于入职月 %',
      p_from_period, to_char(v_hired, 'YYYY-MM');
  END IF;
  -- ★ 离职月可以缴（当月缴不缴由录入决定），离职月之后不行
  IF v_left IS NOT NULL AND v_start > date_trunc('month', v_left)::date THEN
    RAISE EXCEPTION 'E_SIL_AFTER_LEAVE: 起缴月 % 晚于离职月 %',
      p_from_period, to_char(v_left, 'YYYY-MM');
  END IF;

  -- 申报基数（133）与月薪标准：只取这一次，逐险种夹上下限
  v_decl := public.fn_si_declared_base(p_employee, v_city, v_end);
  SELECT s.monthly_amount INTO v_wage
    FROM public.employment e
    JOIN public.salary_standard s ON s.employment_id = e.id
   WHERE e.person_id = p_employee
     AND s.effective_from <= v_end
     AND e.hire_date <= v_end
     AND (e.leave_date IS NULL OR e.leave_date >= v_start)
   ORDER BY s.effective_from DESC, e.hire_date DESC
   LIMIT 1;

  -- 这个人以前在别的城市参过 → 这是转入，不是新入职参保
  v_src := CASE WHEN EXISTS (
             SELECT 1 FROM public.si_enrollment x
              WHERE x.employee_id = p_employee AND x.city <> v_city)
           THEN 'transfer' ELSE 'hire' END;

  FOR r IN
    SELECT DISTINCT ON (public.fn_si_item_canon(q.item))
           public.fn_si_item_canon(q.item) AS item,
           q.base_amount
      FROM (
        SELECT CASE WHEN jsonb_typeof(j.e) = 'string' THEN j.e #>> '{}'
                    ELSE j.e ->> 'item' END AS item,
               CASE WHEN jsonb_typeof(j.e) = 'object'
                    THEN NULLIF(j.e ->> 'base_amount', '')::numeric END AS base_amount
          FROM jsonb_array_elements(p_items) AS j(e)
      ) q
     WHERE q.item IS NOT NULL AND btrim(q.item) <> ''
     ORDER BY public.fn_si_item_canon(q.item), q.base_amount NULLS LAST
  LOOP
    v_seen := v_seen + 1;

    SELECT sp.rate_employee, sp.rate_employer, sp.base_floor, sp.base_ceiling
      INTO v_re, v_rr, v_floor, v_ceil
      FROM public.si_policy sp
     WHERE sp.city = v_city AND sp.item = r.item AND sp.effective_from <= v_end
     ORDER BY sp.effective_from DESC
     LIMIT 1;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'E_SIL_NO_POLICY: % 的 % 在 % 之前没有生效的社保政策（先录 si_policy：费率与上下限）',
        v_city, r.item, v_end;
    END IF;

    v_base := COALESCE(r.base_amount, v_decl, v_wage);
    IF v_base IS NULL THEN
      RAISE EXCEPTION 'E_SIL_NO_BASE: 员工 % 在 % 没有申报基数（133）、也没有月薪标准，缴费基数算不出',
        p_employee, p_from_period;
    END IF;
    IF v_base <= 0 THEN
      RAISE EXCEPTION 'E_SIL_BAD_ARG: 缴费基数必须大于 0（收到 %）', v_base;
    END IF;
    -- 参保一律夹进上下限：申报基数与月薪都会随年份变化，越界是常态不是异常
    v_base := LEAST(GREATEST(v_base, v_floor), v_ceil);

    -- 幂等：同一段、同基数、同费率已经记过 → 不动
    IF EXISTS (
      SELECT 1 FROM public.si_enrollment s
       WHERE s.employee_id = p_employee AND s.city = v_city AND s.item = r.item
         AND s.start_period = p_from_period AND s.end_period IS NULL
         AND s.base_amount = v_base
         AND s.rate_employee = v_re AND s.rate_employer = v_rr) THEN
      CONTINUE;
    END IF;

    INSERT INTO public.si_enrollment
      (employee_id, city, item, start_period, end_period,
       base_amount, rate_employee, rate_employer, source, created_by)
    VALUES
      (p_employee, v_city, r.item, p_from_period, NULL,
       v_base, v_re, v_rr, v_src, p_by);
    v_n := v_n + 1;
  END LOOP;

  IF v_seen = 0 THEN
    RAISE EXCEPTION 'E_SIL_BAD_ARG: items 里没有可识别的险种键（期望 pension/medical/unemployment/injury/maternity/housing_fund）';
  END IF;

  RETURN v_n;
END;
$$;

COMMENT ON FUNCTION fn_si_enroll IS
  '批量参保（166）：按 si_policy 取**起缴月所在月**的费率与上下限，基数夹在 floor/ceiling 之间。'
  '同一段同基数重复调用是幂等的（返回 0）；期间重叠由 ex_sie_no_overlap 拒（23P01）。';

-- ---------------------------------------------------------------------------
-- 4. 停缴：给在缴段填上末缴月
-- ---------------------------------------------------------------------------
-- ★ 不删行、不改 source。删了就答不出"他 3 月参保了吗"；
--   把 hire 改写成 leave 会抹掉"这一段是怎么开始的"。
--   停缴人/时间写进 note（200 字上限，超出截断）。
CREATE OR REPLACE FUNCTION fn_si_stop(
  p_employee   bigint,
  p_city       varchar,
  p_end_period varchar,
  p_by         varchar DEFAULT 'system'
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_city varchar(32) := btrim(COALESCE(p_city, ''));
  v_n    int;
  v_bad  record;
BEGIN
  IF p_employee IS NULL OR p_employee <= 0 THEN
    RAISE EXCEPTION 'E_SIL_BAD_ARG: employee 必须是正整数';
  END IF;
  IF v_city = '' THEN
    RAISE EXCEPTION 'E_SIL_BAD_ARG: city 不能为空';
  END IF;
  IF NOT public.fn_sil_period_ok(p_end_period) THEN
    RAISE EXCEPTION 'E_SIL_BAD_ARG: 末缴月必须是 YYYY-MM（收到 %）', p_end_period;
  END IF;

  SELECT count(*)::int INTO v_n
    FROM public.si_enrollment e
   WHERE e.employee_id = p_employee AND e.city = v_city AND e.end_period IS NULL;
  IF v_n = 0 THEN
    RAISE EXCEPTION 'E_SIL_NOT_ENROLLED: 员工 % 在 % 没有在缴的参保段，无从停缴', p_employee, v_city;
  END IF;

  SELECT e.item, e.start_period INTO v_bad
    FROM public.si_enrollment e
   WHERE e.employee_id = p_employee AND e.city = v_city
     AND e.end_period IS NULL AND e.start_period > p_end_period
   LIMIT 1;
  IF v_bad.item IS NOT NULL THEN
    RAISE EXCEPTION 'E_SIL_STOP_BEFORE_START: % 的起缴月 % 晚于末缴月 % —— 停缴不能早于参保',
      v_bad.item, v_bad.start_period, p_end_period;
  END IF;

  UPDATE public.si_enrollment e
     SET end_period = p_end_period,
         note = left(
           COALESCE(NULLIF(e.note, '') || '；', '')
           || format('停缴：末缴月 %s（%s）', p_end_period, COALESCE(p_by, 'system')),
           200)
   WHERE e.employee_id = p_employee AND e.city = v_city AND e.end_period IS NULL;

  GET DIAGNOSTICS v_n = ROW_COUNT;
  RETURN v_n;
END;
$$;

COMMENT ON FUNCTION fn_si_stop IS
  '停缴（166）：把该人该城所有在缴段的 end_period 收口到末缴月，返回段数。'
  '末缴月含在内（[] 语义）。没有任何在缴段 → E_SIL_NOT_ENROLLED；末缴月早于起缴月 → E_SIL_STOP_BEFORE_START。';

-- ---------------------------------------------------------------------------
-- 5. 调基：收口旧段 + 写留痕 + 新开一段
-- ---------------------------------------------------------------------------
-- 每年 7 月调基 = 一个动作，三处落笔（同一事务）：
--   ① si_base_history 写一条（旧基数/新基数/原因/谁）；
--   ② 旧参保段 end_period = 生效月前一个月（不是删除，历史月份仍按旧基数）；
--   ③ 新段从生效月起，基数为新基数，费率取**生效月**的政策（调基常伴随费率调整）。
--
-- ★ 手工给的基数越界 → 拒（E_SIL_BASE_RANGE），不静默夹。
--   参保时夹是"从工资推基数"的必然（工资每年变）；调基是人给的判断，
--   越过上下限说明这个数错了（少报会被追缴），应当让人看见并改对。
CREATE OR REPLACE FUNCTION fn_si_adjust_base(
  p_employee         bigint,
  p_city             varchar,
  p_effective_period varchar,
  p_new_base         numeric,
  p_reason           varchar,
  p_by               varchar DEFAULT 'system'
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_city  varchar(32) := btrim(COALESCE(p_city, ''));
  v_new   numeric(12,2);
  v_prev  varchar(7);
  v_end   date;
  v_floor numeric(12,2);
  v_ceil  numeric(12,2);
  v_re    numeric(6,4);
  v_rr    numeric(6,4);
  v_n     int := 0;
  r       record;
BEGIN
  IF p_employee IS NULL OR p_employee <= 0 THEN
    RAISE EXCEPTION 'E_SIL_BAD_ARG: employee 必须是正整数';
  END IF;
  IF v_city = '' THEN
    RAISE EXCEPTION 'E_SIL_BAD_ARG: city 不能为空';
  END IF;
  IF NOT public.fn_sil_period_ok(p_effective_period) THEN
    RAISE EXCEPTION 'E_SIL_BAD_ARG: 生效月必须是 YYYY-MM（收到 %）', p_effective_period;
  END IF;
  v_new := round(p_new_base, 2);
  IF v_new IS NULL OR v_new <= 0 THEN
    RAISE EXCEPTION 'E_SIL_BAD_ARG: 新基数必须大于 0';
  END IF;
  IF length(btrim(COALESCE(p_reason, ''))) < 4 THEN
    RAISE EXCEPTION 'E_SIL_NO_REASON: 调基必须写原因（至少 4 个字）—— 员工问"为什么扣多了"时，这是唯一的解释';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.si_enrollment e
                  WHERE e.employee_id = p_employee AND e.city = v_city
                    AND e.end_period IS NULL) THEN
    RAISE EXCEPTION 'E_SIL_NOT_ENROLLED: 员工 % 在 % 没有在缴的参保段，不能调基', p_employee, v_city;
  END IF;

  v_prev := public.fn_sil_prev_period(p_effective_period);
  v_end  := public.fn_sil_month_last(p_effective_period);

  FOR r IN
    SELECT e.id, e.item, e.base_amount, e.start_period
      FROM public.si_enrollment e
     WHERE e.employee_id = p_employee AND e.city = v_city AND e.end_period IS NULL
     ORDER BY public.fn_si_item_seq(e.item), e.item
  LOOP
    -- 生效月必须晚于这一段开始：同月改基数等于把参保当天的数改掉，那是重录参保不是调基
    IF p_effective_period <= r.start_period THEN
      RAISE EXCEPTION 'E_SIL_ADJUST_BEFORE_START: % 的生效月 % 不晚于起缴月 %',
        r.item, p_effective_period, r.start_period;
    END IF;

    SELECT sp.rate_employee, sp.rate_employer, sp.base_floor, sp.base_ceiling
      INTO v_re, v_rr, v_floor, v_ceil
      FROM public.si_policy sp
     WHERE sp.city = v_city AND sp.item = r.item AND sp.effective_from <= v_end
     ORDER BY sp.effective_from DESC
     LIMIT 1;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'E_SIL_NO_POLICY: % 的 % 在 % 之前没有生效的社保政策', v_city, r.item, v_end;
    END IF;
    IF v_new < v_floor OR v_new > v_ceil THEN
      RAISE EXCEPTION 'E_SIL_BASE_RANGE: % 的新基数 % 超出 % 的上下限 % ~ %（调基不静默夹，越界要人改对）',
        r.item, v_new, v_effective_period, v_floor, v_ceil;
    END IF;
    -- 同值不写留痕：ck_sbh_diff 会拒，但那会以 23514 的形式出现 —— 参数错该有名字
    IF r.base_amount = v_new THEN
      RAISE EXCEPTION 'E_SIL_BAD_ARG: % 的新基数与旧基数相同（%），这不是调基', r.item, v_new;
    END IF;

    INSERT INTO public.si_base_history
      (employee_id, city, item, effective_period, old_base, new_base,
       reason, changed_by)
    VALUES
      (p_employee, v_city, r.item, p_effective_period, r.base_amount, v_new,
       btrim(p_reason), COALESCE(p_by, 'system'));

    UPDATE public.si_enrollment e
       SET end_period = v_prev
     WHERE e.id = r.id;

    INSERT INTO public.si_enrollment
      (employee_id, city, item, start_period, end_period,
       base_amount, rate_employee, rate_employer, source, note, created_by)
    VALUES
      (p_employee, v_city, r.item, p_effective_period, NULL,
       v_new, v_re, v_rr, 'adjust',
       format('调基：%s → %s（%s）', r.base_amount, v_new, btrim(p_reason)),
       COALESCE(p_by, 'system'));

    v_n := v_n + 1;
  END LOOP;

  RETURN v_n;
END;
$$;

COMMENT ON FUNCTION fn_si_adjust_base IS
  '调基（166）：逐险种写一条 si_base_history、旧段收口到生效月前一个月、新段从生效月开。'
  '费率取生效月的政策（调基常伴随费率调整）；新基数越界直接拒（E_SIL_BASE_RANGE），不静默夹。';

-- ---------------------------------------------------------------------------
-- 6. 月度明细：只读台账，不读当前政策
-- ---------------------------------------------------------------------------
-- ★ 这是本文件与 141 最根本的区别：
--   141 是"按今天的政策重算一张申报表"（给税务/社保局看，要按当期口径）；
--   本函数是"这个人这个月实际是怎么缴的"（给员工和稽核看，要按当时落账的数）。
--   拿政策重算历史月份，等于让去年的社保随今年的政策变化 —— 工资条却已经发了。
CREATE OR REPLACE FUNCTION fn_si_month(p_employee bigint, p_period varchar)
RETURNS TABLE (
  city          varchar(32),
  item          varchar(24),
  item_name     varchar(32),
  seq           smallint,
  base_amount   numeric(12,2),
  rate_employee numeric(6,4),
  rate_employer numeric(6,4),
  emp_amount    numeric(12,2),
  er_amount     numeric(12,2),
  source        varchar(16)
)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
BEGIN
  IF NOT public.fn_sil_period_ok(p_period) THEN
    RAISE EXCEPTION 'E_SIL_BAD_ARG: 缴费月必须是 YYYY-MM（收到 %）', p_period;
  END IF;

  RETURN QUERY
  SELECT e.city::varchar(32),
         e.item::varchar(24),
         public.fn_si_item_name(e.item)::varchar(32),
         public.fn_si_item_seq(e.item)::smallint,
         e.base_amount::numeric(12,2),
         e.rate_employee,
         e.rate_employer,
         round(e.base_amount * e.rate_employee, 2)::numeric(12,2),
         round(e.base_amount * e.rate_employer, 2)::numeric(12,2),
         e.source::varchar(16)
    FROM public.si_enrollment e
   WHERE e.employee_id = p_employee
     AND e.start_period <= p_period
     AND (e.end_period IS NULL OR e.end_period >= p_period)
   ORDER BY public.fn_si_item_seq(e.item), e.item;
END;
$$;

COMMENT ON FUNCTION fn_si_month IS
  '某人在某缴费月的逐险种明细：基数、个人额、单位额 —— 全部读台账行，'
  '不按当前 si_policy 重算（重算会让历史月份随政策变化，而工资条已经发了）。'
  '返回空集 = 这个月没有参保记录（不是"扣了 0"）。';

-- ---------------------------------------------------------------------------
-- 7. 对账：台账 vs 工资条
-- ---------------------------------------------------------------------------
-- 工资条一侧的实际扣款，按三种形态取（历史数据三种都存在）：
--   ① 105 之后：分险种各一行（SI_PENSION / SI_MEDICAL …），没有 SI_EMPLOYEE 行；
--   ② 105 之前：一行 SI_EMPLOYEE（合计）；
--   ③ 明细被删过/结构项覆盖：只剩 payslip.si_employee 表头合计。
-- 优先 ①/② 的明细，最后才回退表头 —— 明细是"扣了哪些"，表头只是汇总。
--
-- ★ 同一 (人, 法人, 期间) 可能有多版批次（calc_version），只取最新一版；
--   直接 SUM 会把 v1/v2 加两遍。
-- ★ 缺一边也算差异：工资扣了台账没有（no_ledger）= 漏保；台账有工资没扣
--   （no_payslip）= 漏扣或少报。两者都必须能被列出来。
CREATE OR REPLACE FUNCTION fn_si_reconcile(p_period varchar)
RETURNS TABLE (
  employee_no      varchar(16),
  person_name      varchar(64),
  cities           varchar(64),
  ledger_employee  numeric(12,2),
  payslip_employee numeric(12,2),
  diff             numeric(12,2),
  status           varchar(16)
)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
BEGIN
  IF NOT public.fn_sil_period_ok(p_period) THEN
    RAISE EXCEPTION 'E_SIL_BAD_ARG: 缴费月必须是 YYYY-MM（收到 %）', p_period;
  END IF;

  RETURN QUERY
  WITH led AS (
    SELECT e.employee_id,
           sum(round(e.base_amount * e.rate_employee, 2))::numeric(12,2) AS led_amt,
           string_agg(DISTINCT e.city, ',' ORDER BY e.city)::varchar(64) AS city_list
      FROM public.si_enrollment e
     WHERE e.start_period <= p_period
       AND (e.end_period IS NULL OR e.end_period >= p_period)
     GROUP BY e.employee_id
  ), lat AS (
    -- 每个 (人, 法人) 取最新一版月度批次；年终奖批次不参与社保对账
    SELECT DISTINCT ON (s.employee_id, r.legal_entity_id)
           s.id AS slip_id, s.employee_id, s.si_employee
      FROM public.payslip s
      JOIN public.pay_run r ON r.id = s.pay_run_id
     WHERE r.period = p_period
       AND COALESCE(r.kind, 'monthly') = 'monthly'
     ORDER BY s.employee_id, r.legal_entity_id, r.calc_version DESC, r.id DESC
  ), act AS (
    SELECT a.employee_id,
           sum(COALESCE(
             (SELECT sum(-pi.amount) FROM public.payslip_item pi
               WHERE pi.payslip_id = a.slip_id AND pi.item_code = 'SI_EMPLOYEE'),
             (SELECT sum(-pi.amount) FROM public.payslip_item pi
               WHERE pi.payslip_id = a.slip_id
                 AND pi.item_code LIKE 'SI#_%' ESCAPE '#'),
             a.si_employee))::numeric(12,2) AS slip_amt
      FROM lat a
     GROUP BY a.employee_id
  )
  SELECT
    (SELECT n.no FROM public.employee_no n
      WHERE n.assigned_person_id = u.employee_id AND n.retired_at IS NULL
      ORDER BY n.assigned_at DESC LIMIT 1)::varchar(16),
    p.full_name::varchar(64),
    COALESCE(l.city_list, '')::varchar(64),
    COALESCE(l.led_amt, 0)::numeric(12,2),
    COALESCE(a.slip_amt, 0)::numeric(12,2),
    (COALESCE(l.led_amt, 0) - COALESCE(a.slip_amt, 0))::numeric(12,2),
    (CASE WHEN l.employee_id IS NULL     THEN 'no_ledger'
          WHEN a.employee_id IS NULL     THEN 'no_payslip'
          WHEN COALESCE(l.led_amt, 0) = COALESCE(a.slip_amt, 0) THEN 'ok'
          ELSE 'diff' END)::varchar(16)
  FROM (SELECT employee_id FROM led UNION SELECT employee_id FROM act) u
  LEFT JOIN led l ON l.employee_id = u.employee_id
  LEFT JOIN act a ON a.employee_id = u.employee_id
  LEFT JOIN public.person p ON p.id = u.employee_id
  -- 缺一边的排前面（它是漏保/漏扣，比金额差更严重），其次按差额绝对值
  ORDER BY CASE WHEN l.employee_id IS NULL OR a.employee_id IS NULL THEN 0 ELSE 1 END,
           abs(COALESCE(l.led_amt, 0) - COALESCE(a.slip_amt, 0)) DESC,
           u.employee_id;
END;
$$;

COMMENT ON FUNCTION fn_si_reconcile IS
  '社保对账（166）：台账算出的个人额 vs 工资条实际扣款，逐人返回差额。'
  'status：ok 相等 / diff 不等 / no_ledger 工资扣了但台账没有（漏保）/ '
  'no_payslip 台账有但本期没发工资（漏扣或少报）。';

