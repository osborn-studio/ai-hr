-- ----------------------------------------------------------------------------
-- 本文件只建"会算错钱"的那部分：五列物理量 + 快照口径列 + 四条勾稽约束。
-- 排班、班段、异常处理等不在此列（它们错了会被人发现，这里错了不会）。
--
-- 四条约束的分工：
--   chk_ads_span   物理锚：span_hours 必须等于真实时刻差（唯一"无外部锚"的一条）
--   chk_ads_sum    口径勾稽：work 是否扣在岗休息，取决于"写这条记录时的口径"
--   chk_ads_off    非负：负休息会让 work > span
--   chk_ads_nonneg 五列非负
-- 一条排斥约束：
--   ex_ads_no_overlap  同一人同一天不得两行
-- ============================================================================

CREATE TABLE attendance_daily_store (
  -- ★ 第五次同一个坑。这次不再单点修，见 test/run.mjs 的 Q9：
  --   凡「单列 bigint 主键叫 id」的表，必须有生成方式，由一条机器判据扫全库。
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id       bigint NOT NULL,
  store_id          bigint NOT NULL,
  work_date         date   NOT NULL,

  -- 时刻（用来锚定 span_hours）
  shift_start_at    timestamptz NOT NULL,
  shift_end_at      timestamptz NOT NULL,

  -- 五列物理量（§3.3.2：自洽的封闭体系）
  span_hours             numeric(6,2) NOT NULL,
  on_duty_hours          numeric(6,2) NOT NULL,
  off_duty_hours         numeric(6,2) NOT NULL,
  break_on_duty_hours    numeric(6,2) NOT NULL,
  in_attendance_hours    numeric(6,2) NOT NULL,
  work_hours             numeric(6,2) NOT NULL,

  -- ★ 快照口径列：这一行"当时按哪种口径算 work"，必须是写入当时的固化了的事实
  snap_on_duty_break_basis varchar(12) NOT NULL,
  -- ...（其余 13 个 snap_* 列见 04 §3.3.5，本文件从略，不影响本组断言）

  CONSTRAINT chk_ads_range    CHECK (shift_end_at > shift_start_at),
  CONSTRAINT chk_ads_max24    CHECK (shift_end_at - shift_start_at <= interval '24 hours'),

  -- ★★ 物理锚：唯一"锚定来源 = 无"的一条，必须自带断言。
  --    精确比，不用容差：round(...,2) 的结果与 numeric(6,2) 同为 2 位小数格点。
  --    写成 abs(...) < 0.01 与 = 0 完全等价（同标度差值只能是 0.01 的整数倍）；
  --    而写成 <= 0.01 才真的允许差一格 —— 那正是要拦的形态。
  CONSTRAINT chk_ads_span CHECK (
    span_hours = round(EXTRACT(EPOCH FROM (shift_end_at - shift_start_at)) / 3600.0, 2)
  ),

  -- ★★ 口径勾稽：两支全析取。用 ELSE 兜底会让下一个新取值静默落进某条分支。
  CONSTRAINT chk_ads_sum CHECK (
       (snap_on_duty_break_basis =  'hourly' AND work_hours = in_attendance_hours)
    OR (snap_on_duty_break_basis <> 'hourly' AND work_hours = in_attendance_hours - break_on_duty_hours)
  ),

  CONSTRAINT chk_ads_off CHECK (in_attendance_hours <= span_hours),
  CONSTRAINT chk_ads_nonneg CHECK (
    LEAST(span_hours, on_duty_hours, off_duty_hours,
          break_on_duty_hours, in_attendance_hours, work_hours) >= 0
  ),

  -- ★ 值域：显式列出三种。缺这一条时，拼错的值会落进 chk_ads_sum 的
  --   "<> 'hourly'" 一支而静默通过（见断言 E7）。
  CONSTRAINT ck_ads_snap_odb CHECK (
    snap_on_duty_break_basis IN ('allowance', 'hourly', 'none')
  )
);

-- 同一人同一天不得两行（'[]' 而非 '[)'：一天就是一格，不是区间）
ALTER TABLE attendance_daily_store ADD CONSTRAINT ex_ads_no_overlap
  EXCLUDE USING gist (employee_id WITH =, daterange(work_date, work_date, '[]') WITH &&);

