-- ============================================================================
-- 133_si_declare.sql · 社保缴费基数：按"上年度月平均"，一年定一次
-- ----------------------------------------------------------------------------
-- 到 132 为止，社保基数是这么来的：
--
--     v_si_one := fn_si_base('上海', si.item, v_monthly, v_period_end) * rate
--
-- 也就是**每月按当月月薪标准**算一次、夹一次上下限。这有两个问题，
-- 而它们都属于"看起来合理、对账时答不出来"的那一类：
--
--   ① **基数每年只该定一次。** 7 月调基之后，一年内不随月薪变动。
--      现在的实现里，某人 9 月涨薪 2000，9 月的社保基数当场跟着涨 ——
--      而社保局那边收到的是 7 月申报的那个数，两边永远差一截。
--
--   ② **"月薪标准"不等于"上年度月平均工资"。** 法定口径是
--      「职工本人上年度月平均工资」，它含奖金、津贴、加班费；
--      而月薪标准只是合同约定。用月薪标准当基数，旺季奖金多的人会少缴，
--      而少缴是欠缴 —— 会被追缴并加收滞纳金。
--
-- 依据：
--   《社会保险法》第 60 条：用人单位应当自行申报、按时足额缴纳。
--   《社会保险费申报缴纳管理规定》（人社部令第 20 号）第 8 条：
--     缴费基数按职工本人上年度月平均工资申报。
--   各地实施办法：基数下限=当地上年度全口径平均工资的 60%，上限 300%；
--     调整时间各地不同（上海 7 月、部分城市 1 月），所以生效日不写死，由录入决定。
--
-- ★ 三条设计取舍：
--
--   ① **不做"自动调基"**。生成的是 `source='calc'` 的**待确认**记录，
--      HR 核过之后才算数（与节假日骨架同一套思路：系统算，人确认）。
--      理由：基数报错了要更正申报，比补一张请假单麻烦得多。
--
--   ② **上下限不预置**。各地每年 7 月公布，写死等于明年一定错。
--      `si_policy` 里已经有 base_floor / base_ceiling，这版只是让"用哪个月的"
--      说得清：申报基数用**申报生效日**那天的上下限，不是每月重新夹。
--
--   ③ **默认不计入年终奖工资条**。`SI_BASE_INCLUDE_BONUS` 默认 off：
--      年终奖是独立工资条（108），各地对"是否计入缴费基数"口径不同，
--      默认沿用上线前行为（不含），客户按当地口径自己开。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 申报基数
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS si_base_declare (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id    bigint NOT NULL,
  city           varchar(32) NOT NULL,
  declare_year   int    NOT NULL,          -- 2027 = 2027-07 起的那个社保年度
  effective_from date   NOT NULL,          -- 通常是 7/1（各地不同，由录入决定）
  monthly_avg    numeric(12,2) NOT NULL,   -- 上年度月平均（夹之前，留证据）
  base_amount    numeric(12,2) NOT NULL,   -- 实际申报的基数（夹过上下限）
  months_counted int    NOT NULL,          -- 上年度实际计薪月数（不满 12 个月的按实际）
  source         varchar(16) NOT NULL DEFAULT 'calc',
  reason         varchar(200) NOT NULL,
  created_by     varchar(64) NOT NULL DEFAULT 'system',
  created_at     timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT uk_sbd UNIQUE (employee_id, city, declare_year),
  CONSTRAINT ck_sbd_year CHECK (declare_year BETWEEN 2000 AND 2100),
  CONSTRAINT ck_sbd_amt  CHECK (monthly_avg >= 0 AND base_amount > 0),
  CONSTRAINT ck_sbd_src  CHECK (source IN ('calc','manual','import'))
);

CREATE INDEX IF NOT EXISTS ix_sbd_lookup ON si_base_declare (employee_id, city, effective_from);

COMMENT ON TABLE si_base_declare IS
  '社保缴费基数申报（133）。一年一条，effective_from 起一年内不变。'
  'monthly_avg 是夹之前的"上年度月平均"，留着是为了回答"为什么是这个数"。';

