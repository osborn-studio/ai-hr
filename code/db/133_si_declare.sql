-- ---------------------------------------------------------------------------
-- 3. 取申报基数（没有就回退月薪标准，保证既有账不变）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_si_declared_base(p_employee bigint, p_city varchar, p_on date)
RETURNS numeric
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT d.base_amount
    FROM public.si_base_declare d
   WHERE d.employee_id = p_employee AND d.city = p_city
     AND d.effective_from <= p_on
     AND d.effective_from > (p_on - interval '1 year')::date
   ORDER BY d.effective_from DESC
   LIMIT 1;
$$;

COMMENT ON FUNCTION fn_si_declared_base IS
  '某人某时点的社保申报基数；没有申报记录返回 NULL（调用方回退月薪标准）。'
  '有效期按"生效日起一年内"判断 —— 申报基数一年只定一次，不随月薪变动。';

-- 算薪用的统一入口：有申报用申报，没有用月薪标准（= 133 之前的行为）
CREATE OR REPLACE FUNCTION fn_si_base_eff(
  p_employee bigint, p_city varchar, p_item varchar, p_wage numeric, p_on date
) RETURNS numeric
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE
  v_decl numeric;
BEGIN
  v_decl := public.fn_si_declared_base(p_employee, p_city, p_on);
  IF v_decl IS NULL THEN
    RETURN public.fn_si_base(p_city, p_item, p_wage, p_on);
  END IF;
  -- ★ 申报基数**再夹一次**：上下限每年调，去年申报的数今年可能已经越界。
  --   夹逼只有一处实现（fn_si_base 的那条 LEAST/GREATEST），所以这里复用它：
  --   把申报基数当成"工资"传进去，等于只做夹逼、不做别的。
  RETURN public.fn_si_base(p_city, p_item, v_decl, p_on);
END;
$$;

COMMENT ON FUNCTION fn_si_base_eff IS
  '算薪用：优先取申报基数（再按当期上下限夹一次），没有申报则回退月薪标准。'
  '回退分支保证 133 之前的历史月份重算结果不变。';

-- ---------------------------------------------------------------------------
-- 4. 生成申报基数：上年度月平均工资
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_si_declare_build(
  p_year int, p_city varchar DEFAULT '上海', p_from date DEFAULT NULL, p_by varchar DEFAULT 'system'
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_eff    date := COALESCE(p_from, make_date(p_year, 7, 1));
  v_inc_b  boolean := false;
  v_n      int := 0;
  v_basis  varchar(8);
  e        record;
  v_sum    numeric(14,2);
  v_cnt    int;
  v_avg    numeric(12,2);
  v_base   numeric(12,2);
  v_floor  numeric(12,2);
  v_ceil   numeric(12,2);
BEGIN
  IF p_year < 2000 OR p_year > 2100 THEN
    RAISE EXCEPTION 'E_SI_YEAR: 年度 % 不合理（2000–2100）', p_year;
  END IF;

  SELECT COALESCE(value_text,'off') = 'on' INTO v_inc_b
    FROM public.fn_policy_effective('SI_BASE_INCLUDE_BONUS', NULL, v_eff);

  -- 该城市在该生效日的上下限（取养老那条：各地养老与医疗的上下限通常一致，
  -- 若不一致说明政策录错了，这里只做一次夹逼，不按险种分别夹）
  SELECT p.base_floor, p.base_ceiling INTO v_floor, v_ceil
    FROM public.si_policy p
   WHERE p.city = p_city AND p.effective_from <= v_eff
   ORDER BY p.effective_from DESC LIMIT 1;

  IF v_floor IS NULL THEN
    RAISE EXCEPTION 'E_SI_NO_POLICY: % 在 % 之前没有社保政策，算不出上下限', p_city, v_eff;
  END IF;

  FOR e IN
    SELECT em.person_id
      FROM public.employment em
     WHERE daterange(em.hire_date, em.leave_date, '[]') @> v_eff
  LOOP
    -- 上年度 1–12 月的应发合计（可选含年终奖工资条）
    SELECT COALESCE(SUM(p.gross_amount), 0), COUNT(*)
      INTO v_sum, v_cnt
      FROM public.payslip p
      JOIN public.pay_run pr ON pr.id = p.pay_run_id
     WHERE p.employee_id = e.person_id
       AND pr.period BETWEEN (p_year - 1) || '-01' AND (p_year - 1) || '-12'
       AND pr.status IN ('sealed','paid')
       -- ★ kind 用 COALESCE 兜住 NULL：108 之前建的批次没有 kind，
       --   直接写 `kind='monthly'` 会让那些月份整月被过滤掉（NULL 比较恒为 NULL），
       --   于是"这个人上年度没发过薪"—— 而他明明发了。
       AND (v_inc_b OR COALESCE(pr.kind, 'monthly') = 'monthly');

    IF v_cnt = 0 THEN CONTINUE; END IF;   -- 上年度没发过薪（新入职）：不生成，等明年

    v_avg := round(v_sum / v_cnt, 2);
    v_base := LEAST(GREATEST(v_avg, v_floor), v_ceil);

    INSERT INTO public.si_base_declare(employee_id, city, declare_year, effective_from,
                                       monthly_avg, base_amount, months_counted,
                                       source, reason, created_by)
    VALUES (e.person_id, p_city, p_year, v_eff, v_avg, v_base, v_cnt,
            'calc', format('%s 年度调基：上年度 %s 个月应发平均 %s 元，夹到 %s~%s',
                           p_year, v_cnt, v_avg, v_floor, v_ceil), p_by)
    ON CONFLICT (employee_id, city, declare_year) DO UPDATE
      -- ★ source='manual' 的行**金额一律不动**：手工改过的数就是人的判断，
      --   重跑一次生成就把它冲掉，会让人再也不敢手工改。
      --   第一版只把 source 保成 'manual'、金额却照旧覆盖 —— 注释写对了、SQL 没跟上，
      --   SID5 立刻抓到（改 12000，重跑后变回 7384）。
      SET monthly_avg    = CASE WHEN si_base_declare.source = 'manual'
                                THEN si_base_declare.monthly_avg ELSE EXCLUDED.monthly_avg END,
          base_amount    = CASE WHEN si_base_declare.source = 'manual'
                                THEN si_base_declare.base_amount ELSE EXCLUDED.base_amount END,
          months_counted = CASE WHEN si_base_declare.source = 'manual'
                                THEN si_base_declare.months_counted ELSE EXCLUDED.months_counted END,
          reason         = CASE WHEN si_base_declare.source = 'manual'
                                THEN si_base_declare.reason ELSE EXCLUDED.reason END,
          effective_from = EXCLUDED.effective_from,
          source         = CASE WHEN si_base_declare.source = 'manual'
                                THEN 'manual' ELSE 'calc' END;
    v_n := v_n + 1;
  END LOOP;

  RETURN v_n;
END;
$$;

COMMENT ON FUNCTION fn_si_declare_build IS
  '按上年度 1–12 月应发月平均生成申报基数，夹到该年度的上下限之间。'
  '只处理上年度发过薪的人（新入职的等下一个年度）。手工改过的行不覆盖金额。';

-- ---------------------------------------------------------------------------
-- 5. 手工改 / 确认
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_si_declare_set(
  p_employee bigint, p_year int, p_base numeric, p_city varchar,
  p_why varchar, p_by varchar DEFAULT 'system'
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_id    bigint;
  v_floor numeric(12,2);
  v_ceil  numeric(12,2);
  v_eff   date;
BEGIN
  IF p_why IS NULL OR length(btrim(p_why)) < 4 THEN
    RAISE EXCEPTION 'E_SI_NO_REASON: 改申报基数必须写原因（至少 4 个字）；'
      '这个数报错了要更正申报，比补一张请假单麻烦得多';
  END IF;
  IF p_base IS NULL OR p_base <= 0 THEN
    RAISE EXCEPTION 'E_SI_BASE_INVALID: 基数必须大于 0';
  END IF;

  SELECT d.effective_from INTO v_eff
    FROM public.si_base_declare d
   WHERE d.employee_id = p_employee AND d.city = p_city AND d.declare_year = p_year;
  v_eff := COALESCE(v_eff, make_date(p_year, 7, 1));

  SELECT p.base_floor, p.base_ceiling INTO v_floor, v_ceil
    FROM public.si_policy p
   WHERE p.city = p_city AND p.effective_from <= v_eff
   ORDER BY p.effective_from DESC LIMIT 1;

  IF v_floor IS NOT NULL AND (p_base < v_floor OR p_base > v_ceil) THEN
    RAISE EXCEPTION 'E_SI_BASE_RANGE: 基数 % 不在 %~% 之间（% 在 % 的上下限）',
      p_base, v_floor, v_ceil, p_city, v_eff;
  END IF;

  INSERT INTO public.si_base_declare(employee_id, city, declare_year, effective_from,
                                     monthly_avg, base_amount, months_counted,
                                     source, reason, created_by)
  VALUES (p_employee, p_city, p_year, v_eff, p_base, p_base, 0, 'manual',
          btrim(p_why), p_by)
  ON CONFLICT (employee_id, city, declare_year) DO UPDATE
    SET base_amount = EXCLUDED.base_amount,
        source = 'manual',
        reason = EXCLUDED.reason,
        created_by = EXCLUDED.created_by,
        created_at = now()
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_si_declare_set IS
  '手工指定某人的申报基数（要写原因、要落在上下限内）。source 置 manual，重跑生成不会冲掉。';

