-- Source-backed foundation import. Only selected organization/employment fields
-- are retained. No customer workbook, bank data or salary values are seeded.
CREATE TABLE ty_foundation_import_batch (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id bigint NOT NULL REFERENCES ty_group(id), ledger_id bigint NOT NULL,
  source_kind text NOT NULL CHECK(source_kind='hk_roster_z14'),
  source_sha256 text NOT NULL CHECK(source_sha256 ~ '^[0-9a-f]{64}$'),
  filename text NOT NULL, status text NOT NULL CHECK(status IN ('committed','committed_with_pending')),
  company_mapping jsonb NOT NULL, stats jsonb NOT NULL DEFAULT '{}',
  created_by bigint NOT NULL, created_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY(ledger_id,group_id) REFERENCES ty_ledger(id,group_id),
  UNIQUE(group_id,source_sha256)
);
CREATE TABLE ty_foundation_import_company (
  batch_id bigint NOT NULL REFERENCES ty_foundation_import_batch(id), source_label text NOT NULL,
  company_id bigint REFERENCES ty_company(id), mapping_kind text NOT NULL CHECK(mapping_kind IN ('created_operating','existing','hq_pending')),
  internal_code_generated boolean NOT NULL DEFAULT false,
  PRIMARY KEY(batch_id,source_label)
);
CREATE TABLE ty_foundation_import_row (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id bigint NOT NULL REFERENCES ty_foundation_import_batch(id), source_row integer NOT NULL CHECK(source_row>=3),
  source_id_text text NOT NULL CHECK(btrim(source_id_text)<>''),
  person_id bigint NOT NULL REFERENCES ty_person(id), employment_id bigint REFERENCES ty_employment(id),
  company_id bigint REFERENCES ty_company(id), status text NOT NULL CHECK(status IN ('imported_employment','identity_only_pending')),
  source_data jsonb NOT NULL, issues jsonb NOT NULL DEFAULT '[]',
  CHECK(jsonb_typeof(source_data)='object' AND jsonb_typeof(issues)='array'),
  UNIQUE(batch_id,source_row), UNIQUE(batch_id,source_id_text)
);
CREATE TABLE ty_foundation_import_event (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  batch_id bigint NOT NULL REFERENCES ty_foundation_import_batch(id),
  source_row integer, event_kind text NOT NULL, details jsonb NOT NULL,
  occurred_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE FUNCTION fn_ty_foundation_import_immutable() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
BEGIN RAISE EXCEPTION 'E_TY_CONFLICT: 导入来源、异常及批次记录只可追加，不得覆盖或清空'; END; $$;
CREATE TRIGGER ty_foundation_import_batch_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON ty_foundation_import_batch FOR EACH STATEMENT EXECUTE FUNCTION fn_ty_foundation_import_immutable();
CREATE TRIGGER ty_foundation_import_company_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON ty_foundation_import_company FOR EACH STATEMENT EXECUTE FUNCTION fn_ty_foundation_import_immutable();
CREATE TRIGGER ty_foundation_import_row_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON ty_foundation_import_row FOR EACH STATEMENT EXECUTE FUNCTION fn_ty_foundation_import_immutable();
CREATE TRIGGER ty_foundation_import_event_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON ty_foundation_import_event FOR EACH STATEMENT EXECUTE FUNCTION fn_ty_foundation_import_immutable();

CREATE FUNCTION fn_ty_commit_foundation_import(gid bigint,lid bigint,sha text,file_name text,source_rows jsonb,mappings jsonb,actor bigint,review_ack boolean)
RETURNS jsonb LANGUAGE plpgsql SET search_path='' AS $$
DECLARE l public.ty_ledger%ROWTYPE; old_batch public.ty_foundation_import_batch%ROWTYPE; bid bigint; r jsonb; m jsonb; label text; cid bigint; pid bigint; eid bigint;
  created_companies integer=0; existing_companies integer=0; identities integer=0; employments integer=0; pending integer=0; idx integer=0;
  mapping_result jsonb='{}'; row_issues jsonb; stats jsonb; mapping_kind text; pno text; source_state text;
BEGIN
  IF NOT public.fn_role_can(actor,'ledger','write') THEN RAISE EXCEPTION 'E_TY_FORBIDDEN: 批量基础导入仅限基础管理员'; END IF;
  IF review_ack IS DISTINCT FROM true THEN RAISE EXCEPTION 'E_TY_ARGUMENT: 请先核验门店映射、来源编号与缺失组织信息并明确确认'; END IF;
  IF jsonb_typeof(source_rows) IS DISTINCT FROM 'array' OR jsonb_array_length(source_rows)=0 OR jsonb_array_length(source_rows)>10000 THEN
    RAISE EXCEPTION 'E_TY_ARGUMENT: 来源明细须为1至10000行';
  END IF;
  PERFORM 1 FROM public.ty_group WHERE id=gid AND status='active' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'E_TY_ARGUMENT: 集团不存在或已停用'; END IF;
  SELECT * INTO l FROM public.ty_ledger WHERE id=lid AND group_id=gid AND status='active' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'E_TY_ARGUMENT: 帐套不属于所选集团或已停用'; END IF;
  SELECT * INTO old_batch FROM public.ty_foundation_import_batch WHERE group_id=gid AND source_sha256=sha;
  IF FOUND THEN RETURN jsonb_build_object('already_imported',true,'batch_id',old_batch.id,'ledger_id',old_batch.ledger_id,'stats',old_batch.stats); END IF;
  IF EXISTS(SELECT 1 FROM jsonb_array_elements(source_rows) a JOIN public.ty_external_identity x ON x.group_id=gid AND x.source_system='roster'
    AND x.raw_id_text=a.value->>'source_id_text' AND x.source_namespace<>('hk_roster_z14:'||sha)) THEN
    RAISE EXCEPTION 'E_TY_CONFLICT: 另一来源批次含相同未核验编号，须先核验身份；不自动按编号或姓名合并或重复建人';
  END IF;
  FOR label IN SELECT DISTINCT value->>'source_department' FROM jsonb_array_elements(source_rows) ORDER BY 1 LOOP
    IF coalesce(btrim(label),'')='' THEN RAISE EXCEPTION 'E_TY_ARGUMENT: 来源部门/门店标签缺失'; END IF;
    IF label ~ '(总经理室|總經理室)' THEN
      IF coalesce((mappings->label->>'create')::boolean,false) THEN RAISE EXCEPTION 'E_TY_ARGUMENT: 总经理室是总部单位，不得自动创建为门店公司'; END IF;
      mapping_result=mapping_result||jsonb_build_object(label,jsonb_build_object('company_id',NULL,'kind','hq_pending','internal_code_generated',false));
      CONTINUE;
    END IF;
    m=mappings->label;
    IF m ? 'company_id' THEN
      cid=(m->>'company_id')::bigint;
      IF NOT EXISTS(SELECT 1 FROM public.ty_company WHERE id=cid AND group_id=gid AND ledger_id=lid AND status='active' AND company_kind='store') THEN
        RAISE EXCEPTION 'E_TY_ARGUMENT: 来源门店必须匹配同帐套的有效经营公司';
      END IF;
      existing_companies=existing_companies+1;mapping_kind='existing';
    ELSIF m->>'create'='true' THEN
      idx=idx+1;
      INSERT INTO public.ty_company(group_id,ledger_id,brand_id,code,name,company_kind)
      VALUES(gid,lid,l.brand_id,'IMP-'||left(sha,12)||'-'||idx,label,'store') RETURNING id INTO cid;
      created_companies=created_companies+1;mapping_kind='created_operating';
    ELSE RAISE EXCEPTION 'E_TY_ARGUMENT: 每个门店标签必须显式选择已有公司或创建经营公司'; END IF;
    mapping_result=mapping_result||jsonb_build_object(label,jsonb_build_object('company_id',cid,'kind',mapping_kind,'internal_code_generated',mapping_kind='created_operating'));
  END LOOP;
  -- Batch provenance is inserted once with its final immutable statistics below.
  -- IDs are reserved before inserting children; no partially committed batch can
  -- exist because the caller owns one transaction around this function.
  bid=nextval(pg_get_serial_sequence('public.ty_foundation_import_batch','id'));
  FOR r IN SELECT value FROM jsonb_array_elements(source_rows) LOOP
    IF coalesce(btrim(r->>'source_id_text'),'')='' OR coalesce(btrim(r->>'full_name'),'')='' THEN RAISE EXCEPTION 'E_TY_ARGUMENT: 来源编号及中文姓名不可为空'; END IF;
    identities=identities+1;cid=(mapping_result->(r->>'source_department')->>'company_id')::bigint;
    source_state=r->>'employment_state';
    IF cid IS NOT NULL AND source_state IN ('active','ended') AND r->>'hire_date' IS NOT NULL THEN employments=employments+1; ELSE pending=pending+1; END IF;
  END LOOP;
  stats=jsonb_build_object('source_rows',jsonb_array_length(source_rows),'identities_created',identities,'employments_created',employments,'pending_employments',pending,
    'companies_created',created_companies,'companies_reused',existing_companies,'external_identities_needs_review',identities);
  INSERT INTO public.ty_foundation_import_batch(id,group_id,ledger_id,source_kind,source_sha256,filename,status,company_mapping,stats,created_by)
  VALUES(bid,gid,lid,'hk_roster_z14',sha,file_name,CASE WHEN pending>0 THEN 'committed_with_pending' ELSE 'committed' END,mapping_result,stats,actor);
  FOR label,m IN SELECT key,value FROM jsonb_each(mapping_result) LOOP
    INSERT INTO public.ty_foundation_import_company(batch_id,source_label,company_id,mapping_kind,internal_code_generated)
    VALUES(bid,label,(m->>'company_id')::bigint,m->>'kind',(m->>'internal_code_generated')::boolean);
  END LOOP;
  FOR r IN SELECT value FROM jsonb_array_elements(source_rows) LOOP
    pid=public.fn_ty_create_person(gid,NULL,r->>'full_name',NULL);eid=NULL;
    SELECT person_number INTO pno FROM public.ty_person WHERE id=pid;
    INSERT INTO public.ty_external_identity(group_id,person_id,source_system,source_namespace,raw_id_text,id_kind,review_status)
    VALUES(gid,pid,'roster','hk_roster_z14:'||sha,r->>'source_id_text','source_person_id','needs_review');
    cid=(mapping_result->(r->>'source_department')->>'company_id')::bigint;row_issues=coalesce(r->'issues','[]');source_state=r->>'employment_state';
    IF cid IS NOT NULL AND source_state IN ('active','ended') AND r->>'hire_date' IS NOT NULL THEN
      INSERT INTO public.ty_employment(group_id,person_id,company_id,employment_type,hire_date,leave_date,status)
      VALUES(gid,pid,cid,r->>'employment_type',(r->>'hire_date')::date,(r->>'leave_date')::date,source_state) RETURNING id INTO eid;
    END IF;
    INSERT INTO public.ty_foundation_import_row(batch_id,source_row,source_id_text,person_id,employment_id,company_id,status,source_data,issues)
    VALUES(bid,(r->>'source_row')::integer,r->>'source_id_text',pid,eid,cid,CASE WHEN eid IS NULL THEN 'identity_only_pending' ELSE 'imported_employment' END,r,row_issues);
    IF jsonb_array_length(row_issues)>0 THEN
      INSERT INTO public.ty_foundation_import_event(batch_id,source_row,event_kind,details) VALUES(bid,(r->>'source_row')::integer,'source_anomaly',row_issues);
    END IF;
  END LOOP;
  INSERT INTO public.ty_foundation_import_event(batch_id,event_kind,details) VALUES(bid,'commit',jsonb_build_object('review_ack',true,'stats',stats));
  INSERT INTO public.ty_audit(actor_id,action,entity_kind,entity_id,after_data) VALUES(actor,'import','foundation_roster',bid,jsonb_build_object('source_sha256',sha,'stats',stats));
  RETURN jsonb_build_object('already_imported',false,'batch_id',bid,'ledger_id',lid,'stats',stats);
END; $$;

DO $$ BEGIN
  IF to_regclass('public.sys_check_registry') IS NOT NULL THEN
    INSERT INTO public.sys_check_registry(check_code,name,domain,kind,guard_object,guard_schema,guard_table,guard_kind,runner,assertion_sql)
    VALUES('SUITE.TY-ROSTER-IMPORT','原生花名册：显式映射、总部待定、原始日期与哈希幂等','ORG','DATA_QUALITY',
      'ty_foundation_import_row_immutable','public','ty_foundation_import_row','TRIGGER','node test/foundation-import.test.mjs','node test/foundation-import.test.mjs')
    ON CONFLICT(check_code) DO NOTHING;
  END IF;
END; $$;
