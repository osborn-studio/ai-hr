CREATE FUNCTION fn_ty_check_company_ledger() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE l public.ty_ledger%ROWTYPE;
BEGIN
  IF TG_OP='UPDATE' AND NEW.group_id<>OLD.group_id THEN
    RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='公司所属集团身份域不可直接变更';
  END IF;
  -- 锁帐套保证两个并发请求不能各建一家公司绕过门店帐套上限。
  SELECT * INTO l FROM public.ty_ledger WHERE id=NEW.ledger_id FOR UPDATE;
  IF l.scope_mode='brand' AND NEW.brand_id IS DISTINCT FROM l.brand_id THEN
    RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='品牌帐套下公司必须属于该品牌';
  END IF;
  IF l.scope_mode='store' AND EXISTS (SELECT 1 FROM public.ty_company c WHERE c.ledger_id=NEW.ledger_id AND c.id<>NEW.id) THEN
    RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='门店帐套只能管理一家经营核算公司';
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_ty_company_ledger BEFORE INSERT OR UPDATE ON ty_company
FOR EACH ROW EXECUTE FUNCTION fn_ty_check_company_ledger();

CREATE FUNCTION fn_ty_check_ledger_update() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
BEGIN
  IF NEW.group_id<>OLD.group_id THEN
    RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='帐套所属集团不可直接变更';
  END IF;
  IF NEW.scope_mode='store' AND (SELECT count(*) FROM public.ty_company WHERE ledger_id=NEW.id)>1 THEN
    RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='已有多家公司的帐套不能直接改为门店帐套';
  END IF;
  IF NEW.scope_mode='brand' AND EXISTS (SELECT 1 FROM public.ty_company c WHERE c.ledger_id=NEW.id AND c.brand_id IS DISTINCT FROM NEW.brand_id) THEN
    RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='现有公司与拟修改的品牌帐套范围不一致';
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_ty_ledger_update BEFORE UPDATE ON ty_ledger
FOR EACH ROW EXECUTE FUNCTION fn_ty_check_ledger_update();

