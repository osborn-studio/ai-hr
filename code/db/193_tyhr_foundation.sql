CREATE FUNCTION fn_ty_create_person(p_group bigint,p_number text,p_name text,p_legacy bigint DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql SET search_path='' AS $$
DECLARE v_no text; v_counter bigint; v_id bigint;
BEGIN
  v_no:=nullif(btrim(p_number),'');
  IF v_no IS NULL THEN
    LOOP
      UPDATE public.ty_group SET person_counter=person_counter+1 WHERE id=p_group RETURNING person_counter INTO v_counter;
      IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='23503',MESSAGE='集团不存在'; END IF;
      v_no:='TY'||lpad(v_counter::text,greatest(6,length(v_counter::text)),'0');
      EXIT WHEN NOT EXISTS(SELECT 1 FROM public.ty_person WHERE group_id=p_group AND person_number=v_no);
    END LOOP;
  END IF;
  INSERT INTO public.ty_person(group_id,person_number,full_name,legacy_person_id)
  VALUES(p_group,v_no,p_name,p_legacy) RETURNING id INTO v_id;
  RETURN v_id;
END; $$;

