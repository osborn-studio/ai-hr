CREATE FUNCTION fn_ty_check_assignment_dates() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE e public.ty_employment%ROWTYPE;
BEGIN
  SELECT * INTO e FROM public.ty_employment WHERE id=NEW.employment_id FOR UPDATE;
  IF FOUND AND NEW.status<>'cancelled' AND (e.status='cancelled' OR NEW.valid_from<e.hire_date
    OR (e.leave_date IS NOT NULL AND (NEW.valid_to IS NULL OR NEW.valid_to>e.leave_date+1 OR NEW.valid_from>e.leave_date))) THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='任职有效期必须在雇佣区间内，离职日含当天';
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_ty_assignment_dates BEFORE INSERT OR UPDATE ON ty_position_assignment
FOR EACH ROW EXECUTE FUNCTION fn_ty_check_assignment_dates();
CREATE FUNCTION fn_ty_check_employment() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE p public.ty_employment%ROWTYPE;
BEGIN
  IF TG_OP='UPDATE' AND (NEW.group_id<>OLD.group_id OR NEW.person_id<>OLD.person_id OR NEW.company_id<>OLD.company_id) THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='雇佣所属集团、人员与公司不可改写，跨公司应建立新的雇佣关系';
  END IF;
  IF NEW.rehire_link IS NOT NULL THEN
    SELECT * INTO p FROM public.ty_employment WHERE id=NEW.rehire_link;
    IF FOUND AND (p.person_id<>NEW.person_id OR p.group_id<>NEW.group_id OR p.leave_date IS NULL OR NEW.hire_date<=p.leave_date) THEN
      RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='复聘须关联同一人员已结束的雇佣段，且新入职日在原离职日之后';
    END IF;
  END IF;
  IF TG_OP='UPDATE' AND EXISTS (SELECT 1 FROM public.ty_position_assignment a WHERE a.employment_id=NEW.id AND a.status<>'cancelled'
    AND (NEW.status='cancelled' OR a.valid_from<NEW.hire_date OR (NEW.leave_date IS NOT NULL AND (a.valid_to IS NULL OR a.valid_to>NEW.leave_date+1)))) THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='先关闭或调整任职区间，再结束雇佣';
  END IF;
  IF TG_OP='UPDATE' AND EXISTS (SELECT 1 FROM public.ty_employment next_e WHERE next_e.rehire_link=NEW.id
    AND (NEW.leave_date IS NULL OR next_e.hire_date<=NEW.leave_date)) THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='修改历史雇佣末日会冲突已存在的复聘经历';
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_ty_employment_guard BEFORE INSERT OR UPDATE ON ty_employment
FOR EACH ROW EXECUTE FUNCTION fn_ty_check_employment();

CREATE FUNCTION fn_ty_end_employment(p_employment bigint,p_leave date)
RETURNS void LANGUAGE plpgsql SET search_path='' AS $$
DECLARE e public.ty_employment%ROWTYPE;
BEGIN
  SELECT * INTO e FROM public.ty_employment WHERE id=p_employment FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='23503',MESSAGE='雇佣记录不存在'; END IF;
  IF p_leave IS NULL OR p_leave<e.hire_date OR e.status='cancelled' THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='离职日期无效';
  END IF;
  -- 未来尚未开始的任职取消，其余在离职日次日右开关闭。
  UPDATE public.ty_position_assignment SET status='cancelled'
    WHERE employment_id=p_employment AND status<>'cancelled' AND valid_from>p_leave;
  UPDATE public.ty_position_assignment
    SET valid_to=CASE WHEN valid_to IS NULL OR valid_to>p_leave+1 THEN p_leave+1 ELSE valid_to END,
        status='ended'
    WHERE employment_id=p_employment AND status<>'cancelled';
  UPDATE public.ty_employment SET leave_date=p_leave,status='ended' WHERE id=p_employment;
END; $$;

