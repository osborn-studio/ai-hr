CREATE FUNCTION fn_ty_person_timeline(p_person bigint) RETURNS jsonb
LANGUAGE sql STABLE SET search_path='' AS $$
  SELECT jsonb_build_object('person',to_jsonb(p),'employments',COALESCE((
    SELECT jsonb_agg(to_jsonb(e)||jsonb_build_object('company_name',c.name,'ledger_id',c.ledger_id,'ledger_name',l.name,
      'assignments',COALESCE((SELECT jsonb_agg(to_jsonb(a)||jsonb_build_object('department_name',d.name,'position_name',cp.name,'work_area_name',wa.name)
        ORDER BY a.valid_from,a.id) FROM public.ty_position_assignment a
        JOIN public.ty_department d ON d.id=a.department_id JOIN public.ty_company_position cp ON cp.id=a.position_id
        LEFT JOIN public.ty_work_area wa ON wa.id=a.work_area_id WHERE a.employment_id=e.id),'[]'::jsonb)) ORDER BY e.hire_date,e.id)
    FROM public.ty_employment e JOIN public.ty_company c ON c.id=e.company_id JOIN public.ty_ledger l ON l.id=c.ledger_id
    WHERE e.person_id=p.id),'[]'::jsonb)) FROM public.ty_person p WHERE p.id=p_person;
$$;
COMMENT ON FUNCTION fn_ty_person_timeline IS '完整集团时间线，仅供已鉴权服务内部调用；服务必须按授权范围过滤雇佣及任职后返回。';

