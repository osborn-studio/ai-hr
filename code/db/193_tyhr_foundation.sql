CREATE FUNCTION fn_ty_check_department_cycle() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
BEGIN
  IF TG_OP='UPDATE' AND NEW.company_id<>OLD.company_id THEN
    RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='部门所属公司不可直接变更，应在新公司建立部门';
  END IF;
  IF NEW.parent_department_id IS NOT NULL AND EXISTS (
    WITH RECURSIVE chain AS (
      SELECT d.id,d.parent_department_id FROM public.ty_department d WHERE d.id=NEW.parent_department_id
      UNION
      SELECT d.id,d.parent_department_id FROM public.ty_department d JOIN chain c ON d.id=c.parent_department_id
    ) SELECT 1 FROM chain WHERE id=NEW.id
  ) THEN RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='部门层级不能形成循环'; END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_ty_department_cycle BEFORE INSERT OR UPDATE ON ty_department
FOR EACH ROW EXECUTE FUNCTION fn_ty_check_department_cycle();

