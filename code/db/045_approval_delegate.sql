-- ===========================================================================
-- 045_approval_delegate.sql · 代理：人不在，责任还在
-- ---------------------------------------------------------------------------
-- 041 做了转签：把**这一步**转给别人。它解决的是"这一单怎么办"。
-- 代理解决的是另一个问题："我下周整周不在"—— 每一单都要转一次是不现实的。
--
-- 三条判断：
--
-- ① **代理不改变责任人。** 待办的 `approver_id` 仍然是原审批人，
--    代理人只是**被授权代他动手**。改了 approver_id 的话，事后查这单是"谁该审的"，
--    会答成代理人 —— 那不是事实。
--
-- ② **代理有期限，且区间不许重叠。** 没有期限的代理就是"永久多一个人有审批权"；
--    区间重叠会让"现在谁在代理"有两个答案。
--
-- ③ **代理人不能是本人**，也不能在未授权的情况下代人批 —— 否则它就是一个
--    "谁都能批别人的单"的后门。
-- ===========================================================================

-- 操作日志的动作取值要扩：'transfer' 是被转签，而"代理人代批"是另一件事 ——
-- 用同一个值会让"这单为什么是他批的"有两种解释。
ALTER TABLE approval_task_log DROP CONSTRAINT ck_atl_action;
ALTER TABLE approval_task_log ADD CONSTRAINT ck_atl_action
  CHECK (action IN ('transfer','addsign','cc','act_by_delegate'));

CREATE TABLE approval_delegate (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_user   bigint      NOT NULL,
  to_user     bigint      NOT NULL,
  from_date   date        NOT NULL,
  to_date     date        NOT NULL,
  reason      varchar(200) NOT NULL,
  created_by  varchar(64) NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT clock_timestamp(),
  revoked_at  timestamptz,
  CONSTRAINT ck_ad_range  CHECK (to_date >= from_date),
  CONSTRAINT ck_ad_self   CHECK (from_user <> to_user),
  CONSTRAINT ck_ad_reason CHECK (length(btrim(reason)) >= 4),
  -- 代理期上限：90 天。与 001 里 HANDOVER_READONLY 的 90 天同一条判断 ——
  -- "先给一年"最后都会变成永久。
  CONSTRAINT ck_ad_span   CHECK (to_date - from_date <= 90)
);

-- 同一个人的代理区间不许重叠（否则"现在谁在代理"有两个答案）
ALTER TABLE approval_delegate ADD CONSTRAINT ex_ad_no_overlap
  EXCLUDE USING gist (from_user WITH =, daterange(from_date, to_date, '[]') WITH &&)
  WHERE (revoked_at IS NULL);

CREATE INDEX ix_ad_lookup ON approval_delegate(from_user, from_date, to_date)
  WHERE revoked_at IS NULL;

CREATE OR REPLACE FUNCTION fn_delegate_add(
  p_from bigint, p_to bigint, p_from_date date, p_to_date date,
  p_reason varchar, p_by varchar
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_id bigint;
BEGIN
  IF p_from = p_to THEN
    RAISE EXCEPTION 'E_DELEGATE_SELF: 不能代理自己（那只是给自己多记一条）';
  END IF;
  IF p_reason IS NULL OR length(btrim(p_reason)) < 4 THEN
    RAISE EXCEPTION 'E_DELEGATE_NO_REASON: 代理必须写原因';
  END IF;
  IF p_to_date - p_from_date > 90 THEN
    RAISE EXCEPTION 'E_DELEGATE_TOO_LONG: 代理期最长 90 天（本次 % 天）', p_to_date - p_from_date;
  END IF;

  INSERT INTO public.approval_delegate(from_user, to_user, from_date, to_date, reason, created_by)
  VALUES (p_from, p_to, p_from_date, p_to_date, btrim(p_reason), p_by)
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

/** 这个人在这天是否被授权代 p_approver 审批 */
CREATE OR REPLACE FUNCTION fn_delegate_covers(
  p_approver bigint, p_actor bigint, p_on date
) RETURNS boolean
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.approval_delegate d
     WHERE d.from_user = p_approver
       AND d.to_user   = p_actor
       AND d.revoked_at IS NULL
       AND daterange(d.from_date, d.to_date, '[]') @> p_on
  );
$$;

COMMENT ON FUNCTION fn_delegate_covers IS
  '代理关系是"人不在、责任还在"：待办仍挂在原审批人名下，'
  '代理人只是被授权代他动手 —— 所以这里只判"能不能代"，不改任务归属。';

-- ---------------------------------------------------------------------------
-- 让 fn_appr_act 接受代理人（其余逻辑不变）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_appr_act(
  p_instance bigint, p_user bigint, p_approve boolean, p_note varchar
) RETURNS varchar
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_st varchar(16); v_seq int; v_tplver bigint; v_owner bigint; v_on date;
  v_def jsonb; v_next jsonb; v_biz_type varchar; v_biz_id bigint;
  v_pending_cs int; v_rejected int; v_org bigint; v_app bigint;
BEGIN
  SELECT status, template_version_id, biz_type, biz_id
    INTO v_st, v_tplver, v_biz_type, v_biz_id
    FROM public.approval_instance WHERE id = p_instance FOR UPDATE;
  IF v_st IS NULL THEN
    RAISE EXCEPTION 'E_APPR_NO_INSTANCE: 审批实例 % 不存在', p_instance;
  END IF;
  IF v_st <> 'running' THEN
    RAISE EXCEPTION 'E_APPR_FINISHED: 实例 % 已 %', p_instance, v_st;
  END IF;

  SELECT min(seq) INTO v_seq FROM public.approval_task
   WHERE instance_id = p_instance AND status = 'pending';
  IF v_seq IS NULL THEN
    RAISE EXCEPTION 'E_APPR_NO_TASK: 实例 % 没有待办任务', p_instance;
  END IF;

  -- 这一步的审批人（可能是多人）
  SELECT approver_id INTO v_owner
    FROM public.approval_task
   WHERE instance_id = p_instance AND seq = v_seq AND status = 'pending'
     AND approver_id = p_user;

  IF v_owner IS NULL THEN
    -- ★ 不是我的待办：只有"我在代理他"才算。判据按**业务日期**，
    --   不按今天：补录旧单要找当时的代理关系。
    v_on := public.fn_appr_biz_date(v_biz_type, v_biz_id);
    SELECT t.approver_id INTO v_owner
      FROM public.approval_task t
     WHERE t.instance_id = p_instance AND t.seq = v_seq AND t.status = 'pending'
       AND public.fn_delegate_covers(t.approver_id, p_user, v_on)
     ORDER BY t.approver_id LIMIT 1;

    IF v_owner IS NULL THEN
      RAISE EXCEPTION 'E_APPR_NOT_YOURS: 第 % 步不是 % 的待办（也不是他代理的人）', v_seq, p_user;
    END IF;

    -- 代批必须留痕：动作落在原审批人的任务上，但谁按的手要记下来
    INSERT INTO public.approval_task_log(task_id, action, from_user, to_user, by_user, reason)
    SELECT t.id, 'act_by_delegate', t.approver_id, t.approver_id, p_user, '代理人代批'
      FROM public.approval_task t
     WHERE t.instance_id = p_instance AND t.seq = v_seq
       AND t.approver_id = v_owner AND t.status = 'pending' LIMIT 1;
  END IF;

  UPDATE public.approval_task
     SET status = CASE WHEN p_approve THEN 'approved' ELSE 'rejected' END,
         acted_at = now()
   WHERE instance_id = p_instance AND seq = v_seq AND approver_id = v_owner;

  SELECT count(*) INTO v_rejected FROM public.approval_task
   WHERE instance_id = p_instance AND seq = v_seq AND status = 'rejected';
  IF v_rejected > 0 THEN
    UPDATE public.approval_instance SET status='rejected', finished_at=now() WHERE id=p_instance;
    PERFORM public.fn_appr_sync_biz(v_biz_type, v_biz_id, false, p_user);
    RETURN 'rejected';
  END IF;

  SELECT count(*) INTO v_pending_cs FROM public.approval_task
   WHERE instance_id = p_instance AND seq = v_seq
     AND status = 'pending' AND act_kind = 'countersign';
  IF v_pending_cs > 0 THEN
    RETURN 'running';
  END IF;

  UPDATE public.approval_task SET status='skipped', acted_at=now()
   WHERE instance_id = p_instance AND seq = v_seq AND status = 'pending';

  SELECT v.definition INTO v_def FROM public.approval_template_version v WHERE v.id = v_tplver;
  SELECT s INTO v_next FROM jsonb_array_elements(v_def -> 'steps') s
   WHERE (s ->> 'seq')::int = v_seq + 1;

  IF v_next IS NULL THEN
    UPDATE public.approval_instance SET status='approved', finished_at=now() WHERE id=p_instance;
    PERFORM public.fn_appr_sync_biz(v_biz_type, v_biz_id, true, p_user);
    RETURN 'approved';
  END IF;

  v_org := public.fn_appr_biz_org(v_biz_type, v_biz_id);
  v_on  := public.fn_appr_biz_date(v_biz_type, v_biz_id);
  v_app := public.fn_appr_biz_applicant(v_biz_type, v_biz_id);

  IF public.fn_appr_spawn(p_instance, v_next, v_org, v_on, v_app) = 0 THEN
    RAISE EXCEPTION 'E_APPROVAL_NO_APPROVER: 第 % 步没有可用审批人'
      '（组织 %；若上一步通过后组织归属变了，请检查归属基线）', v_seq + 1, v_org;
  END IF;

  RETURN 'running';
END;
$$;

