-- ============================================================================
-- 168_att_exception.sql · 考勤异常闭环：补卡单 / 异常识别 / 处理留痕
-- ----------------------------------------------------------------------------
-- 到 165 为止，考勤这条链路上有三个洞，**每一个都不报错**：
--
--   ① **漏打卡只能改打卡记录**。065 的 punch 是只增不改的（对的：它是证据），
--      于是"补一次卡"的唯一办法是绕过触发器直接插一行 —— 插进去之后
--      查不出"谁批的、为什么、补的是哪一端"。而补卡正是考勤造假的高发口：
--      代人打卡的人最需要的就是一个"能改历史"的入口。
--
--   ② **异常没有识别口径**。迟到/早退/漏卡/工时不足/无排班却打卡，
--      现在是算的时候顺手判一下，判完不留痕。员工月底拿着"缺勤 1 天"
--      来问是哪一天，答不出来 —— 因为那个判断只活在那一刻的那条 SQL 里。
--
--   ③ **异常处理没有闭环**。识别 → 通知 → 员工说明 → 主管处理 → 关闭。
--      中间任一步断了，月底就是一笔糊涂账：既不知道是哪一天，
--      也不知道"这 1 天"最后被算成了什么。
--
-- ★ 三条设计取舍（每一条都可以被反驳，所以写在这里）：
--
--   ① **补卡是一条单据，不是一个 UPDATE**（与 163 的异动单同一条理由）。
--      单据存补的是哪一端、什么时刻、为什么、谁批的、什么时候落库。
--
--   ② **异常是"算出来的一行记录"，不是"查询时顺手判一下"**。
--      识别一次、落一次库，于是月底那句"缺勤 1 天"能被指到具体某一天、
--      某一条、某个分钟数。重跑不翻倍（同一人同一天同 kind 唯一）。
--
--   ③ **处理只增不改**。notify / explain / resolve / waive 四步各留一行，
--      谁也不许回去改上一条 —— "他说过什么"和"谁批的"是同一类证据。
--
-- ★ 补卡落库写到**哪张表**（这是本文件最需要说清的一件事）：
--   `attendance_daily` 只是**权限资源码**（063），物理表是 `attendance_daily_store`；
--   而那张表里**没有"实际打卡时刻"这类字段** —— 它的 shift_start_at /
--   shift_end_at 是**班次窗口**（chk_ads_span 用它们锚定 span_hours，115 的报错
--   称它们为"当天班次跨度"）。把补卡时刻写进那两个字段 = 偷偷改掉班次，
--   而班次是排班与算薪的分母。
--
--   所以补卡落库分两步，缺一不可：
--     (a) 事件本体 → `punch`（source='web'、ext_id='PFX:<单号>:<in|out>'，
--         于是这条打卡能顺着 ext_id 追回那张补卡单）；
--     (b) 当天工时 → `attendance_daily_store` 的 work_hours / in_attendance_hours，
--         口径 = 「补后有效上下班时刻 ∩ 当日班次窗口 − 在岗内休息」，
--         写入走 `fn_att_daily_set`（115），所以"补卡改的"和"手工改的"
--         在 att_daily_adjust 里是同一种痕迹。
--   ★ 不做 (b) 的话，补卡只是在证据表里多一行，报表一分钱不变 ——
--     那会让人以为已经处理完了，而月底工资照旧少算。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 补卡单
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.punch_fix (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        varchar(32)  NOT NULL UNIQUE,
  employee_id bigint       NOT NULL REFERENCES public.person(id),
  work_date   date         NOT NULL,

  -- 补的是哪一端：in 上班卡 / out 下班卡 / both 两端都没打
  fix_type    varchar(8)   NOT NULL,
  -- 被补的那个时刻。★ 它同时是 punch.punch_at 的值：
  --   "什么时候按的这一下"是证据，不能因为"今天才补"就记成今天。
  fix_time    timestamptz  NOT NULL,

  reason      varchar(200) NOT NULL,

  status      varchar(16)  NOT NULL DEFAULT 'draft',
  -- 决定人 / 决定时刻。★ 名字叫 approved_*，但**拒绝也填**：
  --   否则"谁否的"查不到，而"被否了一次"与"从没提过"在报告上同形。
  approved_by varchar(64),
  approved_at timestamptz,

  -- 落库（写进 punch + 重算当日人日）的时刻与人。
  -- ★ 这也正是"未拒绝的同一人同一天同类型只能有一张"之外的第二道闸：
  --   applied_at 非空 = 这张单已经改过账，重复 apply 必须拒。
  applied_at  timestamptz,
  applied_by  varchar(64),

  created_by  varchar(64)  NOT NULL DEFAULT 'system',
  created_at  timestamptz  NOT NULL DEFAULT now(),

  CONSTRAINT ck_pfx_type   CHECK (fix_type IN ('in','out','both')),
  CONSTRAINT ck_pfx_status CHECK (status IN ('draft','approved','rejected')),
  -- 空白理由不行：NOT NULL 能通过一个空格，而"补了但没理由"等于没留痕
  CONSTRAINT ck_pfx_reason CHECK (length(btrim(reason)) >= 4),
  -- 草稿之外必须有决定人与决定时刻（通过/拒绝都是）
  CONSTRAINT ck_pfx_decided CHECK (
    (status = 'draft') = (approved_by IS NULL AND approved_at IS NULL)
  ),
  -- 落库人与落库时刻同生同灭
  CONSTRAINT ck_pfx_applied_pair CHECK ((applied_at IS NULL) = (applied_by IS NULL)),
  -- 只有通过的单子落过库；草稿与被拒的单子不可能有 applied_at
  CONSTRAINT ck_pfx_applied_state CHECK (applied_at IS NULL OR status = 'approved')
);

-- ★ 同一人 / 同一天 / 同一端，只能有一张**未拒绝**的单。
--   用部分索引而不是 UNIQUE 约束：被拒的单子必须允许再提一张，
--   否则"否一次"就等于"这一天这条记录永远不许补"。
CREATE UNIQUE INDEX IF NOT EXISTS uk_pfx_live
  ON public.punch_fix (employee_id, work_date, fix_type)
  WHERE status <> 'rejected';

CREATE INDEX IF NOT EXISTS ix_pfx_emp_day
  ON public.punch_fix (employee_id, work_date DESC);
CREATE INDEX IF NOT EXISTS ix_pfx_pending
  ON public.punch_fix (work_date) WHERE status = 'draft';

COMMENT ON TABLE public.punch_fix IS
  '补卡单（168）：漏打卡**只能**走这里，不再直接插 punch。'
  '存补哪一端、哪个时刻、为什么、谁批的、什么时候落库 —— 这五样缺一样，'
  '"这条打卡是谁补的"就答不出来。';
COMMENT ON COLUMN public.punch_fix.fix_time IS
  '被补的那个时刻，同时作为 punch.punch_at 写入。★ 补卡不是"今天按了一下"，'
  '是"那天他几点按的" —— 记成今天会让当天的工时凭空多出来几个小时。';
COMMENT ON COLUMN public.punch_fix.approved_by IS
  '决定人（通过 = 批的人，拒绝 = 否的人）。列名比语义窄：拒绝也填这一列，'
  '因为"谁否的"与"谁批的"是同一类证据。';

-- ---------------------------------------------------------------------------
-- 2. 异常
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.att_exception (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id bigint      NOT NULL REFERENCES public.person(id),
  work_date   date        NOT NULL,
  kind        varchar(12) NOT NULL,
  -- 偏差分钟数（迟到多少分钟 / 缺多少分钟 / 缺勤班次多长）。
  -- no_roster 记 0：它问的是"这天为什么有打卡"，不是一个时长。
  minutes     int         NOT NULL DEFAULT 0,

  source      varchar(8)  NOT NULL DEFAULT 'auto',   -- auto 扫出来 / manual 人记的
  status      varchar(12) NOT NULL DEFAULT 'open',
  note        varchar(300),

  -- 关闭时的处理人与时刻。只对 resolved / waived 有值：
  -- "已处理"必须有主语，否则它只是一句没人负责的断言。
  resolved_by varchar(64),
  resolved_at timestamptz,

  created_at  timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT ck_atx_kind CHECK (kind IN
    ('late','early','absent','miss_punch','no_roster','under_hours')),
  CONSTRAINT ck_atx_source CHECK (source IN ('auto','manual')),
  CONSTRAINT ck_atx_status CHECK (status IN ('open','explained','resolved','waived')),
  CONSTRAINT ck_atx_minutes CHECK (minutes >= 0),
  -- 状态与处理人同生同灭：只加列不写这条，会留下"已解决但没人解决"的一行
  CONSTRAINT ck_atx_closed CHECK (
    (status IN ('resolved','waived')) = (resolved_by IS NOT NULL AND resolved_at IS NOT NULL)
  )
);

-- ★ 同一人 / 同一天 / 同一种异常只有一条。它同时是 fn_att_scan 的幂等键：
--   重跑靠 ON CONFLICT DO NOTHING，而不是"先删再插" ——
--   先删会把已经 explain 过的说明一起删掉，那是销毁证据。
CREATE UNIQUE INDEX IF NOT EXISTS uk_atx_day_kind
  ON public.att_exception (employee_id, work_date, kind);
CREATE INDEX IF NOT EXISTS ix_atx_open
  ON public.att_exception (work_date, kind) WHERE status IN ('open','explained');

COMMENT ON TABLE public.att_exception IS
  '考勤异常（168）：识别一次、落一行。★ 它不是视图 —— 视图查不出"上周判过什么"，'
  '而员工月底问的恰恰是"哪一天、哪一条"。';
COMMENT ON COLUMN public.att_exception.minutes IS
  '偏差分钟数。late/early 是差了多少分钟，absent/miss_punch 是当天班次多长，'
  'under_hours 是少了多少分钟，no_roster 恒为 0（它问的是"为什么有打卡"）。';

-- ---------------------------------------------------------------------------
-- 3. 处理留痕（只增不改）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.att_exception_action (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exception_id bigint      NOT NULL REFERENCES public.att_exception(id),
  action       varchar(8)  NOT NULL,
  by_user      varchar(64) NOT NULL,
  note         varchar(300),
  at           timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT ck_atxa_action CHECK (action IN ('notify','explain','resolve','waive'))
);

CREATE INDEX IF NOT EXISTS ix_atxa_exc
  ON public.att_exception_action (exception_id, at);

COMMENT ON TABLE public.att_exception_action IS
  '异常处理的每一步：通知 / 员工说明 / 处理 / 豁免。只增不改 ——'
  '"他说过什么"和"谁批的"是同一类证据，改一条等于把事故现场重刷一遍。';

CREATE OR REPLACE FUNCTION public.fn_atxa_append_only() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  RAISE EXCEPTION 'E_ATX_APPEND_ONLY: 异常处理留痕只增不改（它是证据）';
END;
$$;

DROP TRIGGER IF EXISTS trg_atxa_append_only ON public.att_exception_action;
CREATE TRIGGER trg_atxa_append_only
  BEFORE UPDATE OR DELETE ON public.att_exception_action
  FOR EACH ROW EXECUTE FUNCTION public.fn_atxa_append_only();

-- ---------------------------------------------------------------------------
-- 4. 开单 / 决定
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_punch_fix_open(
  p_employee  bigint,
  p_work_date date,
  p_fix_type  varchar,
  p_fix_time  timestamptz,
  p_reason    varchar,
  p_by        varchar DEFAULT 'system'
) RETURNS TABLE (fix_id bigint, fix_code varchar)
-- ★ 输出列不叫 code / id：它们与 punch_fix 的列同名，而 plpgsql 的默认
--   variable_conflict=error 会让函数体里的裸列引用直接报 "column reference is ambiguous"。
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_code varchar(32);
  v_id   bigint;
  v_kind varchar(8);
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.person p WHERE p.id = p_employee) THEN
    RAISE EXCEPTION 'E_PFX_NO_EMPLOYEE: 员工 % 不存在', p_employee;
  END IF;
  IF p_fix_type IS NULL OR p_fix_type NOT IN ('in','out','both') THEN
    RAISE EXCEPTION 'E_PFX_TYPE: 补卡类型只能是 in / out / both（收到 %）', p_fix_type;
  END IF;
  IF p_work_date IS NULL THEN
    RAISE EXCEPTION 'E_PFX_NO_DATE: 补哪一天必填（不填就只能"补今天"，而今天还没过完）';
  END IF;
  IF p_reason IS NULL OR length(btrim(p_reason)) < 4 THEN
    RAISE EXCEPTION 'E_PFX_REASON: 补卡必须写原因（至少 4 个字）—— 补了没理由等于没留痕';
  END IF;
  IF p_fix_time IS NULL THEN
    RAISE EXCEPTION 'E_PFX_NO_TIME: 补卡必须给被补的那个时刻（不是提交时刻）';
  END IF;
  -- 补的时刻必须落在补的那一天（业务时区）。落不到一天的补卡会让"哪一天的工时变了"说不清
  IF (p_fix_time AT TIME ZONE public.app_tz())::date <> p_work_date THEN
    RAISE EXCEPTION 'E_PFX_TIME_DAY: 补卡时刻 %（% 日）不在工作日 % 当天',
      p_fix_time, (p_fix_time AT TIME ZONE public.app_tz())::date, p_work_date;
  END IF;

  -- ★ 部分唯一索引只管"同类型一张"，管不住 in 与 both 并存 ——
  --   那是同一次漏卡的两张单，落库时会互相覆盖（后 apply 的把前一张的结果改掉）。
  SELECT f.fix_type INTO v_kind
    FROM public.punch_fix f
   WHERE f.employee_id = p_employee AND f.work_date = p_work_date
     AND f.status <> 'rejected'
     AND (f.fix_type = p_fix_type
          OR f.fix_type = 'both' OR p_fix_type = 'both')
   LIMIT 1;
  IF v_kind IS NOT NULL THEN
    RAISE EXCEPTION 'E_PFX_DUP: % 在 % 已经有一张未拒绝的 % 补卡单'
      '（同一次漏卡开两张，落库时后一张会把前一张的结果改掉）',
      p_employee, p_work_date, v_kind;
  END IF;

  v_code := 'BK' || to_char(p_work_date, 'YYYYMM') || '-'
    || lpad(((SELECT count(*) FROM public.punch_fix f
               WHERE f.work_date >= date_trunc('month', p_work_date)) + 1)::text, 4, '0');

  INSERT INTO public.punch_fix
    (code, employee_id, work_date, fix_type, fix_time, reason, status, created_by)
  VALUES (v_code, p_employee, p_work_date, p_fix_type, p_fix_time, btrim(p_reason),
          'draft', p_by)
  RETURNING id INTO v_id;

  RETURN QUERY SELECT v_id, v_code::varchar;
END;
$$;

COMMENT ON FUNCTION public.fn_punch_fix_open IS
  '开一张补卡单（草稿）：补的时刻必须落在补的那一天，理由至少 4 个字，'
  '同一人同一天不许有第二张未拒绝的补卡单（含 in/both 这种重叠组合）。';

CREATE OR REPLACE FUNCTION public.fn_punch_fix_decide(
  p_fix      bigint,
  p_decision varchar,
  p_by       varchar,
  p_note     varchar DEFAULT NULL
) RETURNS TABLE (fix_id bigint, new_status varchar, fix_code varchar)
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_f public.punch_fix%ROWTYPE;
BEGIN
  IF p_decision IS NULL OR p_decision NOT IN ('approve','reject') THEN
    RAISE EXCEPTION 'E_PFX_DECISION: 决定只能是 approve / reject（收到 %）', p_decision;
  END IF;

  SELECT * INTO v_f FROM public.punch_fix f WHERE f.id = p_fix FOR UPDATE;
  IF v_f.id IS NULL THEN
    RAISE EXCEPTION 'E_PFX_NOT_FOUND: 补卡单 % 不存在', p_fix;
  END IF;
  IF v_f.status <> 'draft' THEN
    RAISE EXCEPTION 'E_PFX_DECIDED: 补卡单 % 已经决定过（%），不能再决定一次', v_f.code, v_f.status;
  END IF;

  UPDATE public.punch_fix f
     SET status = CASE WHEN p_decision = 'approve' THEN 'approved' ELSE 'rejected' END,
         approved_by = p_by,
         approved_at = clock_timestamp()
   WHERE f.id = p_fix;

  RETURN QUERY SELECT p_fix, (CASE WHEN p_decision = 'approve' THEN 'approved'
                                   ELSE 'rejected' END)::varchar, v_f.code::varchar;
END;
$$;

COMMENT ON FUNCTION public.fn_punch_fix_decide IS
  '审批补卡单：draft → approved / rejected，记决定人与时刻。'
  '★ 拒绝也记人：只把 status 改成 rejected 而不记"谁否的"，等于把一次驳回变成一次匿名事件。';

-- ---------------------------------------------------------------------------
-- 5. 补卡落库：写 punch + 重算当天人日（一个事务，重复 apply 拒）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_punch_fix_apply(
  p_fix bigint,
  p_by  varchar DEFAULT 'system'
) RETURNS TABLE (fix_id bigint, punch_n int, work_hours numeric, hours_before numeric,
                 at_store bigint)
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  f        public.punch_fix%ROWTYPE;
  a        public.attendance_daily_store%ROWTYPE;
  v_at     timestamptz;
  v_in     timestamptz;
  v_out    timestamptz;
  v_min    numeric;
  v_hours  numeric(6,2);
  v_n      int := 0;
BEGIN
  SELECT * INTO f FROM public.punch_fix x WHERE x.id = p_fix FOR UPDATE;
  IF f.id IS NULL THEN
    RAISE EXCEPTION 'E_PFX_NOT_FOUND: 补卡单 % 不存在', p_fix;
  END IF;
  IF f.status <> 'approved' THEN
    RAISE EXCEPTION 'E_PFX_NOT_APPROVED: 补卡单 % 状态是 %，只有已通过的单子能落库',
      f.code, f.status;
  END IF;
  IF f.applied_at IS NOT NULL THEN
    RAISE EXCEPTION 'E_PFX_ALREADY_APPLIED: 补卡单 % 已于 % 落库，不能重复落库'
      '（重复落库会把当时算出的工时再算一遍，而中间可能有人手动调过）', f.code, f.applied_at;
  END IF;

  -- 当天的人日：补卡改的是这一天的工时，没有这一行就没有可改的东西。
  -- ★ 不"顺手建一条"（与 115 同一条规矩）：新建人日等于替门店决定"这天他来了"，
  --   而补卡单只决定"他几点打的卡"。人日缺失请先补勤/导入。
  SELECT * INTO a FROM public.attendance_daily_store y
   WHERE y.employee_id = f.employee_id AND y.work_date = f.work_date;
  IF a.id IS NULL THEN
    RAISE EXCEPTION 'E_PFX_NO_DAILY: % 在 % 没有考勤人日记录，补卡无从落起'
      '（先补勤或导入当天人日；封账后的修正走补账）', f.employee_id, f.work_date;
  END IF;

  -- 封账期间不许动：这是 016 的规矩，补卡不能成为第四种绕过路径
  IF EXISTS (SELECT 1 FROM public.attendance_close c
              WHERE c.store_id = a.store_id
                AND c.period = to_char(f.work_date, 'YYYY-MM')
                AND c.status = 'closed') THEN
    RAISE EXCEPTION 'E_PFX_CLOSED: % 店 % 已封账，补卡不能改已封账的考勤'
      '（封账后的修正请走补账 fn_att_adjust）', a.store_id, to_char(f.work_date, 'YYYY-MM');
  END IF;

  -- ---- (a) 事件本体写进 punch ----
  -- ext_id 把这一行钉回单据：'PFX:<单号>:<in|out>'，(source, ext_id) 上有唯一索引，
  -- 所以"同一张单落两次"在结构上不可能。
  IF f.fix_type IN ('in','both') THEN
    -- in：补的就是那个时刻。both：上班卡取**当日班次开始**，不是"比下班早多久" ——
    -- 两端都没有原始卡时，班次开始是唯一有据可依的上班时刻；
    -- 替员工编一个更早的时间，就是替他多要工时。
    v_at := CASE WHEN f.fix_type = 'in' THEN f.fix_time ELSE a.shift_start_at END;
    INSERT INTO public.punch(employee_id, punch_at, kind, source, store_id, ext_id)
    VALUES (f.employee_id, v_at, 'in', 'web', a.store_id, 'PFX:' || f.code || ':in')
    ON CONFLICT (source, ext_id) WHERE ext_id IS NOT NULL DO NOTHING;
    v_n := v_n + 1;
  END IF;
  IF f.fix_type IN ('out','both') THEN
    INSERT INTO public.punch(employee_id, punch_at, kind, source, store_id, ext_id)
    VALUES (f.employee_id, f.fix_time, 'out', 'web', a.store_id, 'PFX:' || f.code || ':out')
    ON CONFLICT (source, ext_id) WHERE ext_id IS NOT NULL DO NOTHING;
    v_n := v_n + 1;
  END IF;

  -- ---- (b) 用补后的卡重算当天工时，写进人日 ----
  -- 口径（与 065 的"工时只有一条链路"同源，这里只是把补后的卡喂进那条链路）：
  --   有效上班 = 当天最早 in，有效下班 = 当天最晚 out
  --   计入工时 = (有效上下班 ∩ 当日班次窗口) − 在岗内休息
  --   窗口外的那部分不作为工时（加班有 120 的单独通道，不从补卡里冒出来）
  -- ★ 取卡按"日历日"（业务时区），与 065 的 v_punch_today 同口径。
  --   代价：跨零点班次（CLOSE 17:00–01:00）的下班卡落在次日，这张单会命中
  --   E_PFX_INCOMPLETE 并提示"还差一端" —— 那是显式拒绝，不是静默算错。
  SELECT min(p.punch_at) FILTER (WHERE p.kind = 'in'),
         max(p.punch_at) FILTER (WHERE p.kind = 'out')
    INTO v_in, v_out
    FROM public.punch p
   WHERE p.employee_id = f.employee_id
     AND (p.punch_at AT TIME ZONE public.app_tz())::date = f.work_date;

  IF v_in IS NULL OR v_out IS NULL THEN
    RAISE EXCEPTION 'E_PFX_INCOMPLETE: 补卡单 % 落库后当天仍然只有一端打卡（in=%，out=%），'
      '工时算不出来 —— 请补另一端的卡', f.code, v_in, v_out;
  END IF;

  v_min := GREATEST(
    EXTRACT(EPOCH FROM (least(v_out, a.shift_end_at) - greatest(v_in, a.shift_start_at))) / 60,
    0);

  IF a.snap_on_duty_break_basis = 'hourly' THEN
    v_hours := round(v_min / 60, 2);
  ELSE
    v_hours := GREATEST(round(v_min / 60 - a.break_on_duty_hours, 2), 0);
  END IF;

  -- 走 115 的写入口径：它负责 work_hours / in_attendance_hours 的联动、
  -- 封账保护、以及 att_daily_adjust 的留痕（"补卡改的"与"手工改的"同一种痕迹）
  PERFORM public.fn_att_daily_set(
    f.employee_id, f.work_date, v_hours,
    '补卡单 ' || f.code || ' 落库：' || left(f.reason, 150), p_by);

  UPDATE public.punch_fix x
     SET applied_at = clock_timestamp(), applied_by = p_by
   WHERE x.id = p_fix;

  RETURN QUERY SELECT p_fix, v_n, v_hours, a.work_hours, a.store_id;
END;
$$;

COMMENT ON FUNCTION public.fn_punch_fix_apply IS
  '补卡落库（一个函数 = 一个事务）：把被补的时刻写进 punch（ext_id 钉回单号），'
  '再用补后的卡按"当日班次窗口 ∩ 有效上下班 − 在岗休息"重算当天工时，'
  '经 fn_att_daily_set 写进 attendance_daily_store 并留痕。'
  '★ 不写 attendance_daily_store 的 shift_start_at / shift_end_at：那是班次窗口，'
  '不是实际打卡时刻（chk_ads_span 用它们锚定 span_hours）。';

-- ---------------------------------------------------------------------------
-- 6. 扫一个月：按排班与打卡生成异常（幂等）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_att_scan(
  p_period    varchar,
  p_grace_min int DEFAULT 5
) RETURNS TABLE (exc_kind varchar, inserted int)
-- ★ 输出列不叫 kind：att_exception 有同名列，而 RETURNING kind 会被 plpgsql
--   当成 OUT 参数（065 踩过同一个坑，报的是 "column reference is ambiguous"）。
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_from  date;
  v_to    date;
  v_grace int := COALESCE(p_grace_min, 5);
BEGIN
  IF p_period IS NULL OR p_period !~ '^\d{4}-(0[1-9]|1[0-2])$' THEN
    RAISE EXCEPTION 'E_ATX_PERIOD: 期间必须是 YYYY-MM（收到 %）', p_period;
  END IF;
  IF v_grace < 0 OR v_grace > 120 THEN
    RAISE EXCEPTION 'E_ATX_GRACE: 迟到宽限必须在 0–120 分钟之间（收到 %）', p_grace_min;
  END IF;

  v_from := to_date(p_period || '-01', 'YYYY-MM-DD');
  v_to   := (v_from + interval '1 month - 1 day')::date;

  RETURN QUERY
  WITH sh AS (
    -- 排班：人 × 日 × 班次 → 这一天的"应该在"窗口（业务时区）
    -- ★ 跨零点的班（17:00–01:00）下班落在次日，否则"早退"会把整晚都算成早退
    SELECT rs.employee_id, rs.work_date, rs.store_id,
           (rs.work_date + sd.start_time) AT TIME ZONE public.app_tz() AS s_at,
           ((CASE WHEN sd.end_time > sd.start_time THEN rs.work_date
                  ELSE rs.work_date + 1 END) + sd.end_time)
             AT TIME ZONE public.app_tz() AS e_at,
           COALESCE(sd.work_minutes,
                    round(EXTRACT(EPOCH FROM
                      ((CASE WHEN sd.end_time > sd.start_time
                             THEN sd.end_time - sd.start_time
                             ELSE sd.end_time - sd.start_time + interval '24 hours' END))
                      / 60)))::int AS plan_min
      FROM public.roster_slot rs
      JOIN public.shift_def sd ON sd.code = rs.shift_code
     WHERE rs.work_date BETWEEN v_from AND v_to
       AND rs.work_date <= public.app_today()      -- 还没到的日子不判"缺勤"
       AND sd.is_rest = false
       AND sd.start_time <> sd.end_time
  ),
  pu AS (
    -- 打卡：同一天的原始事件压成一对（取最早 in / 最晚 out，与 065 同口径）
    SELECT p.employee_id,
           (p.punch_at AT TIME ZONE public.app_tz())::date AS d,
           min(p.punch_at) FILTER (WHERE p.kind = 'in')   AS first_in,
           max(p.punch_at) FILTER (WHERE p.kind = 'out')  AS last_out,
           count(*)::int AS n
      FROM public.punch p
     WHERE (p.punch_at AT TIME ZONE public.app_tz())::date BETWEEN v_from AND v_to
     GROUP BY 1, 2
  ),
  lv AS (
    -- 已批准的请假：有假就不算旷工（不算的话，休年假的人月底会被记成缺勤）
    SELECT l.employee_id, g.d::date AS d
      FROM public.leave_request l
      CROSS JOIN LATERAL generate_series(l.date_from, l.date_to, interval '1 day') g(d)
     WHERE l.status = 'approved'
       AND l.date_to >= v_from AND l.date_from <= v_to
  ),
  day AS (
    SELECT sh.*, pu.first_in, pu.last_out, COALESCE(pu.n, 0) AS n,
           -- "工时不足"要看**人日算出来的工时**，不能看两个卡之间的跨度：
           -- 断班（10–12 / 13–19）的跨度是 9 小时，而那 1 小时午休不算工时；
           -- 拿跨度去比，永远"超了"，这一条就再也不会亮。
           COALESCE(dd.work_hours, 0) AS day_hours,
           EXISTS (SELECT 1 FROM lv
                    WHERE lv.employee_id = sh.employee_id AND lv.d = sh.work_date) AS on_leave
      FROM sh
      LEFT JOIN pu ON pu.employee_id = sh.employee_id AND pu.d = sh.work_date
      LEFT JOIN public.attendance_daily_store dd
             ON dd.employee_id = sh.employee_id AND dd.work_date = sh.work_date
  ),
  gen AS (
    SELECT 'late'::varchar AS kind, d.employee_id, d.work_date,
           (EXTRACT(EPOCH FROM (d.first_in - d.s_at)) / 60)::int AS minutes,
           format('排班 %s–%s，实际到岗 %s（迟 %s 分钟）',
                  to_char(d.s_at AT TIME ZONE public.app_tz(), 'HH24:MI'),
                  to_char(d.e_at AT TIME ZONE public.app_tz(), 'HH24:MI'),
                  to_char(d.first_in AT TIME ZONE public.app_tz(), 'HH24:MI'),
                  (EXTRACT(EPOCH FROM (d.first_in - d.s_at)) / 60)::int) AS note
      FROM day d
     WHERE d.first_in IS NOT NULL
       AND d.first_in > d.s_at + make_interval(mins => v_grace)

    UNION ALL
    SELECT 'early', d.employee_id, d.work_date,
           (EXTRACT(EPOCH FROM (d.e_at - d.last_out)) / 60)::int,
           format('排班 %s–%s，实际离岗 %s（早退 %s 分钟）',
                  to_char(d.s_at AT TIME ZONE public.app_tz(), 'HH24:MI'),
                  to_char(d.e_at AT TIME ZONE public.app_tz(), 'HH24:MI'),
                  to_char(d.last_out AT TIME ZONE public.app_tz(), 'HH24:MI'),
                  (EXTRACT(EPOCH FROM (d.e_at - d.last_out)) / 60)::int)
      FROM day d
     WHERE d.last_out IS NOT NULL AND d.last_out < d.e_at

    UNION ALL
    SELECT 'miss_punch', d.employee_id, d.work_date, d.plan_min,
           format('排班 %s–%s，缺%s卡（当天只有 %s 条打卡）',
                  to_char(d.s_at AT TIME ZONE public.app_tz(), 'HH24:MI'),
                  to_char(d.e_at AT TIME ZONE public.app_tz(), 'HH24:MI'),
                  CASE WHEN d.first_in IS NULL THEN '上班' ELSE '下班' END, d.n)
      FROM day d
     WHERE d.n > 0 AND (d.first_in IS NULL OR d.last_out IS NULL)

    UNION ALL
    SELECT 'absent', d.employee_id, d.work_date, d.plan_min,
           format('排班 %s–%s（%s 分钟），当天没有任何打卡，也没有已批准的请假',
                  to_char(d.s_at AT TIME ZONE public.app_tz(), 'HH24:MI'),
                  to_char(d.e_at AT TIME ZONE public.app_tz(), 'HH24:MI'), d.plan_min)
      FROM day d
     WHERE d.n = 0 AND NOT d.on_leave

    UNION ALL
    SELECT 'under_hours', d.employee_id, d.work_date,
           d.plan_min - round(d.day_hours * 60)::int,
           format('排班 %s 分钟，人日只算出 %s 小时（少 %s 分钟，且不迟到不早退）',
                  d.plan_min, d.day_hours, d.plan_min - round(d.day_hours * 60)::int)
      FROM day d
     WHERE d.first_in IS NOT NULL AND d.last_out IS NOT NULL
       AND d.first_in <= d.s_at + make_interval(mins => v_grace)
       AND d.last_out >= d.e_at
       AND round(d.day_hours * 60)::int < d.plan_min - 30

    UNION ALL
    SELECT 'no_roster', pu.employee_id, pu.d, 0,
           format('当天有 %s 条打卡，但没有排班（打卡的工时无从归属）', pu.n)
      FROM pu
     WHERE NOT EXISTS (SELECT 1 FROM public.roster_slot rs
                        WHERE rs.employee_id = pu.employee_id AND rs.work_date = pu.d)
  ),
  ins AS (
    INSERT INTO public.att_exception(employee_id, work_date, kind, minutes, source, status, note)
    SELECT g.employee_id, g.work_date, g.kind, GREATEST(g.minutes, 0), 'auto', 'open',
           left(g.note, 300)
      FROM gen g
    ON CONFLICT DO NOTHING
    RETURNING kind
  )
  SELECT ins.kind::varchar, count(*)::int
    FROM ins GROUP BY ins.kind;
END;
$$;

COMMENT ON FUNCTION public.fn_att_scan IS
  '扫一个月的排班与打卡，生成考勤异常（late / early / absent / miss_punch / under_hours / '
  'no_roster）。幂等：同一人同一天同 kind 已存在就跳过（ON CONFLICT DO NOTHING），'
  '所以重跑不翻倍，也不会把已经 explain 过的说明一起删掉。'
  '★ 迟到宽限默认 5 分钟：1 分钟的"迟到"是噪声，而噪声多了就没人看这张表了。';

-- ---------------------------------------------------------------------------
-- 7. 状态机：open → explained → resolved / waived
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_att_exception_close(
  p_exception bigint,
  p_action    varchar,
  p_by        varchar,
  p_note      varchar DEFAULT NULL
) RETURNS TABLE (exception_id bigint, new_status varchar, exc_kind varchar)
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  e        public.att_exception%ROWTYPE;
  v_status varchar(12);
  v_note   varchar(300) := btrim(COALESCE(p_note, ''));
BEGIN
  IF p_action IS NULL OR p_action NOT IN ('notify','explain','resolve','waive') THEN
    RAISE EXCEPTION 'E_ATX_ACTION: 处理动作只能是 notify / explain / resolve / waive（收到 %）',
      p_action;
  END IF;

  SELECT * INTO e FROM public.att_exception x WHERE x.id = p_exception FOR UPDATE;
  IF e.id IS NULL THEN
    RAISE EXCEPTION 'E_ATX_NOT_FOUND: 异常 % 不存在', p_exception;
  END IF;
  IF e.status IN ('resolved','waived') THEN
    RAISE EXCEPTION 'E_ATX_CLOSED: 异常 %（% %）已经是 %，不能再处理',
      e.id, e.work_date, e.kind, e.status;
  END IF;

  -- 除"通知"之外的动作都要写一句话：不写就不知道员工怎么解释的、主管凭什么关的
  IF p_action <> 'notify' AND length(v_note) < 2 THEN
    RAISE EXCEPTION 'E_ATX_NO_NOTE: % 必须写说明（至少 2 个字）—— 处理不留话等于没处理',
      p_action;
  END IF;

  v_status := e.status;

  IF p_action = 'explain' THEN
    IF e.status <> 'open' THEN
      RAISE EXCEPTION 'E_ATX_SKIP_STEP: 异常 % 已经是 %，不能再说一次说明', e.id, e.status;
    END IF;
    v_status := 'explained';

  ELSIF p_action IN ('resolve','waive') THEN
    -- ★ 跳步要拒：open 直接 resolve，等于"没人问过员工，主管自己把事结了"，
    --   而这类记录事后无法与"员工认可了这个结论"区分。
    IF e.status <> 'explained' THEN
      RAISE EXCEPTION 'E_ATX_SKIP_STEP: 异常 % 现在是 %，必须先有员工说明（explain）才能 %',
        e.id, e.status, p_action;
    END IF;
    v_status := CASE WHEN p_action = 'resolve' THEN 'resolved' ELSE 'waived' END;
  END IF;

  UPDATE public.att_exception x
     SET status = v_status,
         resolved_by = CASE WHEN v_status IN ('resolved','waived') THEN p_by
                            ELSE x.resolved_by END,
         resolved_at = CASE WHEN v_status IN ('resolved','waived') THEN clock_timestamp()
                            ELSE x.resolved_at END
   WHERE x.id = p_exception;

  INSERT INTO public.att_exception_action(exception_id, action, by_user, note)
  VALUES (p_exception, p_action, p_by, NULLIF(left(v_note, 300), ''));

  RETURN QUERY SELECT p_exception, v_status::varchar, e.kind::varchar;
END;
$$;

COMMENT ON FUNCTION public.fn_att_exception_close IS
  '异常的处置（状态机）：notify 只留痕不改状态；explain 把 open 推到 explained；'
  'resolve / waive 只能从 explained 出发。跳步被拒 —— open 直接 resolve，'
  '事后无法与"员工认可了这个结论"区分。';

-- ---------------------------------------------------------------------------
-- 8. 疑似代人打卡：只报不拦
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_att_dup_punch(p_period varchar)
RETURNS TABLE (reason varchar, employee_id bigint, peer_id bigint, punched_at timestamptz,
               device_id varchar, gap_sec int, work_date date)
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE
  v_from date;
  v_to   date;
BEGIN
  IF p_period IS NULL OR p_period !~ '^\d{4}-(0[1-9]|1[0-2])$' THEN
    RAISE EXCEPTION 'E_ATX_PERIOD: 期间必须是 YYYY-MM（收到 %）', p_period;
  END IF;
  v_from := to_date(p_period || '-01', 'YYYY-MM-DD');
  v_to   := (v_from + interval '1 month - 1 day')::date;

  RETURN QUERY
  WITH w AS (
    SELECT p.id, p.employee_id, p.punch_at, p.device_id,
           lag(p.punch_at) OVER (PARTITION BY p.employee_id ORDER BY p.punch_at) AS prev_at
      FROM public.punch p
     WHERE (p.punch_at AT TIME ZONE public.app_tz())::date BETWEEN v_from AND v_to
  )
  -- ① 同一个人 60 秒内连打两次：要么手抖，要么一台手机替两个人按
  SELECT 'same_person_60s'::varchar, w.employee_id, w.employee_id, w.punch_at, w.device_id,
         (EXTRACT(EPOCH FROM (w.punch_at - w.prev_at)))::int,
         (w.punch_at AT TIME ZONE public.app_tz())::date
    FROM w
   WHERE w.prev_at IS NOT NULL
     AND w.punch_at - w.prev_at <= interval '60 seconds'

  UNION ALL

  -- ② 不同的人、同一台设备、同一分钟：这是"代人打卡"最直接的形态
  --   ★ 只报不拦：门店共用一台考勤机时同样会命中，硬拦会把正常打卡挡在外面，
  --     然后大家改用口头报备 —— 那比"标出来给人看"糟得多。
  SELECT 'same_device_minute'::varchar, a.employee_id, b.employee_id, a.punch_at, a.device_id,
         abs(EXTRACT(EPOCH FROM (a.punch_at - b.punch_at)))::int,
         (a.punch_at AT TIME ZONE public.app_tz())::date
    FROM public.punch a
    JOIN public.punch b
      ON b.device_id = a.device_id
     AND b.employee_id <> a.employee_id
     AND b.id > a.id
     AND date_trunc('minute', b.punch_at) = date_trunc('minute', a.punch_at)
   WHERE a.device_id IS NOT NULL
     AND (a.punch_at AT TIME ZONE public.app_tz())::date BETWEEN v_from AND v_to

  ORDER BY 4;
END;
$$;

COMMENT ON FUNCTION public.fn_att_dup_punch IS
  '疑似代人打卡：同一人 60 秒内两次打卡、或不同人同一设备同一分钟。'
  '★ 只报不拦 —— 门店共用一台考勤机也会命中，硬拦会把人逼回口头报备，'
  '那比"标出来给人看"坏得多。';

