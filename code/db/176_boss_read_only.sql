-- ============================================================================
-- 176_boss_read_only.sql · 老板只读：收回写权限，一个读权限都不动
-- ----------------------------------------------------------------------------
-- 三处说法本来就是打架的：
--   · 063_roles.sql:176  sys_role.description 写着「老板·全局只读：看板/报表/编制，不改数」
--   · 073_acting.sql:33  CROSS JOIN 全资源把老板改成 **can_write=true**（"业务全权"）
--   · seed-chain 的注释    「老板点算薪应该被拒」
-- 最后生效的是 073（它晚于 063），所以第三条一直是一句空话。
--
-- ★ 真实的错误形态不是"老板算不了薪"，而是**"他算薪被拒的理由是错的"**：
--   实测他点算薪拿到 409「批次已封账」—— 拦他的是封账闸，不是权限。
--   也就是说权限上他本来就能算，只是这一期碰巧封了账；换一期没封账的，
--   他就真的算下去了。这类"看起来被拦住了"最难查：断言只要判 `!== 200`
--   就会把它记成绿。
--
-- ★ 为什么 CROSS JOIN 而不是逐资源码：
--   073 是用 CROSS JOIN 一次给全的（新增资源那天老板自动也有写权限）。
--   既然如此，收回也必须按同一口径收 —— 挑几个资源码去改，收的当天就漏掉剩下的，
--   而下一条新资源出来时又会自动带上写权限。两边形状必须对称。
--
-- ★ can_read **一个都不减**：老板要看全部，这是"只读"不是"无权"。
--   这里唯一的读操作是 `can_read = true`（对已经是 true 的行是空操作，
--   对漏配的行是补齐），永远不会把读收窄。
--
-- ★ 代理不是第二条写路径（查过 073 全文，结论写在这里）：
--   073 把代理接进了 fn_role_can —— 代理拿到的是**某个角色**，判据仍然是
--   `sys_role_resource` 里那张表（`JOIN sys_role_resource rr ON rr.role_id = g.role_id`）。
--   所以"副手顶老板"拿到的就是老板 now 的权限：读全通、写全无。
--   不存在"代理绕开资源矩阵"的写法，本迁移也就不需要额外堵代理。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 全资源：读到、写不给（形状与 073 那条对称）
-- ---------------------------------------------------------------------------
INSERT INTO sys_role_resource (role_id, resource_code, can_read, can_write)
SELECT r.id, res.resource_code, true, false
  FROM sys_role r CROSS JOIN sys_perm_resource res
 WHERE r.code = 'boss'
ON CONFLICT (role_id, resource_code) DO UPDATE
   SET can_read  = true,       -- 只补不放：老板要能看全部
       can_write = false;      -- ★ 收回写：这是本迁移唯一的目的

-- ---------------------------------------------------------------------------
-- 2. 角色描述改回真话
-- ---------------------------------------------------------------------------
-- ★ 073 把它改成了"业务全权：所有资源可读可写"。留着它，下一个人会按那句
--   描述去理解权限；而描述与数据不一致时，被怀疑的总是数据。
UPDATE sys_role
   SET description = '全局只读：所有资源可读、零可写（授权与系统参数仍归 admin）'
 WHERE code = 'boss';

-- ---------------------------------------------------------------------------
-- 3. 判据登记：不新增一行
-- ---------------------------------------------------------------------------
-- ★ 由两处钉住：
--   · test/run.mjs 的 **AC7**（数据库层）：老板 全资源可读 / 零可写 / is_super=false
--   · test/run.mjs 的 **SICK5**：payroll_policy 的写权限收窄到 hr_ops（原本是 boss+hr_ops）
--   · test/perm-matrix.mjs 的 **PM10**（接口层）：老板点算薪 403/E_RESOURCE_FORBIDDEN
--     （不是 409、不是 200），而读工资条/花名册仍 200
--   都记进既有的 SUITE.RC / SUITE.SICK / SUITE.PM，所以这里不再登记新行 ——
--   登记一条永远没人跑的行只会让覆盖率报表多一条自造的 never_run（173/175 同）。
