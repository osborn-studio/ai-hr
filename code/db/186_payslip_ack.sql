-- ============================================================================
-- 186_payslip_ack.sql · 工资条**签收**（线上"我确认已阅"）
-- ----------------------------------------------------------------------------
-- 184/185 解决的是"谁看过"（留痕，append-only）。签收是另一件事：
--   **员工本人确认这张数他没意见**。两者的区别不是措辞，是责任：
--     · 留痕回答"HR 动过我的工资条吗"  → 取证用
--     · 签收回答"我认不认这张数"        → 发薪闭环用（发错了算谁的）
-- 现状（改之前）：打印件上有**纸质**签收栏（`docs/02g:59` 的 P0 已实现），
-- 但线上"确认已阅"一条都没有 —— 远程/异地门店的工资条永远停在"发了，没人认"。
--
-- ★ 设计一：签收的对象是**一张工资条**（`payslip.id`），不是"某一期"。
--   一期的清单里有 374 张单，员工签的是自己那一张；按"期"记会让"我签了但我那行
--   后来被重算过"变成无法表达的状态 —— 而那恰恰是最需要说清的情况。
--   `UNIQUE (payslip_id)` 保证一张单只有一条回执；改数会生成新的 payslip 行
--   （重算走新的 payslip id），于是"重算后需要重新签收"自动成立，不需要额外标记。
--
-- ★ 设计二：**不做"撤回签收"**
--   签收是员工行为。点错了要撤，本身就是一件该留痕的事（谁替谁撤的、为什么）。
--   本期不做，理由写在这里：真要做就加一张撤销记录表，而不是 UPDATE 掉原来那条 ——
--   UPDATE 掉的回执等于"这个员工从来没签过"，而那是不实的。
--   所以本表也是 append-only（触发器拒 UPDATE / DELETE）。
--
-- ★ 设计三：代录（纸质回执录回系统）用 `method` 区分，不混成一条
--   `web`=本人线上签；`paper`=纸质签收后代录；`import`=批量导入。
--   `acked_by` 记代录人。混成一个 method 会让审计看不出"这条是本人点的还是别人代录的"。
--
-- ★ 不加外键（与 185 同理）：历史批次清理时，回执不该阻塞删除；
--   被引用的 payslip 消失后，"他确实签过"这件事仍然成立。
--
-- 幂等：CREATE TABLE IF NOT EXISTS / CREATE INDEX IF NOT EXISTS
--       / DROP TRIGGER IF EXISTS。不动 001–185 的任何字节。
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.payslip_ack (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payslip_id  bigint      NOT NULL,
  employee_id bigint      NOT NULL,      -- person.id（与 payslip.employee_id 同义）
  pay_run_id  bigint      NOT NULL,
  acked_at    timestamptz NOT NULL DEFAULT now(),
  method      varchar(8)  NOT NULL DEFAULT 'web',
  acked_by    bigint,                    -- 代录人（web 时为本人）
  ip          inet,
  note        text,
  CONSTRAINT ck_ack_method CHECK (method IN ('web','paper','import'))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_ack_payslip ON public.payslip_ack (payslip_id);
CREATE INDEX IF NOT EXISTS ix_ack_run ON public.payslip_ack (pay_run_id);
CREATE INDEX IF NOT EXISTS ix_ack_emp ON public.payslip_ack (employee_id, acked_at DESC);

COMMENT ON TABLE public.payslip_ack IS
  '工资条签收（186）。一张单一条回执（ux_ack_payslip）；method 区分本人线上/纸质代录/导入。'
  '★ 与 payslip_view_log 不是一回事：那是"谁看过"（取证），这是"我认不认这张数"（闭环）。'
  '★ 不做撤回：撤回本身该留痕，本期不实现（不要 UPDATE 掉回执——那等于"他没签过"）。';

COMMENT ON COLUMN public.payslip_ack.acked_by IS
  '代录人（method=paper/import 时是经办人；web 时等于本人账号）。'
  '★ 与 employee_id 分开：员工没账号时也能有回执（纸质签了，HR 代录），'
  '  那种行的 employee_id 有值、acked_by 是经办人。';

-- ---------------------------------------------------------------------------
-- append-only：回执不能被改
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_ack_append_only()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  RAISE EXCEPTION 'E_ACK_READONLY: 签收回执不可 % —— 改掉一条回执等于"这个员工从来没签过"，'
                  '那是不实的；要撤回应新增一条撤销记录（本期未实现）', TG_OP;
END;
$$;

DROP TRIGGER IF EXISTS trg_ack_append_only ON public.payslip_ack;
CREATE TRIGGER trg_ack_append_only
  BEFORE UPDATE OR DELETE ON public.payslip_ack
  FOR EACH ROW EXECUTE FUNCTION public.fn_ack_append_only();

-- ---------------------------------------------------------------------------
-- 一期一店的签收进度（HR 用；按行闸收窄在服务层做，视图只做汇总口径）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW public.v_payslip_ack_progress AS
  SELECT p.pay_run_id,
         count(*)::int                                              AS slips,
         count(a.id)::int                                            AS acked,
         (count(*) - count(a.id))::int                                AS pending,
         round(100.0 * count(a.id) / NULLIF(count(*), 0), 1)          AS ack_rate,
         max(a.acked_at)                                              AS last_ack_at
    FROM public.payslip p
    LEFT JOIN public.payslip_ack a ON a.payslip_id = p.id
   GROUP BY p.pay_run_id;

COMMENT ON VIEW public.v_payslip_ack_progress IS
  '每期签收进度（186）：slips / acked / pending / ack_rate / last_ack_at。'
  '★ 这里**不做行闸**：谁看得到哪些门店由服务层用 fn_scope_people 收窄，'
  '  视图若自己带一套范围，两处口径一定会漂。';

