-- ============================================================================
-- 192_mpf_account.sql · MPF（强积金）账号台账 + "该有而没有"的清单
-- ----------------------------------------------------------------------------
-- docs/45 与 docs/42 §六.9 的结论：门店花名册有 MPF 相关列（AD 計畫、AE 方案開始日、
-- AF 退休日、AG/AH 供款日），但**系统里一行都没有** —— `mpf` / `强积金` 在
-- `db/*.sql` 与 `app/*.mjs` 里 0 命中。于是每次核对 MPF 都是拿 Excel 对 Excel。
--
-- ★ 设计一：MPF 账号**按计划分开存**（UNIQUE (person_id, scheme_name)）。
--   一个人在换雇主/转计划时可能同时有两个计划（旧计划留着、新计划新开），
--   把它压成 person 上的一个 `mpf_no` 列，第二次开户就要覆盖第一次 ——
--   而历史供款记录指向的是旧账号。
--
-- ★ 设计二：`status` 而不是"有没有这一行"。
--   有账号 ≠ 在供款：离职后账号还在（保留/转移中）、刚入职还没开户（pending）、
--   已终止（terminated）。用"删行"表达"停供"，会让"他从来没开过户"与
--   "他开过户又停了"变成同一种状态，而这两种在核对时责任完全不同。
--
-- ★ 设计三：**这一版不算钱**（docs/44 的口径）。
--   MPF 供款额仍然由算薪那一侧按 docs/44 反推的口径计算（雇员 5% / 下限 7,100 /
--   上限 30,000 / 雇主无下限 / 年龄与在职天数的豁免，见 docs/44 §CK19–CK20）。
--   本表**不接入** salary_standard、不接入任何工资公式、不改 payslip 的 si_* 列。
--   它回答的是另一件事：**"谁该有账号但没有"** —— 这是合规动作，不是算薪。
--   ★ 反过来也一样：本表有账号**不代表**这个人本月要供款（可能 <60 天、
--     可能已满 65 岁）。把两边接起来，会让"资料没录"变成"钱算错"。
--
-- ★ 设计四：fn_mpf_missing 的豁免口径**不是这里发明的**，全部来自 docs/44：
--   · 年龄 ≥ 65 免供（CK19/CK20 的 `P3>=65`）
--   · 在职 < 60 天免供（`(E3-F3+1)<60`，含离职段 <60 天）
--   · 7,100 下限只对**雇员**供款，与"该不该开户"无关，因此不参与本判定
--   生日未知的人**不默认豁免**（按"可能该有"列入，age 返回 NULL 让人核）——
--   因为"档案缺一格"不该自动变成一项权利。
--
-- 幂等：CREATE TABLE IF NOT EXISTS / CREATE INDEX IF NOT EXISTS / CREATE OR REPLACE。
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.mpf_account (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id    bigint NOT NULL REFERENCES public.person(id),
  scheme_name  varchar(128) NOT NULL,      -- 计划名（如 Manulife Global Select (MPF) Scheme）
  account_no   varchar(64),                -- 账号：老资料里常常只有计划名，所以可空
  join_date    date,                       -- 参加日（AE「方案開始日期」，常与入职日不同）
  status       varchar(16) NOT NULL DEFAULT 'active',
  note         varchar(200),
  created_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_mpf_status CHECK (status IN ('active','pending','terminated')),
  CONSTRAINT ck_mpf_scheme CHECK (length(btrim(scheme_name)) > 0),
  CONSTRAINT ux_mpf_scheme UNIQUE (person_id, scheme_name)
);

CREATE INDEX IF NOT EXISTS ix_mpf_person ON public.mpf_account (person_id);

COMMENT ON TABLE public.mpf_account IS
  'MPF 账号台账（192）。按计划分存（UNIQUE (person_id, scheme_name)）：'
  '换计划时旧计划留着，历史供款记录指向旧账号。'
  'status：active=在供款 / pending=已入职未开户 / terminated=已终止（账号仍在）。'
  '★★ 与算薪**无耦合**：MPF 金额仍按 docs/44 的 CK19–CK20 口径在算薪侧算，'
  '本表不接入 salary_standard、不改 payslip 的任何一列。'
  '★ 有账号 ≠ 本月要供款（可能 <60 天、可能已满 65 岁）；'
  '没有账号 ≠ 没交过 MPF（可能只是没录）。两句话都要写在界面上，否则会被当成对账结论。';

COMMENT ON COLUMN public.mpf_account.join_date IS
  '参加日（花名册 AE「方案開始日期」）。★ 与入职日**不是**同一天：'
  'docs/42 抽查有 8 人两者不等（满 60 天后才开户）。'
  '写成"等于 hire_date"会在核对时把开户日挪早，进而把不该供的月份算成该供。';

COMMENT ON COLUMN public.mpf_account.account_no IS
  '账号。可空：老资料里 26/218 只填了计划名（docs/42 §2.1 AD 列），'
  '强制非空会让那批人根本录不进来 —— 而"录不进来"的结果是一个都不会录。';

-- ---------------------------------------------------------------------------
-- 只读函数：该有 MPF 却没有账号的人
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_mpf_missing()
RETURNS TABLE (
  person_id     bigint,
  full_name     varchar,
  hire_date     date,
  days_employed int,
  age           int,          -- NULL = 生日未知（**不默认豁免**，列出来让人核）
  reason        varchar
)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE v_today date;
BEGIN
  v_today := public.app_today();

  RETURN QUERY
  SELECT t.person_id, p.full_name, t.hire_date, t.days_employed, t.age,
         (CASE WHEN t.age IS NULL THEN 'birth_unknown' ELSE 'no_mpf_account' END)::varchar
    FROM (
      -- ★ DISTINCT ON：一个人可能有多段重叠任职（重新入职 / 跨法人并行），
      --   而"该不该开户"是**按人**问一次的。取最近那段入职日 —— 那决定 60 天门槛。
      --   不压住的话，同一个人会在缺失清单里出现两行，而清单是要拿去催办的。
      SELECT DISTINCT ON (e.person_id)
             e.person_id, e.hire_date,
             (v_today - e.hire_date)::int AS days_employed,
             EXTRACT(YEAR FROM age(v_today,
               COALESCE(public.fn_id_birth(nid.profile_value), ex.birth_date)))::int AS age
        FROM public.employment e
        -- 当前在职：任职段覆盖今天（离职日当天仍算在职，007 的 '[]'）
        -- 生日：身份证派生优先、档案补充兜底（与 fn_emp_roster 同一条口径）
        LEFT JOIN LATERAL (
          SELECT pf.profile_value FROM public.person_profile pf
           WHERE pf.person_id = e.person_id AND pf.profile_type = 'national_id'
           ORDER BY (pf.verified_by IS NOT NULL) DESC, pf.id DESC LIMIT 1
        ) nid ON true
        LEFT JOIN public.employee_extra ex ON ex.employee_id = e.person_id
       WHERE daterange(e.hire_date, e.leave_date, '[]') @> v_today
       ORDER BY e.person_id, e.hire_date DESC
    ) t
    JOIN public.person p ON p.id = t.person_id
   WHERE t.days_employed >= 60                          -- docs/44：在职 <60 天免供
     AND (t.age IS NULL OR t.age < 65)                  -- docs/44：年龄 ≥65 免供
     AND (t.age IS NULL OR t.age >= 18)                 -- 18 岁以下不在 MPF 覆盖范围
     AND NOT EXISTS (
       SELECT 1 FROM public.mpf_account m
        WHERE m.person_id = t.person_id AND m.status IN ('active','pending'))
   ORDER BY t.hire_date, t.person_id;
END;
$$;

COMMENT ON FUNCTION fn_mpf_missing IS
  '该有 MPF 账号却没有的人（192）。豁免口径照 docs/44 的 CK19–CK20，不是本仓发明的：'
  '在职 <60 天免供、年龄 ≥65 免供、18 岁以下不在覆盖范围。'
  '★ 只算**当前在职**的人（离职的人不因"缺账号"被追）。'
  '★ 生日未知（age 为 NULL）不默认豁免 —— "档案缺一格"不该自动变成一项权利；'
  '  这种行 reason=birth_unknown，需要人核一次。'
  '★ 它回答"谁该开户"，**不回答"该供多少钱"** —— 后者在算薪侧（docs/44）。';

