-- ============================================================================
-- 106_salary_adjust.sql · 工资调整单（人为调整 · 留下版本 · 按月 · 可被导入覆盖）
-- ----------------------------------------------------------------------------
-- 现实里"这个月给谁调多少"不是一次数据库 UPDATE，而是一张**单据**：
-- 谁调的、从多少调到多少、为什么、什么时候生效。四件事缺一件，一个月后
-- 就没人说得清"他这 14500 是怎么来的"。
--
-- 三个设计判断：
--
-- ① **调整单是"变更记录"，不是"当前值"**。当前值仍在 salary_standard /
--    salary_structure_item —— 它们按 effective_from 天然带版本。
--    调整单记的是 before/after 两份快照，所以"当时改成什么样"永远查得到，
--    哪怕后来又被改过三次。
--
-- ② **应用是一次性动作**，draft → applied 不可回退（要改就再开一张）。
--    允许"改已应用的调整单"等于允许改历史工资的解释，而工资条已经发出去了。
--
-- ③ **导入也走同一张单据**（source='import'）。否则"手工调的"有痕迹、
--    "导入覆盖的"没痕迹 —— 而后者一次能改几十个人，出事时更该查得到。
--
-- 期间口径：调整在**期间首日**生效（与工资表的 effective_from 一致），
-- 所以"11 月的调整"从 11-01 起算，不会被 10 月的算薪读到。
-- ============================================================================

CREATE TABLE salary_adjustment (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code            varchar(32) NOT NULL UNIQUE,
  period          varchar(7)  NOT NULL,
  person_id       bigint NOT NULL REFERENCES person(id),
  employment_id   bigint NOT NULL REFERENCES employment(id),
  before_monthly  numeric(12,2),
  after_monthly   numeric(12,2) NOT NULL CHECK (after_monthly >= 0),
  before_items    jsonb NOT NULL DEFAULT '[]'::jsonb,
  after_items     jsonb NOT NULL DEFAULT '[]'::jsonb,
  delta           numeric(12,2) NOT NULL DEFAULT 0,
  source          varchar(16) NOT NULL DEFAULT 'manual',
  reason          varchar(200) NOT NULL,
  status          varchar(16) NOT NULL DEFAULT 'draft',
  created_by      varchar(64) NOT NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  applied_by      varchar(64),
  applied_at      timestamptz,
  CONSTRAINT ck_sa_period CHECK (period ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  CONSTRAINT ck_sa_source CHECK (source IN ('manual','import')),
  CONSTRAINT ck_sa_status CHECK (status IN ('draft','applied','cancelled')),
  CONSTRAINT ck_sa_reason CHECK (length(btrim(reason)) >= 4),
  CONSTRAINT ck_sa_applied CHECK ((status = 'applied') = (applied_at IS NOT NULL))
);

CREATE INDEX ix_sa_period ON salary_adjustment (period, status);
CREATE INDEX ix_sa_person ON salary_adjustment (person_id, period DESC);

COMMENT ON TABLE salary_adjustment IS
  '工资调整单：before/after 快照 + 原因 + 来源（manual/import）。'
  '当前值不在这里 —— 在 salary_standard / salary_structure_item（按生效日带版本），'
  '调整单只解释"某次是谁改的、从多少改到多少"。';

-- ---------------------------------------------------------------------------
-- 建单
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_salary_adjust_create(
  p_person bigint, p_period varchar, p_after_items jsonb,
  p_reason varchar, p_source varchar DEFAULT 'manual', p_by varchar DEFAULT 'system'
) RETURNS varchar
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_emp bigint;
  v_from date;
  v_before_monthly numeric(12,2);
  v_before_items jsonb;
  v_after_total numeric(12,2);
  v_bad text;
  v_seq int;
  v_code varchar(32);
BEGIN
  IF p_period !~ '^\d{4}-(0[1-9]|1[0-2])$' THEN
    RAISE EXCEPTION 'E_PERIOD_INVALID: 期间必须是 YYYY-MM';
  END IF;
  IF p_reason IS NULL OR length(btrim(p_reason)) < 4 THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 调整原因至少 4 个字';
  END IF;

  v_from := to_date(p_period || '-01', 'YYYY-MM-DD');

  SELECT e.id INTO v_emp
    FROM public.employment e
   WHERE e.person_id = p_person
     AND daterange(e.hire_date, e.leave_date, '[]') @> v_from
   ORDER BY e.hire_date DESC LIMIT 1;
  IF v_emp IS NULL THEN
    RAISE EXCEPTION 'E_NO_EMPLOYMENT: 人员 % 在 % 没有在职记录', p_person, p_period;
  END IF;

  -- 只允许拆固定项：把"算出来的"（个税/社保）写进结构，会让政策变成约定
  SELECT string_agg(DISTINCT x->>'item_code', '、') INTO v_bad
    FROM jsonb_array_elements(p_after_items) x
    LEFT JOIN public.salary_item si ON si.code = (x->>'item_code')
   WHERE si.code IS NULL OR si.item_kind <> 'fixed';
  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION 'E_SS_ITEM: 调整单只能填固定工资项（收到：%）', v_bad;
  END IF;

  SELECT COALESCE(sum((x->>'amount')::numeric), 0) INTO v_after_total
    FROM jsonb_array_elements(p_after_items) x;
  IF v_after_total <= 0 THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 调整后合计必须大于 0';
  END IF;

  -- 变更前快照
  SELECT COALESCE((SELECT s.monthly_amount FROM public.salary_standard s
                    WHERE s.employment_id = v_emp AND s.effective_from <= v_from
                    ORDER BY s.effective_from DESC LIMIT 1), 0) INTO v_before_monthly;
  SELECT COALESCE(jsonb_agg(jsonb_build_object('item_code', f.item_code, 'amount', f.amount)), '[]'::jsonb)
    INTO v_before_items
    FROM public.fn_salary_structure_of(v_emp, v_from) f;

  SELECT count(*) + 1 INTO v_seq FROM public.salary_adjustment WHERE period = p_period;
  v_code := 'ADJ-' || replace(p_period, '-', '') || '-' || lpad(v_seq::text, 4, '0');

  INSERT INTO public.salary_adjustment(
    code, period, person_id, employment_id, before_monthly, after_monthly,
    before_items, after_items, delta, source, reason, created_by)
  VALUES (v_code, p_period, p_person, v_emp, v_before_monthly, v_after_total,
          v_before_items, p_after_items, v_after_total - v_before_monthly,
          COALESCE(p_source, 'manual'), btrim(p_reason), p_by);
  RETURN v_code;
END;
$$;

COMMENT ON FUNCTION fn_salary_adjust_create IS
  '建工资调整单（draft）：快照 before/after、算差额、生成单号。'
  '建单不动当前值 —— 应用是另一次显式动作。';

-- ---------------------------------------------------------------------------
-- 应用
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_salary_adjust_apply(p_code varchar, p_by varchar DEFAULT 'system')
RETURNS numeric
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  a public.salary_adjustment%ROWTYPE;
  v_from date;
  v_dup bigint;
BEGIN
  SELECT * INTO a FROM public.salary_adjustment WHERE code = p_code FOR UPDATE;
  IF a.id IS NULL THEN RAISE EXCEPTION 'E_NOT_FOUND: 调整单 % 不存在', p_code; END IF;
  IF a.status <> 'draft' THEN
    RAISE EXCEPTION 'E_ADJ_NOT_DRAFT: 调整单 % 当前是 %，只有草稿能应用', p_code, a.status;
  END IF;

  v_from := to_date(a.period || '-01', 'YYYY-MM-DD');

  -- 月薪标准：同生效日覆盖（同一期间反复调，以最后一张为准），否则新增一版
  SELECT id INTO v_dup FROM public.salary_standard
   WHERE employment_id = a.employment_id AND effective_from = v_from;
  IF v_dup IS NOT NULL THEN
    UPDATE public.salary_standard SET monthly_amount = a.after_monthly WHERE id = v_dup;
  ELSE
    INSERT INTO public.salary_standard(employment_id, monthly_amount, effective_from)
    VALUES (a.employment_id, a.after_monthly, v_from);
  END IF;

  -- 结构：fn_salary_structure_set 会校验合计 = 月薪，并关掉旧版本
  PERFORM public.fn_salary_structure_set(a.employment_id, v_from, a.after_items, p_by);

  UPDATE public.salary_adjustment
     SET status = 'applied', applied_by = p_by, applied_at = now()
   WHERE id = a.id;

  RETURN a.after_monthly;
END;
$$;

COMMENT ON FUNCTION fn_salary_adjust_apply IS
  '应用调整单：写月薪标准 + 工资结构（同期间覆盖、跨期间新增版本），并把单据置为 applied。'
  '应用不可回退 —— 要改就再开一张（历史解释不能被改）。';

