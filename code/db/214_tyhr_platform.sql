CREATE FUNCTION fn_ty_platform_scope_guard() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE g bigint;c bigint;p bigint;r jsonb:=to_jsonb(NEW);
BEGIN
 g:=(r->>'group_id')::bigint;c:=(r->>'company_id')::bigint;p:=(r->>'person_id')::bigint;
 IF c IS NOT NULL AND NOT EXISTS(SELECT 1 FROM public.ty_company WHERE id=c AND group_id=g)THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='公司不属于当前集团';END IF;
 IF p IS NOT NULL AND NOT EXISTS(SELECT 1 FROM public.ty_person WHERE id=p AND group_id=g)THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='人员不属于当前集团';END IF;
 IF TG_OP='UPDATE'AND((to_jsonb(OLD)->>'group_id')IS DISTINCT FROM(r->>'group_id'))THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='已有配置或业务不能搬到其他集团';END IF;
 RETURN NEW;
END;$$;
