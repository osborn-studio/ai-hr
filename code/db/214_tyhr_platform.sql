CREATE FUNCTION fn_ty_platform_identity_guard() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE j jsonb:=to_jsonb(NEW);o jsonb;g bigint:=(j->>'group_id')::bigint;a bigint;col text;
BEGIN
 IF TG_OP='UPDATE' THEN
  o:=to_jsonb(OLD);
  FOREACH col IN ARRAY CASE TG_TABLE_NAME
   WHEN 'ty_operator_binding' THEN ARRAY['account_id','group_id','person_id','profile_code']
   WHEN 'ty_auth_role' THEN ARRAY['group_id','legacy_role_id','code']
   WHEN 'ty_auth_membership' THEN ARRAY['group_id','role_id','account_id']
   WHEN 'ty_auth_grant' THEN ARRAY['group_id','subject_type','account_id','role_id','resource']
   ELSE ARRAY[]::text[] END LOOP
   IF j->col IS DISTINCT FROM o->col THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='已建授权主体、身份和资源不可改换，请撤销后另建';END IF;
  END LOOP;
 END IF;
 IF TG_TABLE_NAME IN('ty_auth_role','ty_auth_grant')AND EXISTS(SELECT 1 FROM public.sys_role WHERE id=(j->>'legacy_role_id')::bigint AND is_super)THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='自定义角色不可绑定超级角色';END IF;
 IF TG_TABLE_NAME IN('ty_auth_membership','ty_auth_grant')THEN
  a:=(j->>'account_id')::bigint;
  IF a IS NOT NULL AND NOT EXISTS(SELECT 1 FROM public.sys_account s LEFT JOIN public.ty_operator_binding b ON b.account_id=s.id LEFT JOIN public.ty_test_account_profile p ON p.account_id=s.id WHERE s.id=a AND coalesce(b.group_id,p.group_id)=g)THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='授权操作人员不属于集团';END IF;
 END IF;
 IF TG_TABLE_NAME='ty_auth_grant' THEN
  IF EXISTS(SELECT 1 FROM unnest(NEW.department_ids)x WHERE NOT EXISTS(SELECT 1 FROM public.ty_department d JOIN public.ty_company c ON c.id=d.company_id WHERE d.id=x AND c.group_id=g))OR EXISTS(SELECT 1 FROM unnest(NEW.person_ids)x WHERE NOT EXISTS(SELECT 1 FROM public.ty_person p WHERE p.id=x AND p.group_id=g))THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='部门或人员范围不属于集团';END IF;
 END IF;
 RETURN NEW;
END;$$;
