CREATE FUNCTION fn_ty_integration_mapping_guard() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE g bigint;root_company bigint;target_company bigint;
BEGIN
 SELECT group_id,company_id INTO g,root_company FROM public.ty_integration_connection WHERE id=NEW.connection_id;
 IF TG_OP='UPDATE' AND(NEW.connection_id,NEW.external_type,NEW.external_id)IS DISTINCT FROM(OLD.connection_id,OLD.external_type,OLD.external_id)THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='外部标识不可换绑，请保留原对照历史';END IF;
 IF(NEW.company_id IS NOT NULL AND(NEW.local_type<>'company'OR NOT EXISTS(SELECT 1 FROM public.ty_company WHERE id=NEW.company_id AND group_id=g)))OR(NEW.department_id IS NOT NULL AND(NEW.local_type<>'department'OR NOT EXISTS(SELECT 1 FROM public.ty_department d JOIN public.ty_company c ON c.id=d.company_id WHERE d.id=NEW.department_id AND c.group_id=g)))OR(NEW.person_id IS NOT NULL AND(NEW.local_type<>'person'OR NOT EXISTS(SELECT 1 FROM public.ty_person WHERE id=NEW.person_id AND group_id=g)))THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='对照类型或集团范围不符';END IF;
 IF(NEW.external_type='person'AND NEW.local_type IS NOT NULL AND NEW.local_type<>'person')OR(NEW.external_type='department'AND NEW.local_type='person')THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='外部人员和组织不可混作同一对照类型';END IF;
 IF root_company IS NOT NULL AND num_nonnulls(NEW.company_id,NEW.department_id,NEW.person_id)=1 THEN
  target_company:=NEW.company_id;
  IF NEW.department_id IS NOT NULL THEN SELECT company_id INTO target_company FROM public.ty_department WHERE id=NEW.department_id;END IF;
  IF NOT EXISTS(WITH RECURSIVE c AS(SELECT id FROM public.ty_company WHERE id=root_company UNION SELECT x.id FROM public.ty_company x JOIN c ON x.parent_company_id=c.id)SELECT 1 FROM c WHERE c.id=target_company OR(NEW.person_id IS NOT NULL AND EXISTS(SELECT 1 FROM public.ty_employment e WHERE e.person_id=NEW.person_id AND e.company_id=c.id AND e.status<>'cancelled')))THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='对照目标不属于连接的公司范围';END IF;
 END IF;
