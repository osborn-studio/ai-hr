CREATE FUNCTION fn_ty_platform_instance_guard() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE f public.ty_form_definition;w public.ty_workflow_definition;
BEGIN
 SELECT * INTO f FROM public.ty_form_definition WHERE id=NEW.form_id;
 SELECT * INTO w FROM public.ty_workflow_definition WHERE id=NEW.workflow_id;
 IF (TG_OP='INSERT'AND(f.status<>'published'OR w.status<>'published'))OR f.workflow_id<>w.id OR f.version<>NEW.form_version OR w.version<>NEW.workflow_version OR f.group_id<>NEW.group_id OR w.group_id<>NEW.group_id OR NEW.graph_snapshot<>w.graph OR(f.company_id IS NOT NULL AND f.company_id IS DISTINCT FROM NEW.company_id)OR(w.company_id IS NOT NULL AND w.company_id IS DISTINCT FROM NEW.company_id)THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='须绑定确切已发布表单与流程版本';
 END IF;
 IF TG_OP='UPDATE'AND(to_jsonb(NEW)-ARRAY['status','business_state','current_node','block_reason','revision','last_approver_id','finished_at'])<>(to_jsonb(OLD)-ARRAY['status','business_state','current_node','block_reason','revision','last_approver_id','finished_at'])THEN
