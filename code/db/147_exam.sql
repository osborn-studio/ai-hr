-- ---------------------------------------------------------------------------
-- 11. 结业联动：课程有启用中的试卷时，学时够还不够
-- ---------------------------------------------------------------------------
-- ★ 下面这个函数是 144 的**原文**，只在"学时够了"那一支里加了考试检查。
--   不重写：结业判据一旦有两份实现，学时和考试两条规则迟早各自漂，
--   而漂出来的结果是"有些人莫名结不了业"，很难查。
--
-- ★ 顺序刻意如此：学时不够仍然返回 attended（144 的老行为，不改）；
--   学时够了但没及格 → 报 E_TR_EXAM_REQUIRED。两条判据都在，谁也不会盖掉谁。
CREATE OR REPLACE FUNCTION fn_training_attend(
  p_enroll bigint, p_hours numeric DEFAULT NULL, p_by varchar DEFAULT 'system'
) RETURNS varchar
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  e        record;
  s        record;
  c        record;
  v_hours  numeric(6,2);
  v_status varchar(16);
BEGIN
  SELECT * INTO e FROM public.training_enrollment WHERE id = p_enroll FOR UPDATE;
  IF e.id IS NULL THEN RAISE EXCEPTION 'E_TR_NOT_FOUND: 报名记录 % 不存在', p_enroll; END IF;
  IF e.status = 'completed' THEN
    RAISE EXCEPTION 'E_TR_COMPLETED: 已结业，不能再改学时（要补学另开一场）';
  END IF;

  SELECT * INTO s FROM public.training_session WHERE id = e.session_id;
  SELECT * INTO c FROM public.training_course WHERE id = s.course_id;

  -- 默认给"本场学时"；也可以少于（迟到早退），但不会多于本场
  v_hours := COALESCE(p_hours, s.hours);
  IF v_hours < 0 THEN RAISE EXCEPTION 'E_TR_HOURS: 学时不能为负'; END IF;
  IF v_hours > s.hours THEN
    RAISE EXCEPTION 'E_TR_HOURS: 本场只给了 % 学时，不能记 %（多记学时是伪造培训记录）',
      s.hours, v_hours;
  END IF;

  -- ★ 结业判据用**课程**的标准学时，不是本场学时：
  --   本场只讲半天（4h）而课程标准是 8h，那这个人就是没学完 ——
  --   用本场学时判，等于"讲多少算多少"，标准学时这个字段就失效了。
  IF v_hours >= c.std_hours THEN
    -- ---- 147 新增：这门课有启用中的试卷，就必须有及格成绩 ----
    -- 只认"这门课"的卷子，不认别的课的；pass of any attempt 都算（补考过了就是过了）。
    IF EXISTS (SELECT 1 FROM public.exam_paper p
                WHERE p.course_id = c.id AND p.is_active)
       AND NOT EXISTS (
             SELECT 1 FROM public.exam_attempt a
               JOIN public.exam_paper p ON p.id = a.paper_id
              WHERE p.course_id = c.id
                AND a.employee_id = e.employee_id
                AND a.passed) THEN
      -- ★ 这里不写"先置 attended 再报错"：同一条语句里 RAISE 会把那次 UPDATE 一起回滚，
      --   写进来的是死代码。到场学时晚一点记（考完再调一次）比留一条半截记录强 ——
      --   一条"去了但没考试"的记录，将来会被当成结业证据。
      RAISE EXCEPTION
        'E_TR_EXAM_REQUIRED: 学时已够（% / % 学时），但课程「%」有启用中的试卷，'
        '还没有及格成绩 —— 考过之后再记一次到场，才会结业',
        v_hours, c.std_hours, c.name;
    END IF;

    v_status := 'completed';
    UPDATE public.training_enrollment
       SET status = 'completed', attended_hours = v_hours, completed_at = now()
     WHERE id = p_enroll;
  ELSE
    v_status := 'attended';
    UPDATE public.training_enrollment
       SET status = 'attended', attended_hours = v_hours, completed_at = NULL
     WHERE id = p_enroll;
  END IF;
  RETURN v_status;
END;
$$;

COMMENT ON FUNCTION fn_training_attend IS
  '记到场学时并判定结业（144，147 重定义）。学时判据同 144；'
  '课程有**启用中**的试卷时另需"该人该课程有及格答卷"，否则报 E_TR_EXAM_REQUIRED —— '
  '只记学时不算学完：上课 + 考试才叫完成。';

