-- ============================================================================
-- 147_exam.sql · 培训考试：卷子由库判，分数不由前端传，答案不随卷下发
-- ----------------------------------------------------------------------------
-- 144 把培训做成了"课程 → 场次 → 到场 → 结业"一条链，结业只看学时。
-- 这对**听课类**培训是对的，对另外两类是错的：
--
--   ① 安全生产培训：监管查的是"考没考过"，不是"坐了几个小时"。
--   ② 岗前培训：员工手册、操作规范，签到了不等于记住了。
--
-- 只记学时，等于把"人在教室里"当成"人会了"。所以这一层补的是考试成绩。
--
-- ★ 四条设计取舍，每条都在替客户挡一件将来会被追问的事：
--
--   ① **判分在库里，前端只交"我选了什么"。**
--      分数由 fn_exam_submit 从 exam_question.answer 算出来。接口如果收分数，
--      改一个请求参数就能及格 —— 而这个分数是要拿去过监管检查的。
--
--   ② **多选必须完全一致，选一半给 0 分。**
--      给部分分看上去"人性化"，实际打开了一扇门：把 4 个选项全勾上，
--      每道多选都能拿到一半以上的分，攒够及格线。全选得 0 才是对的。
--
--   ③ **答案不下发。** fn_exam_paper_for 是卷子离开服务端的唯一形状，
--      它没有 answer 列。答案随卷子发到浏览器，这场考试就没有意义了 ——
--      任何一个考生按 F12 都能看到答案，而"监考"这件事实体上做不到。
--
--   ④ **交卷之后不可改，也不可重复交。**
--      与工资条封账、绩效封存同一条规矩：已经作为"证据"用出去的东西不能再变。
--      要重考就再发一份卷（exam_attempt 允许多份，只禁止改历史）。
--
-- ★ 一处联动：课程**有启用中的试卷**时，结业要"学时够 + 有及格成绩"两件事。
--   所以本文件末尾 CREATE OR REPLACE 了 144 的 fn_training_attend ——
--   原件照抄，只在"学时够了"那一支里加了一段考试检查。理由很直接：
--   结业判据只有一份实现，否则学时和考试两条规则迟早各自漂。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 试卷：挂在一门课上，及格线是这张卷的事
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS exam_paper (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id   bigint      NOT NULL REFERENCES training_course(id),
  code        varchar(32) NOT NULL UNIQUE,
  name        varchar(96) NOT NULL,
  pass_score  numeric(6,2) NOT NULL DEFAULT 60,
  is_active   boolean     NOT NULL DEFAULT true,
  note        varchar(200),
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_ep_pass CHECK (pass_score > 0)
);

CREATE INDEX IF NOT EXISTS ix_ep_course ON exam_paper (course_id) WHERE is_active;

COMMENT ON TABLE exam_paper IS
  '试卷（147）。一门课可以有多张卷（换版、难易不同的补考），'
  '但**启用中的**存在时才要求考试 —— 停用的卷子只作为历史记录留着。'
  'pass_score 是这张卷的及格线，不是全局的：安全考试 80 分与入职考试 60 分是两回事。';

-- ---------------------------------------------------------------------------
-- 2. 题目：kind 决定怎么判，answer 是唯一的事实来源
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS exam_question (
  id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paper_id bigint      NOT NULL REFERENCES exam_paper(id) ON DELETE CASCADE,
  seq      int         NOT NULL,
  kind     varchar(8)  NOT NULL,
  stem     varchar(500) NOT NULL,
  -- [{"k":"A","t":"…"}, …]；判断题为空数组时按固定的 A=对 / B=错 下发
  options  jsonb       NOT NULL DEFAULT '[]'::jsonb,
  -- 单选 'A'；多选 'A,C'（规范顺序、无空格；由 fn_exam_norm 统一成这个形状）；
  -- 判断 'A'/'B'。**这一列永远不出现在下发给前端的结构里。**
  answer   varchar(32) NOT NULL,
  score    numeric(6,2) NOT NULL,
  CONSTRAINT uk_eq_seq UNIQUE (paper_id, seq),
  CONSTRAINT ck_eq_kind CHECK (kind IN ('single','multi','judge')),
  CONSTRAINT ck_eq_score CHECK (score > 0),
  CONSTRAINT ck_eq_json  CHECK (jsonb_typeof(options) = 'array'),
  -- judge 的选项固定两个（或交给下发时补），不留"只有三个选项的判断题"
  CONSTRAINT ck_eq_judge CHECK (kind <> 'judge' OR jsonb_array_length(options) IN (0, 2)),
  -- 答案形状：单选一个字母、多选逗号分隔的字母、判断 A/B。
  -- ★ 这里只做形状检查；**顺序与去重由 fn_exam_norm 在写入前统一**，
  --   否则 'C,A' 和 'A,C' 在库里是两行不同的字符串，判分时永远对不上。
  CONSTRAINT ck_eq_ans CHECK (
       (kind = 'single' AND answer ~ '^[A-H]$')
    OR (kind = 'multi'  AND answer ~ '^[A-H](,[A-H])*$')
    OR (kind = 'judge'  AND answer IN ('A','B'))
  ),
  CONSTRAINT ck_eq_single_opt CHECK (kind <> 'single' OR jsonb_array_length(options) >= 2),
  CONSTRAINT ck_eq_multi_opt  CHECK (kind <> 'multi'  OR jsonb_array_length(options) >= 2)
);

CREATE INDEX IF NOT EXISTS ix_eq_paper ON exam_question (paper_id, seq);

COMMENT ON TABLE exam_question IS
  '题目（147）。answer 是判分的唯一事实来源，也是**唯一不出现**在下发结构里的列。'
  '多选答案按规范顺序存（fn_exam_norm 负责），否则 ''C,A'' 与 ''A,C'' 判分时对不上。';

-- ---------------------------------------------------------------------------
-- 3. 答卷：一份卷一次提交
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS exam_attempt (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paper_id     bigint      NOT NULL REFERENCES exam_paper(id),
  employee_id  bigint      NOT NULL,          -- person.id（与 144 同：不挂外键）
  session_id   bigint      REFERENCES training_session(id),
  started_at   timestamptz NOT NULL DEFAULT now(),
  submitted_at timestamptz,
  score        numeric(6,2),
  passed       boolean,
  -- ★ 三件事同生同灭：没交卷就没有分数，没有分数就没有及格与否。
  --   与 ck_pr_sealed / ck_te_done 同一条规矩 —— 半个状态比没有状态更难解释。
  CONSTRAINT ck_ea_state CHECK ((submitted_at IS NULL) = (score IS NULL)),
  CONSTRAINT ck_ea_pass  CHECK ((score IS NULL) = (passed IS NULL)),
  CONSTRAINT ck_ea_score CHECK (score IS NULL OR score >= 0)
);

CREATE INDEX IF NOT EXISTS ix_ea_paper_emp ON exam_attempt (paper_id, employee_id);
CREATE INDEX IF NOT EXISTS ix_ea_emp ON exam_attempt (employee_id);
CREATE INDEX IF NOT EXISTS ix_ea_open ON exam_attempt (paper_id, employee_id)
  WHERE submitted_at IS NULL;

COMMENT ON TABLE exam_attempt IS
  '答卷（147）。允许同一人多份（补考），但同一张卷同时只该有一份没交的'
  '（fn_exam_start 幂等返回那一份）。已交卷的不许改、不许删、不许再交。';

-- ---------------------------------------------------------------------------
-- 4. 答题明细：本题得分由判分函数写，不是考生填
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS exam_answer (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_id  bigint      NOT NULL REFERENCES exam_attempt(id) ON DELETE CASCADE,
  question_id bigint      NOT NULL REFERENCES exam_question(id),
  picked      varchar(32),                 -- 考生选的（规范顺序）；没答 = NULL
  score       numeric(6,2),                -- 本题得分（未交卷前为 NULL/0，由 fn_exam_submit 定）
  CONSTRAINT uk_exa_once UNIQUE (attempt_id, question_id)
);

COMMENT ON TABLE exam_answer IS
  '答题明细（147）。picked 是"考生选了什么"，score 是"这题得了多少"——'
  '后者只能由 fn_exam_submit 按 exam_question.answer 算出，前端传的分数在库里没有落点。';

-- ---------------------------------------------------------------------------
-- 5. 答案规范化：一份实现，写入与判分共用
-- ---------------------------------------------------------------------------
-- ★ 为什么不各写一份：写入时存 'c, a '、判分时按 'A,C' 比，是两条独立的字符串处理，
--   它们不同步的那一天，正确作答的人会得 0 分 —— 而这种错误不会报错，只会让人不及格。
CREATE OR REPLACE FUNCTION fn_exam_norm(p_kind varchar, p_raw text)
RETURNS varchar
LANGUAGE plpgsql IMMUTABLE
SET search_path = ''
AS $$
DECLARE
  v   text;
  v_o text;
BEGIN
  v := upper(btrim(COALESCE(p_raw, '')));
  IF v = '' THEN RETURN NULL; END IF;   -- 没答（空着）就是没答，不猜

  IF p_kind = 'multi' THEN
    -- 去空格、去重、排序：' c, a ,c ' → 'A,C'
    -- ★ 先把空格全去掉再切：'A, C' 切出来是 'A' 和 ' C'，两个 token 不一致，
    --   排序也排不对 —— 这种半格空格造成的"答案不一致"最难查。
    v := replace(v, ' ', '');
    SELECT string_agg(DISTINCT t, ',' ORDER BY t) INTO v_o
      FROM unnest(string_to_array(v, ',')) AS u(t)
     WHERE t <> '';
    IF v_o IS NULL THEN RETURN NULL; END IF;
    IF v_o !~ '^[A-H](,[A-H])*$' THEN
      RAISE EXCEPTION 'E_EXAM_BAD_ANSWER: 多选答案只能是 A-H 之间用逗号分隔的选项字母（收到 %）', p_raw;
    END IF;
    RETURN v_o;
  END IF;

  IF v !~ '^[A-H]$' THEN
    RAISE EXCEPTION 'E_EXAM_BAD_ANSWER: %题只能选一个字母 A-H（收到 %）',
      CASE p_kind WHEN 'judge' THEN '判断' ELSE '单选' END, p_raw;
  END IF;
  RETURN v;
END;
$$;

COMMENT ON FUNCTION fn_exam_norm IS
  '答案规范化（147）：大写、去空格、多选去重排序。**写入题目与判分共用这一份** —— '
  '两处各写一遍，不同步的那天正确作答的人会得 0 分，而且不报错。';

-- 题目入库前先规范化，answer 的"规范顺序"是保证，不是约定
CREATE OR REPLACE FUNCTION fn_eq_normalize() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  NEW.answer := public.fn_exam_norm(NEW.kind, NEW.answer);
  IF NEW.answer IS NULL THEN
    RAISE EXCEPTION 'E_EXAM_BAD_ANSWER: 题目 % 的标准答案不能为空', NEW.seq;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_eq_normalize ON exam_question;
CREATE TRIGGER trg_eq_normalize BEFORE INSERT OR UPDATE ON exam_question
  FOR EACH ROW EXECUTE FUNCTION fn_eq_normalize();

-- ---------------------------------------------------------------------------
-- 6. 已交卷不可改：答题明细
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_exam_answer_guard() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_att bigint;
  v_sub timestamptz;
BEGIN
  v_att := CASE TG_OP WHEN 'DELETE' THEN OLD.attempt_id ELSE NEW.attempt_id END;
  SELECT a.submitted_at INTO v_sub FROM public.exam_attempt a WHERE a.id = v_att;
  IF v_sub IS NOT NULL THEN
    RAISE EXCEPTION 'E_EXAM_SUBMITTED: 答卷 % 已于 % 交卷，答题记录不能%——要重考就再发一份卷',
      v_att, v_sub,
      CASE TG_OP WHEN 'INSERT' THEN '补' WHEN 'UPDATE' THEN '改' ELSE '删' END;
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$;

DROP TRIGGER IF EXISTS trg_exam_answer_guard ON exam_answer;
CREATE TRIGGER trg_exam_answer_guard BEFORE INSERT OR UPDATE OR DELETE ON exam_answer
  FOR EACH ROW EXECUTE FUNCTION fn_exam_answer_guard();

-- ---------------------------------------------------------------------------
-- 7. 已交卷不可改：答卷本身（分数、及格与否、换卷、换人，全锁）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_exam_attempt_guard() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  -- ★ 只管 OLD：fn_exam_submit 自己那次 UPDATE 的 OLD 是"未交卷"，必须放行；
  --   按 NEW 判会把判分函数自己拦在门外。
  IF OLD.submitted_at IS NOT NULL THEN
    RAISE EXCEPTION 'E_EXAM_SUBMITTED: 答卷 % 已于 % 交卷（% 分），不能%',
      OLD.id, OLD.submitted_at, OLD.score,
      CASE TG_OP WHEN 'DELETE' THEN '删' ELSE '改' END;
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$;

DROP TRIGGER IF EXISTS trg_exam_attempt_guard ON exam_attempt;
CREATE TRIGGER trg_exam_attempt_guard BEFORE UPDATE OR DELETE ON exam_attempt
  FOR EACH ROW EXECUTE FUNCTION fn_exam_attempt_guard();

-- ---------------------------------------------------------------------------
-- 8. 发卷
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_exam_start(
  p_paper bigint, p_employee bigint, p_session bigint DEFAULT NULL
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  p    record;
  v_n  int;
  v_id bigint;
BEGIN
  SELECT * INTO p FROM public.exam_paper WHERE id = p_paper;
  IF p.id IS NULL THEN
    RAISE EXCEPTION 'E_EXAM_NO_PAPER: 试卷 % 不存在', p_paper;
  END IF;
  IF NOT p.is_active THEN
    RAISE EXCEPTION 'E_EXAM_PAPER_INACTIVE: 试卷 % 已停用，不能再发', p_paper;
  END IF;

  -- 0 题的卷子判出来是 0 分，看着"没通过"，实际是卷子生成错了。
  -- 这种事必须当场说，不能等到考生交了白卷才让人去猜。
  SELECT count(*)::int INTO v_n FROM public.exam_question WHERE paper_id = p_paper;
  IF v_n = 0 THEN
    RAISE EXCEPTION 'E_EXAM_NO_QUESTION: 试卷 % 还没有题目，发不了（0 题的卷子判不出分）', p_paper;
  END IF;

  -- 幂等：同时只给一份没交的卷，否则"最终成绩"变成"最后一次提交"
  SELECT a.id INTO v_id FROM public.exam_attempt a
   WHERE a.paper_id = p_paper AND a.employee_id = p_employee
     AND a.submitted_at IS NULL;
  IF v_id IS NOT NULL THEN RETURN v_id; END IF;

  INSERT INTO public.exam_attempt(paper_id, employee_id, session_id)
  VALUES (p_paper, p_employee, p_session)
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_exam_start IS
  '发卷（147）：返回 attempt_id。停用卷、空卷都拒；同一人同一卷已有未交的一份时'
  '幂等返回它 —— 两张同时在答的卷子会让"最终成绩"变成"最后一次提交"。';

-- ---------------------------------------------------------------------------
-- 9. 卷面（给考生看的那一份）：没有 answer
-- ---------------------------------------------------------------------------
-- ★ 这是**唯一**允许把卷子发给前端的地方。答案随卷下发，考试就没有意义了：
--   任何考生按 F12 都能看到标准答案，而"监考"这件事在线上做不到。
--   页面要显示答案，只能等交卷之后（那时看的是自己答错哪题，不是别人的卷）。
CREATE OR REPLACE FUNCTION fn_exam_paper_for(p_paper bigint)
RETURNS TABLE (
  paper_id bigint, paper_code varchar(32), paper_name varchar(96),
  pass_score numeric(6,2),
  question_id bigint, seq int, kind varchar(8), stem varchar(500),
  options jsonb, score numeric(6,2)
)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT p.id, p.code, p.name, p.pass_score,
         q.id, q.seq, q.kind, q.stem,
         -- 判断题的选项是固定的，库里不存一份也就不存在"跟标准不一致"
         CASE WHEN q.kind = 'judge' AND jsonb_array_length(q.options) = 0
              THEN '[{"k":"A","t":"对"},{"k":"B","t":"错"}]'::jsonb
              ELSE q.options END,
         q.score
    FROM public.exam_paper p
    LEFT JOIN public.exam_question q ON q.paper_id = p.id
   WHERE p.id = p_paper
   ORDER BY q.seq;
$$;

COMMENT ON FUNCTION fn_exam_paper_for IS
  '卷面（147）：只给题干/选项/分值，**不含 answer**。这是卷子离开服务端的唯一形状 —— '
  '答案随卷下发，考试就没有意义了（F12 就能看到标准答案）。';

-- ---------------------------------------------------------------------------
-- 10. 判分：前端只交"我选了什么"
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_exam_submit(p_attempt bigint, p_answers jsonb)
RETURNS TABLE (
  score numeric, passed boolean, total_score numeric,
  right_count int, question_count int
)
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  a        record;
  p        record;
  q        record;
  v_item   jsonb;
  v_qid    bigint;
  v_pick   varchar(32);
  v_sum    numeric(8,2) := 0;
  v_total  numeric(8,2) := 0;
  v_right  int := 0;
  v_n      int := 0;
  v_seen   bigint[] := '{}';
  v_keys   text[];
BEGIN
  SELECT * INTO a FROM public.exam_attempt WHERE id = p_attempt FOR UPDATE;
  IF a.id IS NULL THEN
    RAISE EXCEPTION 'E_EXAM_NO_ATTEMPT: 答卷 % 不存在', p_attempt;
  END IF;
  IF a.submitted_at IS NOT NULL THEN
    RAISE EXCEPTION 'E_EXAM_SUBMITTED: 答卷 % 已于 % 交过卷（% 分），不能重复提交',
      p_attempt, a.submitted_at, a.score;
  END IF;
  SELECT * INTO p FROM public.exam_paper WHERE id = a.paper_id;

  -- ---- 先整体校验，再动数据：半份答案落库比整份被拒更难解释 ----
  IF p_answers IS NULL OR jsonb_typeof(p_answers) <> 'array' THEN
    RAISE EXCEPTION 'E_EXAM_BAD_ANSWER: 答案要是数组，形如 [{"q":1,"picked":"A"}]';
  END IF;

  FOR v_item IN SELECT * FROM jsonb_array_elements(p_answers) LOOP
    v_qid := COALESCE(v_item->>'q', v_item->>'question_id')::bigint;
    IF v_qid IS NULL THEN
      RAISE EXCEPTION 'E_EXAM_BAD_ANSWER: 数组元素缺 q（题号）：%', v_item;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.exam_question q2
                    WHERE q2.id = v_qid AND q2.paper_id = a.paper_id) THEN
      RAISE EXCEPTION 'E_EXAM_BAD_ANSWER: 题 % 不属于答卷 % 的这份卷子', v_qid, p_attempt;
    END IF;
    -- 同一题传两次是调用方的 bug，不是"后一次覆盖"：静默取一条会让人以为改了答案
    IF v_qid = ANY(v_seen) THEN
      RAISE EXCEPTION 'E_EXAM_BAD_ANSWER: 题 % 在这次提交里出现了两次', v_qid;
    END IF;
    v_seen := v_seen || v_qid;
  END LOOP;

  -- ---- 逐题判：卷面上的每一题都算分，没答就是 0（"不答不扣分"不成立）----
  FOR q IN SELECT * FROM public.exam_question WHERE paper_id = a.paper_id ORDER BY seq LOOP
    v_n := v_n + 1;
    v_total := v_total + q.score;

    v_pick := NULL;
    SELECT COALESCE(i->>'picked', i->>'answer') INTO v_pick
      FROM jsonb_array_elements(p_answers) i
     WHERE COALESCE(i->>'q', i->>'question_id')::bigint = q.id
     LIMIT 1;
    v_pick := public.fn_exam_norm(q.kind, v_pick);

    -- 选了卷面上不存在的选项（比如 2 选项的题交了 C）—— 报出来，不静默算 0：
    -- 静默算 0 的话，"我明明答了却 0 分"要靠人去猜是前端还是卷子的问题。
    IF v_pick IS NOT NULL THEN
      IF q.kind = 'judge' AND jsonb_array_length(q.options) = 0 THEN
        v_keys := ARRAY['A','B'];
      ELSE
        SELECT array_agg(upper(o->>'k')) INTO v_keys
          FROM jsonb_array_elements(q.options) o;
      END IF;
      IF v_keys IS NOT NULL
         AND NOT (string_to_array(v_pick, ',') <@ v_keys) THEN
        RAISE EXCEPTION 'E_EXAM_BAD_ANSWER: 第 % 题只有选项 %，收到 %',
          q.seq, array_to_string(v_keys, '/'), v_pick;
      END IF;
    END IF;

    -- ★ 多选必须**完全一致**才得分。选一半给部分分，等于"全选"能骗到及格线：
    --   4 个选项全勾，每题至少拿一半，几道题就攒够了 60 分。
    IF v_pick IS NOT NULL AND v_pick = q.answer THEN
      v_sum := v_sum + q.score;
      v_right := v_right + 1;
      INSERT INTO public.exam_answer(attempt_id, question_id, picked, score)
      VALUES (p_attempt, q.id, v_pick, q.score);
    ELSE
      INSERT INTO public.exam_answer(attempt_id, question_id, picked, score)
      VALUES (p_attempt, q.id, v_pick, 0);
    END IF;
  END LOOP;

  IF v_n = 0 THEN
    RAISE EXCEPTION 'E_EXAM_NO_QUESTION: 试卷 % 没有题目，判不了分', p.code;
  END IF;

  -- 分数在这里落库：本次唯一一次写 score/passed/submitted_at 的地方
  UPDATE public.exam_attempt
     SET submitted_at = now(), score = v_sum, passed = (v_sum >= p.pass_score)
   WHERE id = p_attempt;

  RETURN QUERY
    SELECT v_sum, (v_sum >= p.pass_score), v_total, v_right, v_n;
END;
$$;

