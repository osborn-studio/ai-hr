-- ============================================================================
-- 017_org_version.sql · 组织树版本切片
-- ----------------------------------------------------------------------------
-- 这是「四维归属」剩下的最后一个洞。
--
-- 014 已经做到了：某一天他在哪个 org（employee_org_assignment 带时间版本）。
-- 但 **org 这棵树本身没有版本**。于是：
--
--   2026-03  员工挂在 102（A 店），A 店属于 20（华东区）
--   2026-09  区域重组，A 店改挂 30（上海大区）
--   现在查 "2026-03 这个人属于哪个区" → 返回 30
--
-- 而 30 在 2026-03 还不存在。报表会显示"华东区去年三月业绩为零"，
-- 每一行都能追到，每一行都是错的。
--
-- 解法不是给 org_unit 加历史列，是**整棵树按版本快照**：
-- 一次重组 = 一个新版本 = 一份完整快照。查询永远先定版本，再读快照。
-- 这样"历史"不是被维护的东西，是**没有被改写的东西**。
-- ============================================================================

CREATE TABLE org_version (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_no     int          NOT NULL UNIQUE,
  effective_date date         NOT NULL UNIQUE,   -- 同一天两个版本 = 当天归属不可判
  status         varchar(16)  NOT NULL DEFAULT 'draft',
  published_at   timestamptz,
  note           varchar(200),
  CONSTRAINT ck_ov_status CHECK (status IN ('draft','published')),
  -- 状态与发布时间同生同灭
  CONSTRAINT ck_ov_pub CHECK ((status = 'published') = (published_at IS NOT NULL))
);

CREATE TABLE org_unit_snapshot (
  version_id bigint      NOT NULL REFERENCES org_version(id),
  unit_id    bigint      NOT NULL,
  parent_id  bigint,
  name       varchar(64) NOT NULL,
  -- ★ path 冗余存一份，不是懒：它是这个版本里的祖先链本身。
  --   靠 parent_id 递归也能算出来，但那样每次查询都在重算"当时的树"，
  --   而重算的输入是**快照**——既然输入已经冻结，输出也该冻结。
  path       text        NOT NULL,
  PRIMARY KEY (version_id, unit_id),
  -- path 与 001 的 org_unit 同一套分段约定（'001.030.010'），不另立一套
  CONSTRAINT ck_ous_path CHECK (path ~ '^[0-9]+(\.[0-9]+)*$')
);

-- ---------------------------------------------------------------------------
-- 定版本：时点 → 版本。找不到就报错，不返回"当前值"
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_org_version_asof(p_on date)
RETURNS bigint
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE v bigint;
BEGIN
  SELECT id INTO v FROM public.org_version
   WHERE status = 'published' AND effective_date <= p_on
   ORDER BY effective_date DESC LIMIT 1;

  -- ★ 这里必须抛，不能返回 NULL 让调用方 coalesce 到当前版本。
  --   "没有那个时点的组织版"与"那个时点用了当前这版"在报表上同形，
  --   而前者意味着这一段历史**不可判**，不该给出任何数。
  IF v IS NULL THEN
    RAISE EXCEPTION 'E_ORG_NO_VERSION: % 之前没有已发布的组织版本，该时点归属不可判', p_on;
  END IF;
  RETURN v;
END;
$$;

-- 时点祖先链（含自身），按由近及远
CREATE OR REPLACE FUNCTION fn_org_ancestors(p_unit bigint, p_on date)
RETURNS TABLE (unit_id bigint, name varchar, depth int)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  WITH v AS (SELECT public.fn_org_version_asof(p_on) AS vid),
       me AS (SELECT s.path FROM public.org_unit_snapshot s, v
               WHERE s.version_id = v.vid AND s.unit_id = p_unit)
  SELECT s.unit_id, s.name,
         -- 层级 = 路径段数。不用 length 差：unit_id 位数不同，
         -- 字节差会给出 0/5/8 这种"看起来像层级其实不是"的数。
         COALESCE(array_length(string_to_array(s.path, '.'), 1), 0) AS depth
    FROM public.org_unit_snapshot s, v, me
   WHERE s.version_id = v.vid
     AND me.path LIKE s.path || '%'
   ORDER BY depth DESC;
$$;

-- ---------------------------------------------------------------------------
-- 发布：整棵树必须齐，且发布后不可再改
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_org_publish(p_version bigint)
RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_status varchar(16); v_missing text;
BEGIN
  SELECT status INTO v_status FROM public.org_version WHERE id = p_version FOR UPDATE;
  IF v_status IS NULL THEN
    RAISE EXCEPTION 'E_ORG_NO_VERSION_ROW: 版本 % 不存在', p_version;
  END IF;
  IF v_status <> 'draft' THEN
    RAISE EXCEPTION 'E_ORG_ALREADY_PUBLISHED: 版本 % 已是 %', p_version, v_status;
  END IF;

  -- ★ 完整性检查只对**最新版**成立。
  --   漏一个的直接后果是"新开的店在组织树里不存在"，
  --   而它在归属表里照样能挂上——两个模块各自都对，合起来树是缺的。
  --
  --   但不能拿今天的树去要求一个历史版本：2026-01 那版里本来就没有
  --   2026-09 才拆出来的节点，那叫"当时的真相"，不叫"缺"。
  --   用今天的要求去检查过去，会得到一条永远修不好的红。
  IF p_version = (SELECT id FROM public.org_version ORDER BY effective_date DESC LIMIT 1) THEN
    SELECT string_agg(u.id::text, ',' ORDER BY u.id) INTO v_missing
      FROM public.org_unit u
     WHERE NOT EXISTS (SELECT 1 FROM public.org_unit_snapshot s
                        WHERE s.version_id = p_version AND s.unit_id = u.id);

    IF v_missing IS NOT NULL THEN
      RAISE EXCEPTION 'E_ORG_VERSION_INCOMPLETE: 版本 % 缺少现行组织节点：%',
        p_version, v_missing;
    END IF;
  END IF;

  UPDATE public.org_version
     SET status = 'published', published_at = clock_timestamp()
   WHERE id = p_version;
END;
$$;

-- 冻结：已发布版本的快照与生效日都不可改
CREATE OR REPLACE FUNCTION fn_org_snapshot_frozen() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_status varchar(16); v_id bigint;
BEGIN
  v_id := COALESCE(NEW.version_id, OLD.version_id);
  SELECT status INTO v_status FROM public.org_version WHERE id = v_id;
  IF v_status = 'published' THEN
    RAISE EXCEPTION 'E_ORG_SNAPSHOT_FROZEN: 版本 % 已发布，快照不可增删改', v_id;
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$;

CREATE TRIGGER trg_ous_frozen
  BEFORE INSERT OR UPDATE OR DELETE ON org_unit_snapshot
  FOR EACH ROW EXECUTE FUNCTION fn_org_snapshot_frozen();

CREATE OR REPLACE FUNCTION fn_org_version_frozen() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF OLD.status = 'published' THEN
    -- 生效日不许改：改了它，等于把过去一段时间的归属整体换到另一版。
    -- 这一步是合法 UPDATE，而报表不会报错，只会换一套数。
    IF NEW.effective_date <> OLD.effective_date THEN
      RAISE EXCEPTION 'E_ORG_DATE_FROZEN: 已发布版本的生效日不可改（% → %）',
        OLD.effective_date, NEW.effective_date;
    END IF;
    IF NEW.status = 'draft' THEN
      RAISE EXCEPTION 'E_ORG_UNPUBLISH: 不允许把已发布版本退回 draft';
    END IF;
  END IF;
  IF TG_OP = 'DELETE' THEN
    IF OLD.status = 'published' THEN
      RAISE EXCEPTION 'E_ORG_VERSION_DELETED: 不允许删除已发布版本（删掉它，那些时点的归属就不可判了）';
    END IF;
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_ov_frozen
  BEFORE UPDATE OR DELETE ON org_version
  FOR EACH ROW EXECUTE FUNCTION fn_org_version_frozen();

COMMENT ON TABLE org_unit_snapshot IS
  '整棵树按版本快照。一次重组 = 一个新版本 = 一份完整快照。'
  '历史不是被维护的东西，是**没有被改写的东西**。';
