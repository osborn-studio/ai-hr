-- ============================================================================
-- 025_recruitment.sql · 招聘：需求 → offer → 入职
-- ----------------------------------------------------------------------------
-- 这一块的价值不在"多一套表"，在**把编制这个抽象额度，变成一个具体的人**。
-- 中间会经过若干次承诺，而每一次承诺都在占用额度。
--
-- 所以核心判据只有一条：**编制说还能招 2 个，招聘就只能发 2 个 offer。**
-- 这条不在库里，编制管理就只是一张报表——谁都可以绕过它发 offer，
-- 而发出去的 offer 又不能不发（那是法律承诺）。
--
-- 三个必须分清的量：
--
--   used      已入职（事实）
--   offered   有效 offer（承诺）
--   可招      = 额度 − 已下分 − used          ← 不含承诺
--   还能发    = 可招 − offered                ← 含承诺
--
-- 只算 used 的后果：同一个编可以同时发出十个 offer，第一个入职的人把位置占了，
-- 后面九个都是法律承诺，而系统在整个过程中一直是绿的。
--
-- 两处时间语义：
--   ① offer 有有效期，**过期靠时点派生，不靠定时任务改状态**。
--      定时任务停了三天，就会多发出三个本来发不出的 offer，而没人会发现。
--   ② 额度是按月设的，招聘发生在某一天。所以取额度要用
--      "该月或更早最近一期"（fn_hc_quota_asof），而不是要求那个月恰好有额度。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 招聘需求
-- ---------------------------------------------------------------------------
CREATE TABLE requisition (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id      bigint      NOT NULL REFERENCES org_unit(id),
  position    varchar(64) NOT NULL,
  headcount   int         NOT NULL,
  status      varchar(16) NOT NULL DEFAULT 'open',
  opened_at   date        NOT NULL,
  closed_at   date,
  reason      varchar(200) NOT NULL,
  created_by  varchar(64) NOT NULL,
  CONSTRAINT ck_rq_head   CHECK (headcount > 0),
  CONSTRAINT ck_rq_status CHECK (status IN ('open','closed','cancelled')),
  CONSTRAINT ck_rq_closed CHECK ((status = 'open') = (closed_at IS NULL)),
  CONSTRAINT ck_rq_reason CHECK (length(btrim(reason)) >= 4)
);

-- ---------------------------------------------------------------------------
-- Offer：身份 + append-only 版本
-- ---------------------------------------------------------------------------
-- ★ 薪资与岗位放在版本行里，不放在身份行里。
--   发出去的 offer 改薪资，业务上是**重新发一次**，不是改那一行——
--   因为对方手里已经有一份纸质/邮件版本，而两份不同的承诺必须都能查到。
CREATE TABLE offer (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requisition_id  bigint      NOT NULL REFERENCES requisition(id),
  candidate_key   varchar(64) NOT NULL,     -- 身份证 hash 或候选人编号，不用姓名
  candidate_name  varchar(64) NOT NULL,
  org_id          bigint      NOT NULL REFERENCES org_unit(id),
  status          varchar(16) NOT NULL DEFAULT 'pending',
  onboard_person  bigint,
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_of_status CHECK (status IN
    ('pending','accepted','rejected','withdrawn','onboarded')),
  -- 入职态必须有对应自然人；非入职态不许有
  CONSTRAINT ck_of_onboard CHECK ((status = 'onboarded') = (onboard_person IS NOT NULL))
);

COMMENT ON COLUMN offer.candidate_key IS
  '候选人标识用不可逆键，不用姓名：同名同姓在千人级招聘里一定会出现，'
  '而"按姓名判断是不是同一个人"没有任何一条判据能兜住。';

CREATE TABLE offer_version (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  offer_id       bigint       NOT NULL REFERENCES offer(id),
  version        int          NOT NULL,
  position       varchar(64)  NOT NULL,
  monthly_amount numeric(12,2) NOT NULL,
  valid_until    date         NOT NULL,
  created_by     varchar(64)  NOT NULL,
  reason         varchar(200) NOT NULL,
  created_at     timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT uk_ov UNIQUE (offer_id, version),
  CONSTRAINT ck_ov_amt    CHECK (monthly_amount > 0),
  CONSTRAINT ck_ov_reason CHECK (length(btrim(reason)) >= 4)
);

CREATE OR REPLACE FUNCTION fn_ov_append_only() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  RAISE EXCEPTION 'E_OFFER_APPEND_ONLY: offer 条款只增不改（改条款请追加新版本）';
END;
$$;

CREATE TRIGGER trg_ov_append_only
  BEFORE UPDATE OR DELETE ON offer_version
  FOR EACH ROW EXECUTE FUNCTION fn_ov_append_only();

CREATE OR REPLACE FUNCTION fn_offer_valid_until(p_offer bigint)
RETURNS date
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT valid_until FROM public.offer_version
   WHERE offer_id = p_offer ORDER BY version DESC LIMIT 1;
$$;

-- 同一候选人不得同时持有两个有效 offer
-- 用部分唯一索引：只约束 pending / accepted，历史状态不参与
CREATE UNIQUE INDEX uk_offer_live_candidate ON offer(candidate_key)
  WHERE status IN ('pending','accepted');


-- ---------------------------------------------------------------------------
-- 额度：按天的口径（该月或更早最近一期）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_hc_quota_asof(p_org bigint, p_on date)
RETURNS int
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT quota FROM public.headcount_budget
   WHERE org_id = p_org AND period <= to_char(p_on, 'YYYY-MM')
   ORDER BY period DESC, version DESC LIMIT 1;
$$;

COMMENT ON FUNCTION fn_hc_quota_asof IS
  '招聘发生在某一天，而额度是按月设的。取"该月或更早最近一期"——'
  '要求那个月恰好有额度会让"每月重设一次"变成隐性前置条件，'
  '而忘了重设的症状是"突然什么都招不了"，看起来像权限问题。';

-- 有效 offer 数（子树）：pending / accepted 且未过期
CREATE OR REPLACE FUNCTION fn_hc_offered(p_org bigint, p_on date)
RETURNS int
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  WITH me AS (SELECT path FROM public.org_unit WHERE id = p_org)
  SELECT count(*)::int
    FROM public.offer o
    JOIN public.org_unit g ON g.id = o.org_id
   WHERE g.path LIKE (SELECT path || '%' FROM me)
     AND o.status IN ('pending','accepted')
     -- ★ 过期靠时点派生。写一个定时任务去翻状态的话，
     --   任务停三天就多发三个 offer，而没人会发现。
     AND public.fn_offer_valid_until(o.id) >= p_on;
$$;

-- 还能发几个 offer
CREATE OR REPLACE FUNCTION fn_hc_can_offer(p_org bigint, p_on date)
RETURNS int
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT COALESCE(public.fn_hc_quota_asof(p_org, p_on), 0)
       - public.fn_hc_allocated(p_org, to_char(p_on,'YYYY-MM'))
       - public.fn_hc_used(p_org, to_char(p_on,'YYYY-MM'))
       - public.fn_hc_offered(p_org, p_on);
$$;

-- ★ 开需求时校验：名额不得超过「还能发」
CREATE OR REPLACE FUNCTION fn_rq_guard() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_can int; v_open int;
BEGIN
  -- ★ 需求只能挂在**叶子组织**（没有下级）上。
  --   给区域发 offer 时，"这个人占哪个门店的编"答不出来；
  --   而如果允许，`fn_hc_can_offer` 会同时扣 allocated（下分给门店的部分）
  --   和 used（子树内的人），同一个编被扣两次，区域的可招数会变成负数。
  --   这不是算错，是这个问题本身没有答案——招聘发生在编制的最末端。
  IF EXISTS (SELECT 1 FROM public.org_unit c
              WHERE c.parent_id = NEW.org_id AND c.is_active) THEN
    RAISE EXCEPTION 'E_RQ_NOT_LEAF: 组织 % 有下级，需求只能挂在门店这类叶子组织上', NEW.org_id;
  END IF;

  v_can := public.fn_hc_can_offer(NEW.org_id, NEW.opened_at);

  -- 同一组织已有未关闭的需求，其名额也要占坑——
  -- 否则可以开十张各 2 人的需求，每张都"单独看没超"。
  SELECT COALESCE(sum(headcount), 0) INTO v_open
    FROM public.requisition
   WHERE org_id = NEW.org_id AND status = 'open';

  IF v_open + NEW.headcount > v_can THEN
    RAISE EXCEPTION 'E_RQ_OVER_HEADCOUNT: % 还能发 % 个 offer（已开需求 % 个），本次要开 % 个',
      NEW.org_id, v_can, v_open, NEW.headcount;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_rq_guard
  BEFORE INSERT ON requisition
  FOR EACH ROW EXECUTE FUNCTION fn_rq_guard();

-- ---------------------------------------------------------------------------
-- 发 offer：名额内 + 需求内 + 编制内
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_offer_issue(
  p_rq bigint, p_candidate_key varchar, p_candidate_name varchar,
  p_position varchar, p_amount numeric, p_valid_until date,
  p_on date, p_by varchar, p_reason varchar
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  rq record; v_live int; v_can int; v_id bigint;
BEGIN
  SELECT * INTO rq FROM public.requisition WHERE id = p_rq FOR UPDATE;
  IF rq.id IS NULL THEN RAISE EXCEPTION 'E_RQ_NOT_FOUND: 需求 % 不存在', p_rq; END IF;
  IF rq.status <> 'open' THEN
    RAISE EXCEPTION 'E_RQ_CLOSED: 需求 % 已是 %，不能再发 offer', p_rq, rq.status;
  END IF;

  -- ① 需求名额
  SELECT count(*) INTO v_live FROM public.offer
   WHERE requisition_id = p_rq AND status IN ('pending','accepted');
  IF v_live >= rq.headcount THEN
    RAISE EXCEPTION 'E_OFFER_OVER_RQ: 需求 % 名额 %，已有 % 个有效 offer', p_rq, rq.headcount, v_live;
  END IF;

  -- ② 编制（含已发出的 offer）
  -- ★ 业务日期显式传入，不取 current_date。
  --   写路径用时钟看起来无害，但它让"这次为什么被拒"永远复现不出来：
  --   同一批数据今天能发、明天发不出，而拒绝信息里没有日期。
  v_can := public.fn_hc_can_offer(rq.org_id, p_on);
  IF v_can <= 0 THEN
    RAISE EXCEPTION 'E_OFFER_OVER_HC: % 已无可招编制（额度−已下分−已入职−已发 offer = %）',
      rq.org_id, v_can;
  END IF;

  INSERT INTO public.offer(requisition_id, candidate_key, candidate_name, org_id)
  VALUES (p_rq, p_candidate_key, p_candidate_name, rq.org_id)
  RETURNING id INTO v_id;

  INSERT INTO public.offer_version(offer_id, version, position, monthly_amount,
                                   valid_until, created_by, reason)
  VALUES (v_id, 1, p_position, p_amount, p_valid_until, p_by, p_reason);

  RETURN v_id;
END;
$$;

-- 改条款 = 追加版本（不是改那一行）
CREATE OR REPLACE FUNCTION fn_offer_revise(
  p_offer bigint, p_position varchar, p_amount numeric, p_valid_until date,
  p_by varchar, p_reason varchar
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_status varchar(16); v_ver int;
BEGIN
  SELECT status INTO v_status FROM public.offer WHERE id = p_offer FOR UPDATE;
  IF v_status IS NULL THEN RAISE EXCEPTION 'E_OFFER_NOT_FOUND: %', p_offer; END IF;
  IF v_status NOT IN ('pending','accepted') THEN
    RAISE EXCEPTION 'E_OFFER_NOT_LIVE: offer % 已是 %，不可修改条款', p_offer, v_status;
  END IF;

  SELECT COALESCE(max(version),0) + 1 INTO v_ver
    FROM public.offer_version WHERE offer_id = p_offer;

  INSERT INTO public.offer_version(offer_id, version, position, monthly_amount,
                                   valid_until, created_by, reason)
  VALUES (p_offer, v_ver, p_position, p_amount, p_valid_until, p_by, p_reason);
  RETURN v_ver;
END;
$$;

-- ---------------------------------------------------------------------------
-- 入职：承诺变成事实的那一刻，三个字段必须一字不差
-- ---------------------------------------------------------------------------
-- ★ 这是全套系统里"承诺 → 事实"的唯一关卡。入职后写的三条记录
--   （任职、成本组织归属、月薪标准）必须与 offer 的最后版本一致：
--   它们本来就是同一个承诺的三个面。任何一处不一致，都会在第一次算薪时
--   变成"这人工资不对"，而那时已经发了。
CREATE OR REPLACE FUNCTION fn_offer_onboard(
  p_offer bigint, p_person bigint, p_hire_date date, p_legal_entity bigint, p_by varchar
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  o record; v record; v_emp bigint; v_ver int;
BEGIN
  SELECT * INTO o FROM public.offer WHERE id = p_offer FOR UPDATE;
  IF o.id IS NULL THEN RAISE EXCEPTION 'E_OFFER_NOT_FOUND: %', p_offer; END IF;
  IF o.status NOT IN ('pending','accepted') THEN
    RAISE EXCEPTION 'E_OFFER_NOT_LIVE: offer % 已是 %，不可入职', p_offer, o.status;
  END IF;

  SELECT * INTO v FROM public.offer_version WHERE offer_id = p_offer
   ORDER BY version DESC LIMIT 1;
  IF v.valid_until < p_hire_date THEN
    RAISE EXCEPTION 'E_OFFER_EXPIRED: offer % 有效期至 %，入职日 %',
      p_offer, v.valid_until, p_hire_date;
  END IF;

  INSERT INTO public.employment(person_id, legal_entity_id, hire_date)
  VALUES (p_person, p_legal_entity, p_hire_date)
  RETURNING id INTO v_emp;

  -- 成本组织：与 offer 上的一致，不另填
  INSERT INTO public.employee_org_assignment(employee_id, dim_code, org_id, valid_from)
  VALUES (p_person, 'cost_org', o.org_id, p_hire_date);

  -- 月薪：与 offer 上的一致，不另填
  INSERT INTO public.salary_standard(employment_id, monthly_amount, effective_from)
  VALUES (v_emp, v.monthly_amount, p_hire_date);

  UPDATE public.offer SET status='onboarded', onboard_person=p_person WHERE id = p_offer;

  -- 留一条版本，说明"这是入职确认"，而不是把 offer 版本改掉
  SELECT COALESCE(max(version),0) + 1 INTO v_ver
    FROM public.offer_version WHERE offer_id = p_offer;
  INSERT INTO public.offer_version(offer_id, version, position, monthly_amount,
                                   valid_until, created_by, reason)
  VALUES (p_offer, v_ver, v.position, v.monthly_amount, v.valid_until, p_by,
          '入职确认：按本版条款落任职/归属/月薪');

  RETURN v_emp;
END;
$$;

-- 状态不可回退：入职后回到 pending 就等于让这个编可以再招一次
CREATE OR REPLACE FUNCTION fn_offer_no_regress() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF OLD.status = 'onboarded' AND NEW.status <> 'onboarded' THEN
    RAISE EXCEPTION 'E_OFFER_ONBOARDED: offer % 已入职，状态不可回退（回退＝这个编可以再招一次）',
      OLD.id;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_offer_no_regress
  BEFORE UPDATE ON offer
  FOR EACH ROW EXECUTE FUNCTION fn_offer_no_regress();
