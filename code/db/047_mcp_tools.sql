-- ============================================================================
-- 047_mcp_tools.sql · 开放层的第二层：只读工具也要留痕，也要过同一道门
-- ----------------------------------------------------------------------------
-- 010 只管住了**写**：没有 plan 就写不进去。但只读那半边一直没有规矩，
-- 而只读恰恰是 AI 用得最多的部分。三个具体的洞：
--
--   ① **只读不落审计**：AI 读了 200 条工资条，`sys_mcp_audit` 里一条记录都没有。
--      "谁调过什么"这个问题，对读操作是空白 —— 而读正是泄露的形态。
--   ② **只读可能绕过掩码**：开放层是同一份数据的**第二个门**。列表页掩了、
--      MCP 没掩，那掩码就只是"页面上的装饰"。
--   ③ **只读可能绕过行闸**：同理，AI 拿到的行数必须与这个人自己看到的行数一致。
--
-- 所以这一层不再自己写查询：只读工具**复用同一个服务函数**
-- （`attendance.listDaily` / `payroll.listSlips` / `headcount.view` /
--  `leave.getBalance`）。掩码与行闸只有一份实现，开放层没有第二套机会写错。
--
-- 另加一个**写**工具的示范：`headcount_set`。它证明写工具不是只能有一个，
-- 而多一个的门槛不是"再写一遍权限"，是**再写一遍预览**——
-- 预览必须能说清"改前 / 改后 / 会不会超编"，否则 plan 就只是个橡皮图章。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 只读调用的审计（写调用的审计在 fn_mcp_execute 里，因为写要绑 plan）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_mcp_audit_read(
  p_tool varchar, p_actor varchar, p_affected int
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_id bigint;
BEGIN
  -- ★ 只读也记，`shift_run = false`。不记的话，"AI 读过什么"永远答不出来，
  --   而泄露正是通过读发生的。
  INSERT INTO public.sys_mcp_audit(tool_name, actor, shift_run, affected)
  VALUES (p_tool, p_actor, false, p_affected)
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_mcp_audit_read IS
  '只读工具的审计落库（shift_run=false）。读也要留痕 —— 泄露是通过读发生的。';

-- ---------------------------------------------------------------------------
-- 2. 各账号的开放层用量（限流与"谁在猛读"共用一处）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW v_mcp_usage AS
SELECT actor,
       count(*) FILTER (WHERE NOT shift_run) AS reads,
       count(*) FILTER (WHERE shift_run)     AS writes,
       max(called_at)                        AS last_call_at
  FROM sys_mcp_audit
 GROUP BY actor;

COMMENT ON VIEW v_mcp_usage IS
  '按调用者统计读写次数与最后调用时间。读多写少的形态与"有人在爬"的形态要靠它区分。';

