-- ============================================================================
-- 026_performance.sql · 绩效：周期 / 结果 / 封存后进算薪
-- ----------------------------------------------------------------------------
-- 这一块和前十个模块不同：**它要动算薪**。而算薪那条链路上已经有
-- 封账冻结、勾稽、累计预扣三道保护，任何新东西接进来都必须先被约束住，
-- 否则它会成为那条链上唯一一个"算完还能改"的输入。
--
-- 四条先行规则：
--
-- ① **绩效周期必须封存才能参与算薪。**
--    未封存就参与，等于按一份还会变的分发钱。而"算完再调分"这件事
--    在绩效季是常态——调完之后工资已发，绩效表也"看起来对"。
--
-- ② **系数在封存时固化，不在读取时按当前方案算。**
--    和 `snap_on_duty_break_basis` 同一条：分数与系数是**当时的事实**。
--    读取时现算的话，改一次方案会把去年已发过钱的绩效系数也改掉。
--
-- ③ **未参与考核必须是显式状态，不是 NULL。**
--    NULL 会让"没考核"与"考核了但没录分"同形，而两者处置相反：
--    前者不该发绩效工资，后者是数据缺失、要补。
--
-- ④ **强制分布只报不拦。**
--    拦的后果是有人去调分——而调过的分与真分在表里同形，看不出来。
--    所以做成"可查的超限清单 + 一条告警"，而不是一道拒绝。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 方案（版本化）+ 档位
-- ---------------------------------------------------------------------------
CREATE TABLE perf_scheme (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version        int          NOT NULL,
  name           varchar(64)  NOT NULL,
  effective_from date         NOT NULL,
  -- 绩效工资 = 月薪 × 系数。系数口径写在这里，不散在代码里。
  CONSTRAINT uk_ps UNIQUE (version),
  CONSTRAINT ck_ps_ver CHECK (version >= 1)
);

CREATE TABLE perf_grade (
  scheme_id bigint       NOT NULL REFERENCES perf_scheme(id),
  grade     varchar(8)   NOT NULL,
  min_score numeric(5,2) NOT NULL,
  max_score numeric(5,2) NOT NULL,
  factor    numeric(6,4) NOT NULL,
  -- 是否参与强制分布，以及目标占比（NULL = 不参与）
  target_pct numeric(5,2),
  PRIMARY KEY (scheme_id, grade),
  CONSTRAINT ck_pg_range  CHECK (max_score >= min_score),
  CONSTRAINT ck_pg_factor CHECK (factor >= 0),
  CONSTRAINT ck_pg_pct    CHECK (target_pct IS NULL OR (target_pct > 0 AND target_pct <= 100))
);

CREATE OR REPLACE FUNCTION fn_perf_scheme_asof(p_on date)
RETURNS bigint
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE v bigint;
BEGIN
  SELECT id INTO v FROM public.perf_scheme
   WHERE effective_from <= p_on ORDER BY effective_from DESC, version DESC LIMIT 1;
  IF v IS NULL THEN
    RAISE EXCEPTION 'E_PERF_NO_SCHEME: % 之前没有生效的绩效方案', p_on;
  END IF;
  RETURN v;
END;
$$;

CREATE OR REPLACE FUNCTION fn_perf_grade_of(p_scheme bigint, p_score numeric)
RETURNS varchar(8)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE v varchar(8);
BEGIN
  SELECT grade INTO v FROM public.perf_grade
   WHERE scheme_id = p_scheme AND p_score >= min_score AND p_score <= max_score
   ORDER BY min_score DESC LIMIT 1;
  IF v IS NULL THEN
    -- ★ 分数落在档位之外必须报错，不能"最接近的那一档"。
    --   兜底到最近档会让 200 分和 100 分拿同一个系数，而报表上看不出区别。
    RAISE EXCEPTION 'E_PERF_SCORE_OUT_OF_RANGE: 方案 % 没有覆盖分数 % 的档位', p_scheme, p_score;
  END IF;
  RETURN v;
END;
$$;

-- ---------------------------------------------------------------------------
-- 周期
-- ---------------------------------------------------------------------------
CREATE TABLE perf_cycle (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          varchar(32) NOT NULL UNIQUE,
  name          varchar(64) NOT NULL,
  period_from   date        NOT NULL,
  period_to     date        NOT NULL,
  -- ★ 这个周期喂哪个发薪期。一列一个关系，避免"从日期推算"——
  --   推算会在跨月周期上给出两个答案，而两个都说得通。
  pay_period    varchar(7)  NOT NULL UNIQUE,
  status        varchar(16) NOT NULL DEFAULT 'open',
  sealed_at     timestamptz,
  sealed_by     varchar(64),
  scheme_id     bigint      REFERENCES perf_scheme(id),
  CONSTRAINT ck_pc_span   CHECK (period_to >= period_from),
  CONSTRAINT ck_pc_status CHECK (status IN ('open','sealed')),
  CONSTRAINT ck_pc_sealed CHECK ((status = 'sealed') = (sealed_at IS NOT NULL AND scheme_id IS NOT NULL)),
  CONSTRAINT ck_pc_payper CHECK (pay_period ~ '^\d{4}-(0[1-9]|1[0-2])$')
);

COMMENT ON COLUMN perf_cycle.pay_period IS
  '一列一个关系。靠日期推算"这个绩效周期该进哪个月工资"在跨月周期上会给出两个答案，'
  '而两个都说得通——于是不同的人会算出不同的数，且都"有依据"。';

-- ---------------------------------------------------------------------------
-- 结果
-- ---------------------------------------------------------------------------
CREATE TABLE perf_result (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id    bigint      NOT NULL REFERENCES perf_cycle(id),
  employee_id bigint      NOT NULL,
  state       varchar(16) NOT NULL DEFAULT 'scored',
  score       numeric(5,2),
  grade       varchar(8),
  -- 封存时固化的系数。未封存前为 NULL —— 它此刻还不该有值。
  factor      numeric(6,4),
  note        varchar(200),
  CONSTRAINT uk_pr UNIQUE (cycle_id, employee_id),
  CONSTRAINT ck_pr_state CHECK (state IN ('scored','excluded')),
  -- ★ ③：两种状态在字段上就不同形，不靠读 note 判断
  CONSTRAINT ck_pr_scored   CHECK ((state = 'scored')   = (score IS NOT NULL)),
  CONSTRAINT ck_pr_grade    CHECK ((state = 'scored')   = (grade IS NOT NULL)),
  -- 未参与考核必须写原因，空白不算
  CONSTRAINT ck_pr_excluded CHECK (state <> 'excluded'
                                   OR (note IS NOT NULL AND length(btrim(note)) >= 4)),
  -- 封存前的 factor 必须为空：先有值再有分，等于系数在分数之前就定了
  CONSTRAINT ck_pr_factor_pre CHECK (factor IS NULL OR score IS NOT NULL)
);

-- ★ 封存后结果不可改（改分 / 删行 / 换档）
CREATE OR REPLACE FUNCTION fn_pr_frozen() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_status varchar(16);
BEGIN
  SELECT status INTO v_status FROM public.perf_cycle
   WHERE id = COALESCE(NEW.cycle_id, OLD.cycle_id);
  IF v_status = 'sealed' THEN
    RAISE EXCEPTION 'E_PERF_SEALED: 绩效周期已封存，结果不可增删改';
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$;

CREATE TRIGGER trg_pr_frozen
  BEFORE INSERT OR UPDATE OR DELETE ON perf_result
  FOR EACH ROW EXECUTE FUNCTION fn_pr_frozen();

-- ---------------------------------------------------------------------------
-- 封存：把系数固化下来
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_perf_seal(p_cycle bigint, p_by varchar)
RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v record; v_scheme bigint; n int := 0;
BEGIN
  SELECT * INTO v FROM public.perf_cycle WHERE id = p_cycle FOR UPDATE;
  IF v.id IS NULL THEN RAISE EXCEPTION 'E_PERF_NO_CYCLE: %', p_cycle; END IF;
  IF v.status = 'sealed' THEN RAISE EXCEPTION 'E_PERF_ALREADY_SEALED: 周期 % 已封存', p_cycle; END IF;

  -- 方案取「周期结束日」生效的那一版：分数是在那个时点评的
  v_scheme := public.fn_perf_scheme_asof(v.period_to);

  UPDATE public.perf_result
     SET factor = (SELECT g.factor FROM public.perf_grade g
                    WHERE g.scheme_id = v_scheme AND g.grade = perf_result.grade)
   WHERE cycle_id = p_cycle AND state = 'scored' AND factor IS NULL;
  GET DIAGNOSTICS n = ROW_COUNT;

  IF EXISTS (SELECT 1 FROM public.perf_result
              WHERE cycle_id = p_cycle AND state = 'scored' AND factor IS NULL) THEN
    RAISE EXCEPTION 'E_PERF_FACTOR_MISSING: 周期 % 有已评分但无法定档的行（档位不在方案里）', p_cycle;
  END IF;

  UPDATE public.perf_cycle
     SET status='sealed', sealed_at=clock_timestamp(), sealed_by=p_by, scheme_id=v_scheme
   WHERE id = p_cycle;

  RETURN n;
END;
$$;

CREATE OR REPLACE FUNCTION fn_perf_no_reopen() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF OLD.status = 'sealed' AND NEW.status = 'open' THEN
    RAISE EXCEPTION 'E_PERF_REOPEN: 绩效周期 % 不可解封（解封后算过的工资与绩效对不上）', OLD.id;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_perf_no_reopen
  BEFORE UPDATE ON perf_cycle
  FOR EACH ROW EXECUTE FUNCTION fn_perf_no_reopen();

-- ---------------------------------------------------------------------------
-- 算薪读它：只读已封存
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_perf_factor(p_employee bigint, p_pay_period varchar)
RETURNS numeric
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT r.factor
    FROM public.perf_result r
    JOIN public.perf_cycle  c ON c.id = r.cycle_id
   WHERE r.employee_id = p_employee
     AND c.pay_period = p_pay_period
     AND c.status = 'sealed'
     AND r.state = 'scored';
$$;

COMMENT ON FUNCTION fn_perf_factor IS
  '未封存返回 NULL，不返回 0。返回 0 会让"这个周期还没封"与'
  '"这个人绩效系数 0"同形，而前者是流程问题、后者是发钱问题。';

-- 强制分布：只报不拦
CREATE OR REPLACE FUNCTION fn_perf_distribution(p_cycle bigint)
RETURNS TABLE (grade varchar(8), n int, pct numeric, target_pct numeric, over_by numeric)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  WITH t AS (
    SELECT count(*)::numeric AS total FROM public.perf_result
     WHERE cycle_id = p_cycle AND state = 'scored'
  ), d AS (
    SELECT r.grade, count(*)::int AS n
      FROM public.perf_result r
     WHERE r.cycle_id = p_cycle AND r.state = 'scored'
     GROUP BY r.grade
  )
  SELECT d.grade, d.n,
         round(100.0 * d.n / NULLIF((SELECT total FROM t), 0), 2),
         g.target_pct,
         round(100.0 * d.n / NULLIF((SELECT total FROM t), 0) - g.target_pct, 2)
    FROM d JOIN public.perf_cycle c ON c.id = p_cycle
    LEFT JOIN public.perf_grade g ON g.scheme_id = COALESCE(c.scheme_id, public.fn_perf_scheme_asof(c.period_to))
                                 AND g.grade = d.grade
   ORDER BY d.grade;
$$;

COMMENT ON FUNCTION fn_perf_distribution IS
  '只报不拦。拦的后果是有人去调分——而调过的分与真分在表里同形，看不出来。'
  '超限这件事必须留在纸面上，才有机会被人讨论。';
