-- ============================================================================
-- 016_attendance_close.sql · 考勤封账 → 算薪的时间边界
-- ----------------------------------------------------------------------------
-- 这是整套系统里**时间语义最硬的一段**：同一条考勤人日，在封账前和封账后
-- 是两个不同的东西——不是"权限不同"，是"它还算不算数"不同。
--
-- 四件必须同时成立，少一件就漏：
--   ① 封账前可变、封账后不可变 —— 靠触发器（但触发器可以被 DISABLE，所以有 ②）
--   ② 封账时冻结一个「数」 —— 不只是状态位。否则事后无法证明"封账那天数据是对的"
--   ③ 封账 → 开 是绕过路径 —— 改状态、删封账行，两条都要堵
--   ④ 封账后的修正 = 补账记录，不是改历史 —— 结构上不允许改历史
--
-- 关于 ② 为什么必须存在（这是本文件的核心）：
--   只有触发器时，"封账后没人改过"是一个**没有证据的断言**：
--   ALTER TABLE ... DISABLE TRIGGER 一句就能改，而改完一切看起来正常。
--   只有快照摘要时，"改过的都跑不掉"但改本身不会被拦住，且要等下次校验才知道。
--   两条合起来才是：**拦得住，且拦不住的也查得出**。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 封账记录
-- ---------------------------------------------------------------------------
CREATE TABLE attendance_close (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id        bigint       NOT NULL,
  period          varchar(7)   NOT NULL,          -- 'YYYY-MM'
  status          varchar(16)  NOT NULL DEFAULT 'open',

  closed_at       timestamptz,
  closed_by       varchar(64),

  -- 封账当时看到的三个数。不是统计，是**证据**：它证明"那一刻数据长这样"。
  snap_rows       int,
  snap_hours      numeric(14,2),
  snap_digest     text,

  CONSTRAINT ck_ac_period CHECK (period ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  CONSTRAINT ck_ac_status CHECK (status IN ('open','closed')),
  -- ★ 状态与三个证据列同生同灭。只加列不写这条，会留下"已封账但没快照"的
  --   一格——而那一格的封账是不可证的，与没封账在报告上同形。
  CONSTRAINT ck_ac_closed CHECK (
       (status = 'closed')
       = (closed_at IS NOT NULL AND snap_digest IS NOT NULL
          AND snap_rows IS NOT NULL AND snap_hours IS NOT NULL)
  ),
  UNIQUE (store_id, period)
);

COMMENT ON COLUMN attendance_close.snap_digest IS
  'md5(string_agg(id:work_hours ORDER BY id))。它存在的唯一理由：'
  '触发器可以被 DISABLE，而摘要不会。';

-- ---------------------------------------------------------------------------
-- 摘要计算（确定性：ORDER BY id，与物理顺序无关）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_att_snapshot(p_store bigint, p_period varchar)
RETURNS TABLE (n int, hours numeric, digest text)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT count(*)::int,
         COALESCE(sum(a.work_hours), 0)::numeric(14,2),
         md5(COALESCE(string_agg(a.id::text || ':' || a.work_hours::text, '|' ORDER BY a.id), ''))
    FROM public.attendance_daily_store a
   WHERE a.store_id = p_store
     AND to_char(a.work_date, 'YYYY-MM') = p_period;
$$;

-- ---------------------------------------------------------------------------
-- 封账 / 反查
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_att_close(p_store bigint, p_period varchar, p_by varchar)
RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE s record; v_status varchar(16);
BEGIN
  SELECT c.status INTO v_status FROM public.attendance_close c
   WHERE c.store_id = p_store AND c.period = p_period FOR UPDATE;

  IF v_status = 'closed' THEN
    RAISE EXCEPTION 'E_ATT_ALREADY_CLOSED: % 店 % 已封账', p_store, p_period;
  END IF;

  SELECT * INTO s FROM public.fn_att_snapshot(p_store, p_period);

  -- ★ 空期间不许封账。封一个空的期间，日后填数据时"已封账"会挡住它，
  --   而那时的第一反应是解封 —— 一个本可以避免的绕过。
  IF s.n = 0 THEN
    RAISE EXCEPTION 'E_ATT_CLOSE_EMPTY: % 店 % 没有任何考勤行，不允许封账', p_store, p_period;
  END IF;

  INSERT INTO public.attendance_close(store_id, period, status, closed_at, closed_by,
                                      snap_rows, snap_hours, snap_digest)
  VALUES (p_store, p_period, 'closed', clock_timestamp(), p_by, s.n, s.hours, s.digest)
  ON CONFLICT (store_id, period) DO UPDATE
    SET status='closed', closed_at=clock_timestamp(), closed_by=p_by,
        snap_rows=s.n, snap_hours=s.hours, snap_digest=s.digest;
END;
$$;

-- 校验：重算摘要，与封账时冻结的那份比。返回不一致的行（必须为空）。
CREATE OR REPLACE FUNCTION fn_att_verify(p_store bigint, p_period varchar)
RETURNS TABLE (snap_rows int, now_rows int, snap_digest text, now_digest text)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT c.snap_rows, s.n, c.snap_digest, s.digest
    FROM public.attendance_close c, public.fn_att_snapshot(p_store, p_period) s
   WHERE c.store_id = p_store AND c.period = p_period AND c.status = 'closed'
     AND (c.snap_digest IS DISTINCT FROM s.digest
          OR c.snap_rows  IS DISTINCT FROM s.n
          OR c.snap_hours IS DISTINCT FROM s.hours);
$$;

-- ---------------------------------------------------------------------------
-- 防线 ①：封账后不可增删改考勤
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_ads_frozen() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_store bigint; v_period varchar(7); v_status varchar(16);
BEGIN
  v_store  := COALESCE(NEW.store_id, OLD.store_id);
  v_period := to_char(COALESCE(NEW.work_date, OLD.work_date), 'YYYY-MM');

  SELECT c.status INTO v_status FROM public.attendance_close c
   WHERE c.store_id = v_store AND c.period = v_period;

  IF v_status = 'closed' THEN
    RAISE EXCEPTION 'E_ATT_CLOSED: % 店 % 已封账，考勤不可增删改（封账后修正请走补账）',
      v_store, v_period;
  END IF;

  RETURN COALESCE(NEW, OLD);
END;
$$;

CREATE TRIGGER trg_ads_frozen
  BEFORE INSERT OR UPDATE OR DELETE ON attendance_daily_store
  FOR EACH ROW EXECUTE FUNCTION fn_ads_frozen();

-- ---------------------------------------------------------------------------
-- 防线 ②：两条绕过路径
-- ---------------------------------------------------------------------------
-- ③-A 封账行改回 open：每一步都是合法 UPDATE
-- ③-B **删掉封账行**。这一条比 A 更隐蔽——因为"没有封账记录"与"从未封账"
--      在库里同形，而门禁判据是 NOT EXISTS(closed)，删掉一行就等于解封，
--      且不留任何"这里曾经封过"的痕迹。
CREATE OR REPLACE FUNCTION fn_ac_no_reopen() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.status = 'closed' THEN
      RAISE EXCEPTION 'E_ATT_CLOSE_ROW_DELETED: 不允许删除封账记录（% 店 %）；'
        '删掉它等于解封，而且不留痕迹', OLD.store_id, OLD.period;
    END IF;
    RETURN OLD;
  END IF;

  IF OLD.status = 'closed' AND NEW.status = 'open' THEN
    RAISE EXCEPTION 'E_ATT_REOPEN: 不允许解封（% 店 %）；封账后修正请走补账',
      OLD.store_id, OLD.period;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_ac_no_reopen
  BEFORE UPDATE OR DELETE ON attendance_close
  FOR EACH ROW EXECUTE FUNCTION fn_ac_no_reopen();

-- ---------------------------------------------------------------------------
-- 补账：封账后唯一的修正通道
-- ---------------------------------------------------------------------------
-- ★ 结构上不允许改历史：apply_period 必须晚于 work_date 所在期间。
--   这条 CHECK 不是"提醒"，是"这条记录无法表达追溯修改"——
--   它没有那个字段，也就没有那条路径。
CREATE TABLE attendance_adjustment (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id  bigint       NOT NULL,
  store_id     bigint       NOT NULL,
  work_date    date         NOT NULL,
  hours_delta  numeric(6,2) NOT NULL,
  apply_period varchar(7)   NOT NULL,
  reason       varchar(200) NOT NULL,
  created_by   varchar(64)  NOT NULL,
  created_at   timestamptz  NOT NULL DEFAULT now(),

  CONSTRAINT ck_aa_delta CHECK (hours_delta <> 0),
  CONSTRAINT ck_aa_period CHECK (apply_period ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  -- ★ 补账只能往后。写成 `<>` 就允许往前，而往前就是改历史换了个名字。
  CONSTRAINT ck_aa_forward CHECK (apply_period > to_char(work_date, 'YYYY-MM')),
  -- ★ 空白理由不行。理由可以是"门店报错"，但不能是空串——
  --   而空串能通过 NOT NULL，这不是理论风险：表单里那个必填框能被敲一个空格。
  CONSTRAINT ck_aa_reason CHECK (length(btrim(reason)) >= 4)
);

COMMENT ON TABLE attendance_adjustment IS
  '封账后唯一的修正通道。与原记录的关系是「另起一笔」，不是「改那一笔」——'
  '因为发薪日已经按当时的数发过钱，而"当时我们以为的"必须还能查出来。';

-- ---------------------------------------------------------------------------
-- 算薪前置门：本期有考勤的门店-期间必须全部封账
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_att_unclosed(p_period varchar)
RETURNS TABLE (store_id bigint, why text)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT DISTINCT a.store_id,
         CASE WHEN c.id IS NULL THEN '从未封账'
              ELSE '已建期间但未封账' END
    FROM public.attendance_daily_store a
    LEFT JOIN public.attendance_close c
      ON c.store_id = a.store_id AND c.period = p_period AND c.status = 'closed'
   WHERE to_char(a.work_date, 'YYYY-MM') = p_period
     AND c.id IS NULL
   ORDER BY 1;
$$;

COMMENT ON FUNCTION fn_att_unclosed IS
  '返回本期「有考勤但未封账」的门店清单。算薪门禁读它；'
  '**清单本身要被报出来**——否则"本期没有考勤"与"考勤没封账"在算薪结果上同形。';
