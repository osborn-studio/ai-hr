-- ===========================================================================
-- 037_exception.sql · 例外必须有退出条件
-- ---------------------------------------------------------------------------
-- 这套系统里已经出现过几次「临时放开」，每次的形式不同：
--
--   · 超编走审批通道（`HEADCOUNT_OVER = require_approval`）
--   · 检查登记表的豁免（`waived_period/waived_by/waived_reason` 三件套）
--   · 补账只能往后（`apply_period > 工作月份`）
--
-- 它们的共同点：**例外是允许的，但必须带一个"什么时候结束"**。
-- 没有退出条件的例外不是例外，是**改了规矩而没人说**。
--
-- 四条判断：
--
-- ① `expires_at` NOT NULL。 「永久例外」这个说法本身就是矛盾的：
--    它要么已经变成常态（那就该改规矩），要么是一笔没人认领的债。
--
-- ② 期限有上限，按类型给（`default_ttl_days` / `max_ttl_days`）。
--    没有上限的话，"先给一年"会成为默认值，而一年后没人记得。
--
-- ③ 关闭 = 写 `closed_at/closed_by/close_reason`，**不是删行**。
--    删行之后，"这里曾经有过一个例外"就消失了 —— 那正是复盘要看的东西。
--
-- ④ 到期必须**看得见**（`v_exception_overdue`）。靠人记的到期日等于没有到期日。
-- ===========================================================================

CREATE TABLE sys_exception_kind (
  code            varchar(32) PRIMARY KEY,
  name            varchar(128) NOT NULL,
  -- 默认期限与上限（天）。上限是硬约束：填超了直接拒，不是截断到上限
  default_ttl_days int NOT NULL,
  max_ttl_days     int NOT NULL,
  -- 是否需要指定责任人：几乎总是需要，但"系统自动重试"这类可能不需要
  requires_owner  boolean NOT NULL DEFAULT true,
  severity        varchar(8) NOT NULL DEFAULT 'warn',
  CONSTRAINT ck_sek_ttl   CHECK (default_ttl_days > 0 AND max_ttl_days >= default_ttl_days),
  CONSTRAINT ck_sek_sev   CHECK (severity IN ('info','warn','block'))
);

