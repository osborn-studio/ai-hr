CREATE TABLE exception_registry (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind_code     varchar(32) NOT NULL REFERENCES sys_exception_kind(code),
  subject_type  varchar(32) NOT NULL,       -- leave_request / payslip / org_unit …
  subject_id    bigint      NOT NULL,
  reason        varchar(400) NOT NULL,
  owner         varchar(64),                -- 责任人（kind.requires_owner 为真时必填）
  created_at    timestamptz NOT NULL DEFAULT clock_timestamp(),
  expires_at    timestamptz NOT NULL,       -- ★ 无默认值、不许为 NULL
  closed_at     timestamptz,
  closed_by     varchar(64),
  close_reason  varchar(400),
  CONSTRAINT ck_ex_reason  CHECK (length(btrim(reason)) >= 4),
  CONSTRAINT ck_ex_close   CHECK ((closed_at IS NULL) = (closed_by IS NULL)
                                  AND (closed_at IS NULL) = (close_reason IS NULL)),
  CONSTRAINT ck_ex_close_r CHECK (close_reason IS NULL OR length(btrim(close_reason)) >= 4),
  -- 关闭时刻不能早于创建（时间倒退会让"存在了多久"变成负数）
  CONSTRAINT ck_ex_order   CHECK (closed_at IS NULL OR closed_at >= created_at)
);

CREATE INDEX ix_ex_open ON exception_registry(expires_at) WHERE closed_at IS NULL;
CREATE INDEX ix_ex_subject ON exception_registry(subject_type, subject_id);

-- ---------------------------------------------------------------------------
-- 建例外：三条判据（类型存在 / 必须有责任人 / 期限不超上限）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_exception_open(
  p_kind varchar, p_subject_type varchar, p_subject_id bigint,
  p_reason varchar, p_owner varchar, p_ttl_days int DEFAULT NULL
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE k public.sys_exception_kind%ROWTYPE; v_ttl int; v_id bigint;
BEGIN
  SELECT * INTO k FROM public.sys_exception_kind WHERE code = p_kind;
  IF k.code IS NULL THEN
    RAISE EXCEPTION 'E_EX_KIND: 例外类型 % 未登记（未登记的类型没有期限上限，等于永久例外）', p_kind;
  END IF;

  IF k.requires_owner AND (p_owner IS NULL OR length(btrim(p_owner)) < 2) THEN
    RAISE EXCEPTION 'E_EX_NO_OWNER: 类型 % 必须指定责任人（没有责任人的例外没人会去关）', p_kind;
  END IF;

  v_ttl := COALESCE(p_ttl_days, k.default_ttl_days);
  IF v_ttl <= 0 THEN
    RAISE EXCEPTION 'E_EX_TTL: 期限必须为正天数（收到 %）', v_ttl;
  END IF;
  IF v_ttl > k.max_ttl_days THEN
    RAISE EXCEPTION 'E_EX_TTL_TOO_LONG: % 最长 % 天，本次要 % 天', p_kind, k.max_ttl_days, v_ttl;
  END IF;

  INSERT INTO public.exception_registry(kind_code, subject_type, subject_id,
                                        reason, owner, expires_at)
  VALUES (p_kind, p_subject_type, p_subject_id, p_reason, p_owner,
          clock_timestamp() + make_interval(days => v_ttl))
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_exception_open IS
  '开一个例外。期限必填且不得超过类型上限 —— 「永久例外」要么已经该改规矩，'
  '要么是一笔没人认领的债，两种都不该躺在表里。';

-- ---------------------------------------------------------------------------
-- 关闭：写三件套，不删行
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_exception_close(
  p_id bigint, p_by varchar, p_reason varchar
) RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_closed timestamptz;
BEGIN
  SELECT closed_at INTO v_closed FROM public.exception_registry WHERE id = p_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'E_EX_NOT_FOUND: 例外 % 不存在', p_id;
  END IF;
  IF v_closed IS NOT NULL THEN
    RAISE EXCEPTION 'E_EX_ALREADY_CLOSED: 例外 % 已于 % 关闭', p_id, v_closed;
  END IF;
  IF p_by IS NULL OR length(btrim(p_by)) < 2 THEN
    RAISE EXCEPTION 'E_EX_NO_OWNER: 关闭必须写操作人';
  END IF;

  UPDATE public.exception_registry
     SET closed_at = clock_timestamp(), closed_by = p_by, close_reason = p_reason
   WHERE id = p_id;
END;
$$;

-- 删除必须被拒：删行会让「这里曾经有过一个例外」消失
CREATE OR REPLACE FUNCTION fn_ex_no_delete() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  RAISE EXCEPTION 'E_EX_NO_DELETE: 例外不可删除（关闭请用 fn_exception_close）';
END;
$$;

CREATE TRIGGER trg_ex_no_delete BEFORE DELETE ON exception_registry
  FOR EACH ROW EXECUTE FUNCTION fn_ex_no_delete();

-- 建出来就是过期的不算例外；已关闭的不可重开
CREATE OR REPLACE FUNCTION fn_ex_guard() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF NEW.expires_at <= NEW.created_at THEN
    RAISE EXCEPTION 'E_EX_TTL: 到期时间必须晚于创建时间';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_ex_guard BEFORE INSERT ON exception_registry
  FOR EACH ROW EXECUTE FUNCTION fn_ex_guard();

-- ---------------------------------------------------------------------------
-- 到期必须看得见
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW v_exception_overdue AS
  SELECT e.id, e.kind_code, k.name AS kind_name, k.severity,
         e.subject_type, e.subject_id, e.owner, e.expires_at,
         date_part('day', clock_timestamp() - e.expires_at)::int AS overdue_days
    FROM exception_registry e
    JOIN sys_exception_kind k ON k.code = e.kind_code
   WHERE e.closed_at IS NULL
     AND e.expires_at <= clock_timestamp()
   ORDER BY k.severity DESC, e.expires_at;

COMMENT ON VIEW v_exception_overdue IS
  '到期未关闭的例外。只靠人记到期日的机制等于没有到期日 —— '
  '这张视图是"例外真的会结束"的唯一证据。';

-- 当前的（未关闭且未过期）例外：给业务查询用
CREATE OR REPLACE VIEW v_exception_active AS
  SELECT e.*, k.name AS kind_name, k.severity
    FROM exception_registry e
    JOIN sys_exception_kind k ON k.code = e.kind_code
   WHERE e.closed_at IS NULL AND e.expires_at > clock_timestamp();

