-- ---------------------------------------------------------------------------
-- 3. 结算单
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS severance_settlement (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employment_id      bigint NOT NULL REFERENCES employment(id),
  person_id          bigint NOT NULL,
  leave_date         date   NOT NULL,
  reason_code        varchar(24) NOT NULL REFERENCES severance_reason(code),
  city               varchar(32) NOT NULL DEFAULT '上海',

  service_months     int    NOT NULL,     -- 本单位工作月数（完整月）
  service_days_rest  int    NOT NULL DEFAULT 0,  -- 不足一月的天数
  n_months           numeric(5,2) NOT NULL,      -- 补偿月数（N）
  avg_wage           numeric(12,2) NOT NULL,     -- 前 12 个月平均工资
  cap_multiple       numeric(3,1) NOT NULL DEFAULT 3.0,
  cap_applied        boolean NOT NULL DEFAULT false,
  cap_years_applied  boolean NOT NULL DEFAULT false,
  base_wage          numeric(12,2) NOT NULL,     -- 实际用来乘 N 的月工资（可能被三倍封顶）

  severance_amount   numeric(12,2) NOT NULL DEFAULT 0,
  notice_amount      numeric(12,2) NOT NULL DEFAULT 0,
  annual_leave_amount numeric(12,2) NOT NULL DEFAULT 0,

  tax_exempt_amount  numeric(12,2) NOT NULL DEFAULT 0,
  taxable_amount     numeric(12,2) NOT NULL DEFAULT 0,
  tax_amount         numeric(12,2) NOT NULL DEFAULT 0,

  total_amount       numeric(12,2) NOT NULL DEFAULT 0,   -- 税前合计
  net_amount         numeric(12,2) NOT NULL DEFAULT 0,   -- 税后

  status             varchar(12) NOT NULL DEFAULT 'draft',
  note               varchar(300) NOT NULL,
  created_by         varchar(64) NOT NULL DEFAULT 'system',
  created_at         timestamptz NOT NULL DEFAULT now(),
  confirmed_by       varchar(64),
  confirmed_at       timestamptz,

  CONSTRAINT uk_ss_once UNIQUE (employment_id),
  CONSTRAINT ck_ss_status CHECK (status IN ('draft','confirmed','void')),
  CONSTRAINT ck_ss_confirmed CHECK ((status = 'confirmed') = (confirmed_at IS NOT NULL)),
  CONSTRAINT ck_ss_note CHECK (length(btrim(note)) >= 4)
);

COMMENT ON TABLE severance_settlement IS
  '离职结算单：经济补偿金 + 代通知金 + 年假折现，单独计税（不并入当月工资）。'
  '同一段任职只能有一张（重复结算会把金额改掉，而发过的钱不会跟着变）。';

-- ---------------------------------------------------------------------------
-- 4. 计算：年限 / N / 月工资 / 三倍封顶 / 个税
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_severance_n(p_months int, p_days_rest int)
RETURNS numeric
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
  v_years int;
  v_rest  int;
  v_n     numeric(5,2);
BEGIN
  IF p_months IS NULL OR p_months < 0 THEN RETURN 0; END IF;
  v_years := p_months / 12;
  v_rest  := p_months % 12;
  v_n := v_years;

  IF v_rest >= 6 THEN
    v_n := v_n + 1;                       -- 六个月以上不满一年 → 按一年
  ELSIF v_rest > 0 OR COALESCE(p_days_rest,0) > 0 THEN
    v_n := v_n + 0.5;                     -- 不满六个月 → 半个月
  END IF;

  RETURN v_n;
END;
$$;

COMMENT ON FUNCTION fn_severance_n IS
  '第 47 条的年限进位：每满一年一个月；余月 ≥6 个月 → 再算一年；余月 1–5 或只有零头天数 → 半个月。'
  '工作 3 年 7 个月 → 4；3 年 5 个月 → 3.5；3 年整 → 3；只有 5 个月 → 0.5。';

-- 前 12 个月平均工资（含奖金/津贴/加班费，剔除一次性补偿与年终奖独立条）
CREATE OR REPLACE FUNCTION fn_severance_avg_wage(p_person bigint, p_on date)
RETURNS numeric
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE
  v_avg numeric(12,2);
  v_std numeric(12,2);
  v_n   int;
BEGIN
  SELECT round(avg(x.g), 2), count(*) INTO v_avg, v_n
    FROM (
      SELECT p.gross_amount AS g
        FROM public.payslip p
        JOIN public.pay_run pr ON pr.id = p.pay_run_id
       WHERE p.employee_id = p_person
         AND pr.status IN ('sealed','paid')
         AND pr.period <= to_char(p_on, 'YYYY-MM')
         AND COALESCE(pr.kind,'monthly') = 'monthly'
       ORDER BY pr.period DESC
       LIMIT 12
    ) x;

  IF v_n > 0 AND v_avg > 0 THEN RETURN v_avg; END IF;

  SELECT s.monthly_amount INTO v_std
    FROM public.salary_standard s
    JOIN public.employment e ON e.id = s.employment_id
   WHERE e.person_id = p_person AND s.effective_from <= p_on
   ORDER BY s.effective_from DESC LIMIT 1;

  RETURN COALESCE(v_std, 0);
END;
$$;

COMMENT ON FUNCTION fn_severance_avg_wage IS
  '第 47 条的"月工资"= 解除前 12 个月平均应发（含奖金/津贴/加班费）。'
  '与年假折现的基数（剔除加班费）**不是同一个数**，两处不能互用。';

-- 一次性补偿金的个税：3 倍社平以内免征，超过部分单独按综合所得税率表
CREATE OR REPLACE FUNCTION fn_severance_tax(p_amount numeric, p_city varchar, p_year int)
RETURNS TABLE(exempt numeric, taxable numeric, tax numeric)
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE
  v_avg numeric(12,2);
  v_ex  numeric(12,2);
BEGIN
  SELECT w.monthly INTO v_avg
    FROM public.local_avg_wage w
   WHERE w.city = p_city AND w.wage_year <= p_year
   ORDER BY w.wage_year DESC LIMIT 1;

  IF v_avg IS NULL THEN
    RAISE EXCEPTION 'E_SEV_NO_AVG_WAGE: % 没有 % 年及以前的职工月平均工资，算不出免税额与三倍封顶', p_city, p_year;
  END IF;

  v_ex := round(v_avg * 3, 2);
  exempt  := v_ex;
  taxable := GREATEST(COALESCE(p_amount,0) - v_ex, 0);
  -- ★ 单独适用综合所得税率表：直接套年度税率表，不乘 12、不累计
  --   （财税〔2018〕164 号）。并入当月工资会把这个月的累计预扣整个搞乱。
  tax := public.fn_iit_cumulative(taxable);
  RETURN NEXT;
END;
$$;

COMMENT ON FUNCTION fn_severance_tax IS
  '一次性补偿金个税：免税额 = 当地上年度职工月平均工资 × 3；超过部分单独适用综合所得税率表。'
  '不并入当年综合所得，也不与当月工资合并预扣。';

-- 试算（不落单）
CREATE OR REPLACE FUNCTION fn_severance_calc(
  p_employment bigint, p_leave date, p_reason varchar, p_city varchar DEFAULT '上海',
  p_notice boolean DEFAULT false
) RETURNS TABLE(
  service_months int, service_days_rest int, n_months numeric, raw_n numeric,
  avg_wage numeric, cap_applied boolean, cap_years_applied boolean, base_wage numeric,
  severance numeric, notice numeric, annual_leave numeric,
  exempt numeric, taxable numeric, tax numeric, total numeric, net numeric,
  cap_multiple numeric, local_avg numeric
)
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE
  e        public.employment%ROWTYPE;
  r        public.severance_reason%ROWTYPE;
  iv       interval;
  v_m      int;
  v_d      int;
  v_avg    numeric(12,2);
  v_local  numeric(12,2);
  v_cap    numeric(12,2);
  v_base   numeric(12,2);
  v_cap_app boolean := false;
  v_cap_y   boolean := false;
  v_n       numeric(5,2);
  v_sev     numeric(12,2);
  v_al      numeric(12,2) := 0;
  v_tx      record;
BEGIN
  SELECT * INTO e FROM public.employment WHERE id = p_employment;
  IF e.id IS NULL THEN RAISE EXCEPTION 'E_SEV_NO_EMP: 没有这条任职记录（id=%）', p_employment; END IF;
  IF p_leave < e.hire_date THEN
    RAISE EXCEPTION 'E_SEV_BEFORE_HIRE: 离职日 % 早于入职日 %', p_leave, e.hire_date;
  END IF;

  SELECT * INTO r FROM public.severance_reason WHERE code = p_reason;
  IF r.code IS NULL THEN RAISE EXCEPTION 'E_SEV_REASON: 不认识离职情形 %', p_reason; END IF;

  -- 工作年限：完整月数 + 不足一月的天数
  iv := age(p_leave, e.hire_date);
  v_m := (EXTRACT(year FROM iv)::int * 12) + EXTRACT(month FROM iv)::int;
  v_d := EXTRACT(day FROM iv)::int;

  n_months := public.fn_severance_n(v_m, v_d) * r.n_multiple;
  raw_n := public.fn_severance_n(v_m, v_d);
  service_months := v_m;
  service_days_rest := v_d;

  v_avg := public.fn_severance_avg_wage(e.person_id, p_leave);
  avg_wage := v_avg;

  SELECT w.monthly INTO v_local
    FROM public.local_avg_wage w
   WHERE w.city = p_city AND w.wage_year <= EXTRACT(year FROM p_leave)::int
   ORDER BY w.wage_year DESC LIMIT 1;
  IF v_local IS NULL THEN
    RAISE EXCEPTION 'E_SEV_NO_AVG_WAGE: % 没有职工月平均工资数据，算不出三倍封顶', p_city;
  END IF;
  local_avg := v_local;
  cap_multiple := 3.0;
  v_cap := round(v_local * 3, 2);

  -- 第 47 条第 2 款：月工资高于三倍的按三倍计，且年限最高 12 年
  v_base := v_avg;
  IF v_avg > v_cap THEN
    v_base := v_cap;
    v_cap_app := true;
    IF n_months > 12 THEN
      n_months := 12;
      v_cap_y := true;
    END IF;
  END IF;
  cap_applied := v_cap_app;
  cap_years_applied := v_cap_y;
  base_wage := v_base;

  v_sev := round(v_base * n_months, 2);
  severance := v_sev;

  notice := CASE WHEN p_notice AND r.notice_pay THEN round(v_base, 2) ELSE 0 END;

  -- 年假折现：取该员工离职年度的 pending/paid 折现单（129 登记的那张）
  SELECT COALESCE(SUM(c.amount), 0) INTO v_al
    FROM public.leave_cashout c
   WHERE c.employee_id = e.person_id
     AND c.leave_year = EXTRACT(year FROM p_leave)::int
     AND c.status IN ('pending','paid');
  annual_leave := v_al;

  -- 个税只对补偿金算（代通知金按工资计税、年假折现进工资条计税）
  SELECT * INTO v_tx FROM public.fn_severance_tax(v_sev, p_city, EXTRACT(year FROM p_leave)::int);
  exempt := v_tx.exempt;
  taxable := v_tx.taxable;
  tax := v_tx.tax;

  total := round(v_sev + notice + v_al, 2);
  -- 税后 = 补偿金 − 税 + 代通知金 + 年假折现（后两项的税在工资条里已扣）
  net := round(v_sev - v_tx.tax + notice + v_al, 2);
  RETURN NEXT;
END;
$$;

COMMENT ON FUNCTION fn_severance_calc IS
  '离职结算试算：年限进位 → N（乘倍数）→ 前 12 个月平均 → 三倍社平封顶（超限时年限封 12）→ 补偿金 → 代通知金 → 年假折现 → 单独计税。'
  '不落单，界面与 AI 都可以先看数再决定。';

-- ---------------------------------------------------------------------------
-- 5. 落单 / 作废
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_severance_create(
  p_employment bigint, p_leave date, p_reason varchar, p_city varchar,
  p_note varchar, p_by varchar DEFAULT 'system', p_notice boolean DEFAULT false
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  c  record;
  e  public.employment%ROWTYPE;
  v_id bigint;
BEGIN
  IF p_note IS NULL OR length(btrim(p_note)) < 4 THEN
    RAISE EXCEPTION 'E_SEV_NO_NOTE: 结算单要写说明（至少 4 个字）；'
      '三个月后没人答得出"为什么按 N 而不是 N+1 结"';
  END IF;

  SELECT * INTO e FROM public.employment WHERE id = p_employment;
  IF e.id IS NULL THEN RAISE EXCEPTION 'E_SEV_NO_EMP: 没有这条任职记录（id=%）', p_employment; END IF;

  SELECT * INTO c FROM public.fn_severance_calc(p_employment, p_leave, p_reason, p_city, p_notice);

  INSERT INTO public.severance_settlement(
    employment_id, person_id, leave_date, reason_code, city,
    service_months, service_days_rest, n_months, avg_wage,
    cap_multiple, cap_applied, cap_years_applied, base_wage,
    severance_amount, notice_amount, annual_leave_amount,
    tax_exempt_amount, taxable_amount, tax_amount,
    total_amount, net_amount, status, note, created_by)
  VALUES (
    p_employment, e.person_id, p_leave, p_reason, p_city,
    c.service_months, c.service_days_rest, c.n_months, c.avg_wage,
    c.cap_multiple, c.cap_applied, c.cap_years_applied, c.base_wage,
    c.severance, c.notice, c.annual_leave,
    c.exempt, c.taxable, c.tax,
    c.total, c.net, 'draft', btrim(p_note), p_by)
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_severance_create IS
  '落一张离职结算单（draft）。金额全部来自 fn_severance_calc，这里不重算。';

CREATE OR REPLACE FUNCTION fn_severance_confirm(p_id bigint, p_by varchar DEFAULT 'system')
RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE s public.severance_settlement%ROWTYPE;
BEGIN
  SELECT * INTO s FROM public.severance_settlement WHERE id = p_id FOR UPDATE;
  IF s.id IS NULL THEN RAISE EXCEPTION 'E_SEV_NOT_FOUND: 结算单 % 不存在', p_id; END IF;
  IF s.status = 'confirmed' THEN RETURN; END IF;
  IF s.status = 'void' THEN RAISE EXCEPTION 'E_SEV_VOID: 结算单 % 已作废', p_id; END IF;

  UPDATE public.severance_settlement
     SET status = 'confirmed', confirmed_by = p_by, confirmed_at = now()
   WHERE id = p_id;
END;
$$;

CREATE OR REPLACE FUNCTION fn_severance_void(p_id bigint, p_why varchar, p_by varchar DEFAULT 'system')
RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE s public.severance_settlement%ROWTYPE;
BEGIN
  IF p_why IS NULL OR length(btrim(p_why)) < 4 THEN
    RAISE EXCEPTION 'E_SEV_NO_NOTE: 作废要写原因（至少 4 个字）';
  END IF;
  SELECT * INTO s FROM public.severance_settlement WHERE id = p_id FOR UPDATE;
  IF s.id IS NULL THEN RAISE EXCEPTION 'E_SEV_NOT_FOUND: 结算单 % 不存在', p_id; END IF;
  IF s.status = 'confirmed' THEN
    RAISE EXCEPTION 'E_SEV_CONFIRMED: 结算单 % 已确认，不能作废；'
      '钱发过了要走红冲，否则账上会凭空少一笔', p_id;
  END IF;

  UPDATE public.severance_settlement
     SET status = 'void', note = note || ' | 作废：' || btrim(p_why)
   WHERE id = p_id;
END;
$$;

