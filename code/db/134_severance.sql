-- ============================================================================
-- 134_severance.sql · 离职结算：最后一个月工资 + 年假折现 + 经济补偿金 + 代通知金
-- ----------------------------------------------------------------------------
-- 到 133 为止，离职只做了一半：`fn_emp_terminate` 会把额度结算掉（057/129），
-- 年假折现落在离职当月工资条上。但**经济补偿金一分钱都没算过**。
--
-- 而这是离职时最大的一笔钱，也是错一次就上仲裁的一笔：
--
--   · 年限半年进位算错 → 差半个月 → 几千块；
--   · 忘了三倍社平封顶 → 高薪员工多付一倍；
--   · 把补偿金并进当月工资计税 → 多缴几万（财税〔2018〕164 号：3 倍社平以内免征，
--     超过部分**单独**适用综合所得税率表，不并入当年综合所得）。
--
-- 依据：
--   《劳动合同法》
--     第 40 条：无过失性辞退需提前 30 日书面通知，或额外支付一个月工资（代通知金）。
--     第 46 条：应当支付经济补偿的情形。
--     第 47 条：每满一年一个月工资；六个月以上不满一年按一年；不满六个月付半个月。
--              月工资高于当地上年度职工月平均工资三倍的，按三倍计，年限最高 12 年。
--              月工资 = 解除或终止前**十二个月**的平均工资。
--     第 87 条：违法解除，按第 47 条标准的**二倍**支付赔偿金。
--   财税〔2018〕164 号第 5 条：一次性补偿收入在当地上年职工平均工资 3 倍以内免征；
--     超过部分不并入当年综合所得，单独适用综合所得税率表。
--
-- ★ 三个"看起来能算、其实必须写成配置"的地方：
--   ① **社平工资**各地每年公布，落在 `local_avg_wage` 表里，不写死；
--   ② **离职情形 → 补偿倍数**（0 / 1N / 2N）是法定判断，落在 `severance_reason` 表，
--      预置九种，公司可以加"协商一致给 1.5N"这种优于法定的；
--   ③ **代通知金按上月工资**还是按 12 个月平均，各地口径不一 ——
--      默认按上月（主流），制度项可改。这一条差一个月工资，界面必须显示用了哪个。
--
-- ★ 为什么补偿金不进月工资条：
--   它的个税算法完全不同（单独计税，不并入综合所得）。并进工资条会让那个月的
--   累计预扣整个失真，而且改不回来。所以它是**独立一张结算单**，单独计税。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 当地职工月平均工资（三倍封顶与免税额度都用它）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS local_avg_wage (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city       varchar(32) NOT NULL,
  wage_year  int    NOT NULL,          -- 数据所属年度（"上年度"的那个上一年）
  monthly    numeric(12,2) NOT NULL,
  note       varchar(160),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uk_law UNIQUE (city, wage_year),
  CONSTRAINT ck_law_amt CHECK (monthly > 0)
);

COMMENT ON TABLE local_avg_wage IS
  '当地上年度职工月平均工资（社平工资）。三倍封顶与补偿金免税额度都按它算。'
  '各地每年由统计局公布，不预置 —— 填错了会直接改变补偿金与个税。';

-- ★ 这里**不做**从 si_policy 反推：迁移在种子之前跑，那时 si_policy 还是空表，
--   INSERT ... SELECT 会一条都插不进去，而且不报错（最坏的那种失败）。
--   初始化放在 server 的种子块里（那里 si_policy 刚灌完），并且标"待核对"。
--   客户也可以在界面上手工录 —— 这个数每年由统计局公布，不该猜。

