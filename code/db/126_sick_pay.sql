-- ---------------------------------------------------------------------------
-- 4. 取值函数
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_min_wage(p_city varchar, p_on date)
RETURNS numeric
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT m.monthly FROM public.min_wage m
   WHERE m.city = p_city AND m.effective_from <= p_on
   ORDER BY m.effective_from DESC LIMIT 1;
$$;

COMMENT ON FUNCTION fn_min_wage IS
  '当地最低工资（取 p_on 之前最新一条）。查不到返回 NULL —— 调用方要知道"没配"与"配成 0"不同。';

CREATE OR REPLACE FUNCTION fn_sick_rate(p_years numeric)
RETURNS numeric
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT t.rate FROM public.sick_pay_tier t
   WHERE t.years_from <= p_years
   ORDER BY t.years_from DESC LIMIT 1;
$$;

COMMENT ON FUNCTION fn_sick_rate IS
  '按连续工龄取病假工资比例（取不超过工龄的最高档）。';

-- ---------------------------------------------------------------------------
-- 5. 某人某期的病假工资
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_sick_pay(p_person bigint, p_period varchar)
RETURNS numeric
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE
  v_end date;
  v_days numeric(6,2);
  v_years numeric(6,2);
  v_monthly numeric(12,2);
  v_hour_rate numeric(6,2);
  v_daily numeric(12,2);
  v_rate numeric(4,3);
  v_gross numeric(12,2);
  v_floor_daily numeric(12,2);
  v_minw numeric(12,2);
BEGIN
  IF p_period !~ '^\d{4}-(0[1-9]|1[0-2])$' THEN
    RAISE EXCEPTION 'E_PERIOD_INVALID: 期间必须是 YYYY-MM（收到 %）', p_period;
  END IF;
  v_end := (to_date(p_period || '-01','YYYY-MM-DD') + interval '1 month - 1 day')::date;

  SELECT COALESCE(sum(public.fn_leave_approved_days(p_person, p_period, 'SICK')), 0)
    INTO v_days;
  IF v_days <= 0 THEN RETURN 0; END IF;

  -- 工龄：从入职日到本期期末
  SELECT round((v_end - e.hire_date)::numeric / 365, 1)
    INTO v_years
    FROM public.employment e
   WHERE e.person_id = p_person
     AND daterange(e.hire_date, e.leave_date, '[]') @> v_end
   ORDER BY e.hire_date DESC LIMIT 1;
  v_years := COALESCE(v_years, 0);

  SELECT s.monthly_amount INTO v_monthly
    FROM public.salary_standard s
    JOIN public.employment e ON e.id = s.employment_id
   WHERE e.person_id = p_person AND s.effective_from <= v_end
   ORDER BY s.effective_from DESC LIMIT 1;
  IF v_monthly IS NULL THEN RETURN 0; END IF;

  SELECT COALESCE(value_num, 8) INTO v_hour_rate
    FROM public.fn_policy_effective('PAY_WORK_HOURS_DAY', NULL, v_end);

  -- 日薪：法定折算口径（21.75），与事假扣款同一分母
  v_daily := v_monthly / GREATEST(
    (SELECT COALESCE(value_num, 21.75) FROM public.fn_policy_effective(
       'PAY_DAYS_PER_MONTH', NULL, v_end)), 1);

  v_rate := COALESCE(public.fn_sick_rate(v_years), 0.6);
  v_gross := round(v_daily * v_rate * v_days, 2);

  -- 下限：不得低于当地最低工资的 80%（按天折算）
  v_minw := public.fn_min_wage('上海', v_end);
  IF v_minw IS NOT NULL THEN
    v_floor_daily := round(v_minw * 0.8 / GREATEST(
      (SELECT COALESCE(value_num, 21.75) FROM public.fn_policy_effective(
         'PAY_DAYS_PER_MONTH', NULL, v_end)), 1), 4);
    IF v_daily * v_rate < v_floor_daily THEN
      v_gross := round(v_floor_daily * v_days, 2);
    END IF;
  END IF;

  RETURN v_gross;
END;
$$;

COMMENT ON FUNCTION fn_sick_pay IS
  '病假工资 = 病假天数 × 日薪 × 工龄对应比例，且不低于"当地最低工资×80%÷21.75"×天数。'
  '没配最低工资时只按比例算（不设下限），界面上必须提示"未配最低工资"。';

-- ---------------------------------------------------------------------------
-- 6. 事假扣款函数里加上病假（day 模式）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_leave_deduction(p_employee bigint, p_period varchar)
RETURNS numeric
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT CASE
    WHEN public.fn_pay_basis(p_employee, p_period) = 'hour' THEN 0
    ELSE
      -- 事假：全扣
      COALESCE(round(
        COALESCE(
          (SELECT r.personal_leave_days FROM public.att_period_report r
            WHERE r.period = p_period AND r.person_id = p_employee
              AND r.status = 'confirmed'),
          public.fn_leave_approved_days(p_employee, p_period, 'PERSONAL'))
        * (SELECT s.monthly_amount / GREATEST((SELECT COALESCE(value_num, 21.75)
                 FROM public.fn_policy_effective('PAY_DAYS_PER_MONTH', NULL,
                   (to_date(p_period || '-01','YYYY-MM-DD') + interval '1 month - 1 day')::date)), 1)
             FROM public.salary_standard s
             JOIN public.employment e ON e.id = s.employment_id
            WHERE e.person_id = p_employee
            ORDER BY s.effective_from DESC LIMIT 1), 2), 0)
      -- 病假：只扣"日薪 − 病假工资"那部分（病假工资另算，见 fn_sick_pay）
      + COALESCE(round(
          public.fn_leave_approved_days(p_employee, p_period, 'SICK')
          * (SELECT s.monthly_amount / GREATEST((SELECT COALESCE(value_num, 21.75)
                 FROM public.fn_policy_effective('PAY_DAYS_PER_MONTH', NULL,
                   (to_date(p_period || '-01','YYYY-MM-DD') + interval '1 month - 1 day')::date)), 1)
             FROM public.salary_standard s
             JOIN public.employment e ON e.id = s.employment_id
            WHERE e.person_id = p_employee
            ORDER BY s.effective_from DESC LIMIT 1), 2), 0)
      - public.fn_sick_pay(p_employee, p_period)
  END;
$$;

COMMENT ON FUNCTION fn_leave_deduction IS
  '请假扣款（day 模式）：事假全扣 + 病假扣"日薪 − 病假工资"（病假工资不由这扣，是另算的应发）。'
  'hour 模式返回 0：缺勤已体现在工时里，病假工资改为加项（见 fn_payroll_calc）。';

