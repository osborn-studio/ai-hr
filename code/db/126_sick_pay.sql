-- ============================================================================
-- 126_sick_pay.sql · 病假工资：法定 60% 起、按工龄递增、不低于最低工资 80%
-- ----------------------------------------------------------------------------
-- 依据：
--   《劳动保险条例实施细则修正草案》第 16 条（病假工资按连续工龄）：
--     不满 2 年 60% ｜ 2–4 年 70% ｜ 4–6 年 80% ｜ 6–8 年 90% ｜ 8 年以上 100%
--   《关于贯彻执行〈劳动法〉若干问题的意见》第 59 条：
--     病假工资不得低于当地最低工资标准的 80%
--
-- 之前病假是按事假处理的（全扣）。这不只是少给钱，是**违法**：
-- 病假期间用人单位必须支付病假工资。
--
-- ★ 客户说得很清楚：**默认按法定，但界面要能改，改要有权限（HR 主管以上）**
--   所以这一版不写死比例：
--     · sick_pay_tier 表存档位，界面可改（默认灌法定五档）；
--     · min_wage 表存当地最低工资（默认值标注"待核对"，因为各地每年调）；
--     · 改这些需要 payroll_policy 权限，只给 boss / hr_ops。
--
--   为什么不做成"只能按法定"：有的企业整体优于法定（比如一律 80%），
--   有的地区细则不同（上海按连续工龄且分是否满 6 个月）。
--   系统给的是**默认值与底线**，不是替客户定政策。
--
-- ★ 硬底线仍然保留：比例不得低于 60%、最低工资必须填了才生效。
--   低于 60% 就是违法，这个不留给界面去"灵活"。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 基础假种（原来一张空表，导致病假/年假根本汇总不出来）
-- ---------------------------------------------------------------------------
-- ★ leave_type.id 不是 identity（老表），只能自己编号。
--   为什么不用一条 INSERT ... SELECT max(id)+row_number()：
--   同一条语句里 SELECT max(id) 看不到本语句刚插的行（快照隔离），
--   于是每行都算出同一个 id —— 照样撞主键。逐条插、每次重取 max 才稳。
DO $$
DECLARE r record; v_id bigint;
BEGIN
  FOR r IN SELECT * FROM (VALUES
             ('ANNUAL',     '年假', 'payout'),
             ('SICK',       '病假', 'void'),
             ('PERSONAL',   '事假', 'void'),
             ('MARRIAGE',   '婚假', 'void'),
             ('MATERNITY',  '产假', 'void'),
             ('BEREAVEMENT','丧假', 'void'),
             ('COMP_TIME',  '调休', 'void')
           ) AS v(code, name, pol)
  LOOP
    IF NOT EXISTS (SELECT 1 FROM public.leave_type t WHERE t.code = r.code) THEN
      SELECT COALESCE(max(id), 0) + 1 INTO v_id FROM public.leave_type;
      INSERT INTO public.leave_type(id, code, name, expire_policy)
      VALUES (v_id, r.code, r.name, r.pol);
    END IF;
  END LOOP;
END $$;

-- ---------------------------------------------------------------------------
-- 2. 病假工资档位（按连续工龄）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sick_pay_tier (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  years_from  numeric(4,1) NOT NULL,     -- 连续工龄下限（含）
  rate        numeric(4,3) NOT NULL,     -- 病假工资占日薪比例
  note        varchar(120),

  CONSTRAINT uk_spt UNIQUE (years_from),
  CONSTRAINT ck_spt_years CHECK (years_from >= 0),
  -- ★ 硬底线：法定最低档是 60%（不满 2 年）。低于它就是违法，
  --   这一条不给界面留"灵活空间"—— 有的口径可以放宽，违法不行。
  CONSTRAINT ck_spt_rate CHECK (rate >= 0.6 AND rate <= 1.0)
);

COMMENT ON TABLE sick_pay_tier IS
  '病假工资档位：连续工龄满 years_from 年起，按日薪的 rate 计发。'
  '默认灌法定五档（60/70/80/90/100%），界面可改但不得低于 60%。';

INSERT INTO sick_pay_tier(years_from, rate, note) VALUES
  (0, 0.60, '不满 2 年（法定）'),
  (2, 0.70, '满 2 年不满 4 年（法定）'),
  (4, 0.80, '满 4 年不满 6 年（法定）'),
  (6, 0.90, '满 6 年不满 8 年（法定）'),
  (8, 1.00, '满 8 年以上（法定）')
ON CONFLICT (years_from) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 3. 当地最低工资（病假工资的下限基准）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS min_wage (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city           varchar(32) NOT NULL,
  effective_from date        NOT NULL,
  monthly        numeric(10,2) NOT NULL,
  note           varchar(200),

  CONSTRAINT uk_mw UNIQUE (city, effective_from),
  CONSTRAINT ck_mw_pos CHECK (monthly > 0)
);

COMMENT ON TABLE min_wage IS
  '当地月最低工资。病假工资不得低于它的 80%。'
  '★ 这个数各地每年都在调，默认值只是示例，客户必须按当地人社公布核对 —— '
  '填错了会直接算出违法工资，而系统不会报错（它只觉得是个数）。';

