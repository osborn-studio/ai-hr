-- ============================================================================
-- 007_person.sql · 自然人 / 任职 / 任职分段 / 员工编号（T02）
-- ----------------------------------------------------------------------------
-- 三条硬口径，每条都有对应断言：
--   ① **编号绑 person，不绑 employment。** 一个员工在这家店离职、三个月后
--      在另一家店重新入职，系统里是同一个人，编号沿用、工龄连得上。
--   ② **离职日当天算在职。** 区间用 '[]'，不是 '[)'。
--      餐饮的人员流动率决定了「同一个人回来」是常态而非例外。
--   ③ **编号永不复用。** 复用之后，历史单据指向的是另一个人，而单号看起来正常。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 自然人
-- ---------------------------------------------------------------------------
CREATE TABLE person (
  id         bigint PRIMARY KEY,
  full_name  varchar(64) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- ★ 身份是判断，不是属性。
-- 身份证号/手机号是"人携带的事实"，与雇主无关；employee_no 是"雇主分配的标识"。
-- 判据不是"这个字段稳不稳"，是「换一个雇主之后它还在不在」。
CREATE TABLE person_profile (
  id           bigint PRIMARY KEY,
  person_id    bigint NOT NULL REFERENCES person(id),
  profile_type varchar(24) NOT NULL,        -- national_id | mobile | bank_card
  profile_value varchar(64) NOT NULL,
  verified_by  bigint,                      -- ★ NULL = 未核实
  verified_at  timestamptz
);

-- ★ 唯一性只在"已核实"时生效（部分索引）。
--   未核实的号码可以被两条记录同时携带 —— 因为**两个人填错同一个号，
--   比一个人真的有两个档案更常见**。在核实之前，"A 是不是重复"不能由系统回答。
CREATE UNIQUE INDEX ux_profile_national_id_verified
  ON person_profile(profile_type, profile_value)
  WHERE verified_by IS NOT NULL;

-- ---------------------------------------------------------------------------
-- 2. 任职（一人可多段、多法人并行）
-- ---------------------------------------------------------------------------
CREATE TABLE employment (
  -- ★ 第三次踩同一个坑：surrogate PK 没有生成方式，函数插入时漏写 id 会报 not-null，
  --   而报错指向 id，看起来像数据问题而不是表设计问题。
  --   凡"会被函数 INSERT 的表"，主键一律给 IDENTITY。
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id        bigint NOT NULL REFERENCES person(id),
  legal_entity_id  bigint NOT NULL,          -- 发薪法人
  hire_date        date   NOT NULL,
  leave_date       date,                     -- ★ 离职日当天仍算在职
  CONSTRAINT ck_emp_span CHECK (leave_date IS NULL OR leave_date >= hire_date)
);

-- ★ '[]' 而不是 '[)'：入职日与离职日都是"人在"的日子。
--   用 '[)' 会让离职当天算离职，而工资要算到当天 —— 差一天就是一天的钱。
CREATE OR REPLACE FUNCTION fn_is_active(p_person bigint, p_on date)
RETURNS boolean LANGUAGE sql STABLE SET search_path = '' AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.employment e
     WHERE e.person_id = p_person
       AND daterange(e.hire_date, e.leave_date, '[]') @> p_on);
$$;

-- ---------------------------------------------------------------------------
-- 3. 任职分段（计薪口径按段切）
-- ---------------------------------------------------------------------------
CREATE TABLE employment_segment (
  id            bigint PRIMARY KEY,
  employment_id bigint NOT NULL REFERENCES employment(id),
  seq           int    NOT NULL,             -- 这个人的第几段
  valid_from    date   NOT NULL,
  valid_to      date,
  CONSTRAINT ck_seg_span CHECK (valid_to IS NULL OR valid_to >= valid_from),
  UNIQUE (employment_id, seq)
);

ALTER TABLE employment_segment ADD CONSTRAINT ex_seg_no_overlap
  EXCLUDE USING gist (
    employment_id WITH =,
    daterange(valid_from, valid_to, '[]') WITH &&
  );

-- ---------------------------------------------------------------------------
-- 4. 员工编号：永不复用
-- ---------------------------------------------------------------------------
CREATE TABLE employee_no (
  no                varchar(32) PRIMARY KEY,
  assigned_person_id bigint NOT NULL REFERENCES person(id),
  assigned_at       timestamptz NOT NULL DEFAULT now(),
  retired_at        timestamptz             -- 人走了，编号退休，但这一行永不删除
);

COMMENT ON TABLE employee_no IS
  '编号绑 person，不绑 employment。永不复用、永不删除：复用之后历史单据指向的是另一个人，而单号看起来正常。';

-- 分配函数：同一个编号只能属于同一个人
CREATE OR REPLACE FUNCTION fn_assign_employee_no(p_person bigint, p_no varchar)
RETURNS void LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE v_owner bigint;
BEGIN
  SELECT assigned_person_id INTO v_owner FROM public.employee_no WHERE no = p_no;
  IF v_owner IS NOT NULL AND v_owner <> p_person THEN
    RAISE EXCEPTION 'E_EMPLOYEE_NO_REUSED: 编号 % 已属于 person %，不得改分配给 %',
      p_no, v_owner, p_person;
  END IF;
  IF v_owner IS NULL THEN
    INSERT INTO public.employee_no(no, assigned_person_id) VALUES (p_no, p_person);
  ELSE
    -- 同一个人再入职：沿用原编号，清掉退休标记
    UPDATE public.employee_no SET retired_at = NULL WHERE no = p_no;
  END IF;
END;
$$;
