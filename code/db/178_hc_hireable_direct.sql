-- ============================================================================
-- 178_hc_hireable_direct.sql · 「可招几个」的占编要按**直属**算，不是子树
-- ----------------------------------------------------------------------------
-- 现象（编制补了三级之后仍然不消失）：
--   集团 编 388 已分 388 在编 374 → 可招 -374
--   城市 编 148 已分 148 在编 142 → 可招 -142
--   门店 编  11 已分   0 在编  11 → 可招   0   ✓
--   只有叶子节点是对的。父节点全是负数，而且**补编补不掉**：要让集团非负，
--   额度得 ≥ 已分 + 在编 = 762，那等于编制翻倍 —— 是更错的修法。
--
-- 根因（022 里两个函数的口径不一致）：
--   fn_hc_allocated(p_org) = **直接子节点**额度之和   （父节点 388）
--   fn_hc_used(p_org)      = **子树内**占编人数       （父节点 374，走 path LIKE）
--   在父节点上，这两个数覆盖的是**同一批人**（下分给门店的编制，和门店里的人），
--   相减必然为负。而 022:134 那行注释写的是「额度 − 已下分 − **自身**已占」——
--   ★ 注释是"自身"，实现是"子树"：这条缺陷从头到尾就是代码与注释不符，
--     不是"口径需要商量"。所以修法是**把实现改回注释**，不是改注释。
--
-- ★ 为什么"直属"才是对的：
--   父节点的 `quota − allocated` 已经收回了下分给下级的那部分，
--   剩下的是"留在我这一层、还能挂人"的名额 —— 与之相配的占编只能是
--   **直接挂在我名下**的人。用子树占编去减，等于把下级的人同时算进
--   "已下分的额度"和"已占的名额"里，扣了两次。
--
-- ★ 这个数仍然可以是负数，**没有 GREATEST(0, …)**：
--   门店超编（额度 1、占了 3 人）时它必须是 −2。clamp 成 0 的后果是看板好看了，
--   而"超编"这件事从此永远看不见 —— 那正是 022 全篇在防的那类"看起来正常"。
--   父节点的负数（如果真有）也是真的：说明直接挂在父节点上的人超过了它留下的名额。
--
-- ★ fn_hc_available 不动：它是"还能往下分多少"，本来就不含占编，口径是对的。
--   两个数仍然不是一回事：
--     available = 额度 − 已下分        （还能分给下级几个）
--     hireable  = available − 直属已占  （本层还能招几个）
-- ============================================================================

CREATE OR REPLACE FUNCTION fn_hc_hireable(p_org bigint, p_period varchar)
RETURNS int
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT COALESCE(public.fn_hc_quota(p_org, p_period), 0)
       - public.fn_hc_allocated(p_org, p_period)
       -- ★ 直属（a.org_id = p_org），不是子树（path LIKE）：
       --   子树口径会把下级的占编再扣一次，而那一份已经在 allocated 里扣过了。
       - (SELECT count(DISTINCT a.employee_id)::int
            FROM public.employee_org_assignment a
           WHERE a.dim_code = 'cost_org'
             AND a.org_id = p_org
             AND daterange(a.valid_from, a.valid_to, '[]')
                 @> (to_date(p_period || '-01','YYYY-MM-DD') + interval '1 month - 1 day')::date);
$$;

COMMENT ON FUNCTION fn_hc_hireable IS
  '本层还能招几个：额度 − 已下分给直接下级 − **直属**已占（不是子树已占）。'
  '★ 178 修的口径不一致：allocated 是直接子节点、used 是子树，在父节点上'
  '覆盖同一批人，相减必负，而且补编补不掉（要非负得把编制翻倍）。'
  '★ 故意不加 GREATEST(0,…)：超编时这个数就该是负的，clamp 掉会让"超编"永远看不见。'
  '★ 与 fn_hc_available 不是一回事：available 是"还能往下分多少"，'
  'hireable 是"本层还能招几个"。混用会让门店以为还有 12 个编，招到第 2 个就超编。';
