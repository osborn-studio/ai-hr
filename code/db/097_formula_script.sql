-- ============================================================================
-- 097_formula_script.sql · 多行公式脚本 + 计算规则（钩子）
-- ----------------------------------------------------------------------------
-- 客户经验里的"工资项里能写代码"，实际要的是两件不同的事：
--
--   ① **分步计算**：中间变量、条件分支，最后给出结果。
--      Excel 里是辅助列，专业工资软件里是一段脚本。
--   ② **计算规则 / 钩子**：算薪前后做检查或干预 ——
--      "应发超过 5 万必须人工复核"、"离职当月不再计提成"、"社保基数低于下限要拦"。
--
-- 这两件事都可以用**同一门语言**表达（就是 092 那套表达式），
-- 区别只在于脚本允许多行、规则是"命中即动作"。
--
-- ★ 明确不做"任意代码执行"（JS/Python）：
--   薪资系统的三个硬要求 —— 可审计（能说清这个数怎么来的）、
--   可重复（同样输入永远同样输出）、可回滚（旧工资条不被新脚本改掉）——
--   在"可以 import 任意模块"的世界里全都不成立。
--   所以这里给的是**受限脚本**：只有赋值、return、注释，每行仍是白名单表达式。
--   没有循环、没有 IO、没有函数定义 —— 想要循环的人，其实想要的是规则，
--   而规则应该由系统提供参数（天数、次数），不该由脚本去遍历数据。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 脚本求值：逐行赋值 + return
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_formula_script_eval(p_script text, p_vars jsonb)
RETURNS numeric
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE
  v_lines text[]; v_line text; v_name text; v_expr text;
  v_scope jsonb := COALESCE(p_vars, '{}'::jsonb);
  v_val numeric; v_last text := NULL; i int;
BEGIN
  IF p_script IS NULL OR btrim(p_script) = '' THEN
    RAISE EXCEPTION 'E_FORMULA_EMPTY: 脚本不能为空';
  END IF;

  -- 单行（没有换行）就直接当表达式算 —— 兼容 089 以来的所有公式
  IF position(E'\n' in p_script) = 0 AND position(E'\r' in p_script) = 0 THEN
    RETURN public.fn_formula_eval(p_script, v_scope);
  END IF;

  v_lines := string_to_array(replace(p_script, E'\r\n', E'\n'), E'\n');
  FOR i IN 1 .. COALESCE(array_length(v_lines, 1), 0) LOOP
    v_line := btrim(v_lines[i]);
    CONTINUE WHEN v_line = '' OR v_line LIKE '#%' OR v_line LIKE '//%';

    IF v_line ~* '^return\M' THEN
      v_expr := btrim(substr(v_line, 7));
      IF v_expr = '' THEN RAISE EXCEPTION 'E_SCRIPT_SYNTAX: return 后面要有表达式'; END IF;
      RETURN public.fn_formula_eval(v_expr, v_scope);
    END IF;

    IF v_line ~ '^[A-Za-z_][A-Za-z0-9_]*\s*=' THEN
      v_name := (regexp_match(v_line, '^([A-Za-z_][A-Za-z0-9_]*)\s*='))[1];
      v_expr := btrim(substr(v_line, length(v_name) + 1));
      v_expr := btrim(ltrim(v_expr, '='));
      IF v_expr = '' THEN RAISE EXCEPTION 'E_SCRIPT_SYNTAX: % = 后面要有表达式', v_name; END IF;
      -- 变量名若与已登记的项目同名（大小写不同），一律拒：
      -- 那会让"读这一项"和"写中间变量"变成同一个名字，而值从哪来将无人说得清。
      IF EXISTS (SELECT 1 FROM public.salary_item WHERE upper(code) = upper(v_name)) THEN
        RAISE EXCEPTION 'E_SCRIPT_NAME: 中间变量「%」与已登记的工资项同名，换一个名字', v_name;
      END IF;
      v_val := public.fn_formula_eval(v_expr, v_scope);
      v_scope := v_scope || jsonb_build_object(v_name, v_val);
      CONTINUE;
    END IF;

    -- 既不是赋值也不是 return：留作"最后一行表达式"（脚本可以不写 return）
    v_last := v_line;
  END LOOP;

  IF v_last IS NULL THEN
    RAISE EXCEPTION 'E_SCRIPT_NO_RESULT: 脚本没有给出结果（最后一行写表达式，或显式 return）';
  END IF;
  RETURN public.fn_formula_eval(v_last, v_scope);
END;
$$;

COMMENT ON FUNCTION fn_formula_script_eval IS
  '多行公式脚本：`名字 = 表达式` 累积中间变量，`return 表达式` 给结果；'
  '最后一行是表达式时等价于 return。每一行仍然走白名单校验 —— 脚本不是 eval。';

/** 不抛错的脚本校验（含逐行试算），导入与界面用 */
CREATE OR REPLACE FUNCTION fn_formula_script_try(p_script text, p_allow jsonb DEFAULT NULL)
RETURNS varchar
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE v_probe jsonb;
BEGIN
  v_probe := (SELECT COALESCE(jsonb_object_agg(key, 1), '{}'::jsonb)
                FROM jsonb_object_keys(
                  COALESCE(p_allow, '{}'::jsonb)
                  || jsonb_build_object('MONTHLY',1,'COMMISSION',1,'PRESENT_DAYS',1,
                                        'WORK_DAYS',1,'LEAVE_DAYS',1,'SI_BASE',1,
                                        'TAX_THRESHOLD',1)) AS k(key));
  PERFORM public.fn_formula_script_eval(p_script, v_probe);
  RETURN NULL;
EXCEPTION WHEN others THEN
  RETURN SQLERRM;
END;
$$;

COMMENT ON FUNCTION fn_formula_script_try IS
  '不抛错的脚本校验：逐行校验 + 全 1 变量试算。通过返回 NULL，否则返回错误文本。';

-- ---------------------------------------------------------------------------
-- 2. 计算规则（钩子）：算薪前后做检查或干预
-- ---------------------------------------------------------------------------
CREATE TABLE salary_rule (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        varchar(32) NOT NULL UNIQUE,
  name        varchar(96) NOT NULL,
  stage       varchar(8)  NOT NULL DEFAULT 'before',
  formula     varchar(1000) NOT NULL,       -- 命中条件：结果非 0 即命中
  action      varchar(8)  NOT NULL DEFAULT 'warn',
  message     varchar(200) NOT NULL,
  is_active   boolean NOT NULL DEFAULT true,
  sort_order  int NOT NULL DEFAULT 100,
  created_by  varchar(64) NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_sr_stage  CHECK (stage IN ('before','after')),
  CONSTRAINT ck_sr_action CHECK (action IN ('block','warn')),
  CONSTRAINT ck_sr_msg    CHECK (length(btrim(message)) >= 4)
);

COMMENT ON TABLE salary_rule IS
  '计算规则：算薪前(before)或算薪后(after)跑一段公式，命中(action) 则拦截或告警。'
  '例：before + block + "应发超过 50000 需人工复核"；after + warn + "实发为 0 请检查结构"。';

CREATE TABLE salary_rule_hit (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id     bigint NOT NULL,
  person_id  bigint NOT NULL,
  rule_code  varchar(32) NOT NULL,
  stage      varchar(8) NOT NULL,
  action     varchar(8) NOT NULL,
  message    varchar(200) NOT NULL,
  amount     numeric(12,2),
  hit_at     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_srh_run ON salary_rule_hit (run_id, person_id);

COMMENT ON TABLE salary_rule_hit IS
  '规则命中记录：拦截的、告警的都留。拦一条不记一条的话，'
  '"这个月为什么有个人没算出来"就只剩一句 E_RULE_BLOCK。';

/** 跑一遍某阶段的规则，返回命中的（block 由调用方决定是否抛错） */
CREATE OR REPLACE FUNCTION fn_salary_rule_run(p_stage varchar, p_vars jsonb)
-- ★ 输出列不能叫 action / message：RETURNS TABLE 的列名在函数体里就是变量，
--   与 `SELECT ... action ...` 的列同名会得到 "column reference is ambiguous"。
RETURNS TABLE (rule_code varchar, rule_action varchar, rule_message varchar, amount numeric)
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE r record; v numeric;
BEGIN
  FOR r IN
    SELECT code, formula, action, message FROM public.salary_rule
     WHERE is_active AND stage = p_stage
     ORDER BY sort_order, code
  LOOP
    BEGIN
      v := public.fn_formula_script_eval(r.formula, p_vars);
    EXCEPTION WHEN others THEN
      -- 规则自己算不出来：**当成命中并拦截**。规则坏了还继续算薪，
      -- 等于把一道门焊死成通道 —— 而没人会注意到门没了。
      rule_code := r.code; rule_action := 'block';
      rule_message := '规则「' || r.code || '」自身出错：' || SQLERRM;
      amount := NULL;
      RETURN NEXT;
      CONTINUE;
    END;
    IF COALESCE(v, 0) <> 0 THEN
      rule_code := r.code; rule_action := r.action; rule_message := r.message; amount := v;
      RETURN NEXT;
    END IF;
  END LOOP;
END;
$$;

COMMENT ON FUNCTION fn_salary_rule_run IS
  '按 stage 跑规则，返回命中项。规则自身出错按 block 处理（坏规则不能放行）。';

