CREATE FUNCTION fn_ty_dorm_settlement_guard() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE c public.ty_dorm_charge%ROWTYPE;p public.ty_dorm_settlement%ROWTYPE;net numeric;held numeric;pay numeric;BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='费用结算不可删除';END IF;
 IF TG_OP='UPDATE' AND (NEW.charge_id,NEW.source_key,NEW.method,NEW.amount,NEW.refund_of) IS DISTINCT FROM (OLD.charge_id,OLD.source_key,OLD.method,OLD.amount,OLD.refund_of) THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='结算身份和金额不可覆盖';END IF;
 SELECT * INTO c FROM public.ty_dorm_charge WHERE id=NEW.charge_id FOR UPDATE;
 IF TG_OP='UPDATE' AND OLD.state IN('confirmed','released') AND NEW IS DISTINCT FROM OLD THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='终态结算只能关联退款或新意图';END IF;
 SELECT coalesce(sum(CASE WHEN method='refund' THEN -amount ELSE amount END) FILTER(WHERE state='confirmed'),0),coalesce(sum(amount) FILTER(WHERE state IN('reserved','unknown') AND method<>'refund'),0),coalesce(sum(amount) FILTER(WHERE method='payroll' AND state IN('reserved','unknown','confirmed')),0)
 INTO net,held,pay FROM public.ty_dorm_settlement WHERE charge_id=c.id AND id<>NEW.id;
 IF NEW.method='refund' THEN
  SELECT * INTO p FROM public.ty_dorm_settlement WHERE id=NEW.refund_of;
  IF NOT FOUND OR p.charge_id<>c.id OR p.method='refund' OR p.state<>'confirmed' OR NEW.amount+coalesce((SELECT sum(amount) FROM public.ty_dorm_settlement WHERE refund_of=p.id AND state<>'released' AND id<>NEW.id),0)>p.amount THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='退款须关联同义务有效收款且不能超原净额';END IF;
 ELSE
  IF NEW.state IN('reserved','unknown') THEN held:=held+NEW.amount;ELSIF NEW.state='confirmed' THEN net:=net+NEW.amount;END IF;
  IF NEW.state<>'released' AND (c.disputed OR net+held>c.target) THEN
   -- A previously unknown external outcome is an existing fact to reconcile,
   -- even when a later legal reduction requires a refund. Never manufacture a
   -- second collection or conceal the actual receipt to make balances look tidy.
   IF TG_OP='INSERT' THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='费用争议或跨渠道余额不足';
   ELSIF NOT(OLD.state='unknown' AND NEW.state='confirmed') THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='费用争议或跨渠道余额不足';END IF;
  END IF;
  IF NEW.method='payroll' AND NEW.state<>'released' AND (NOT c.payroll_allowed OR pay+NEW.amount>c.payroll_limit) THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='工资扣结缺已核适用依据或超渠道上限';END IF;
 END IF;RETURN NEW;END;$$;
CREATE TRIGGER ty_dorm_settlement_guard BEFORE INSERT OR UPDATE OR DELETE ON ty_dorm_settlement FOR EACH ROW EXECUTE FUNCTION fn_ty_dorm_settlement_guard();
