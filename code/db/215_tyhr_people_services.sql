CREATE FUNCTION fn_ty_dorm_bill_conservation() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE bid bigint;b public.ty_dorm_bill%ROWTYPE;s numeric;BEGIN
 IF TG_TABLE_NAME='ty_dorm_bill' THEN bid:=NEW.id;ELSE bid:=NEW.bill_id;END IF;
 SELECT * INTO b FROM public.ty_dorm_bill WHERE id=bid;
 IF b.state='posted' THEN SELECT coalesce(sum(allocated),0)INTO s FROM public.ty_dorm_charge WHERE bill_id=bid;
 IF s+b.enterprise_residual<>b.amount THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='账单源金额与实际分摊不守恒';END IF;END IF;
 RETURN NULL;END;$$;
