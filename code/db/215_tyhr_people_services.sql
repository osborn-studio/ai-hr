-- Direct SQL must not transplant identities or introduce cross-group employers.
CREATE FUNCTION fn_ty_ps_scope_guard() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE j jsonb:=to_jsonb(NEW); oldj jsonb; e public.ty_employment%ROWTYPE; b public.ty_dorm_bed%ROWTYPE; t public.ty_cert_type%ROWTYPE; h public.ty_cert_holding%ROWTYPE; d public.ty_goods_doc%ROWTYPE;
BEGIN
 IF TG_OP='UPDATE' THEN
  oldj:=to_jsonb(OLD);
  IF EXISTS(SELECT 1 FROM unnest(ARRAY['group_id','company_id','person_id','employment_id','source_key','parent_key','type_id','item_id','bill_id','house_id','room_id','bed_id']) k WHERE j?k AND j->k IS DISTINCT FROM oldj->k) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='人员服务稳定身份不可搬移';
  END IF;
 END IF;
 IF nullif(j->>'employment_id','') IS NOT NULL THEN
  SELECT * INTO e FROM public.ty_employment WHERE id=(j->>'employment_id')::bigint;
  IF NOT FOUND OR e.person_id IS DISTINCT FROM (j->>'person_id')::bigint OR e.group_id<>(j->>'group_id')::bigint OR e.company_id<>(j->>'company_id')::bigint THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='雇佣、人员、公司及集团不一致';
  END IF;
 END IF;
 IF TG_TABLE_NAME IN('ty_dorm_stay','ty_dorm_repair') THEN
  SELECT * INTO b FROM public.ty_dorm_bed WHERE id=NEW.bed_id;
  IF b.group_id<>NEW.group_id THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='床位与住户集团不一致';END IF;
 END IF;
 IF TG_TABLE_NAME IN('ty_cert_holding','ty_cert_requirement') THEN
  SELECT * INTO t FROM public.ty_cert_type WHERE id=NEW.type_id;
  IF (t.owner_kind='person') IS DISTINCT FROM (NEW.person_id IS NOT NULL) THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='证照持有人类型不一致';END IF;
 END IF;
 IF TG_TABLE_NAME='ty_cert_holding' THEN
 IF NEW.supersedes_id IS NOT NULL THEN
  SELECT * INTO h FROM public.ty_cert_holding WHERE id=NEW.supersedes_id;
  IF NOT FOUND OR (h.group_id,h.company_id,h.type_id,h.person_id,h.source_key,h.revision+1) IS DISTINCT FROM (NEW.group_id,NEW.company_id,NEW.type_id,NEW.person_id,NEW.source_key,NEW.revision) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='续期须同一持证义务并连续版本';END IF;
 END IF;END IF;
 IF TG_TABLE_NAME='ty_goods_doc' THEN
 IF NEW.related_doc_id IS NOT NULL THEN
  SELECT * INTO d FROM public.ty_goods_doc WHERE id=NEW.related_doc_id;
  IF NOT FOUND OR d.state<>'posted' OR (d.group_id,d.company_id,d.item_id) IS DISTINCT FROM (NEW.group_id,NEW.company_id,NEW.item_id) OR (NEW.kind='return' AND (d.kind<>'issue' OR d.person_id IS DISTINCT FROM NEW.person_id)) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='退回更正必须关联同项已实际办理原单';END IF;
 END IF;END IF;
 RETURN NEW;
END;$$;
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['ty_ps_candidate','ty_dorm_house','ty_dorm_room','ty_dorm_bed','ty_dorm_stay','ty_dorm_repair','ty_dorm_bill','ty_dorm_charge','ty_cert_type','ty_cert_requirement','ty_cert_holding','ty_goods_purpose','ty_goods_item','ty_goods_doc'] LOOP
 EXECUTE format('CREATE TRIGGER %I BEFORE INSERT OR UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION fn_ty_ps_scope_guard()',t||'_scope',t);END LOOP;
END;$$;

CREATE FUNCTION fn_ty_goods_movement_guard() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE d public.ty_goods_doc%ROWTYPE;s numeric; expected numeric;
BEGIN
 IF TG_OP<>'INSERT' THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='库存流水不可改删，须关联更正';END IF;
 SELECT * INTO d FROM public.ty_goods_doc WHERE id=NEW.doc_id FOR UPDATE;
 IF d.state<>'posted' OR d.item_id<>NEW.item_id THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='库存流水须对应已办理单据';END IF;
 expected:=CASE WHEN d.kind IN('receipt','return','correction_in') THEN d.quantity ELSE -d.quantity END;
 IF NEW.delta<>expected THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='实际单据与库存变化不一致';END IF;
 PERFORM 1 FROM public.ty_goods_item WHERE id=NEW.item_id FOR UPDATE;
 IF d.kind='return' AND d.quantity+coalesce((SELECT sum(quantity) FROM public.ty_goods_doc WHERE related_doc_id=d.related_doc_id AND kind='return' AND state='posted' AND id<>d.id),0)>(SELECT quantity FROM public.ty_goods_doc WHERE id=d.related_doc_id) THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='累计退回超原领用';END IF;
 UPDATE public.ty_goods_item SET stock=stock+NEW.delta WHERE id=NEW.item_id RETURNING stock INTO s;
 RETURN NEW;
END;$$;
CREATE TRIGGER ty_goods_movement_guard BEFORE INSERT OR UPDATE OR DELETE ON ty_goods_movement FOR EACH ROW EXECUTE FUNCTION fn_ty_goods_movement_guard();
CREATE FUNCTION fn_ty_goods_conservation() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE i bigint; BEGIN
 IF TG_TABLE_NAME='ty_goods_item' THEN i:=NEW.id;ELSE i:=NEW.item_id;END IF;
 IF (SELECT stock FROM public.ty_goods_item WHERE id=i)<>coalesce((SELECT sum(delta) FROM public.ty_goods_movement WHERE item_id=i),0) THEN
 RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='库存余额不等于实际流水';END IF;RETURN NULL;END;$$;
CREATE CONSTRAINT TRIGGER ty_goods_item_balance AFTER INSERT OR UPDATE ON ty_goods_item DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION fn_ty_goods_conservation();
