CREATE FUNCTION fn_ty_ps_frozen_guard() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE j jsonb:=to_jsonb(NEW);o jsonb;BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='业务历史不可删除，须撤销或关联更正';END IF;
 o:=to_jsonb(OLD);
 IF TG_TABLE_NAME='ty_goods_doc' THEN
  IF OLD.state IN('approved','posted','cancelled','rejected') AND (j-ARRAY['state','handled_by','execution_ref']) IS DISTINCT FROM (o-ARRAY['state','handled_by','execution_ref']) THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='核准物品单明细不可覆盖';END IF;
  IF OLD.state IN('posted','cancelled','rejected') AND j IS DISTINCT FROM o THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='物品终态须关联更正';END IF;
 END IF;
 IF TG_TABLE_NAME='ty_cert_holding' THEN
  IF OLD.state IN('verified','rejected','revoked') AND (j-ARRAY['state','revocation_ref']) IS DISTINCT FROM (o-ARRAY['state','revocation_ref']) THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='已核证据不可覆盖，须新版本';END IF;
  IF OLD.state='verified' AND NEW.state NOT IN('verified','revoked') OR OLD.state IN('rejected','revoked') AND NEW.state<>OLD.state THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='证照核验终态不可重开';END IF;
 END IF;
 IF TG_TABLE_NAME='ty_dorm_bill' THEN
  IF OLD.state='posted' AND j IS DISTINCT FROM o THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='发布账单不可覆盖';END IF;
 END IF;
 RETURN NEW;END;$$;
