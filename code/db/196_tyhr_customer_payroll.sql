-- Customer payroll snapshots and explicit, versioned calculation rules.
-- No source workbook data, names or statutory assumptions are shipped here.
CREATE TABLE ty_payroll_ruleset (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 group_id bigint NOT NULL REFERENCES ty_group(id),
 name text NOT NULL CHECK(btrim(name)<>''),
 currency text NOT NULL CHECK(currency ~ '^[A-Z]{3}$'),
 region text NOT NULL CHECK(btrim(region)<>''),
 status text NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','approved')),
 rules jsonb NOT NULL CHECK(jsonb_typeof(rules)='array' AND jsonb_array_length(rules)>0),
 policy_notes text NOT NULL DEFAULT '',
 created_by bigint NOT NULL, approved_by bigint, approved_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK((status='approved')=(approved_by IS NOT NULL AND approved_at IS NOT NULL)),
 UNIQUE(id,group_id)
);
CREATE TABLE ty_payroll_batch (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 group_id bigint NOT NULL REFERENCES ty_group(id),
 period text NOT NULL CHECK(period ~ '^\d{4}-(0[1-9]|1[0-2])$'),
 currency text NOT NULL CHECK(currency ~ '^[A-Z]{3}$'),
 label text NOT NULL,
 kind text NOT NULL CHECK(kind IN ('source_snapshot','calculated')),
 status text NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','validated','confirmed')),
 metadata jsonb NOT NULL DEFAULT '{}'::jsonb CHECK(jsonb_typeof(metadata)='object'),
 ruleset_id bigint,
 created_by bigint NOT NULL, confirmed_by bigint, confirmed_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK((status='confirmed')=(confirmed_by IS NOT NULL AND confirmed_at IS NOT NULL)),
 CHECK(kind<>'calculated' OR ruleset_id IS NOT NULL OR status<>'confirmed'),
 FOREIGN KEY(ruleset_id,group_id) REFERENCES ty_payroll_ruleset(id,group_id),
 UNIQUE(id,group_id)
);
CREATE TABLE ty_payroll_row (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 batch_id bigint NOT NULL, group_id bigint NOT NULL,
 source_key text NOT NULL CHECK(btrim(source_key)<>''),
 source_data jsonb NOT NULL CHECK(jsonb_typeof(source_data)='object'),
 company_id bigint, person_id bigint, employment_id bigint,
 match_reason text,
 result_data jsonb,
 validation jsonb NOT NULL DEFAULT '{}'::jsonb,
 FOREIGN KEY(batch_id,group_id) REFERENCES ty_payroll_batch(id,group_id),
 FOREIGN KEY(company_id,group_id) REFERENCES ty_company(id,group_id),
 FOREIGN KEY(person_id,group_id) REFERENCES ty_person(id,group_id),
 FOREIGN KEY(employment_id,company_id,group_id) REFERENCES ty_employment(id,company_id,group_id),
 CHECK(employment_id IS NULL OR (person_id IS NOT NULL AND company_id IS NOT NULL)),
 UNIQUE(batch_id,source_key)
);
CREATE TABLE ty_payroll_audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 batch_id bigint REFERENCES ty_payroll_batch(id),
 ruleset_id bigint REFERENCES ty_payroll_ruleset(id),
 actor_id bigint NOT NULL, action text NOT NULL,
 detail jsonb NOT NULL DEFAULT '{}'::jsonb,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK(batch_id IS NOT NULL OR ruleset_id IS NOT NULL)
);
CREATE INDEX ty_payroll_row_company_idx ON ty_payroll_row(batch_id,company_id);
CREATE UNIQUE INDEX ty_payroll_source_once_idx ON ty_payroll_batch(group_id,period,(metadata->>'source_sha256'))
 WHERE metadata->>'source_sha256' IS NOT NULL;
-- A separate posting key provides concurrency-safe protection, including two
-- confirmations racing in different transactions. Corrections require a future
-- explicit workflow; ordinary batches cannot silently pay the same month twice.
CREATE TABLE ty_payroll_posted_person (
 group_id bigint NOT NULL REFERENCES ty_group(id),
 period text NOT NULL,
 company_id bigint NOT NULL REFERENCES ty_company(id),
 person_id bigint NOT NULL REFERENCES ty_person(id),
 batch_id bigint NOT NULL REFERENCES ty_payroll_batch(id),
 PRIMARY KEY(group_id,period,company_id,person_id)
);
-- Confirmed performance is a separate, append-only input, never a rewrite of
-- the original payroll workbook. The stable source key makes posting idempotent.
CREATE TABLE ty_payroll_performance_input (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 batch_id bigint NOT NULL REFERENCES ty_payroll_batch(id),
 row_id bigint NOT NULL REFERENCES ty_payroll_row(id),
 source_key text NOT NULL,
 cycle_id bigint NOT NULL,
 result_version integer NOT NULL CHECK(result_version>0),
 amount numeric(18,2) NOT NULL,
 currency text NOT NULL CHECK(currency ~ '^[A-Z]{3}$'),
 candidate jsonb NOT NULL,
 created_by bigint NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(batch_id,source_key), UNIQUE(batch_id,row_id,cycle_id)
);
CREATE FUNCTION fn_ty_payroll_performance_guard() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE b public.ty_payroll_batch%ROWTYPE; r public.ty_payroll_row%ROWTYPE;
BEGIN
 IF TG_OP<>'INSERT' THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='已过账绩效来源不可改写或删除，请建立更正工资批次';
 END IF;
 SELECT * INTO b FROM public.ty_payroll_batch WHERE id=NEW.batch_id FOR UPDATE;
 SELECT * INTO r FROM public.ty_payroll_row WHERE id=NEW.row_id;
 IF b.status='confirmed' OR r.batch_id IS DISTINCT FROM NEW.batch_id OR b.currency<>NEW.currency THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='绩效输入与工资批次不一致或批次已锁定';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER ty_payroll_performance_guard BEFORE INSERT OR UPDATE OR DELETE ON ty_payroll_performance_input FOR EACH ROW EXECUTE FUNCTION fn_ty_payroll_performance_guard();
CREATE FUNCTION fn_ty_payroll_rules_guard() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
BEGIN
 IF TG_OP='DELETE' OR (TG_OP='UPDATE' AND OLD.status='approved') THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='已批准的薪酬规则版本不能修改或删除，请新建版本';
 END IF;
 IF TG_OP='UPDATE' AND (NEW.group_id<>OLD.group_id OR NEW.created_by<>OLD.created_by) THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='规则来源身份不可变更';
 END IF;
 IF NOT EXISTS(SELECT 1 FROM public.ty_group WHERE id=NEW.group_id AND status='active') THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='薪酬集团已停用';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER ty_payroll_rules_guard BEFORE INSERT OR UPDATE OR DELETE ON ty_payroll_ruleset FOR EACH ROW EXECUTE FUNCTION fn_ty_payroll_rules_guard();
CREATE FUNCTION fn_ty_payroll_batch_guard() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
BEGIN
 IF TG_OP='DELETE' OR (TG_OP='UPDATE' AND OLD.status='confirmed') THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='已确认工资批次不可改写或删除，请建立更正批次';
 END IF;
 IF TG_OP='UPDATE' AND (NEW.group_id<>OLD.group_id OR NEW.period<>OLD.period OR NEW.currency<>OLD.currency OR NEW.created_by<>OLD.created_by OR NEW.metadata IS DISTINCT FROM OLD.metadata) THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='工资批次来源和期间不可改写';
 END IF;
 IF TG_OP='INSERT' AND NOT EXISTS(SELECT 1 FROM public.ty_group WHERE id=NEW.group_id AND status='active') THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='薪酬集团已停用';
 END IF;
 IF NEW.status='confirmed' THEN
  IF NOT EXISTS(SELECT 1 FROM public.ty_payroll_row WHERE batch_id=NEW.id) OR EXISTS(SELECT 1 FROM public.ty_payroll_row WHERE batch_id=NEW.id AND (company_id IS NULL OR person_id IS NULL OR employment_id IS NULL OR validation->>'ok' IS DISTINCT FROM 'true')) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='工资人员匹配和核验尚未完成';
  END IF;
  IF NEW.kind='calculated' AND NOT EXISTS(SELECT 1 FROM public.ty_payroll_ruleset WHERE id=NEW.ruleset_id AND status='approved' AND currency=NEW.currency AND group_id=NEW.group_id) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='计算批次必须使用同币种已批准规则';
  END IF;
  IF EXISTS(SELECT 1 FROM public.ty_payroll_row r JOIN public.ty_payroll_posted_person p ON p.group_id=r.group_id AND p.person_id=r.person_id AND p.company_id=r.company_id WHERE r.batch_id=NEW.id AND p.period=NEW.period) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='本期间人员和公司已有已确认工资，普通批次不能重复确认；补发更正尚需独立流程';
  END IF;
  INSERT INTO public.ty_payroll_posted_person(group_id,period,company_id,person_id,batch_id)
   SELECT NEW.group_id,NEW.period,company_id,person_id,NEW.id FROM public.ty_payroll_row WHERE batch_id=NEW.id;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER ty_payroll_batch_guard BEFORE INSERT OR UPDATE OR DELETE ON ty_payroll_batch FOR EACH ROW EXECUTE FUNCTION fn_ty_payroll_batch_guard();
CREATE FUNCTION fn_ty_payroll_row_guard() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE bid bigint; b public.ty_payroll_batch%ROWTYPE; e public.ty_employment%ROWTYPE;
BEGIN
 bid:=CASE WHEN TG_OP='DELETE' THEN OLD.batch_id ELSE NEW.batch_id END;
 SELECT * INTO b FROM public.ty_payroll_batch WHERE id=bid FOR UPDATE;
 IF b.status='confirmed' OR TG_OP='DELETE' THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='工资来源行不可删除，已确认行不可修改';
 END IF;
 IF TG_OP='UPDATE' AND (NEW.batch_id<>OLD.batch_id OR NEW.group_id<>OLD.group_id OR NEW.source_key<>OLD.source_key OR NEW.source_data IS DISTINCT FROM OLD.source_data) THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='工资来源数据不可改写，请建立更正批次';
 END IF;
 IF NEW.employment_id IS NOT NULL THEN
  SELECT * INTO e FROM public.ty_employment WHERE id=NEW.employment_id;
  IF e.person_id IS DISTINCT FROM NEW.person_id OR e.company_id IS DISTINCT FROM NEW.company_id OR e.group_id IS DISTINCT FROM NEW.group_id THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='工资雇佣、人员与公司不一致';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER ty_payroll_row_guard BEFORE INSERT OR UPDATE OR DELETE ON ty_payroll_row FOR EACH ROW EXECUTE FUNCTION fn_ty_payroll_row_guard();
