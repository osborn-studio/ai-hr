-- ============================================================================
-- 149_roster_rule.sql · 排班规则：产品有四层，我们一层都没有
-- ----------------------------------------------------------------------------
-- 白皮书 2.1 把排班规则拆成四组，官方界面（白皮书插图）长这样：
--
--   排班设置 → 排班规则 →「+ 新增排班规则」
--     ├ 排班合规性设置
--     │   ├ 排班上限设置：[每日排班][每周排班][每月排班]
--     │   │   ☑ 工作日可排班，排班累计超过 [ ] 小时，不允许再排班
--     │   │   ☑ 休息日可排班，排班累计超过 [ ] 小时，不允许再排班
--     │   │   ☐ 节假日可排班，排班累计超过 [ ] 小时，不允许再排班
--     │   ├ 连续排班限制：[无限制 ▾]      （同一个人最多连续排 N 天）
--     │   ├ 月排休限制：  [无限制 ▾]      （每月排休天数 ≥ N）
--     │   └ 风险预警：每日/每周/每月累计超过 X 小时 → 提醒主管或排班人
--     ├ 打卡限制
--     │   ☐ 未排班时，员工可以选择班次打卡
--     │   ☐ 未排班时，员工可以打卡
--     ├ 排班修改规则
--     │   ⦿ 可修改已发生排班 （可修改 6 个月内已打过卡、逾期未排班的排班）
--     │   ○ 不可修改已发生排班
--     ├ 排休修改规则
--     │   ☐ 考勤组主负责人不能修改   ☐ 考勤组子负责人不能修改排休
--     │   ☐ 排班子管理员不能修改排班 ☐ 排班人不能修改排休
--     ├ 排班发布规则
--     │   ⦿ 保存即自动发布  ○ 手动发布
--     │   ○ 审批通过后自动发布  ○ 审批通过后手动发布
--     └ 未排班提醒（开关）
--         ├ 提醒时间：[提前一天 ▾]
--         ├ 发送未排班提醒：[…▾]
--         └ 提醒范围：⦿ 仅提醒排班人  ○ 提醒排班人和未被排班的员工
--
-- ★ 这一层为什么先做：**它不改任何交互**，只在写路径上加校验。
--   而"排班工时超法定""连续上班没休息"是餐饮被罚的最常见原因 ——
--   产品把它做成硬拦 + 预警两级，这个设计是对的，照做。
--
-- ★ 三条落库时的取舍：
--
--   ① **硬拦与预警分开**。超上限是 `RAISE`（排不进去）；接近上限是**返回一行预警**
--      （排得进去，但页面标黄）。合成一个就会出现"要么什么都没说、要么直接不让排"。
--
--   ② **上限挂在组织上，不挂在人上**（照产品的"考勤组"思路）。我们没有考勤组，
--      用 `org_id`（成本组织）—— 门店就是排班的天然单位。
--      取规则的顺序：本组织 → 上级组织 → 无规则（= 不校验，沿用上线前行为）。
--
--   ③ **发布模式默认"保存即生效"**。产品有四种发布模式，但 2026-07 最新方案里
--      这个说法已经消失（只剩"换班留痕可查"）。所以做成配置项、默认关：
--      老客户不会为它买单，新客户要就走审批单，不把它做成必经流程。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 规则表：一行一套规则，按组织挂
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS roster_rule (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code            varchar(32) NOT NULL UNIQUE,
  name            varchar(96) NOT NULL,
  org_id          bigint      NOT NULL,          -- 成本组织（门店/区域）；0 = 全局缺省
  is_active       boolean     NOT NULL DEFAULT true,

  -- ① 排班上限（分钟）。NULL = 该日型不限；0 = 不许排
  max_min_workday   int,
  max_min_restday   int,
  max_min_holiday   int,
  -- ② 周期上限（分钟/周、分钟/月）
  max_min_week      int,
  max_min_month     int,
  -- ③ 连续排班：同一个人最多连续 N 天（NULL = 无限制）
  max_consecutive_days int,
  -- ④ 月排休：每月至少 N 天休息（NULL = 无限制）
  min_rest_days_month  int,
  -- ⑤ 风险预警阈值（小时，升序；如 [8,10,12]）。到档提醒，不拦
  warn_daily_hours  numeric(6,2)[],
  warn_week_hours   numeric(6,2)[],
  warn_month_hours  numeric(6,2)[],

  -- ⑥ 打卡限制
  allow_pick_shift_unrostered boolean NOT NULL DEFAULT false,
  allow_punch_unrostered      boolean NOT NULL DEFAULT false,

  -- ⑦ 修改规则
  can_edit_past       boolean NOT NULL DEFAULT true,
  edit_window_months  int     NOT NULL DEFAULT 6,
  lock_rest_by_role   jsonb   NOT NULL DEFAULT '{}'::jsonb,  -- {"store_mgr":true,…}

  -- ⑧ 发布规则
  publish_mode        varchar(24) NOT NULL DEFAULT 'save',
  -- ⑨ 未排班提醒
  remind_enabled      boolean NOT NULL DEFAULT false,
  remind_before_days  int     NOT NULL DEFAULT 1,
  remind_scope        varchar(16) NOT NULL DEFAULT 'manager',

  created_by varchar(64) NOT NULL DEFAULT 'system',
  created_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT ck_rr_publish CHECK (publish_mode IN ('save','manual','approve_auto','approve_manual')),
  CONSTRAINT ck_rr_scope   CHECK (remind_scope IN ('manager','both')),
  CONSTRAINT ck_rr_consec  CHECK (max_consecutive_days IS NULL OR max_consecutive_days BETWEEN 1 AND 366),
  CONSTRAINT ck_rr_rest    CHECK (min_rest_days_month IS NULL OR min_rest_days_month BETWEEN 0 AND 31),
  CONSTRAINT ck_rr_win     CHECK (edit_window_months BETWEEN 0 AND 120)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_rr_org ON roster_rule (org_id) WHERE is_active;

COMMENT ON TABLE roster_rule IS
  '排班规则（149）：合规上限 / 连续排班 / 月排休 / 风险预警 / 打卡限制 / 修改规则 / 发布 / 提醒。'
  '一个组织一条启用中的规则；取不到就向上级找，再取不到 = 不校验（沿用上线前行为）。'
  '上限是**硬拦**，预警阈值是**提示**——两者分开，否则要么什么都没说、要么直接不让排。';

-- ---------------------------------------------------------------------------
-- 2. 取生效规则：本组织 → 上级 → 无
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_roster_rule_of(p_org bigint)
RETURNS public.roster_rule
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE
  r  public.roster_rule;
  up bigint;
BEGIN
  SELECT * INTO r FROM public.roster_rule
   WHERE org_id = p_org AND is_active LIMIT 1;
  IF r.id IS NOT NULL THEN RETURN r; END IF;

  -- 向上找一级（门店 → 区域 → 集团）。只找一级不做递归：
  -- 递归会让人在集团改一条规则、所有门店的排班当场变，而他们看不到是谁改的。
  SELECT o.parent_id INTO up FROM public.org_unit o WHERE o.id = p_org;
  IF up IS NOT NULL THEN
    SELECT * INTO r FROM public.roster_rule
     WHERE org_id = up AND is_active LIMIT 1;
    IF r.id IS NOT NULL THEN RETURN r; END IF;
  END IF;

  SELECT * INTO r FROM public.roster_rule
   WHERE org_id = 0 AND is_active LIMIT 1;    -- 全局缺省
  RETURN r;   -- 可能是空行（id IS NULL）
END;
$$;

COMMENT ON FUNCTION fn_roster_rule_of IS
  '取某组织的生效排班规则：本组织 → 上一级 → 全局缺省。都没有则返回空行（= 不校验）。'
  '只向上找一级，不做递归继承：递归会让集团一次改动静默影响所有门店的排班。';

-- ---------------------------------------------------------------------------
-- 3. 校验：排这一段之前先问规则
-- ---------------------------------------------------------------------------
-- 返回命中清单：kind='block' 时调用方必须拒；kind='warn' 时排进去但要提示。
-- ★ 判据与写入口分开：fn_roster_line / fn_roster_assign 都调它，
--   将来加"周期排班"也调同一个 —— 校验只有一份实现。
CREATE OR REPLACE FUNCTION fn_roster_check(
  p_employee bigint, p_date date, p_org bigint, p_minutes int
) RETURNS TABLE (kind varchar(8), rule_code varchar(32), message varchar, used_minutes int, limit_minutes int)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE
  r        public.roster_rule;
  v_day    int;
  v_week   int;
  v_month  int;
  v_limit  int;
  v_consec int;
  v_rest   int;
  v_rest_n int;
  v_dom    varchar(16);
BEGIN
  SELECT * INTO r FROM public.fn_roster_rule_of(p_org);
  IF r.id IS NULL THEN RETURN; END IF;   -- 没有规则 = 不校验

  -- 当日已排（含本次）：把这次要加的分钟数算进去
  SELECT COALESCE(sum(ROUND(EXTRACT(epoch FROM (sg.end_at - sg.start_at)) / 60)), 0)::int
    INTO v_day
    FROM public.schedule s
    JOIN public.schedule_segment sg ON sg.schedule_id = s.id
   WHERE s.employee_id = p_employee AND s.work_date = p_date;

  SELECT COALESCE(sum(ROUND(EXTRACT(epoch FROM (sg.end_at - sg.start_at)) / 60)), 0)::int
    INTO v_week
    FROM public.schedule s
    JOIN public.schedule_segment sg ON sg.schedule_id = s.id
   WHERE s.employee_id = p_employee
     AND s.work_date >= date_trunc('week', p_date)::date
     AND s.work_date <  date_trunc('week', p_date)::date + 7;

  SELECT COALESCE(sum(ROUND(EXTRACT(epoch FROM (sg.end_at - sg.start_at)) / 60)), 0)::int
    INTO v_month
    FROM public.schedule s
    JOIN public.schedule_segment sg ON sg.schedule_id = s.id
   WHERE s.employee_id = p_employee
     AND s.work_date >= date_trunc('month', p_date)::date
     AND s.work_date <  (date_trunc('month', p_date) + interval '1 month')::date;

  v_day := v_day + p_minutes; v_week := v_week + p_minutes; v_month := v_month + p_minutes;

  -- 日型：法定节假日 > 休息日 > 工作日（优先级与加班三档一致，避免两处口径不同）
  IF EXISTS (SELECT 1 FROM public.legal_holiday h WHERE h.holiday_date = p_date) THEN
    v_dom := 'holiday';
  ELSIF public.fn_is_rest_day(p_date, p_employee) THEN
    v_dom := 'restday';
  ELSE
    v_dom := 'workday';
  END IF;

  v_limit := CASE v_dom
               WHEN 'holiday' THEN r.max_min_holiday
               WHEN 'restday' THEN r.max_min_restday
               ELSE r.max_min_workday END;

  IF v_limit IS NOT NULL THEN
    IF v_limit = 0 THEN
      kind := 'block'; rule_code := 'R_DAY_FORBID';
      message := format('%s 是%s，规则不允许排班', p_date,
        CASE v_dom WHEN 'holiday' THEN '法定节假日' WHEN 'restday' THEN '休息日' ELSE '工作日' END);
      used_minutes := v_day; limit_minutes := 0;
      RETURN NEXT; RETURN;
    ELSIF v_day > v_limit THEN
      kind := 'block'; rule_code := 'R_DAY_LIMIT';
      message := format('当天累计 %s 小时，超过上限 %s 小时（%s）',
        ROUND(v_day / 60.0, 1), ROUND(v_limit / 60.0, 1), r.name);
      used_minutes := v_day; limit_minutes := v_limit;
      RETURN NEXT; RETURN;
    END IF;
  END IF;

  IF r.max_min_week IS NOT NULL AND v_week > r.max_min_week THEN
    kind := 'block'; rule_code := 'R_WEEK_LIMIT';
    message := format('本周累计 %s 小时，超过上限 %s 小时',
      ROUND(v_week / 60.0, 1), ROUND(r.max_min_week / 60.0, 1));
    used_minutes := v_week; limit_minutes := r.max_min_week;
    RETURN NEXT; RETURN;
  END IF;

  IF r.max_min_month IS NOT NULL AND v_month > r.max_min_month THEN
    kind := 'block'; rule_code := 'R_MONTH_LIMIT';
    message := format('本月累计 %s 小时，超过上限 %s 小时',
      ROUND(v_month / 60.0, 1), ROUND(r.max_min_month / 60.0, 1));
    used_minutes := v_month; limit_minutes := r.max_min_month;
    RETURN NEXT; RETURN;
  END IF;

  -- 连续排班：从今天往前数，连着有班的天数（含今天）
  IF r.max_consecutive_days IS NOT NULL THEN
    SELECT count(*)::int INTO v_consec
      FROM (
        SELECT d::date AS dd,
               EXISTS (SELECT 1 FROM public.schedule s2 WHERE s2.employee_id = p_employee
                        AND s2.work_date = d::date) AS has
          FROM generate_series(p_date - (r.max_consecutive_days - 1), p_date, '1 day') d
      ) t WHERE t.has;
    -- 只要这 N 天一天不缺，就是连续 N 天
    IF v_consec >= r.max_consecutive_days THEN
      kind := 'block'; rule_code := 'R_CONSECUTIVE';
      message := format('已经连续排班 %s 天（上限 %s 天）—— 休息一天再排',
        v_consec, r.max_consecutive_days);
      used_minutes := v_consec; limit_minutes := r.max_consecutive_days;
      RETURN NEXT; RETURN;
    END IF;
  END IF;

  -- 月排休：本月已排的"有段天数"还剩几天可排（不够就提醒，不硬拦）
  IF r.min_rest_days_month IS NOT NULL THEN
    SELECT (date_trunc('month', p_date) + interval '1 month - 1 day')::date
           - date_trunc('month', p_date)::date + 1
           - count(DISTINCT s.work_date)
      INTO v_rest_n
      FROM public.schedule s
      WHERE s.employee_id = p_employee
        AND s.work_date >= date_trunc('month', p_date)::date
        AND s.work_date <  (date_trunc('month', p_date) + interval '1 month')::date;

    -- v_rest_n = 剩下"没有排班"的天数（含今天之前已过去的，所以只做提示）
    IF v_rest_n < r.min_rest_days_month THEN
      kind := 'warn'; rule_code := 'R_MIN_REST';
      message := format('本月休息天数将不足 %s 天（剩余可休 %s 天）', r.min_rest_days_month, v_rest_n);
      used_minutes := v_rest_n; limit_minutes := r.min_rest_days_month;
      RETURN NEXT;
    END IF;
  END IF;

  -- 风险预警：到了哪个档就出一行提示（不拦）
  IF r.warn_daily_hours IS NOT NULL THEN
    FOR v_limit IN SELECT unnest(r.warn_daily_hours)::int * 60 LOOP
      IF v_day >= v_limit THEN
        kind := 'warn'; rule_code := 'R_WARN_DAY';
        message := format('当天累计 %s 小时，已达预警线 %s 小时',
          ROUND(v_day / 60.0, 1), ROUND(v_limit / 60.0, 1));
        used_minutes := v_day; limit_minutes := v_limit;
        RETURN NEXT;
        EXIT;
      END IF;
    END LOOP;
  END IF;
END;
$$;

COMMENT ON FUNCTION fn_roster_check IS
  '排一段之前问规则：超上限 → kind=''block''（调用方必须拒）；到预警线/月休不足 → kind=''warn''（排得进去，页面标黄）。'
  '校验只有这一份实现：划线、固定班次、将来的周期排班都调它。';

