$$;

COMMENT ON FUNCTION fn_station_choices IS
  '某品牌线可选的档口（通用 + 本线）。铺档口的下拉列表用它，'
  '专门店才不会在候选里看见烧腊档。';

CREATE OR REPLACE FUNCTION fn_store_station_enable(
  p_store bigint, p_station bigint, p_opened_at date, p_seq int DEFAULT NULL
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_id bigint; v_seq int;
BEGIN
  SELECT COALESCE(p_seq, s.seq) INTO v_seq FROM public.station s WHERE s.id = p_station;
  IF v_seq IS NULL THEN
    RAISE EXCEPTION 'E_STN_NO_DEF: 档口 % 不在词表里', p_station;
  END IF;

  -- 幂等：这一时点已经开着就返回它（同店同档口同一时点由 ex_ss_no_overlap 排他）
  SELECT ss.id INTO v_id
    FROM public.store_station ss
   WHERE ss.store_id = p_store AND ss.station_id = p_station
     AND daterange(ss.opened_at, ss.closed_at, '[]') @> p_opened_at;
  IF v_id IS NOT NULL THEN RETURN v_id; END IF;

  INSERT INTO public.store_station(store_id, station_id, seq, opened_at)
  VALUES (p_store, p_station, v_seq, p_opened_at)
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

-- 按品牌线一次把预置档口全开。
-- ★ 品牌线**只在铺档口这一刻是筛选条件**，铺完之后 store_station 就是事实，
--   不回头校验。理由：门店换品牌（茶餐厅转做天妇罗）是真实事件，
--   硬校验会让它变成"先删光档口" —— 而删光会连带丢掉编制与全部历史。
--   要改门店的产品线，改词表的 brand_line 或手工开关档口，都是显式动作。
CREATE OR REPLACE FUNCTION fn_store_station_preset(
  p_store bigint, p_brand varchar, p_opened_at date DEFAULT NULL
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_on date := COALESCE(p_opened_at, public.app_today());
        v_n int := 0; r record;
BEGIN
  FOR r IN SELECT c.station_id, c.seq FROM public.fn_station_choices(p_brand) c LOOP
    PERFORM public.fn_store_station_enable(p_store, r.station_id, v_on, r.seq);
    v_n := v_n + 1;
  END LOOP;
  RETURN v_n;
END;
$$;

-- 关档口：还有人在这个档口的岗位上站着就拒。
-- 停用一个还有在职人员的档口，这些人下次查归属是空，而空会被下游当成"未分配"
-- —— 与 086:11-16（停用还有在职人员的部门）是同一类错。
CREATE OR REPLACE FUNCTION fn_store_station_close(
  p_store_station bigint, p_closed_at date
) RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_ss public.store_station%ROWTYPE; v_n int;
BEGIN
  SELECT * INTO v_ss FROM public.store_station WHERE id = p_store_station;
  IF v_ss.id IS NULL THEN
    RAISE EXCEPTION 'E_STN_NOT_FOUND: 门店档口 % 不存在', p_store_station;
  END IF;
  IF p_closed_at < v_ss.opened_at THEN
    RAISE EXCEPTION 'E_STN_SPAN: 关闭日 % 早于开启日 %', p_closed_at, v_ss.opened_at;
  END IF;

  SELECT count(DISTINCT pp.person_id) INTO v_n
    FROM public.station_position sp
    JOIN public.person_position pp ON pp.position_id = sp.position_id
                                  AND daterange(pp.valid_from, pp.valid_to, '[]') @> p_closed_at
    JOIN public.employment e ON e.person_id = pp.person_id
                            AND daterange(e.hire_date, e.leave_date, '[]') @> p_closed_at
    JOIN public.employee_org_assignment a ON a.employee_id = pp.person_id
                                         AND a.dim_code = 'cost_org'
                                         AND daterange(a.valid_from, a.valid_to, '[]') @> p_closed_at
   WHERE sp.store_station_id = p_store_station
     AND a.org_id = v_ss.store_id;
  IF v_n > 0 THEN
    RAISE EXCEPTION 'E_STN_IN_USE: 这个档口在 % 还有 % 人在岗，先把他们调走或调岗再关',
      p_closed_at, v_n;
  END IF;

  UPDATE public.store_station SET closed_at = p_closed_at WHERE id = p_store_station;
END;
$$;

-- ---------------------------------------------------------------------------
-- 6. 档口定编
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_sp_set(
  p_store_station bigint, p_position bigint, p_period varchar,
  p_headcount int, p_by varchar, p_reason varchar
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_ver int;
BEGIN
  IF p_headcount IS NULL OR p_headcount < 0 THEN
    RAISE EXCEPTION 'E_SP_NEGATIVE: 档口编制不能为负（% 个）', p_headcount;
  END IF;
  IF p_period !~ '^\d{4}-(0[1-9]|1[0-2])$' THEN
    RAISE EXCEPTION 'E_SP_PERIOD: 期间格式必须是 YYYY-MM（收到 %）', p_period;
  END IF;
  IF p_reason IS NULL OR length(btrim(p_reason)) < 4 THEN
    RAISE EXCEPTION 'E_SP_REASON: 调编原因至少 4 个字（"上个月编了几个"要有据可查）';
  END IF;

  SELECT COALESCE(max(sp.version), 0) + 1 INTO v_ver
    FROM public.station_position sp
   WHERE sp.store_station_id = p_store_station
     AND sp.position_id = p_position
     AND sp.period = p_period;

  -- 三条判据在 trg_sp_guard 里（外包岗 / 同店不跨档口 / Σ档口编 ≤ 门店编）
  INSERT INTO public.station_position
    (store_station_id, position_id, period, version, headcount, set_by, reason)
  VALUES (p_store_station, p_position, p_period, v_ver, p_headcount,
          COALESCE(NULLIF(btrim(p_by), ''), 'system'), btrim(p_reason));

  RETURN v_ver;
END;
$$;

COMMENT ON FUNCTION fn_sp_set IS
  '档口定编：追加一个版本，不改历史。子项之和 ≤ 门店编这条判据在 trg_sp_guard，'
  '不在这里 —— MCP / 批量导入 / 手工 INSERT 都绕得过函数，绕不过触发器。';

-- ---------------------------------------------------------------------------
-- 7. 「缺了多久」：派生，不落列
-- ---------------------------------------------------------------------------
-- 口径：**使得到岗岗次 ≥ 编制的最晚一个时点，次日起就是缺口起点。**
--
-- 到岗与编制都是分段常量（阶梯函数），跳变点只有两类：
--   ① 某人在这个岗位上的任职起 / 止（valid_from / valid_to + 1）
--   ② 编制某期的生效日（该期 1 号）
-- 所以断点集合有限且很小（一个档口岗位最多几个人 × 几版），逐点求值即可 ——
-- 不做回溯扫描、不建快照表、不起定时任务。
--
-- ★ 为什么不能落成一列 gap_since：入职 / 离职 / 转岗 / 调编四条路径都要维护它，
--   必然漂；漂的表现是"缺岗 30 天"其实是 3 天。与 022:128-130 同一条理由。
CREATE OR REPLACE FUNCTION fn_sp_gap_since(
  p_store_station bigint, p_position bigint, p_on date
) RETURNS date
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  WITH hc AS (
    -- 每期取最大版本；生效日 = 该期 1 号（与 fn_hc_used 用期末日不冲突：
    -- 编制是"这一期有效"，起点就是 1 号）
    SELECT DISTINCT ON (sp.period)
           make_date(substr(sp.period,1,4)::int, substr(sp.period,6,2)::int, 1) AS d,
           sp.headcount
      FROM public.station_position sp
     WHERE sp.store_station_id = p_store_station
       AND sp.position_id = p_position
       AND make_date(substr(sp.period,1,4)::int, substr(sp.period,6,2)::int, 1) <= p_on
     ORDER BY sp.period, sp.version DESC
  ),
  v_start AS (SELECT min(hc.d) AS d FROM hc),
  brk AS (
    SELECT hc.d FROM hc
    UNION
    SELECT pp.valid_from FROM public.person_position pp WHERE pp.position_id = p_position
    UNION
    SELECT pp.valid_to + 1 FROM public.person_position pp
     WHERE pp.position_id = p_position AND pp.valid_to IS NOT NULL
  ),
  -- 断点只取"有编制之后、查询日之前"的那些：缺口只能从有编制那天起算。
  -- 早于编制生效日的任职断点只是多了几个求值点，滤掉更省事也更不容易误读。
  pts AS (
    SELECT DISTINCT b.d
      FROM brk b, v_start s
     WHERE s.d IS NOT NULL AND b.d >= s.d AND b.d <= p_on
  ),
  ev AS (
    SELECT p.d,
           -- 编制：这一时点生效的是"最近一期"，不是"历期之和"
           (SELECT k.headcount FROM hc k WHERE k.d <= p.d ORDER BY k.d DESC LIMIT 1) AS hc_at,
           -- 到岗：与 fn_station_fill 同一表达式（三个 daterange 缺一不可）
           (SELECT count(DISTINCT pp.person_id)
              FROM public.person_position pp
              JOIN public.employment e ON e.person_id = pp.person_id
                                      AND daterange(e.hire_date, e.leave_date, '[]') @> p.d
              JOIN public.employee_org_assignment a ON a.employee_id = pp.person_id
                                                   AND a.dim_code = 'cost_org'
                                                   AND daterange(a.valid_from, a.valid_to, '[]') @> p.d
              JOIN public.store_station st ON st.id = p_store_station
                                          AND st.store_id = a.org_id
             WHERE pp.position_id = p_position
               AND daterange(pp.valid_from, pp.valid_to, '[]') @> p.d
           ) AS held_at
      FROM pts p
  )
  SELECT COALESCE(
           -- 最后一次"到岗 ≥ 编制"之后的下一个断点 —— 那一天就是缺口的起点。
           -- ★ 不能写成"最后一次满足的断点 + 1 天"：值在两个断点之间是常量，
           --   满足的最后一个断点是 03-01、下个断点是 03-11（有人离职）时，
           --   缺口起点是 03-11，不是 03-02。差 9 天，而两种写法都不会报错。
           (SELECT min(x.d) FROM ev x
             WHERE x.d > (SELECT max(y.d) FROM ev y WHERE y.held_at >= y.hc_at)),
           -- 一次都没配满过 → 从有编制那天起就缺
           (SELECT min(z.d) FROM ev z))
    ;
$$;

COMMENT ON FUNCTION fn_sp_gap_since IS
  '这个 (档口,岗位) 从哪天开始缺人：到岗最后一次 ≥ 编制的那一天的次日。'
  '从没配满过 → 编制首期生效日。没有编制 → NULL。派生，不落列。';

-- ---------------------------------------------------------------------------
-- 8. 三个数字：**一个函数一次取齐**
-- ---------------------------------------------------------------------------
-- 为什么不拆成"编制函数 + 到岗函数 + 缺岗函数"：三个数来自三次查询就来自三个时点。
-- 页面把三个时点的数并排放，会算出"编制 8、到岗 8、缺 1"这种自相矛盾的一屏，
-- 而每个数单独看都对。所以一次返回，门店级/档口级/岗位级都在同一份结果里。
--
-- 返回粒度 = (档口, 岗位)。档口级与门店级用同一份结果聚合（调用方在 JS 里滚），
-- 不另发一条 SQL —— 这也正是"同一次取数"的含义。
CREATE OR REPLACE FUNCTION fn_station_fill(p_store bigint, p_on date DEFAULT NULL)
RETURNS TABLE (
  store_station_id   bigint,
  station_id         bigint,
  station_code       varchar,
  station_name       varchar,
  line_code          varchar,
  station_seq        int,
  position_id        bigint,
  position_code      varchar,
  position_name      varchar,
  position_level     smallint,
  headcount          int,     -- 该岗位档口编；NULL = 这个岗位当期没定编
  holders            int,     -- 到岗（这个岗位几个人在岗）—— 岗位级 岗次 = 人头
  gap                int,     -- 编制 − 到岗；NULL = 未定编
  gap_since          date,    -- 从哪天开始缺；只有 gap > 0 时才有值
  days_open          int,     -- p_on − gap_since
  holder_names       text,
  station_quota      int,     -- 档口编（岗次）；NULL = 这个档口当期一个岗都没定编
  station_slots      int,     -- 档口到岗（岗次，一人两岗算两次）
  station_holders    int,     -- 档口到岗（人头，一人两岗算一次）★ 与上面那个不是一回事
  station_gap        int,     -- 档口缺岗（岗次）
  store_quota        int,     -- 门店编；NULL = 门店没定编
  store_heads        int,     -- 门店到岗（**人头**，按 cost_org 口径）
  store_unallocated  int,     -- 门店编 − Σ已定编档口编 = 还没分到档口的部分
  station_count      int      -- 这家店当期的档口数
)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE
  v_on     date        := COALESCE(p_on, public.app_today());
  v_period varchar(7)  := to_char(COALESCE(p_on, public.app_today()), 'YYYY-MM');
  v_part   varchar(16);
BEGIN
  -- 兼职口径：默认占编也算到岗；'exclude' 时小时工既不占编也不计到岗
  -- （两件事必须同时排除，只排除一边会出现"到岗 > 编制"）
  SELECT v.value_text INTO v_part
    FROM public.fn_policy_effective('HC_STATION_PARTTIME', p_store, v_on) v;
  v_part := COALESCE(v_part, 'occupy');

  RETURN QUERY
  WITH ss AS (
    -- 这家店当期有效的档口（区间语义，所以关了再开的两个实例各归各的期间）
    SELECT s.id, s.station_id, s.seq AS ss_seq
      FROM public.store_station s
     WHERE s.store_id = p_store
       AND daterange(s.opened_at, s.closed_at, '[]') @> v_on
  ),
  meta AS (
    SELECT ss.id AS store_station_id, st.id AS station_id, st.code, st.name,
           st.line_code, COALESCE(ss.ss_seq, st.seq) AS seq
      FROM ss JOIN public.station st ON st.id = ss.station_id
  ),
  -- 当期编制：每个 (档口,岗位) 取该期最大版本
  sp AS (
    SELECT DISTINCT ON (x.store_station_id, x.position_id)
           x.store_station_id, x.position_id, x.headcount
      FROM public.station_position x
      JOIN ss ON ss.id = x.store_station_id
     WHERE x.period = v_period
     ORDER BY x.store_station_id, x.position_id, x.version DESC
  ),
  -- 明细骨架：有定编的档口按岗位展开；一个岗都没定编的档口给一行 position_id = NULL。
  -- ★ 后者是「未定编」这个状态能出现在页面上的唯一来源 —— 少了它，
  --   未定编的档口会从列表里整条消失（而不是显示成"缺 0"）。
  spx AS (
    SELECT sp.store_station_id, sp.position_id, sp.headcount, true AS configured
      FROM sp
    UNION ALL
    SELECT ss.id, NULL::bigint, NULL::int, false
      FROM ss
     WHERE NOT EXISTS (SELECT 1 FROM sp WHERE sp.store_station_id = ss.id)
  ),
  -- 到岗的人（人级，后面按岗位/档口两级滚）
  fillp AS (
    SELECT DISTINCT spx.store_station_id, spx.position_id, pp.person_id, pe.full_name
      FROM spx
      JOIN public.person_position pp ON pp.position_id = spx.position_id
                                    AND daterange(pp.valid_from, pp.valid_to, '[]') @> v_on
      JOIN public.employment e ON e.person_id = pp.person_id
                              AND daterange(e.hire_date, e.leave_date, '[]') @> v_on
      JOIN public.employee_org_assignment a ON a.employee_id = pp.person_id
                                           AND a.dim_code = 'cost_org'
                                           AND daterange(a.valid_from, a.valid_to, '[]') @> v_on
                                            -- ★ 等值，不用 path LIKE：跨店支援天天发生，
                                            --   LIKE 会把"人在这家店、成本在那家店"的支援人员串进来
                                           AND a.org_id = p_store
      JOIN public.person pe ON pe.id = pp.person_id
     WHERE spx.configured
       -- 兼职排除口径（policy）：只在显式选了 exclude 时才生效
       AND (v_part <> 'exclude'
            OR public.fn_pay_basis(pp.person_id, v_period) <> 'hour')
  ),
  fill AS (
    SELECT f.store_station_id, f.position_id,
           count(DISTINCT f.person_id)::int AS holders,
           string_agg(DISTINCT f.full_name, '、') AS names
      FROM fillp f
     GROUP BY 1, 2
  ),
  st_agg AS (
    -- 档口到岗：岗次 = Σ 各岗位人数；人头 = 档口内去重（一人两岗只算一次）
    SELECT spx.store_station_id,
           sum(CASE WHEN spx.configured THEN COALESCE(f.holders, 0) ELSE 0 END)::int AS slots,
           (SELECT count(DISTINCT f2.person_id)::int FROM fillp f2
             WHERE f2.store_station_id = spx.store_station_id) AS heads
      FROM spx
      LEFT JOIN fill f ON f.store_station_id = spx.store_station_id
                      AND f.position_id = spx.position_id
     GROUP BY spx.store_station_id
  ),
  st_q AS (
    SELECT spx.store_station_id,
           CASE WHEN bool_or(spx.configured)
                THEN COALESCE(sum(spx.headcount) FILTER (WHERE spx.configured), 0)::int
           END AS quota
      FROM spx
     GROUP BY spx.store_station_id
  ),
  store_q AS (
    SELECT public.fn_hc_quota(p_store, v_period) AS quota
  ),
  -- 门店到岗（人头）。与档口到岗**同一个维度**（cost_org）、同一个在职判定 ——
  -- 否则"门店 10 人 / 档口 11 岗次"里那 1 个差会被读成算错，而不是一人两岗。
  -- ★ 注意这与 /api/org/tree 的"在编"不是一个问题：那边按 attendance_org
  --   （谁在这家店打卡），这边按 cost_org（人算在哪家店的成本）。
  --   跨店支援时两个数本来就不同，且都对 —— 页面要标口径，不要并排做加减。
  store_heads AS (
    SELECT count(DISTINCT a.employee_id)::int AS n
      FROM public.employee_org_assignment a
      JOIN public.employment e ON e.person_id = a.employee_id
                              AND daterange(e.hire_date, e.leave_date, '[]') @> v_on
     WHERE a.dim_code = 'cost_org'
       AND daterange(a.valid_from, a.valid_to, '[]') @> v_on
       AND a.org_id = p_store
       AND (v_part <> 'exclude'
            OR public.fn_pay_basis(a.employee_id, v_period) <> 'hour')
  ),
  alloc AS (
    SELECT COALESCE(sum(q.quota), 0)::int AS allocated, count(*)::int AS n FROM st_q q
  )
  SELECT m.store_station_id, m.station_id, m.code, m.name, m.line_code, m.seq,
         spx.position_id, p.code, p.name, p.level,
         spx.headcount,
         COALESCE(f.holders, 0)::int AS holders,
         CASE WHEN spx.configured THEN spx.headcount - COALESCE(f.holders, 0) END AS gap,
         g.since AS gap_since,
         CASE WHEN g.since IS NOT NULL THEN v_on - g.since END AS days_open,
         f.names,
         q.quota AS station_quota,
         COALESCE(a.slots, 0)::int AS station_slots,
         COALESCE(a.heads, 0)::int AS station_holders,
         CASE WHEN q.quota IS NOT NULL THEN q.quota - COALESCE(a.slots, 0) END AS station_gap,
         (SELECT sq.quota FROM store_q sq) AS store_quota,
         (SELECT sh.n FROM store_heads sh) AS store_heads,
         CASE WHEN (SELECT sq.quota FROM store_q sq) IS NOT NULL
              THEN (SELECT sq.quota FROM store_q sq) - (SELECT al.allocated FROM alloc al) END AS store_unallocated,
         (SELECT al.n FROM alloc al) AS station_count
    FROM meta m
    JOIN spx ON spx.store_station_id = m.store_station_id
    LEFT JOIN public.position p ON p.id = spx.position_id
    LEFT JOIN fill f ON f.store_station_id = spx.store_station_id
                    AND f.position_id = spx.position_id
    LEFT JOIN st_agg a ON a.store_station_id = m.store_station_id
    LEFT JOIN st_q q ON q.store_station_id = m.store_station_id
    -- gap_since 只算一次（下面两处都要用它），而且只在不缺人时不算 ——
    -- 这一列的代价是"每个缺口行一次断点求值"，不缺时没必要付。
    LEFT JOIN LATERAL (
      SELECT public.fn_sp_gap_since(m.store_station_id, spx.position_id, v_on) AS since
       WHERE spx.configured AND spx.headcount - COALESCE(f.holders, 0) > 0
    ) g ON true
   ORDER BY m.seq, m.code, p.level, p.name;
END;
$$;

