-- ============================================================================
-- 172_store_station.sql · 门店 → 档口 → 岗位 → 编制
-- ----------------------------------------------------------------------------
-- 餐饮的门店里，除了店长/副店长，还有一层"档口"：炉灶、砧板、打荷、水台、
-- 上什、烧腊、点心、前厅…… 不同门店配不同种类、不同数量的档口。
-- 组织架构图上要看得见每条线有多少人、到岗多少、缺几个，点开能看"哪个岗位缺几个"。
--
-- 这件事有三种落法，本文件选了第三种。前两种的错法各写在下面 ——
-- 因为它们都比第三种"看起来更自然"，而每一个都会**静默**破掉已有机制。
--
-- ----------------------------------------------------------------------------
-- ✗ 错法一：给 org_unit.kind 加一个 'station'
-- ----------------------------------------------------------------------------
-- "档口就是一个小部门嘛" —— 这句话对了一半。它确实是个分组，但它不是**组织**：
-- 它不参与四维归属、不参与权限行闸、不参与编制下分。加进树里，一次破五处，
-- 而每一处都不是在档口自己的测试里暴露的：
--
--   ① ck_ou_kind 直接把 'station' 拒掉（076:39-41），迁移被迫改约束 →
--      SUITE.OG 的判据面跟着变。
--   ② **门店一旦有了子节点，所有门店级招聘需求全报 E_RQ_NOT_LEAF**
--      （025:174：需求只能挂在叶子组织）。fn_rq_guard 是 requisition 的
--      BEFORE INSERT 触发器（025:212-214），于是招聘功能整体瘫痪，
--      而报错信息会把人引向"为什么门店不能开需求"，不是"谁加了档口"。
--   ③ 编制被双计：fn_hc_used 按 cost_org 的 path 前缀累加子树（022:113-126），
--      fn_hc_allocated 按直接子组织的额度累加（022:92-100）。
--      人挂档口后，门店的 used 已含这批人，allocated 又含档口额度 ——
--      同一批人扣两次。而 fn_hc_set 的"子项≤父项"校验（022:178-193）照样通过，
--      fn_hc_hireable 只是静默变成负数，没有任何一处报错。
--   ④ **门店 HR 一个人都看不到**：fn_scope_people 用 cost_org **精确匹配**
--      scope 节点（170:29-45），不是 path 前缀。人挂档口后，
--      `a.org_id = 档口id` 匹配不上门店节点 → fail-closed 返回 0 行。
--      （fail-closed 是它的优点；这里它变成"门店 HR 打开人事档案是空的"。）
--   ⑤ /api/org/tree 的直属人数是 `WHERE a.org_id = t.id` 精确匹配
--      （server.mjs:2744）→ 门店卡片人数塌成 0。
--
-- ✗ 错法二：给 position 加一列 headcount
-- ----------------------------------------------------------------------------
-- 083 的 position 是**集团岗位词表**，`uk_pos_code UNIQUE (code)`（083:31）：
-- "炉头"这个岗位全集团只有一行，10 家店共用。在这唯一一行上写 headcount，
-- 只能写一个数 —— 没法表达"A 店 2 个炉头、B 店 3 个炉头"。
-- **编制必须落在 (门店, 档口, 岗位) 这个三元组上，不能落在岗位档案上。**
--
-- ✗ 错法三：复用 headcount_budget 加一个可空 station_id
-- ----------------------------------------------------------------------------
-- 那个表的形状是"一行 = 一个组织的额度"，而 fn_hc_quota / allocated / used /
-- hireable / set / over / uncovered / slack 八个函数、fn_hc_guard 触发器、
-- /api/headcount/set、MCP 工具 headcount_set 全都建立在这个形状上。
-- 加一列可空 station_id 会让这八个函数**全部**需要 `AND station_id IS NULL`
-- —— 漏写一处就是编制翻倍，而漏写不会报错。
--
-- ----------------------------------------------------------------------------
-- ✓ 本文件的落法：三张纯增量表，org_unit / position / employee_org_assignment
--   / headcount_budget / sys_perm_dim 一个都不改
-- ----------------------------------------------------------------------------
--   station          档口词表（集团级，带品牌线）—— 与 position 同位：都是词表
--     └ store_station   这家店有哪几个档口（带启停区间，同店同档口同一时点唯一）
--          └ station_position  这个档口配几个什么岗、当期编制几个
--
-- 于是：
--   · 四维归属仍挂门店 —— "人在哪个档口"由 person_position + station_position
--     **推导**，不落列、不入维度（与 022:128-130「占编是派生的，不落列」同理：
--     存一列 station_id 的话，入职/转岗/调店三条路径各自更新它，必然漂）。
--   · 门店编 ≥ Σ档口编，差额是"还没分到档口的编"（店长/副店长这类不进档口的岗）
--     —— 与 022:10-13「下分是分配，不是复制」同一条规则。
--   · 迁移是纯增量：172 可以单独 revert 而不影响任何现有功能，
--     因为没有任何现有对象引用这三张表。
--
-- ----------------------------------------------------------------------------
-- 三个数字的口径（这是本文件最容易被问住的地方，先写清）
-- ----------------------------------------------------------------------------
--   编制（hc）   = 当期 station_position 里各 (档口,岗位) 的最大 version 之和
--   到岗        = 在编 + 在职 + cost_org 落在**这家店** + 当期任职在这个岗位上
--   缺岗        = 编制 − 到岗（都按**岗次**算）
--
--   ★ 门店数**人头**，档口数**岗次** —— 这两个数本来就该不同，不能相减。
--     083:152-153 已经定了："一人多岗时，他在每个岗位下都算一次 ——
--     这是对的：编制看的是'岗位有没有人'，不是'人头去重'。"
--     所以一个人兼炉头 + 打荷，档口到岗是 2 个岗次、1 个人头。
--     fn_station_fill 两个数都给（slots 与 holders），页面分栏显示。
--
--   ★ 「未定编」≠「缺 0」。当期一行 station_position 都没有 → 编制与缺岗都返回
--     NULL，不是 0。依据 022:242-244（"没额度就没有判据：占编 200 人也不会超编，
--     而报表上一片绿"）与 server.mjs:2767-2771 的既有实现。
--
--   ★ 外包不占编、不算到岗。outsourced_worker 刻意没有 person_id（019:64-67），
--     硬算等于给外包编一个假身份，把他拉进"按 person"的每一张清单。
--     外包的真身是工时（supplier_timesheet，019:95），接口另给一栏，不折算成 FTE
--     —— 折算需要"标准月工时"，而全系统工时口径只有 schedule_segment 一处
--     （150:25-26 明确"班组不承载工时……把组也当成工时来源就有了第二条算薪口径"）。
--     所以 fn_sp_guard 直接**拒绝**把 is_outsourced 的岗位配进档口编制。
--
--   ★ 兼职（employment.pay_basis = 'hour'）默认**占编也算到岗** ——
--     他的合同在我方，不占编就会出现"招进来不占编"的口子。
--     要不要排除由 policy HC_STATION_PARTTIME 决定（默认 occupy）。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 档口词表
-- ---------------------------------------------------------------------------
-- 独立一张词表而不是把名字写在 store_station 上：改一次名要 UPDATE 10 家店，
-- 漏更新的那 2 家会让报表按名字分组时**静默分裂成两个档口** ——
-- 与 086:44-46（fn_org_rename 拒绝同父重名）防的是同一件事。
CREATE TABLE IF NOT EXISTS station (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code       varchar(32) NOT NULL,
  name       varchar(64) NOT NULL,
  -- 线：后厨 / 前厅 / 后勤。组织图上按这条线分组，与"档口"是两个正交的维度
  line_code  varchar(16) NOT NULL DEFAULT 'kitchen',
  -- 品牌线：这个档口属于哪条产品线。'common' = 任何店都有。
  -- ★ 只在**铺档口那一刻**当筛选条件（见 §3 的 fn_station_choices）。
  --   不落到门店上、不做长期校验 —— 理由写在 fn_store_station_preset 的注释里。
  brand_line varchar(24) NOT NULL DEFAULT 'common',
  seq        int         NOT NULL DEFAULT 100,
  is_active  boolean     NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uk_station_code UNIQUE (code),
  CONSTRAINT ck_station_line CHECK (line_code IN ('kitchen','floor','support'))
);

COMMENT ON TABLE station IS
  '档口词表（172）。就是西餐 Station Chef System 里的 Station —— 中餐叫"档口"、'
  '西餐叫 station、粤菜叫"线"，同一件事。集团唯一，10 家店共用，'
  '所以**编制不能挂在这张表上**（那只能存一个数），要挂 station_position。';

COMMENT ON COLUMN station.brand_line IS
  '品牌线：common=通用 / cantonese=粤菜港式 / sichuan=川菜 / tempura=天妇罗专门店 / '
  'noodle=面馆 / hotpot=火锅 / western=西餐。用于铺档口时筛选 —— '
  '天妇罗专门店的预置里不该出现烧腊档。';

-- 品牌线是**开放集合**（每接一个品牌就多一条），所以 CHECK 用 DO 块写，
-- 新增品牌线时按 076:37-40 的老办法 DROP + ADD 一条约束，不另立一套词表。
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_station_brand') THEN
    ALTER TABLE station ADD CONSTRAINT ck_station_brand CHECK (brand_line IN
      ('common','cantonese','sichuan','tempura','noodle','hotpot','western'));
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_station_brand ON station (brand_line, seq)
  WHERE is_active;

-- ---------------------------------------------------------------------------
-- 2. 门店 × 档口
-- ---------------------------------------------------------------------------
-- ★ 不用 uk(store_id, station_id) + closed_at，而是**区间 + 排他约束**（与
--   014:28-32 的 ex_eoa_no_overlap、083:51-53 的 ex_pp_no_overlap 同法）。
--   两个理由：
--     ① 关档口再开是真实事件（装修、旺季临时加个炸物台）。用 closed_at 加
--        UPDATE 会把这中间的空档抹掉，而"3 月到 6 月这家店没有烧腊档"
--        正是成本分析要看的事实；
--     ② 到岗人数要**唯一归属**：同店同档口在同一时点只能有一个实例，
--        靠排他约束守，而不是靠"记得先关再开"。
CREATE TABLE IF NOT EXISTS store_station (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id   bigint NOT NULL REFERENCES org_unit(id),
  station_id bigint NOT NULL REFERENCES station(id),
  seq        int    NOT NULL DEFAULT 100,   -- 店内展示顺序（炉灶在前、水台在后）
  opened_at  date   NOT NULL,
  closed_at  date,
  CONSTRAINT ck_ss_span CHECK (closed_at IS NULL OR closed_at >= opened_at)
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ex_ss_no_overlap') THEN
    ALTER TABLE store_station ADD CONSTRAINT ex_ss_no_overlap
      EXCLUDE USING gist (store_id WITH =, station_id WITH =,
                          daterange(opened_at, closed_at, '[]') WITH &&);
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_ss_store ON store_station (store_id);

COMMENT ON TABLE store_station IS
  '门店 × 档口（172）。"不同门店配不同种类、不同数量的档口"就是这张表里有几行。'
  '★ 同一家店同一时点只能有一个同名档口实例（ex_ss_no_overlap）—— '
  '到岗人数的唯一归属靠它，不靠人记得先关再开。';

-- 门店必须是 kind='dept' 的启用节点。挂在 group/region 上会让"这家店的档口"
-- 这个词失去意义（区域级档口 = 又一个组织层，正是本文件开头否掉的那种设计）。
--
-- ★ 错误码前缀用 E_STN_（statioN）而不是 E_SS_：E_SS_* 已经被 087/088 的
--   工资表结构（salary structure）占了（见 errors.mjs）。同名前缀的错混在日志里，
--   排查的人会先去看工资表。
CREATE OR REPLACE FUNCTION fn_stn_guard() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_kind varchar(16); v_active boolean; v_name varchar(64);
BEGIN
  SELECT o.kind, o.is_active, o.name INTO v_kind, v_active, v_name
    FROM public.org_unit o WHERE o.id = NEW.store_id;
  IF v_kind IS NULL THEN
    RAISE EXCEPTION 'E_STN_NO_STORE: 组织 % 不存在', NEW.store_id;
  END IF;
  IF v_kind <> 'dept' THEN
    RAISE EXCEPTION 'E_STN_NOT_STORE: 档口只能挂在部门（门店是部门名的一种）下，% 的类型是 %',
      v_name, v_kind;
  END IF;
  IF NOT v_active THEN
    RAISE EXCEPTION 'E_STN_STORE_INACTIVE: 门店「%」已停用，不能再挂档口', v_name;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_stn_guard ON store_station;
CREATE TRIGGER trg_stn_guard
  BEFORE INSERT OR UPDATE ON store_station
  FOR EACH ROW EXECUTE FUNCTION fn_stn_guard();

-- ---------------------------------------------------------------------------
-- 3. 档口 × 岗位 × 月 × 版本编制
-- ---------------------------------------------------------------------------
-- 形状照 022 的 headcount_budget（月粒度 + 版本行 + 只增不改），**不发明第二套**：
-- "上个月这个档口几个编"必须还能查出来。就地 UPDATE 之后，上个月缺岗的事实
-- 会随着编制被调低而消失，而没有任何一处报错。
CREATE TABLE IF NOT EXISTS station_position (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_station_id bigint      NOT NULL REFERENCES store_station(id),
  position_id      bigint      NOT NULL REFERENCES position(id),
  period           varchar(7)  NOT NULL,
  version          int         NOT NULL,
  headcount        int         NOT NULL,
  set_by           varchar(64) NOT NULL,
  reason           varchar(200) NOT NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uk_sp UNIQUE (store_station_id, position_id, period, version),
  CONSTRAINT ck_sp_period CHECK (period ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  CONSTRAINT ck_sp_hc     CHECK (headcount >= 0),
  CONSTRAINT ck_sp_ver    CHECK (version >= 1),
  CONSTRAINT ck_sp_reason CHECK (length(btrim(reason)) >= 4)
);

CREATE INDEX IF NOT EXISTS ix_sp_lookup ON station_position (store_station_id, period, position_id);

COMMENT ON TABLE station_position IS
  '档口编制（172）：这个门店的这个档口，配几个什么岗、当期编几个。'
  '月粒度 + 版本行，与 headcount_budget 同构 —— 历史可查，只增不改。';

-- 只增不改（与 022:65-76 的 trg_hb_append_only 同一条理由）
CREATE OR REPLACE FUNCTION fn_sp_append_only() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  RAISE EXCEPTION 'E_SP_APPEND_ONLY: 档口编制只增不改（调编请用 fn_sp_set 追加新版本）';
END;
$$;

DROP TRIGGER IF EXISTS trg_sp_append_only ON station_position;
CREATE TRIGGER trg_sp_append_only
  BEFORE UPDATE OR DELETE ON station_position
  FOR EACH ROW EXECUTE FUNCTION fn_sp_append_only();

-- 该门店当期的 Σ 档口编（只算**期末仍然开着**的档口；未定编的档口不计入）
--
-- ★ 必须带"期末还开着"这个条件。不带的话会出两个口径：
--   3-10 关掉砧板档之后，页面按"还开着的档口"算出 3 个编，
--   而这里仍把砧板档那 2 个算进去得 5 —— 于是
--   "还没分到档口"（门店编 − Σ档口编）在同一屏上算出两个数，
--   而两个数都对得上自己的算式。实测过：关档前 5=5，关档后 5 vs 3。
--
-- ★ 用**期末日**而不是当天，与 022:119-125 的 fn_hc_used 同一个约定：
--   编制是"这一期有效"，一期之内关掉的档口从**下一期**起才退出合计，
--   否则 3 月 30 日关一个档口会把 3 月整月的编制追溯改小。
CREATE OR REPLACE FUNCTION fn_store_station_quota(p_store bigint, p_period varchar)
RETURNS int
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT COALESCE(sum(x.headcount), 0)::int
    FROM (
      SELECT DISTINCT ON (sp.store_station_id, sp.position_id) sp.headcount
        FROM public.station_position sp
        JOIN public.store_station ss ON ss.id = sp.store_station_id
       WHERE ss.store_id = p_store
         AND sp.period = p_period
         AND daterange(ss.opened_at, ss.closed_at, '[]') @>
             (to_date(p_period || '-01','YYYY-MM-DD') + interval '1 month - 1 day')::date
       ORDER BY sp.store_station_id, sp.position_id, sp.version DESC
    ) x;
$$;

COMMENT ON FUNCTION fn_store_station_quota IS
  '门店当期 Σ 档口编（岗次）。★ 必须按 (档口,岗位) 各自取 max(version) 再求和 ——'
  '写成"先按档口取 max(version) 再 sum"会给炉头改编时把砧板那一行漏掉。';

-- 档口编制的三条写入判据。放在触发器而不是只放在 fn_sp_set 里：
-- MCP、批量导入、手工 INSERT 都会绕过函数，而绕过之后的错不会报错。
CREATE OR REPLACE FUNCTION fn_sp_guard() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_store      bigint;
  v_out        boolean;
  v_pos_name   varchar(64);
  v_other      bigint;
  v_store_q    int;
  v_allocated  int;
  v_old        int;
  v_st_name    varchar(64);
BEGIN
  SELECT ss.store_id INTO v_store FROM public.store_station ss WHERE ss.id = NEW.store_station_id;
  IF v_store IS NULL THEN
    RAISE EXCEPTION 'E_SP_NO_STATION: 门店档口 % 不存在', NEW.store_station_id;
  END IF;

  SELECT p.is_outsourced, p.name INTO v_out, v_pos_name
    FROM public.position p WHERE p.id = NEW.position_id;

  -- ① 外包岗不进档口编制。编的是"内部人头预算"，外包按工时结算，
  --    两件事混在一张表上，会让"编制 3 / 到岗 3"里站着两个外包 —— 而工资单上没有他们。
  IF v_out THEN
    RAISE EXCEPTION 'E_SP_OUTSOURCED: 岗位「%」是外包岗，不占内部编制（外包按工时另行统计）',
      v_pos_name;
  END IF;

  -- ② 同一家店内，一个岗位只能属于一个档口。
  --    否则"人在哪个档口"有两个答案，两个档口各算一次到岗 ——
  --    档口到岗之和 > 实际人力，缺岗被低估，而每一行单独看都合规。
  SELECT ss2.id INTO v_other
    FROM public.station_position sp2
    JOIN public.store_station ss2 ON ss2.id = sp2.store_station_id
   WHERE ss2.store_id = v_store
     AND sp2.position_id = NEW.position_id
     AND sp2.period = NEW.period
     AND sp2.store_station_id <> NEW.store_station_id
   LIMIT 1;
  IF v_other IS NOT NULL THEN
    SELECT st.name INTO v_st_name
      FROM public.store_station ss3 JOIN public.station st ON st.id = ss3.station_id
     WHERE ss3.id = v_other;
    RAISE EXCEPTION 'E_SP_CROSS_STATION: 岗位「%」在本店 % 已属于档口「%」，'
      '同一家店内一个岗位只能属一个档口（否则到岗人数没有唯一归属）',
      v_pos_name, NEW.period, v_st_name;
  END IF;

  -- ③ Σ档口编 ≤ 门店编。不约束的话会出现"门店 12/12 满编，炉灶档还缺 2 人" ——
  --    系统给出两条互相矛盾的结论，而操作员会去调其中一条，把真实情况盖掉。
  --    ★ 门店没定编时不拦（与 022:265-278 的 fn_hc_guard 同一条规矩：
  --      没额度就没有判据，但不拦的东西必须被 fn_station_fill 的 headcount=NULL 报出来）。
  v_store_q := public.fn_hc_quota(v_store, NEW.period);
  IF v_store_q IS NOT NULL THEN
    v_allocated := public.fn_store_station_quota(v_store, NEW.period);
    SELECT COALESCE(max(headcount), 0) INTO v_old
      FROM public.station_position sp4
     WHERE sp4.store_station_id = NEW.store_station_id
       AND sp4.position_id = NEW.position_id
       AND sp4.period = NEW.period;
    IF v_allocated - v_old + NEW.headcount > v_store_q THEN
      RAISE EXCEPTION 'E_SP_OVER_STORE: 门店编 % 个，档口已分 % 个，本次要 % 个（超出 %）',
        v_store_q, v_allocated - v_old, NEW.headcount,
        (v_allocated - v_old + NEW.headcount - v_store_q);
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_sp_guard ON station_position;
CREATE TRIGGER trg_sp_guard
  BEFORE INSERT ON station_position
  FOR EACH ROW EXECUTE FUNCTION fn_sp_guard();

