CREATE OR REPLACE FUNCTION fn_station_upsert(
  p_code varchar, p_name varchar,
  p_line varchar DEFAULT 'kitchen', p_brand varchar DEFAULT 'common',
  p_seq int DEFAULT 100
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_id bigint;
BEGIN
  IF p_name IS NULL OR length(btrim(p_name)) < 2 THEN
    RAISE EXCEPTION 'E_STATION_NAME: 档口名称至少 2 个字';
  END IF;
  IF p_code IS NULL OR length(btrim(p_code)) < 2 THEN
    RAISE EXCEPTION 'E_STATION_CODE: 档口编码至少 2 个字符';
  END IF;
  INSERT INTO public.station(code, name, line_code, brand_line, seq)
  VALUES (btrim(upper(p_code)), btrim(p_name), p_line, p_brand, p_seq)
  ON CONFLICT (code) DO UPDATE
     SET name = EXCLUDED.name, line_code = EXCLUDED.line_code,
         brand_line = EXCLUDED.brand_line, seq = EXCLUDED.seq
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

-- 铺档口时"可选哪些档口"：这就是"按品牌线筛选"的落点。
-- 天妇罗专门店走 p_brand='tempura'，返回里没有烧腊档/点心档/打荷档。
CREATE OR REPLACE FUNCTION fn_station_choices(p_brand varchar DEFAULT 'common')
RETURNS TABLE (station_id bigint, code varchar, name varchar,
               line_code varchar, brand_line varchar, seq int)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT s.id, s.code, s.name, s.line_code, s.brand_line, s.seq
