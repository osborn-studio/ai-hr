-- ============================================================================
-- 052_person_hire.sql · 从 offer 到在职：第六个「门没有」，而且撞上第六次同一个坑
-- ----------------------------------------------------------------------------
-- 025 写了 fn_offer_onboard（入职 = 落任职 + 归属 + 月薪 + offer 状态），
-- 而且**有断言**（R 组那两条）。但它只被测试调用过，**没有接口层**：
-- 于是「从 offer 到在职」这条链在界面上走不通 —— 招聘漏斗的末端是断的。
--
-- 更麻烦的是它需要先有一个 person。而这个仓库里**没有任何"新建员工"的入口**：
-- person 只能靠种子插。所以补这一层时必然要写 fn_person_create，
-- 而那一刻就撞上了本仓的第六次同一个坑：
--
--   person.id 是 `bigint PRIMARY KEY`，**没有生成方式**。
--   种子用显式 id 插，所以一直没红；一旦由函数插入，就是 23502 not-null on id。
--
-- 这次它**被机器判据抓到了**（Q14：会被函数 INSERT 的表，主键必须有生成方式），
-- 而不是等到某天运行时炸。这条判据本身就是为这个坑写的，这是它第一次真的救了场。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 补上生成方式（第六次）
-- ---------------------------------------------------------------------------
ALTER TABLE person ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

-- ★ 序列对齐**不在这里做**：迁移跑完时表还是空的，这里 setval 出来的值
--   会被后面的种子（显式 id）越过，于是第一次自动插入撞主键。
--   对齐统一放在"种子之后"（server.mjs 与 test/run.mjs 的 syncIds），
--   而且做成**扫全部 IDENTITY 列**的通用收尾 —— 一张表一张表地记，
--   就会像这次一样漏掉一个。

-- ---------------------------------------------------------------------------
-- 2. 最小的人事建档
-- ---------------------------------------------------------------------------
-- 刻意只收姓名。真实系统这里要身份证/手机号/银行卡，而那些字段的采集、
-- 加密与授权是另一套东西（003 的字段权限管"谁能看"，不管"怎么收"）。
-- 收一个姓名能跑通"offer → 在职"这条链，且不会假装已经把人事档案做完。
CREATE OR REPLACE FUNCTION fn_person_create(p_name varchar)
RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_id bigint;
BEGIN
  IF p_name IS NULL OR length(btrim(p_name)) < 1 THEN
    RAISE EXCEPTION 'E_PERSON_NO_NAME: 姓名不能为空';
  END IF;
  INSERT INTO public.person(full_name) VALUES (btrim(p_name)) RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_person_create IS
  '最小人事建档：只收姓名。身份证/银行卡的采集与加密不在这一层，'
  '不要因为"反正要收"就在这里多收几个字段 —— 字段权限管的是"谁能看"，不是"怎么收"。';

-- ---------------------------------------------------------------------------
-- 3. 入职：offer → 任职 + 归属 + 月薪（复用 025，不重写一遍）
-- ---------------------------------------------------------------------------
-- ★ 为什么包一层而不是让服务层自己插：
--   "任职 / 归属 / 月薪 三处必须同源（都来自 offer 的最新版本）"这条判断
--   已经在 fn_offer_onboard 里了。服务层再写一遍，就会出现两份口径，
--   而它们的差别会在某次 offer 改薪之后才显现。
CREATE OR REPLACE FUNCTION fn_hire_from_offer(
  p_offer       bigint,
  p_person      bigint,          -- NULL = 按 offer 上的候选人姓名新建
  p_hire_date   date,
  p_legal_entity bigint,
  p_by          varchar
) RETURNS TABLE (person_id bigint, employment_id bigint)
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_person bigint; v_emp bigint; v_name varchar(64);
BEGIN
  IF p_hire_date IS NULL THEN
    RAISE EXCEPTION 'E_HIRE_NO_DATE: 入职日必填（"今天"在跨月那一天会变成另一天）';
  END IF;

  SELECT o.candidate_name INTO v_name FROM public.offer o WHERE o.id = p_offer;
  IF v_name IS NULL THEN
    RAISE EXCEPTION 'E_OFFER_NOT_FOUND: offer % 不存在', p_offer;
  END IF;

  v_person := COALESCE(p_person, public.fn_person_create(v_name));

  v_emp := public.fn_offer_onboard(p_offer, v_person, p_hire_date, p_legal_entity, p_by);

  RETURN QUERY SELECT v_person, v_emp;
END;
$$;

COMMENT ON FUNCTION fn_hire_from_offer IS
  '入职：p_person 为空时按 offer 上的候选人姓名建档。'
  '任职/归属/月薪的写入仍走 fn_offer_onboard —— 一份口径，不另写一遍。';

