-- ---------------------------------------------------------------------------
-- 1. 定义的结构校验：发布时就挡住，不留到启动时
-- ---------------------------------------------------------------------------
-- 一个"发布成功、跑起来才报错"的模板，等于把失败推到最不该出现的地方：
-- 申请人的第一次提交。那时他只会看到"发起失败"，不知道该找谁。
CREATE OR REPLACE FUNCTION fn_appr_validate_def(p_def jsonb)
RETURNS void
LANGUAGE plpgsql
IMMUTABLE
SET search_path = ''
AS $$
DECLARE
  v_n int; v_prev int := 0; s jsonb; r jsonb; v_seq int;
BEGIN
  IF p_def IS NULL OR jsonb_typeof(p_def -> 'steps') <> 'array' THEN
    RAISE EXCEPTION 'E_APPR_DEF_INVALID: 定义必须有 steps 数组';
  END IF;

  v_n := jsonb_array_length(p_def -> 'steps');
  IF v_n = 0 THEN
    RAISE EXCEPTION 'E_APPR_DEF_INVALID: steps 不能为空（空流程＝自动通过）';
  END IF;

  FOR s IN SELECT * FROM jsonb_array_elements(p_def -> 'steps') LOOP
    v_seq := COALESCE((s ->> 'seq')::int, 0);
    -- ★ seq 必须从 1 连续。允许跳号，就会出现"第 2 步之后没有了"的单子
    --   永远停在 running，而它看起来只是"还没人审"。
    IF v_seq <> v_prev + 1 THEN
      RAISE EXCEPTION 'E_APPR_DEF_INVALID: steps 的 seq 必须从 1 连续（期望 %，收到 %）',
        v_prev + 1, v_seq;
    END IF;
    v_prev := v_seq;

    IF COALESCE(s ->> 'mode', 'any') NOT IN ('any', 'all') THEN
      RAISE EXCEPTION 'E_APPR_DEF_INVALID: 第 % 步的 mode 只能是 any / all', v_seq;
    END IF;

    IF jsonb_typeof(s -> 'resolvers') <> 'array' OR jsonb_array_length(s -> 'resolvers') = 0 THEN
      RAISE EXCEPTION 'E_APPR_DEF_INVALID: 第 % 步没有审批人来源（resolvers 为空）', v_seq;
    END IF;

    FOR r IN SELECT * FROM jsonb_array_elements(s -> 'resolvers') LOOP
      IF COALESCE(r ->> 'kind', '') NOT IN ('role', 'user') THEN
        RAISE EXCEPTION 'E_APPR_DEF_INVALID: 第 % 步的 resolver.kind 只能是 role / user', v_seq;
      END IF;
      IF (r ->> 'kind') = 'role' AND COALESCE((r ->> 'role_id')::bigint, 0) <= 0 THEN
        RAISE EXCEPTION 'E_APPR_DEF_INVALID: 第 % 步 role resolver 缺 role_id', v_seq;
      END IF;
      IF (r ->> 'kind') = 'user' AND COALESCE((r ->> 'user_id')::bigint, 0) <= 0 THEN
        RAISE EXCEPTION 'E_APPR_DEF_INVALID: 第 % 步 user resolver 缺 user_id', v_seq;
      END IF;
    END LOOP;
  END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION fn_atv_validate() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  -- 只校验非草稿：草稿允许边写边存，这是草稿存在的理由
  IF NEW.status <> 'draft' THEN
    PERFORM public.fn_appr_validate_def(NEW.definition);
    IF NEW.effective_from IS NULL THEN
      RAISE EXCEPTION 'E_APPR_NO_EFFECTIVE: 发布版本必须给 effective_from';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_atv_validate BEFORE INSERT OR UPDATE ON approval_template_version
  FOR EACH ROW EXECUTE FUNCTION fn_atv_validate();

-- ---------------------------------------------------------------------------
-- 2. 业务侧三个查询：审批引擎需要知道"这是谁的单、哪个组织、哪一天"
-- ---------------------------------------------------------------------------
-- ★ 引擎不认识请假单。它只通过这三个函数取上下文：
--   新增一种业务（调令、报销）只要加一个分支，不动引擎。

CREATE OR REPLACE FUNCTION fn_appr_biz_applicant(p_biz_type varchar, p_biz_id bigint)
RETURNS bigint
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT CASE p_biz_type
           WHEN 'leave' THEN (SELECT employee_id FROM public.leave_request WHERE id = p_biz_id)
         END;
$$;

CREATE OR REPLACE FUNCTION fn_appr_biz_date(p_biz_type varchar, p_biz_id bigint)
RETURNS date
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT CASE p_biz_type
           WHEN 'leave' THEN (SELECT date_from FROM public.leave_request WHERE id = p_biz_id)
         END;
$$;

-- 业务所属组织：用请假**开始那天**的成本组织归属（时点派生，不取当前）
CREATE OR REPLACE FUNCTION fn_appr_biz_org(p_biz_type varchar, p_biz_id bigint)
RETURNS bigint
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT CASE p_biz_type
           WHEN 'leave' THEN (
             SELECT a.org_id
               FROM public.leave_request r
               JOIN public.employee_org_assignment a
                 ON a.employee_id = r.employee_id AND a.dim_code = 'cost_org'
              WHERE r.id = p_biz_id
                AND daterange(a.valid_from, a.valid_to, '[]') @> r.date_from
              ORDER BY a.valid_from DESC LIMIT 1)
         END;
$$;

-- ---------------------------------------------------------------------------
-- 3. 审批人解析
-- ---------------------------------------------------------------------------
-- 两种来源，都**按业务日期**算：
--   direct    账号上的角色（sys_user_role 有效行）
--   组织授权  角色被授在业务组织的祖先链上，且此人挂在被授组织（或其子树）下
--             —— 这正是「集团把门店HR角色授给华东区，华东区各店的人都能审」
--
-- ★ 返回的是**人**（user_id），不是角色。审计要回答"谁审的"，
--   而不是"哪个角色当时有权限"。
CREATE OR REPLACE FUNCTION fn_appr_resolve_role(
  p_role bigint, p_org bigint, p_on date
) RETURNS TABLE (user_id bigint, source varchar)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  WITH biz AS (
    SELECT o.id, o.path FROM public.org_unit o WHERE o.id = p_org
  ),
  granted AS (
    SELECT g.org_id, go.path
      FROM public.sys_org_grant g, biz b, public.org_unit go
     WHERE go.id = g.org_id
       AND g.role_id = p_role
       AND g.revoked_at IS NULL
       AND g.effective_from <= p_on
       AND (g.effective_to IS NULL OR g.effective_to >= p_on)
       AND b.path LIKE go.path || '%'
  )
  SELECT DISTINCT ur.user_id, 'direct'::varchar
    FROM public.sys_user_role ur
   WHERE ur.role_id = p_role
     AND ur.superseded_by IS NULL
     AND daterange(ur.effective_from, ur.effective_to, '[)') @> p_on
  UNION
  SELECT DISTINCT uo.user_id, 'org'::varchar
    FROM public.sys_user_org uo
    JOIN granted gr ON TRUE
    JOIN public.org_unit u ON u.id = uo.org_id
   WHERE daterange(uo.effective_from, uo.effective_to, '[)') @> p_on
     AND u.path LIKE gr.path || '%';
$$;

COMMENT ON FUNCTION fn_appr_resolve_role IS
  '按业务日期解析"谁能审这个组织的单"。组织授权沿祖先链生效：授在华东区 → 华东区所辖各店都算。'
  '返回人，不返回角色 —— 审计要回答"谁审的"。';

-- ---------------------------------------------------------------------------
-- 4. 建一步的任务行（返回本步实际待办条数）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_appr_spawn(
  p_inst bigint, p_step jsonb, p_org bigint, p_on date, p_applicant bigint
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_seq int := (p_step ->> 'seq')::int;
  v_mode varchar := COALESCE(p_step ->> 'mode', 'any');
  r jsonb;
BEGIN
  FOR r IN SELECT * FROM jsonb_array_elements(p_step -> 'resolvers') LOOP
    IF (r ->> 'kind') = 'user' THEN
      -- ★ act_kind 必须同样按 mode 决定。第一版这里写死 'approve'，
      --   于是 mode='all' 的指定人步骤变成了或签：第一个人点完就整单通过，
      --   而第二个人看到的待办还在 —— 两次读数都"看起来对"。
      INSERT INTO public.approval_task(instance_id, seq, approver_id, act_kind)
      SELECT p_inst, v_seq, (r ->> 'user_id')::bigint,
             CASE v_mode WHEN 'all' THEN 'countersign' ELSE 'approve' END
       WHERE (r ->> 'user_id')::bigint <> p_applicant;
    ELSE
      -- 会签与或签都先落成行，区别在 act_kind：推进时按它判"要不要等人人"
      INSERT INTO public.approval_task(instance_id, seq, approver_id, act_kind)
      SELECT p_inst, v_seq, x.user_id,
             CASE v_mode WHEN 'all' THEN 'countersign' ELSE 'approve' END
        FROM public.fn_appr_resolve_role((r ->> 'role_id')::bigint, p_org, p_on) x
       WHERE x.user_id <> p_applicant;
    END IF;
  END LOOP;

  -- ★ 计数必须回头查实际行数，不能累加循环次数：
  --   循环跑了几次 ≠ 建了几行（角色解析可能为 0 人、去掉申请人后为 0），
  --   而返回值被用来判"有没有审批人"，错了会在"有人可审"时也报 NO_APPROVER。
  RETURN (SELECT count(*)::int FROM public.approval_task
           WHERE instance_id = p_inst AND seq = v_seq AND status = 'pending');
END;
$$;

-- ---------------------------------------------------------------------------
-- 5. 启动
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_appr_start(
  p_template_code varchar, p_biz_type varchar, p_biz_id bigint, p_on date
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_tpl bigint; v_ver bigint; v_def jsonb; v_first jsonb;
  v_inst bigint; v_org bigint; v_app bigint;
BEGIN
  SELECT t.id INTO v_tpl FROM public.approval_template t WHERE t.code = p_template_code;
  IF v_tpl IS NULL THEN
    RAISE EXCEPTION 'E_APPR_NO_TEMPLATE: 模板 % 不存在', p_template_code;
  END IF;

  -- 按业务日期选版本，不按今天
  SELECT v.id, v.definition INTO v_ver, v_def
    FROM public.approval_template_version v
   WHERE v.template_id = v_tpl AND v.status = 'published' AND v.effective_from <= p_on
   ORDER BY v.effective_from DESC, v.version_no DESC
   LIMIT 1;
  IF v_ver IS NULL THEN
    RAISE EXCEPTION 'E_APPR_NO_VERSION: 模板 % 在 % 之前没有已发布版本', p_template_code, p_on;
  END IF;

  v_app := public.fn_appr_biz_applicant(p_biz_type, p_biz_id);
  v_org := public.fn_appr_biz_org(p_biz_type, p_biz_id);
  IF v_app IS NULL THEN
    RAISE EXCEPTION 'E_APPR_NO_BIZ: 业务 %#% 不存在', p_biz_type, p_biz_id;
  END IF;
  -- 组织取不到就明确失败：拿 1（集团）兜底等于让最上面的人来审所有单
  IF v_org IS NULL THEN
    RAISE EXCEPTION 'E_APPR_NO_ORG: 业务 %#% 在 % 没有成本组织归属', p_biz_type, p_biz_id, p_on;
  END IF;

  INSERT INTO public.approval_instance(template_version_id, biz_type, biz_id)
  VALUES (v_ver, p_biz_type, p_biz_id)
  RETURNING id INTO v_inst;

  v_first := v_def -> 'steps' -> 0;

  -- ★ 剔除申请人后没人可审 → 失败。不许"自动通过"：
  --   自动通过的流程，记录上写着 approved，而没有任何人看过。
  IF public.fn_appr_spawn(v_inst, v_first, v_org, p_on, v_app) = 0 THEN
    RAISE EXCEPTION 'E_APPROVAL_NO_APPROVER: 第 1 步没有可用审批人'
      '（已剔除申请人 %；检查角色是否有人、组织授权是否覆盖组织 %）', v_app, v_org;
  END IF;

  RETURN v_inst;
END;
$$;

-- ---------------------------------------------------------------------------
-- 6. 审批：推进 / 否决 / 结束
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_appr_act(
  p_instance bigint, p_user bigint, p_approve boolean, p_note varchar
) RETURNS varchar
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_st varchar(16); v_seq int; v_tplver bigint;
  v_def jsonb; v_next jsonb; v_biz_type varchar; v_biz_id bigint;
  v_pending_cs int; v_rejected int; v_org bigint; v_on date; v_app bigint;
BEGIN
  SELECT status, template_version_id, biz_type, biz_id
    INTO v_st, v_tplver, v_biz_type, v_biz_id
    FROM public.approval_instance WHERE id = p_instance FOR UPDATE;
  IF v_st IS NULL THEN
    RAISE EXCEPTION 'E_APPR_NO_INSTANCE: 审批实例 % 不存在', p_instance;
  END IF;
  IF v_st <> 'running' THEN
    RAISE EXCEPTION 'E_APPR_FINISHED: 实例 % 已 %', p_instance, v_st;
  END IF;

  -- 只能处理**当前步**：跳步审批会让前一步的会签失去意义
  SELECT min(seq) INTO v_seq FROM public.approval_task
   WHERE instance_id = p_instance AND status = 'pending';
  IF v_seq IS NULL THEN
    RAISE EXCEPTION 'E_APPR_NO_TASK: 实例 % 没有待办任务', p_instance;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.approval_task
                  WHERE instance_id = p_instance AND seq = v_seq
                    AND approver_id = p_user AND status = 'pending') THEN
    RAISE EXCEPTION 'E_APPR_NOT_YOURS: 第 % 步不是 % 的待办（或已处理）', v_seq, p_user;
  END IF;

  UPDATE public.approval_task
     SET status = CASE WHEN p_approve THEN 'approved' ELSE 'rejected' END,
         acted_at = now()
   WHERE instance_id = p_instance AND seq = v_seq AND approver_id = p_user;

  -- 一票否决：任何一人拒绝，这一步立即结束
  SELECT count(*) INTO v_rejected FROM public.approval_task
   WHERE instance_id = p_instance AND seq = v_seq AND status = 'rejected';
  IF v_rejected > 0 THEN
    UPDATE public.approval_instance SET status='rejected', finished_at=now() WHERE id=p_instance;
    PERFORM public.fn_appr_sync_biz(v_biz_type, v_biz_id, false, p_user);
    RETURN 'rejected';
  END IF;

  -- 会签：本步还有会签人没处理就等（或签人已通过即可往下走）
  SELECT count(*) INTO v_pending_cs FROM public.approval_task
   WHERE instance_id = p_instance AND seq = v_seq
     AND status = 'pending' AND act_kind = 'countersign';
  IF v_pending_cs > 0 THEN
    RETURN 'running';
  END IF;

  -- 或签：一人通过，同一步其余待办标 skipped（不是删掉）
  UPDATE public.approval_task SET status='skipped', acted_at=now()
   WHERE instance_id = p_instance AND seq = v_seq AND status = 'pending';

  SELECT v.definition INTO v_def FROM public.approval_template_version v WHERE v.id = v_tplver;
  SELECT s INTO v_next FROM jsonb_array_elements(v_def -> 'steps') s
   WHERE (s ->> 'seq')::int = v_seq + 1;

  IF v_next IS NULL THEN
    UPDATE public.approval_instance SET status='approved', finished_at=now() WHERE id=p_instance;
    PERFORM public.fn_appr_sync_biz(v_biz_type, v_biz_id, true, p_user);
    RETURN 'approved';
  END IF;

  -- 下一步的审批人**在这一刻**解析并落行（此时的组织与授权才是"当时"的）
  v_org := public.fn_appr_biz_org(v_biz_type, v_biz_id);
  v_on  := public.fn_appr_biz_date(v_biz_type, v_biz_id);
  v_app := public.fn_appr_biz_applicant(v_biz_type, v_biz_id);

  IF public.fn_appr_spawn(p_instance, v_next, v_org, v_on, v_app) = 0 THEN
    RAISE EXCEPTION 'E_APPROVAL_NO_APPROVER: 第 % 步没有可用审批人'
      '（组织 %；若上一步通过后组织归属变了，请检查归属基线）', v_seq + 1, v_org;
  END IF;

  RETURN 'running';
END;
$$;

-- ---------------------------------------------------------------------------
-- 7. 业务回写：审批层唯一知道"请假单怎么改状态"的地方
-- ---------------------------------------------------------------------------
-- ★ 这里**调用**原有的 fn_leave_decide_by，而不是自己 UPDATE 单据 ——
--   两条路径改同一张表，就会出现"审批历史齐全、额度没动"这类接缝。
-- ★ 前提：本切片里 person_id 与 user_id 1:1（见文件头 ⑤）。
CREATE OR REPLACE FUNCTION fn_appr_sync_biz(
  p_biz_type varchar, p_biz_id bigint, p_approve boolean, p_by bigint
) RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF p_biz_type = 'leave' THEN
    PERFORM public.fn_leave_decide_by(p_biz_id, p_approve, p_by);
  ELSE
    RAISE EXCEPTION 'E_APPR_NO_BIZ_SYNC: 业务类型 % 还没有回写实现', p_biz_type;
  END IF;
END;
$$;

COMMENT ON FUNCTION fn_appr_sync_biz IS
  '审批结果 → 业务单据的唯一回写点。业务回写散在多处时，'
  '最容易出的错是"实例批了、单据还是 pending"，而两边都自洽。';

