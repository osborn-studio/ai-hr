-- ---------------------------------------------------------------------------
-- 9. 一张单只能有一个在跑的审批实例
-- ---------------------------------------------------------------------------
-- ★ 没有这条，同一张单可以发起两次：两条流程各自推进、各自回写业务状态，
--   而"谁最后写的"取决于点得快慢 —— 这类冲突不会报错，只会让审批记录
--   与单据状态对不上，且两边都自洽。
CREATE UNIQUE INDEX uk_ai_one_running
