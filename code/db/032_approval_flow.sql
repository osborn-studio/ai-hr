-- ===========================================================================
-- 032_approval_flow.sql · 审批引擎接电：模板 → 实例 → 任务 → 业务回写
-- ---------------------------------------------------------------------------
-- 006 建了三张表（模板版本 / 实例 / 任务）和两条冻结判据，但**没有任何东西往里写**。
-- 于是请假走的是 `fn_leave_decide_by`：一个人点一下，单子就批了。
-- 那证明了"自审会被拒"，但撑不起真实审批 —— 真实审批有几步、谁审、审到谁为止。
--
-- 这一版补的是"跑起来"的最小闭环。五条判断写在前头：
--
-- ① **模板在发布时就固定，在途单据锁住它。** 006 已有这两条冻结判据；
--    这里补"按哪个版本跑"——`effective_from`，且按业务发生的**日期**选版本。
--    否则补录一张上个月的单，会用上个月还不存在的流程。
--
-- ② **审批人在启动时解析并落成行**（`approval_task`），不是每次点的时候现算。
--    现算的后果：中间改一次组织授权，同一张单的"该谁审"会变，两次查询都"看起来对"。
--
-- ③ **申请人不在审批人集合里。** 不是"点了再拒"，是启动时剔除；
--    剔除后为空 → 明确失败（`E_APPROVAL_NO_APPROVER`），
--    而不是"没人可审就自动通过"——那是最安静的越权。
--
-- ④ **业务回写只在一个地方**（`fn_appr_sync_biz`）。散在多处，
--    就会出现"实例批了、单据还是 pending"。
--
-- ⑤ **本切片里账号与员工是 1:1**（`person_id = user_id`，见 007 的种子与
--    `services/leave.mjs` 的 resolveEmployee）。真实系统里这是两套实体；
--    这里刻意不假装：`fn_appr_sync_biz` 的注释里写明了这个前提。
-- ===========================================================================

