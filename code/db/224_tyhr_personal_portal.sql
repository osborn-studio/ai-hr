CREATE TABLE ty_personal_service_request(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,request_key text NOT NULL UNIQUE,
 group_id bigint NOT NULL REFERENCES ty_group(id),company_id bigint NOT NULL,
 person_id bigint NOT NULL,employment_id bigint NOT NULL,
 kind text NOT NULL CHECK(kind IN('dorm_checkout','dorm_transfer','goods_issue')),
 source_id bigint NOT NULL,target_bed_id bigint REFERENCES ty_dorm_bed(id),
 at timestamptz,ends_at timestamptz,reason_box jsonb NOT NULL,source_hash text NOT NULL,
 created_by bigint NOT NULL REFERENCES sys_account(id),created_at timestamptz NOT NULL DEFAULT now(),
 status text NOT NULL DEFAULT 'pending'CHECK(status IN('pending','approved','executed','rejected','cancelled','blocked')),
 approved_by bigint REFERENCES sys_account(id),executed_by bigint REFERENCES sys_account(id),
 domain_result_id bigint,workflow_instance_id bigint REFERENCES ty_workflow_instance(id),
 revision integer NOT NULL DEFAULT 1,
 FOREIGN KEY(company_id,group_id)REFERENCES ty_company(id,group_id),
 FOREIGN KEY(person_id,group_id)REFERENCES ty_person(id,group_id),
 FOREIGN KEY(employment_id,company_id,group_id)REFERENCES ty_employment(id,company_id,group_id),
 CHECK((kind='dorm_transfer')=(target_bed_id IS NOT NULL)),
 CHECK((kind<>'goods_issue')=(at IS NOT NULL)),CHECK(kind<>'dorm_transfer'OR ends_at>at),
 CHECK(status<>'executed'OR(executed_by IS NOT NULL AND domain_result_id IS NOT NULL AND workflow_instance_id IS NOT NULL))
);
CREATE UNIQUE INDEX ty_personal_service_one_open ON ty_personal_service_request(kind,source_id)WHERE status IN('pending','approved');
CREATE FUNCTION fn_ty_personal_service_guard()RETURNS trigger LANGUAGE plpgsql SET search_path=''AS $$
DECLARE s record;w public.ty_workflow_instance%ROWTYPE;
BEGIN
 IF TG_OP='DELETE'THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='个人业务申请不可删除';END IF;
 IF TG_OP='UPDATE'AND(to_jsonb(NEW)-ARRAY['status','approved_by','executed_by','domain_result_id','workflow_instance_id','revision'])IS DISTINCT FROM(to_jsonb(OLD)-ARRAY['status','approved_by','executed_by','domain_result_id','workflow_instance_id','revision'])THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='个人业务申请来源和内容不可改写';END IF;
 IF TG_OP='INSERT'AND NOT EXISTS(SELECT 1 FROM public.ty_test_account_profile WHERE account_id=NEW.created_by AND group_id=NEW.group_id AND person_id=NEW.person_id)THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='个人申请必须由关联本人的原账号登记';END IF;
 IF TG_OP='UPDATE'AND(OLD.status IN('executed','rejected','cancelled','blocked')OR NEW.revision<>OLD.revision+1)THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='已处理个人申请不可改写，每次办理须推进版本';END IF;
 IF NEW.status='executed'THEN
  SELECT*INTO w FROM public.ty_workflow_instance WHERE id=NEW.workflow_instance_id;
  IF w.id IS NULL OR w.status<>'approved'OR w.subject_type<>'personal_service'OR w.subject_id<>NEW.id OR w.group_id<>NEW.group_id OR w.person_id IS DISTINCT FROM NEW.person_id OR w.applicant_id<>NEW.created_by OR NEW.approved_by IS NULL OR w.last_approver_id IS DISTINCT FROM NEW.approved_by OR NEW.approved_by=NEW.created_by OR EXISTS(SELECT 1 FROM public.ty_test_account_profile WHERE account_id=NEW.approved_by AND group_id=NEW.group_id AND person_id=NEW.person_id)THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='实际办理须关联同一人的独立已批准流程';END IF;
  IF NEW.kind='goods_issue'THEN
   IF NEW.domain_result_id<>NEW.source_id OR NOT EXISTS(SELECT 1 FROM public.ty_goods_doc WHERE id=NEW.source_id AND state='posted'AND handled_by=NEW.executed_by AND length(btrim(execution_ref))>=4)THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='领用办结须有同一实际出库单';END IF;
  ELSE
   IF NOT EXISTS(SELECT 1 FROM public.ty_dorm_stay WHERE id=NEW.source_id AND state='ended'AND checked_out_at=NEW.at AND length(btrim(execution_ref))>=4)THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='退宿换房须完成原入住交接';END IF;
   IF NEW.kind='dorm_checkout'AND NEW.domain_result_id<>NEW.source_id THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='退宿结果须为原入住单';END IF;
   IF NEW.kind='dorm_transfer'AND NOT EXISTS(SELECT 1 FROM public.ty_dorm_stay WHERE id=NEW.domain_result_id AND group_id=NEW.group_id AND company_id=NEW.company_id AND person_id=NEW.person_id AND employment_id=NEW.employment_id AND bed_id=NEW.target_bed_id AND state='occupied'AND starts_at=NEW.at AND ends_at=NEW.ends_at AND source_key='PERSONAL-TRANSFER:'||NEW.id::text)THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='换房结果须对应本人确切目标床位和期间';END IF;
  END IF;
 END IF;
 IF NEW.kind='goods_issue'THEN SELECT group_id,company_id,person_id,employment_id INTO s FROM public.ty_goods_doc WHERE id=NEW.source_id AND kind='issue';
 ELSE SELECT group_id,company_id,person_id,employment_id INTO s FROM public.ty_dorm_stay WHERE id=NEW.source_id;END IF;
 IF s IS NULL OR s.group_id<>NEW.group_id OR s.company_id<>NEW.company_id OR s.person_id<>NEW.person_id OR s.employment_id<>NEW.employment_id THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='个人申请须对应确切人员及实际业务来源';END IF;
 IF NEW.target_bed_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM public.ty_dorm_bed WHERE id=NEW.target_bed_id AND group_id=NEW.group_id)THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='换宿目标须属于当前集团';END IF;RETURN NEW;
END;$$;
CREATE TRIGGER ty_personal_service_guard BEFORE INSERT OR UPDATE OR DELETE ON ty_personal_service_request FOR EACH ROW EXECUTE FUNCTION fn_ty_personal_service_guard();

CREATE FUNCTION fn_ty_personal_service_binding()RETURNS trigger LANGUAGE plpgsql SET search_path=''AS $$
DECLARE r public.ty_personal_service_request%ROWTYPE;
BEGIN
 IF NEW.subject_type<>'personal_service'THEN RETURN NEW;END IF;
 SELECT*INTO r FROM public.ty_personal_service_request WHERE id=NEW.subject_id FOR UPDATE;
 IF r.id IS NULL OR r.status<>'pending'OR r.workflow_instance_id IS NOT NULL OR r.created_by<>NEW.applicant_id OR r.person_id IS DISTINCT FROM NEW.person_id OR r.group_id<>NEW.group_id OR r.company_id IS DISTINCT FROM NEW.company_id THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='个人业务申请仅能绑定一个确切本人的审批流程';END IF;
 UPDATE public.ty_personal_service_request SET workflow_instance_id=NEW.id,revision=revision+1 WHERE id=r.id;
 RETURN NEW;
END;$$;
CREATE TRIGGER ty_personal_service_binding AFTER INSERT ON ty_workflow_instance FOR EACH ROW EXECUTE FUNCTION fn_ty_personal_service_binding();
