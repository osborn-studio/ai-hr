CREATE FUNCTION fn_ty_personal_transfer_guard()RETURNS trigger LANGUAGE plpgsql SET search_path=''AS $$
BEGIN
 IF TG_OP='UPDATE'AND NEW.self_requested IS DISTINCT FROM OLD.self_requested THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='个人发起来源不可改写';END IF;
 IF NEW.self_requested AND NEW.action<>'transfer'THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='个人调店来源只可用于调动意图';END IF;RETURN NEW;
END;$$;
CREATE TRIGGER ty_personal_transfer_guard BEFORE INSERT OR UPDATE ON ty_hr_change_request FOR EACH ROW EXECUTE FUNCTION fn_ty_personal_transfer_guard();
CREATE FUNCTION fn_ty_workflow_department_snapshot()RETURNS trigger LANGUAGE plpgsql SET search_path=''AS $$
DECLARE found_departments bigint[];
BEGIN
 IF TG_OP='UPDATE'THEN
  IF NEW.department_id IS DISTINCT FROM OLD.department_id THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='已提交事项部门快照不可改写';END IF;RETURN NEW;
 END IF;
 SELECT array_agg(DISTINCT a.department_id)INTO found_departments FROM public.ty_employment e JOIN public.ty_position_assignment a ON a.employment_id=e.id
 WHERE e.group_id=NEW.group_id AND e.company_id=NEW.company_id AND e.person_id=NEW.person_id AND e.status<>'cancelled'
 AND e.hire_date<=public.app_today()AND(e.leave_date IS NULL OR e.leave_date>=public.app_today())
 AND a.status<>'cancelled'AND a.valid_from<=public.app_today()AND(a.valid_to IS NULL OR a.valid_to>public.app_today())AND a.department_id IS NOT NULL;
 NEW.department_id=CASE WHEN cardinality(found_departments)=1 THEN found_departments[1]ELSE NULL END;
 RETURN NEW;
END;$$;
CREATE TRIGGER ty_workflow_department_snapshot BEFORE INSERT OR UPDATE ON ty_workflow_instance FOR EACH ROW EXECUTE FUNCTION fn_ty_workflow_department_snapshot();

CREATE TABLE ty_pf_attachment(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 file_key text NOT NULL UNIQUE CHECK(file_key ~ '^[0-9a-f-]{36}$'),
 group_id bigint NOT NULL REFERENCES ty_group(id),company_id bigint,
 owner_kind text NOT NULL DEFAULT 'form'CHECK(owner_kind ~ '^[a-z][a-z0-9_]{0,63}$'),owner_key text NOT NULL,
 form_id bigint,field_key text NOT NULL CHECK(field_key ~ '^[a-z][a-z0-9_]{0,63}$'),
 owner_id bigint NOT NULL REFERENCES sys_account(id),metadata_box jsonb NOT NULL,
 mime text NOT NULL,byte_length integer NOT NULL CHECK(byte_length BETWEEN 1 AND 8388608),
 sha256 text NOT NULL CHECK(sha256 ~ '^[0-9a-f]{64}$'),
 cipher bytea NOT NULL,iv text NOT NULL,tag text NOT NULL,
 status text NOT NULL DEFAULT 'ready'CHECK(status IN('ready','discarded')),
 created_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(company_id,group_id)REFERENCES ty_company(id,group_id),
 FOREIGN KEY(form_id,group_id)REFERENCES ty_form_definition(id,group_id),
 UNIQUE(owner_id,owner_kind,owner_key,field_key,sha256),CHECK(octet_length(cipher)=byte_length),
 CHECK((owner_kind='form')=(form_id IS NOT NULL)),CHECK(owner_kind<>'form'OR owner_key=form_id::text)
);
CREATE TABLE ty_pf_attachment_use(
 attachment_id bigint NOT NULL REFERENCES ty_pf_attachment(id),
 instance_id bigint NOT NULL REFERENCES ty_workflow_instance(id),field_key text NOT NULL,
 submitted_company_id bigint REFERENCES ty_company(id),created_by bigint NOT NULL REFERENCES sys_account(id),
 created_at timestamptz NOT NULL DEFAULT now(),PRIMARY KEY(attachment_id,instance_id,field_key)
);
CREATE FUNCTION fn_ty_pf_attachment_guard()RETURNS trigger LANGUAGE plpgsql SET search_path=''AS $$
DECLARE f public.ty_pf_attachment%ROWTYPE;i public.ty_workflow_instance%ROWTYPE;s jsonb;
BEGIN
 IF TG_TABLE_NAME='ty_pf_attachment'THEN
  IF TG_OP='DELETE'THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='原附件不可删除，保留证据和引用';END IF;
  IF TG_OP='UPDATE'THEN
   IF(OLD.status<>'ready'OR NEW.status<>'discarded')OR(to_jsonb(NEW)-'status')IS DISTINCT FROM(to_jsonb(OLD)-'status')OR EXISTS(SELECT 1 FROM public.ty_pf_attachment_use WHERE attachment_id=OLD.id)THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='原附件与已绑定内容不可改写';END IF;
  END IF;RETURN NEW;
 END IF;
 IF TG_OP<>'INSERT'THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='附件与审批原件关联不可改写';END IF;
 SELECT*INTO f FROM public.ty_pf_attachment WHERE id=NEW.attachment_id;
 SELECT*INTO i FROM public.ty_workflow_instance WHERE id=NEW.instance_id;
 SELECT schema INTO s FROM public.ty_form_definition WHERE id=i.form_id;
 IF f.id IS NULL OR i.id IS NULL OR f.owner_kind<>'form'OR f.status<>'ready'OR f.form_id<>i.form_id OR f.group_id<>i.group_id OR f.owner_id<>i.applicant_id OR NEW.created_by<>i.applicant_id OR NEW.field_key<>f.field_key OR NEW.submitted_company_id IS DISTINCT FROM f.company_id OR(i.company_id IS NOT NULL AND i.company_id IS DISTINCT FROM f.company_id)
 OR NOT EXISTS(SELECT 1 FROM jsonb_array_elements(s->'fields')x WHERE x->>'key'=f.field_key AND x->>'type'='file')
 OR NOT(coalesce(i.form_values->f.field_key,'[]'::jsonb) ? ('pf:'||f.file_key))THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='附件必须是当前申请人、原表单字段与确切公司范围的已存原件';END IF;
 RETURN NEW;
END;$$;
CREATE TRIGGER ty_pf_attachment_immutable BEFORE UPDATE OR DELETE ON ty_pf_attachment FOR EACH ROW EXECUTE FUNCTION fn_ty_pf_attachment_guard();
CREATE TRIGGER ty_pf_attachment_use_guard BEFORE INSERT OR UPDATE OR DELETE ON ty_pf_attachment_use FOR EACH ROW EXECUTE FUNCTION fn_ty_pf_attachment_guard();
