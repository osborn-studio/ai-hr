-- ---------------------------------------------------------------------------
-- 5. 报名：容量与重复都要拦
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_training_enroll(
  p_session bigint, p_employee bigint, p_by varchar DEFAULT 'system'
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  s    record;
  v_n  int;
  v_id bigint;
BEGIN
  SELECT * INTO s FROM public.training_session WHERE id = p_session;
  IF s.id IS NULL THEN RAISE EXCEPTION 'E_TR_NO_SESSION: 场次 % 不存在', p_session; END IF;
  IF s.status = 'cancelled' THEN
    RAISE EXCEPTION 'E_TR_SESSION_CLOSED: 场次 % 已取消', p_session;
  END IF;

  IF EXISTS (SELECT 1 FROM public.training_enrollment e
              WHERE e.session_id = p_session AND e.employee_id = p_employee) THEN
    RAISE EXCEPTION 'E_TR_DUP: 这个人已经在这场培训里了（同一场不能报两次）';
  END IF;

  IF s.capacity IS NOT NULL THEN
    SELECT count(*)::int INTO v_n FROM public.training_enrollment e
     WHERE e.session_id = p_session AND e.status <> 'cancelled';
    IF v_n >= s.capacity THEN
      -- ★ 不自动扩容：容量是人定的（教室多大、讲师带几个），
      --   系统悄悄加一个座位，等于替现场做决定。
      RAISE EXCEPTION 'E_TR_CAPACITY: 场次 % 已满（% / %）—— 加人要先改容量并写原因',
        p_session, v_n, s.capacity;
    END IF;
  END IF;

  INSERT INTO public.training_enrollment(session_id, employee_id, status)
  VALUES (p_session, p_employee, 'invited')
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_training_enroll IS
  '报名/指派。重复报名与超容量都直接拒 —— 不自动扩容：容量是人定的，'
  '系统悄悄加座位等于替现场做决定。';

-- ---------------------------------------------------------------------------
-- 6. 出勤：到场才有学时；学时够了才结业
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_training_attend(
  p_enroll bigint, p_hours numeric DEFAULT NULL, p_by varchar DEFAULT 'system'
) RETURNS varchar
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  e        record;
  s        record;
  c        record;
  v_hours  numeric(6,2);
  v_status varchar(16);
BEGIN
  SELECT * INTO e FROM public.training_enrollment WHERE id = p_enroll FOR UPDATE;
  IF e.id IS NULL THEN RAISE EXCEPTION 'E_TR_NOT_FOUND: 报名记录 % 不存在', p_enroll; END IF;
  IF e.status = 'completed' THEN
    RAISE EXCEPTION 'E_TR_COMPLETED: 已结业，不能再改学时（要补学另开一场）';
  END IF;

  SELECT * INTO s FROM public.training_session WHERE id = e.session_id;
  SELECT * INTO c FROM public.training_course WHERE id = s.course_id;

  -- 默认给"本场学时"；也可以少于（迟到早退），但不会多于本场
  v_hours := COALESCE(p_hours, s.hours);
  IF v_hours < 0 THEN RAISE EXCEPTION 'E_TR_HOURS: 学时不能为负'; END IF;
  IF v_hours > s.hours THEN
    RAISE EXCEPTION 'E_TR_HOURS: 本场只给了 % 学时，不能记 %（多记学时是伪造培训记录）',
      s.hours, v_hours;
  END IF;

  -- ★ 结业判据用**课程**的标准学时，不是本场学时：
  --   本场只讲半天（4h）而课程标准是 8h，那这个人就是没学完 ——
  --   用本场学时判，等于"讲多少算多少"，标准学时这个字段就失效了。
  IF v_hours >= c.std_hours THEN
    v_status := 'completed';
    UPDATE public.training_enrollment
       SET status = 'completed', attended_hours = v_hours, completed_at = now()
     WHERE id = p_enroll;
  ELSE
    v_status := 'attended';
    UPDATE public.training_enrollment
       SET status = 'attended', attended_hours = v_hours, completed_at = NULL
     WHERE id = p_enroll;
  END IF;
  RETURN v_status;
END;
$$;

COMMENT ON FUNCTION fn_training_attend IS
  '记到场学时并判定结业。判据是**课程**的标准学时（不是本场学时）：'
  '本场只讲半天而标准是 8 小时，那就是没学完。学时够了由函数置 completed，'
  '不由人点"通过"。';

-- ---------------------------------------------------------------------------
-- 7. 学时汇总：按人按年，按类别
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_training_hours(p_person bigint, p_year int)
RETURNS numeric
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT COALESCE(sum(e.attended_hours), 0)::numeric
    FROM public.training_enrollment e
    JOIN public.training_session s ON s.id = e.session_id
   WHERE e.employee_id = p_person
     AND e.status = 'completed'
     AND EXTRACT(year FROM s.starts_at) = p_year;
$$;

COMMENT ON FUNCTION fn_training_hours IS
  '某人某年的**已结业**学时合计。只算 completed：'
  'attended（来了但学时不够）不计入年度学时 —— 那门课他没学完。';

-- 法定学时缺口：谁没达标、差多少
CREATE OR REPLACE FUNCTION fn_training_gap(p_entity bigint, p_year int)
RETURNS TABLE (
  employee_id bigint, person_name varchar(64), employee_no varchar(16),
  got_hours numeric(14,2), need_hours numeric(14,2), gap_hours numeric(14,2)
)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE v_need numeric(12,2);
BEGIN
  SELECT COALESCE(value_num, 0) INTO v_need
    FROM public.fn_policy_effective('TRAINING_MIN_HOURS_YEAR', NULL,
           make_date(p_year, 12, 31));

  RETURN QUERY
  SELECT em.person_id, pe.full_name::varchar(64),
         (SELECT n.no FROM public.employee_no n
           WHERE n.assigned_person_id = pe.id AND n.retired_at IS NULL
           ORDER BY n.assigned_at DESC LIMIT 1)::varchar(16),
         public.fn_training_hours(em.person_id, p_year)::numeric(14,2),
         v_need::numeric(14,2),
         GREATEST(v_need - public.fn_training_hours(em.person_id, p_year), 0)::numeric(14,2)
    FROM public.employment em
    JOIN public.person pe ON pe.id = em.person_id
   WHERE em.legal_entity_id = p_entity
     AND daterange(em.hire_date, em.leave_date, '[]') @> make_date(p_year, 12, 31)
     -- 制度没开（0）就不列人：一个"人人都差 0 学时"的清单只会让人不再看它
     AND v_need > 0
   ORDER BY GREATEST(v_need - public.fn_training_hours(em.person_id, p_year), 0) DESC,
            pe.full_name;
END;
$$;

COMMENT ON FUNCTION fn_training_gap IS
  '年度学时缺口清单（144）。制度没开（TRAINING_MIN_HOURS_YEAR=0）时返回 0 行 —— '
  '一个"人人都差 0 学时"的清单只会让人不再看它。';

