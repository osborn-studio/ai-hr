-- ============================================================================
-- 144_training.sql · 培训学习：学时是到场记录，不是填报数字
-- ----------------------------------------------------------------------------
-- 到 143 为止，"培训学习"这一屏的正文是"还没做 —— 这里不放编造的数据"。
-- 那句话是对的（比摆三张假课程表强），但一个 HR 系统没有培训，等于少了
-- 三件真实会发生的事：
--
--   ① **法定必训要有证据。** 安全生产培训、岗前培训是监管会查的，
--      查的时候要的不是"我们培训过了"，是"谁、哪天、几学时、签到了没有"。
--   ② **证书会过期。** 特种作业、健康证、消防证——过期了人还在岗，是隐患。
--   ③ **学时是算出来的，不是填出来的。** 一旦允许人直接填"我学了 8 小时"，
--      这份记录就只证明"有人说他学了"。
--
-- ★ 所以这一层只做**记录链**：课程（标准学时）→ 场次（谁讲、哪天、几学时）
--   → 报名/出勤（到场才有学时）→ 结业（学时够了才算完）。四步都有时间与人。
--
-- ★ 三条设计取舍：
--
--   ① **结业由学时判定，不由人点"通过"。** 到场学时 < 课程标准学时 → 不结业，
--      报错里写清差多少。允许人点通过的话，这个字段迟早全是"通过"。
--
--   ② **结业之后不可改。** 学时、场次、人都锁住（触发器拦 UPDATE/DELETE）——
--      与工资条封账同一条规矩：已经作为"证据"用出去的东西不能再变。
--      要纠正走**补一场**（再记一次培训），不改历史。
--
--   ③ **法定学时做成配置项，不写死。** 高危行业与写字楼的年度再培训学时不同，
--      地方规定也不同。默认 0 = 不检查（不改变上线前行为），客户按当地口径开。
--      拿不准的口径做成配置项，比替客户选一个数强。
--
-- ★ 两份"不做"：
--   · 不做在线课程内容与考试题库（那是 LMS，不是 HR 系统）；
--   · 不做证书文件上传（扫描件进对象存储是另一件事，这里只记"有效期到哪天"）。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 课程：标准学时是结业门槛
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS training_course (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          varchar(32)  NOT NULL UNIQUE,
  name          varchar(96)  NOT NULL,
  category      varchar(16)  NOT NULL DEFAULT 'skill',
  std_hours     numeric(6,2) NOT NULL,
  is_statutory  boolean      NOT NULL DEFAULT false,
  valid_months  int,                          -- 证书有效期（NULL = 长期有效）
  note          varchar(200),
  is_active     boolean      NOT NULL DEFAULT true,
  created_at    timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT ck_tc_cat   CHECK (category IN ('safety','onboarding','skill','compliance')),
  CONSTRAINT ck_tc_hours CHECK (std_hours > 0),
  CONSTRAINT ck_tc_valid CHECK (valid_months IS NULL OR valid_months BETWEEN 1 AND 600)
);

COMMENT ON TABLE training_course IS
  '课程主档（144）。std_hours 是**结业门槛**：到场学时不够就不结业 —— '
  '允许人点"通过"的话，这个字段迟早全是"通过"。'
  'valid_months 只记有效期长度，到期提醒靠它算，不存证书文件。';

-- ---------------------------------------------------------------------------
-- 2. 场次：一次具体的培训
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS training_session (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id       bigint      NOT NULL REFERENCES training_course(id),
  legal_entity_id bigint      NOT NULL,
  starts_at       timestamptz NOT NULL,
  ends_at         timestamptz NOT NULL,
  hours           numeric(6,2) NOT NULL,      -- 本场给多少学时（可与课程标准不同）
  trainer         varchar(64),
  place           varchar(96),
  capacity        int,
  status          varchar(16) NOT NULL DEFAULT 'planned',
  created_by      varchar(64) NOT NULL DEFAULT 'system',
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_ts_span  CHECK (ends_at > starts_at),
  CONSTRAINT ck_ts_hours CHECK (hours > 0),
  CONSTRAINT ck_ts_cap   CHECK (capacity IS NULL OR capacity > 0),
  CONSTRAINT ck_ts_st    CHECK (status IN ('planned','done','cancelled'))
);

CREATE INDEX IF NOT EXISTS ix_ts_entity ON training_session (legal_entity_id, starts_at);

COMMENT ON TABLE training_session IS
  '场次（144）。hours 是本场实际给的学时，可以小于课程标准的（比如只讲了半天），'
  '那样这一场就结不了业 —— 这是对的：学时不够就是不够。';

-- ---------------------------------------------------------------------------
-- 3. 报名 / 出勤 / 结业
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS training_enrollment (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id     bigint      NOT NULL REFERENCES training_session(id),
  employee_id    bigint      NOT NULL,        -- person.id（与 payslip 同：不挂外键）
  status         varchar(16) NOT NULL DEFAULT 'invited',
  attended_hours numeric(6,2),
  completed_at   timestamptz,
  note           varchar(200),
  enrolled_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uk_te_once   UNIQUE (session_id, employee_id),
  CONSTRAINT ck_te_st     CHECK (status IN ('invited','attended','absent','cancelled','completed')),
  -- 状态与时刻同生同灭（与 ck_pr_sealed / ck_pr_paid 同一条规矩）
  CONSTRAINT ck_te_done   CHECK ((status = 'completed') = (completed_at IS NOT NULL)),
  -- 没有到场学时就不该是 attended/completed
  CONSTRAINT ck_te_hours  CHECK (
       (status IN ('attended','completed') AND attended_hours IS NOT NULL AND attended_hours >= 0)
    OR (status IN ('invited','absent','cancelled'))
  )
);

CREATE INDEX IF NOT EXISTS ix_te_emp ON training_enrollment (employee_id);
CREATE INDEX IF NOT EXISTS ix_te_sess ON training_enrollment (session_id);

COMMENT ON TABLE training_enrollment IS
  '报名与出勤（144）。attended_hours 是**到场记录**，不是"我申报我学了 8 小时"：'
  '它只能由 fn_training_attend 写入，且结业由它判定。';

-- 结业之后不可改：它已经作为证据用出去了
CREATE OR REPLACE FUNCTION fn_te_frozen() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF OLD.status = 'completed' THEN
    IF TG_OP = 'DELETE' THEN
      RAISE EXCEPTION 'E_TR_COMPLETED: 已结业的记录不能删（它是"这门课他学完了"的证据）';
    END IF;
    RAISE EXCEPTION 'E_TR_COMPLETED: 已结业的记录不能改（要纠正走补一场，不改历史）';
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$;

DROP TRIGGER IF EXISTS trg_te_frozen ON training_enrollment;
CREATE TRIGGER trg_te_frozen BEFORE UPDATE OR DELETE ON training_enrollment
  FOR EACH ROW EXECUTE FUNCTION fn_te_frozen();

