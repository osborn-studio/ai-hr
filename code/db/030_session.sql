-- ===========================================================================
-- 030_session.sql · 会话落库：token 存摘要、过期靠派生、吊销是显式事实
-- ---------------------------------------------------------------------------
-- 在这之前，会话是应用进程里的一个 `new Map()`：
--
--   const sessions = new Map();   // token -> userId
--
-- 三个后果，都不是"将来要考虑"，而是"现在就不成立"：
--
--   ① **重启即全员掉线**（内存里的东西跟着进程走）。
--   ② **无法吊销**：员工离职、手机丢了、token 泄露 —— 没有地方能把它作废，
--      只能等重启，而重启会连正常用户一起踢下线。
--   ③ **无法回答"这个 token 现在还能不能用"**：安全审计问的第一句话。
--
-- 三条设计判断与全仓其它部分一致，不另立一套：
--
--   · **存摘要，不存明文。** 库里被打出来（备份、日志、误导出）时，
--     明文 token 等于所有人的通行证；摘要被拿走，冒充不了任何人。
--   · **过期是派生的，不是状态。** 同一个查询换一天两个答案的毛病，
--     在"过期"这件事上代价特别大：靠定时任务翻状态，任务停三天就有一批
--     早该失效的会话还能用，而表里看起来一切正常。
--   · **吊销是显式事实**（revoked_at/by/reason 三件套），不是删行。
--     删行之后，"这里曾有过一个被吊销的会话"就消失了 ——
--     而那正是泄密排查要看的东西。
-- ===========================================================================

CREATE TABLE sys_session (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- sha256 摘要（64 位 hex）。列名就叫 hash，让"这里不该有明文"写在名字上。
  token_hash     char(64)    NOT NULL UNIQUE,
  user_id        bigint      NOT NULL,
  issued_at      timestamptz NOT NULL DEFAULT clock_timestamp(),
  expires_at     timestamptz NOT NULL,
  last_seen_at   timestamptz,
  revoked_at     timestamptz,
  revoked_by     varchar(64),
  revoked_reason varchar(200),

  CONSTRAINT ck_ss_ttl      CHECK (expires_at > issued_at),
  -- 上限：不允许签发十年有效的会话。这类"临时放开"最后都会变成永久。
  CONSTRAINT ck_ss_ttl_max  CHECK (expires_at <= issued_at + interval '30 days'),
  CONSTRAINT ck_ss_rev      CHECK ((revoked_at IS NULL) = (revoked_by IS NULL)),
  CONSTRAINT ck_ss_reason   CHECK (revoked_at IS NULL OR length(btrim(revoked_reason)) >= 4)
);

CREATE INDEX ix_ss_user ON sys_session(user_id, issued_at DESC);
CREATE INDEX ix_ss_live ON sys_session(expires_at) WHERE revoked_at IS NULL;

COMMENT ON COLUMN sys_session.token_hash IS
  'sha256(token) 的 hex。明文永不落库：库被导出时，摘要冒充不了任何人。';

-- ---------------------------------------------------------------------------
-- 三个不许改的东西
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_session_guard() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  -- ① 身份三件套不可改：改了就是把 A 的会话变成 B 的
  IF NEW.token_hash <> OLD.token_hash
     OR NEW.user_id <> OLD.user_id
     OR NEW.issued_at <> OLD.issued_at THEN
    RAISE EXCEPTION 'E_SESSION_TAINTED: 会话的 token_hash / user_id / issued_at 不可修改';
  END IF;

  -- ② 不许延长：续期只能新签发一个会话。
  --    "就地改过期时间"看起来无害，但它等于把每一个泄露的 token 都变成永久的。
  IF NEW.expires_at > OLD.expires_at THEN
    RAISE EXCEPTION 'E_SESSION_EXTEND: 会话不可延长有效期（续期请重新登录签发）';
  END IF;

  -- ③ 吊销不可撤销：撤销是事实，不是开关
  IF OLD.revoked_at IS NOT NULL AND NEW.revoked_at IS NULL THEN
    RAISE EXCEPTION 'E_SESSION_REVIVE: 已吊销的会话不可复活（复活＝那个 token 又能用了）';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_ss_guard
  BEFORE UPDATE ON sys_session
  FOR EACH ROW EXECUTE FUNCTION fn_session_guard();

-- 吊销三件套必须同时给：只给 revoked_at 的"匿名吊销"回答不了"谁吊销的"
CREATE OR REPLACE FUNCTION fn_session_revoke_guard() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF NEW.revoked_at IS NOT NULL AND OLD.revoked_at IS NULL
     AND (NEW.revoked_by IS NULL OR NEW.revoked_reason IS NULL) THEN
    RAISE EXCEPTION 'E_SESSION_REVOKE_INCOMPLETE: 吊销必须同时给 by 与 reason';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_ss_revoke_guard
  BEFORE UPDATE ON sys_session
  FOR EACH ROW EXECUTE FUNCTION fn_session_revoke_guard();

-- ---------------------------------------------------------------------------
-- 签发 / 校验 / 吊销
-- ---------------------------------------------------------------------------
-- ★ 摘要由应用算（PGlite 没有 pgcrypto 的 sha256），库只收摘要。
--   为了避免"下一个人顺手把明文塞进来"，每个入口都校验格式：
--   明文 token 一定不是 64 位 hex，于是它会在第一行被拒，而不是被静默存下来。
CREATE OR REPLACE FUNCTION fn_assert_token_hash(p_hash text)
RETURNS void
LANGUAGE plpgsql
IMMUTABLE
SET search_path = ''
AS $$
BEGIN
  IF p_hash IS NULL OR p_hash !~ '^[0-9a-f]{64}$' THEN
    RAISE EXCEPTION 'E_SESSION_NOT_HASHED: 这里只收 sha256 摘要（64 位小写 hex），收到 % 个字符',
      COALESCE(length(p_hash), 0);
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION fn_session_issue(
  p_user       bigint,
  p_token_hash text,
  p_ttl        interval
) RETURNS timestamptz
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_exp timestamptz;
BEGIN
  PERFORM public.fn_assert_token_hash(p_token_hash);

  v_exp := clock_timestamp() + p_ttl;

  INSERT INTO public.sys_session(token_hash, user_id, expires_at)
  VALUES (p_token_hash, p_user, v_exp);

  RETURN v_exp;
END;
$$;

COMMENT ON FUNCTION fn_session_issue IS
  '签发会话。调用方生成 token 并算 sha256，库里只留摘要 —— '
  '这样库就算被完整导出，也冒充不了任何人。';

-- 校验：**返回"为什么不能用"，而不是返回 NULL**。
-- ★ NULL 只有一种语义，而"这个 token 从来不存在""过期了""被吊销了"
--   在处置上完全不同（前者可能是探测，后两者要看是谁吊销的）。
--   合成一个 NULL，等于把三种情况都推给调用方去猜。
CREATE OR REPLACE FUNCTION fn_session_check(p_token_hash text)
RETURNS TABLE (user_id bigint, status varchar, expires_at timestamptz, revoked_reason varchar)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT s.user_id,
         CASE
           WHEN s.revoked_at IS NOT NULL              THEN 'revoked'
           WHEN s.expires_at <= clock_timestamp()     THEN 'expired'
           ELSE 'ok'
         END::varchar,
         s.expires_at,
         s.revoked_reason
    FROM public.sys_session s
   WHERE s.token_hash = p_token_hash;
$$;

COMMENT ON FUNCTION fn_session_check IS
  '三态而非 NULL：missing / expired / revoked / ok。过期是**比较出来的**，'
  '不是某个定时任务翻的状态 —— 任务停三天，这里也不会多放行一个会话。';

CREATE OR REPLACE FUNCTION fn_session_revoke(p_token_hash text, p_by varchar, p_reason varchar)
RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_n int;
BEGIN
  UPDATE public.sys_session
     SET revoked_at = COALESCE(revoked_at, clock_timestamp()),
         revoked_by = COALESCE(revoked_by, p_by),
         revoked_reason = COALESCE(revoked_reason, p_reason)
   WHERE token_hash = p_token_hash
     AND revoked_at IS NULL;
  GET DIAGNOSTICS v_n = ROW_COUNT;
  -- 吊销一个不存在的会话：静默成功比报错危险得多 —— 调用方会以为它已作废。
  IF v_n = 0 THEN
    RAISE EXCEPTION 'E_SESSION_NOT_FOUND: 没有可吊销的会话（或已吊销）';
  END IF;
END;
$$;

-- 活跃会话（派生视图：不靠任何状态列）
CREATE OR REPLACE VIEW v_session_active AS
  SELECT s.id, s.user_id, s.issued_at, s.expires_at, s.last_seen_at
    FROM sys_session s
   WHERE s.revoked_at IS NULL AND s.expires_at > clock_timestamp();

COMMENT ON VIEW v_session_active IS
  '活跃会话。刻意不含 token_hash：这张视图是给人看的，'
  '能被 SELECT * 出来的一列摘要，也会被贴进聊天窗口。';

-- 心跳：只在超过 60 秒没更新时才写，避免每个请求一次写放大
CREATE OR REPLACE FUNCTION fn_session_touch(p_token_hash text)
RETURNS void
LANGUAGE sql
SET search_path = ''
AS $$
  UPDATE public.sys_session
     SET last_seen_at = clock_timestamp()
   WHERE token_hash = p_token_hash
     AND revoked_at IS NULL
     AND (last_seen_at IS NULL OR last_seen_at < clock_timestamp() - interval '60 seconds');
$$;

-- ---------------------------------------------------------------------------
-- 按会话 id 吊销（界面上"退出其它设备"用的就是这个）
-- ---------------------------------------------------------------------------
-- ★ 带上 p_user：吊销是"我吊销我自己的"，不是"谁都能吊销任何一条"。
--   不带 user 条件的吊销函数，一定会在某个客户端被传成任意 id。
CREATE OR REPLACE FUNCTION fn_session_revoke_id(
  p_id bigint, p_user bigint, p_by varchar, p_reason varchar
) RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_owner bigint;
BEGIN
  SELECT user_id INTO v_owner FROM public.sys_session WHERE id = p_id FOR UPDATE;
  IF v_owner IS NULL THEN
    RAISE EXCEPTION 'E_SESSION_NOT_FOUND: 会话 % 不存在', p_id;
  END IF;
  IF v_owner <> p_user THEN
    RAISE EXCEPTION 'E_OUT_OF_SCOPE: 会话 % 不属于用户 %', p_id, p_user;
  END IF;
  IF (SELECT revoked_at FROM public.sys_session WHERE id = p_id) IS NOT NULL THEN
    RAISE EXCEPTION 'E_SESSION_NOT_FOUND: 会话 % 已吊销', p_id;
  END IF;

  UPDATE public.sys_session
     SET revoked_at = clock_timestamp(), revoked_by = p_by, revoked_reason = p_reason
   WHERE id = p_id;
END;
$$;
