-- ============================================================================
-- 108_annual_bonus.sql · 年终奖：单独计税，单独一张工资条
-- ----------------------------------------------------------------------------
-- 年终奖（全年一次性奖金）的计税方式与月薪**完全不同**：
--
--   月薪：累计预扣，一年内税额逐月累进；
--   年终奖：奖金 ÷ 12 找月度税率，税额 = 奖金 × 税率 − 速算扣除。
--
-- 所以它不能塞进月度工资条：
--   · 塞进 gross → 会把当月的累计预扣顶到高档，之后 11 个月的税全被抬高；
--   · 塞进 tax_amount → 勾稽（明细和 = 应发 − 社保 − 个税）还能平，
--     但"这一次的税是哪一种"就再也分不出来了。
--
-- 因此：**单独一个 pay_run（kind='bonus'）**，单独一张工资条，
-- 社保为 0（年终奖不计社保基数），只有奖金与奖金税两行。
--
-- 政策依据：全年一次性奖金单独计税延续至 2027-12-31。这是一条会变的政策，
-- 所以税率表放在函数里，注释写明适用期 —— 到期只需要改一个函数，不改数据。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 批次类型：月度 / 年终奖
-- ---------------------------------------------------------------------------
ALTER TABLE pay_run ADD COLUMN IF NOT EXISTS kind varchar(8) NOT NULL DEFAULT 'monthly';
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_pr_kind') THEN
    ALTER TABLE pay_run ADD CONSTRAINT ck_pr_kind CHECK (kind IN ('monthly','bonus'));
  END IF;
END $$;

-- ★ 原唯一键是 (period, legal_entity_id, calc_version)：年终奖与月度工资
--   同期间会被判成"同一批"，于是"12 月的年终奖"和"12 月的工资"只能存在一个。
--   把 kind 加进唯一键，两者各占一条。
DO $$
DECLARE c text;
BEGIN
  SELECT conname INTO c FROM pg_constraint
   WHERE conrelid = 'public.pay_run'::regclass AND contype = 'u'
     AND pg_get_constraintdef(oid) LIKE '%period, legal_entity_id, calc_version%'
   LIMIT 1;
  IF c IS NOT NULL THEN EXECUTE format('ALTER TABLE public.pay_run DROP CONSTRAINT %I', c); END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uk_pr_period_entity_kind') THEN
    ALTER TABLE public.pay_run
      ADD CONSTRAINT uk_pr_period_entity_kind UNIQUE (period, legal_entity_id, calc_version, kind);
  END IF;
END $$;

COMMENT ON COLUMN pay_run.kind IS
  'monthly = 月度工资（累计预扣）；bonus = 年终奖（单独计税，社保为 0）。'
  '两者不能混在同一批 —— 混了之后"这一次的税是哪一种"就分不出来了。';

-- ---------------------------------------------------------------------------
-- 2. 年终奖发放记录
-- ---------------------------------------------------------------------------
CREATE TABLE annual_bonus (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id  bigint NOT NULL REFERENCES person(id),
  year       int NOT NULL,
  amount     numeric(12,2) NOT NULL CHECK (amount > 0),
  note       varchar(200),
  created_by varchar(64) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uk_ab_person_year UNIQUE (person_id, year)
);

COMMENT ON TABLE annual_bonus IS
  '年终奖：一年一人一次。单独计税，不与月度工资合并 —— '
  '一年发两次就不能再按"全年一次性"算，所以这里用唯一约束挡住。';

-- ---------------------------------------------------------------------------
-- 3. 年终奖计税：奖金÷12 找月度税率，税额 = 奖金×税率 − 速算扣除
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_iit_bonus(p_amount numeric)
RETURNS numeric
LANGUAGE plpgsql IMMUTABLE
SET search_path = ''
AS $$
DECLARE
  v_monthly numeric;
  v_rate numeric(6,4);
  v_deduct numeric(12,2);
BEGIN
  IF p_amount IS NULL OR p_amount <= 0 THEN RETURN 0; END IF;
  v_monthly := p_amount / 12;

  -- 月度综合所得税率表（全年一次性奖金按此表换算）
  IF    v_monthly <= 3000  THEN v_rate := 0.03; v_deduct := 0;
  ELSIF v_monthly <= 12000 THEN v_rate := 0.10; v_deduct := 210;
  ELSIF v_monthly <= 25000 THEN v_rate := 0.20; v_deduct := 1410;
  ELSIF v_monthly <= 35000 THEN v_rate := 0.25; v_deduct := 2660;
  ELSIF v_monthly <= 55000 THEN v_rate := 0.30; v_deduct := 4410;
  ELSIF v_monthly <= 80000 THEN v_rate := 0.35; v_deduct := 7160;
  ELSE  v_rate := 0.45; v_deduct := 15160;
  END IF;

  RETURN GREATEST(round(p_amount * v_rate - v_deduct, 2), 0);
END;
$$;

COMMENT ON FUNCTION fn_iit_bonus IS
  '全年一次性奖金个税（单独计税，政策延续至 2027-12-31）：'
  '奖金÷12 找月度税率，税 = 奖金×税率 − 速算扣除。政策到期只改这一个函数。';

-- ---------------------------------------------------------------------------
-- 4. 算年终奖批次
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_payroll_bonus_calc(p_run bigint)
RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  r public.pay_run%ROWTYPE;
  b record;
  v_tax numeric(12,2);
  v_slip bigint;
  v_n int := 0;
  v_year int;
BEGIN
  SELECT * INTO r FROM public.pay_run WHERE id = p_run FOR UPDATE;
  IF r.id IS NULL THEN RAISE EXCEPTION 'E_RUN_NOT_FOUND: %', p_run; END IF;
  IF r.kind <> 'bonus' THEN
    RAISE EXCEPTION 'E_RUN_KIND: 批次 % 不是年终奖批次（kind=%）', p_run, r.kind;
  END IF;
  IF r.status <> 'draft' THEN
    RAISE EXCEPTION 'E_RUN_SEALED: 批次 % 已封账，不可重算', p_run;
  END IF;

  v_year := left(r.period, 4)::int;

  FOR b IN
    SELECT ab.person_id, ab.amount
      FROM public.annual_bonus ab
      JOIN public.employment e ON e.person_id = ab.person_id
     WHERE ab.year = v_year
       AND e.legal_entity_id = r.legal_entity_id
       AND daterange(e.hire_date, e.leave_date, '[]') @> (to_date(r.period || '-01','YYYY-MM-DD')
                                                          + interval '1 month - 1 day')::date
  LOOP
    v_tax := public.fn_iit_bonus(b.amount);

    INSERT INTO public.payslip(pay_run_id, employee_id, gross_amount, net_amount,
                               si_employee, tax_amount, cum_taxable, leave_deduct)
    VALUES (p_run, b.person_id, b.amount, b.amount - v_tax, 0, v_tax, b.amount, 0)
    ON CONFLICT (pay_run_id, employee_id) DO UPDATE
      SET gross_amount = EXCLUDED.gross_amount, net_amount = EXCLUDED.net_amount,
          si_employee = 0, tax_amount = EXCLUDED.tax_amount,
          cum_taxable = EXCLUDED.cum_taxable
    RETURNING id INTO v_slip;

    DELETE FROM public.payslip_item WHERE payslip_id = v_slip;
    INSERT INTO public.payslip_item(payslip_id, item_code, amount) VALUES
      (v_slip, 'ANNUAL_BONUS', b.amount);
    IF v_tax <> 0 THEN
      INSERT INTO public.payslip_item(payslip_id, item_code, amount) VALUES
        (v_slip, 'BONUS_TAX', -v_tax);
    END IF;

    v_n := v_n + 1;
  END LOOP;

  IF v_n = 0 THEN
    RAISE EXCEPTION 'E_PAYROLL_NO_ELIGIBLE: 批次 % 一个人都没算出来（检查 % 年的年终奖记录）',
      p_run, v_year;
  END IF;
  RETURN v_n;
END;
$$;

COMMENT ON FUNCTION fn_payroll_bonus_calc IS
  '年终奖批次算薪：奖金计入应发，只扣奖金税，社保为 0，明细两行。'
  '不与月度工资合并 —— 合并会把当月累计预扣顶到高档，之后每个月都多扣税。';

