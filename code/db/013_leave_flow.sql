-- ============================================================================
-- 013_leave_flow.sql · 请假申请 → 审批 → 额度 → 工资条（端到端业务流）
-- ----------------------------------------------------------------------------
-- 这条流串起四个模块：人员(007) / 额度(011) / 审批(006) / 算薪(009)。
-- 它存在的目的不是"再加一张表"，而是暴露**模块之间的接缝**：
-- 四个模块各自的状态都对，但组合起来可能出四种不一致（见文件末尾）。
-- ============================================================================

CREATE TABLE leave_request (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id   bigint NOT NULL,
  leave_type_id bigint NOT NULL REFERENCES leave_type(id),
  qty           numeric(8,2) NOT NULL CHECK (qty > 0),
  date_from     date NOT NULL,
  date_to       date NOT NULL,
  status        varchar(16) NOT NULL DEFAULT 'pending',
  created_at    timestamptz NOT NULL DEFAULT now(),
  decided_at    timestamptz,
  CONSTRAINT ck_lr_span   CHECK (date_to >= date_from),
  CONSTRAINT ck_lr_status CHECK (status IN ('pending','approved','rejected','cancelled')),
  -- ★ 决定时刻与状态同生同灭：非 pending 必须有 decided_at
  CONSTRAINT ck_lr_decided CHECK ((status = 'pending') = (decided_at IS NULL))
);

-- ---------------------------------------------------------------------------
-- 申请：写单据 + 冻结额度，**同一个函数**
-- ---------------------------------------------------------------------------
-- ★ 分两步（先建单再冻结）会留下"单据在、额度没冻"的中间态；
--   并发下两个申请都通过校验，冻结总和超过可用。
CREATE OR REPLACE FUNCTION fn_leave_apply(
  p_employee bigint, p_type bigint, p_qty numeric,
  p_from date, p_to date
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_id bigint;
BEGIN
  INSERT INTO public.leave_request(employee_id, leave_type_id, qty, date_from, date_to)
  VALUES (p_employee, p_type, p_qty, p_from, p_to)
  RETURNING id INTO v_id;

  -- 冻结失败会抛异常，整个函数回滚，单据不会留下
  PERFORM public.fn_leave_freeze(p_employee, p_type, p_qty, v_id);
  RETURN v_id;
END;
$$;

-- ---------------------------------------------------------------------------
-- 审批：状态与额度一起前进
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_leave_decide(p_request bigint, p_approve boolean)
RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_status varchar(16);
BEGIN
  SELECT status INTO v_status FROM public.leave_request WHERE id = p_request FOR UPDATE;
  IF v_status IS NULL THEN
    RAISE EXCEPTION 'E_LEAVE_NO_REQUEST: 请假单 % 不存在', p_request;
  END IF;
  IF v_status <> 'pending' THEN
    RAISE EXCEPTION 'E_LEAVE_ALREADY_DECIDED: 请假单 % 已是 %', p_request, v_status;
  END IF;

  IF p_approve THEN
    UPDATE public.leave_request SET status='approved', decided_at=now() WHERE id=p_request;
    PERFORM public.fn_leave_approve(p_request);
  ELSE
    UPDATE public.leave_request SET status='rejected', decided_at=now() WHERE id=p_request;
    PERFORM public.fn_leave_reject(p_request);
  END IF;
END;
$$;

-- ---------------------------------------------------------------------------
-- 已批准的事假天数（**只管天数，不管钱**）
-- ---------------------------------------------------------------------------
-- ★ 这里原来叫 fn_leave_deduction，从 payslip.gross_amount 取日薪算钱 —— 循环依赖：
--   算薪时要先知道扣款，而扣款要读还没生成的工资条。
--   更要紧的是分层错了：**假期模块不该知道金额**。它只回答"批了几天"，
--   一天值多少钱属于薪酬模块（015）。分开之后两边都能单独测。
--
-- ★ 只认 approved：pending 就扣钱等于"申请了但没批"先扣款，
--   而员工连通知都还没收到。
CREATE OR REPLACE FUNCTION fn_leave_approved_days(
  p_employee bigint, p_period varchar, p_type_code varchar DEFAULT 'PERSONAL'
) RETURNS numeric
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT COALESCE(SUM(lr.qty), 0)
    FROM public.leave_request lr
    JOIN public.leave_type lt ON lt.id = lr.leave_type_id
   WHERE lr.employee_id = p_employee
     AND lr.status = 'approved'
     AND lt.code = p_type_code
     AND to_char(lr.date_from, 'YYYY-MM') = p_period;
$$;

-- ---------------------------------------------------------------------------
-- 接缝自检视图：四种"各自对、组合错"的不一致
-- ---------------------------------------------------------------------------
-- ① 单据 approved，但额度没有 used（审批走了、额度没走）
-- ② 单据 rejected，但额度仍 frozen（驳回没释放）
-- ③ 单据 pending，但没有对应的 frozen 记录（冻结丢了）
-- ④ 额度 used，但找不到 approved 的单据（有账无单）
CREATE VIEW v_leave_inconsistent AS
SELECT 'approved_but_not_used' AS kind, lr.id AS request_id
  FROM leave_request lr
 WHERE lr.status = 'approved'
   AND NOT EXISTS (SELECT 1 FROM leave_usage u
                    WHERE u.request_id = lr.id AND u.state = 'used')
UNION ALL
SELECT 'rejected_but_still_frozen', lr.id
  FROM leave_request lr
 WHERE lr.status = 'rejected'
   AND EXISTS (SELECT 1 FROM leave_usage u
                WHERE u.request_id = lr.id AND u.state = 'frozen')
UNION ALL
SELECT 'pending_without_freeze', lr.id
  FROM leave_request lr
 WHERE lr.status = 'pending'
   AND NOT EXISTS (SELECT 1 FROM leave_usage u
                    WHERE u.request_id = lr.id AND u.state = 'frozen')
UNION ALL
SELECT 'used_without_approved_request', u.request_id
  FROM leave_usage u
 WHERE u.state = 'used'
   AND NOT EXISTS (SELECT 1 FROM leave_request lr
                    WHERE lr.id = u.request_id AND lr.status = 'approved');

COMMENT ON VIEW v_leave_inconsistent IS
  '四种接缝不一致，任一非空即说明两个模块的状态不同步。'
  '这条视图的价值不在"能查"，在"它必须为空"——每增加一条业务流，就多加一个 UNION 分支。';
