-- ============================================================================
-- 159_perf_metric.sql · 绩效从「一个人一个数」变成「几个指标加权出一个数」
-- ----------------------------------------------------------------------------
-- 050 补上了打分（fn_perf_score），但它只收**一个 0–100 的数**。
-- 门店的真实形态不是这样：营业额达成 40% + 客诉 20% + 卫生 20% + 出勤 20%，
-- 每一项都要有目标、有实际值、有它自己的得分上下限，最后加权成总分。
-- 只给一个总分的界面，最后一定会变成"店长凭印象填个数"——
-- 而这个数进了工资，事后没人说得清它是怎么来的。
--
-- 用友 NC 6.3 绩效手册的口径，这一版取其中真正决定"数能不能对得上"的部分：
--   ① 指标库分四类（量化 / 行为价值观 / 加分项 / 扣分项），
--      **大类决定"实际值怎么来"**：量化有目标值、行为是考评录入、加减分是直接给分。
--   ② 取数方式里公式计算与录入并存 —— 有 formula 就走公式，没有就按实际值折分。
--   ③ 权重挂在「方案 × 指标」上（perf_item），不挂在人上。
--      **同一套方案对全部门店，差异在目标值，不在权重**；权重因人而异的话，
--      "这家店为什么比那家高"会被解释成"因为它的权重配得松"。
--   ④ 评分异常管控：单项得分设上下限，超限**必须写说明**才放行。
--      不写说明就放行，等于下限是个装饰；一律拒绝，等于业务上真的调不动。
--
-- 三条刻意不做的事：
--   ★ 不做"目标值按人设"。perf_item 是方案级的，个人目标请另开方案版本 ——
--     否则同一方案下每行一个目标值，方案就不再是"一套口径"。
--   ★ 不直接 UPDATE perf_result.score。总分必须穿过 fn_perf_score，
--     让档位重算 / 封存拦截 / 改分留痕继续是**同一条路**。绕过它的写法
--     会让"改分"与"算分"在表里同形，事后分不出来。
--   ★ 超额封顶 150%，不是无限。完成率 300% 的店与 100% 的店拿同一个单项上限，
--     差距靠"加分项"显式表达 —— 而加分项是有名字、可审计的。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 0. 方案上加汇总规则
-- ---------------------------------------------------------------------------
-- 三选一：加权求和 / 算术求和 / 算术平均。默认 weighted —— 与 026 的存量一致，
-- 加这一列不改任何既有周期的算法。
ALTER TABLE public.perf_scheme
  ADD COLUMN IF NOT EXISTS agg_rule varchar(16) NOT NULL DEFAULT 'weighted';

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_ps_agg') THEN
    ALTER TABLE public.perf_scheme ADD CONSTRAINT ck_ps_agg
      CHECK (agg_rule IN ('weighted','sum','avg'));
  END IF;
END $$;

COMMENT ON COLUMN public.perf_scheme.agg_rule IS
  '汇总规则：weighted=按 perf_item.weight 加权求和（默认）；'
  'sum=各项得分的算术和；avg=各项得分的算术平均。'
  '三种规则算出来的数**不能互相比较**，所以规则是方案的一部分，不是查询参数。';

-- ---------------------------------------------------------------------------
-- 1. 指标库
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.perf_metric (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code       varchar(32) NOT NULL,
  name       varchar(64) NOT NULL,
  kind       varchar(16) NOT NULL,
  unit       varchar(16),
  direction  varchar(8)  NOT NULL DEFAULT 'up',
  -- ★ 这里是**该项得分的上下限**，不是完成率的上下限。
  --   默认 0–150：与"超额封顶 150%"同一条口径，改一处就够。
  score_min  numeric(6,2) NOT NULL DEFAULT 0,
  score_max  numeric(6,2) NOT NULL DEFAULT 150,
  note       varchar(200),
  is_active  boolean      NOT NULL DEFAULT true,
  CONSTRAINT uk_pm_code  UNIQUE (code),
  CONSTRAINT ck_pm_kind  CHECK (kind IN ('quant','behavior','bonus','penalty')),
  CONSTRAINT ck_pm_dir   CHECK (direction IN ('up','down')),
  CONSTRAINT ck_pm_range CHECK (score_max >= score_min)
);

COMMENT ON COLUMN public.perf_metric.kind IS
  'quant=量化（有目标值）/ behavior=行为价值观（考评录入）/ bonus=加分项 / penalty=扣分项。'
  '大类决定 min/max 的合理取值：加分项通常 (0,20]，扣分项通常 [-20,0)。';
COMMENT ON COLUMN public.perf_metric.direction IS
  'up=越大越好；down=越小越好（客诉次数、损耗率）。'
  'down 的折分是 target/actual，且**不给超额加分** —— 零客诉已经是满分，'
  '再给 150 分会让它把一个季度的营业额缺口抹平。';
COMMENT ON COLUMN public.perf_metric.score_min IS
  '该项得分的下限（不是完成率下限）。得分越界且没写说明 → E_PERF_SCORE_RANGE。';

-- ---------------------------------------------------------------------------
-- 2. 考核项：挂在方案上
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.perf_item (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scheme_id    bigint        NOT NULL REFERENCES public.perf_scheme(id) ON DELETE CASCADE,
  metric_id    bigint        NOT NULL REFERENCES public.perf_metric(id),
  weight       numeric(6,4)  NOT NULL,
  target_value numeric(14,4),
  formula      varchar(200),
  seq          int           NOT NULL DEFAULT 0,
  -- 同一方案里一个指标只能出现一次：重复会让"权重 0.2"变成两行各 0.2，
  -- 而汇总时两行都参与，实际权重悄悄翻倍。
  CONSTRAINT uk_pi UNIQUE (scheme_id, metric_id),
  CONSTRAINT ck_pi_weight CHECK (weight >= 0 AND weight <= 1)
);

CREATE INDEX IF NOT EXISTS ix_pi_scheme ON public.perf_item(scheme_id, seq);

COMMENT ON COLUMN public.perf_item.target_value IS
  '目标值。NULL = 没有目标（行为/加减分项），此时录入值**直接当分**。';
COMMENT ON COLUMN public.perf_item.formula IS
  '公式（可选）。给了就按公式算该项得分，变量 ACTUAL / TARGET / WEIGHT。'
  '公式返回的是**该项得分**，不是实际值 —— 实际值仍由 perf_result_item.actual_value 留着。';

-- 权重合计必须等于 1 这件事**存的时候就校验**（fn_perf_item_set）。
-- 等到汇总时才发现加起来 0.95，那时已经有人按"评过了"在沟通了。

-- ---------------------------------------------------------------------------
-- 3. 逐项得分：一条结果下 N 行
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.perf_result_item (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  result_id    bigint        NOT NULL REFERENCES public.perf_result(id) ON DELETE CASCADE,
  item_id      bigint        NOT NULL REFERENCES public.perf_item(id),
  actual_value numeric(14,4),
  score        numeric(8,2)  NOT NULL,
  note         varchar(200),
  CONSTRAINT uk_pri UNIQUE (result_id, item_id)
);

CREATE INDEX IF NOT EXISTS ix_pri_result ON public.perf_result_item(result_id);

COMMENT ON COLUMN public.perf_result_item.actual_value IS
  '实际完成值（客诉 0 次、营业额 38 万）。公式项也留，'
  '否则事后只能说"按公式算的"，说不出"拿什么算的"。';

-- ★ 封存后逐项得分同样不可改。050 的触发器只管 perf_result；
--   逐项表没有这道门，就会出现"总分封住了、明细还能改"——
--   而明细是"这个分怎么来的"的唯一证据。
CREATE OR REPLACE FUNCTION public.fn_pri_frozen() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE v_status varchar(16);
BEGIN
  SELECT c.status INTO v_status
    FROM public.perf_result r
    JOIN public.perf_cycle  c ON c.id = r.cycle_id
   WHERE r.id = COALESCE(NEW.result_id, OLD.result_id);
  IF v_status = 'sealed' THEN
    RAISE EXCEPTION 'E_PERF_SEALED: 绩效周期已封存，逐项得分不可增删改';
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$;

DROP TRIGGER IF EXISTS trg_pri_frozen ON public.perf_result_item;
CREATE TRIGGER trg_pri_frozen
  BEFORE INSERT OR UPDATE OR DELETE ON public.perf_result_item
  FOR EACH ROW EXECUTE FUNCTION public.fn_pri_frozen();

-- ---------------------------------------------------------------------------
-- 4. 整方案写入考核项（先删后插，同一事务）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_perf_item_set(
  p_scheme bigint,
  p_items  jsonb,
  p_by     varchar
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v            jsonb;
  v_idx        int;
  v_metric     bigint;
  v_mcode      text;
  v_weight     numeric;
  v_target     numeric;
  v_formula    varchar(200);
  v_seq        int;
  v_sum        numeric := 0;
  v_n          int := 0;
  v_seen       bigint[] := ARRAY[]::bigint[];
  v_err        varchar;
BEGIN
  IF p_scheme IS NULL OR NOT EXISTS (SELECT 1 FROM public.perf_scheme WHERE id = p_scheme) THEN
    RAISE EXCEPTION 'E_PERF_NO_SCHEME: 绩效方案 % 不存在', p_scheme;
  END IF;
  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' THEN
    RAISE EXCEPTION 'E_PERF_ITEM_ARG: 考核项必须是 JSON 数组（收到 %）',
      COALESCE(jsonb_typeof(p_items), 'null');
  END IF;
  IF jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'E_PERF_ITEM_EMPTY: 方案 % 不能没有考核项（权重和 0 永远不等于 1）', p_scheme;
  END IF;

  -- ★ 已经被打分引用过就拒绝整方案覆盖：先删后插会让明细指向不存在的项，
  --   或者更糟 —— 悄悄改变已评过的那批人的口径。要改口径请新开一版方案
  --   （perf_scheme 本来就有 version）。
  IF EXISTS (
    SELECT 1 FROM public.perf_item i
      JOIN public.perf_result_item ri ON ri.item_id = i.id
     WHERE i.scheme_id = p_scheme
  ) THEN
    RAISE EXCEPTION 'E_PERF_ITEMS_IN_USE: 方案 % 的考核项已被打分引用，改口径请新开一版方案', p_scheme;
  END IF;

  -- ---- 第一遍：全部校验 + 累加权重（校验没过之前一行都不删） ----
  FOR v, v_idx IN
    SELECT e.value, e.ordinality
      FROM jsonb_array_elements(p_items) WITH ORDINALITY AS e(value, ordinality)
  LOOP
    v_mcode := NULLIF(btrim(COALESCE(v->>'metric_code', '')), '');
    IF (v->>'metric_id') ~ '^\d+$' THEN
      v_metric := (v->>'metric_id')::bigint;
    ELSIF v_mcode IS NOT NULL THEN
      SELECT id INTO v_metric FROM public.perf_metric WHERE code = v_mcode;
    ELSE
      RAISE EXCEPTION 'E_PERF_ITEM_ARG: 第 % 项既没有 metric_id 也没有 metric_code', v_idx;
    END IF;
    IF v_metric IS NULL OR NOT EXISTS (SELECT 1 FROM public.perf_metric WHERE id = v_metric) THEN
      RAISE EXCEPTION 'E_PERF_ITEM_ARG: 第 % 项的指标 % 不在指标库里', v_idx, COALESCE(v_mcode, v->>'metric_id');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.perf_metric WHERE id = v_metric AND is_active) THEN
      RAISE EXCEPTION 'E_PERF_METRIC_INACTIVE: 第 % 项的指标 % 已停用，不能挂到方案上', v_idx, v_mcode;
    END IF;
    IF v_metric = ANY (v_seen) THEN
      RAISE EXCEPTION 'E_PERF_DUP_METRIC: 第 % 项的指标 % 在同一方案里重复出现（权重会被算两遍）',
        v_idx, COALESCE(v_mcode, v_metric::text);
    END IF;
    v_seen := v_seen || v_metric;

    IF (v->>'weight') IS NULL OR btrim(v->>'weight') = '' THEN
      RAISE EXCEPTION 'E_PERF_ITEM_ARG: 第 % 项没有 weight', v_idx;
    END IF;
    IF (v->>'weight') !~ '^-?[0-9]+(\.[0-9]+)?$' THEN
      RAISE EXCEPTION 'E_PERF_ITEM_ARG: 第 % 项的 weight「%」不是数字', v_idx, v->>'weight';
    END IF;
    v_weight := (v->>'weight')::numeric;
    IF v_weight < 0 OR v_weight > 1 THEN
      RAISE EXCEPTION 'E_PERF_ITEM_ARG: 第 % 项的 weight % 不在 0–1 之间', v_idx, v_weight;
    END IF;
    v_sum := v_sum + v_weight;

    v_formula := NULLIF(btrim(COALESCE(v->>'formula', '')), '');
    IF v_formula IS NOT NULL THEN
      IF length(v_formula) > 200 THEN
        RAISE EXCEPTION 'E_PERF_ITEM_ARG: 第 % 项的公式超过 200 字', v_idx;
      END IF;
      -- 公式在这里就试算一遍：等到打分时才发现写错，那时周期已经开了。
      v_err := public.fn_formula_script_try(
                 v_formula, '{"ACTUAL":1,"TARGET":1,"WEIGHT":1}'::jsonb);
      IF v_err IS NOT NULL THEN
        RAISE EXCEPTION 'E_PERF_ITEM_FORMULA: 第 % 项的公式算不出来：%', v_idx, v_err;
      END IF;
    END IF;
  END LOOP;

  -- ---- 权重和：这是"存的时候就校验"的那一处 ----
  -- 容差 0.001：三位分成 0.3333 这类写法合计 0.9999，是舍入不是配错；
  -- 而 0.9 / 0.95 这种真配错的，差得远不止 0.001。
  IF abs(v_sum - 1) > 0.001 THEN
    RAISE EXCEPTION 'E_PERF_WEIGHT_SUM: 方案 % 的权重合计是 %，必须等于 1（差 %）',
      p_scheme, round(v_sum, 4), round(1 - v_sum, 4);
  END IF;

  -- ---- 第二遍：先删后插 ----
  DELETE FROM public.perf_item WHERE scheme_id = p_scheme;

  FOR v, v_idx IN
    SELECT e.value, e.ordinality
      FROM jsonb_array_elements(p_items) WITH ORDINALITY AS e(value, ordinality)
  LOOP
    v_mcode := NULLIF(btrim(COALESCE(v->>'metric_code', '')), '');
    IF (v->>'metric_id') ~ '^\d+$' THEN
      v_metric := (v->>'metric_id')::bigint;
    ELSE
      SELECT id INTO v_metric FROM public.perf_metric WHERE code = v_mcode;
    END IF;

    v_target  := CASE WHEN (v->>'target_value') ~ '^-?[0-9]+(\.[0-9]+)?$'
                      THEN (v->>'target_value')::numeric END;
    v_formula := NULLIF(btrim(COALESCE(v->>'formula', '')), '');
    v_seq     := CASE WHEN (v->>'seq') ~ '^-?\d+$' THEN (v->>'seq')::int ELSE v_idx::int END;

    INSERT INTO public.perf_item(scheme_id, metric_id, weight, target_value, formula, seq)
    VALUES (p_scheme, v_metric, (v->>'weight')::numeric, v_target, v_formula, v_seq);
    v_n := v_n + 1;
  END LOOP;

  RETURN v_n;
END;
$$;

COMMENT ON FUNCTION public.fn_perf_item_set IS
  '整方案覆盖式写入考核项（先删后插）。权重和 ≠ 1 → E_PERF_WEIGHT_SUM，'
  '指标重复 → E_PERF_DUP_METRIC，公式算不出来 → E_PERF_ITEM_FORMULA。'
  '被打过分的方案拒绝覆盖（E_PERF_ITEMS_IN_USE）—— 改口径请新开一版。';

-- ---------------------------------------------------------------------------
-- 5. 录实际值 → 算出该项得分
-- ---------------------------------------------------------------------------
-- 折分口径（**不要自己在别处再算一遍**）：
--   有 formula      → fn_formula_script_eval，变量 ACTUAL / TARGET / WEIGHT
--   目标值 NULL     → p_actual 直接当分（行为价值观 / 加减分项 / 录入考评分）
--   direction=down  → 目标 0（零容忍）时：实际 ≤0 得 100，否则 0；
--                     否则 LEAST(target/actual, 1) * 100
--   direction=up    → LEAST(actual/target, 1.5) * 100（封顶 150%，超额不是无限）
--   up 且目标为 0   → 视同没有目标，p_actual 直接当分
CREATE OR REPLACE FUNCTION public.fn_perf_item_score(
  p_result bigint,
  p_item   bigint,
  p_actual numeric,
  p_note   varchar
) RETURNS numeric
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  r         public.perf_result%ROWTYPE;
  c         public.perf_cycle%ROWTYPE;
  i         public.perf_item%ROWTYPE;
  m         public.perf_metric%ROWTYPE;
  v_scheme  bigint;
  v_score   numeric;
BEGIN
  SELECT * INTO r FROM public.perf_result WHERE id = p_result FOR UPDATE;
  IF r.id IS NULL THEN
    RAISE EXCEPTION 'E_PERF_NO_RESULT: 绩效结果 % 不存在', p_result;
  END IF;

  SELECT * INTO c FROM public.perf_cycle WHERE id = r.cycle_id;
  IF c.status = 'sealed' THEN
    RAISE EXCEPTION 'E_PERF_SEALED: 周期 % 已封存，逐项得分不可再改', c.code;
  END IF;
  IF r.state <> 'scored' THEN
    RAISE EXCEPTION 'E_PERF_RESULT_EXCLUDED: 结果 % 是"不参与考核"，不该有逐项得分', p_result;
  END IF;

  -- 方案取「周期结束日」生效的那一版 —— 与 fn_perf_score / fn_perf_seal 同一条口径。
  v_scheme := public.fn_perf_scheme_asof(c.period_to);

  SELECT * INTO i FROM public.perf_item WHERE id = p_item AND scheme_id = v_scheme;
  IF i.id IS NULL THEN
    RAISE EXCEPTION 'E_PERF_ITEM_NOT_IN_SCHEME: 考核项 % 不在周期 % 生效的方案 % 里', p_item, c.code, v_scheme;
  END IF;

  SELECT * INTO m FROM public.perf_metric WHERE id = i.metric_id;
  IF NOT m.is_active THEN
    RAISE EXCEPTION 'E_PERF_METRIC_INACTIVE: 指标 % 已停用', m.code;
  END IF;

  IF p_actual IS NULL THEN
    RAISE EXCEPTION 'E_PERF_NO_ACTUAL: 指标 % 必须给实际值（公式项也要给 ACTUAL）', m.code;
  END IF;

  IF i.formula IS NOT NULL AND btrim(i.formula) <> '' THEN
    v_score := public.fn_formula_script_eval(
                 i.formula,
                 jsonb_build_object('ACTUAL', p_actual,
                                    'TARGET', COALESCE(i.target_value, 0),
                                    'WEIGHT', i.weight));
  ELSIF i.target_value IS NULL THEN
    v_score := p_actual;
  ELSIF m.direction = 'down' THEN
    IF i.target_value = 0 THEN
      v_score := CASE WHEN p_actual <= 0 THEN 100 ELSE 0 END;
    ELSE
      v_score := CASE WHEN p_actual <= 0 THEN 100
                      ELSE LEAST(i.target_value / p_actual, 1) * 100 END;
    END IF;
  ELSIF i.target_value = 0 THEN
    v_score := p_actual;
  ELSE
    v_score := LEAST(p_actual / i.target_value, 1.5) * 100;
  END IF;

  v_score := round(v_score, 2);

  -- ★ 超限必须填说明才放行。规则本身允许特批（业务上确实有），
  --   但特批必须留下"为什么" —— 否则月度复盘时只有一个突兀的高分。
  IF v_score < m.score_min OR v_score > m.score_max THEN
    IF p_note IS NULL OR length(btrim(p_note)) < 4 THEN
      RAISE EXCEPTION 'E_PERF_SCORE_RANGE: 指标「%」得分 % 超出 [%, %]，写说明（≥4 字）才能特批',
        m.code, v_score, m.score_min, m.score_max;
    END IF;
  END IF;

  INSERT INTO public.perf_result_item(result_id, item_id, actual_value, score, note)
  VALUES (p_result, p_item, p_actual, v_score, NULLIF(btrim(p_note), ''))
  ON CONFLICT (result_id, item_id) DO UPDATE
     SET actual_value = EXCLUDED.actual_value,
         score        = EXCLUDED.score,
         note         = EXCLUDED.note;

  RETURN v_score;
END;
$$;

COMMENT ON FUNCTION public.fn_perf_item_score IS
  '录实际值 → 算该项得分（并落库）。有 formula 走公式引擎，无目标值则录入值直接当分，'
  'up 按 LEAST(actual/target,1.5)*100 折分，down 按 target/actual 折分且不给超额加分。'
  '得分越过 perf_metric 的 score_min/max 且没写说明 → E_PERF_SCORE_RANGE。';

-- ---------------------------------------------------------------------------
-- 6. 加权汇总 → 回写总分
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_perf_total(
  p_result bigint,
  p_by     varchar DEFAULT NULL
) RETURNS numeric
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  r         public.perf_result%ROWTYPE;
  c         public.perf_cycle%ROWTYPE;
  v_scheme  bigint;
  v_rule    varchar(16);
  v_items   int;
  v_wsum    numeric;
  v_total   numeric;
  v_missing text[];
BEGIN
  SELECT * INTO r FROM public.perf_result WHERE id = p_result FOR UPDATE;
  IF r.id IS NULL THEN
    RAISE EXCEPTION 'E_PERF_NO_RESULT: 绩效结果 % 不存在', p_result;
  END IF;

  SELECT * INTO c FROM public.perf_cycle WHERE id = r.cycle_id;
  IF c.status = 'sealed' THEN
    RAISE EXCEPTION 'E_PERF_SEALED: 周期 % 已封存，总分不可重算（封存前算的才是发钱的依据）', c.code;
  END IF;
  IF r.state <> 'scored' THEN
    RAISE EXCEPTION 'E_PERF_RESULT_EXCLUDED: 结果 % 是"不参与考核"，不该汇总', p_result;
  END IF;

  v_scheme := public.fn_perf_scheme_asof(c.period_to);
  SELECT agg_rule INTO v_rule FROM public.perf_scheme WHERE id = v_scheme;

  SELECT count(*) INTO v_items FROM public.perf_item WHERE scheme_id = v_scheme;
  IF v_items = 0 THEN
    RAISE EXCEPTION 'E_PERF_NO_ITEMS: 方案 % 没有考核项，无法汇总（先 fn_perf_item_set）', v_scheme;
  END IF;

  SELECT COALESCE(sum(weight), 0) INTO v_wsum
    FROM public.perf_item WHERE scheme_id = v_scheme;

  IF v_rule = 'weighted' AND abs(v_wsum - 1) > 0.001 THEN
    RAISE EXCEPTION 'E_PERF_WEIGHT_SUM: 方案 % 的权重合计是 %，加权汇总前必须等于 1',
      v_scheme, round(v_wsum, 4);
  END IF;

  -- 缺项：按 0 参与汇总，但**不静默** —— 名单在这里，调用方看得见。
  SELECT array_agg(m.code ORDER BY i.seq, i.id) INTO v_missing
    FROM public.perf_item i
    JOIN public.perf_metric m ON m.id = i.metric_id
    LEFT JOIN public.perf_result_item ri
           ON ri.item_id = i.id AND ri.result_id = p_result
   WHERE i.scheme_id = v_scheme AND ri.id IS NULL;

  SELECT CASE v_rule
           WHEN 'sum' THEN sum(COALESCE(ri.score, 0))
           WHEN 'avg' THEN avg(COALESCE(ri.score, 0))
           ELSE           sum(COALESCE(ri.score, 0) * i.weight)
         END
    INTO v_total
    FROM public.perf_item i
    LEFT JOIN public.perf_result_item ri
           ON ri.item_id = i.id AND ri.result_id = p_result
   WHERE i.scheme_id = v_scheme;

  v_total := COALESCE(v_total, 0);

  -- ★ 总分口径是 0–100（档位表只覆盖这个区间）。单项 150% 封顶只在单项里生效；
  --   汇总超过 100 时**封到 100 并告警**，不静默、也不让 fn_perf_score 报一个
  --   看起来像"分数填错"的 E_PERF_SCORE_OUT_OF_RANGE。
  IF v_total > 100 THEN
    RAISE WARNING 'E_PERF_TOTAL_CAP: 结果 % 的%s汇总为 %，按 100 封顶（档位口径是百分制）',
      p_result, CASE v_rule WHEN 'sum' THEN '算术和' WHEN 'avg' THEN '算术平均' ELSE '加权和' END,
      round(v_total, 2);
    v_total := 100;
  ELSIF v_total < 0 THEN
    RAISE WARNING 'E_PERF_TOTAL_CAP: 结果 % 汇总为 %，按 0 封底', p_result, round(v_total, 2);
    v_total := 0;
  END IF;
  v_total := round(v_total, 2);

  IF v_missing IS NOT NULL THEN
    RAISE WARNING 'E_PERF_ITEM_MISSING: 结果 % 还缺 % 项（按 0 计）：%',
      p_result, cardinality(v_missing), array_to_string(v_missing, ', ');
  END IF;

  -- ★ 回写必须穿过 fn_perf_score：档位重算 / 封存拦截 / 改分留痕都在那条路上。
  --   直接 UPDATE perf_result 会把这三件事一起绕过，而表里看不出走的是哪条路。
  --   158 起 fn_perf_score 会写 scored_by —— 汇总也是"一次打分"，
  --   所以 p_by 一路传下去；没传时退回 'perf_total'（自动汇总，不冒名）。
  PERFORM public.fn_perf_score(r.cycle_id, r.employee_id, v_total, r.note,
                               COALESCE(NULLIF(btrim(p_by), ''), 'perf_total'));

  RETURN v_total;
END;
$$;

COMMENT ON FUNCTION public.fn_perf_total IS
  '按方案的 agg_rule（weighted/sum/avg）汇总逐项得分，并穿过 fn_perf_score 回写总分 + 重算档位。'
  '缺项按 0 计但不静默（E_PERF_ITEM_MISSING 告警 + 调用方另有清单）。'
  '总分封顶 100（E_PERF_TOTAL_CAP 告警）—— 档位表只覆盖百分制。';

-- ---------------------------------------------------------------------------
-- 7. 方案体检：一次把问题列全
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_perf_item_check(p_scheme bigint)
RETURNS TABLE (metric_code varchar, problem varchar)
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE
  v_err    varchar;
  v_sum    numeric;
  v_n      int;
  v        record;
BEGIN
  IF p_scheme IS NULL OR NOT EXISTS (SELECT 1 FROM public.perf_scheme WHERE id = p_scheme) THEN
    RETURN QUERY SELECT NULL::varchar,
                        format('方案 %s 不存在', COALESCE(p_scheme::text, '(空)'))::varchar;
    RETURN;
  END IF;

  SELECT count(*), COALESCE(sum(weight), 0) INTO v_n, v_sum
    FROM public.perf_item WHERE scheme_id = p_scheme;

  IF v_n = 0 THEN
    RETURN QUERY SELECT NULL::varchar, '方案下没有任何考核项'::varchar;
    RETURN;
  END IF;

  IF abs(v_sum - 1) > 0.001 THEN
    RETURN QUERY SELECT NULL::varchar,
      format('权重合计是 %s，应为 1（差 %s）', round(v_sum, 4), round(1 - v_sum, 4))::varchar;
  END IF;

  FOR v IN
    SELECT m.code, m.name, m.kind, m.is_active, i.weight, i.target_value, i.formula
      FROM public.perf_item i
      JOIN public.perf_metric m ON m.id = i.metric_id
     WHERE i.scheme_id = p_scheme
     ORDER BY i.seq, i.id
  LOOP
    IF NOT v.is_active THEN
      RETURN QUERY SELECT v.code::varchar, '指标已停用，但仍挂在方案上'::varchar;
    END IF;

    IF v.weight = 0 THEN
      RETURN QUERY SELECT v.code::varchar, '权重为 0：挂在方案上但不参与总分'::varchar;
    END IF;

    -- 量化项既没目标值也没公式：只能把录入值直接当分，而"分"与"完成值"是两回事
    IF v.kind = 'quant' AND v.target_value IS NULL
       AND (v.formula IS NULL OR btrim(v.formula) = '') THEN
      RETURN QUERY SELECT v.code::varchar,
        '量化项没有目标值也没有公式：录入值会被直接当分用（确认这是本意）'::varchar;
    END IF;

    IF v.formula IS NOT NULL AND btrim(v.formula) <> '' THEN
      v_err := public.fn_formula_script_try(
                 v.formula, '{"ACTUAL":1,"TARGET":1,"WEIGHT":1}'::jsonb);
      IF v_err IS NOT NULL THEN
        RETURN QUERY SELECT v.code::varchar, ('公式算不出来：' || v_err)::varchar;
      END IF;
    END IF;
  END LOOP;
END;
$$;

COMMENT ON FUNCTION public.fn_perf_item_check IS
  '方案体检：权重和 / 权重为 0 / 量化项缺目标 / 指标停用 / 公式算不出来，一次列全。'
  '返回行数 = 问题数；0 行才说明这套方案能用来打分。';

