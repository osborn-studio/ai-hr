-- ---------------------------------------------------------------------------
-- 8. 时间窗接进答卷写入（不改 147/156 的文件，只重定义那个触发器函数）
-- ---------------------------------------------------------------------------
-- ★ 为什么要重定义：闸只做成一个"请调用方记得调"的函数，等于没闸 ——
--   147 的核心原则是"分数由库算，前端改不了"，时间窗同理。
--   下面这个函数是 156 fn_exam_attempt_prepare 的**原文**，只在开头加了一段
--   时间窗检查（与 147 重定义 fn_training_attend 是同一个做法：
--   原件照抄 + 一处新增，规则只有一份实现）。
CREATE OR REPLACE FUNCTION fn_exam_attempt_prepare() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  p      record;
  v_done int;
BEGIN
  SELECT * INTO p FROM public.exam_paper WHERE id = NEW.paper_id;
  IF p.id IS NULL THEN
    RAISE EXCEPTION 'E_EXAM_NO_PAPER: 试卷 % 不存在', NEW.paper_id;
  END IF;

  -- 157 新增：不在任何任务窗口内 → E_EXAM_TASK_CLOSED（该卷没有任务时放行）
  PERFORM public.fn_exam_task_check(NEW.paper_id, COALESCE(NEW.started_at, now()));

  -- 次数：只数已交卷的
  IF p.max_attempts IS NOT NULL THEN
    SELECT count(*)::int INTO v_done
      FROM public.exam_attempt a
     WHERE a.paper_id = NEW.paper_id
       AND a.employee_id = NEW.employee_id
       AND a.submitted_at IS NOT NULL;
    IF v_done >= p.max_attempts THEN
      RAISE EXCEPTION 'E_EXAM_NO_ATTEMPT_LEFT: 《%》只能考 % 次，已经考过 % 次（已用完）',
        p.name, p.max_attempts, v_done;
    END IF;
  END IF;

  -- 截止时刻：库端算，前端只负责显示
  IF p.duration_min IS NOT NULL AND NEW.deadline_at IS NULL THEN
    NEW.deadline_at := COALESCE(NEW.started_at, now()) + make_interval(mins => p.duration_min);
  END IF;

  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION fn_exam_attempt_prepare IS
  '开考时补三件事（156 原文 + 157 的时间窗）：卡时间窗、算截止时刻、卡次数（只数已交卷的）。'
  '时间窗在这一层而不是 fn_exam_start 里：任何直接插 exam_attempt 的路径都绕不过去。';

-- ---------------------------------------------------------------------------
-- 9. 切屏事件流：存时间点，不存次数
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.exam_cheat_log (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_id bigint      NOT NULL REFERENCES public.exam_attempt(id) ON DELETE CASCADE,
  -- ★ 时间点由库端给（服务层不传）：客户端时钟是考生能改的东西，
  --   而这条记录的全部价值就是"几点几分"，改得了就没有价值。
  -- ★ clock_timestamp() 不是 now()：now() 是**事务开始**时刻，同一个请求里
  --   连记三条会得到三个一模一样的时间点，而"同一秒切了三次"与"只切一次"就分不开了。
  --   判定型时间戳一律用 clock_timestamp()（与 004 的 app_event_log 同一条规矩）。
  event_at   timestamptz NOT NULL DEFAULT clock_timestamp(),
  kind       varchar(12) NOT NULL,
  detail     varchar(120),
  CONSTRAINT ck_ecl_kind CHECK (kind IN ('blur', 'hidden', 'paste', 'screenshot'))
);

CREATE INDEX IF NOT EXISTS ix_ecl_attempt ON public.exam_cheat_log (attempt_id, event_at);

COMMENT ON TABLE public.exam_cheat_log IS
  '切屏/失焦事件流（157）：**一次一行、存时间点**，不存"切屏 3 次"这种聚合值。'
  '次数是聚合出来的，写死就解释不了"那 3 次分别几点" —— 而争论发生时只有时间点能回答。'
  'kind：blur=窗口失焦 / hidden=页面隐藏 / paste=粘贴 / screenshot=截屏。';
COMMENT ON COLUMN public.exam_cheat_log.event_at IS
  '事件发生时刻（库端 clock_timestamp()）。不存次数、不接收前端传的时间：'
  '改本地时间就能伪造"我当时没切屏"，而同一事务内连记三条也要能看出先后。';
COMMENT ON COLUMN public.exam_cheat_log.detail IS
  '补充说明（≤120 字），例如"切走 12 秒后返回"。是给人看的线索，不是判据。';

-- 交卷后不许补记：否则"事后栽赃"没有边界
CREATE OR REPLACE FUNCTION fn_exam_cheat_guard() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_sub timestamptz;
BEGIN
  IF TG_OP = 'INSERT' THEN
    SELECT a.submitted_at INTO v_sub
      FROM public.exam_attempt a WHERE a.id = NEW.attempt_id;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'E_EXAM_NO_ATTEMPT: 答卷 % 不存在，事件记不上', NEW.attempt_id;
    END IF;
    -- ★ 交卷后不能补记。这一条守的不是技术边界，是**证据边界**：
    --   交卷之后再往这份卷上加三条切屏，等于事后栽赃，而事后没人分得清真假。
    --   要补就当场补 —— 监考的价值恰恰在于"当时"。
    IF v_sub IS NOT NULL THEN
      RAISE EXCEPTION
        'E_EXAM_SUBMITTED: 答卷 % 已于 % 交卷，不能再补记切屏事件（补记等于事后栽赃）',
        NEW.attempt_id, v_sub;
    END IF;
    RETURN NEW;
  END IF;

  IF TG_OP = 'DELETE' THEN
    -- 级联删（答卷本身被删）放行：父行已经不在，事件没有归属。
    -- 除此之外事件是**证据**，不能改、不能删 —— 要更正就再记一条。
    IF NOT EXISTS (SELECT 1 FROM public.exam_attempt a WHERE a.id = OLD.attempt_id) THEN
      RETURN OLD;
    END IF;
  END IF;

  RAISE EXCEPTION 'E_EXAM_CHEAT_APPEND_ONLY: 切屏事件是证据，不能%（要更正就再记一条）',
    CASE TG_OP WHEN 'UPDATE' THEN '改' ELSE '删' END;
END;
$$;

DROP TRIGGER IF EXISTS trg_exam_cheat_guard ON public.exam_cheat_log;
CREATE TRIGGER trg_exam_cheat_guard
  BEFORE INSERT OR UPDATE OR DELETE ON public.exam_cheat_log
  FOR EACH ROW EXECUTE FUNCTION fn_exam_cheat_guard();

COMMENT ON FUNCTION fn_exam_cheat_guard IS
  '事件守卫（157）：答卷不存在 → E_EXAM_NO_ATTEMPT；已交卷 → E_EXAM_SUBMITTED；'
  '已写入的事件不许改/删（E_EXAM_CHEAT_APPEND_ONLY），级联删随答卷放行。';

-- 某份卷的全部事件（监考可以实时看，交卷前后都能看）
CREATE OR REPLACE FUNCTION fn_exam_cheat(p_attempt bigint)
RETURNS TABLE (event_at timestamptz, kind varchar(12), detail varchar(120))
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.exam_attempt a WHERE a.id = p_attempt) THEN
    RAISE EXCEPTION 'E_EXAM_NO_ATTEMPT: 答卷 % 不存在', p_attempt;
  END IF;
  RETURN QUERY
  SELECT c.event_at, c.kind, c.detail
    FROM public.exam_cheat_log c
   WHERE c.attempt_id = p_attempt
   ORDER BY c.event_at, c.id;
END;
$$;

COMMENT ON FUNCTION fn_exam_cheat IS
  '某份答卷的切屏事件（157），按 (event_at, id) 正序 —— 同一毫秒的多条按写入顺序排。'
  '**交卷前也能查**：监考要看的是现在。';

-- 这张卷哪些人可疑
CREATE OR REPLACE FUNCTION fn_exam_flagged(p_paper bigint)
RETURNS TABLE (
  person_name varchar(64),
  attempt_id  bigint,
  events      int,
  first_at    timestamptz,
  last_at     timestamptz
)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT COALESCE(pe.full_name, '（人已删除）'),
         c.attempt_id,
         count(*)::int,
         min(c.event_at),
         max(c.event_at)
    FROM public.exam_cheat_log c
    JOIN public.exam_attempt a ON a.id = c.attempt_id
    LEFT JOIN public.person pe ON pe.id = a.employee_id
   WHERE a.paper_id = p_paper
   GROUP BY pe.full_name, c.attempt_id
   ORDER BY count(*) DESC, min(c.event_at);
$$;

COMMENT ON FUNCTION fn_exam_flagged IS
  '这张卷的可疑答卷（157）：按事件数降序。第一列是人名、第二列是答卷 —— '
  '同一个人两次考试要能分开看，所以不是按人聚合。';

