-- ============================================================================
-- 157_exam_task.sql · 考试补四个缺口：任务层（时间窗）、错题回顾、成绩聚合、切屏证据
-- ----------------------------------------------------------------------------
-- 147 做了"判分在库、答案不下发、交卷不可改"，156 补了"限时、限次"。
-- 放到真实客户那里还差四件，每一件都对应一个具体的、会被追问的场景：
--
--   ① **一张卷只能整体开考。** 连锁多门店的刚需是"批次"：A 店本周考消防、
--      B 店下周考，同一张卷、不同的时间窗。147 的试卷直接挂课程，没有中间层，
--      于是只能"全公司同时开"或者"按门店复制几张一样的卷"——
--      后者一改题就要改 N 张，且统计时要跨 N 张卷汇总。
--      产品的真实层级是「题库 → 试题 → 试卷 → **考试任务**」，缺的就是最后一层。
--
--   ② **交卷后看不见自己错哪了。** 147 刻意不下发答案（防作弊），但交卷之后
--      也不给，等于"考完不知道学什么"。这两件事必须分开：
--      **交卷前不给，是防作弊；交卷后给，是让他知道错哪了。**
--
--   ③ **店长看不到分布。** "及格率 60%" 这句话解释不了任何事 ——
--      是三个人都在 58 分（题太难），还是两个人 95、一个人 40（有人不会）。
--      分段 + 应考未考名单，才是能派活的报表。
--
--   ④ **切屏没有证据。** "考试期间切屏 3 次"是个聚合值，写死在答卷上就解释不了
--      "那 3 次分别几点、在答第几题的时候"。而争论发生时（"我只是接了个电话"），
--      能回答的只有时间点。
--
-- ★ 四条共同的取舍：**能由库判的一律在库里判。** 时间窗、错题、分段、事件守卫
--   全是函数/触发器，不是服务层的 if —— 服务层的 if 绕过一次就没有记录。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 考试任务：试卷 + 给谁 + 什么时候能考
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.exam_task (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paper_id    bigint      NOT NULL REFERENCES public.exam_paper(id),
  name        varchar(96) NOT NULL,
  -- NULL = 全公司。★ 用 NULL 表达"所有人"，不用 org_id = 集团根的组织 id：
  --   后者在组织重构（集团根换 id / 拆分公司）时会静默变成"只给某一个分支"。
  org_id      bigint      REFERENCES public.org_unit(id),
  open_at     timestamptz NOT NULL,
  close_at    timestamptz NOT NULL,
  is_required boolean     NOT NULL DEFAULT true,
  created_by  varchar(64) NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),

  -- ★ 严格大于，不是 >=：零长度窗口（open = close）在页面上是"一秒的考试"，
  --   在库里是一条永远发不出卷的任务，而它看起来是建好了的。
  CONSTRAINT ck_et_span CHECK (close_at > open_at),
  CONSTRAINT ck_et_name CHECK (length(btrim(name)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_et_paper  ON public.exam_task (paper_id, open_at);
CREATE INDEX IF NOT EXISTS ix_et_org    ON public.exam_task (org_id) WHERE org_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_et_window ON public.exam_task (open_at, close_at);

COMMENT ON TABLE public.exam_task IS
  '考试任务（157）：试卷 + 面向组织 + 时间窗，是"题库→试题→试卷→考试任务"的最后一层。'
  'org_id 为 NULL = 全公司；一张卷可以有多个任务（分批开考），互不干扰。';
COMMENT ON COLUMN public.exam_task.org_id IS
  '面向组织。NULL = 全公司。匹配用人的 attendance_org 或 cost_org 当天归属（两个维度都认）——'
  '真实客户里有的把门店挂在 cost_org、有的挂 attendance_org，只认一个会让一半门店"没有待考任务"。';
COMMENT ON COLUMN public.exam_task.is_required IS
  '是否必考。只影响清单上的排序与提示，不改变"能不能考"——'
  '把非必考的卷锁死会让"想补学的人"考不了。';

-- ---------------------------------------------------------------------------
-- 2. 开一个考试任务
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_exam_task_open(
  p_paper    bigint,
  p_name     varchar,
  p_org      bigint      DEFAULT NULL,
  p_open     timestamptz DEFAULT NULL,
  p_close    timestamptz DEFAULT NULL,
  p_required boolean     DEFAULT true,
  p_by       varchar     DEFAULT 'system'
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_name varchar(96);
  v_open timestamptz;
  v_id   bigint;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.exam_paper p WHERE p.id = p_paper) THEN
    RAISE EXCEPTION 'E_EXAM_NO_PAPER: 试卷 % 不存在，开不了考试任务', p_paper;
  END IF;

  v_name := btrim(COALESCE(p_name, ''));
  IF v_name = '' THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 任务名称必填 —— 页面上靠它分辨"A店本周"与"B店下周"两个批次';
  END IF;

  IF p_org IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.org_unit o WHERE o.id = p_org) THEN
    RAISE EXCEPTION 'E_ORG_NOT_FOUND: 组织 % 不存在（开给全公司就不传 org）', p_org;
  END IF;

  -- 不给开始时间 = 现在就开。不给关闭时间不行：没有截止的考试等于永远可以补考，
  -- 而"这批到底考完没有"就永远没有答案。
  v_open := COALESCE(p_open, now());
  IF p_close IS NULL THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 关闭时间必填（没有截止的考试等于永远能补考）';
  END IF;
  IF p_close <= v_open THEN
    RAISE EXCEPTION 'E_EXAM_TASK_WINDOW: 关闭时间 % 不晚于开始时间 %（写反了）', p_close, v_open;
  END IF;

  INSERT INTO public.exam_task(paper_id, name, org_id, open_at, close_at, is_required, created_by)
  VALUES (p_paper, v_name, p_org, v_open, p_close,
          COALESCE(p_required, true), COALESCE(NULLIF(btrim(p_by), ''), 'system'))
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_exam_task_open IS
  '开一个考试任务（157）：返回 task_id。p_open 不给 = 现在；p_close 必填。'
  '同一张卷可以开多个任务（A店本周 / B店下周），组织不同、窗口不同、互不干扰。';

-- ---------------------------------------------------------------------------
-- 3. 某人当天该考什么
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_exam_task_for(
  p_employee bigint,
  p_on       date DEFAULT NULL
) RETURNS TABLE (
  task_id     bigint,
  paper_id    bigint,
  paper_name  varchar(96),
  open_at     timestamptz,
  close_at    timestamptz,
  is_required boolean,
  done        boolean,
  score       numeric
)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE
  v_on date;
BEGIN
  IF p_employee IS NULL OR p_employee <= 0 THEN
    RAISE EXCEPTION 'E_ARG_INVALID: employee 必须是正整数（person.id）';
  END IF;
  v_on := COALESCE(p_on, public.app_today());

  RETURN QUERY
  SELECT t.id, t.paper_id, p.name, t.open_at, t.close_at, t.is_required,
         -- ★ done 的口径是"**这个窗口里**交过卷"，不是"这张卷他考过"：
         --   上一次批次的成绩不算这一批完成 —— 否则 B 店的任务一开，
         --   上个月在 A 店考过的人立刻显示"已完成"，而这一批他根本没考。
         (x.best IS NOT NULL) AS done,
         x.best               AS score
    FROM public.exam_task t
    JOIN public.exam_paper p ON p.id = t.paper_id
    -- 窗口与"那天"有没有交集：先把窗口换到业务时区取日期，再比日期。
    -- 不这么写就要在 timestamptz 上做区间判断，而"今天"是业务概念不是绝对时刻。
   CROSS JOIN LATERAL (
     SELECT max(a.score) AS best
       FROM public.exam_attempt a
      WHERE a.paper_id = t.paper_id
        AND a.employee_id = p_employee
        AND a.submitted_at >= t.open_at
        AND a.submitted_at <= t.close_at
   ) x
   WHERE (t.open_at  AT TIME ZONE public.app_tz())::date <= v_on
     AND (t.close_at AT TIME ZONE public.app_tz())::date >= v_on
     -- 当天在职：离职的人不该出现在"待考"清单里（他连门都进不来）
     AND EXISTS (SELECT 1 FROM public.employment e
                  WHERE e.person_id = p_employee
                    AND daterange(e.hire_date, e.leave_date, '[]') @> v_on)
     -- 组织匹配：全公司任务（org IS NULL）人人可见；指定组织的任务只给当天挂在那儿的人
     AND (t.org_id IS NULL OR EXISTS (
           SELECT 1 FROM public.employee_org_assignment a
            WHERE a.employee_id = p_employee
              AND a.org_id = t.org_id
              AND a.dim_code IN ('attendance_org', 'cost_org')
              AND daterange(a.valid_from, a.valid_to, '[]') @> v_on))
   ORDER BY t.is_required DESC, t.close_at, t.id;
END;
$$;

COMMENT ON FUNCTION fn_exam_task_for IS
  '某人某天该考什么（157）：按 attendance_org 或 cost_org 当天归属匹配任务，'
  '全公司任务（org 为空）人人可见。done = **这个时间窗内**已交过卷（不是及格 —— '
  '及格看 score 与该卷 pass_score）；score = 窗口内最高分（补考取最好的，不是最后一次）。';

-- ---------------------------------------------------------------------------
-- 4. 时间窗闸：不在窗口内不许开考
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_exam_task_check(
  p_paper bigint,
  p_on    timestamptz DEFAULT NULL
) RETURNS void
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE
  v_on  timestamptz;
  v_n   int;
  v_win text;
BEGIN
  v_on := COALESCE(p_on, now());

  SELECT count(*)::int INTO v_n FROM public.exam_task t WHERE t.paper_id = p_paper;
  -- ★ 这张卷**没有任何任务** → 放行。这是 147 的老行为（一张卷直接挂课程），
  --   必须留着：任务层是**可选**的批次层，加了它不等于"以后每张卷都要先建任务"。
  --   一旦这里改成"没任务就拒绝"，147 那套和现有数据会在升级当天全部停摆。
  IF v_n = 0 THEN RETURN; END IF;

  IF EXISTS (SELECT 1 FROM public.exam_task t
              WHERE t.paper_id = p_paper
                AND v_on >= t.open_at AND v_on <= t.close_at) THEN
    RETURN;
  END IF;

  -- 报错里给窗口，不然"不在时间窗内"要人去猜是哪天 —— 而考生就在电话那头。
  SELECT string_agg(w.win, '、') INTO v_win FROM (
    SELECT to_char(t.open_at  AT TIME ZONE public.app_tz(), 'MM-DD HH24:MI')
           || ' ~ '
           || to_char(t.close_at AT TIME ZONE public.app_tz(), 'MM-DD HH24:MI') AS win
      FROM public.exam_task t
     WHERE t.paper_id = p_paper
     ORDER BY t.open_at
     LIMIT 3) w;
  IF v_n > 3 THEN v_win := v_win || ' 等 ' || v_n || ' 个任务'; END IF;

  RAISE EXCEPTION
    'E_EXAM_TASK_CLOSED: 试卷 % 现在不在任何考试任务的时间窗内（现在 %，窗口 %）',
    p_paper, to_char(v_on AT TIME ZONE public.app_tz(), 'YYYY-MM-DD HH24:MI'), v_win;
END;
$$;

COMMENT ON FUNCTION fn_exam_task_check IS
  '时间窗闸（157）：不在任何任务窗口内 → E_EXAM_TASK_CLOSED。'
  '**该卷没有任何任务时放行** —— 任务层是可选的批次层，加上它不等于旧卷全部停摆。'
  '这一条已接进 exam_attempt 的 BEFORE INSERT（见第 8 节），所以 fn_exam_start '
  '与任何直接插答卷的路径都绕不过去。';

-- ---------------------------------------------------------------------------
-- 5. 错题回顾：交卷后才给，且是唯一允许下发 answer 的入口
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_exam_review(p_attempt bigint)
RETURNS TABLE (
  seq     int,
  stem    varchar(500),
  options jsonb,
  picked  varchar(32),
  answer  varchar(32),
  is_right boolean,
  score   numeric,
  got     numeric
)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE
  a record;
BEGIN
  SELECT * INTO a FROM public.exam_attempt WHERE id = p_attempt;
  IF a.id IS NULL THEN
    RAISE EXCEPTION 'E_EXAM_NO_ATTEMPT: 答卷 % 不存在', p_attempt;
  END IF;
  -- ★ 未交卷一律不给：这一屏带着 answer，交卷前让它出去等于把卷子送出去。
  --   交卷后给是**另一件事**：让他知道自己错在哪，是这场考试存在的理由之一。
  IF a.submitted_at IS NULL THEN
    RAISE EXCEPTION 'E_EXAM_NOT_SUBMITTED: 答卷 % 还没交，不能看错题（答案在交卷前不下发）', p_attempt;
  END IF;

  RETURN QUERY
  SELECT q.seq, q.stem,
         -- 判断题的选项库里不存，这里补固定的 A=对 / B=错（与 fn_exam_paper_for 同一套）
         CASE WHEN q.kind = 'judge' AND jsonb_array_length(q.options) = 0
              THEN '[{"k":"A","t":"对"},{"k":"B","t":"错"}]'::jsonb
              ELSE q.options END,
         ans.picked,
         q.answer,
         (ans.picked IS NOT NULL AND ans.picked = q.answer) AS is_right,
         q.score            AS score,   -- 本题满分
         COALESCE(ans.score, 0) AS got   -- 本题实得（没答 = 0）
    FROM public.exam_question q
    LEFT JOIN public.exam_answer ans
      ON ans.question_id = q.id AND ans.attempt_id = p_attempt
   WHERE q.paper_id = a.paper_id
   ORDER BY q.seq;
END;
$$;

COMMENT ON FUNCTION fn_exam_review IS
  '错题回顾（157）：只对**已交卷**的答卷开放，未交卷 → E_EXAM_NOT_SUBMITTED。'
  '这是除 fn_exam_submit 之外**唯一**把 exam_question.answer 发出去的地方 —— '
  '两个时刻是两件事：交卷前不给是防作弊，交卷后给是让他知道错哪了。'
  'score = 本题满分，got = 本题实得。';

-- ---------------------------------------------------------------------------
-- 6. 成绩聚合：分段分布 + 及格率（分母是已交卷人数）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_exam_stat(
  p_paper bigint,
  p_org   bigint DEFAULT NULL
) RETURNS TABLE (
  bucket       varchar,
  person_count int,
  avg_score    numeric,
  pass_count   int,
  pass_rate    numeric
)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
DECLARE
  v_pass numeric(6,2);
BEGIN
  SELECT p.pass_score INTO v_pass FROM public.exam_paper p WHERE p.id = p_paper;
  IF v_pass IS NULL THEN
    RAISE EXCEPTION 'E_EXAM_NO_PAPER: 试卷 % 不存在', p_paper;
  END IF;
  IF p_org IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.org_unit o WHERE o.id = p_org) THEN
    RAISE EXCEPTION 'E_ORG_NOT_FOUND: 组织 % 不存在', p_org;
  END IF;

  RETURN QUERY
  WITH best AS (
    -- ★ 一人一行，取**最高分**：补考过了就是过了，"最后一次"会让过了的人因为
    --   后来又考了一次低分而变回"没通过"，那不是真实情况。
    SELECT a.employee_id, max(a.score) AS score
      FROM public.exam_attempt a
     WHERE a.paper_id = p_paper AND a.submitted_at IS NOT NULL
     GROUP BY a.employee_id
  ),
  pop AS (
    SELECT b.employee_id, b.score, (b.score >= v_pass) AS passed
      FROM best b
     WHERE p_org IS NULL OR EXISTS (
             SELECT 1
               FROM public.employee_org_assignment a
               JOIN public.org_unit o ON o.id = a.org_id
               JOIN public.org_unit s ON s.id = p_org
              WHERE a.employee_id = b.employee_id
                AND a.dim_code IN ('attendance_org', 'cost_org')
                AND daterange(a.valid_from, a.valid_to, '[]') @> public.app_today()
                AND o.path LIKE s.path || '%')
  ),
  -- 六个桶全部列出来（含 0 人的）：报表要的是固定的六行，
  -- 少一行等于让页面去猜"这段没人"还是"这段没查"。
  band AS (
    SELECT * FROM (VALUES (0, 'all'::varchar, NULL::numeric, NULL::numeric),
                          (1, '90-100', 90::numeric,   NULL::numeric),
                          (2, '80-89',  80::numeric,   90::numeric),
                          (3, '70-79',  70::numeric,   80::numeric),
                          (4, '60-69',  60::numeric,   70::numeric),
                          (5, '<60',    NULL::numeric, 60::numeric))
                  v(o, bucket, lo, hi)
  )
  SELECT bd.bucket,
         count(pop.employee_id)::int,
         round(avg(pop.score), 2),
         count(pop.employee_id) FILTER (WHERE pop.passed)::int,
         -- ★ 分母是**已交卷人数**，不是应考人数：把没交的算进分母，
         --   及格率就变成"考勤率"，而那是 fn_exam_missing 的活。
         CASE WHEN count(pop.employee_id) = 0 THEN NULL
              ELSE round((count(pop.employee_id) FILTER (WHERE pop.passed))::numeric
                         / count(pop.employee_id), 4) END
    FROM band bd
    LEFT JOIN pop
      ON (bd.lo IS NULL OR pop.score >= bd.lo)
     AND (bd.hi IS NULL OR pop.score <  bd.hi)
   GROUP BY bd.o, bd.bucket
   ORDER BY bd.o;
END;
$$;

COMMENT ON FUNCTION fn_exam_stat IS
  '成绩分布（157）：6 行 = all + 90-100 / 80-89 / 70-79 / 60-69 / <60（0 人的段也返回）。'
  '一人一行取最高分；pass_rate 的分母是**已交卷人数**，不是应考人数。'
  '分段按**原始分**（与 pass_score 同一刻度、与考生看到的那个分一致）；'
  '卷面总分不是 100 时分段会整体偏移 —— 不做归一化是刻意的：'
  '归一化之后"85 分"与及格线就对不上，店长会问"到底按哪个数"。'
  'p_org 给了就只算**今天**挂在它（含子树）上的人。';

-- ---------------------------------------------------------------------------
-- 7. 该考没考的人
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_exam_missing(
  p_paper bigint,
  p_org   bigint DEFAULT NULL
) RETURNS TABLE (
  person_id   bigint,
  person_name varchar(64),
  employee_no varchar(32),
  attempts    int
)
LANGUAGE plpgsql STABLE
SET search_path = ''
AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.exam_paper p WHERE p.id = p_paper) THEN
    RAISE EXCEPTION 'E_EXAM_NO_PAPER: 试卷 % 不存在', p_paper;
  END IF;
  IF p_org IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.org_unit o WHERE o.id = p_org) THEN
    RAISE EXCEPTION 'E_ORG_NOT_FOUND: 组织 % 不存在', p_org;
  END IF;

  RETURN QUERY
  WITH emp AS (
    SELECT e.person_id
      FROM public.employment e
     WHERE daterange(e.hire_date, e.leave_date, '[]') @> public.app_today()
  ),
  -- 应考 = 已开考的任务 × 落在该任务组织里的人（全公司任务 = 全部在职）
  sched AS (
    SELECT t.id AS task_id, t.open_at, t.close_at, emp.person_id
      FROM public.exam_task t
      JOIN emp ON (t.org_id IS NULL OR EXISTS (
             SELECT 1 FROM public.employee_org_assignment a
              WHERE a.employee_id = emp.person_id
                AND a.org_id = t.org_id
                AND a.dim_code IN ('attendance_org', 'cost_org')
                AND daterange(a.valid_from, a.valid_to, '[]') @> public.app_today()))
     WHERE t.paper_id = p_paper
       -- ★ 只算**已经开考**的任务：下周才开的那批不该出现在今天的催考清单里，
       --   否则一张为下个月建的任务会把全公司今天就列成"缺考"。
       AND t.open_at <= now()
  ),
  todo AS (
    SELECT s.person_id
      FROM sched s
     WHERE NOT EXISTS (
             SELECT 1 FROM public.exam_attempt a
              WHERE a.paper_id = p_paper
                AND a.employee_id = s.person_id
                AND a.submitted_at >= s.open_at
                AND a.submitted_at <= s.close_at)
     GROUP BY s.person_id
  )
  SELECT td.person_id, pe.full_name,
         (SELECT n.no FROM public.employee_no n
           WHERE n.assigned_person_id = td.person_id AND n.retired_at IS NULL
           ORDER BY n.assigned_at DESC LIMIT 1),
         -- 历史交卷次数：>0 说明"他考过别的批次"，与"从来没考"要能分开看
         (SELECT count(*)::int FROM public.exam_attempt a
           WHERE a.paper_id = p_paper AND a.employee_id = td.person_id
             AND a.submitted_at IS NOT NULL)
    FROM todo td
    JOIN public.person pe ON pe.id = td.person_id
   WHERE p_org IS NULL OR EXISTS (
           SELECT 1
             FROM public.employee_org_assignment a
             JOIN public.org_unit o ON o.id = a.org_id
             JOIN public.org_unit s ON s.id = p_org
            WHERE a.employee_id = td.person_id
              AND a.dim_code IN ('attendance_org', 'cost_org')
              AND daterange(a.valid_from, a.valid_to, '[]') @> public.app_today()
              AND o.path LIKE s.path || '%')
   ORDER BY pe.full_name;
END;
$$;

COMMENT ON FUNCTION fn_exam_missing IS
