-- ============================================================================
-- 154_roster_swap.sql · 换班：员工填单 → 对方确认 → 主管审批 → 自动改排班
-- ----------------------------------------------------------------------------
-- 产品原话（介绍 p21）：
--
--   「员工填写审批单，**多维度、按天、按班次调整**，表单审批通过会**自动更新
--     排班表班次**，排班报表中可随时查看员工**换班记录**，可查可控」
--
-- 机场外包案例里还有一句关键的：「换班套件可以实现**一天两个班次，
-- 且交换半天的班次**」—— 所以段（segment）粒度是必需的，不是"以后再说"。
--
-- ★ 四种类型，一种都不能少（形态的不同决定了"谁确认、谁改哪一段"）：
--
--   self     调换自己的班次       —— 只改自己的段（改 shift），不需要对方确认
--   swap     和别人调换班次       —— 两边的段**互换归属**（连日期一起换）
--   cover    我替别人上班         —— 把对方那天的段挪到我名下
--   covered  别人替我上班         —— 把我那天的段挪到对方名下
--
--   cover / covered 看起来是同一个动作的两个方向，**但它们不是同一个类型**：
--   "我替别人"与"别人替我"在报表上是两条不同的事实（谁欠谁的班），
--   合并之后换班记录就答不出"这个人这个月替了几次、被替了几次"。
--
-- ★ 这一轮钉住的四件事，每一件都写在这里是因为它们都有代价：
--
--   ① **归属只存在一处**：`schedule_segment` 没有 employee_id，
--      归属是 `schedule.employee_id`。所以"把这一段给另一个人"在物理上只能是
--      「删掉这一段 + 在目标人名下新建一段同时段的」—— 不是 UPDATE 一个字段。
--      这也是半天换班唯一的做法：**只删被指名的那一段，另一段动都不动**。
--      代价是段 id 会变、确认单要重建（not_started）—— 那是对的：
--      换过人之后，门店之前确认的那张字签的不是这个人。
--
--   ② **重叠要在 create 就算一遍**，不能等审批通过才炸。
--      通过那一刻已经有人点了"同意"，此时再报"重叠"，那张单要么被强改、
--      要么挂在那里谁也关不掉。所以 create 用同一个函数把"换完之后的时段"
--      算一遍：与自己（或对方）原有的段相交 → E_SWAP_OVERLAP，直接退回改单。
--      审批通过前**再算一遍**（从填单到审批之间排班可能被动过）。
--
--   ③ **对方确认不能省**（self 除外）。没有这一步，"我替别人上班"可以由
--      发起人一个人点完 —— 而当事人从没答应过。状态机：
--        draft → agreed（对方确认）→ approved（主管审批）→ 自动落库
--      self 只有 draft → approved。未确认就审批 = E_SWAP_NOT_AGREED。
--
--   ④ **定案之后冻结**。approved / rejected 之后不许 UPDATE、不许 DELETE
--      （E_SWAP_APPLIED）。换班记录是"可查可控"的那个"控"：
--      一张能随手改回来的审批单，事后无法回答"当时到底换没换"。
--
-- ★ 三条与既有模块的接缝（不重复造，也不绕开）：
--   · **锁定 / 门店已确认的段不许换**（E_ROSTER_LOCKED，145 的规矩）：
--     锁定是门店签过的字，换班也是一种改。要换先退回。
--   · **roster_slot 要同步**（145/148 的镜像）：它还在算薪链路上
--     （应出勤、休息日加班、排班天数）。只改 schedule 不改它，
--     会出现"排班表上换过人、算薪还按原来那个人算"——而页面看起来一切正常。
--   · **建段即建确认单**（008：段有行 = 该有确认单，缺单是缺陷不是状态）。
--
-- ★ 一件不做：**不做"超时自动确认"**。本仓没有调度器，写成"打开页面时顺带算
--   一下"就变成"谁登录谁触发"——145 已经在同一处做过同样的取舍。
--
-- ★ 一处偏离原设计并说明理由：`decide` 的 p_note（审批意见）需要落库，
--   而表字段清单里没有它的位置。加 `decide_note` 一列，不塞进 reason：
--   reason 是**员工填的换班原因**，审批意见是**主管写的判断**，
--   两者混在一列之后，"为什么换"与"为什么批"再也分不开。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 表
-- ---------------------------------------------------------------------------
-- ★ 主键给生成方式（本仓第 12 次同一个坑）：这张表**每一行都由函数 INSERT**，
--   写 `id bigint PRIMARY KEY` 的第一条就 23502，而报错指向 id，看起来像数据缺失。
CREATE TABLE roster_swap (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind         varchar(8)  NOT NULL,
  -- 发起人（员工本人）
  from_person  bigint      NOT NULL REFERENCES person(id),
  -- 对方。**self 时为空** —— "调自己的班"没有对方这个人，
  -- 填成自己会在报表里多出一条"自己和自己换班"。
  to_person    bigint      REFERENCES person(id),
  from_date    date        NOT NULL,
  -- 段：写该段的**开始时刻** HH:MM。段在库里没有名字（只有 seq，而 seq 在
  -- 同一天多段时是从 1 重来的），开始时刻是它唯一稳定、人也能核对的身份。
  -- NULL = 整天（那天所有段一起动）。
  from_seg     varchar(5),
  to_date      date        NOT NULL,
  to_seg       varchar(5),
  -- 班次码（记录当时换的是哪两个班）。划线排班没有班次身份，可以为空。
  from_shift   varchar(16) REFERENCES shift_def(code),
  to_shift     varchar(16) REFERENCES shift_def(code),
  reason       varchar(200) NOT NULL,
  status       varchar(12) NOT NULL DEFAULT 'draft',
  -- 定案（通过 / 驳回）时的审批意见
  decide_note  varchar(500),
  agreed_at    timestamptz,
  approved_by  varchar(64),
  approved_at  timestamptz,
  applied_at   timestamptz,
  created_by   varchar(64) NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT ck_sw_kind CHECK (kind IN ('self','swap','cover','covered')),
  CONSTRAINT ck_sw_status CHECK (status IN ('draft','agreed','approved','rejected','cancelled')),
  -- ★ 状态与落库时间必须同时说真话：approved 却没有 applied_at，
  --   事后无法证明"排班真的改过"；反过来有 applied_at 却不是 approved，
  --   说明有一次改排班没有被任何状态承认。
  CONSTRAINT ck_sw_applied CHECK ((status = 'approved') = (applied_at IS NOT NULL)),
  -- self：没有对方；非 self：必须有对方且不能是自己
  CONSTRAINT ck_sw_party CHECK (
       (kind = 'self'  AND to_person IS NULL AND to_date = from_date AND to_seg IS NULL)
    OR (kind <> 'self' AND to_person IS NOT NULL AND to_person <> from_person)
  ),
  CONSTRAINT ck_sw_self_no_agree CHECK (kind <> 'self' OR agreed_at IS NULL),
  CONSTRAINT ck_sw_from_seg CHECK (from_seg IS NULL OR from_seg ~ '^([01]\d|2[0-3]):[0-5]\d$'),
  CONSTRAINT ck_sw_to_seg   CHECK (to_seg   IS NULL OR to_seg   ~ '^([01]\d|2[0-3]):[0-5]\d$'),
  -- 原因至少 4 字：审批的人要知道"为什么换"，不是只看到一个"换"
  CONSTRAINT ck_sw_reason CHECK (length(btrim(reason)) >= 4)
);

COMMENT ON TABLE roster_swap IS
  '换班单（154）：self 调自己 / swap 互调 / cover 我替别人 / covered 别人替我。'
  '审批通过（applied_at 非空）意味着排班已经改过 —— 归属在 schedule.employee_id，'
  '所以"换归属"是删段 + 在目标人名下重建段，不是改一个字段。';

COMMENT ON COLUMN roster_swap.from_seg IS
  '要被换走的那一段，写段开始时刻 HH:MM；NULL = 整天（那天所有段）。'
  '段没有名字也没有稳定 seq（同日多段时 seq 从 1 重来），开始时刻是它唯一的身份。';

COMMENT ON COLUMN roster_swap.decide_note IS
  '审批意见（154）。与 reason 分开：reason 是员工写的"为什么换"，'
  '这一列是主管写的"为什么批 / 为什么不批"。混成一列之后两者再也分不开。';

CREATE INDEX ix_sw_from ON roster_swap (from_person, from_date);
CREATE INDEX ix_sw_to   ON roster_swap (to_person, to_date);
CREATE INDEX ix_sw_status ON roster_swap (status);

-- ---------------------------------------------------------------------------
-- 2. 取"某人某天要动的那几段"
-- ---------------------------------------------------------------------------
-- p_seg 为 NULL = 整天（那天全部段）。否则按段的开始时刻精确匹配。
-- 返回多行是刻意的：整天换班时一天可能有两段（"一天两个班次"），
-- 只取一段就会漏掉另一半，而漏掉的那一半**不会报错**。
CREATE OR REPLACE FUNCTION fn_swap_segs(
  p_person bigint,
  p_date   date,
  p_seg    varchar
) RETURNS TABLE (segment_id bigint, schedule_id bigint, store_id bigint,
                 shift_id bigint, seq int, start_at timestamptz, end_at timestamptz)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT g.id, s.id, g.store_id, s.shift_id, g.seq, g.start_at, g.end_at
    FROM public.schedule s
    JOIN public.schedule_segment g ON g.schedule_id = s.id
   WHERE s.employee_id = p_person
     AND s.work_date = p_date
     AND (p_seg IS NULL
          OR to_char(g.start_at AT TIME ZONE public.app_tz(), 'HH24:MI') = btrim(p_seg))
   ORDER BY g.start_at, g.seq;
$$;

COMMENT ON FUNCTION fn_swap_segs IS
  '某人某天的段（154）；p_seg=NULL 取全部，否则按开始时刻 HH:MM 精确匹配。'
  '整天换班必须返回多行 —— 一天两个班次时只取一段，漏掉的那段不会报错。';

-- ---------------------------------------------------------------------------
-- 3. 换完之后会不会撞上已有时段
-- ---------------------------------------------------------------------------
-- 只看 p_person 在 p_date 前后一天内的段（跨零点的段落在邻日，只看当天会漏），
-- 并把"正被换走的那些段"排除掉 —— 它们马上就不属于这个人了。
CREATE OR REPLACE FUNCTION fn_swap_overlap(
  p_person bigint,
  p_date   date,
  p_start  timestamptz,
  p_end    timestamptz,
  p_skip   bigint[]
) RETURNS TABLE (segment_id bigint, work_date date, start_at timestamptz, end_at timestamptz)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT g.id, s.work_date, g.start_at, g.end_at
    FROM public.schedule s
    JOIN public.schedule_segment g ON g.schedule_id = s.id
   WHERE s.employee_id = p_person
     AND s.work_date BETWEEN p_date - 1 AND p_date + 1
     AND NOT (g.id = ANY (COALESCE(p_skip, ARRAY[]::bigint[])))
     AND tstzrange(g.start_at, g.end_at, '[)') && tstzrange(p_start, p_end, '[)')
   ORDER BY g.start_at
   LIMIT 1;
$$;

COMMENT ON FUNCTION fn_swap_overlap IS
  '换班前的重叠试算（154）：这个人换上 %-% 之后会不会与自己已有的段相交。'
  'p_skip 是被换走的段 id（它们不算冲突）。区间相交，不加 EXCLUDE 约束 —— '
  '存量数据未必过得了约束，而约束会在升级当天把库拦住。';

-- 报错里的人看得懂的时刻（业务时区、月-日 时:分）。直接用 timestamptz 打印
-- 会得到 `2026-11-26 03:00:00+00`（UTC）—— 排班的人对着它算不出是几点。
CREATE OR REPLACE FUNCTION fn_swap_hm(p_at timestamptz) RETURNS text
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT to_char(p_at AT TIME ZONE public.app_tz(), 'MM-DD HH24:MI');
$$;

-- ---------------------------------------------------------------------------
-- 4. 把一个段放到某人名下（新建 schedule 行 / 复用同日同班次的行）
-- ---------------------------------------------------------------------------
-- ★ 段表没有 employee_id，所以"换人"必须走这一条：目标人当天的 schedule 行
--   要么已存在（同班次）就复用，要么新建一行，段挂上去。
-- ★ seq 取该 schedule 行现有最大 seq + 1：同一行可以挂多段（148 的划线）。
CREATE OR REPLACE FUNCTION fn_swap_place_seg(
  p_person bigint,
  p_date   date,
  p_shift  bigint,
  p_store  bigint,
  p_start  timestamptz,
  p_end    timestamptz
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_sid bigint;
  v_seq int;
  v_seg bigint;
BEGIN
  IF p_shift IS NOT NULL THEN
    SELECT s.id INTO v_sid
      FROM public.schedule s
     WHERE s.employee_id = p_person AND s.work_date = p_date AND s.shift_id = p_shift
     LIMIT 1;
  END IF;

  IF v_sid IS NULL THEN
    INSERT INTO public.schedule(employee_id, work_date, shift_id, store_id)
    VALUES (p_person, p_date, p_shift, p_store)
    RETURNING id INTO v_sid;
  END IF;

  SELECT COALESCE(max(g.seq), 0) + 1 INTO v_seq
    FROM public.schedule_segment g WHERE g.schedule_id = v_sid;

  INSERT INTO public.schedule_segment(schedule_id, seq, store_id, start_at, end_at)
  VALUES (v_sid, v_seq, p_store, p_start, p_end)
  RETURNING id INTO v_seg;

  -- ★ 建段即建确认单（008：段有行 = 该有确认单，缺单是缺陷不是状态）。
  --   not_started 是对的：换了人，门店之前确认的那张字签的不是这个人。
  INSERT INTO public.confirm_sheet(segment_id, status) VALUES (v_seg, 'not_started');

  RETURN v_seg;
END;
$$;

COMMENT ON FUNCTION fn_swap_place_seg IS
  '把一段挂到某人名下（154）：同班次的 schedule 行存在就复用，否则新建。'
  '同时建确认单（not_started）—— 008 说段有行 = 该有确认单，缺单是缺陷。';

-- ---------------------------------------------------------------------------
-- 5. 同步 roster_slot（算薪链路上的镜像）
-- ---------------------------------------------------------------------------
-- ★ 145/148 都双写 roster_slot，四个读者靠它（应出勤 / 休息日加班 / 排班天数）。
--   换班只改 schedule 不改它 → "排班表上换过人、算薪还按原来那个人算"，
--   而页面看起来一切正常，错的是钱。
-- ★ 清空壳 schedule 行：只清"没有段、也不是排休"的行。排休行本来就没有段
--   （145：休息只建 schedule 不建段），按"没段就删"会把休息日一起删掉。
CREATE OR REPLACE FUNCTION fn_swap_slot_sync(
  p_person bigint,
  p_date   date,
  p_by     varchar
) RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_store bigint;
  v_code  varchar;
BEGIN
  DELETE FROM public.schedule s
   WHERE s.employee_id = p_person AND s.work_date = p_date
     AND NOT EXISTS (SELECT 1 FROM public.schedule_segment g WHERE g.schedule_id = s.id)
     AND NOT EXISTS (SELECT 1 FROM public.shift_def sd
                      WHERE sd.shift_id = s.shift_id AND sd.is_rest);

  -- 当天还有段 → 班次取最早那段所属的 schedule；只剩排休 → 取排休班次码
  SELECT s.store_id, COALESCE(sd.code, 'REST') INTO v_store, v_code
    FROM public.schedule s
    JOIN public.schedule_segment g ON g.schedule_id = s.id
    LEFT JOIN public.shift_def sd ON sd.shift_id = s.shift_id
   WHERE s.employee_id = p_person AND s.work_date = p_date
   ORDER BY g.start_at, g.seq
   LIMIT 1;

  IF NOT FOUND THEN
    SELECT s.store_id, sd.code INTO v_store, v_code
      FROM public.schedule s
      LEFT JOIN public.shift_def sd ON sd.shift_id = s.shift_id
     WHERE s.employee_id = p_person AND s.work_date = p_date
     LIMIT 1;
    IF NOT FOUND THEN
      -- 这一天这个人彻底没班了（替别人上、被别人替、段换走了）
      DELETE FROM public.roster_slot r
       WHERE r.employee_id = p_person AND r.work_date = p_date;
      RETURN;
    END IF;
  END IF;

  INSERT INTO public.roster_slot(employee_id, store_id, work_date, shift_code, updated_by)
  VALUES (p_person, v_store, p_date, v_code, btrim(COALESCE(p_by, 'system')))
  ON CONFLICT (employee_id, work_date) DO UPDATE
    SET store_id = EXCLUDED.store_id,
        shift_code = EXCLUDED.shift_code,
        updated_by = EXCLUDED.updated_by,
        updated_at = now();
END;
$$;

COMMENT ON FUNCTION fn_swap_slot_sync IS
  '换班后同步 roster_slot（154）：清空壳 schedule 行（排休行保留）、重写当天班次，'
  '当天彻底没班则删掉那一格。它还在算薪链路上，漏同步会静默算错钱。';

-- ---------------------------------------------------------------------------
-- 6. 试算：这张单批下来会动哪几段、会不会撞
-- ---------------------------------------------------------------------------
-- 一个函数同时被 create 和 decide 调用，**只此一份判断**：
-- 填单时算一遍（重叠当场退回改单），审批通过前再算一遍（期间排班可能被动过）。
-- 返回描述符数组：{seg 源段, src_person/src_date 源, person/date 目标,
--                  shift/store/start/end 新段的形状}
CREATE OR REPLACE FUNCTION fn_swap_descriptors(
  p_kind        varchar,
  p_from_person bigint,
  p_to_person   bigint,
  p_from_date   date,
  p_from_seg    varchar,
  p_to_date     date,
  p_to_seg      varchar,
  p_to_shift    varchar
) RETURNS jsonb
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_arr        jsonb := '[]'::jsonb;
  v_part       jsonb;
  v_seg        record;
  v_hit        record;
  v_sd         record;
  v_n          int;
  v_skip_a     bigint[];
  v_skip_b     bigint[];
  v_cur        varchar;
  v_start      timestamptz;
  v_end        timestamptz;
  v_shift_id   bigint;
BEGIN
  -- ---- ① 源侧的段：self / swap / covered 动发起人这边的 ----------
  IF p_kind IN ('self','swap','covered') THEN
    v_skip_a := ARRAY(SELECT f.segment_id
                        FROM public.fn_swap_segs(p_from_person, p_from_date, p_from_seg) f);
    v_n := COALESCE(array_length(v_skip_a, 1), 0);
    IF v_n = 0 THEN
      RAISE EXCEPTION 'E_SWAP_NO_SEG: % 在 % 没有可换的段（from_seg=%，该段不在那天的排班里）',
        p_from_person, p_from_date, COALESCE(p_from_seg, '整天');
    END IF;
    -- ★ 一天两段时"整天"说不清要换哪一段：让人指明，不替他猜。
    --   猜错的后果是把另一半班也换走了，而单子上看不出来。
    IF p_kind = 'self' AND p_from_seg IS NULL AND v_n > 1 THEN
      RAISE EXCEPTION 'E_SWAP_NO_SEG: % 在 % 有 % 段，请指明换哪一段（from_seg 写该段开始时刻 HH:MM）',
        p_from_person, p_from_date, v_n;
    END IF;
    IF EXISTS (SELECT 1 FROM public.confirm_sheet cs
                WHERE cs.segment_id = ANY(v_skip_a)
                  AND cs.status IN ('locked','store_confirmed')) THEN
      RAISE EXCEPTION 'E_ROSTER_LOCKED: % 在 % 要换的段门店已确认或已锁定（那是门店签过的字，先退回）',
        p_from_person, p_from_date;
    END IF;
  END IF;

  -- ---- ② 对方侧的段：swap / cover 动对方那边的 ----------------
  IF p_kind IN ('swap','cover') THEN
    v_skip_b := ARRAY(SELECT f.segment_id
                        FROM public.fn_swap_segs(p_to_person, p_to_date, p_to_seg) f);
    v_n := COALESCE(array_length(v_skip_b, 1), 0);
    IF v_n = 0 THEN
      RAISE EXCEPTION 'E_SWAP_NO_SEG: 对方 % 在 % 没有可换的段（to_seg=%，该段不在那天的排班里）',
        p_to_person, p_to_date, COALESCE(p_to_seg, '整天');
    END IF;
    IF EXISTS (SELECT 1 FROM public.confirm_sheet cs
                WHERE cs.segment_id = ANY(v_skip_b)
                  AND cs.status IN ('locked','store_confirmed')) THEN
      RAISE EXCEPTION 'E_ROSTER_LOCKED: 对方 % 在 % 要换的段门店已确认或已锁定（先退回）',
        p_to_person, p_to_date;
    END IF;
  END IF;

  -- ---- ③ self 换班次：新时段算出来，与当天其它段试算 ----------
  IF p_kind = 'self' THEN
    IF p_to_shift IS NULL OR btrim(p_to_shift) = '' THEN
      RAISE EXCEPTION 'E_SWAP_NO_SHIFT: 调换自己的班次要说换成哪个班（to_shift）';
    END IF;
    SELECT * INTO v_sd FROM public.shift_def WHERE code = btrim(p_to_shift);
    IF NOT FOUND THEN
      RAISE EXCEPTION 'E_SWAP_NO_SHIFT: 班次 % 不存在（见 shift_def）', p_to_shift;
    END IF;
    IF v_sd.is_rest THEN
      RAISE EXCEPTION 'E_SWAP_NO_SHIFT: % 是休息班 —— 换休请走请假，不要用换班（换班只换上班的时段）',
        p_to_shift;
    END IF;

    SELECT sd.code INTO v_cur
      FROM public.fn_swap_segs(p_from_person, p_from_date, p_from_seg) f
      JOIN public.schedule s ON s.id = f.schedule_id
      LEFT JOIN public.shift_def sd ON sd.shift_id = s.shift_id
     ORDER BY f.start_at
     LIMIT 1;
    IF v_cur IS NOT DISTINCT FROM btrim(p_to_shift) THEN
      RAISE EXCEPTION 'E_SWAP_NO_SHIFT: % 在 % 已经是 % 了（换成同一个班不是换班）',
        p_from_person, p_from_date, p_to_shift;
    END IF;

    IF v_sd.shift_id IS NULL THEN
      RAISE EXCEPTION 'E_SWAP_NO_SHIFT: 班次 % 没有 shift_id（重跑 145 迁移）', p_to_shift;
    END IF;
    v_shift_id := v_sd.shift_id;

    v_start := (p_from_date + v_sd.start_time) AT TIME ZONE public.app_tz();
    v_end   := (p_from_date + v_sd.end_time)   AT TIME ZONE public.app_tz();
    IF v_end <= v_start THEN
      v_end := v_end + interval '1 day';        -- 跨零点（闭店、夜班）
    END IF;

    SELECT * INTO v_hit
      FROM public.fn_swap_overlap(p_from_person, p_from_date, v_start, v_end, v_skip_a);
    IF FOUND THEN
      RAISE EXCEPTION 'E_SWAP_OVERLAP: 换成 % 之后（% ~ %）与 % 在 % 已有的段（% ~ %，段 %）重叠'
        '—— 同一时段两段 = 两倍工时，请在填单时就改掉',
        p_to_shift, public.fn_swap_hm(v_start), public.fn_swap_hm(v_end),
        p_from_person, v_hit.work_date,
        public.fn_swap_hm(v_hit.start_at), public.fn_swap_hm(v_hit.end_at), v_hit.segment_id;
    END IF;

    SELECT COALESCE(jsonb_agg(jsonb_build_object(
             'seg', f.segment_id,
             'src_person', p_from_person, 'src_date', p_from_date,
             'person', p_from_person,     'date', p_from_date,
             'shift', v_shift_id, 'store', f.store_id,
             'start', v_start, 'end', v_end)), '[]'::jsonb)
      INTO v_arr
      FROM public.fn_swap_segs(p_from_person, p_from_date, p_from_seg) f;
    RETURN v_arr;
  END IF;

  -- ---- ④ 互换 / 代班：接收方不能被排成两段 --------------------
  -- swap：两边互相接收（各自留在**对方那一天**上，日期随班走）
  -- cover：发起人接收对方那天的段
  -- covered：对方接收发起人那天的段
  IF p_kind IN ('swap','cover') THEN
    FOR v_seg IN SELECT * FROM public.fn_swap_segs(p_to_person, p_to_date, p_to_seg) LOOP
      SELECT * INTO v_hit
        FROM public.fn_swap_overlap(p_from_person, p_to_date, v_seg.start_at, v_seg.end_at, v_skip_a);
      IF FOUND THEN
        RAISE EXCEPTION 'E_SWAP_OVERLAP: 换完之后 % 在 % 会同时有两段：换进来的 % ~ %（段 %）'
          '与已有的 % ~ %（段 %）—— 同一时段两段 = 两倍工时，请在填单时就改掉',
          p_from_person, p_to_date, public.fn_swap_hm(v_seg.start_at),
          public.fn_swap_hm(v_seg.end_at), v_seg.segment_id,
          public.fn_swap_hm(v_hit.start_at), public.fn_swap_hm(v_hit.end_at), v_hit.segment_id;
      END IF;
    END LOOP;
  END IF;

  IF p_kind = 'swap' THEN
    FOR v_seg IN SELECT * FROM public.fn_swap_segs(p_from_person, p_from_date, p_from_seg) LOOP
      SELECT * INTO v_hit
        FROM public.fn_swap_overlap(p_to_person, p_from_date, v_seg.start_at, v_seg.end_at, v_skip_b);
      IF FOUND THEN
        RAISE EXCEPTION 'E_SWAP_OVERLAP: 换完之后 % 在 % 会同时有两段：换进来的 % ~ %（段 %）'
          '与已有的 % ~ %（段 %）—— 同一时段两段 = 两倍工时，请在填单时就改掉',
          p_to_person, p_from_date, public.fn_swap_hm(v_seg.start_at),
          public.fn_swap_hm(v_seg.end_at), v_seg.segment_id,
          public.fn_swap_hm(v_hit.start_at), public.fn_swap_hm(v_hit.end_at), v_hit.segment_id;
      END IF;
    END LOOP;
  END IF;

  IF p_kind = 'covered' THEN
    FOR v_seg IN SELECT * FROM public.fn_swap_segs(p_from_person, p_from_date, p_from_seg) LOOP
      SELECT * INTO v_hit
        FROM public.fn_swap_overlap(p_to_person, p_from_date, v_seg.start_at, v_seg.end_at, v_skip_b);
      IF FOUND THEN
        RAISE EXCEPTION 'E_SWAP_OVERLAP: 换完之后 % 在 % 会同时有两段：换进来的 % ~ %（段 %）'
          '与已有的 % ~ %（段 %）—— 同一时段两段 = 两倍工时，请在填单时就改掉',
          p_to_person, p_from_date, public.fn_swap_hm(v_seg.start_at),
          public.fn_swap_hm(v_seg.end_at), v_seg.segment_id,
          public.fn_swap_hm(v_hit.start_at), public.fn_swap_hm(v_hit.end_at), v_hit.segment_id;
      END IF;
    END LOOP;
  END IF;

  -- ---- ⑤ 描述符：源侧的段 -> 目标人 -----------------------------
  IF p_kind IN ('swap','covered') THEN
    SELECT COALESCE(jsonb_agg(jsonb_build_object(
             'seg', f.segment_id,
             'src_person', p_from_person, 'src_date', p_from_date,
             'person', p_to_person, 'date', p_from_date,
             'shift', s.shift_id, 'store', f.store_id,
             'start', f.start_at, 'end', f.end_at)), '[]'::jsonb)
      INTO v_part
      FROM public.fn_swap_segs(p_from_person, p_from_date, p_from_seg) f
      JOIN public.schedule s ON s.id = f.schedule_id;
    v_arr := v_arr || v_part;
  END IF;

  -- ---- ⑥ 描述符：对方侧的段 -> 发起人 ---------------------------
  IF p_kind IN ('swap','cover') THEN
    SELECT COALESCE(jsonb_agg(jsonb_build_object(
             'seg', f.segment_id,
             'src_person', p_to_person, 'src_date', p_to_date,
             'person', p_from_person, 'date', p_to_date,
             'shift', s.shift_id, 'store', f.store_id,
             'start', f.start_at, 'end', f.end_at)), '[]'::jsonb)
      INTO v_part
      FROM public.fn_swap_segs(p_to_person, p_to_date, p_to_seg) f
      JOIN public.schedule s ON s.id = f.schedule_id;
    v_arr := v_arr || v_part;
  END IF;

  RETURN v_arr;
END;
$$;

COMMENT ON FUNCTION fn_swap_descriptors IS
  '换班试算（154）：算出这张单批下来会动哪几段，并在这里把重叠、段不存在、'
  '锁定、班次不存在全部拒掉（E_SWAP_NO_SEG / E_SWAP_OVERLAP / E_ROSTER_LOCKED / '
  'E_SWAP_NO_SHIFT）。create 与 decide 调的是同一份判断，不写第二遍。';

-- ---------------------------------------------------------------------------
-- 7. 落库：删源段 → 在目标人名下重建 → 同步 roster_slot
-- ---------------------------------------------------------------------------
-- ★ 必须"先全删再全插"。边删边插在同日互换时会出问题：A 收下 B 的段那一刻，
--   B 的段还在，而段表没有 employee_id —— 归属只由 schedule 决定，
--   一旦两行 schedule 同时挂着同一个时段的段，就分不清谁是谁的了。
CREATE OR REPLACE FUNCTION fn_swap_apply(
  p_desc jsonb,
  p_by   varchar
) RETURNS int
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_d   record;
  v_p   record;
  v_n   int := 0;
BEGIN
  IF p_desc IS NULL OR jsonb_array_length(p_desc) = 0 THEN
    RAISE EXCEPTION 'E_SWAP_NO_SEG: 这张单没有任何段要动（试算结果为空，审批不该通过）';
  END IF;

  -- ★ jsonb_array_elements 出来的是一行一列（列名 value），不是"这一行的字段"：
  --   直接在循环变量上写 -> 会得到 `record ->> unknown`（42883），
  --   所以要显式给它一个列别名 e(v)。
  FOR v_d IN SELECT e.v AS j FROM jsonb_array_elements(p_desc) e(v) LOOP
    DELETE FROM public.schedule_segment WHERE id = (v_d.j->>'seg')::bigint;
  END LOOP;

  FOR v_d IN SELECT e.v AS j FROM jsonb_array_elements(p_desc) e(v) LOOP
    PERFORM public.fn_swap_place_seg(
      (v_d.j->>'person')::bigint,
      (v_d.j->>'date')::date,
      NULLIF(v_d.j->>'shift', '')::bigint,
      (v_d.j->>'store')::bigint,
      (v_d.j->>'start')::timestamptz,
      (v_d.j->>'end')::timestamptz);
    v_n := v_n + 1;
  END LOOP;

  -- 两边的 roster_slot 都要重算：走的人那天可能空了，来的人那天可能变了班次
  FOR v_p IN
    SELECT DISTINCT t.person, t.d FROM (
      SELECT (e.v->>'person')::bigint AS person, (e.v->>'date')::date AS d
        FROM jsonb_array_elements(p_desc) e(v)
      UNION
      SELECT (e.v->>'src_person')::bigint, (e.v->>'src_date')::date
        FROM jsonb_array_elements(p_desc) e(v)
    ) t
  LOOP
    PERFORM public.fn_swap_slot_sync(v_p.person, v_p.d, p_by);
  END LOOP;

  RETURN v_n;
END;
$$;

COMMENT ON FUNCTION fn_swap_apply IS
  '换班落库（154）：删源段 → 在目标人名下按新归属重建（建确认单）→ 重算两边 '
  'roster_slot。先全删再全插，同一天两个班次互调时才不会两边同时挂着同一时段。';

-- ---------------------------------------------------------------------------
-- 8. 填单
-- ---------------------------------------------------------------------------
-- 签字顺序：fn_swap_create（员工填）→ fn_swap_agree（对方确认，self 跳过）
--           → fn_swap_decide（主管审批）→ 自动改排班
CREATE OR REPLACE FUNCTION fn_swap_create(
  p_kind        varchar,
  p_from_person bigint,
  p_to_person   bigint,
  p_from_date   date,
  p_from_seg    varchar,
  p_to_date     date,
  p_to_seg      varchar,
  p_reason      varchar,
  p_by          varchar,
  p_to_shift    varchar DEFAULT NULL   -- 仅 self 用：换成哪个班次
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_kind      varchar(8);
  v_to_person bigint;
  v_to_date   date;
  v_from_seg  varchar;
  v_to_seg    varchar;
  v_desc      jsonb;
  v_from_shift varchar;
  v_to_shift   varchar;
  v_id        bigint;
BEGIN
  v_kind := lower(btrim(COALESCE(p_kind, '')));
  IF v_kind NOT IN ('self','swap','cover','covered') THEN
    RAISE EXCEPTION 'E_SWAP_KIND: 换班类型只认 self / swap / cover / covered（收到 %）',
      COALESCE(NULLIF(p_kind, ''), '空');
  END IF;

  IF p_from_person IS NULL OR p_from_date IS NULL THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 发起人与日期（from_date）必填';
  END IF;

  IF length(btrim(COALESCE(p_reason, ''))) < 4 THEN
    RAISE EXCEPTION 'E_SWAP_NO_REASON: 换班原因至少 4 个字 —— 审批的人要知道"为什么换"，'
                    '而不是只看到一个"换"';
  END IF;

  v_from_seg := NULLIF(btrim(COALESCE(p_from_seg, '')), '');
  v_to_seg   := NULLIF(btrim(COALESCE(p_to_seg, '')), '');
  -- seg 只认 HH:MM：段没有名字，开始时刻是它唯一的身份（见列注释）
  IF v_from_seg IS NOT NULL AND v_from_seg !~ '^([01]\d|2[0-3]):[0-5]\d$' THEN
    RAISE EXCEPTION 'E_ARG_INVALID: from_seg 写段开始的 HH:MM（收到 %）', v_from_seg;
  END IF;
  IF v_to_seg IS NOT NULL AND v_to_seg !~ '^([01]\d|2[0-3]):[0-5]\d$' THEN
    RAISE EXCEPTION 'E_ARG_INVALID: to_seg 写段开始的 HH:MM（收到 %）', v_to_seg;
  END IF;

  IF v_kind = 'self' THEN
    -- 调自己的班：没有"对方"。传了别人就直接拒 —— 那不是 self，是 swap。
    IF p_to_person IS NOT NULL AND p_to_person <> p_from_person THEN
      RAISE EXCEPTION 'E_SWAP_NO_PERSON: self 是调换自己的班次，不能指定别人（收到 %）；'
                      '与别人换请用 swap', p_to_person;
    END IF;
    v_to_person := NULL;          -- 表上的约定：self 时 to_person 为空
    v_to_date   := p_from_date;
    v_to_seg    := NULL;
  ELSE
    IF p_to_person IS NULL THEN
      RAISE EXCEPTION 'E_SWAP_NO_PERSON: % 类型必须给"对方"是谁（to_person）', v_kind;
    END IF;
    IF p_to_person = p_from_person THEN
      RAISE EXCEPTION 'E_SWAP_NO_PERSON: 对方不能是自己 —— 调自己的班次请用 self';
    END IF;
    v_to_person := p_to_person;
    IF p_to_date IS NULL THEN
      IF v_kind = 'covered' THEN
        v_to_date := p_from_date;     -- 别人替我：被替的那天就是我这天
      ELSE
        RAISE EXCEPTION 'E_ARG_INVALID: % 类型必须给对方的日期（to_date）', v_kind;
      END IF;
    ELSE
      v_to_date := p_to_date;
    END IF;
    -- 被换走的那一段只在一侧：cover 在对方那天，covered 在我这天
    IF v_kind = 'covered' THEN v_to_seg := NULL; END IF;
    IF v_kind = 'cover'   THEN v_from_seg := NULL; END IF;
  END IF;

  IF NOT public.fn_is_active(p_from_person, p_from_date) THEN
    RAISE EXCEPTION 'E_SWAP_NO_EMPLOYEE: % 在 % 不在职（换班要挂在在职的人身上）',
      p_from_person, p_from_date;
  END IF;
  IF v_to_person IS NOT NULL AND NOT public.fn_is_active(v_to_person, v_to_date) THEN
    RAISE EXCEPTION 'E_SWAP_NO_EMPLOYEE: 对方 % 在 % 不在职（换班要挂在在职的人身上）',
      v_to_person, v_to_date;
  END IF;

  -- ★ 试算一次：段是否存在、有没有被锁、换完会不会重叠 —— 全部在填单时拒。
  --   重叠等到审批通过那一刻才发现，单子已经有人点了"同意"，那时要么强改，
  --   要么挂在那里谁也关不掉。
  v_desc := public.fn_swap_descriptors(v_kind, p_from_person, v_to_person,
               p_from_date, v_from_seg, v_to_date, v_to_seg, p_to_shift);

  -- 记录当时换的是哪两个班（划线排班没有班次身份 → 为空）
  SELECT sd.code INTO v_from_shift
    FROM public.fn_swap_segs(p_from_person, p_from_date, v_from_seg) f
    JOIN public.schedule s ON s.id = f.schedule_id
    LEFT JOIN public.shift_def sd ON sd.shift_id = s.shift_id
   ORDER BY f.start_at LIMIT 1;

  SELECT sd.code INTO v_to_shift
    FROM public.fn_swap_segs(v_to_person, v_to_date, v_to_seg) f
    JOIN public.schedule s ON s.id = f.schedule_id
    LEFT JOIN public.shift_def sd ON sd.shift_id = s.shift_id
   ORDER BY f.start_at LIMIT 1;

  IF v_kind = 'self' THEN
    v_to_shift := btrim(p_to_shift);
  END IF;

  INSERT INTO public.roster_swap(kind, from_person, to_person, from_date, from_seg,
                                 to_date, to_seg, from_shift, to_shift,
                                 reason, status, created_by)
  VALUES (v_kind, p_from_person, v_to_person, p_from_date, v_from_seg,
          v_to_date, v_to_seg, v_from_shift, v_to_shift,
          btrim(p_reason), 'draft', btrim(COALESCE(p_by, 'system')))
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$$;

COMMENT ON FUNCTION fn_swap_create IS
  '填换班单（154）：四种类型都走这里。校验两边在职（E_SWAP_NO_EMPLOYEE）、'
  '原因 ≥4 字（E_SWAP_NO_REASON）、段属于那天（E_SWAP_NO_SEG）、'
  '换完不许重叠（E_SWAP_OVERLAP，填单时就拒）。self 用第 10 个参数 p_to_shift 说换成哪个班。';

-- ---------------------------------------------------------------------------
-- 9. 对方确认（self 跳过）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_swap_agree(
  p_id bigint,
  p_by varchar
) RETURNS varchar
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_r      public.roster_swap%ROWTYPE;
  v_uid    bigint;
  v_person bigint;
BEGIN
  IF p_id IS NULL THEN RAISE EXCEPTION 'E_ARG_INVALID: 单号必填'; END IF;

  SELECT * INTO v_r FROM public.roster_swap WHERE id = p_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'E_SWAP_NO_SWAP: 换班单 % 不存在', p_id;
  END IF;

  IF v_r.kind = 'self' THEN
    RAISE EXCEPTION 'E_SWAP_STATE: 单 % 是调换自己的班次，没有需要确认的对方（可直接审批）', p_id;
  END IF;

  IF v_r.status IN ('approved','rejected','cancelled') THEN
    RAISE EXCEPTION 'E_SWAP_APPLIED: 换班单 % 已经定案（%），确认不再改变任何东西', p_id, v_r.status;
  END IF;
  IF v_r.status <> 'draft' THEN
    RAISE EXCEPTION 'E_SWAP_STATE: 换班单 % 当前是 %，只有 draft 可以确认', p_id, v_r.status;
  END IF;

  -- ★ 只认对方本人。p_by 可能是登录名，也可能是 app 层传的账号 id（两种都认，
  --   与 145 的 fn_roster_lock 同一个做法）。解不出账号就是"说不清是谁" ——
  --   说不清是谁的确认，等于没人确认。
  SELECT a.id, a.person_id INTO v_uid, v_person
    FROM public.sys_account a
   WHERE a.login = btrim(COALESCE(p_by, '')) LIMIT 1;
  IF v_uid IS NULL THEN
    SELECT a.id, a.person_id INTO v_uid, v_person
      FROM public.sys_account a
     WHERE a.id::text = btrim(COALESCE(p_by, '')) LIMIT 1;
  END IF;

  IF v_uid IS NULL OR v_person IS DISTINCT FROM v_r.to_person THEN
    RAISE EXCEPTION 'E_SWAP_NOT_YOURS: 只有对方本人（% ）能确认这张单，% 不是',
      v_r.to_person, COALESCE(NULLIF(btrim(p_by), ''), '未署名');
  END IF;

  UPDATE public.roster_swap
     SET status = 'agreed', agreed_at = now()
   WHERE id = p_id AND status = 'draft';

  RETURN 'agreed';
END;
$$;

COMMENT ON FUNCTION fn_swap_agree IS
  '对方确认（154）：draft → agreed，只允许 to_person 本人（E_SWAP_NOT_YOURS）。'
  'self 类型没有对方，调用即拒（E_SWAP_STATE）。';

-- ---------------------------------------------------------------------------
-- 10. 审批（通过 = 自动落库改排班）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_swap_decide(
  p_id   bigint,
  p_ok   boolean,
  p_note varchar DEFAULT NULL,
  p_by   varchar DEFAULT 'system'
) RETURNS varchar
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_r    public.roster_swap%ROWTYPE;
  v_desc jsonb;
  v_by   varchar := btrim(COALESCE(p_by, 'system'));
BEGIN
  IF p_id IS NULL THEN RAISE EXCEPTION 'E_ARG_INVALID: 单号必填'; END IF;
  IF p_ok IS NULL THEN
    RAISE EXCEPTION 'E_ARG_INVALID: 要明确说"通过"还是"驳回"（ok=1 / ok=0）';
  END IF;

  SELECT * INTO v_r FROM public.roster_swap WHERE id = p_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'E_SWAP_NO_SWAP: 换班单 % 不存在', p_id;
  END IF;

  IF v_r.status IN ('approved','rejected','cancelled') THEN
    RAISE EXCEPTION 'E_SWAP_APPLIED: 换班单 % 已经定案（%），通过之后不可再改', p_id, v_r.status;
  END IF;

  IF NOT p_ok THEN
    UPDATE public.roster_swap
       SET status = 'rejected',
           decide_note = NULLIF(btrim(COALESCE(p_note, '')), ''),
           approved_by = v_by,
           approved_at = now()
     WHERE id = p_id;
    RETURN 'rejected';
  END IF;

  -- ★ 非 self 必须对方先确认。没有这一步，"我替别人上班"可以由发起人一个人
  --   点完 —— 而被替的那个人从没答应过。
  IF v_r.kind <> 'self' AND v_r.status <> 'agreed' THEN
    RAISE EXCEPTION 'E_SWAP_NOT_AGREED: 换班单 % 还没等对方确认（当前 %）—— % 类型必须先'
                    '由对方确认再审批', p_id, v_r.status, v_r.kind;
  END IF;

  -- 落库前再算一遍：从填单到审批之间排班可能被动过（段改了、加了班、被锁了）。
  -- 这一遍要是炸，拒的是"这张单现在已经不成立了"，而不是"当初填错了"。
  v_desc := public.fn_swap_descriptors(v_r.kind, v_r.from_person, v_r.to_person,
               v_r.from_date, v_r.from_seg, v_r.to_date, v_r.to_seg, v_r.to_shift);

  PERFORM public.fn_swap_apply(v_desc, v_by);

  UPDATE public.roster_swap
     SET status = 'approved',
         applied_at = now(),
         approved_by = v_by,
         approved_at = now(),
         decide_note = NULLIF(btrim(COALESCE(p_note, '')), '')
   WHERE id = p_id;

  RETURN 'approved';
END;
$$;

COMMENT ON FUNCTION fn_swap_decide IS
  '审批换班单（154）：通过 → 按类型落库改排班（self 改班次 / swap 两边对调 / '
  'cover、covered 改归属）并写 applied_at；驳回 → rejected（不动排班）。'
  '非 self 未确认就通过 → E_SWAP_NOT_AGREED；已定案再动 → E_SWAP_APPLIED。';

-- ---------------------------------------------------------------------------
-- 11. 换班记录（产品明确要"可查可控"）
-- ---------------------------------------------------------------------------
-- 一个人既是发起人也可能是对方，所以两个方向都要出；role 说出他在这张单里
-- 是"我发起的"还是"我是对方"—— 否则同一条记录在两个人的列表里长得一样。
CREATE OR REPLACE FUNCTION fn_swap_log(
  p_person bigint,
  p_from   date,
  p_to     date
) RETURNS TABLE (
  swap_id      bigint,
  kind         varchar,
  role         varchar,
  other_person bigint,
  other_name   varchar,
  from_date    date,
  from_seg     varchar,
  to_date      date,
  to_seg       varchar,
  from_shift   varchar,
  to_shift     varchar,
  reason       varchar,
  status       varchar,
  agreed_at    timestamptz,
  approved_by  varchar,
  approved_at  timestamptz,
  applied_at   timestamptz,
  created_at   timestamptz
)
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT s.id, s.kind::varchar,
         CASE WHEN s.from_person = p_person THEN 'from' ELSE 'to' END::varchar,
         CASE WHEN s.from_person = p_person THEN s.to_person ELSE s.from_person END,
         pe.full_name::varchar,
         s.from_date, s.from_seg::varchar, s.to_date, s.to_seg::varchar,
         s.from_shift::varchar, s.to_shift::varchar, s.reason::varchar,
         s.status::varchar, s.agreed_at, s.approved_by::varchar,
         s.approved_at, s.applied_at, s.created_at
    FROM public.roster_swap s
    LEFT JOIN public.person pe
      ON pe.id = CASE WHEN s.from_person = p_person THEN s.to_person ELSE s.from_person END
   WHERE (s.from_person = p_person OR s.to_person = p_person)
     AND s.from_date >= COALESCE(p_from, s.from_date)
     AND s.from_date <= COALESCE(p_to,   s.from_date)
   ORDER BY s.created_at DESC, s.id DESC;
$$;

COMMENT ON FUNCTION fn_swap_log IS
  '某人的换班记录（154）：两个方向都出，role 说明他是发起方还是对方。'
  '日期区间按 from_date 过滤（NULL = 不限）。产品要求"排班报表里可随时查看换班记录"。';

-- ---------------------------------------------------------------------------
-- 12. 定案之后冻结
-- ---------------------------------------------------------------------------
-- ★ 一张能随手改回来的审批单，事后无法回答"当时到底换没换"。
--   approved 之后排班已经改过了，改这张单会让记录与排班表各说一套；
--   rejected 之后同样冻结 —— 否则"驳回 → 改成通过"可以绕过对方确认。
CREATE OR REPLACE FUNCTION tr_swap_freeze() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.status IN ('approved','rejected') THEN
      RAISE EXCEPTION 'E_SWAP_APPLIED: 换班单 % 已定案（%），不许删 —— 换班记录要"可查可控"',
        OLD.id, OLD.status;
    END IF;
    RETURN OLD;
  END IF;

  IF OLD.status IN ('approved','rejected') THEN
    RAISE EXCEPTION 'E_SWAP_APPLIED: 换班单 % 已定案（%），之后不许再改（含状态回退）',
      OLD.id, OLD.status;
  END IF;
  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION tr_swap_freeze IS
  '定案冻结（154）：approved / rejected 之后 UPDATE 与 DELETE 都拒（E_SWAP_APPLIED）。';

CREATE TRIGGER trg_swap_freeze
  BEFORE UPDATE OR DELETE ON public.roster_swap
  FOR EACH ROW EXECUTE FUNCTION tr_swap_freeze();

