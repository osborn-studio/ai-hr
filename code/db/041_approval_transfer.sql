-- ===========================================================================
-- 041_approval_transfer.sql · 转签：审批人请假/离职时的唯一合法出路
-- ---------------------------------------------------------------------------
-- 审批人解析在**启动时**落成行（032）。这在正常路径上是对的，但它带来一个
-- 必然会发生的问题：**审批人自己不在**（休假、出差、离职）。
--
-- 三种"处理方式"，只有一种是对的：
--
--   ① 让管理员直接改 `approval_task.approver_id` —— 改得动，但**没有痕迹**，
--      事后无法回答"这单为什么是他批的"。
--   ② 让申请人重提 —— 单据重来一遍，前面批过的人白批。
--   ③ **转签**：原审批人（或代理）把这一步转给另一个人，记下谁转的、为什么。
--
-- 这一版实现 ③。三条判据：
--
--   · 只能转**自己的**待办，且只能是**当前步**（跳步转签会让前一步的会签失去意义）
--   · 不能转给申请人（那等于自审换了个入口），也不能转给自己（等于没转）
--   · 每一次转签**都要有原因**，并落进 `approval_task_log`（只增不改）
-- ===========================================================================

CREATE TABLE approval_task_log (
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id   bigint      NOT NULL REFERENCES approval_task(id),
  action    varchar(16) NOT NULL,
  from_user bigint,
  to_user   bigint,
  by_user   bigint      NOT NULL,
  reason    varchar(200) NOT NULL,
  at        timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT ck_atl_action CHECK (action IN ('transfer','addsign','cc')),
  CONSTRAINT ck_atl_reason CHECK (length(btrim(reason)) >= 4)
);

CREATE INDEX ix_atl_task ON approval_task_log(task_id, at);

-- 日志只增不改：改一条日志＝改一段审批历史，而那正是要留的东西
CREATE OR REPLACE FUNCTION fn_atl_append_only() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  RAISE EXCEPTION 'E_APPR_LOG_APPEND_ONLY: 审批操作日志只增不改';
END;
$$;

CREATE TRIGGER trg_atl_append_only
  BEFORE UPDATE OR DELETE ON approval_task_log
  FOR EACH ROW EXECUTE FUNCTION fn_atl_append_only();

CREATE OR REPLACE FUNCTION fn_appr_transfer(
  p_task bigint, p_to bigint, p_by bigint, p_reason varchar
) RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  t record; v_applicant bigint; v_biz_type varchar; v_biz_id bigint; v_min_seq int; v_inst bigint;
BEGIN
  IF p_reason IS NULL OR length(btrim(p_reason)) < 4 THEN
    RAISE EXCEPTION 'E_APPR_TRANSFER_NO_REASON: 转签必须写原因（至少 4 个字）';
  END IF;
  IF p_to = p_by THEN
    RAISE EXCEPTION 'E_APPR_TRANSFER_SELF: 不能转给自己（那等于没转，只是多了一条日志）';
  END IF;

  SELECT * INTO t FROM public.approval_task WHERE id = p_task FOR UPDATE;
  IF t.id IS NULL THEN
    RAISE EXCEPTION 'E_APPR_NO_TASK: 待办 % 不存在', p_task;
  END IF;
  IF t.status <> 'pending' THEN
    RAISE EXCEPTION 'E_APPR_TASK_DONE: 待办 % 已是 %，不可转签', p_task, t.status;
  END IF;
  IF t.approver_id <> p_by THEN
    RAISE EXCEPTION 'E_APPR_NOT_YOURS: 待办 % 不属于 %', p_task, p_by;
  END IF;

  -- 只能转当前步：跳步转签会让前一步的会签失去意义
  v_inst := t.instance_id;
  SELECT min(seq) INTO v_min_seq FROM public.approval_task
   WHERE instance_id = v_inst AND status = 'pending';
  IF t.seq <> v_min_seq THEN
    RAISE EXCEPTION 'E_APPR_NOT_CURRENT_STEP: 第 % 步还不是当前步（当前是第 % 步）', t.seq, v_min_seq;
  END IF;

  SELECT biz_type, biz_id INTO v_biz_type, v_biz_id
    FROM public.approval_instance WHERE id = v_inst;
  v_applicant := public.fn_appr_biz_applicant(v_biz_type, v_biz_id);

  -- ★ 转给申请人 = 自审换了个入口。申请人在启动时就被剔除过一次，
  --   如果转签能把他加回来，那条剔除规则就白写了。
  IF p_to = v_applicant THEN
    RAISE EXCEPTION 'E_APPR_TRANSFER_TO_APPLICANT: 不能转给申请人 %（那是自审的另一个入口）', p_to;
  END IF;

  -- ★ 转给"这一步已经在等他审的人"没有意义（或签下他本来就能批），
  --   而且会撞 uk_at_inst_seq_approver。这条错误必须**有名字**：
  --   直接落 23505 的话，前端只能显示"冲突"，而真相是"选错人了"。
  IF EXISTS (SELECT 1 FROM public.approval_task x
              WHERE x.instance_id = v_inst AND x.seq = t.seq
                AND x.approver_id = p_to AND x.status = 'pending') THEN
    RAISE EXCEPTION 'E_APPR_TRANSFER_DUPLICATE: % 已经是第 % 步的审批人，不需要转签', p_to, t.seq;
  END IF;

  INSERT INTO public.approval_task_log(task_id, action, from_user, to_user, by_user, reason)
  VALUES (p_task, 'transfer', t.approver_id, p_to, p_by, btrim(p_reason));

  UPDATE public.approval_task SET approver_id = p_to WHERE id = p_task;
END;
$$;

COMMENT ON FUNCTION fn_appr_transfer IS
  '把当前步的待办转给另一个人，并留痕。不允许转给申请人（那是自审的另一个入口），'
  '也不允许转给自己；每次转签都要有原因，日志只增不改。';

