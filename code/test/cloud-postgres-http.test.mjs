import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { createCloudApp } from '../app/cloud-server.mjs';
import { withTx } from '../app/db.mjs';
import { hashPassword } from '../app/services/auth.mjs';

if (!process.env.DATABASE_URL) throw new Error('必须使用隔离空PostgreSQL数据库');
process.env.TYHR_DATA_MODE = 'postgres';
const app = await createCloudApp();
const db = app.db;
let passed = 0;
const check = (name, value) => { assert.ok(value, name); passed++; console.log('PASS '+name); };
const q = async (sql, params = []) => (await db.query(sql, params)).rows;
const password = randomBytes(18).toString('base64url');
try {
  check('cloud bootstrap never silently creates demo group', Number((await q('SELECT count(*) n FROM ty_group'))[0].n) === 0);
  const group = (await q("INSERT INTO ty_group(code,name)VALUES('CLOUD-HTTP','虚构云端测试集团') RETURNING id"))[0];
  await withTx(db, async tx => {
    await tx.query("INSERT INTO sys_data_scope(id,name,combinator)VALUES(94001,'虚构云端测试范围','intersection')");
    await tx.query("INSERT INTO sys_account(id,login,display_name)OVERRIDING SYSTEM VALUE VALUES(94001,'cloud_http_fixture','云端测试经办人')");
    await tx.query("INSERT INTO sys_user_role(user_id,role_id,data_scope_id,effective_from,grant_kind,grant_reason)VALUES(94001,10,94001,'2000-01-01','ROLE','独立虚构HTTP验收')");
    await tx.query('SELECT fn_credential_set($1,$2,false)', [94001,hashPassword(password)]);
    await tx.query("INSERT INTO ty_test_account_profile(account_id,group_id,profile_code,seed_version)VALUES(94001,$1,'demo','CLOUD-HTTP-FIXTURE')", [group.id]);
    await tx.query("INSERT INTO ty_access_grant(account_id,group_id,can_read,can_write,valid_from)VALUES(94001,$1,true,true,'2000-01-01')", [group.id]);
  });
  await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${app.server.address().port}`;
  const home = await fetch(base+'/');
  const html = await home.text();
  check('one Node serves actual built React HTML', home.status === 200 && html.includes('id="root"') && !html.includes('legacyFrame'));
  const asset = html.match(/src="(\/assets\/[^"\s]+\.js)"/);
  check('actual React build references own module asset', !!asset);
  const js = await fetch(base+asset[1]);
  check('same process serves built JS with script CSP', js.status === 200 && /javascript/.test(js.headers.get('content-type')) && /script-src 'self'/.test(js.headers.get('content-security-policy')));
  check('PG-backed readiness responds healthy', (await fetch(base+'/readyz')).status === 200);
  check('domain query cannot run before authenticated login', (await fetch(base+'/api/v2/query/foundation.bootstrap',{method:'POST',headers:{'content-type':'application/json'},body:'{}'})).status === 401);
  const login = await fetch(base+'/login', {method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({login:'cloud_http_fixture',password})});
  const loginResult = await login.json();
  check('actual credential login issues a session token', login.status === 200 && typeof loginResult.token === 'string');
  const headers = {authorization:`Bearer ${loginResult.token}`,'content-type':'application/json'};
  const post = (kind,name,input,operationId) => fetch(`${base}/api/v2/${kind}/${name}`,{method:'POST',headers:{...headers,...(operationId?{'idempotency-key':operationId}:{})},body:JSON.stringify(input)});
  const bootstrap = await post('query','foundation.bootstrap',{group_id:group.id});
  const data = await bootstrap.json();
  check('real domain query reads authorized PG organization', bootstrap.status === 200 && data.groups.some(g=>g.code==='CLOUD-HTTP'));
  check('forged actor is rejected by actual HTTP path', (await post('query','foundation.bootstrap',{group_id:group.id,userId:1})).status === 403);
  const input = {group_id:group.id,code:'corporate-annual-http',name:'虚构HTTP企业年假',jurisdiction:'CN',unit:'day',statutory:false,valid_from:'2026-01-01',rules:{quantity_basis:'calendar',step:'0.5',max_quantity:'20',expiry_action:'expire'}};
  check('persistent command without stable ID is rejected', (await post('command','leave.scheme.create',input)).status === 422);
  const created = await post('command','leave.scheme.create',input,'cloud-http-create-0001');
  const result = await created.json();
  if(created.status!==200)console.error('unexpected creation response',JSON.stringify(result));
  check('real advanced leave scheme command commits through route transaction', created.status === 200 && !!result.scheme?.id);
  const repeated = await post('command','leave.scheme.create',input,'cloud-http-create-0001');
  const replay = await repeated.json();
  check('HTTP retry returns same persistent scheme and receipt', repeated.status === 200 && String(replay.scheme?.id)===String(result.scheme?.id) && replay.replayed===true);
  check('same key different command input conflicts', (await post('command','leave.scheme.create',{...input,name:'改变内容'},'cloud-http-create-0001')).status === 409);
  check('query path cannot persist an adjustment preview', (await post('query','leave.adjustment.preview',{lot_id:1,mode:'delta',value:'2'})).status === 404);
  const nextPassword = randomBytes(18).toString('base64url');
  const changed = await fetch(base+'/api/me/password',{method:'POST',headers,body:JSON.stringify({oldPassword:password,newPassword:nextPassword})});
  check('password changes use JSON rather than credential-bearing URLs', changed.status === 200);
  check('password change keeps the current authenticated session', (await post('query','foundation.bootstrap',{group_id:group.id})).status === 200);
  const newLogin = await fetch(base+'/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({login:'cloud_http_fixture',password:nextPassword})});
  check('updated credential authenticates against real PostgreSQL', newLogin.status === 200);
  const logout = await fetch(base+'/api/me/logout',{method:'POST',headers,body:'{}'});
  check('same backend revokes session', logout.status === 200);
  check('revoked session cannot re-enter domain query', (await post('query','foundation.bootstrap',{})).status === 401);
} finally {
  if(app.server.listening)await new Promise(resolve=>app.server.close(resolve));
  await db.close();
}
console.log(`真实PostgreSQL + React构建 + Node HTTP ${passed}项通过`);
